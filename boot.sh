#!/bin/sh
# boot.sh — РЕЗИДЕНТНЫЙ ЗАПУСКАТЕЛЬ: единственная цель всех cron-строк проекта.
#
# ЗАЧЕМ. Код проекта может лежать НЕ на флеше роутера. В режиме полной установки (`full`) на
# /data остаётся только этот бутстрап, а код, настройки и бинари живут на внешнем накопителе:
# у чужих роутеров размер /data неизвестен (бывает 10–15 МБ), и есть люди, принципиально не
# желающие держать на роутере что-либо своё. Cron при этом обязан остаться прежним — он не
# знает и не должен знать, где сегодня лежит heal.sh. Поэтому строка cron зовёт ЭТОТ файл, а
# он решает, откуда запускать цель:
#
#   */1 * * * * /data/usr/app/enodia-boot/boot.sh heal.sh >/dev/null 2>&1
#
# РЕЖИМ ОПРЕДЕЛЯЕТСЯ ПО ФАКТУ — маркера режима НЕТ и не будет. Есть /data/usr/app/enodia/цель
# ⇒ код на флеше роутера (режимы `data` и `bins`), пути дефолтные, `exec` немедленно. Нет ⇒
# режим `full`: ищем накопитель, экспортируем три пути, `exec` оттуда. Причин две:
#   * маркер оффлоада (.bin-store) лежит в $ENODIA_STATE, а в `full` состояние САМО на
#     накопителе — курица и яйцо: маркер режима пришлось бы читать раньше, чем он доступен;
#   * это тот же принцип, за который уже заплачено в store-lib.sh — судим по ФАКТУ (`-f`,
#     `-x`), а не по намерению. Побочная выгода: роутер БЕЗ накопителя (это большинство)
#     платит за всю фичу ОДИН тест `[ -f ]` и НИ ОДНОГО форка.
#
# ФОРКОВ НА БЫСТРОМ ПУТИ БЫТЬ НЕ ДОЛЖНО. Нас зовут семь строк cron (раз в минуту — heal), и
# каждая подстановка `$(…)` здесь — лишний процесс на роутере со 128 МБ ОЗУ. Отсюда форма
# «функция кладёт ответ в ГЛОБАЛЬНУЮ переменную» вместо `x=$(func)`: она же спасает от второй
# беды — разбиения пути по пробелам. Пробел в пути к хранилищу законен (маркер и кэш его несут и
# переживают разбор — проверено стендом store-pin-test.sh), а `set -- $строка` порвал бы его.
#
# ЦЕЛЬ ЗОВЁМ `sh "$X"`, гард — по НАЛИЧИЮ файла, не по биту `-x`: бит не наш (на exFAT chmod
# вообще no-op, `--push` кладёт 644), и `[ -x ] && "$X"` на слетевшем бите — тихий отказ с
# кодом 0. Заодно это снимает требование +x с целей: он нужен только САМОМУ boot.sh, потому
# что его зовёт cron, а cron не наш.
#
# ЧЕГО ЗДЕСЬ НЕТ: реестра целей. Первый аргумент — ИМЯ скрипта в каталоге кода, и добавление
# новой cron-строки не требует правки бутстрапа. Реестр разъехался бы — это отдельный класс
# наших багов, на него уже заведены C-проверки.
#
# Вербы:
#   boot.sh <имя>.sh [аргументы]  — запустить цель из АКТИВНОГО каталога кода
#   boot.sh hotplug               — накопитель воткнули (зовёт /etc/hotplug.d/block/99-enodia-usb)
#   boot.sh doh-early             — ранний подъём шифрованного DNS (зовёт /etc/init.d/enodia-early)
#   boot.sh sync [каталог]        — собрать/обновить сам бутстрап из каталога кода (зовёт install.sh)
#   boot.sh ram-migrate           — перенести наши имена в /tmp из прошлой эпохи (зовёт --push)
#   boot.sh paths                 — три пути машине (dump.sh, панель, ПК-сторона)
#   boot.sh status                — то же человеку, плюс режим и заглушка

BOOT_DIR=${ENODIA_BOOT:-/data/usr/app/enodia-boot}
# Пути ФЛЕША РОУТЕРА — литералами: это те самые дефолты, которые все 54 файла объявляют формой
# ${VAR:=литерал}. Бутстрап — единственное место, где им положено быть записанными явно: он
# решает, оставить их или подменить накопителем.
DATA_DIR=/data/usr/app/enodia            # boot-lit: бутстрап и решает, оставить этот путь или подменить
DATA_STATE=/data/usr/app/enodia-state
DATA_BIN=/data/usr/app/enodia-bin

# Последний известный путь хранилища. Это КЭШ, а не настройка: потеря стоит одного лишнего
# сканирования, а решение принимается всё равно по факту (`-f` у цели внутри). Держим его
# рядом с бутстрапом, потому что в режиме `full` /data больше ничего нашего не содержит.
STORE_CACHE="$BOOT_DIR/.store-cache"
STUB_PID=/tmp/enodia-stub.pid
STUB_PORT=8088                          # тот же порт, что у панели (web-ui.sh: PORT) — заглушка
                                        # занимает его РОВНО пока панели нет; следит C58
SCAN_STAMP=/tmp/enodia-boot-scan        # когда последний раз искали накопитель (аптайм, секунды)
SCAN_EVERY=45                           # чаще незачем: строк cron семь, а поиск монтирует кандидатов
BOOT_LOCK=/tmp/enodia-boot.lock         # событий одной флешки бывает несколько — второму делать нечего
HEAL_LOCK=/tmp/enodia-heal.lock         # лок heal.sh (пид / «done …»): hotplug-тик ждёт по нему «отработал»
HOTPLUG_WAIT=${HOTPLUG_WAIT:-240}       # потолок ожидания ЖИВОГО heal (с закачкой списков он идёт до ~170 с)
HOTPLUG_NOLOCK_WAIT=${HOTPLUG_NOLOCK_WAIT:-60}   # …а когда лок пуст/держит труп — ждать нечего: минута на старт heal по cron
HOTPLUG_PID=/tmp/enodia-hotplug-tick.pid   # его же передаём start-stop-daemon: два литерала на один файл разъехались бы молча
BOOT_SYNC_LOCK=/tmp/enodia-boot-sync.lock   # переливка бутстрапа: цели cron бегут ВПЕРЕМЕШКУ
CRON=/etc/crontabs/root                 # только для ПЕРЕВОДА прежних строк на бутстрап (cron_to_boot)
HOOK=/etc/hotplug.d/block/99-enodia-usb
# Ранний старт там, где /etc переживает ребут (AX3600, BE3600). На BE7000 /etc — ramfs, и эти
# три пути просто не заводятся: доказательства персистентности не будет (см. etc_persistent).
PERSIST_PROBE=/etc/enodia-persist
# Идентификатор ЗАГРУЗКИ — своей переменной по той же причине, что списки монтирований в
# mount-lib.sh: без подменяемого источника ветка «/etc пережил ребут» не гоняется вовсе, а
# именно в ней решается, класть ли на роутер файл, который переживёт удаление.
BOOT_ID=/proc/sys/kernel/random/boot_id
INIT_SCRIPT=/etc/init.d/enodia-early
INIT_LINK=/etc/rc.d/S20enodia-early
INIT_TAG='# enodia early v1 — ранний подъём шифрованного DNS (кладёт boot.sh)'
HOOK_TAG='# enodia hotplug v1 — кладётся boot.sh на каждом прогоне (/etc/hotplug.d = ramfs)'
# ИЗ ЧЕГО СОСТОИТ БУТСТРАП — список ровно один, здесь. Он же используется и при сборке
# (`sync` из install.sh), и при самообновлении: два списка разъехались бы, и на роутере
# оказалась бы половина бутстрапа — то есть запускатель, который не умеет искать накопитель.
BOOT_FILES='boot.sh mount-lib.sh store-lib.sh router-lib.sh'

# --- цель ---------------------------------------------------------------------------------

# Имя цели проверяем ПО ФОРМЕ, а не доверием: строку cron может поправить человек, а `exec sh`
# с чужим путём — это запуск чего угодно от root. Только `*.sh`, только без слэшей и «..».
target_ok() {
    case "$1" in
        *.sh) ;;
        *) return 1 ;;
    esac
    case "$1" in
        */*|..*|-*) return 1 ;;
    esac
    return 0
}

# --- самообновление бутстрапа ---------------------------------------------------------------
#
# Бутстрап — ПРОИЗВОДНОЕ активного кода, а не отдельный артефакт: своего манифеста у него нет и
# apply-scripts про него не знает. Разошлись номера сборок — переливаем к себе файлы списка и
# заглушку. Иначе обновление кода оставило бы на /data вечно старый запускатель, а он в режиме
# `full` — единственная дорога ко ВСЕМУ.
#
# `sh -n` ПЕРЕД подменой обязателен: обновление, привёзшее синтаксически битый boot.sh, кирпичит
# роутер целиком — цели перестают запускаться все разом, включая панель, которой это чинят.
# Подмена через tmp+mv: `mv` переименовывает inode, и ЭТОТ, уже читаемый шеллом файл доживёт до
# конца (перезапись на месте порвала бы его в середине). /data смонтирован sync ⇒ своего sync
# не нужно.
# VERSION копируем ПОСЛЕДНИМ — он и есть отметка «переливка удалась»: умерли на середине,
# номера всё ещё расходятся, следующий тик повторит.

# code_of <файл VERSION> — кладёт CODE в $CODE_OF. Без форков: этот путь горячий.
code_of() {
    CODE_OF=
    [ -f "$1" ] || return 1
    while read -r _co_l; do
        case "$_co_l" in CODE=*) CODE_OF=${_co_l#CODE=} ;; esac
    done < "$1"
    [ -n "$CODE_OF" ]
}

# ЛОК ПЕРЕЛИВКИ. Ступень `<файл>.new` в бутстрапе ОДНА на всех, а целей cron семь, и на общей
# минуте они стартуют ВМЕСТЕ (heal раз в минуту, сторож раз в две, трафик и панель раз в пять):
# после обновления кода все разом видят расхождение номеров и льют файлы через одно имя. Каждый
# файл атомарен сам по себе (cp в ступень + mv), а вот ступень общая — и `mv` одного процесса
# уносит inode из-под `cp` другого, который дописывает дальше уже В ЖИВОЙ boot.sh. Окно короткое,
# цена ему — усечённый запускатель, то есть роутер без heal, сторожа и панели РАЗОМ, причём
# чинить его будет нечем: панель поднимает он же.
# ЖДЁТ ТОЛЬКО СБОРКА (`sync` из установщика и переезда режима): тику ждать незачем — переливку
# повторит следующий, а секунда сна на семи целях дороже отложенной на минуту переливки.
boot_sync_lock() {      # $1 = сколько секунд ждать (пусто = не ждать вовсе)
    _bl_w=${1:-0}; _bl_i=0; _bl_b=0; _bl_e=0
    while :; do
        if mkdir "$BOOT_SYNC_LOCK" 2>/dev/null; then
            printf '%s\n' "$$" > "$BOOT_SYNC_LOCK/pid" 2>/dev/null
            return 0
        fi
        # Держатель мёртв — свидетельство окончательное (тот же приём, что у usb-offload.sh):
        # /tmp это ОЗУ, сам себя лок не снимет, а держателя мог унести kill посреди переливки.
        # Пустой pid — ОКНО между mkdir и записью, а не протухший лок: его не ломаем.
        _bl_p=
        [ -f "$BOOT_SYNC_LOCK/pid" ] && read -r _bl_p < "$BOOT_SYNC_LOCK/pid" 2>/dev/null
        case "$_bl_p" in
            # Пусто ТРИ ОПРОСА ПОДРЯД — уже не окно, а держатель, убитый ровно между `mkdir` и
            # записью pid: лок без владельца заперт бы до ребута (/tmp это ОЗУ, сам он не
            # рассосётся). Тику эта ветка недостижима (он не ждёт вовсе) — и правильно: цена
            # его отказа ровно одна пропущенная переливка, а сборке отказывать нельзя.
            ''|*[!0-9]*)
                _bl_e=$((_bl_e + 1))
                if [ "$_bl_e" -ge 3 ] && [ "$_bl_b" -lt 3 ]; then
                    rm -rf "$BOOT_SYNC_LOCK" 2>/dev/null; _bl_b=$((_bl_b + 1)); _bl_e=0; continue
                fi ;;
            *) _bl_e=0
               if [ ! -d "/proc/$_bl_p" ] && [ "$_bl_b" -lt 3 ]; then
                   rm -rf "$BOOT_SYNC_LOCK" 2>/dev/null; _bl_b=$((_bl_b + 1)); continue
               fi ;;
        esac
        [ "$_bl_i" -ge "$_bl_w" ] && return 1
        _bl_i=$((_bl_i + 1)); sleep 1
    done
}

boot_refresh() {     # $1 = каталог кода, $2 = "force" (сборка бутстрапа с нуля)
    code_of "$1/VERSION" || return 0
    _br_a="$CODE_OF"
    if [ "$2" != force ]; then
        code_of "$BOOT_DIR/VERSION" || CODE_OF=
        [ "$_br_a" = "$CODE_OF" ] && return 0
    fi
    # ЛОК БЕРЁМ ПОСЛЕ СВЕРКИ НОМЕРОВ: у того, кому переливать нечего (а это каждый тик, кроме
    # первого после обновления), не должно остаться ни одного лишнего форка.
    if [ "$2" = force ]; then
        boot_sync_lock 10 || { echo "boot: переливку бутстрапа держит другой процесс" >&2; return 1; }
    else
        boot_sync_lock || return 0
    fi
    mkdir -p "$BOOT_DIR" 2>/dev/null
    _br_rc=0
    for _br_f in $BOOT_FILES; do
        # НЕТ ФАЙЛА В ИСТОЧНИКЕ. На тике молчим и идём дальше: так ведёт себя роутер, откатанный
        # на версию без этого файла, — прежние копии в бутстрапе рабочие, а жалоба раз в минуту
        # уходила бы в лог сторожа. А вот СБОРКА (`sync`) обязана отказать: её зовут установщик
        # и обновление, и «бутстрап собран» при неполном payload — это обещание, за которым
        # ничего нет: в режиме `full` он единственная дорога ко всему.
        if [ ! -f "$1/$_br_f" ]; then
            [ "$2" = force ] || continue
            echo "boot: в $1 нет $_br_f — бутстрап собирать НЕ из чего" >&2
            _br_rc=1
            break
        fi
        cp "$1/$_br_f" "$BOOT_DIR/$_br_f.new" 2>/dev/null || continue
        if sh -n "$BOOT_DIR/$_br_f.new" 2>/dev/null; then
            mv "$BOOT_DIR/$_br_f.new" "$BOOT_DIR/$_br_f"
        else
            rm -f "$BOOT_DIR/$_br_f.new"
            echo "boot: $_br_f из $1 не разбирается — оставляю прежний" >&2
            _br_rc=1
            break
        fi
    done
    if [ "$_br_rc" = 0 ]; then
        chmod +x "$BOOT_DIR/boot.sh" 2>/dev/null      # его зовёт cron, а cron не наш
        if [ -f "$1/web/stub/index.html" ]; then
            mkdir -p "$BOOT_DIR/stub" 2>/dev/null
            cp "$1/web/stub/index.html" "$BOOT_DIR/stub/index.html.new" 2>/dev/null \
                && mv "$BOOT_DIR/stub/index.html.new" "$BOOT_DIR/stub/index.html"
        fi
        cp "$1/VERSION" "$BOOT_DIR/VERSION.new" 2>/dev/null && mv "$BOOT_DIR/VERSION.new" "$BOOT_DIR/VERSION"
    fi
    rm -rf "$BOOT_SYNC_LOCK" 2>/dev/null
    return $_br_rc
}

# --- ПЕРЕВОД ПРЕЖНИХ CRON-СТРОК НА БУТСТРАП --------------------------------------------------
#
# ЗАЧЕМ. Установка, обновлённая ИЗ ПАНЕЛИ, установщика не переживает: файлы приезжают по одному
# (apply-scripts), а cron-строки остаются такими, какими их когда-то записал install.sh, —
# прямым путём в каталог кода. Пока код лежит на флеше роутера, они работают, и трогать их
# незачем. Но ровно до переезда на накопитель: в режиме `full` каталога кода на флеше НЕТ, и
# строка `*/1 * * * * /data/usr/app/enodia/heal.sh` указывает в пустоту — после ребута не
# поднимается НИЧЕГО, включая панель, которой это чинят. Поэтому перевод делаем тогда, когда
# бутстрап собирают (`sync`), а `usb-offload.sh mode full` перед переездом ПРОВЕРЯЕТ, что
# прежних строк не осталось.
# ЭТО ПЕРЕВОД, А НЕ НОВАЯ ФОРМА: владельцы формы прежние (install.sh::cron_put и
# update-sched.sh::write_cron), здесь расписание и аргументы остаются ДОСЛОВНО — меняется
# только цель. Своей таблицы задач у бутстрапа нет и быть не должно.
cron_to_boot() {
    [ -f "$CRON" ] || return 0
    grep -q "$DATA_DIR/" "$CRON" 2>/dev/null || return 0     # прежних строк нет — тишина
    sed -i "s#$DATA_DIR/\([A-Za-z0-9_-]*\.sh\)#$BOOT_DIR/boot.sh \1#g" "$CRON" 2>/dev/null || return 1
    /etc/init.d/cron restart >/dev/null 2>&1 || /etc/init.d/crond restart >/dev/null 2>&1 \
        || killall -HUP crond 2>/dev/null || true
    echo "boot: cron-строки переведены на бутстрап ($BOOT_DIR/boot.sh)"
    return 0
}

# --- накопитель ------------------------------------------------------------------------------

libs_loaded=
load_libs() {
    [ -n "$libs_loaded" ] && return 0
    # Сорсим СВОИ копии, а не копии из каталога кода: в режиме `full` того каталога ещё нет —
    # ровно за этим бутстрап их и держит. Гард `if [ -f ]` обязателен: провалившийся `.` в
    # busybox ash убивает шелл НА МЕСТЕ, мимо любого `|| true`.
    if [ -f "$BOOT_DIR/store-lib.sh" ]; then . "$BOOT_DIR/store-lib.sh"; fi
    if [ -f "$BOOT_DIR/mount-lib.sh" ]; then . "$BOOT_DIR/mount-lib.sh"; fi
    command -v store_locate >/dev/null 2>&1 || return 1
    libs_loaded=1
    return 0
}

# ПЕРЕИМЕНОВАНИЕ НАШИХ ИМЁН В /tmp — чужая забота, а вот МОМЕНТ наш. Обновление подменяет
# скрипты под живыми демонами, и новый код ищет пидфайл под новым именем; не найдя — не убьёт
# никого и поднимет второй инстанс (разбор — в шапке ram-lib.sh). Единственная точка, через
# которую проходит КАЖДЫЙ запуск наших целей, — этот файл, поэтому зов стоит здесь, ДО exec.
# Список и правило живут в ram-lib.sh; нет файла (откат на версию без него) — молча мимо.
# В ПОДОБОЛОЧКЕ, и это не перестраховка. Провалившийся `.` в ash — фатальная ошибка спецбилтина:
# шелл выходит НА МЕСТЕ, мимо любого гарда. Файл на накопителе прочитаться может и наполовину
# (том выдернули, флешка сыпется), а этот запускатель — ЕДИНСТВЕННАЯ дорога ко ВСЕМ целям cron
# разом: heal, сторож, панель, трафик. Ровно тем же доводом выше объяснён `sh -n` перед подменой
# boot.sh. Цена — один форк на тик, и он остаётся единственным на быстром пути.
ram_mig() {     # $1 = каталог кода
    if [ -f "$1/ram-lib.sh" ]; then ( . "$1/ram-lib.sh"; ram_migrate ) 2>/dev/null || :; fi
}

# Аптайм целым числом секунд, в $UPTIME_S. Берём именно его, а не `date`: часы на этих роутерах
# прыгают вперёд через ~13 минут после загрузки (RTC нет), и разность настенных часов в этот
# момент врёт — на этом уже хоронили живой туннель (clock-lib.sh::age_since).
# ВЛАДЕЛЕЦ ОТВЕТА — clock-lib.sh::uptime_s (следит C83), и своё чтение тут ОСОЗНАННОЕ. Имя
# РАЗНОЕ намеренно: контракт другой — не печатаем, а
# кладём в переменную, чтобы на быстром пути cron не платить лишним форком. И «не знаю» тут
# ПРОТИВОПОЛОЖНОЕ: владелец отвечает 999999999 («ограничение не сработает»), а мы 0 — для
# find_store это «искать можно», то есть тоже «ограничение не сработает». Копировать слово
# владельца сюда нельзя: с ним троттл сканирования замер бы навсегда. И СОРСИТЬ clock-lib.sh ради
# аптайма бутстрап не станет: он ищет каталог кода — библиотека лежит ВНУТРИ того, чего он ещё не
# нашёл (в раскладке `full` — на несмонтированном накопителе). Разные имена делают это безопасным:
# подключи кто-нибудь библиотеку, и `uptime_s` останется ЕЁ функцией, а наша не перекроется.
uptime_read() {
    UPTIME_S=0
    read -r UPTIME_S _us_rest < /proc/uptime 2>/dev/null || UPTIME_S=0   # raw-uptime: резидентный бутстрап, библиотеки может ещё не быть
    UPTIME_S=${UPTIME_S%%.*}
    case "$UPTIME_S" in ''|*[!0-9]*) UPTIME_S=0 ;; esac
}

# Прерванный переезд кода на накопитель: `enodia` уже переименован, `enodia.new` ещё не встал.
# Окно — один rename, но чинить его больше НЕКОМУ: код, который умеет чинить, лежал бы внутри
# того самого каталога. Поэтому несколько строк живут здесь, в резидентной части.
store_repair() {     # $1 = каталог-хранилище
    [ -d "$1/enodia" ] && return 0
    if [ -f "$1/enodia.new/heal.sh" ]; then
        mv "$1/enodia.new" "$1/enodia" 2>/dev/null && echo "boot: доиграл прерванный переезд ($1/enodia.new)"
    elif [ -f "$1/enodia.old/heal.sh" ]; then
        mv "$1/enodia.old" "$1/enodia" 2>/dev/null && echo "boot: вернул код из $1/enodia.old — переезд не удался"
    fi
    [ -d "$1/enodia" ]
}

# Найти хранилище с кодом; путь кладёт в $FOUND_STORE.
# Сперва КЭШ — это нормальный путь после первой удачи: один тест вместо перебора монтирований.
# Промах кэша ведёт к поиску, но не чаще раза в $SCAN_EVERY секунд: строк cron семь, а поиск
# перебирает файловые системы на КАЖДОМ кандидате.
find_store() {
    FOUND_STORE=
    if [ -f "$STORE_CACHE" ]; then
        _fs_c=
        read -r _fs_c < "$STORE_CACHE" 2>/dev/null || :
        if [ -n "$_fs_c" ] && [ -f "$_fs_c/enodia/heal.sh" ]; then
            FOUND_STORE="$_fs_c"; return 0
        fi
    fi
    load_libs || return 1
    uptime_read
    _fs_now="$UPTIME_S"
    if [ -f "$SCAN_STAMP" ]; then
        _fs_last=0
        read -r _fs_last < "$SCAN_STAMP" 2>/dev/null || _fs_last=0
        case "$_fs_last" in ''|*[!0-9]*) _fs_last=0 ;; esac
        # Аптайм МЕНЬШЕ отметки быть не может: /tmp — ОЗУ, ребут снимает и отметку тоже.
        [ $((_fs_now - _fs_last)) -lt "$SCAN_EVERY" ] && return 1
    fi
    printf '%s\n' "$_fs_now" > "$SCAN_STAMP" 2>/dev/null
    store_locate || return 1
    store_repair "$STORE_FOUND" || return 1
    [ -f "$STORE_FOUND/enodia/heal.sh" ] || return 1
    # Кэш переписываем ТОЛЬКО при смене пути: /data смонтирован sync, а нас зовут каждую минуту.
    _fs_old=
    [ -f "$STORE_CACHE" ] && read -r _fs_old < "$STORE_CACHE" 2>/dev/null
    [ "$_fs_old" = "$STORE_FOUND" ] || printf '%s\n' "$STORE_FOUND" > "$STORE_CACHE" 2>/dev/null
    FOUND_STORE="$STORE_FOUND"
    return 0
}

# --- заглушка ---------------------------------------------------------------------------------
#
# Без неё «панели нет» ничем не объясняется: в режиме `full` панель, письма и журнал — всё на
# накопителе, и человек видит мёртвый адрес. Держим резидентно пару килобайт и поднимаем на них
# тот же uhttpd. Ни CGI, ни Basic: показывать нечего, кроме причины.
stub_running() {
    [ -f "$STUB_PID" ] || return 1
    _sr_p=
    read -r _sr_p < "$STUB_PID" 2>/dev/null || return 1
    [ -n "$_sr_p" ] && [ -d "/proc/$_sr_p" ]
}

stub_up() {
    stub_running && return 0
    [ -f "$BOOT_DIR/stub/index.html" ] || return 1
    [ -x /usr/sbin/uhttpd ] || return 1
    if [ -f "$BOOT_DIR/router-lib.sh" ]; then . "$BOOT_DIR/router-lib.sh"; fi
    command -v lan_if >/dev/null 2>&1 || return 1
    _su_if=$(lan_if)
    [ -n "$_su_if" ] || return 1
    _su_ip=$(ip -4 addr show "$_su_if" 2>/dev/null | awk '/inet /{print $2; exit}' | cut -d/ -f1)
    # АДРЕСА ЕЩЁ НЕТ — не поднимаемся вовсе. Иначе занимаем «дефолтный» 192.168.31.1, который
    # на этом роутере может принадлежать кому угодно (та же грабля, что у web-ui.sh на буте).
    [ -n "$_su_ip" ] || return 1
    # Порт занят кем-то ещё (настоящая панель успела встать) — заглушке там делать нечего.
    netstat -ltn 2>/dev/null | grep -q "[.:]$STUB_PORT " && return 0
    start-stop-daemon -S -b -m -p "$STUB_PID" -x /usr/sbin/uhttpd -- \
        -f -h "$BOOT_DIR/stub" -p "$_su_ip:$STUB_PORT" -I index.html -D -S
}

# `-K` пишет в STDOUT — глушим: нас зовут из cron и из hotplug, а вывод уходит в лог сторожа.
stub_down() {
    stub_running || { rm -f "$STUB_PID" 2>/dev/null; return 0; }
    start-stop-daemon -K -p "$STUB_PID" -x /usr/sbin/uhttpd >/dev/null 2>&1
    rm -f "$STUB_PID" 2>/dev/null
}

# --- hotplug ------------------------------------------------------------------------------------
#
# /etc/hotplug.d — ramfs (на BE7000 весь /etc), файл гибнет на ребуте ⇒ кладём его на КАЖДОМ
# прогоне. Первый бут хук не ускоряет — его ещё нет; зато вставка на ходу отрабатывает за
# секунду вместо минуты ожидания cron. UCI-fstab для этого не годится: серийник тома exFAT
# меняется при форматировании, а второй монтаж того же устройства бьёт ФС.
hook_ensure() {
    # Каталог берём ИЗ САМОГО $HOOK, а не литералом: второй экземпляр пути разошёлся бы с первым,
    # а стенд подменяет ровно одну переменную.
    _he_d=${HOOK%/*}
    [ -d "$_he_d" ] || mkdir -p "$_he_d" 2>/dev/null || return 1
    if [ -f "$HOOK" ]; then
        _he1=; _he2=
        { read -r _he1; read -r _he2; } < "$HOOK" 2>/dev/null
        [ "$_he2" = "$HOOK_TAG" ] && return 0
    fi
    {
        echo '#!/bin/sh'
        echo "$HOOK_TAG"
        echo '[ "$ACTION" = add ] || exit 0'
        echo 'case "$DEVNAME" in sd*) ;; *) exit 0 ;; esac'
        echo "$BOOT_DIR/boot.sh hotplug >/dev/null 2>&1"
    } > "$HOOK.new" 2>/dev/null || return 1
    chmod +x "$HOOK.new" 2>/dev/null
    mv "$HOOK.new" "$HOOK" 2>/dev/null
}

# --- РАННИЙ СТАРТ (там, где /etc переживает ребут) -----------------------------------------
#
# ЗАЧЕМ. На роутерах с персистентным /etc (AX3600, BE3600) наш сниппет `server=127.0.0.1#5053`
# переживает ребут: dnsmasq стартует рано и сразу форвардит на прокси шифрованного DNS, а прокси
# поднимал ПЕРВЫЙ ТИК CRON, то есть на ближайшей границе минуты. Замер 31.08.2026 на живом
# AX3600: аптайм 60 с — порт 5053 не слушает, 107 с — слушает. Снаружи это выглядит как
# «перезагрузил роутер — полминуты нет интернета» при полностью живом роутере.
# Фолбэк вторым `server=` на публичный DNS не годится: это ровно та утечка, от которой
# шифрованный DNS и защищает, причём молча и на каждом буте.
#
# ПЕРСИСТЕНТНОСТЬ /etc УЗНАЁМ ФАКТОМ, А НЕ СПИСКОМ МОДЕЛЕЙ. Кладём файл с идентификатором
# ЗАГРУЗКИ (`/proc/sys/kernel/random/boot_id`); на следующем буте он либо исчез (ramfs — BE7000),
# либо несёт ЧУЖОЙ id, и это доказательство. Пока доказательства нет — не делаем НИЧЕГО: цена
# ошибки в другую сторону — вечный init-скрипт на роутере, который его не переживёт и не уберёт.
# Отсюда же честное свойство: на новой прошивке фича включится со ВТОРОГО ребута.
etc_persistent() {
    _ep_now=
    read -r _ep_now < "$BOOT_ID" 2>/dev/null || return 1
    [ -n "$_ep_now" ] || return 1
    _ep_was=
    [ -f "$PERSIST_PROBE" ] && read -r _ep_was < "$PERSIST_PROBE" 2>/dev/null
    if [ -z "$_ep_was" ]; then
        printf '%s\n' "$_ep_now" > "$PERSIST_PROBE" 2>/dev/null
        return 1
    fi
    [ "$_ep_was" != "$_ep_now" ]
}

# Кладём init-скрипт и включаем его. Идемпотентно и по МЕТКЕ ВЕРСИИ (вторая строка), как хук:
# файл персистентен, и переписывать его каждую минуту — это запись на флеш раз в минуту.
# Симлинк в /etc/rc.d делаем САМИ: это ровно то, что делает `enable` у rc.common, но не зависит
# от того, жив ли rc.common на конкретной прошивке.
init_ensure() {
    etc_persistent || return 1
    # Каталоги берём ИЗ САМИХ путей (как у хука): второй литерал разошёлся бы с первым, а стенд
    # подменяет ровно переменные.
    _ie_d=${INIT_SCRIPT%/*}
    [ -d "$_ie_d" ] || return 1
    if [ -f "$INIT_SCRIPT" ]; then
        _ie1=; _ie2=
        { read -r _ie1; read -r _ie2; } < "$INIT_SCRIPT" 2>/dev/null
        [ "$_ie2" = "$INIT_TAG" ] && [ -e "$INIT_LINK" ] && return 0
    fi
    {
        echo '#!/bin/sh /etc/rc.common'
        echo "$INIT_TAG"
        echo 'START=20'
        echo 'start() {'
        # В ФОНЕ и через бутстрап: загрузка не должна ждать нас, а где лежит код — знает он.
        echo "    $BOOT_DIR/boot.sh doh-early >/dev/null 2>&1 &"
        echo '}'
        echo 'stop() { :; }'
    } > "$INIT_SCRIPT.new" 2>/dev/null || return 1
    chmod +x "$INIT_SCRIPT.new" 2>/dev/null
    mv "$INIT_SCRIPT.new" "$INIT_SCRIPT" 2>/dev/null || return 1
    mkdir -p "${INIT_LINK%/*}" 2>/dev/null
    ln -sf "$INIT_SCRIPT" "$INIT_LINK" 2>/dev/null
    return 0
}

# Хук нужен там, где накопитель вообще участвует: режим `full` (код на нём) или включённый
# оффлоад бинарей (маркер на флеше роутера). В чистом `data` он бесполезен.
hook_wanted() {
    [ -f "$DATA_DIR/heal.sh" ] || return 0
    [ -f "$DATA_STATE/.bin-store" ]
}

# --- разрешение путей ----------------------------------------------------------------------------
#
# Кладёт ответ в R_MODE/R_DIR/R_STATE/R_BIN/R_STORE. Именно переменными, а не строкой полей:
# путь к хранилищу может содержать ПРОБЕЛ (`/mnt/My Flash/enodia-store` — законная точка
# стокового automount), и любая форма `set -- $строка` порвала бы его пополам.
resolve() {
    R_MODE=; R_DIR=; R_STATE=; R_BIN=; R_STORE=
    if [ -f "$DATA_DIR/heal.sh" ]; then
        if [ -f "$DATA_STATE/.bin-store" ]; then R_MODE=bins; else R_MODE=data; fi
        R_DIR="$DATA_DIR"; R_STATE="$DATA_STATE"; R_BIN="$DATA_BIN"
        return 0
    fi
    find_store || return 1
    R_MODE=full
    R_STORE="$FOUND_STORE"
    R_DIR="$FOUND_STORE/enodia"
    R_STATE="$FOUND_STORE/enodia-state"
    R_BIN="$FOUND_STORE/bin"
    return 0
}

export_paths() {
    ENODIA_DIR="$R_DIR"
    ENODIA_STATE="$R_STATE"
    ENODIA_BIN="$R_BIN"
    ENODIA_BOOT="$BOOT_DIR"
    export ENODIA_DIR ENODIA_STATE ENODIA_BIN ENODIA_BOOT
}

# --- вербы ----------------------------------------------------------------------------------------

cmd_hotplug() {
    # СОБЫТИЕ ДИСКА С РАЗДЕЛАМИ — НЕ НАШЕ. Сток монтирует флешку в той же очереди событий: `10-mount`
    # (`/sbin/block hotplug`, auto_mount) — синхронно и на событии РАЗДЕЛА, а наш `99-enodia-usb` в каждом
    # событии идёт после него. На событии ДИСКА (sdb) до раздела очередь ещё не дошла: мы находили sdb1
    # несмонтированным и монтировали его сами, а сток следом монтировал его ещё раз — одно устройство в
    # двух точках на КАЖДОЙ горячей вставке (замер BE7000 28.09.2026, дважды подряд; для ext4 суперблок
    # общий, но NTFS стока другим драйвером на занятое устройство уже не встанет). На событии раздела сток
    # своё уже сделал — там и работаем. ФС прямо на диске (разделов нет) — её событие и есть событие
    # диска. DEVTYPE не пришёл (иная прошивка) — работаем как прежде.
    if [ "$DEVTYPE" = disk ] && [ -n "$DEVNAME" ] && load_libs && dev_has_parts "$DEVNAME"; then return 0; fi
    # …и сами монтируем ТОЛЬКО устройство этого события (mount-lib.sh::mount_candidates): соседний раздел того же диска ждёт
    # СВОЕГО события, на котором сток смонтирует его раньше нас (ревью, круг 1: данные на sdb2 за служебным sdb1). Переменная не
    # экспортируется — heal и панель, которых зовём ниже, её не наследуют; движку накопителя отдаём явно.
    ENODIA_ONLY_DEV=; [ -n "$DEVTYPE" ] && ENODIA_ONLY_DEV=$DEVNAME
    # Лок НЕ ЖДЁТ: событие одной флешки бывает не одно (разделов несколько, повторное add), и второму
    # делать нечего — первый уже монтирует. mkdir атомарен, /tmp = ОЗУ.
    mkdir "$BOOT_LOCK" 2>/dev/null || return 0
    trap 'rm -rf "$BOOT_LOCK"' EXIT
    trap 'exit 1' INT TERM HUP PIPE
    rm -f "$SCAN_STAMP" 2>/dev/null          # событие важнее троттла: ищем немедленно
    hook_ensure
    if resolve; then
        if [ "$R_MODE" = full ]; then
            stub_down
            boot_refresh "$R_DIR"
            export_paths
            [ -f "$R_DIR/web-ui.sh" ] && sh "$R_DIR/web-ui.sh" start >/dev/null 2>&1
            [ -f "$R_DIR/heal.sh" ] && sh "$R_DIR/heal.sh" >/dev/null 2>&1
        else
            # Режимы data|bins: код на месте, а событие интересно движку накопителя — он
            # смонтирует хранилище бинарей, не дожидаясь тика сторожа.
            _mnt_ok=1
            [ -f "$R_DIR/usb-offload.sh" ] && { ENODIA_ONLY_DEV="$ENODIA_ONLY_DEV" sh "$R_DIR/usb-offload.sh" mount-ensure >/dev/null 2>&1; _mnt_ok=$?; }
            # …И СРАЗУ ДАЁМ СТОРОЖУ ТИК. В режиме `bins` бинари приезжают ПОЗЖЕ кода: у тестера
            # (тестер, 01.09.2026) heal побежал на 61-й секунде аптайма, а сток примонтировал
            # накопитель на 90-й — heal свой бутовый лок уже потратил (он 1×/boot) и не
            # возвращается, так что поднять несущую в эту загрузку больше некому, кроме сторожа.
            # Он это умеет (ветка «несущую ещё не поднимали»), но приходит по cron раз в две
            # минуты — и всё это время роутер стоит без транспорта при живом накопителе.
            # Событие уже случилось, ждать нечего; тик сам берёт свой лок, а `carrier_installed`
            # до появления бинарей попыток подъёма не тратит. ТРИ УСЛОВИЯ, и каждое куплено:
            # (1) только при rc=0 от mount-ensure — block-событие приходит на ЛЮБУЮ воткнутую
            # флешку, чужая не повод заводить тик; (2) только ФОНОМ — нас позвал hotplug-
            # обработчик ядра, а тик идёт с таймаутами проб и перебором резервов, то есть
            # держал бы очередь событий (в ней и стоковые обработчики) под нашим $BOOT_LOCK;
            # (3) `nohup`/`setsid` в busybox нет — фон только start-stop-daemon, `-m -p`
            # обязательны. Цель зовём ЧЕРЕЗ БУТСТРАП: пути экспортирует он один. Тик — не сразу,
            # а ПОСЛЕ heal (`hotplug-tick`, см. ниже): пришедший во время heal он вышел бы по грейсу.
            [ "$_mnt_ok" = 0 ] && [ -f "$R_DIR/watchdog.sh" ] && start-stop-daemon -S -b -m -p "$HOTPLUG_PID" \
                -x /bin/sh -- "$BOOT_DIR/boot.sh" hotplug-tick >/dev/null 2>&1
        fi
    fi
    # Порядок «снять, потом сбросить ловушку» — сознательно ОБРАТНЫЙ прочим локам (C121): сроку годности у этого лока нет, и
    # сигнал между сбросом и снятием оставил бы его до ребута — хотплаг молчал бы на КАЖДОЙ флешке. Обратное окно (лок снят
    # дважды) стоит только гонки двух событий одного подключения.
    rm -rf "$BOOT_LOCK"
    trap - EXIT HUP INT TERM PIPE
    return 0
}

# --- hotplug-тик: ДОЖДАТЬСЯ heal, потом тик сторожа ---------------------------------------------
# Тик, спавнутый хуком сразу, приходил, пока heal ещё бежит (у тестера heal стартовал на 61-й
# секунде, сток монтировал на 90-й), а бегущий heal (пид в локе) держит грейс сторожа — тик выходил
# впустую, и подъём уезжал на cron. Ждём «done» (потолок $HOTPLUG_WAIT), затем тик: тот увидит
# «heal отработал, несущей нет, есть чем поднять» и поднимет её сам (watchdog boot_grace_waived).
# Лока ещё нет = heal не стартовал — тоже ждём: он сам увидит накопитель и поднимет несущую
# (heal 5.6 переспрашивает готовность прямо перед подъёмом), а тик потом застанет её живой.
# Фоновый процесс, очередь hotplug не держит; второй hotplug при живом ожидании start-stop-daemon
# не спавнит (пидфайл).
# СРОК ЖДЁМ НЕ СЕКУНДОМЕРОМ, А ЖИЗНЬЮ ПРОЦЕССА (инвариант проекта, daemon-lib.sh): heal бывает и
# длиннее потолка (медленный накопитель, закачка списков, шесть ожиданий резолва), и тогда тик по
# таймауту вышел бы ровно туда, откуда его убирали, — подъём несущей НАПЕРЕГОНКИ с бегущим heal.
# Потолок остаётся страховкой на «лок держит труп»: там ждать нечего. Лока нет вовсе (cron ещё не
# завёл heal) — ждём его появления тем же потолком, потом идём: подъём — наша работа.
cmd_hotplug_tick() {
    _ht=0
    while : ; do
        _hl=$(cat "$HEAL_LOCK" 2>/dev/null | tr -d '\r')
        case "$_hl" in done*) break ;; esac
        _hp=${_hl%% *}
        case "$_hp" in
            ''|*[!0-9]*) _hp='' ;;
            *) if [ -d "/proc/$_hp" ]; then
                   # ПИД МОГ БЫТЬ ПЕРЕИСПОЛЬЗОВАН — спрашиваем cmdline, как это делают сам heal и
                   # сторож. Без этого чужой долгоживущий процесс на том же номере держал бы
                   # ожидание ВЕЧНО (потолок консультируется только при мёртвом держателе), и тик,
                   # заведённый ради скорости, не побежал бы вовсе (ревью 3, 06.09.2026).
                   case "$(tr '\000' ' ' 2>/dev/null < "/proc/$_hp/cmdline")" in
                       ''|*heal.sh*) ;;
                       *) _hp='' ;;
                   esac
               else _hp=''; fi ;;                    # лок держит труп — ждать нечего
        esac
        # Держателя нет (лок пуст, труп, чужой процесс) — ждать НЕЧЕГО: даём heal минуту на старт
        # по cron и идём. Живой heal ждём до потолка: он и поднимет несущую, а мы придём следом.
        [ -n "$_hp" ] || { [ "$_ht" -ge "$HOTPLUG_NOLOCK_WAIT" ] && break; }
        [ "$_ht" -lt "$HOTPLUG_WAIT" ] || break
        sleep 5; _ht=$((_ht + 5))
    done
    # Пидфайл — ДО exec: он остаётся от нас и живёт до ребута, а start-stop-daemon сверяет лишь
    # «пид жив и это /bin/sh» ⇒ любой шелл на переиспользованном номере запретил бы следующий
    # hotplug-тик (ревью 06.09.2026). Свою цель тик уже не потеряет: exec идёт следующей строкой.
    rm -f "$HOTPLUG_PID" 2>/dev/null
    exec sh "$0" watchdog.sh
}

# Печатаем И активные пути, И «домашние» пути флеша роутера. Вторые нужны движку режимов: он
# возвращает код с накопителя обратно, а литералов у него быть не должно — владелец их ОДИН,
# и это бутстрап (тот же довод, что у store-lib.sh для имён хранилища).
# `mode=none` со списком data_* — законный ответ: код на накопителе, а накопителя нет, но
# КУДА его возвращать, спрашивающий узнать вправе.
# Ранний подъём шифрованного DNS — единственное, что делает init-скрипт. Узко и намеренно:
# всё остальное (правила, транспорт, панель) по-прежнему поднимает heal.sh с cron, и звать его
# отсюда нельзя — бутовый лок 1×/boot слишком ранний прогон СЪЕЛ бы.
cmd_doh_early() {
    resolve || return 1
    export_paths
    [ -f "$R_DIR/doh-lib.sh" ] || return 1
    sh "$R_DIR/doh-lib.sh" start
}

cmd_paths() {
    if resolve; then
        echo "mode=$R_MODE"
        echo "dir=$R_DIR"
        echo "state=$R_STATE"
        echo "bin=$R_BIN"
        echo "store=$R_STORE"
    else
        echo "mode=none"
    fi
    echo "boot=$BOOT_DIR"
    echo "data_dir=$DATA_DIR"
    echo "data_state=$DATA_STATE"
    echo "data_bin=$DATA_BIN"
    [ -n "$R_MODE" ]
}

cmd_status() {
    if ! resolve; then
        echo "Режим: full (код на накопителе), но накопитель НЕ НАЙДЕН"
        if stub_running; then echo "Заглушка: поднята (порт $STUB_PORT)"; else echo "Заглушка: не поднята"; fi
        return 1
    fi
    case "$R_MODE" in
        data) echo "Режим: data — всё на флеше роутера" ;;
        bins) echo "Режим: bins — бинари на накопителе, код и настройки на флеше роутера" ;;
        full) echo "Режим: full — код, настройки и бинари на накопителе ($R_STORE)" ;;
    esac
    echo "Код: $R_DIR"
    echo "Настройки: $R_STATE"
    echo "Бинари: $R_BIN"
    code_of "$BOOT_DIR/VERSION" || CODE_OF='?'
    _cs_b="$CODE_OF"
    code_of "$R_DIR/VERSION" || CODE_OF='?'
    echo "Бутстрап: $BOOT_DIR (сборка $_cs_b, код $CODE_OF)"
    stub_running && echo "Заглушка: поднята (порт $STUB_PORT)"
    return 0
}

