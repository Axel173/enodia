    exit 1
fi
R_DIR="$FOUND_STORE/enodia"
R_STATE="$FOUND_STORE/enodia-state"
R_BIN="$FOUND_STORE/bin"
export_paths
ram_mig "$R_DIR"
exec sh "$R_DIR/$target" "$@"
