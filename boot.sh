case "$1" in
    ''|-h|--help|help)
        echo "usage: $0 <имя>.sh [аргументы] | hotplug | hotplug-tick | doh-early | ram-migrate | sync [каталог] | paths | status"
        exit 2
        ;;
    hotplug)   cmd_hotplug;   exit $? ;;
    hotplug-tick) cmd_hotplug_tick; exit $? ;;   # фон из cmd_hotplug: дождаться heal и дать тик сторожу
    doh-early) cmd_doh_early; exit $? ;;
    # Перенос наших имён в /tmp из прошлой эпохи БЕЗ запуска цели. Штатно миграция едет перед
    # КАЖДЫМ запуском цели (ram_mig ниже), но точечная заливка с ПК (`enodia.py --push`) целей не
    # запускает — и до ближайшего тика cron код НОВОЙ эпохи живёт рядом с пидфайлами СТАРОЙ. В это
    # окно `down` не находит пидфайл, никого не гасит, рапортует успех, а `up` поднимает ВТОРОЙ
    # инстанс на том же порту (сирота до ребута). Поэтому у миграции есть свой верб, и его зовёт
    # заливка.
    ram-migrate) resolve || :; ram_mig "$R_DIR"; exit 0 ;;
    paths)   cmd_paths;   exit $? ;;
    status)  cmd_status;  exit $? ;;
    sync)
        # Сборка бутстрапа с нуля — зовёт install.sh. Каталог кода можно указать явно: на
        # установке boot.sh запускают ИЗ payload, до того как бутстрап вообще существует.
        _sy=${2:-$DATA_DIR}
        [ -f "$_sy/VERSION" ] || { echo "boot: нет $_sy/VERSION — нечего собирать" >&2; exit 1; }
        boot_refresh "$_sy" force || exit 1
        # ...и СРАЗУ переводим прежние cron-строки на себя. Момент выбран не случайно: `sync`
        # зовут установщик и обновление (apply-scripts), то есть ровно те двое, после кого
        # бутстрап на роутере уже есть. Строка, оставшаяся с прямым путём, работает — но
        # переживёт переезд кода на накопитель молча мёртвой.
        cron_to_boot
        echo "boot: бутстрап собран в $BOOT_DIR"
        exit 0
        ;;
esac

target=$1
target_ok "$target" || { echo "boot: недопустимая цель «$target»" >&2; exit 2; }
shift

# БЫСТРЫЙ ПУТЬ. Код на флеше роутера — это большинство установок, и стоить он обязан ровно
# одного теста: ни форка, ни обращения к накопителю. Единственный source здесь — ram-lib.sh
# (перенос имён прошлой эпохи в /tmp), и он назван вслух: пропущенный перенос стоит неубиваемого
# демона-сироты, а сам прогон — около миллисекунды по tmpfs. Libs накопителя по-прежнему не трогаем.
if [ -f "$DATA_DIR/$target" ]; then
    hook_wanted && hook_ensure
    init_ensure
    # ЗАГЛУШКА ДЕРЖИТ ПОРТ ПАНЕЛИ. Она поднимается, когда код живёт на накопителе, а накопителя
    # нет; но код мог вернуться на флеш и БЕЗ ребута — переустановкой с ПК или возвратом
    # раскладки. Тогда 8088 остаётся занят процессом, за которым нет ни одного файла, и
    # настоящая панель молча не встаёт («порт занят другим процессом» в start_why). Тест
    # `[ -f ]` бесплатен, а форк случается ровно один раз — в тот тик, когда заглушку гасим.
    [ -f "$STUB_PID" ] && stub_down
    boot_refresh "$DATA_DIR"
    ram_mig "$DATA_DIR"
    exec sh "$DATA_DIR/$target" "$@"
fi

# Кода на флеше нет ⇒ режим `full`.
hook_ensure
init_ensure
if ! find_store; then
