#!/bin/sh
# cgi-paths.sh — ЕДИНСТВЕННЫЙ ответ на «где лежат наши каталоги» ДЛЯ CGI ПАНЕЛИ.
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ, ЕСЛИ ЕСТЬ ФОРМА ${VAR:-литерал}. Потому что у CGI её мало: **uhttpd НЕ
# ПЕРЕДАЁТ СКРИПТУ СВОЁ ОКРУЖЕНИЕ**. Замерено на живом BE7000 01.09.2026 пробным CGI: `$0` —
# полный путь скрипта, `PWD` — docroot, а ВСЕ переменные ENODIA_* пусты, хотя uhttpd подняли с
# ними в окружении. Следствие видно только в режиме «всё на накопителе»: каталога кода на флеше
# нет, литералы указывают в пустоту, и панель на живой системе отвечает «ничего не установлено»
# — карточка за карточкой, без единой ошибки на экране.
#
# ОТКУДА БЕРЁМ ОТВЕТ. Каталог кода — БЕСПЛАТНО из `$0`: CGI лежит внутри дерева кода
# (`<КОД>/web/cgi-bin/<имя>`), и это верно в любой раскладке. Настройки и бинари так не
# выводятся: в раскладке флеша это `enodia-state`/`enodia-bin` рядом с кодом, а на накопителе —
# `enodia-state` рядом и `bin` В КОРНЕ хранилища. Спрашиваем ВЛАДЕЛЬЦА (`boot.sh paths`) и
# ТОЛЬКО когда литерал не существует: у обычной раскладки не тратится ни одного форка.
#
# ЭКСПОРТ ОБЯЗАТЕЛЕН. CGI зовут скрипты роутера (usb-offload.sh, transport.sh, geo.sh…), а те
# спрашивают окружение сами (форма ${VAR:-литерал}, следит C60). Без экспорта ребёнок вернулся
# бы к литералам флеша — то есть ровно к той пустоте, от которой мы тут лечимся.
#
# СОРСИТЬ ТОЛЬКО ТАК (гард обязателен: провалившийся `.` в busybox ash убивает шелл на месте):
#   _cgid=${0%/web/cgi-bin/*}; [ "$_cgid" = "$0" ] && _cgid=
#   if [ -n "$_cgid" ] && [ -f "$_cgid/cgi-paths.sh" ]; then . "$_cgid/cgi-paths.sh"; fi
# Строки идут ПЕРВЫМИ — до собственных объявлений CGI: те написаны формой ${VAR:-литерал} и
# после нас становятся no-op, а до нас определяли бы не тот каталог.

ENODIA_DIR=${ENODIA_DIR:-${_cgid:-/data/usr/app/enodia}}
ENODIA_STATE=${ENODIA_STATE:-/data/usr/app/enodia-state}
ENODIA_BIN=${ENODIA_BIN:-/data/usr/app/enodia-bin}
ENODIA_BOOT=${ENODIA_BOOT:-/data/usr/app/enodia-boot}
# КОГДА СПРАШИВАТЬ БУТСТРАП. Признак «раскладка обычная» — это КАТАЛОГ КОДА, а не наличие
# каталога настроек: код лежит на флеше ⇒ рядом с ним и всё остальное. Судить по `[ -d state ]`
# нельзя, и это не теория: переезд в режим `full` кончается удалением трёх каталогов на флеше, и
# он умеет НЕ УДАЛИТЬСЯ («ВНИМАНИЕ: … удалить не вышло (занят?)» — движок это печатает, а не
# падает). Осиротевший `/data/usr/app/enodia-state` после такой осечки существует — и панель
# молча читала бы настройки С ФЛЕША, живя кодом с накопителя: два состояния, расходящихся тем
# сильнее, чем дольше живёт роутер. Спрашиваем владельца ВСЕГДА, когда код не на флеше.
if { [ "$ENODIA_DIR" != /data/usr/app/enodia ] || [ ! -d "$ENODIA_STATE" ]; } \
   && [ -f "$ENODIA_BOOT/boot.sh" ]; then
    _cgp=$(sh "$ENODIA_BOOT/boot.sh" paths 2>/dev/null)
    _cgs=$(printf '%s\n' "$_cgp" | sed -n 's/^state=//p' | tail -1)
    _cgb=$(printf '%s\n' "$_cgp" | sed -n 's/^bin=//p' | tail -1)
    case "$_cgs" in /*) ENODIA_STATE="$_cgs" ;; esac
    case "$_cgb" in /*) ENODIA_BIN="$_cgb" ;; esac
    unset _cgp _cgs _cgb
fi
export ENODIA_DIR ENODIA_STATE ENODIA_BIN ENODIA_BOOT
