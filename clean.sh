#!/bin/sh
#
# clean.sh — БЕЗОПАСНАЯ чистка флеша /data (на BE7000 это ~20 МБ UBIFS, склонен
# забиваться под 100% от бэкапов переустановок/gh-update; полный /data = «No space»:
# записи виснут/падают, GC тормозит, отсюда транзиентные обрывы и сбросы состояния).
#
# Что делает:
#   1) показывает df НАШЕГО тома + ТОП потребителей (du) в НАШИХ каталогах (код + состояние +
#      бинари) и в корне /data — прозрачно
#      видно, что реально ест флеш (в т.ч. если это НЕ наш мусор, а напр. docker-образы);
#   2) удаляет ТОЛЬКО заведомый мусор НАШЕГО тулинга по белому списку паттернов:
#      .gh-backup/ в каталоге КОДА (снимки пофайлового апдейтера; снимок отката пакета — не мусор) · backups/ · *.bak · *.new (и времянки-точки .*.new) · *.tar.gz/.tgz/.zip ·
#      *.log (на /data) · *.dl брошенной закачки (только пока апдейтер не жив).
#
# КАТАЛОГОВ У НАС ТРИ и судьба у них разная: $ENODIA_DIR (код) обновление заменяет целиком,
# $ENODIA_STATE (настройки) и $ENODIA_BIN (бинари протоколов) его переживают. Мусор заводится
# во ВСЕХ трёх — `*.new` от оборванной закачки бинаря лежит рядом с бинарём, а не с кодом.
#
# ЧТО НИКОГДА НЕ ТРОГАЕТ (нет в списке удаления): рабочие конфиги (awg.conf, configs/,
# xray.json, xray-configs/, hev.yaml, notify.conf), бинари (xray/hev/amneziawg-go),
# скрипты *.sh, файлы состояния (.transport/.active/.failover-*/.bypass-*/.iplist.*).
# Удаление идёт по КОНКРЕТНЫМ паттернам, а не «всё кроме» — сломать рабочее нельзя.
#
# ВЕРБЫ:
#   (без аргумента) — текстовый отчёт + чистка мусора. Артефакт уходит в мессенджер.
#   dryrun          — то же, но НИЧЕГО не удалять (только показать кандидатов).
#   json            — МАШИННЫЙ срез для панели: разбивка занятого по категориям (наше —
#                     `cats[]`, стоковое роутера — `sys[]` покусочно) + кандидаты на чистку
#                     с размерами. Ничего не меняет.
#   clean [группы]  — чистка для панели, ответ JSON. Группы через пробел/запятую:
#                     junk (деф.) · snaps · ramlogs · stocklogs. Без аргументов = только junk.
#
# ЧЕТЫРЕ ГРУППЫ ЧИСТКИ, а не одна — потому что цена у них РАЗНАЯ, и валить их в одну кнопку
# нечестно:
#   * junk    — безусловный мусор (бэкап обновления, архивы, *.bak/*.new, логи на флеше).
#               Сносится смело: восстановление не нужно никому.
#   * snaps   — снимки списков и гео. Это ФОЛБЭК: `iplist-update.sh` поднимает из снимка
#               маршрутизацию, когда источник умер. Снос не теряет данные (докачаются), но
#               теряет страховку до следующей удачной закачки ⇒ ОТДЕЛЬНАЯ галочка.
#   * ramlogs — логи в /tmp. Это ОЗУ, а не флеш: чистка НЕ добавит ни байта на /data, зато
#               снимет мегабайты с tmpfs (у doh.log ротации нет вовсе, на живом роутере он
#               доходил до 1.1 МБ). Подписано в панели именно так, иначе цифра врёт.
#   * stocklogs — СТОКОВЫЙ системный лог роутера на флеше. ЕДИНСТВЕННАЯ группа, где мы трогаем
#               НЕ СВОЁ, и единственная, где потеря необратима: это тот самый лог, что переживает
#               ребут и уезжает в диаг-архив. Зато он же — второй по величине потребитель /data
#               после нашего каталога (замер BE7000 18.08.2026: 3.8 МБ). Деф. ВЫКЛ, галочка
#               отдельная, цена названа прямо в панели.
#
# ПОЧЕМУ БИНАРИ ОПОЗНАЮТСЯ ЭВРИСТИКОЙ, а не списком из packages.sh: список там ведётся ради
# УСТАНОВКИ (связка → файлы), а здесь нужен ответ «что вообще лежит», включая бинарь, которого
# ни одна связка не знает (руками положенный, осиротевший после отката). Правило «исполняемый
# файл в корне ENODIA_DIR, не *.sh и не мусор» самоподдерживающееся: новый бинарь считается сам.
#
# Вывод текстового режима — чистый текст (артефакт уходит в мессенджер), JSON-вербов — одна
# строка JSON (busybox без jq: собираем printf'ом, как остальные CGI-движки проекта).

ENODIA_DIR=${ENODIA_DIR:-/data/usr/app/enodia}
ENODIA_STATE=${ENODIA_STATE:-/data/usr/app/enodia-state}
ENODIA_BIN=${ENODIA_BIN:-/data/usr/app/enodia-bin}
# ...А ЕСЛИ ПО ЛИТЕРАЛАМ НИЧЕГО НЕТ — СПРОСИМ ВЛАДЕЛЬЦА. Нас зовут ТРИ разных места, и одно из
# них — самодостаточный инструмент тестера (enodia-diag.py / enodia-clean.py): он исполняет нас
# через `base64 -d | sh`, то есть БЕЗ единой переменной окружения. В режиме «всё на накопителе»
# каталоги на флеше пусты, и артефакт описал бы НЕ ТУ систему: «нет VERSION», «каталог пуст»,
# «транспорт не выбран» при живом туннеле. Спрашиваем бутстрап и только по ФАКТУ отсутствия —
# у роутера с обычной раскладкой не тратится ни одного форка.
ENODIA_BOOT=${ENODIA_BOOT:-/data/usr/app/enodia-boot}
if [ ! -f "$ENODIA_DIR/VERSION" ] && [ -f "$ENODIA_BOOT/boot.sh" ]; then
    _bp=$(sh "$ENODIA_BOOT/boot.sh" paths 2>/dev/null)
    _bd=$(printf '%s\n' "$_bp" | sed -n 's/^dir=//p' | tail -1)
    _bs=$(printf '%s\n' "$_bp" | sed -n 's/^state=//p' | tail -1)
    _bb=$(printf '%s\n' "$_bp" | sed -n 's/^bin=//p' | tail -1)
    case "$_bd" in /*) ENODIA_DIR="$_bd" ;; esac
    case "$_bs" in /*) ENODIA_STATE="$_bs" ;; esac
    case "$_bb" in /*) ENODIA_BIN="$_bb" ;; esac
    unset _bp _bd _bs _bb
fi
# Наши каталоги ОДНИМ списком: их перечисляют разбивка занятого, обход «не нашего» и
# текстовый ТОП. Три копии перечня разъехались бы на первом же новом каталоге, и цена
# у расхождения разная в каждом месте — от «состояние засчиталось в систему роутера»
# до «мусор в каталоге бинарей не виден кнопке очистки».
# ЧЕТВЁРТЫЙ — резидентный бутстрап на /data (boot.sh + библиотеки поиска накопителя +
# заглушка). Он маленький (десятки килобайт), но в режиме полной установки на накопитель это
# ЕДИНСТВЕННОЕ наше, что лежит на флеше роутера: не назови мы его — разбивка занятого показала
# бы «наших файлов на флеше нет», хотя они есть, и он же не попал бы в обход «не нашего».
# Сам $ENODIA_BOOT объявлен ВЫШЕ — там, где у него первый потребитель (разбор путей бутстрапа).
OUR_DIRS="$ENODIA_DIR $ENODIA_STATE $ENODIA_BIN $ENODIA_BOOT"
# «Жив ли процесс» (daemon-lib.sh::pid_runs) — чтобы не снести `.dl` идущей закачки (junk_targets). У инструмента тестера
# (`base64 -d | sh`) библиотеки может не быть — тогда `.dl` просто не считаем мусором.
if [ -f "$ENODIA_DIR/daemon-lib.sh" ]; then . "$ENODIA_DIR/daemon-lib.sh"; fi
DRY=0
MODE=text
# Пустой аргумент = историчный text-режим (отчёт + чистка) — так нас зовёт enodia-clean.py.
# А вот НЕИЗВЕСТНЫЙ верб раньше проваливался СЮДА ЖЕ, то есть опечатка в вызове («jsno», будущий
# верб на старом роутере) молча УДАЛЯЛА мусор вместо того, чтобы отказаться. Отвечаем usage.
case "${1:-}" in
    "")     : ;;
    dryrun) DRY=1 ;;
    json)   MODE=json ;;
    clean)  MODE=clean ;;
    # ТОЛЬКО перечислить непустые логи в ОЗУ и выйти. Верб read-only и нужен ЧУЖОЙ стороне:
    # «Логи роутера» в enodia.py держал СВОЙ список имён и отстал ровно так же, как отставал
    # дамп (04.08.2026: мимо ПК-просмотра проходили doh, subs-update, support, panel-tls,
    # enodia-dnsq, transport-awg-setup и все пер-слотовые). Список мусора и логов в ОЗУ — истина
    # ОДНА, и живёт она здесь; потребители обязаны СПРАШИВАТЬ, а не копировать.
    ramlogs-list) MODE=ramlogs-list ;;
    *) echo "usage: $0 [dryrun|json|clean [junk snaps ramlogs stocklogs]|ramlogs-list]" >&2; exit 2 ;;
esac

# --- примитивы размера ---------------------------------------------------------------
# busybox du умеет только -s -k (нет -b/-c): считаем в КИЛОБАЙТАХ и переводим в байты сами.
# Размер блочный (с хвостом кластера) — это и правильно: панель показывает, сколько реально
# занято на UBIFS, а не сумму логических длин.
#
# `-x` (не пересекать границу ФС) ОБЯЗАТЕЛЕН, и вот почему (измерено на BE7000): в `/data`
# смонтирована ЧУЖАЯ файловая система — `/dev/mapper/sec_cfg` (ext4) на `/data/etc/config`,
# а её образ лежит тут же файлом `/data/sec_cfg/data.vol` (4 МБ). Без `-x` содержимое образа
# считалось ДВАЖДЫ: один раз как сам файл-контейнер, второй — как смонтированный каталог, и
# «Система роутера» раздувалась на ~140 КБ из воздуха. `--exclude` у busybox НЕТ, `-x` есть.
sz_k() {                        # суммарный размер СУЩЕСТВУЮЩИХ путей, КБ
    _t=0
    for _p in "$@"; do
        [ -e "$_p" ] || continue
        _v=$(du -xsk "$_p" 2>/dev/null | awk '{print $1}')
        case "$_v" in ''|*[!0-9]*) _v=0 ;; esac
        _t=$((_t+_v))
    done
    echo "$_t"
}
# ТОМ, о котором идёт речь, спрашиваем ПО ПУТИ нашего каталога: `df /data` — литерал, а на
# BE10000 `/data` = стоковый cfg-том (4.7 МБ), тогда как наш код и мусор живут на `/data/usr`.
# Разбивка «чем занято» и цифра «освободилось» обязаны быть про ОДИН И ТОТ ЖЕ том (следит C50).
# ГАРД ЧИСЛОВОЙ (`+0`). `df` по НЕСУЩЕСТВУЮЩЕМУ пути печатает в stdout один ЗАГОЛОВОК, и
# `tail -1` отдаёт его как строку данных ($NF="on", $(NF-4)="Used"). Прежний `$(NF-4)>0`
# его НЕ отсекал: у awk сравнение нечислового поля с числом идёт как СТРОКОВОЕ, а
# "Used" > "0" истинно (замерено на busybox awk 1.25.1 31.08.2026) — отсюда «Флеш on» в
# панели и «Division by zero» в дампе. `+0` принуждает поле к числу.
# ПО ПУТИ — ОДНО выражение на любой том: у чистки их бывает ДВА (том кода и том стокового лога — см. режим clean).
df_k_at()  { df -k "$1" 2>/dev/null | tail -1 | awk 'NF>=5 && $(NF-4)+0>0{print $(NF-4)" "$(NF-3)" "$(NF-2)}'; }
df_mp_at() { _dmp=$(df -k "$1" 2>/dev/null | tail -1 | awk 'NF>=5 && $(NF-4)+0>0{print $NF}'); printf '%s' "${_dmp:-/data}"; }
df_k()  { df_k_at "$ENODIA_DIR"; }
df_mp() { df_mp_at "$ENODIA_DIR"; }

# --- ЕДИНЫЙ список мусора (используют ВСЕ три режима) ---------------------------------
# Одна копия на текстовый отчёт, json и clean: разъехавшиеся списки — ровно та грабля, из-за
# которой инлайн-дубль правил в vpn-toggle отставал от mark-core. Печатает пути по одному в
# строке; несуществующие отсеивает сам (busybox без nullglob оставляет литерал глоба).
junk_targets() {
    # ТОЛЬКО пути на /data: сумма отсюда идёт в разбивку «чем занят ФЛЕШ», и один путь из /tmp
    # (RAM) добавил бы к обещанию «освободится» байты, которых на флеше нет — тот самый класс
    # «панель называет разные числа про одно место». Мусор в ОЗУ убирают другие руки: остаток
    # отработавшего снималщика подбирает установщик (см. install.sh).
    # СНИМОК ОТКАТА — НЕ МУСОР (ревью ветки pkg-update, круг 1). Он живёт в $ENODIA_STATE/.gh-backup (пакетное обновление,
    # 30.09.2026), он ОДИН и он — единственная точка отката: экран чистки звал его «бэкапом обновления, восстанавливать нечего», и
    # отмеченный по умолчанию «Мусор» молча снимал «Откатить». Место под него держит сам установщик пакета (снимает прежний после
    # удачной замены). Мусор — только каталог в КОДЕ: снимки пофайлового апдейтера, откатывать к которым новый путь не умеет.
    for _t in "$ENODIA_DIR/.gh-backup" "$ENODIA_DIR/backups" "$ENODIA_DIR/.dl"; do
        [ -e "$_t" ] && echo "$_t"
    done
    # Расширения-мусор ищем в КАЖДОМ нашем каталоге: `iplist.conf.new` рождается у состояния,
    # `xray.new` — у бинарей (оборванный перенос на накопитель), `*.bak` — у кода.
    # ВРЕМЯНКИ-ТОЧКИ — ОТДЕЛЬНЫМ ГЛОБОМ: `*` у шелла НЕ совпадает с ведущей точкой, а почти всё
    # состояние у нас — файлы-точки, и их времянки тоже (`.panel-layout.<pid>.new`,
    # `.sub-info.<pid>.new`, `.subs.new`). Писатель кладёт такую рядом и тут же делает `mv`, так
    # что осиротеть она может, только если его убили между записью и переносом, — но тогда её
    # не видел никто, хотя код писателя уверял, что «хвост .new опознаёт чистка».
    # ТОЛЬКО `.new`, А НЕ ВСЕ МАСКИ СРАЗУ: файлы-точки `.proto-install.log`, `.zapret-install.log`,
    # `.gh-update.log` — не мусор, а СОСТОЯНИЕ, панель читает из них последнюю строку («что
    # сейчас идёт»); `.*.log` снёс бы ответ на вопрос, который человек задаёт прямо сейчас.
    for _d in $OUR_DIRS; do
        for _t in "$_d"/*.bak "$_d"/*.new "$_d"/.*.new "$_d"/*.tar.gz "$_d"/*.tgz "$_d"/*.zip "$_d"/*.log; do
            [ -e "$_t" ] && echo "$_t"
        done
    done
    # БРОШЕННАЯ ЗАКАЧКА — `<файл>.dl` от gh-update.sh (бинарь до 8 МБ рядом с бинарями, манифест у состояния): закачку
    # оборвали (ребут, `kill -9` операции), и файл лежал до следующей закачки ТОГО ЖЕ файла, невидимый кнопке (бэклог ревью
    # ветки fix/dot-tails, круг 2). Мусор он, только пока апдейтера нет в живых: идущую закачку сносить нельзя, а ВОЗРАСТ
    # тут не судья — у брошенной в прошлую загрузку отметка «старше загрузки», и age_since честно отдаёт 0.
    _dls=""
    for _d in $OUR_DIRS; do
        for _t in "$_d"/*.dl "$_d"/.*.dl; do [ -f "$_t" ] && _dls="$_dls $_t"; done
    done
    if [ -n "$_dls" ] && ! dl_writer_alive; then
        for _t in $_dls; do echo "$_t"; done
    fi
    return 0
}
# Жив ли писатель `.dl` (gh-update.sh в любом из его вербов). Процесс — по argv через daemon-lib.sh::pid_runs (C115: сырой
# cmdline показывает только argv[0], а у скрипта это `sh`). Нет библиотеки — «жив»: не знаем, значит не трогаем.
dl_writer_alive() {
    command -v pid_runs >/dev/null 2>&1 || return 0
    for _p in /proc/[0-9]*; do pid_runs "${_p#/proc/}" 'gh-update\.sh' && return 0; done
    return 1
}

# Снимки списков/гео — ФОЛБЭК, не мусор (см. шапку): отдельная группа, отдельная галочка.
snap_targets() {
    for _t in "$ENODIA_STATE/.iplist.snapshot" "$ENODIA_STATE"/geo/.snap-* \
              "$ENODIA_STATE"/lists/*/.snapshot; do
        [ -e "$_t" ] && echo "$_t"
    done
    return 0
}

