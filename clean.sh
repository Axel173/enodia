subs-update support switch-vpn-setup transport-awg-setup xiaomi-bypass zapret-nfqws"
# ХВОСТ СПИСКА — ИМЕНА ДО 02.09.2026, когда наши логи в /tmp получили префикс `enodia-`. Они не
# «на всякий случай»: обновление меняет СКРИПТЫ, а демон (hev, byedpi, hysteria) продолжает
# писать в файл, открытый по СТАРОМУ пути, — до собственного перезапуска. Не знай мы старого
# имени, кнопка «очистить логи» перестала бы видеть ровно тот мегабайт, который сейчас растёт.
# Уйдут отсюда, когда уйдёт последняя установка тех версий; ребут снимает их сам (/tmp = ОЗУ).
# `xray*` префикса НЕ получил осознанно: путь его логов лежит ВНУТРИ конфигов на /data.
# `xray-access` остаётся в списке НАРОЧНО, хотя с 29.08.2026 его никто не пишет: генераторы
# конфига ставят "access": "none", а старый путь гасит xray-transport.sh (access_off). Но конфиг
# живёт на /data и переживает обновление скриптов ⇒ на роутере, который ещё ни разу не поднимал
# xray после апдейта, простыня на 15 МБ/сут лежит в ОЗУ и убрать её должно быть чем.
# У ДОП-ВЫХОДА свой инстанс демона и свой лог (`xray-s3.log`, `hev-s3.log`, `byedpi-s3.log`,
# `hysteria-s3.log`, `xray-s3.access.log` — этот с 30.08.2026 тоже НИКТО не пишет, слот получает
# «none», но у ставившихся раньше он лежит), а у проверки конфигов — свой на каждый временный
# порт (`xray-test.10812.log`). Список выше их не знал, то есть логи выходов росли в ОЗУ, и
# кнопка «очистить логи» их не видела — а именно они пишутся так же бойко, как основные.
# Имена ПРОИЗВОДНЫЕ, но перечень остаётся явным: маску `/tmp/*.log` брать по-прежнему нельзя.
RAM_LOGS_SLOT="xray enodia-hev enodia-hysteria enodia-byedpi hev hysteria byedpi"  # демоны с пер-слотовым инстансом (+ имена до префикса)
RAM_SLOT_IDS="2 3 4"                        # диапазон номеров выходов (slots.sh)
RAM_XTEST_PORTS="10812 10813 10814 10815 10816 10817 10818 10819"   # xray-test.sh
ramlog_targets() {
    for _n in $RAM_LOGS; do [ -s "/tmp/$_n.log" ] && echo "/tmp/$_n.log"; done
    for _i in $RAM_SLOT_IDS; do
        for _n in $RAM_LOGS_SLOT; do [ -s "/tmp/$_n-s$_i.log" ] && echo "/tmp/$_n-s$_i.log"; done
        [ -s "/tmp/xray-s$_i.access.log" ] && echo "/tmp/xray-s$_i.access.log"
    done
    for _p in $RAM_XTEST_PORTS; do
        [ -s "/tmp/xray-test.$_p.log" ] && echo "/tmp/xray-test.$_p.log"
        [ -s "/tmp/xray-test.$_p.access.log" ] && echo "/tmp/xray-test.$_p.access.log"
    done
    return 0
}

# --- РАЗБИВКА занятого по категориям --------------------------------------------------
# Бинари: см. шапку (эвристика). Мусорные расширения исключаем ЗДЕСЬ же, иначе `xray.new`,
# оставшийся от оборванного обновления, посчитался бы дважды — и как бинарь, и как мусор.
bin_targets() {
    for _f in "$ENODIA_BIN"/*; do
        [ -f "$_f" ] || continue
        # ГРАБЛЯ: перенос строки внутри case-паттерна писать НЕЛЬЗЯ — обратный слэш склеит
        # его с отступом следующей строки, и получится паттерн с ВЕДУЩИМИ ПРОБЕЛАМИ,
        # который не совпадёт ни с чем. Держим одной строкой.
        case "$_f" in
            *.sh|*.conf|*.json|*.yaml|*.yml|*.txt|*.md|*.example|*.bak|*.new|*.dl|*.tar.gz|*.tgz|*.zip|*.log|*/VERSION) continue ;;
        esac
        [ -x "$_f" ] && echo "$_f"
    done
    # Стейдж bin/*.user приезжает ВМЕСТЕ С КОДОМ и живёт в его каталоге, пока установщик
    # его не съест (`mv`). Считаем в бинари: человек ищет мегабайты xray, а не их место.
    [ -d "$ENODIA_DIR/bin" ] && echo "$ENODIA_DIR/bin"
    return 0
}
cfg_targets() {
    for _t in "$ENODIA_STATE/configs" "$ENODIA_STATE/xray-configs" "$ENODIA_STATE/server" \
              "$ENODIA_STATE"/*.conf "$ENODIA_STATE"/*.json "$ENODIA_STATE"/*.yaml \
              "$ENODIA_STATE"/*.yml; do
        [ -e "$_t" ] && echo "$_t"
    done
    return 0
}
lst_targets() {
    for _t in "$ENODIA_STATE/lists" "$ENODIA_STATE/geo"; do [ -e "$_t" ] && echo "$_t"; done
    [ -e "$ENODIA_STATE/.iplist.snapshot" ] && echo "$ENODIA_STATE/.iplist.snapshot"
    return 0
}
sh_targets() { for _t in "$ENODIA_DIR"/*.sh; do [ -e "$_t" ] && echo "$_t"; done; return 0; }

# --- НЕ наше на /data: перечислить КУСКАМИ, а не одной строкой «прочее» ------------------
# Раньше это была ОДНА цифра «Система роутера ≈ 7 МБ» = `du(/data) − du(ENODIA_DIR)`, и она не
# отвечала на единственный вопрос, ради которого её открывают: «а это ВООБЩЕ что и можно ли
# с этим что-то сделать?». На BE7000 внутри сидят четыре разные сущности с разной судьбой
# (контейнер настроек фиксированного размера · логи прошивки · конфиги прошивки · служебное),
# и валить их в одну строку — то же самое, что валить в одну кнопку три группы чистки.
#
# Список строим ОБХОДОМ, а не жёстким перечнем путей: на AX3600/BE3600 состав /data другой, и
# захардкоженные `/data/sec_cfg`&Co молча показали бы там ноль, а весь объём свалился бы в
# «прочее» — ровно та непрозрачность, от которой уходим. Правило обхода: печатаем верхний
# уровень, но ветку, ВЕДУЩУЮ к нашему каталогу, раскрываем глубже — иначе получили бы
# «/data/usr — 15 МБ», где 13 из них наши собственные.
# Каталогов у нас ТРИ, и все три — соседи: пропустить надо КАЖДЫЙ. Пропустив только каталог
# кода, мы записали бы настройки и бинари в «Систему роутера» — графу «сделать нельзя ничего».
# Порядок проверок важен: сперва «это МЫ?» (пропуск), и только потом «мы ВНУТРИ?» (спуск).
sys_walk() {
    for _p in "$1"/* "$1"/.[!.]*; do
        [ -e "$_p" ] || continue
        _ours=0
        for _o in $OUR_DIRS; do
            if [ "$_p" = "$_o" ]; then _ours=1; break; fi
            case "$_o" in "$_p"/*) _ours=2 ;; esac
        done
        if [ "$_ours" = 1 ]; then continue; fi
        if [ "$_ours" = 2 ]; then sys_walk "$_p"; else echo "$_p"; fi
    done
    return 0
}

# --- СТОКОВЫЙ СИСТЕМНЫЙ ЛОГ НА ФЛЕШЕ (группа stocklogs) -------------------------------
# ЕДИНСТВЕННОЕ место, где мы трогаем НЕ СВОЁ, поэтому список предельно узкий и явный.
# Замер BE7000 18.08.2026: /data/usr/log = 3.8 МБ (messages.0 — 3.1 МБ + пять .gz), держателя
# дескриптора нет ни у одного файла (живой syslog пишет в /tmp/messages, то есть в ОЗУ).
# Правило то же, что у наших логов: РОТАЦИЯ (имя с точкой) — удаляем, ЖИВОЙ файл (без точки) —
# обрезаем. Живого на BE7000 тут нет вовсе, но на прошивке, где syslog пишет прямо на флеш,
# удаление отдало бы место лишь после перезапуска демона — а обрезание работает всегда.
#
# ЧТО СЮДА НЕ ВХОДИТ И ПОЧЕМУ (иначе допишут «за компанию»):
#   login_records          — история входов, это ДАННЫЕ пользователя, а не лог;
#   wifi_analysis.log.*    — 394 байта, цена внимания выше выигрыша;
#   /data/sec_cfg          — стоковое защищённое хранилище, переписывается по cron;
#   /data/etc/mipctl       — данные mipctld, того самого, над чьими цепочками стоит наша маркировка;
#   /data/etc/crontabs/*   — там лежит dropbearmulti от xmir-patcher: снести = потерять SSH.
# ЦЕНА, которую панель обязана назвать: это ЕДИНСТВЕННЫЙ лог, переживающий ребут, и ровно его
# кладёт в архив `dump.sh archive`. Снёс — разбирать «что было до перезагрузки» будет нечем.
STOCK_LOG_DIR=/data/usr/log
stocklog_rotated() {   # ротации — удаляем
    for _t in "$STOCK_LOG_DIR"/messages.*; do [ -f "$_t" ] && echo "$_t"; done
    return 0
}
stocklog_live() {      # живой лог, если он на этой прошивке лежит на флеше, — обрезаем
    [ -s "$STOCK_LOG_DIR/messages" ] && echo "$STOCK_LOG_DIR/messages"
    return 0
}
stocklog_targets() { stocklog_rotated; stocklog_live; return 0; }

sum_of() { sz_k $("$@" | tr '\n' ' '); }   # КБ по списку из функции-перечислителя

# =====================================================================================
# РЕЖИМ ramlogs-list — перечень непустых логов в ОЗУ (по одному пути в строке). Read-only.
# Стоит ДО json/clean: отвечает и выходит, ничего не считая (его зовут по SSH за одну строку).
# =====================================================================================
if [ "$MODE" = ramlogs-list ]; then
    ramlog_targets
    exit 0
fi

# =====================================================================================
# РЕЖИМ json — срез для панели. НИЧЕГО не меняет.
# =====================================================================================
if [ "$MODE" = json ]; then
    set -- $(df_k); TOT_K=${1:-0}; USED_K=${2:-0}; FREE_K=${3:-0}

    ENODIA_K=$(sz_k $OUR_DIRS)
    BIN_K=$(sum_of bin_targets)
    WEB_K=$(sz_k "$ENODIA_DIR/web")
    SCR_K=$(sum_of sh_targets)
    CFG_K=$(sum_of cfg_targets)
    LST_K=$(sum_of lst_targets)
    JNK_K=$(sum_of junk_targets)
    SNP_K=$(sum_of snap_targets)
    # ЗАПУСКАТЕЛЬ — СВОЕЙ категорией: он резидентен (всегда на флеше), а остальные наши каталоги в раскладке «всё на
    # накопителе» — на накопителе. В остатке «состояния» он записывался бы на чужой том (найдено ревью шага 6b, 23.09.2026).
    BOOT_K=$(sz_k "$ENODIA_BOOT")
    # «Состояние» — ОСТАТОК, а не своя сумма: десятки точек `.transport`/`.bypass-*`/`.events`
    # перечислять руками бессмысленно (список протухнет с первой новой фичей), а остаток
    # гарантирует, что категории СХОДЯТСЯ с du по каталогу и полоса не врёт.
    # Снимки уже сидят внутри LST_K/ENODIA_K — второй раз не прибавляем.
    ST_K=$((ENODIA_K - BIN_K - WEB_K - SCR_K - CFG_K - LST_K - JNK_K - BOOT_K))
    [ "$ST_K" -lt 0 ] && ST_K=0
    # Не наше — ПОКУСКОВО (sys_walk), плюс остаток «прочее»: он обязан быть около нуля, но
    # если прошивка заведёт новую сущность прямо в корне нашей ветки, лучше увидеть её в
    # «прочем», чем недосчитаться мегабайта в полосе.
    #
    # ГРАБЛЯ (измерено на живом BE7000): считать «не наше» как `df_used − du(ENODIA_DIR)` НЕЛЬЗЯ —
    # это вычитание ДВУХ РАЗНЫХ единиц. UBIFS ПРОЖИМАЕТ данные: du отдаёт ЛОГИЧЕСКИЙ размер,
    # df — реально занятые блоки. На роутере автора du по всему /data = 20944 КБ при df-занято
    # 15884 КБ, то есть сжатие «съедает» ~5 МБ разницы, и «прочее» вышло бы вдвое меньше
    # правды. Поэтому вся разбивка живёт в ОДНОЙ системе координат (du), а df отдаём отдельными
    # полями total/used/free — панель нормирует полосу на data_b, а не на used_b, и ПОДПИСЫВАЕТ
    # обе цифры рядом (иначе сумма по du ≈ ёмкости флеша читается как «занято всё»).
    DATA_K=$(sz_k /data)
    SYS_LIST=$(sys_walk /data | while read -r _p; do
        [ -n "$_p" ] && echo "$(sz_k "$_p") $_p"
    done | sort -rn)
    SYS_K=0
    for _v in $(echo "$SYS_LIST" | awk '{print $1}'); do
        case "$_v" in ''|*[!0-9]*) continue ;; esac
        SYS_K=$((SYS_K+_v))
    done
    OTH_K=$((DATA_K - ENODIA_K - SYS_K)); [ "$OTH_K" -lt 0 ] && OTH_K=0

    kb() { echo $(( ${1:-0} * 1024 )); }
    printf '{"total_b":%s,"used_b":%s,"free_b":%s,"awg_b":%s,"data_b":%s,"sys_b":%s,"cats":[' \
        "$(kb "$TOT_K")" "$(kb "$USED_K")" "$(kb "$FREE_K")" "$(kb "$ENODIA_K")" "$(kb "$DATA_K")" \
        "$(kb "$SYS_K")"
    _first=1
    for _c in "bin $BIN_K" "web $WEB_K" "scripts $SCR_K" "configs $CFG_K" \
              "lists $LST_K" "state $ST_K" "junk $JNK_K" "boot $BOOT_K" "other $OTH_K"; do
        set -- $_c
        [ "$_first" = 1 ] || printf ','
        _first=0
        printf '{"id":"%s","b":%s}' "$1" "$(kb "$2")"
    done
    # sys[] — уже отсортирован по убыванию: панель рисует его как есть (своей сортировки не
    # держит), человеческие названия путей — там же, незнакомый путь показывается как есть.
    printf '],"sys":['
    _first=1
    # `ours` — НАШЕ ПО ИМЕНИ вне наших каталогов: по правилу именования проекта всё наше вне своих каталогов носит префикс
    # `enodia-` (так лежала /data/enodia-backup, и панель называла её прошивкой). Числом «не наше» (sys_b) не меняем.
    # `enodia.*` — времянки переезда кода (`usb-offload.sh` кладёт `enodia.new`/`enodia.old` рядом с каталогом): оборванный
    # питанием переезд оставляет копию кода в несколько мегабайт, и она не прошивка (ревью шага 6b, круг 3).
    echo "$SYS_LIST" | while read -r _b _p; do
        [ -n "$_p" ] || continue
        [ "$_first" = 1 ] || printf ','
        _first=0
        case "${_p##*/}" in enodia|enodia-*|enodia.*) _ou=true ;; *) _ou=false ;; esac
        printf '{"path":"%s","b":%s,"ours":%s}' "$_p" "$(kb "$_b")" "$_ou"
    done
    printf '],"junk":['
    _first=1
    junk_targets | while read -r _p; do
        [ "$_first" = 1 ] || printf ','
        _first=0
        printf '{"path":"%s","b":%s}' "$_p" "$(kb "$(sz_k "$_p")")"
    done
    printf '],"junk_b":%s,"snaps_b":%s,"snaps_n":%s,"ramlogs_b":%s,"ramlogs_n":%s,"stocklogs_b":%s,"stocklogs_n":%s}\n' \
        "$(kb "$JNK_K")" "$(kb "$SNP_K")" "$(snap_targets | wc -l)" \
        "$(kb "$(sum_of ramlog_targets)")" "$(ramlog_targets | wc -l)" \
        "$(kb "$(sum_of stocklog_targets)")" "$(stocklog_targets | wc -l)"
    exit 0
fi

# =====================================================================================
# РЕЖИМ clean — чистка по группам, ответ JSON. Группы: junk (деф.) · snaps · ramlogs.
# =====================================================================================
if [ "$MODE" = clean ]; then
    shift
    # ГРАБЛЯ: переменную НЕЛЬЗЯ звать GROUPS — в bash это встроенный массив с GID'ами
    # пользователя, присваивание молча игнорируется (проверено: `GROUPS=junk` даёт «197609»,
    # и ни одна группа не срабатывает). busybox ash такого не знает, то есть на роутере
    # прошло бы, а на любом bash — нет; имя с префиксом снимает вопрос навсегда.
    CL_GROUPS=$(echo "$*" | tr ',' ' ')
    [ -z "$CL_GROUPS" ] && CL_GROUPS=junk
    has_g() { case " $CL_GROUPS " in *" $1 "*) return 0 ;; esac; return 1; }

    set -- $(df_k); BEFORE_K=${3:-0}
    freed_ram=0; n=0
    # ТОМОВ У ЧИСТКИ БЫВАЕТ ДВА (найдено 23.09.2026 на раскладке «всё на накопителе»). Мусор и снимки лежат на томе КОДА, а
    # стоковый лог — на флеше роутера всегда. Пока код на флеше, это один том; в раскладке `full` код на накопителе, и дельта
    # df тома кода стокового лога не видела вовсе (чистка лога отвечала «чистить было нечего»), а свою называла «на флеше».
    # Том кода — на накопителе, когда он не тот, где резидентный бутстрап (то же правило по факту, что packages.sh::
    # disk_on_store; своей библиотеки clean.sh не тянет — он вшит в enodia-clean.py). Том лога меряем отдельно, если он другой.
    CODE_ON_STORE=""; [ -d "$ENODIA_BOOT" ] && [ "$(df_mp)" != "$(df_mp_at "$ENODIA_BOOT")" ] && CODE_ON_STORE=1
    LOG_APART=""; [ -d "$STOCK_LOG_DIR" ] && [ "$(df_mp_at "$STOCK_LOG_DIR")" != "$(df_mp)" ] && LOG_APART=1
    LBEFORE_K=0; if [ -n "$LOG_APART" ]; then set -- $(df_k_at "$STOCK_LOG_DIR"); LBEFORE_K=${3:-0}; fi

    if has_g junk;  then junk_targets | while read -r _p; do rm -rf "$_p" 2>/dev/null; done; fi
    if has_g snaps; then snap_targets | while read -r _p; do rm -rf "$_p" 2>/dev/null; done; fi
    # Логи не УДАЛЯЕМ, а обрезаем: демон держит дескриптор открытым (`>>`), удалённый файл
    # продолжил бы расти невидимкой до перезапуска демона — место бы не вернулось.
    if has_g ramlogs; then
        freed_ram=$(sum_of ramlog_targets)
        ramlog_targets | while read -r _p; do : > "$_p" 2>/dev/null; done
    fi
    # Стоковый лог: ротации удаляем, живой (если он на флеше) обрезаем — см. блок STOCK_LOG_DIR.
    # Выигрыш считает та же дельта df ниже: своей арифметики тут не заводим, иначе она разойдётся
    # с реальностью на сжатии UBIFS (текст жмётся втрое, и «освободил 3.8 МБ» было бы неправдой).
    if has_g stocklogs; then
        stocklog_rotated | while read -r _p; do rm -f "$_p" 2>/dev/null; done
        stocklog_live    | while read -r _p; do : > "$_p" 2>/dev/null; done
    fi
    # UBIFS пишет лениво: без sync `df` ещё несколько секунд показывает старое «занято»
    # и панель отрапортует «освобождено 0» при успешной чистке.
    sync 2>/dev/null
    set -- $(df_k); AFTER_K=${3:-0}
    n=$((AFTER_K - BEFORE_K)); [ "$n" -lt 0 ] && n=0
    nl=0
    if [ -n "$LOG_APART" ]; then set -- $(df_k_at "$STOCK_LOG_DIR"); nl=$(( ${3:-0} - LBEFORE_K )); [ "$nl" -lt 0 ] && nl=0; fi
    # msg собираем ЗДЕСЬ, а не в CGI: числа уже в переменных, а разбирать собственный JSON
    # обратно на busybox (без jq) — это sed по фигурным скобкам, который сломается первым же
    # новым полем. Флеш и ОЗУ называем РАЗДЕЛЬНО: чистка логов не даёт на /data ни байта, и
    # свести их в одну цифру значило бы соврать.
    # Единицу выбираем по величине: «0.0 МБ» на 4-килобайтном логе выглядит как «ничего не
    # сделал», хотя сделал.
    hum() { awk -v k="${1:-0}" 'BEGIN{ if(k<1024) printf "%d КБ", k; else printf "%.1f МБ", k/1024 }'; }
    msg=""
    if [ "$n" -gt 0 ]; then
        if [ -n "$CODE_ON_STORE" ]; then msg="освобождено $(hum "$n") на накопителе"; else msg="освобождено $(hum "$n") на флеше"; fi
    fi
    if [ "$nl" -gt 0 ]; then
        [ -n "$msg" ] && msg="$msg, "
        msg="${msg}освобождено $(hum "$nl") на флеше"
    fi
    if [ "$freed_ram" -gt 0 ]; then
        [ -n "$msg" ] && msg="$msg, "
        msg="${msg}освобождено $(hum "$freed_ram") в ОЗУ (логи)"
    fi
    [ -z "$msg" ] && msg="чистить было нечего"
    # freed_b — том КОДА (как было), freed_log_b — отдельный том стокового лога (0, когда том один).
    printf '{"ok":1,"freed_b":%s,"freed_log_b":%s,"freed_ram_b":%s,"free_b":%s,"msg":"%s"}\n' \
        $((n * 1024)) $((nl * 1024)) $((freed_ram * 1024)) $((AFTER_K * 1024)) "$msg"
    exit 0
fi

# =====================================================================================
# РЕЖИМ text (историчный) — отчёт + чистка. Формат вывода НЕ менять: артефакт уходит в
# мессенджер, и его же гонит enodia-clean.py.
# =====================================================================================
echo "=== df $(df_mp) ДО ==="
df -h "$ENODIA_DIR" 2>/dev/null | tail -1

echo ""
echo "=== ТОП потребителей в наших каталогах (KB, du) ==="
# `-x` — тот же инвариант, что и у sz_k выше (см. комментарий там): в /data смонтирована ЧУЖАЯ
# ФС (/data/etc/config), и без -x её содержимое считается ДВАЖДЫ. Замерено на BE7000:
# `du -sk /data/etc` = 1582 КБ против `du -xsk` = 1444, сумма по /data/* — 15430 против 15292.
for _d in $OUR_DIRS; do du -xsk "$_d"/* "$_d"/.[!.]* 2>/dev/null; done | sort -rn | head -25 \
    | awk '{printf "%8d KB  %s\n",$1,$2}'

echo ""
# НЕ `du -xsk /data/*`: он останавливается на `/data/usr` — а внутри лежим и мы, и стоковый
# ротированный syslog `/data/usr/log/messages*`, то есть на главный вопрос («это наше раздулось
# или прошивка?») строка отвечала «6800 KB /data/usr», и дальше начинались догадки. Разбираем тем
# же sys_walk, что и режим json: он спускается ровно в ту ветку, где лежим мы, и печатает всё
# ОСТАЛЬНОЕ покусочно. Одна логика обхода на оба режима — второй копии не заводим.
# Формат текстового отчёта тут МЕНЯЕТСЯ сознательно (см. шапку режима): единственный машинный
# потребитель `enodia-clean.py` вывод не парсит, а печатает как есть — проверено.
# Заголовок — про ОБА тома: в раскладке «всё» каталоги проекта лежат на накопителе, а обход ниже идёт по флешу роутера, и
# прежний заголовок с томом кода подписывал содержимое /data именем накопителя (ревью шага 6b, круг 3).
echo "=== покусочно (KB, du): НАШЕ — каталоги проекта; стоковое — $(df_mp_at /data) ==="
for _d in $OUR_DIRS; do
    printf "%8d KB  %s  <-- наше\n" "$(sz_k "$_d")" "$_d"
done
sys_walk /data | while read -r _p; do
    [ -n "$_p" ] && echo "$(sz_k "$_p") $_p"
done | sort -rn | head -15 | awk '{printf "%8d KB  %s\n",$1,$2}'

# Удаление одного кандидата (с показом размера). В dryrun только сообщает.
rm_target() {
    t="$1"
    [ -e "$t" ] || return 0
    sz=$(du -xsk "$t" 2>/dev/null | awk '{print $1}')
    if [ "$DRY" = 1 ]; then
        echo "  [dry] удалил бы: $t (${sz:-?} KB)"
    else
        rm -rf "$t" 2>/dev/null && echo "  удалено: $t (${sz:-?} KB)" || echo "  НЕ удалить: $t"
    fi
}

echo ""
echo "=== ЧИСТКА (мусор: бэкапы/temp/архивы; конфиги и бинари НЕ трогаем) ==="
[ "$DRY" = 1 ] && echo "(режим DRYRUN — ничего не удаляю, только показываю кандидатов)"
# «Свободно» берём тем же выражением, что и df_k выше: жёсткое `$4` врёт, как только df
# ПЕРЕНОСИТ длинное имя устройства на вторую строку (тогда $4 — это «78%», а не килобайты).
free_k() { set -- $(df_k); echo "${3:-}"; }   # третье поле df_k = свободно (второй копии выражения не заводим)
freed_before=$(free_k)

junk_targets | while read -r t; do rm_target "$t"; done

# СТОКОВЫЙ лог показываем, но НЕ трогаем даже в боевом текстовом режиме. Этот режим зовёт
# `enodia-clean.py` у ТЕСТЕРА, и удалить там чужой системный лог значило бы стереть
# единственную историю, переживающую ребут, — ровно в тот момент, когда человек собирает данные
# о сбое. Снос делается ОСОЗНАННО, галочкой в панели (группа stocklogs), а тут — только цифра.
_stk=$(sum_of stocklog_targets)
if [ "$_stk" -gt 0 ]; then
    echo "  (не трогаю: стоковый лог роутера $STOCK_LOG_DIR — ${_stk} KB; снимается переключателем «Системный лог роутера» на экране «Место и накопитель»)"
fi

# UBIFS пишет лениво: без sync `df` ещё несколько секунд отдаёт СТАРОЕ «занято», и отчёт
# рапортует «Освобождено: 0» после удачной чистки. В режиме clean sync стоит ровно за этим.
[ "$DRY" != 1 ] && sync 2>/dev/null

echo ""
echo "=== df $(df_mp) ПОСЛЕ ==="
df -h "$ENODIA_DIR" 2>/dev/null | tail -1
freed_after=$(free_k)
if [ "$DRY" != 1 ] && [ -n "$freed_before" ] && [ -n "$freed_after" ]; then
    # Единицу выбираем по величине (как в режиме clean): прежнее округление ВВЕРХ до мегабайта
    # печатало «Освобождено: 1 МБ» на 32 освободившихся килобайтах — цифра, которой нельзя
    # верить, хуже отсутствующей.
    freed_k=$((freed_after - freed_before)); [ "$freed_k" -lt 0 ] && freed_k=0
    echo "Освобождено: $(awk -v k="$freed_k" 'BEGIN{ if(k<1024) printf "%d КБ", k; else printf "%.1f МБ", k/1024 }')"
fi
echo "=== готово ==="
