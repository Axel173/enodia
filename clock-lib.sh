#!/bin/sh
# clock-lib.sh — ЕДИНСТВЕННЫЙ ответ на четыре вопроса про часы: «сколько прошло с отметки»
# (age_since), «настоящие ли часы вообще» (clock_sane), «какая эпоха/ISO в HTTP-дате»
# (http_date_epoch / http_date_iso) и «кто ставит часы» (clock_http_sync, следит C80).
#
# ЗАЧЕМ (поймано на железе 10.08.2026, свой роутер). RTC на роутере НЕТ. На буте стоковый
# sysfixtime ставит часы по mtime файла (у нас вышло −21.5 ч от реального времени), а стоковый
# ntp ходит к пулу ПО ИМЕНАМ и на буте не проходит вовсе:
#     ntp: ERROR: ntp failed, cmd /usr/sbin/ntpd -N -q -n -4 -p 0.pool.ntp.org …
#          do you have a working Internet connection?
#     ntp: try htp…  →  htp sync ok      (часы при этом ОСТАЛИСЬ кривыми)
# Стоковый smartcontroller видит «ntp status ok» и ждать перестаёт, поэтому настоящая
# синхронизация случается только на следующем заходе — у нас через 13.5 минуты после загрузки.
# В этот момент часы ПРЫГАЮТ ВПЕРЁД на всю накопленную ошибку.
#
# Всё, что мы меряем «сколько прошло», — это либо рукопожатие awg (отметку кладёт демон), либо
# отметка в /tmp (кладём мы сами). ОБА рождаются ПОСЛЕ загрузки ⇒ возраст физически не может
# быть больше аптайма. Больше — это НЕ давность, а скачок часов: `now - ts` врёт ровно на
# величину шага. Цена не косметическая (всё замерено в тот же день):
#   - handshake «77282 с назад» при рукопожатии минуту назад ⇒ сторож объявляет живой VPS
#     мёртвым и идёт по лестнице failover, роняя рабочий туннель;
#   - `wait_for_handshake` в switch-vpn судит по тому же числу ⇒ РУЧНОЕ переключение сервера
#     из панели «не поднялось» и откатилось, хотя туннель встал;
#   - панель показывает «рукопожатие 21 час назад» и гасит шапку в «не везёт трафик»;
#   - все троттлы разом «протухают» (штампы в /tmp), бэкофф перебора схлопывается — авария
#     повторяется каждый тик.
#
# Отсюда правило: возраст СТАРШЕ АПТАЙМА — это «неизвестно», а не «давно». Отдаём 0 (свежий):
# решение о смерти не принимается по данным, которых нет, а следующий тик пересчитает по
# свежему рукопожатию/штампу (рукопожатие обновляется само, штамп кладёт тот, кто действует).
# Часы, шагнувшие НАЗАД, дают отрицательный возраст — тоже 0. Направление «свежий» выбрано
# сознательно: ложное «мёртв» рвёт рабочий туннель, ложное «жив» стоит один тик ожидания.
#
# Только POSIX/busybox. Сорсится (`. clock-lib.sh`), сам ничего не печатает.

# Аптайм в секундах, целым. /proc/uptime = «339.05 866457.57» — берём целую часть ПЕРВОГО поля.
# Не прочитали (нет /proc) — отдаём заведомо большое: тогда ограничение не сработает и поведение
# останется прежним, а не превратится в «всё всегда свежее».
# ЕДИНСТВЕННЫЙ ЧИТАТЕЛЬ /proc/uptime СРЕДИ ЦЕЛЕЙ (следит C83; у резидентного бутстрапа своё чтение
# под ДРУГИМ именем — он бежит до того, как известен каталог кода, и метится `# raw-uptime:`).
# Ответов «сколько прошло с загрузки» было ПЯТЬ: свой uptime_secs у сторожа (cut), своя строка в
# totp.sh, шимы в dump.sh и web-ui.sh с РАЗНЫМИ телами (один читал файл, другой всегда врал
# «давно») плюс этот. Цена расхождения —
# не «неточное число»: по нему решают, снимать ли boot-grace и сдвигать ли сессии после скачка
# часов. У потребителей — ШИМ ровно этой строкой, у резидентного бутстрапа своё чтение (он бежит
# ДО того, как известен каталог кода, и метится `# raw-uptime:`).
# 999999999 — не «магия», а СЛОВО «не знаю»: кому важно отличать его от настоящего аптайма
# (totp.sh: сдвиг сессий делается один раз), тот сравнивает с этим же числом и отказывается.
uptime_s() {
	_cl_u=$(awk '{print int($1)}' /proc/uptime 2>/dev/null)
	case "$_cl_u" in ''|*[!0-9]*) _cl_u=999999999 ;; esac
	echo "$_cl_u"
}

# ГРАНИЦА ПРИМЕНИМОСТИ. Кламп «старше аптайма ⇒ 0» верен ТОЛЬКО для отметок, рождающихся ПОСЛЕ
# загрузки: рукопожатие awg (пишет демон) и штампы в /tmp (пишем мы). Для отметки на /data, которая
# ребут ПЕРЕЖИВАЕТ (`.subs-last`, `.iplist.*`), возраст законно больше аптайма, и age_since соврал бы
# «только что» про прогон трёхдневной давности. Такие места считают разность сами и помечены
# `# clock-raw:` — за этим следит проверка C24 в local/check-consistency.ps1.
#
# age_since <epoch> — сколько секунд прошло с отметки, с защитой от скачка часов.
# Пусто / не число / 0 (= отметки не было) → 999999, как и договорено у всех потребителей.
age_since() {
	case "$1" in ''|*[!0-9]*) echo 999999; return ;; esac
	[ "$1" -gt 0 ] || { echo 999999; return; }
	_cl_age=$(( $(date +%s) - $1 ))   # clock-raw: здесь и живёт сама поправка, ниже по тексту
	# `if`, а не `[ … ] && x=0`. ЗАМЕРЕНО на busybox ash роутера (10.08.2026), потому что «страж
	# роняет скрипт под set -e» верно НЕ везде, и разница ровно в позиции:
	#   в середине тела, когда ниже есть команды  → выживает (наш случай — мины тут не было);
	#   ПОСЛЕДНЕЙ командой функции                → функция возвращает 1, и шелл выходит на вызове;
	#   последней командой скрипта                → rc=1.
	# Форма `if` безразлична к позиции, поэтому строку под неё и не надо перечитывать при каждой
	# правке ниже. Библиотека REQUIRED и сорсится девятью файлами — цена ошибки здесь чужая.
	if [ "$_cl_age" -lt 0 ]; then _cl_age=0; fi                     # часы шагнули назад
	if [ "$_cl_age" -gt "$(uptime_s)" ]; then _cl_age=0; fi         # отметка «старше загрузки» = скачок
	echo "$_cl_age"
}

# up_age <отметка аптайма> — сколько секунд прошло с отметки, взятой uptime_s. ДЛЯ ОТМЕТОК, ЖИВУЩИХ ТОЛЬКО В /tmp И НЕ ИМЕНУЕМЫХ
# `*.stamp`: пауза возврата выхода сторожа, отметки hev (slot-tun-lib.sh). У эпохи в них беда двойная (ревью с.93, круг 3): кламп
# age_since «старше загрузки ⇒ 0» после скачка часов вперёд на D держится, пока аптайм не перерастёт D, — а clock_rebase_stamps
# переносит лишь `*.stamp` с одним числом. Роутер загрузился без WAN, часы не сверились, сторож снял выход и завёл паузу — пришёл
# WAN, часы шагнули на сутки, и пауза «не кончалась» сутки: выход лежал до ручного включения. Аптайм не прыгает и гибнет вместе
# с /tmp. Пусто / не число → 999999 (как у age_since); отметка БОЛЬШЕ аптайма (чужая загрузка, прежний формат-эпоха) — тоже давняя.
up_age() {
	case "$1" in ''|*[!0-9]*) echo 999999; return ;; esac
	_cl_ua=$(( $(uptime_s) - $1 ))
	if [ "$_cl_ua" -lt 0 ]; then _cl_ua=999999; fi
	echo "$_cl_ua"
}

# ЧАСЫ «НАСТОЯЩИЕ»? ------------------------------------------------------------------------
# RTC нет: до синхронизации `date +%s` показывает мусор (1970 либо mtime файла), и любое решение
# по эпохе в этот момент — ложь: сертификат панели протух бы, едва часы догонят реальность, TOTP
# не сойдётся, учёт трафика запишет дельту в 1970-й, отметка владельца адреса соврёт дату. Порог
# жил ПЯТЬЮ копиями литерала 1700000000 (doh-lib, lease-lib, totp, traffic-acct, web-ui) —
# теперь ответ один, у потребителей — шим той же строкой (следит C82). Нижняя граница — старше
# сборки прошивки (ноябрь 2023); верхняя — 2100-й: убежавшие в будущее часы так же непригодны,
# как отставшие (сервер AWG запомнит отметку из будущего — см. clock_http_sync ниже).
# clock_sane [эпоха] — без аргумента судит ТЕКУЩИЕ часы. Пусто / не число = не настоящие.
CLOCK_EPOCH_MIN=1700000000
CLOCK_EPOCH_MAX=4102444800
clock_sane() {
	_cse=${1:-$(date +%s 2>/dev/null)}
	case "$_cse" in ''|*[!0-9]*) return 1 ;; esac
	[ "$_cse" -gt "$CLOCK_EPOCH_MIN" ] 2>/dev/null && [ "$_cse" -lt "$CLOCK_EPOCH_MAX" ] 2>/dev/null
}

# ДАТА ИЗ HTTP-ЗАГОЛОВКА — ЕДИНСТВЕННЫЙ РАЗБОРЩИК RFC 1123 на роутер ----------------------
# Формат `Date:` / `Last-Modified:` по RFC 7231 фиксирован: `Sat, 05 Sep 2026 00:55:00 GMT`.
# Разбираем busybox'ом же (`date -D` = strptime, есть на 1.25.1 обоих ядер — проверено на железе
# 05.09.2026); «GMT» и всё за ним (включая CR) отрезаем, время трактуем как UTC (`-u`). До
# 05.09.2026 второй разборщик того же формата жил в geo.sh::ipdeny_iso своей таблицей месяцев.
# http_date_epoch <строка> — эпоха; код 1 = не разобрали. ЧИСТЫЙ разбор, без порога clock_sane:
# `Last-Modified` у ассета, не тронутого с 2022-го, — законная дата, и разборщик обязан её отдать;
# «годится ли как ИСТОЧНИК ЧАСОВ» — вопрос clock_http_date, там порог и стоит.
http_date_epoch() {
	_hde_s=$(printf '%s' "$1" | tr -d '\r' | sed 's/^[[:space:]]*//; s/[[:space:]]*GMT.*$//; s/[[:space:]]*$//')
	[ -n "$_hde_s" ] || return 1
	_hde_e=$(date -u -D '%a, %d %b %Y %H:%M:%S' -d "$_hde_s" +%s 2>/dev/null)
	# Пусто/мусор — СВОЙ отказ (стенд S12 поймал вариант, где пустой разбор подменялся «сейчас»).
	case "$_hde_e" in ''|*[!0-9]*) return 1 ;; esac
	printf '%s' "$_hde_e"
}
# http_date_iso <строка> — та же дата в ISO 8601 UTC («2026-08-13T10:21:06Z»). Приводим ЗДЕСЬ,
# а не в панели: `geoFreshLabel` режет дату как `iso.slice(0,10)`, и RFC-1123 превратился бы в
# «Thu, 13 A». `date -d @эпоха` — тот же разборщик busybox, что и у `date -s @…` в clock_http_sync.
http_date_iso() {
	_hdi_e=$(http_date_epoch "$1") || return 1
	date -u -d "@$_hdi_e" +%Y-%m-%dT%H:%M:%SZ 2>/dev/null
}

# ОТМЕТКА «НЕСУЩУЮ ТОЛЬКО ЧТО ПОДНЯЛИ» ------------------------------------------------------
# ЗАЧЕМ (поймано на железе 14.08.2026). Сторож гардит смену транспорта локом enodia-switching.lock,
# но лок отпускается, когда СТАРТОВАЛИ ДЕМОНЫ, а не когда заработал выход. Тик, попавший в этот
# зазор, честно не получает egress-пробу и пишет SUSPECT: панель показывает «проверяю…» на живом
# канале, а ВТОРАЯ такая осечка уже уходит в лестницу failover — то есть ручной выбор сервера
# может быть отменён авто-резервом. Замер: xray стартовал 02:37:49, тик в 02:38:08 (19 с спустя)
# пробу не получил, следующий в 02:40:01 — получил.
#
# Отметку кладёт КАЖДЫЙ плагин в своём `up` — той же логикой, что и `.transport` (см. шапку
# cmd_switch в transport.sh): несущую поднимают не только через оркестратор, но и напрямую
# (панель, switch-vpn, vpn-toggle repair, heal), и промолчи плагин — грейса не будет ровно в тех
# путях, где он и нужен. Живёт в /tmp: рождается после загрузки ⇒ age_since применим без оговорок.
CARRIER_UP_STAMP=/tmp/.enodia-carrier-up.stamp

# carrier_up_mark — отметить «несущая поднята сейчас». Best-effort: не смогли записать — грейса
# не будет, поведение прежнее. Возврат всегда 0 (зовут последней строкой cmd_up под `set -e`).
carrier_up_mark() {
	date +%s > "$CARRIER_UP_STAMP" 2>/dev/null
	return 0
}

# ЧАСЫ ПО HTTP-ДАТЕ — ДО ПОДЪЁМА НЕСУЩЕЙ -------------------------------------------------------
# ЗАЧЕМ (поймано ребут-тестом 05.09.2026, свой BE7000). Кламп age_since выше чинит ТОЛЬКО наш
# счёт «сколько прошло». А есть вторая, чужая половина той же беды: у WireGuard/AmneziaWG сервер
# ХРАНИТ отметку времени последнего рукопожатия пира и любое новое с отметкой НЕ НОВЕЕ ОТБРАСЫВАЕТ
# МОЛЧА (защита от повтора, по протоколу). После ребута часы стоят на mtime файла — то есть на
# ПРОШЛОМ буте, на дни позади последнего рукопожатия, — и домашний сервер не отвечает вообще:
# tx растёт, rx=0, «handshake 999999с». Замер: 3 минуты без ответа, reup не помог, сторож
# объявил «VPS МЁРТВ» и ушёл на резервный сервер (тот пира давно не видел — отметки нет, принял
# сразу); в sticky-режиме роутер там и остался. После `date -s` на верное время ТОТ ЖЕ домашний
# сервер ответил за 5 секунд. То есть каждый ребут со старыми часами = «после перезагрузки VPN
# на другом сервере», при живом сервере и зелёном логе heal.
#
# Стоковый ntp тут не спасает, и это уже записано в шапке: пул он резолвит ПО ИМЕНАМ, а DNS у нас
# в это окно заперт в несущую, которая как раз и не встала, — круг. Разрывает его ТОЛЬКО источник
# времени БЕЗ DNS и МИМО туннеля: заголовок `Date:` HTTP-ответа с IP-литерала, curl с биндом к
# WAN (`--interface`: без него запрос к 1.1.1.1 уходит в туннель — адрес в iplist_set, см.
# ip-lib.sh про ту же граблю у probe_ext_ip). Точность секунда — рукопожатию хватает с запасом,
# а стоковый ntp через свои 15 минут подправит остаток. (busybox ntpd умеет `-p <IP>` и был бы
# точнее, но UDP/123 режут чаще, чем HTTP/80, а `-q` не ограничен по времени — не взяли.)
#
# ПРАВИЛА, каждое куплено:
#   * ДВА СОГЛАСНЫХ ИСТОЧНИКА, а не «первый ответивший». Заголовок нешифрованный: провайдерский
#     перехват порта 80 (DPI, гостевые сети) отвечает СВОЕЙ датой, и одна кривая коробка
#     уводила бы часы куда угодно — а сервер AWG запомнил бы отметку из будущего и отбрасывал
#     нас, пока реальное время её не догонит. Два независимых IP-литерала, разошедшиеся не более
#     чем на 10 с, — цена один лишний HEAD (~0.2 с). Верхняя граница — 2100 год.
#   * В ОБЕ СТОРОНЫ, порог свой: вперёд > 30 с (меньше — дрожь), назад > 300 с. Убегающие
#     часы — не «безвредно»: сервер запомнит отметку из будущего, стоковый ntp через 15 минут
#     сдвинет часы назад, и с этой секунды КАЖДОЕ наше рукопожатие старее запомненного — до тех
#     пор, пока реальное время не дойдёт до той отметки. Лучше вернуть часы до несущей.
#   * ОТМЕТКИ /tmp ПЕРЕНОСИМ ВМЕСТЕ С ЧАСАМИ (clock_rebase_stamps). Троттлы сторожа лежат
#     эпохами в /tmp/enodia-*.stamp; после сдвига на D секунд их возраст = D + «старше аптайма»,
#     и age_since честно отдаёт 0 = «только что» — ВСЕ троттлы замерзают на D (двое суток без
#     повторного failover). Сдвинули часы — сдвигаем и отметки на ту же величину.
#   * PLAIN HTTP первым, https — последним и с `-k`: у части прошивок curl не находит издателя
#     НИКОГДА (CApath без хешей — грабля из карты проекта), а сертификат с кривыми часами не
#     проверяется вовсе. Нам нужен один заголовок, шифровать его незачем.
#   * РАЗ В ЗАГРУЗКУ. Итог ложится в $CLOCK_SYNC_MARK (/tmp, гибнет с ребутом): потребители
#     спрашивают clock_synced и второй раз в сеть не ходят.
#   * ИНТЕРФЕЙС ОБЯЗАТЕЛЕН. Пустой аргумент = отказ (код 2), а не «попробую без бинда»: без бинда
#     проба ушла бы в туннель, а он в этот момент как раз мёртв. Имя даёт ip-lib.sh::wan_iface,
#     и он же отвечает ПУСТО, когда дефолт main смотрит в нашу несущую.
#   * ВЕРДИКТ — ТОЛЬКО В CLOCK_MSG, stdout молчит. Печатает вызывающий: heal — в свой лог бута,
#     плагин и сторож — через свой log() и ТОЛЬКО на успехе (в здоровом тике сторож молчит).
#     Второго канала нет нарочно: `x=$(clock_http_sync …)` было бы подоболочкой, и всё, что
#     функция кладёт в переменные, погибло бы вместе с ней.
#   * СОБЫТИЕ В ЖУРНАЛ ПАНЕЛИ кладёт САМА функция на успехе (clock_step_event): «почему после
#     ребута не ушли на резерв» обязано быть видно в центре уведомлений, а вызывающих несколько.
# Возврат clock_http_sync: 0 — часы сдвинуты (CLOCK_STEP = на сколько, со знаком); 3 — верны,
# отметка поставлена; 1 — двух согласных источников не нашлось (отметки нет, зовите снова);
# 2 — нет интерфейса.
CLOCK_SYNC_MARK=/tmp/enodia-clock.synced
CLOCK_SYNC_TRIES_F=/tmp/enodia-clock.tries    # «неудач за загрузку» + аптайм последней (см. clock_boot_sync)
# Порядок = порядок опроса; все — IP-литералы (DNS-free), все отвечают на HEAD «/» с Date.
# Замерено 05.09.2026 через WAN: 1.1.1.1 http+https, 94.140.14.14 (AdGuard) http+https,
# 208.67.222.222 (OpenDNS) http, 8.8.8.8 ТОЛЬКО https. 9.9.9.9 и 77.88.8.8 на «/» молчат.
CLOCK_HTTP_URLS="${CLOCK_HTTP_URLS:-http://1.1.1.1/ http://94.140.14.14/ http://208.67.222.222/ https://8.8.8.8/}"
CLOCK_HTTP_TMO=${CLOCK_HTTP_TMO:-3}          # с на источник (коннект — 2); четыре источника = потолок 12 с
CLOCK_AGREE=${CLOCK_AGREE:-10}              # на сколько секунд вправе разойтись два источника
CLOCK_STEP_MIN=${CLOCK_STEP_MIN:-30}        # вперёд двигаем от такого отставания
CLOCK_BACK_MIN=${CLOCK_BACK_MIN:-300}       # назад — от такого убегания
CLOCK_SYNC_TRIES=${CLOCK_SYNC_TRIES:-10}    # неудач за загрузку, после которых clock_boot_sync переходит на редкий шаг
CLOCK_RETRY_GAP=${CLOCK_RETRY_GAP:-300}     # с аптайма между неудачными попытками (12 с curl не на каждый тик)
# …и редкий шаг ПОСЛЕ лимита, а не тишина до ребута: расписания доступа действуют ТОЛЬКО по нашей отметке (clock_trusted), и
# провайдер, вернувшийся через час после отключения света, оставлял их выключенными на весь аптайм (ревью s.112, круг 2)
CLOCK_RETRY_SLOW=${CLOCK_RETRY_SLOW:-1800}
CLOCK_STEP=0
CLOCK_MSG=
CLOCK_LOCK=/tmp/enodia-clock.lock           # heal и тик сторожа могут сверять ОДНОВРЕМЕННО — писатель часов один

# Имя WAN-интерфейса даёт ip-lib.sh::wan_iface (владелец). Шим — здесь, а не у каждого из
# вызывающих: сверку зовут heal, плагин awg и сторож, и без библиотеки все трое молча получили
# бы «нет интерфейса». Сорсится ip-lib раньше этого файла ⇒ command -v видит владельца.
command -v wan_iface >/dev/null 2>&1 || wan_iface() { ip route show default 2>/dev/null | awk '/^default/{d=""; for(i=1;i<=NF;i++) if($i=="dev") d=$(i+1); if(d!="" && d !~ /^(awg|xtun)/){print d; exit}}'; }

clock_synced() { [ -f "$CLOCK_SYNC_MARK" ]; }
# «ВРЕМЯ СВЕРЕНО» — the clock was set from the network THIS boot: our HTTP-date sync of two agreeing sources (the mark above;
# heal at boot, then every watchdog tick until it lands — VPN off and panel-only too). clock_sane alone is not it: after a
# reboot the clock sits on a file's mtime — a sane-looking date hours or days behind. Whoever ACTS on the wall clock (access
# schedules close the internet by it, access-sched.sh) gates on this; whoever only measures an age uses age_since.
# NOT the stock /tmp/ntp.status «ok»: `ntpsetclock` writes it after its htp fallback whenever htpdate exits 0, and htpdate
# exits 0 without setting the clock (the stock script says so itself; on BE7000 05.09.2026 «ok» stood two days behind). Its
# `ntp.failed` flag does not tell the two apart either: every run deletes it first, so a run in progress shows «ok» and no
# «failed» over the htp «ok» of the run before (read on BE7000, review s.112).
clock_trusted() {
	clock_sane || return 1
	clock_synced
}

# clock_http_date <iface> <url> — эпоха из заголовка Date, пусто = не ответил/не разобрали/
# дата вне разумного (clock_sane: раньше сборки прошивки или после 2100-го — сервер-шутник,
# перехват порта 80). Сам разбор — у http_date_epoch (один разборщик формата на роутер).
clock_http_date() {
	_cd_h=$(curl -sI -k --connect-timeout 2 --max-time "$CLOCK_HTTP_TMO" --interface "$1" "$2" 2>/dev/null | awk 'tolower($1)=="date:"{sub(/^[Dd][Aa][Tt][Ee]: */,""); print; exit}')
	[ -n "$_cd_h" ] || return 1
	_cd_e=$(http_date_epoch "$_cd_h") || return 1
	clock_sane "$_cd_e" || return 1
	printf '%s' "$_cd_e"
}

# clock_rebase_stamps <сдвиг_с> — перенести отметки-эпохи в /tmp на величину сдвига часов.
# Только файлы, чьё содержимое — ОДНО целое число (эпоха): так пишут все троттлы сторожа
# (`date +%s > stamp`). Отметка в /tmp могла родиться лишь ПОСЛЕ загрузки ⇒ до сдвига она
# заведомо «в старых часах», и перенос на ту же величину возвращает ей настоящий возраст.
clock_rebase_stamps() {
	_rb_n=0
	for _rb_f in /tmp/enodia-*.stamp /tmp/.enodia-*.stamp; do
		[ -f "$_rb_f" ] || continue
		_rb_v=$(cat "$_rb_f" 2>/dev/null | tr -d ' \r\n')
		case "$_rb_v" in ''|*[!0-9]*) continue ;; esac
		echo $(( _rb_v + $1 )) > "$_rb_f" 2>/dev/null && _rb_n=$((_rb_n + 1))
	done
	return 0
}

clock_http_sync() {
	CLOCK_STEP=0; CLOCK_MSG=
	[ -n "$1" ] || { CLOCK_MSG="часы: нет WAN-интерфейса для бинда — сверку пропускаю (без бинда проба ушла бы в туннель)"; return 2; }
	_cs_d1=; _cs_u1=; _cs_d=; _cs_u=; _cs_ans=0
	for _cs_u in $CLOCK_HTTP_URLS; do
		_cs_web=$(clock_http_date "$1" "$_cs_u") || continue
		_cs_ans=$((_cs_ans + 1))
		_cs_now=$(date +%s)
		_cs_d=$(( _cs_web - _cs_now ))   # clock-raw: две точки одних и тех же секунд, разность = сама поправка
		# Первый ответивший — только ОПОРНЫЙ: запоминаем и ищем ему пару. `_cs_d` обнуляем, иначе
		# после цикла он выдал бы себя за согласованный (стенд S5 поймал ровно это).
		if [ -z "$_cs_d1" ]; then _cs_d1=$_cs_d; _cs_u1=$_cs_u; _cs_d=; continue; fi
		_cs_diff=$(( _cs_d - _cs_d1 )); [ "$_cs_diff" -lt 0 ] && _cs_diff=$(( -_cs_diff ))
		if [ "$_cs_diff" -le "$CLOCK_AGREE" ]; then break; fi
		# Разошлись — первый мог быть перехватом; берём второго за опорного и ищем ему пару.
		_cs_d1=$_cs_d; _cs_u1=$_cs_u; _cs_d=
	done
	if [ -z "$_cs_d" ]; then
		CLOCK_MSG="часы: двух согласных HTTP-источников даты не нашлось (ответили: $_cs_ans) — сверку повторю позже"
		return 1
	fi
	_cs_dir=
	if [ "$_cs_d" -gt "$CLOCK_STEP_MIN" ]; then _cs_dir=вперёд
	elif [ "$_cs_d" -lt "-$CLOCK_BACK_MIN" ]; then _cs_dir=назад
	fi
	if [ -z "$_cs_dir" ]; then
		echo "step=0 src=$_cs_u1+$_cs_u d=$_cs_d" > "$CLOCK_SYNC_MARK" 2>/dev/null
		CLOCK_MSG="часы: верны (расхождение с $_cs_u ${_cs_d} с) — отметка поставлена, больше не сверяю"
		return 3
	fi
	_cs_now=$(date +%s); _cs_web=$(( _cs_now + _cs_d ))
	date -u -s "@$_cs_web" >/dev/null 2>&1 || { CLOCK_MSG="часы: источники дают сдвиг ${_cs_d} с, а date -s не сработал — оставляю как есть"; return 1; }
	CLOCK_STEP=$_cs_d
	clock_rebase_stamps "$_cs_d"
	echo "step=$_cs_d src=$_cs_u1+$_cs_u was=$_cs_now" > "$CLOCK_SYNC_MARK" 2>/dev/null
	if [ "$_cs_dir" = вперёд ]; then
		CLOCK_MSG="часы: отставали на ${_cs_d} с (RTC нет, сток ставит время по mtime файла) — сдвинуты вперёд по HTTP-дате $_cs_u1 и $_cs_u; без этого сервер AWG молча отбрасывает рукопожатие как повтор"
	else
		CLOCK_MSG="часы: убегали на $(( -_cs_d )) с — возвращены назад по HTTP-дате $_cs_u1 и $_cs_u ДО несущей; иначе сервер AWG запомнил бы отметку из будущего и отбрасывал нас после правки стоковым ntp"
	fi
	clock_step_event
	return 0
}

# clock_boot_sync — ОБВЯЗКА для всех, кто зовёт сверку (heal, плагин awg, сторож): одна, чтобы
# правила «когда сверять» не разъехались. Пока отметки нет, есть WAN-интерфейс, лимит неудач
# не исчерпан и с прошлой неудачи прошло CLOCK_RETRY_GAP аптайма — сверить. Возврат 0 ТОЛЬКО когда
# часы реально сдвинуты (вызывающий печатает CLOCK_MSG), иначе 1: сторож по этому коду молчит.
# ЛИМИТ НЕУДАЧ И ПАУЗА ПО АПТАЙМУ, а не окно по аптайму: WAN может встать и через час после
# загрузки (PPPoE, авария у провайдера), и тогда сверка нужна как никогда — а маршрут без выхода
# в сеть (DPI, чёрная дыра) не должен стоить каждому тику до 12 с curl'а до самого ребута.
# Аптайм, а не эпоха: часы здесь как раз и не заслуживают доверия.
clock_boot_sync() {
	if clock_synced; then return 1; fi
	command -v wan_iface >/dev/null 2>&1 || return 1
	_cb_n=0; _cb_last=0
	if [ -f "$CLOCK_SYNC_TRIES_F" ]; then read -r _cb_n _cb_last < "$CLOCK_SYNC_TRIES_F" || :; fi
	case "$_cb_n" in ''|*[!0-9]*) _cb_n=0 ;; esac
	case "$_cb_last" in ''|*[!0-9]*) _cb_last=0 ;; esac
	_cb_gap=$CLOCK_RETRY_GAP; [ "$_cb_n" -lt "$CLOCK_SYNC_TRIES" ] || _cb_gap=$CLOCK_RETRY_SLOW
	_cb_up=$(uptime_s)
	[ "$_cb_n" = 0 ] || [ $(( _cb_up - _cb_last )) -ge "$_cb_gap" ] || return 1
	_cb_if=$(wan_iface)
	[ -n "$_cb_if" ] || return 1
	# ЛОК ПО ПИДУ: heal (0c) и тик сторожа бегут на буте вперемешку, и оба могли бы оказаться внутри
	# пробы разом — два `date -s` наперегонки и две строки в журнале. Держатель жив (/proc) ⇒ уступаем
	# ему (он и напишет отметку); мёртв ⇒ лок протух вместе с ним, забираем. `set -C` — атомарно.
	_cb_lp=$(cat "$CLOCK_LOCK" 2>/dev/null | tr -cd '0-9')
	if [ -n "$_cb_lp" ] && [ -d "/proc/$_cb_lp" ]; then return 1; fi
	[ -n "$_cb_lp" ] && rm -f "$CLOCK_LOCK" 2>/dev/null
	( set -C; echo "$$" > "$CLOCK_LOCK" ) 2>/dev/null || return 1
	clock_http_sync "$_cb_if"; _cb_rc=$?
	rm -f "$CLOCK_LOCK" 2>/dev/null
	case "$_cb_rc" in
		0) return 0 ;;
		3) return 1 ;;
		*) echo "$((_cb_n + 1)) $_cb_up" > "$CLOCK_SYNC_TRIES_F" 2>/dev/null; return 1 ;;
	esac
}

# clock_step_event — строка в журнал событий панели после УСПЕШНОГО сдвига (CLOCK_STEP ≠ 0).
# Только журнал, без письма: сдвиг часов на буте — не авария, а объяснение «почему не ушли на резерв».
# $ENODIA_DIR — из окружения вызывающего (как у doh-lib.sh); нет events.sh — молча.
clock_step_event() {
	_ce_s=${CLOCK_STEP:-0}; _ce_dir=вперёд
	[ "$_ce_s" != 0 ] || return 0
	if [ "$_ce_s" -lt 0 ]; then _ce_s=$(( -_ce_s )); _ce_dir=назад; fi
	[ -n "$ENODIA_DIR" ] && [ -f "$ENODIA_DIR/events.sh" ] || return 0
	# Величину — в человеческих единицах: «2880 мин» никому ничего не говорит, «2 дн» — говорит всё;
	# а сдвиг в 31–59 с без нижней ступени читался бы как «0 мин».
	if [ "$_ce_s" -ge 86400 ]; then _ce_h="$((_ce_s / 86400)) дн"
	elif [ "$_ce_s" -ge 3600 ]; then _ce_h="$((_ce_s / 3600)) ч"
	elif [ "$_ce_s" -ge 60 ]; then _ce_h="$((_ce_s / 60)) мин"
	else _ce_h="$_ce_s с"; fi
	sh "$ENODIA_DIR/events.sh" add clock-step 0 "Часы сдвинуты $_ce_dir на $_ce_h" \
"После перезагрузки часы роутера расходились с реальным временем (RTC нет). Без поправки VPN-сервер отбрасывал бы рукопожатие как повтор, и роутер ушёл бы на резервный сервер. Время взято из HTTP-даты двух независимых узлов, мимо туннеля." >/dev/null 2>&1 || true
	return 0
}
