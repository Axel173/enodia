}
# ИДЁТ СНЯТИЕ СИСТЕМЫ (`uninstall.sh deactivate|purge`)? Пидфайл пишет CGI (`spawn_bg`) и сам uninstall.sh первым шагом — у снятия с
# ПК пидфайла иначе не было. Установка кода посреди purge пересоздавала снесённые каталоги и возвращала cron: половина дерева кода
# на «стоковом» роутере (ревью ветки pkg-update, круг 2). Шаблон — со СНЯТИЕМ в argv: `plan` и `cron-restore` короткоживущие.
