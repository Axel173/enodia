#!/bin/sh
# daemon-lib.sh — ЕДИНСТВЕННЫЙ владелец ОЖИДАНИЯ СТАРТА ДЕМОНА (несущие, слоты, служебный socks).
#
# ЗАЧЕМ. Все плагины несущих поднимали демон и ждали готовности ФИКСИРОВАННЫМ сроком —
# `while [ $i -lt 8 ]` вокруг netstat. Восемь секунд подобраны под флеш роутера (1.4 ГБ/с) и
# ЗАВЕДОМО малы для внешнего накопителя: замер на живом роутере тестера (BE7000, 01.09.2026) —
# 448 КБ/с холодного чтения, бинарь xray весит 8.1 МБ ⇒ ОДНО ТОЛЬКО ЧТЕНИЕ 18 СЕКУНД. Демон при
# этом жив и исправен, а мы объявляли его мёртвым, убивали и уходили на резерв. Со стороны тестера
# это выглядело как «xray отваливается через 1–5 суток, лечит только переустановка»: переустановка
# ПЕРЕЗАПИСЫВАЕТ файл и тем самым греет кэш, вытеснение кэша возвращает холодное чтение.
# Разбор целиком — в заметках разработки (разбор xray, 01.09.2026).
#
# ПРАВИЛО, которое здесь живёт: СТАРТ НЕ МЕРЯЕТСЯ СЕКУНДОМЕРОМ, судим по ПРОЦЕССУ.
#   * процесс УМЕР ⇒ ждать нечего, отказ НЕМЕДЛЕННО (прежний код честно выжидал все 8 с за трупом);
#   * процесс ЖИВ  ⇒ он ГРУЗИТСЯ (или, как hysteria, договаривается с сервером) — ждём до потолка;
#   * потолок — от НОСИТЕЛЯ бинаря: флеш = прежний срок плагина БАЙТ-В-БАЙТ, накопитель = 60 с.
# Потолок нужен и при живом процессе: демон может остаться жив и никогда не забиндить порт
# (чужой держатель, зависший хендшейк), а тик сторожа не имеет права висеть вечно.
#
# И ОТДЕЛЬНО — ОТКАЗ ОБЯЗАН РАЗЛИЧАТЬ «умер» и «жив, но не готов» ($DAEMON_WAIT_WHY). Строка
# «xray не слушает 10808» с пустым логом читается человеком как поломка xray, хотя правда в том,
# что мы не дождались чтения бинаря — и лог пуст ровно потому, что демону ещё нечего было сказать.
#
# КОНТРАКТ ВЫЗЫВАЮЩЕГО: store-lib.sh (`bin_on_store`) — только ради выбора потолка. Нет его (или
# бинарь резидентен) ⇒ носитель считаем флешем, то есть прежний срок и прежнее поведение.
# Спрашиваем именно `bin_on_store`, а НЕ `bin_where`: в раскладке «всё на накопителе» каталог
# бинарей и есть накопитель, и bin_where отвечает «router» про файл на флешке (замер на железе
# 01.09.2026 — потолок тогда не поднимался как раз там, где он нужнее всего).

# Потолок для бинаря НА НАКОПИТЕЛЕ. 60 с = 18 с чтения xray на замеренных 448 КБ/с с запасом на
# вдвое худший носитель; выше поднимать нельзя — тик watchdog ходит раз в 2 минуты и не должен
# перекрываться сам с собой.
DAEMON_WAIT_STORE=${DAEMON_WAIT_STORE:-60}
# Сколько ждём САМ ПИДФАЙЛ. start-stop-daemon -m пишет его в родителе сразу после fork, но
# «пидфайл пуст» и «процесс умер» — РАЗНЫЕ вещи: пустой = ещё не записан (иначе первая же итерация
# читала бы пустоту и объявляла смерть, хотя демон только что стартовал).
DAEMON_PID_GRACE=${DAEMON_PID_GRACE:-3}
# Почему не дождались — заполняет _daemon_wait, читают плагины в строке отказа.
DAEMON_WAIT_WHY=''

# Сколько ждать ЭТОГО демона: на флеше — срок вызывающего, на накопителе — не меньше потолка.
daemon_wait_secs() {   # $1 = имя бинаря ; $2 = срок для флеша ; -> секунды
    _dws=${2:-8}
    if daemon_on_store "$1" && [ "$_dws" -lt "$DAEMON_WAIT_STORE" ]; then _dws=$DAEMON_WAIT_STORE; fi
    printf '%s' "$_dws"
}

# «Бинарь на съёмном носителе?» — ответ ЧУЖОЙ (store-lib.sh), мы лишь переживаем его отсутствие:
# старая установка без библиотеки ⇒ считаем, что на флеше, и работаем прежним сроком.
daemon_on_store() {   # $1 = имя бинаря
    command -v bin_on_store >/dev/null 2>&1 || return 1
    bin_on_store "$1"
}

# Носитель бинаря СЛОВАМИ — для строки отказа и для диага: ответы владельца («да/нет», «store/
# router») машинные, а в лог панели уходит человеческий. Про НОСИТЕЛЬ спрашиваем первым — он и
# есть причина долгого старта; bin_where остаётся лишь чтобы отличить «нет бинаря вовсе».
# БИБЛИОТЕКИ НЕТ — МОЛЧИМ, а не отвечаем «не найден»: отсутствие store-lib.sh (частичный
# apply-scripts) и отсутствие самого бинаря — РАЗНЫЕ вещи, а строка уходит человеку в лог
# панели. «xray не найден» про живой, работающий бинарь отправляет чинить то, что цело.
daemon_where_ru() {   # $1 = имя бинаря
    if daemon_on_store "$1"; then printf 'на накопителе'; return 0; fi
    command -v bin_where >/dev/null 2>&1 || { printf 'носитель неизвестен'; return 0; }
    case "$(bin_where "$1" 2>/dev/null)" in
        '') printf 'не найден' ;;
        *)  printf 'на флеше роутера' ;;
    esac
}

# Пробы готовности. Пробел в шаблоне порта ОБЯЗАТЕЛЕН: без него "10832" матчит и "108320"
# (чужой порт) — грабля, уже оплаченная в slot-tun-lib.sh.
# ЖИВ ЛИ ПРОЦЕСС — И ТОТ ЛИ ЭТО (`pid_runs <pid> <ERE примет argv>`). pid переиспользуется: пидфайл сироты (ребут, OOM, `kill -9`
# посреди операции) указывает на ЧУЖОЙ живой процесс, и «идёт» висело бы, пока тот жив, — а кнопки заперты (ревью шага 6c, круги
# 2–3). Примета — имя нашего скрипта в argv; NUL → пробел ОБЯЗАТЕЛЕН: grep по сырому cmdline на busybox BE7000 не совпадает (замер).
# Спрашивают трое — движок компонентов (`busy` и лок), его CLI-двойник proto-install.sh и апдейтер (обновление и откат): ответ один,
# иначе `busy` пускал бы кнопку, а движок отказывал бы «уже выполняется» (круг 3). Без библиотеки у потребителей шим — прежнее «жив».
pid_runs() { [ -n "$1" ] && [ -r "/proc/$1/cmdline" ] && tr '\000' ' ' 2>/dev/null < "/proc/$1/cmdline" | grep -qE "$2"; }

# ИДЁТ ЛИ РАБОТА СПИСКОВ ИЛИ ГЕО — процессы движка списков, гео и iplist в ЛЮБОЙ фазе. Не по локам: фоновое применение списков
# (heal replay после установки, кнопка панели, cron) идёт ПО КАТЕГОРИЯМ и между ними лок отпускает, а держит ПУТИ, полученные на
# старте. Спрашивает смена раскладки (usb-offload.sh cmd_mode): процесс со старыми путями после переезда дописывал на флеш (замер
# BE7000 30.09.2026: двойник `enodia-state/lists/{adblock,ipblock}/blob`). Один проход по /proc: NUL → перевод строки, и элемент argv
# сверяем ЦЕЛИКОМ с путём скрипта В НАШЕМ каталоге кода (-xF: путь — не регулярка): чужие копии движка — не наша работа (у стендов их
# гоняет соседняя песочница, и смена раскладки ждала бы чужого до отказа), а запускают наши ровно по `$ENODIA_DIR/<скрипт>`.
# СПЕРВА СНИМАЕМ, ПОТОМ СВЕРЯЕМ — не одной трубой: grep в ней стартует раньше, чем cat дочитает /proc, а в его argv (`-e <путь>`) —
# ровно искомая строка, и под нагрузкой проверка находила САМУ СЕБЯ (стенд смены раскладки отказывал «идёт сборка», которой нет).
lists_work_alive() {
    _lwa=$(cat /proc/[0-9]*/cmdline 2>/dev/null | tr '\000' '\n')
    printf '%s\n' "$_lwa" | grep -qxF -e "$ENODIA_DIR/lists-update.sh" -e "$ENODIA_DIR/geo.sh" -e "$ENODIA_DIR/iplist-update.sh"
}

# ЖИВА ЛИ РАБОТА, НАЧАТАЯ ДЕРЖАТЕЛЕМ switching-ЛОКА <пид> — даже если сам держатель уже мёртв. Спрашивают те, кто судит лок с пидом
# (сторож — switch_lock_held, панель — cgi hold_switch): CGI под своим локом ведёт смену ПОТОМКАМИ (оркестратор, плагин напрямую —
# set_xray_server, save_config_raw, — `transport.sh dns`), а закрытую вкладку uhttpd бьёт SIGKILL только у CGI. Лок оставался с
# мёртвым пидом при ЖИВОЙ смене: сторож снимал его и вёл лестницу поверх неё, вторая вкладка забирала «ничей» лок (ревью с.96,
# круги 2–3). Не по именам скриптов — список имён отставал от вызовов дважды подряд, — а по МЕТКЕ в окружении: держатель экспортирует
# ENODIA_SWITCH_HOLDER=<свой пид> (switch_holder_mark), её наследует любой потомок. Снимок /proc/*/environ — сперва, сверка — потом.
switch_holder_mark() { ENODIA_SWITCH_HOLDER=$$; export ENODIA_SWITCH_HOLDER; }
# Работа держателя — наш СКРИПТ (`$ENODIA_DIR/<имя>.sh` в argv: оркестратор, плагин, switch-vpn), а не демон, которого он запустил:
# xray и hev наследуют окружение и живут сутками — по ним лок держался бы вечно. Кандидатов даёт один `grep -l` (подстрока), точная
# метка и argv сверяются у каждого.
switch_work_alive() {   # $1 — пид держателя из лока
    case "$1" in ''|*[!0-9]*) return 1 ;; esac
    for _swf in $(grep -l "ENODIA_SWITCH_HOLDER=$1" /proc/[0-9]*/environ 2>/dev/null); do
        tr '\000' '\n' 2>/dev/null < "$_swf" | grep -qxF "ENODIA_SWITCH_HOLDER=$1" || continue
        tr '\000' '\n' 2>/dev/null < "${_swf%/environ}/cmdline" | awk -v d="$ENODIA_DIR/" \
            'substr($0, 1, length(d)) == d && substr($0, length($0) - 2) == ".sh" { f = 1 } END { exit f ? 0 : 1 }' && return 0
    done
    return 1
}
# СНЯТЬ МЁРТВЫЙ switching-ЛОК — ТОЛЬКО если в нём всё ещё ТО, что увидел вызывающий (пид мёртвого держателя или пустое у лока без
# пида). Снимают двое — сторож (протухший лок) и cgi hold_switch (вкладку убили посреди смены), — и голая пара «сверка → rm» давала
# щель: вторая сторона успевала снять тот же мёртвый лок и положить СВОЙ, а первая следом сносила уже живой (хвост ревью с.96 —
# микросекунды, но тогда две смены идут разом). Сверка и rm — под мьютексом-каталогом (mkdir атомарен), свой лок вызывающий кладёт
# потом сам (`set -C`): чужой, положенный после нашей сверки, не совпадёт с увиденным и уцелеет. Мьютекс, брошенный убитым в
# этой щели, старше 10 с — снимаем. Код 0 — лока с увиденным больше нет (сняли мы или кто-то раньше), 1 — мьютекс занят прямо сейчас.
# Лок БЕЗ пида (пустой: switch-vpn, transport.sh, установка) по содержимому неотличим от СВЕЖЕГО пустого — его сторож признаёт
# протухшим по возрасту и передаёт вторым аргументом увиденный mtime: совпали оба — тот же файл.
switch_lock_reap() {   # $1 — содержимое лока, по которому вызывающий признал его мёртвым; $2 — его mtime (`date -r`), опц.
    _srl=${SWITCH_LOCK:-/tmp/enodia-switching.lock}
    if ! mkdir "$_srl.reap" 2>/dev/null; then
        # Возраст — `date -r`, как mtime лока ниже: `stat` есть не в каждой сборке busybox, а без него брошенный мьютекс жил бы
        # вечно — и сторож (`|| exit 0`) молчал бы до ребута (ревью с.97).
        _srm=$(date -r "$_srl.reap" +%s 2>/dev/null)
        case "$_srm" in ''|*[!0-9]*) return 1 ;; esac
        [ $(( $(date +%s) - _srm )) -gt 10 ] || return 1   # clock-raw: брошенный мьютекс живёт микросекунды — скачок часов лишь снимет его раньше
        rmdir "$_srl.reap" 2>/dev/null; mkdir "$_srl.reap" 2>/dev/null || return 1
    fi
    if [ "$(cat "$_srl" 2>/dev/null | tr -d ' \r\n')" = "$1" ] && { [ -z "$2" ] || [ "$(date -r "$_srl" +%s 2>/dev/null)" = "$2" ]; }; then
        rm -f "$_srl" 2>/dev/null
    fi
    rmdir "$_srl.reap" 2>/dev/null
    return 0
}

# КТО СЕЙЧАС ВЕДЁТ НЕСУЩУЮ — ТИК СТОРОЖА И ПРОГОН HEAL (бутовый или переигрыш). Тот же вопрос «жив ли держатель», что и у старта демона, поэтому здесь.
# Спрашивают те, кто сам меняет то, на что они смотрят: перенос бинарей (usb-offload.sh::move_hold) и «Отключить VPN»
# (vpn-toggle.sh, доводчик выключения). Держатель — ЖИВОЙ процесс под своим локом, а не файл: лок переживает `kill -9`, а номер
# процесса переиспользуется (сверяем cmdline — C115). Пути — литералы владельцев (watchdog.sh LOCK/WD_PID, heal.sh HEAL_LOCK);
# стенды подменяют их окружением.
DL_WD_LOCK=${ENODIA_WD_LOCK:-/tmp/enodia-watchdog.lock}
DL_WD_PID=${ENODIA_WD_PID:-/tmp/enodia-watchdog.pid}
DL_HEAL_LOCK=${ENODIA_HEAL_LOCK:-/tmp/enodia-heal.lock}
wd_tick_alive() {
    [ -e "$DL_WD_LOCK" ] || return 1
    _wta=$(cat "$DL_WD_PID" 2>/dev/null | tr -cd '0-9')
    pid_runs "$_wta" 'watchdog\.sh'
}
# Лок heal — «<pid> …» пока бежит и «done …» после; «done» и труп — не держатель.
# …И ПЕРЕИГРЫШ (`heal.sh replay`) — ТОЖЕ ПРОГОН HEAL: он поднимает несущую, выходы и маркировку тем же порядком, но бутового лока
# не пишет (лок = «в эту загрузку отработал»), и доводчик «Отключить VPN» его не видел (ревью ветки, круг 2). Свой пид он кладёт
# в DL_REPLAY_PID.
DL_REPLAY_PID=${ENODIA_REPLAY_PID:-/tmp/enodia-heal-replay.pid}
heal_alive() {
    _hla=$(cat "$DL_HEAL_LOCK" 2>/dev/null | tr -d '\r'); _hla=${_hla%% *}
    case "$_hla" in ''|*[!0-9]*) _hla= ;; esac
    [ -n "$_hla" ] && pid_runs "$_hla" 'heal\.sh' && return 0
    _hlr=$(cat "$DL_REPLAY_PID" 2>/dev/null | tr -cd '0-9')
    pid_runs "$_hlr" 'heal\.sh'
}
# СМЕНА РАСКЛАДКИ (`usb-offload.sh mode`) ИДЁТ? Пидфайл один у обоих, кто её запускает отцепленно, — CGI `store_mode` и мастер
# `enodia.py`. Судим по argv ЖИВОГО процесса, а не по файлу и не по голому `/proc/<pid>`: пидфайл в /tmp переживает убитый движок,
# номер переиспользуется, а у ответа есть потребитель, которому ложное «идёт» дорого, — гейт входа (totp.sh) на это время вместо
# формы входа говорит «панель переезжает». Шаблон — без пробела после `mode`: переезд кончается `exec` в `mode-drop-*`.
DL_MODE_PID=${ENODIA_MODE_PID:-/tmp/enodia-store-mode.pid}
store_mode_alive() {
    _sma=$(cat "$DL_MODE_PID" 2>/dev/null | tr -cd '0-9')
    pid_runs "$_sma" 'usb-offload\.sh.* mode'
}
# ИДЁТ УСТАНОВКА КОДА (pkg-install.sh: обновление, откат, установка с ПК)? Лок-каталог держит сам установщик на ВСЁ время прогона
# (ревью ветки pkg-update, круг 1): две установки разом рвали друг другу снимок отката, а смена раскладки посреди установки
