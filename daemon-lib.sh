}

# «ОТКЛЮЧИТЬ VPN» — ВОЛЯ ЧЕЛОВЕКА, И НЕСУЩУЮ ПРИ НЕЙ НЕ БЕРЁТ НИКТО. Флаг `.vpn-off` читают в начале сторож, heal и оркестратор, но
# автоматика, уже прошедшая свою проверку, досчитывала до живого сервера и поднимала несущую ПОСЛЕ `vpn-toggle off`: перебор серверов
# AmneziaWG (минуты), перебор резервов xray/hy2, переподъём awg0 и byedpi, heal, обновление подписки, диагностика (`health` byedpi
# переподнимает ciadpi). Латать каждую дорогу — копия «как выключить» в каждой (ревью ветки, круги 1–2: класс пришёл дважды), поэтому
# вопрос задаёт ТОТ, КТО НЕСУЩУЮ БЕРЁТ, — плагин, — и задаёт его ДВАЖДЫ:
#   · ДО: флаг есть ⇒ ничего не делаем (кроме «Включить VPN» и выбора транспорта человеком — они снимают флаг ПЕРВЫМ шагом);
#   · ПОСЛЕ: флаг появился, пока поднимали, ⇒ отпускаем поднятое своим же снятием и отвечаем отказом.
# Окна между ними нет: `off` пишет флаг ПЕРВЫМ шагом, а снимает после — значит флаг, появившийся после нашей второй проверки,
# означает снятие, которое ещё впереди и уберёт и наше. Нет библиотеки (частичное обновление) — у потребителей шим, прежний путь.
carrier_barred() { [ -f "$ENODIA_STATE/.vpn-off" ]; }
_crlog() { if command -v log >/dev/null 2>&1; then log "$1"; else echo "$1"; fi; }
# carrier_run <снятие> <подъём> [аргументы] — подъём под этим правилом; снятие зовётся с ТЕМИ ЖЕ аргументами (у выхода это его id).
carrier_run() {
    _cru=$1; _crf=$2; shift 2
    if carrier_barred; then _crlog "VPN выключен вручную — несущую не поднимаю"; return 1; fi
    "$_crf" "$@"; _crr=$?
    carrier_barred || return "$_crr"
    _crlog "VPN выключили вручную, пока поднималась несущая, — отпускаю её"
    "$_cru" "$@" >/dev/null 2>&1
    return 1
}
# ПРОЦЕССЫ, ИСПОЛНЯЮЩИЕ УДАЛЁННЫЙ ФАЙЛ: «pid путь» построчно, один обход /proc. Файл заменили или перенесли под живым демоном — он
# исполняет прежний inode до перезапуска, а `/proc/<pid>/exe` показывает путь с « (deleted)» (замер BE7000 29.09.2026, у UPX-бинаря
# так же). Спрашивают двое, и вопросы у них разные: «работает прежняя СБОРКА» (gh-update.sh bin-status: путь тот же, файл заменён)
# и «работает со СТАРОГО МЕСТА» (usb-offload.sh: файл переехал, а место держит удалённый inode).
exe_deleted() { ls -l /proc/[0-9]*/exe 2>/dev/null | sed -n 's#^.* /proc/\([0-9][0-9]*\)/exe -> \(.*\) (deleted)$#\1 \2#p'; }
# СМЕРТЬ ПРОЦЕССА ЖДЁМ ТОЖЕ ПО ПРОЦЕССУ. `start-stop-daemon -K` и `kill` шлют сигнал и возвращаются СРАЗУ, а за ними у нас идёт то,
# чему нужен уже мёртвый: бинд того же порта (перезапуск) или снос каталога, из которого процесс служит. Смена раскладки гасила
# uhttpd и тут же сносила настройки на флеше — недоживший сервер отвечал из полуснесённых «нужен вход» при живой сессии (замер
# BE7000 30.09.2026). Потолок — страховка от неубиваемого (D-state): по нему код 1, решать вызывающему. Шаг — `usleep` (дробного
# `sleep` в этом busybox нет); без него — секундный.
daemon_wait_gone() {   # $1 pid ; $2 потолок, с (по умолчанию 5) -> 0 процесса нет, 1 ещё жив
    case "$1" in ''|*[!0-9]*) return 0 ;; esac
    _dwg=0; _dwgm=$(( ${2:-5} * 10 ))
    while [ -d "/proc/$1" ]; do
        [ "$_dwg" -ge "$_dwgm" ] && return 1
        if command -v usleep >/dev/null 2>&1; then usleep 100000; else sleep 1; _dwg=$((_dwg+9)); fi
        _dwg=$((_dwg+1))
    done
    return 0
}
daemon_port_listens()  { netstat -ltn 2>/dev/null | grep -q "$1:$2 "; }
daemon_uport_listens() { netstat -lnu 2>/dev/null | grep -q "$1:$2 "; }   # UDP: резолвер DoH/DoT
daemon_dev_exists()    { ip link show "$1" >/dev/null 2>&1; }

# Ядро. Пробуем готовность, и ТОЛЬКО если её нет — спрашиваем процесс. Порядок важен: демон мог
# успеть стать готовым и умереть (или отдать пид другому — stale-пидфайл), и тогда «готово»
# честнее, чем «умер».
_daemon_wait() {   # $1 пидфайл ; $2 бинарь ; $3 срок-на-флеше ; $4 «чего ждём» словами ; далее — КОМАНДА-проба
    _dwpid="$1"; _dwbin="$2"; _dwwhat="$4"
    _dwmax=$(daemon_wait_secs "$_dwbin" "$3")
    shift 4
    # ШАГ — ПЯТАЯ ДОЛЯ СЕКУНДЫ (`usleep`, как у daemon_wait_gone): демон обычно готов через доли секунды, а секундный шаг
    # добавлял почти целую секунду к КАЖДОМУ подъёму — у смены сервера с «Шифрованным DNS» это прокси, у альтов hev и socks.
    # Счёт — в долях (`_dwt`), секунды (`_dwi`) — для потолка, грейса пидфайла и слов отказа, как раньше. Нет `usleep` — секундный.
    _dwi=0; _dwt=0; _dwq=1; command -v usleep >/dev/null 2>&1 && _dwq=5
    while :; do
        if "$@"; then DAEMON_WAIT_WHY=''; return 0; fi
        # Пид читаем САМИ, а не через proc_alive вызывающего: тому пустой пидфайл и мёртвый pid —
        # одинаково «не жив», а нам это два РАЗНЫХ вердикта («ещё не записан» и «умер»).
        # Жизнь судим по /proc, а НЕ по `kill -0`: ciadpi мы поднимаем под `nobody`, и сигнал
        # от не-root вернул бы EPERM = «умер» на живом демоне. Каталог /proc/<pid> uid-независим.
        # ПОРЯДОК ВЕТОК ОБЯЗАТЕЛЕН: при пустом пиде `/proc/$_dwp` вырождается в `/proc/` — каталог
        # СУЩЕСТВУЮЩИЙ, то есть «жив». Пустоту отсекаем ПЕРВОЙ (та же форма, что у `kill -0 ""`).
        _dwp=$(cat "$_dwpid" 2>/dev/null | tr -d ' \r\n')
        if [ -z "$_dwp" ]; then
            if [ "$_dwi" -ge "$DAEMON_PID_GRACE" ]; then
                DAEMON_WAIT_WHY="процесс НЕ ЗАПУСТИЛСЯ (пидфайл $_dwpid пуст через $_dwi с), $_dwwhat не появился"
                return 1
            fi
        elif [ ! -d "/proc/$_dwp" ]; then
            DAEMON_WAIT_WHY="процесс УМЕР через $_dwi с — $_dwwhat не появился"
            return 1
        fi
        [ "$_dwi" -ge "$_dwmax" ] && break
        if [ "$_dwq" = 5 ]; then usleep 200000; else sleep 1; fi
        _dwt=$((_dwt+1)); _dwi=$((_dwt/_dwq))
    done
    DAEMON_WAIT_WHY="процесс ЖИВ, но за $_dwmax с $_dwwhat не появился (бинарь $_dwbin $(daemon_where_ru "$_dwbin"))"
    return 1
}

# Дождаться, пока демон ЗАЙМЁТ ПОРТ. 0 = слушает; 1 = нет, причина в $DAEMON_WAIT_WHY.
daemon_wait_port() {   # $1 пидфайл ; $2 бинарь ; $3 срок-на-флеше ; $4 адрес ; $5 порт
    _daemon_wait "$1" "$2" "$3" "порт $4:$5" daemon_port_listens "$4" "$5"
}

# То же для UDP-порта: резолвер DoH/DoT слушает :5053/udp, и «жив» там тоже не значит «готов»
# (замер 31.08.2026: между стартом и Listening у https-dns-proxy проходит 26-28 с).
daemon_wait_uport() {  # $1 пидфайл ; $2 бинарь ; $3 срок-на-флеше ; $4 адрес ; $5 порт
    _daemon_wait "$1" "$2" "$3" "порт $4:$5/udp" daemon_uport_listens "$4" "$5"
}

# Дождаться, пока демон СОЗДАСТ УСТРОЙСТВО (tun2socks → xtun/xtunN). 0 = есть; 1 = нет.
daemon_wait_dev() {    # $1 пидфайл ; $2 бинарь ; $3 срок-на-флеше ; $4 имя интерфейса
    _daemon_wait "$1" "$2" "$3" "устройство $4" daemon_dev_exists "$4"
}
