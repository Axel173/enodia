DL_PKG_LOCK=${ENODIA_PKG_INST_LOCK:-/tmp/enodia-pkg-install.lock}
pkg_install_alive() {
    _pia=$(cat "$DL_PKG_LOCK/pid" 2>/dev/null | tr -cd '0-9')
