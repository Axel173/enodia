			case "$_eda" in *"
$d "*) _ar=${_eda#*"
$d "}; _ar=${_ar%%"
"*}; set -- $_ar; _aip=${1:-}; _aip2=${2:-} ;; esac
		fi
		if [ -n "$_aip" ]; then
			_av1=""; _av2=""
			for _ai in $_aip $_aip2; do
