#!/bin/sh
# devwatch.sh — «Что запрашивает устройство»: временное наблюдение за DNS-запросами и
# активными соединениями ОДНОГО клиента LAN, чтобы точечно закинуть его домены/адреса
# «мимо VPN» (боль Mi Home: bypass-домены Xiaomi не ловятся, лечилось только полным VPN off —
# [[mihome-be7000-vpn]]). Два источника, оба уже есть в busybox:
#   • dnsmasq query-log (log-queries + log-facility в ОЗУ) → какие ДОМЕНЫ резолвит клиент.
#     Включается ПО КНОПКЕ на короткое окно (verbose на весь LAN — постоянно держать нельзя),
#     авто-выключается по таймеру. Устройства со СВОИМ DoH мимо dnsmasq тут не видны (оговорка).
#   • conntrack -L -s <ip> → активные соединения СЕЙЧАС (dst-IP/порт), даже если DNS уже в кэше.
#
# Действия («→ мимо VPN» и т.п.) делает НЕ этот скрипт, а панель через apply-bypass.sh add-dst
# (тот же путь, что «Сайты мимо VPN») — здесь только НАБЛЮДЕНИЕ (read) + toggle лога (2 write-verb).
#
# ВТОРОЙ ПОТРЕБИТЕЛЬ ТОЙ ЖЕ ЛЕСТНИЦЫ — верб `route` («что победит», шаг 4d): тот же обход цепочек
# ядра, но для имени или адреса, которое человек ВВЁЛ, а не которое устройство уже спросило. Живёт
# здесь, а не отдельным скриптом, именно чтобы копии порядка ядра не появилось: ответ проверялки и
# строка экрана «Что запрашивает» обязаны совпадать до слова.
#
# ГРАБЛИ (см. карту проекта):
#   • Конфиг query-log пишем в ЖИВОЙ conf-dir /tmp/dnsmasq.d (НЕ /etc — стоковый init на рестарте
#     копит /etc→/tmp аддитивно, стухший файл переживёт; /tmp=RAM, на ребуте само исчезает).
#   • log-queries НЕ переключается по SIGHUP → нужен полный рестарт dnsmasq (краткий DNS-блип на LAN).
#   • Нет nohup/setsid → авто-стоп через start-stop-daemon -b (уникальный pidfile на запуск).
#   • busybox awk без index()/split()/user-функций → парсим полями ($i), без них.

ENODIA_DIR=${ENODIA_DIR:-/data/usr/app/enodia}
ENODIA_STATE=${ENODIA_STATE:-/data/usr/app/enodia-state}
# Сброс УЖЕ УСТАНОВЛЕННЫХ соединений — только через ct-lib.sh: на ядре 4.4 (AX3600/BE3600)
# утилиты conntrack в прошивке НЕТ ВООБЩЕ, и прежний `conntrack -F || true` был тихим no-op —
# правило стояло, а поток шёл по-старому через NSS/ECM. Шим = прежнее поведение (частичный
# apply-scripts не должен падать), полноценный сброс живёт в самой библиотеке.
if [ -f "$ENODIA_DIR/ct-lib.sh" ]; then . "$ENODIA_DIR/ct-lib.sh"; fi
if ! command -v ct_list_src >/dev/null 2>&1; then
    ct_list_src()   { [ -n "$1" ] && conntrack -L -s "$1" 2>/dev/null; return 0; }
fi
if ! command -v ct_list_all >/dev/null 2>&1; then
    ct_list_all()   { conntrack -L 2>/dev/null || cat /proc/net/nf_conntrack 2>/dev/null; return 0; }
fi
# Возраст записи журнала считаем через age_since (clock-lib.sh): часы роутера ПРЫГАЮТ вперёд
# через ~13 мин после загрузки, и голая разность в этот момент показала бы «час назад» у записи,
# сделанной минуту назад. Шим — на случай частично доехавшего apply-scripts.
if [ -f "$ENODIA_DIR/clock-lib.sh" ]; then . "$ENODIA_DIR/clock-lib.sh"; fi
# Правила ядра ЧИТАЕМ (обход цепочек ниже) — и читать их надо под тем же ожиданием xtables-лока, что и ставить:
# лок занят чужим кроном ⇒ `iptables -S` без `-w` отдаёт пустоту, и весь срез честно ответил бы «правил нет».
# Нет библиотеки — прежний путь (без ожидания).
if [ -f "$ENODIA_DIR/ipt-lib.sh" ]; then . "$ENODIA_DIR/ipt-lib.sh"; fi
# Правила по портам читаем ТЕМ ЖЕ разбором, которым apply-bypass.sh ставит цепочку (port-lib.sh): тот же фильтр
# и тот же порядок, иначе «что победит» отвечало бы про правило, которого в ядре нет. Без файла — ответ
# «правил по портам нет» (файл обязательный, ставится вместе с этим).
if [ -f "$ENODIA_DIR/port-lib.sh" ]; then . "$ENODIA_DIR/port-lib.sh"; fi
if ! command -v age_since >/dev/null 2>&1; then
    # clock-raw: библиотеки нет — считаем голой разностью, как было до неё
    age_since() { echo $(( $(date +%s) - $1 )); }
fi
SELF="$ENODIA_DIR/devwatch.sh"
QLOG="/tmp/enodia-dnsq.log"                 # лог dnsmasq (ОЗУ)
QCONF="/tmp/dnsmasq.d/07-querylog.conf"  # сниппет query-log в ЖИВОМ conf-dir
UNTIL="/tmp/enodia-devwatch.until"          # epoch, до которого наблюдаем (переживает окно, не ребут)
DEF_SECS=120; MIN_SECS=10; MAX_SECS=300
# --- ЖУРНАЛ «НЕ ОТВЕТИЛИ ЗА ОКНО» --------------------------------------------
# Список соединений — МГНОВЕННЫЙ срез: запись о молчащем потоке живёт в conntrack, пока идут
# попытки, и исчезает через таймаут (замерено на BE7000: unreplied UDP 60 с, зависший TCP в
# SYN_SENT 30 с). То есть «что отвалилось три минуты назад» в нём не увидеть НИКОГДА, а это ровно
# тот вопрос, ради которого экран и открывают. Домены такой болезни не знают: их пишет dnsmasq
# непрерывно и независимо от того, открыта ли панель. Даём соединениям ту же непрерывность —
# сэмплер живёт в фоновом процессе ОКНА (той же сплилке, что делает авто-стоп), поэтому копит и
# при закрытом экране. Журнал в ОЗУ: на ребуте исчезает сам, флеш не пишем.
DEADLOG="/tmp/enodia-devwatch-dead.tsv"     # src dst dport proto tx first_seen last_seen (через пробел)
SPID="/tmp/enodia-devwatch-sampler.pid"     # ЧЕЙ сейчас сэмплер: перезапуск окна перебивает файл,
                                         # прежняя сплилка видит чужой pid и уходит (иначе два
                                         # писателя в один журнал)
SAMPLE_EVERY=5                           # шаг опроса, с — вдвое меньше самого короткого таймаута
DEAD_MAX=200                             # потолок журнала: сканер портов не должен съесть ОЗУ
DEAD_SHOW=40                             # сколько отдаём панели (свежие сверху)

# Полный рестарт dnsmasq (единственный способ подхватить log-queries). Идентично
# dnsmasq_reload() из lists-lib.sh — тут инлайним, чтобы не тянуть весь lib ради строки.
dns_restart() { /etc/init.d/dnsmasq restart >/dev/null 2>&1 || killall -HUP dnsmasq 2>/dev/null; }

now() { date +%s; }

watching() {  # код 0 = сейчас наблюдаем (until в будущем И конфиг на месте)
	[ -f "$QCONF" ] || return 1
	u=$(cat "$UNTIL" 2>/dev/null); case "$u" in ''|*[!0-9]*) return 1 ;; esac
	[ "$(now)" -lt "$u" ]
}

secs_left() {
	u=$(cat "$UNTIL" 2>/dev/null); case "$u" in ''|*[!0-9]*) echo 0; return ;; esac
	l=$((u - $(now))); [ "$l" -gt 0 ] && echo "$l" || echo 0
}

start() {
	s="$1"; case "$s" in ''|*[!0-9]*) s="$DEF_SECS" ;; esac
	[ "$s" -lt "$MIN_SECS" ] && s="$MIN_SECS"; [ "$s" -gt "$MAX_SECS" ] && s="$MAX_SECS"
	mkdir -p /tmp/dnsmasq.d 2>/dev/null
	# СНАЧАЛА отбираем владение окном у прежнего сэмплера, и только потом чистим. Иначе между
	# очисткой и подъёмом нового сэмплера (а между ними ещё dns_restart — это секунда и больше)
	# старый успевает проснуться, увидеть в $SPID СВОЙ pid и вписать в ТОЛЬКО ЧТО очищенный журнал
	# записи прошлого окна: новое окно началось бы с чужих строк под подписью «за окно наблюдения».
	: > "$SPID" 2>/dev/null                 # пустой владелец ≠ pid любого живого сэмплера
	: > "$QLOG" 2>/dev/null                 # чистим лог прошлого окна (свежий срез)
	: > "$DEADLOG" 2>/dev/null              # …и журнал «не ответили»: окно новое — срез новый
	printf 'log-queries\nlog-facility=%s\n' "$QLOG" > "$QCONF"
	echo $(( $(now) + s )) > "$UNTIL"
	dns_restart
	# Авто-стоп: детач-сплилка на s секунд. Уникальный pidfile на запуск (перезапуск наблюдения
	# бампит UNTIL; старая сплилка проснётся, увидит UNTIL в будущем и НЕ тронет — стоп сделает
	# только та, что проснулась после реального UNTIL). Без -m -p матч всех sh → берём уник. имя.
	rm -f /tmp/enodia-devwatch-stop.*.pid 2>/dev/null
	start-stop-daemon -S -b -m -p "/tmp/enodia-devwatch-stop.$$.pid" -x /bin/sh -- "$SELF" _autostop "$s" 2>/dev/null
	printf '{"ok":true,"watching":true,"secs_left":%d}\n' "$s"
}

stop() {
	rm -f "$QCONF" "$UNTIL" 2>/dev/null
	dns_restart
	printf '{"ok":true,"watching":false,"secs_left":0}\n'
}

# Внутренняя: поспать окно и выключить, ЕСЛИ окно реально истекло (иначе наблюдение продлили).
_autostop() {
	# ЭТА ЖЕ сплилка теперь и СЭМПЛЕР: раз в SAMPLE_EVERY снимает мёртвые потоки в журнал окна.
	# Почему здесь, а не в `view`: журнал обязан копиться и при ЗАКРЫТОМ экране — иначе он повторил
	# бы болезнь живого списка («смотришь — видишь, отвернулся — потерял»), а домены копятся именно
	# так, независимо от панели.
	# Прежняя логика «проснулся, UNTIL в будущем — уходи» работала на ОДНОМ пробуждении. У цикла
	# так нельзя: перезапуск окна поднимает ВТОРУЮ сплилку, и обе писали бы в один журнал. Владелец
	# окна — тот, чей pid лежит в $SPID (последний записавший), остальные уходят на первом же тике.
	echo $$ > "$SPID" 2>/dev/null
	_dwleft="${1:-$DEF_SECS}"
	while [ "$_dwleft" -gt 0 ]; do
		[ "$(cat "$SPID" 2>/dev/null)" = "$$" ] || exit 0   # окно перезапустили — мы лишние
		watching || break                                   # истекло или нажали «Стоп»
		ct_list_all | ct_scan | awk '$5>0' | _dead_merge
		sleep "$SAMPLE_EVERY"
		_dwleft=$((_dwleft - SAMPLE_EVERY))
	done
	watching && exit 0        # UNTIL ещё в будущем → продлили, эта сплилка лишняя
	# watching()=false в ДВУХ случаях: (а) окно истекло (QCONF ещё на месте) — надо снять+рестартнуть;
	# (б) юзер уже нажал «Стоп» (stop() убрал QCONF и УЖЕ перезапустил dnsmasq) — тогда повторный
	# рестарт = лишний DNS-блип на весь LAN через минуту после ручного стопа. Различаем по наличию QCONF.
	[ -f "$QCONF" ] || exit 0
	rm -f "$QCONF" "$UNTIL" 2>/dev/null
	dns_restart
}

# JSON-массив доменов (свежие сверху, уникальные, ≤LIMIT) для клиента <ip> из query-log.
# Формат строки dnsmasq: "... query[A] example.com from 192.168.31.121" — берём поле ПЕРЕД
# "from", когда следующее поле = наш ip. Reverse+dedup: свежие первыми, без повторов.
# --- «Что куда идёт» (индикатор маршрута) ------------------------------------
# Смысл: список доменов/соединений без ответа «а этот сейчас в VPN или мимо?» заставляет
# пользователя гадать и тыкать наугад. Считаем маршрут ЧЕСТНО, в том же порядке, в каком его
# решает ядро: сперва вырезы (цепочка VPN_EXCLUDE стоит первой в mangle PREROUTING и ACCEPT'ом
# рвёт обход), потом маркировка по сетам. Порядок проверок ниже = порядок правил на роутере.
#
# ДОМЕНЫ — ИМЕНА В ПРАВИЛАХ: какие наборы получает домен, видно по `ipset=/дом/наборы` в живых conf'ах подсистем.
# Свои домены разбираем ПО НАБОРУ, а не скопом: enodia_list = «в VPN», enodia_bypass = «мимо VPN» (domain.sh держит
# оба направления в одном файле — см. его шапку). Скопом было бы враньё: домен, уведённый мимо, показывался бы «в VPN».
#
# ЧЛЕНСТВО В СПИСКЕ, А НЕ АНКОР НА КОНЕЦ СТРОКИ: строка conf'а агрегирована — `ipset=/дом/a,b` (groups.sh; dnsmasq
# применяет к домену РОВНО ОДНУ строку, поэтому наборы домена сведены в одну). Прежний `s|/grp_vpn$|` видел бы только
# ПОСЛЕДНИЙ набор списка, а домен, попавший в середину, читался бы как «правила нет».
#
# ОДИН ПРОХОД AWK С ХЭШЕМ НУЖНЫХ ИМЁН, а не список всех доменов набора в строке. Прежде каждый набор разворачивался в
# строку своих доменов, и каждый уровень каждого домена сверялся с ней `case`-ом: гео-категории — тысячи строк, пул
# десинка — десятки тысяч, и срез платил за них на КАЖДОМ опросе (добавленный было блок-лист гео — 297 тыс. строк —
# растянул срез до 12 с, замер BE7000 18.09.2026). Теперь хэш — это домены среза и их родители (≤ 150 имён), conf'ы
# читаются потоком один раз, а на выходе только совпадения: «дом:файл:набор» через пробел — маленькая строка, по ней
# и спрашивает dom_route.
# БЛОК ПО DNS (`address=/дом/0.0.0.0` гео «блокировать» и адблока) — не conf'ом, а ответом из того же журнала запросов:
# dnsmasq пишет «config дом is 0.0.0.0». Так видны оба блок-листа разом, и 300 тыс. строк гео читать не нужно.
GRP_CONF=/tmp/dnsmasq.d/10-groups.conf          # группы и правила устройств (groups.sh)
GEO_CONF=/tmp/dnsmasq.d/11-geo.conf             # гео-категории (geo.sh)
CUSTOM_CONF=/etc/dnsmasq.d/enodia-custom.conf   # одиночные домены (domain.sh)
ZDOM_CONF=/tmp/dnsmasq.d/07-zapret-dom.conf     # доменный пул десинка (lists-update.sh)
load_dom_hits() {   # $1 = домены среза, по строке; $2 = noqlog — не читать журнал запросов → DOM_HITS
	DOM_HITS=" "
	# Флаг запоминаем ЗДЕСЬ: ниже `set --` собирает список файлов для awk и ЗАТИРАЕТ позиционные
	# параметры функции — прочитанный после него `$2` всегда пуст (стенд поймал это первым же прогоном).
	_hnq=${2:-}
	_hw=/tmp/enodia-devwatch.want.$$
	printf '%s\n' "$1" | awk '{ d=$0; while(d!=""){ print d; if(d !~ /[.]/) break; sub("^[^.]*[.]", "", d) } }' > "$_hw" 2>/dev/null
	if [ ! -s "$_hw" ]; then rm -f "$_hw"; return 0; fi
	set -- "$_hw"
	# $2=noqlog — НЕ читать журнал запросов. Блок по DNS он показывает записями ОКНА НАБЛЮДЕНИЯ, а те
	# переживают снятие блока (журнал в ОЗУ живёт до ребута) ⇒ проверялке «что победит», которая
	# спрашивает резолвер САМА и знает ответ на сейчас, стухшая строка сказала бы «заблокировано».
	_hfl="$GRP_CONF $GEO_CONF $CUSTOM_CONF $ZDOM_CONF"
	[ "$_hnq" = noqlog ] || _hfl="$_hfl $QLOG"
	for _hf in $_hfl; do
		if [ -f "$_hf" ]; then set -- "$@" "$_hf"; fi
	done
	DOM_HITS=" $(awk -v wf="$_hw" -v g="$GRP_CONF" -v e="$GEO_CONF" -v c="$CUSTOM_CONF" -v q="$QLOG" '
		FILENAME==wf { W[$0]=1; next }
		FILENAME==q {
			for(i=1;i<=NF-3;i++) if($i=="config" && $(i+2)=="is") {
				k=$(i+1); if((k in W) && ($(i+3)=="0.0.0.0" || $(i+3)=="::") && !(k in B)) { B[k]=1; printf " %s:B:blk", k }
				break }
			next }
		/^ipset=/ {
			l=substr($0, 8); k=l; sub("/.*", "", k)
			if(!(k in W)) next
			v=l; sub("^[^/]*/", "", v)
			if(v=="" || v ~ "/") next
			t=(FILENAME==g) ? "G" : ((FILENAME==e) ? "E" : ((FILENAME==c) ? "C" : "Z"))
			gsub(",", " " k ":" t ":", v)
			printf " %s:%s:%s", k, t, v }' "$@" 2>/dev/null) "
	rm -f "$_hw"
}

# --- правила САМОГО устройства (цепочка VPN_DEV) — для ДОМЕНОВ -----------------
# Наборы VPN_DEV держат АДРЕСА: какое имя в них легло, по ним не восстановить, а строке домена нужен
# ответ «правило устройства, и вот куда». Поэтому для доменов читаем реестр правил устройства (groups.sh
# dev-list): DEV_DOMS — токены «дом=вердикт» (членство через case, busybox без index()). Адресам
# соединений отвечает сама цепочка ядра — её проходит walk (load_walk ниже), второй копии не держим.
load_dev_rules() {   # $1 = IP клиента
	DEV_DOMS=" "
	# Устройство «целиком в десинк» (.desync-ips): его трафик идёт НАПРЯМУЮ и десинкается nfqws
	# ПО ИСТОЧНИКУ, то есть ни в один dst-набор это не записано и по адресам не читается вовсе.
	# Без флага такой клиент выглядел бы как «просто напрямую» — самый частый вопрос «режим включил,
	# а где он виден».
	DESYNC_SRC=0
	grep -qxF "$1" "$ENODIA_STATE/.desync-ips" 2>/dev/null && DESYNC_SRC=1
	[ -f "$ENODIA_DIR/groups.sh" ] || return 0
	_dvl=$(sh "$ENODIA_DIR/groups.sh" dev-list "$1" 2>/dev/null)
	[ -n "$_dvl" ] || return 0
	DEV_DOMS=" $(printf '%s\n' "$_dvl" | awk -F"$(printf '\t')" '
		$2 !~ /^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+(\/[0-9]+)?$/ {
			v = ($3=="vpn") ? (($4+0 > 0) ? "slot" $4 : "vpn") : (($3=="block") ? "block" : "bypass")
			printf "%s=%s ", $2, v }') "
}

# --- ЛЕСТНИЦА ЯДРА ДЛЯ ОДНОГО КЛИЕНТА -------------------------------------------
# Маршрут строки обязан совпадать с вкладкой «Маршрут» того же экрана. Там режим устройства, режим его
# сети, гостевая и «весь трафик в VPN» решают судьбу ВСЕГО трафика — а здесь их не было вовсе:
# устройство «мимо VPN» получало «в VPN · общий список» напротив 8.8.8.8, «целиком в VPN» — «напрямую»
# напротив всего без правила, а при выключенном VPN и на Zapret строки писали «в VPN» (ревью шага 4b,
# круг 2). Три цепочки ловят трафик ПО ИСТОЧНИКУ (VPN_KEEP, VPN_EXCLUDE `-s`/`physdev`, VPN_FORCE), и
# порядок цепочек, и то, какие наборы реально заведены, знает только ядро. Поэтому не пересказываем
# apply-bypass.sh и mark-core.sh своими словами, а ИДЁМ ПО ПРАВИЛАМ ЯДРА: один `iptables -t mangle -S` на
# срез, из него — правила наших цепочек и маркировка PREROUTING в том порядке, в каком их проходит пакет.
# Второй копии порядка в проекте не появляется: переставят цепочки — экран поедет за ними сам.
# Интерфейс станции Wi-Fi (`physdev`) сообщает панель: она берёт его из того же wifi-stats и по нему же
# рисует режим сети — две вкладки обязаны отвечать об одном интерфейсе.

on() { case "$1" in *" $2"*) return 0 ;; esac; return 1; }   # членство в списке «через пробел»

# ip_in_net <адрес> <a.b.c.d/N> → 0, если адрес в подсети. Без форков и без арифметики над адресом
# целиком: на armv7 `$(( ))` знаковый 32-битный, и адрес выше 127.x его переполнил бы. Сравниваем по
# октетам; неполный октет — сдвигом (числа до 255).
ip_in_net() {
	_nip=$1; _nnet=${2%/*}; _nlen=${2#*/}
	case "$2" in */*) ;; *) _nlen=32 ;; esac
	if [ "$_nlen" = 32 ]; then [ "$_nip" = "$_nnet" ]; return; fi
	case "$_nlen" in ''|*[!0-9]*) return 1 ;; esac
	_nI=$IFS; IFS=.
	set -- $_nip $_nnet
	IFS=$_nI
	[ $# -eq 8 ] || return 1
	_nk=1
	while [ "$_nlen" -gt 0 ]; do
		eval "_na=\${$_nk}; _nb=\${$((_nk+4))}"
		if [ "$_nlen" -ge 8 ]; then
			[ "$_na" = "$_nb" ] || return 1
			_nlen=$((_nlen-8))
		else
			_ns=$((8-_nlen))
			[ $((_na>>_ns)) -eq $((_nb>>_ns)) ] || return 1
			_nlen=0
		fi
		_nk=$((_nk+1))
	done
	return 0
}

# --- КУДА ВЕДЁТ МЕТКА -----------------------------------------------------------
# Метка сама по себе никуда не ведёт: её разбирает `ip rule fwmark 0xN → table T`, а таблица без
# `default` НЕ обрывает поиск — пакет проваливается в main, то есть идёт НАПРЯМУЮ. Так выглядят VPN,
# выключенный тумблером (cmd_off снимает `ip rule` всех марок), Zapret основным и прямой режим сторожа (в
# table 1000 нет маршрута). Прежний гейт смотрел только на наличие `ip rule` и писал «в VPN» там, где
# вкладка «Маршрут» того же экрана говорила «напрямую». Отвечаем на каждую метку отдельно: выход с упавшей
# несущей и fallback=main смотрит в table 1000 (mark-core) — его трафик идёт ОСНОВНЫМ туннелем.
# MARK_GO — «метка:куда» через пробел (vpn | slotN | direct). Форков — по одному на таблицу метки (≤4).
#
# ГОСТЕВАЯ «МИМО» — не метка, а правило маршрутизации `from <подсеть> lookup main` с pref НИЖЕ меток
# (apply-bypass.sh guest-on, pref 90): оно срабатывает раньше любого fwmark, и никакая метка гостевой в
# туннель не ведёт. GUEST_MAIN=1 — клиент под таким правилом.
load_marks() {   # $1 = IP клиента
	MARK_GO=" "; GUEST_MAIN=0; _lmip=$1
	_lmr=$(ip -4 rule show 2>/dev/null | awk '{ p=$1; sub(/:$/, "", p); f=""; m=""; t=""
		for(i=2;i<=NF;i++){ if($i=="from"){ i++; f=$i } else if($i=="fwmark"){ i++; m=$i } else if($i=="lookup" || $i=="table"){ i++; t=$i } }
		if(m!=""){ sub(/\/.*/, "", m); print "M " p " " m " " t } else if(f!="" && f!="all" && t=="main") print "F " p " " f }')
	_lmin=""; _lmI=$IFS; IFS='
'
	for _lm in $_lmr; do
		IFS=$_lmI
		set -- $_lm
		[ "$1" = M ] || continue
		[ -n "$_lmin" ] || _lmin=$2
		case "$MARK_GO" in *" $3:"*) continue ;; esac      # у метки действует ПЕРВОЕ правило (вывод — по pref)
		_lmgo=direct
		if ip -4 route show table "$4" 2>/dev/null | grep -q '^default'; then   # not-wan: таблица МЕТКИ (1000/100N), а не WAN
			case "$4" in 100[234]) _lmgo="slot${4#100}" ;; *) _lmgo=vpn ;; esac
		fi
		MARK_GO="$MARK_GO$3:$_lmgo "
	done
	IFS=$_lmI
	[ -n "$_lmin" ] || return 0            # меток нет вовсе — гостевой перебивать нечего
	IFS='
'
	for _lm in $_lmr; do
		IFS=$_lmI
		set -- $_lm
		[ "$1" = F ] || continue
		[ "$2" -lt "$_lmin" ] 2>/dev/null || continue
		if ip_in_net "$_lmip" "$3"; then GUEST_MAIN=1; break; fi
	done
	IFS=$_lmI
}
mark_go() {   # $1 = метка (0x1..0x4) → GO = vpn | slotN | direct
	case "$MARK_GO" in *" $1:"*) GO=${MARK_GO#*" $1:"}; GO=${GO%% *} ;; *) GO=direct ;; esac
}

# --- ОБХОД ЦЕПОЧЕК ЯДРА ---------------------------------------------------------
# WALK — правила, которые пакет ЭТОГО клиента проходит в mangle PREROUTING, в порядке обхода: наши
# цепочки (VPN_DEV, VPN_KEEP, VPN_EXCLUDE, VPN_FORCE, ENODIA_ZAPRET — там, куда их поставил
# ensure_prerouting_order) и маркировка PREROUTING по наборам (mark-core). Строка: «цепочка src dst physdev
# набор цель метка», прочерк — условия нет. Отсеиваем сразу: `-s` другого устройства, `physdev` другого
# интерфейса, преамбулы «локалку наружу» (`-d <приватка> -j RETURN`: приватка в срез не попадает, ct_scan).
# Правило с условием, которого мы не разбираем (порт, метка, состояние…), считается НЕ совпавшим:
# выдумать совпадение хуже, чем недосказать. У наших цепочек таких нет, а VPN_PORTS (у правила есть ПОРТ)
# читаем из хранилища — ip_route спрашивает её первой, как ядро.
# Из того же разбора — ответы для ДОМЕНОВ (адреса у домена нет, обходить нечего): какие наборы реально
# заведены под «в VPN» (MARK_SETS), десинк (ZAP_SETS) и исключения устройства (KEEP_ON), какие метки у правил устройства
# (DEV_MARKS) и забирает ли источник «в VPN» целиком (SRC_FORCE). «Мимо» доменов решает сам обход (dom_route, VPN_EXCLUDE).
load_walk() {   # $1 = IP клиента, $2 = интерфейс его станции Wi-Fi («» — кабель или неизвестно)
	_me=$1
	WALK=""; MARK_SETS=" "; ZAP_SETS=" "; KEEP_ON=" "; DEV_MARKS=" "
	SRC_FORCE=""; SRC_FVIA=""
	# Пустой набор не совпадёт ни с чем — спрашивать его незачем: `ipset test` — форк на КАЖДОЕ соединение.
	# Старая утилита без счётчика в `-t` — список пуст, спрашиваем всё (прежняя цена).
	EMPTY_SETS=" $(ipset list -t 2>/dev/null | awk '$1=="Name:"{n=$2} /^Number of entries:/{ if($4+0==0) printf "%s ", n }') "
	_lw=$(iptables -t mangle -S 2>/dev/null | awk -v me="$1/32" -v ifc="$2" '
		$1!="-A" { next }
		$2=="PREROUTING" && $3=="-j" && NF==4 {
			if($4=="VPN_DEV" || $4=="VPN_KEEP" || $4=="VPN_EXCLUDE" || $4=="VPN_FORCE" || $4=="ENODIA_ZAPRET") P[++np]="J " $4
			next }
		$2!="PREROUTING" && $2!="VPN_DEV" && $2!="VPN_KEEP" && $2!="VPN_EXCLUDE" && $2!="VPN_FORCE" && $2!="ENODIA_ZAPRET" { next }
		{ s="-"; d="-"; p="-"; m="-"; md="dst"; t=""; k="-"; bad=0
		  for(i=3;i<=NF;i++){
		    if($i=="-s"){ i++; s=$i }
		    else if($i=="-d"){ i++; d=$i }
		    else if($i=="-m" && ($(i+1)=="physdev" || $(i+1)=="set")) i++
		    else if($i=="--physdev-in"){ i++; p=$i }
		    else if($i=="--match-set"){ i++; m=$i; i++; md=$i }
		    else if($i=="-j"){ i++; t=$i }
		    else if($i=="--set-xmark" || $i=="--set-mark"){ i++; k=$i }
		    else bad=1
		  }
		  if(bad || md!="dst") next
		  if(t!="MARK" && t!="ACCEPT" && t!="DROP" && t!="RETURN") next
		  if(t=="RETURN" && d!="-") next
		  if(p!="-") PD=1                       # правила ПО ИНТЕРФЕЙСУ станции в цепочках ЕСТЬ (см. WALK_PHYSDEV)
		  if(p!="-" && p!=ifc) next
		  if(s!="-" && s!=me && s ~ /\/32$/) next
		  if($2=="PREROUTING" && m=="-") next
		  sub(/\/.*/, "", k)
		  r=$2 " " s " " d " " p " " m " " t " " k
		  if($2=="PREROUTING") P[++np]="R " r; else { n[$2]++; R[$2 "#" n[$2]]=r } }
		END{ if(PD) print "@physdev"
		     for(i=1;i<=np;i++){ x=P[i]
		       if(substr(x,1,2)=="R "){ print substr(x,3); continue }
		       c=substr(x,3); for(j=1;j<=n[c];j++) print R[c "#" j] } }' 2>/dev/null)
	_lwI=$IFS; IFS='
'
	WALK_PHYSDEV=0
	for _l in $_lw; do
		IFS=$_lwI
		# «@physdev» — не правило, а ответ на вопрос «есть ли в цепочках правила ПО ИНТЕРФЕЙСУ станции».
		# Его задаёт проверялка, когда интерфейс ей не назвали, и второй дамп mangle ради него был бы
		# полным чтением таблицы на каждый вопрос.
		if [ "$_l" = "@physdev" ]; then WALK_PHYSDEV=1; continue; fi
		set -- $_l               # цепочка src dst physdev набор цель метка
		# Подсеть в `-s` (гостевая) — только своя. CIDR в busybox-awk без split() не разобрать, это делает ip_in_net.
		if [ "$2" != - ] && [ "$2" != "$_me/32" ]; then ip_in_net "$_me" "$2" || continue; fi
		WALK="$WALK$_l
"
		case "$1:$6" in
			PREROUTING:MARK) MARK_SETS="$MARK_SETS$5:$7 " ;;
			ENODIA_ZAPRET:ACCEPT) [ "$5" = - ] || ZAP_SETS="$ZAP_SETS$5 " ;;
			VPN_KEEP:MARK) [ "$5" = - ] || KEEP_ON="$KEEP_ON$5:$7 " ;;
			VPN_DEV:MARK) DEV_MARKS="$DEV_MARKS$7 " ;;
			VPN_FORCE:MARK)
				if [ -z "$SRC_FORCE" ] && [ "$3" = - ] && [ "$5" = - ]; then
					SRC_FORCE=$7
					if [ "$4" != - ]; then SRC_FVIA='режим сети'
					elif [ "$2" = - ]; then SRC_FVIA='весь трафик в VPN'
					else case "$2" in */32) SRC_FVIA='режим устройства' ;; *) SRC_FVIA='гостевая сеть' ;; esac; fi
				fi ;;
		esac
	done
	IFS=$_lwI
}

# walk <адрес назначения> → W_T (accept | drop | «» — никто не решил), W_M (метка) и правило, которое
# решило: W_C (цепочка) W_S W_D W_P W_SET. MARK не обрывает обход (как в ядре), ACCEPT и DROP — обрывают,
# RETURN — выход из своей цепочки.
walk() {
	_wa=$1; W_T=""; W_M=""; W_C=""; W_S=""; W_D=""; W_P=""; W_SET=""; _wskip=""; _wls=""; _wlr=1
	_wI=$IFS; IFS='
'
	for _wl in $WALK; do
		IFS=$_wI
		set -- $_wl
		[ "$1" = "$_wskip" ] && continue
		if [ "$3" != - ]; then ip_in_net "$_wa" "$3" || continue; fi
		if [ "$5" != - ]; then
			# Пара MARK+ACCEPT по одному набору — один вопрос к ipset, а не два.
			if [ "$5" != "$_wls" ]; then
				_wls=$5; _wlr=1
				case "$EMPTY_SETS" in *" $5 "*) ;; *) ipset test "$5" "$_wa" >/dev/null 2>&1 && _wlr=0 ;; esac
			fi
			[ "$_wlr" = 0 ] || continue
		fi
		case "$6" in
			MARK)   W_M=$7; W_C=$1; W_S=$2; W_D=$3; W_P=$4; W_SET=$5 ;;
			ACCEPT) W_T=accept; [ -n "$W_M" ] || { W_C=$1; W_S=$2; W_D=$3; W_P=$4; W_SET=$5; }; break ;;
			DROP)   W_T=drop; W_C=$1; W_S=$2; W_D=$3; W_P=$4; W_SET=$5; break ;;
			RETURN) _wskip=$1 ;;
		esac
	done
	IFS=$_wI
}
# Подпись источника по набору — словом панели (переводит её словарь).
set_label() {
	case "$1" in
		iplist_set)                SL='общий список' ;;
		grp_*)                     SL='группа' ;;
		geo_*)                     SL='гео' ;;
		enodia_list|enodia_bypass) SL='свой домен' ;;
		enodia_ip_vpn)             SL='свой адрес' ;;
		zapret_*)                  SL='десинк' ;;
		*)                         SL='правило' ;;
	esac
}
# Правило, которое решило (W_*) → W_VIA (подпись) и W_KIND: dst — «мимо» по адресу назначения, src — режим
# устройства или сети, dsrc — устройство «в десинк» (та же пара ACCEPT в VPN_EXCLUDE, что у «мимо VPN»), zap — пул
# десинка (ENODIA_ZAPRET ведёт напрямую ЛЮБОЙ порт, а ломает рукопожатие только там, где стоит NFQUEUE).
walk_via() {
	W_KIND=dst
	case "$W_C" in
		VPN_DEV) W_VIA='правило устройства' ;;
		VPN_FORCE)
			W_KIND=src
			if [ "$W_P" != - ]; then W_VIA='режим сети'
			elif [ "$W_S" = - ]; then W_VIA='весь трафик в VPN'
			else case "$W_S" in */32) W_VIA='режим устройства' ;; *) W_VIA='гостевая сеть' ;; esac; fi ;;
		VPN_EXCLUDE)
			if [ "$W_SET" != - ]; then set_label "$W_SET"; W_VIA=$SL
			elif [ "$W_D" != - ]; then W_VIA='вырез'
			elif [ "$W_P" != - ]; then W_KIND=src; W_VIA='режим сети'
			else W_KIND=src; W_VIA='режим устройства'; [ "$DESYNC_SRC" = 1 ] && W_KIND=dsrc
			fi ;;
		ENODIA_ZAPRET) W_KIND=zap; W_VIA='десинк' ;;
		*) set_label "$W_SET"; W_VIA=$SL ;;          # VPN_KEEP и маркировка PREROUTING — по набору
	esac
}

# --- БЛОК-ЛИСТЫ (filter FORWARD) ------------------------------------------------
# Гео «блокировать» (ENODIA_GEOBLK) и блок-лист по адресам (ENODIA_BLK) рубят пакет в filter FORWARD — ПОСЛЕ
# маршрутизации, куда бы его ни повела mangle. Без этой ступени адрес из блок-листа показывался «в VPN ·
# общий список», хотя не уходит никуда. Спрашиваем ядро, какие наборы стоят под DROP в подцепленных
# цепочках. Выше DROP у обеих стоит исключение blocklist_allow (ПО ИСТОЧНИКУ и по назначению, lists-lib.sh
# ensure_allow_set): клиент под ним — цепочка не для него вовсе, адрес под ним — не рубится.
load_blk() {   # $1 = IP клиента
	BLK_SETS=""; BLK_ALLOW=""; _lbip=$1
	_lb=$(iptables -S 2>/dev/null | awk '
		$1=="-A" && $2=="FORWARD" && $3=="-j" && NF==4 && ($4=="ENODIA_GEOBLK" || $4=="ENODIA_BLK") { J[$4]=1; next }
		$1=="-A" && ($2=="ENODIA_GEOBLK" || $2=="ENODIA_BLK") {
			m=""; d=""; t=""; x=0
			for(i=3;i<=NF;i++){ if($i=="--match-set"){ m=$(i+1); d=$(i+2) } else if($i=="-j") t=$(i+1); else if($i=="-i") x=1 }
			if(x || m=="") next
			if(t=="DROP" && d=="dst") D[++nd]=$2 " " m
			else if(t=="RETURN") A[m]=1 }
		END{ for(i=1;i<=nd;i++){ c=D[i]; sub(/ .*/, "", c); if(c in J){ x=D[i]; sub(/^[^ ]* /, "", x); print "D " x } }
		     for(a in A) print "A " a }' 2>/dev/null)
	[ -n "$_lb" ] || return 0
	_lbI=$IFS; IFS='
'
	for _l in $_lb; do
		IFS=$_lbI
		set -- $_l
		case "$1" in
			D) BLK_SETS="$BLK_SETS $2" ;;
			A) BLK_ALLOW="$BLK_ALLOW $2" ;;
		esac
	done
	IFS=$_lbI
	for _ba in $BLK_ALLOW; do
		if ipset test "$_ba" "$_lbip" >/dev/null 2>&1; then BLK_SETS=""; return 0; fi
	done
	return 0
}

# Итог лестницы — переменными R_* (маршрут, источник, намерение, десинк), печатают их вызывающие: у
# домена своё поле own. Намерение (want) — куда правило вело бы, если путь сейчас другой: метка есть, а
# туннель её не везёт (напрямую), выход упал на основной туннель. Десинк (dsy) — NFQUEUE стоит в mangle
# POSTROUTING, это ДРУГОЙ хук, и ACCEPT в PREROUTING его не отменяет: на прямом пути он действует поверх
# любой причины. Промолчав, строка писала бы «напрямую» поверх работающего десинка.
res() { R_ROUTE=$1; R_VIA=$2; R_WANT=$3; R_DSY=$4; }
res_direct() {   # $1 = direct|bypass, $2 = источник, $3 = адрес («» у домена), $4 = порт, $5 = намерение, $6 = десинк домена
	DESYNC_VIA=$6
	[ -n "$3" ] && desync_via "$3" "$4"
	# Прямой путь без правила, но с десинком: десинк и есть его причина.
	if [ -z "$2" ] && [ -n "$DESYNC_VIA" ]; then res "$1" "$DESYNC_VIA" "$5" ''; else res "$1" "$2" "$5" "$DESYNC_VIA"; fi
}
res_mark() {   # $1 = метка, $2 = источник, $3 = адрес, $4 = порт, $5 = десинк домена
	if [ "$GUEST_MAIN" = 1 ]; then res_direct direct 'гостевая сеть' "$3" "$4" '' "$5"; return; fi
	mark_go "$1"
	_rw=vpn; [ "$1" = 0x1 ] || _rw="slot${1#0x}"
	case "$GO" in
		direct) res_direct direct "$2" "$3" "$4" "$_rw" "$5" ;;
		"$_rw") res "$GO" "$2" '' '' ;;
		*)      res "$GO" "$2" "$_rw" '' ;;         # выход упал на основной туннель (fallback=main)
	esac
}

# --- ГДЕ ДЕСИНК СТОИТ НА САМОМ ДЕЛЕ -------------------------------------------
# Раньше источник «десинк» ставился по ЧЛЕНСТВУ адреса в списке существующих пулов — то есть по
# НАМЕРЕНИЮ, а не по факту. Два расхождения, оба замерены 28.08.2026 на BE7000:
#   * zapret заводит NFQUEUE ТОЛЬКО на `--dport 443` (его «ГРАНИЦА ЧЕСТНО», см. шапку zapret.sh),
#     а экран подписывал «десинк» соединению на UDP 7600, которого nfqws не видит вовсе — после
#     появления порт-правил такая подпись встала сразу на 27 строках среза;
#   * пул может СУЩЕСТВОВАТЬ и быть наполнен, а правил под него не заведено (выход-десинк
#     выключен) — тогда десинка нет ни для одного адреса этого пула.
# Поэтому спрашиваем ЯДРО: какие пары «сет:порт» реально уехали в NFQUEUE (плюс `@src:порт` —
# правила по ИСТОЧНИКУ, «устройство целиком в десинк»). Один форк на срез. Заведут второй порт или
# новый пул — экран поедет за ними сам, и второй копии этого знания в проекте не появится: прежний
# список слов был зеркалом zapret.sh и по построению мог отстать.
load_desync_wired() {
	DESYNC_WIRED=$(iptables -t mangle -S POSTROUTING 2>/dev/null | awk '
		/-j NFQUEUE/{ _s=""; _p=""; _src="";
		  for(i=1;i<=NF;i++){
		    if($i=="--match-set") _s=$(i+1);
		    else if($i=="--dport") _p=$(i+1);
		    else if($i=="-s") _src=$(i+1);
		  }
		  if(_p=="") next;
		  if(_s!="") print _s":"_p; else if(_src!="") print "@src:"_p }' 2>/dev/null | sort -u | tr '
' ' ')
}
# grp_name <домен> [слот] → «группа «Игры»» — ИМЯ группы, а не безликое «группа». Пользователь
# спрашивает «а почему этот домен мимо VPN?» — ответ «правило есть где-то в группах» бесполезен,
# надо сказать, в КАКОЙ. dnsmasq-conf имён не хранит (там только сет) → ищем домен в членах групп.
# Форки только на СОВПАДЕНИИ (домен уже признан членом группы), т.е. на единицы строк из десятков.
#
# ОДИН домен лежит в НЕСКОЛЬКИХ .list разом (тот же youtube.com — и в рабочем пуле, и в отключённом
# запасном): брать первый попавшийся нельзя, назовём чужую — и, скорее всего, ВЫКЛЮЧЕННУЮ группу,
# которая на маршрут не влияет вовсе. Поэтому перебираем все совпадения и берём ВКЛЮЧЁННУЮ, а при
# известном слоте — ещё и привязанную ИМЕННО к нему (маршрут-то мы уже определили по его сету).
# Имя — поле 5 реестра (id⇥enabled⇥dir⇥slot⇥name[⇥src]); когда-то читалось поле 4, т.е. СЛОТ
# (в панели это выглядело как «группа «0»»).
grp_name() {   # $1 = домен, $2 = слот (опц.; пусто = не проверять)
	for _gf in $(grep -lxF "$1" "$ENODIA_STATE/groups/"*.list 2>/dev/null); do
		_gid=$(basename "$_gf" .list)
		_gl=$(awk -F"$(printf '\t')" -v id="$_gid" '$1==id{print}' "$ENODIA_STATE/groups/groups.tsv" 2>/dev/null | head -1)
		[ -n "$_gl" ] || continue
		[ "$(printf '%s' "$_gl" | cut -f2)" = 1 ] || continue         # выключенная маршрут не задаёт
		# Группа УСТРОЙСТВА сюда не годится: её служебное имя ответило бы на вопрос «почему домен
		# идёт туда» чужим правилом (оно действует для другого источника). Для своего устройства
		# ответ даёт dom_route ещё выше — «правило устройства».
		[ -n "$(printf '%s' "$_gl" | cut -f6)" ] && continue
		if [ -n "$2" ] && [ "$(printf '%s' "$_gl" | cut -f4)" != "$2" ]; then continue; fi
		_gn=$(printf '%s' "$_gl" | cut -f5)
		[ -n "$_gn" ] && { printf 'группа «%s»' "$_gn"; return; }
	done
	printf 'группа'
}
# --- правила по портам (цепочка VPN_PORTS) ------------------------------------
# Они стоят ВЫШЕ всего остального: VPN_PORTS — ПЕРВАЯ цепочка в mangle PREROUTING (порядок держит
# ensure_prerouting_order в apply-bypass.sh), а её ACCEPT обрывает обход ТАБЛИЦЫ — до маркировки по
# сетам дело не доходит вовсе. Пока этой ветки не было, экран писал «в VPN» напротив каждого адреса
# из iplist_set, хотя правило «1024-65535 напрямую» уводило тот же трафик мимо туннеля (замерено
# 28.08.2026 на BE7000: ACCEPT правила насчитал 119K пакетов, игра при этом шла напрямую и не
# подключалась). Это то же враньё «сет наполнен ≠ трафик помечен», от которого сторожит
# mark_go (куда ведёт метка), — только источник другой.
#
# Порт есть ТОЛЬКО у соединения: у домена его нет, поэтому у dom_route такой ветки быть не может —
# какое правило сработает, зависит от порта, который домен ещё не выбрал.
# Локалку спрашивать не нужно: преамбула VPN_PORTS RETURN'ит приватные сети, а emit_conns их и так
# не показывает.
#
# Читаем ОДИН раз на срез (как load_dev_rules): записи «proto:порты:куда» через пробел, выигрывает
# первое совпавшее. Какие строки действуют и в каком порядке — port-lib.sh::port_rules_in_order, ТОТ ЖЕ
# разбор, по которому apply-bypass.sh::rebuild_ports ставит цепочку: сперва правила ЭТОГО устройства,
# потом правила всего роутера (`any`), внутри — узкое раньше широкого (поровну — порядок файла). Двоеточие разделителем безопасно — все
# три поля из словаря без двоеточий (proto/dir — слова, порты после port_list_norm = цифры, запятые,
# дефисы). PORT_DEV/PORT_ANY — ЧЬИ правила есть: панель говорит «у этого устройства есть правила по
# портам» только про его собственные (ревью пачки 3, круг 1: флаг поднимали и одни правила роутера).
load_port_rules() {   # $1 = IP клиента
	PORT_RULES=""; PORT_DEV=false; PORT_ANY=false
	[ -s "$ENODIA_STATE/.port-rules" ] || return 0
	command -v port_rules_in_order >/dev/null 2>&1 || return 0
	_lpt=$(printf '	')
	_lprows=$(port_rules_in_order "$ENODIA_STATE/.port-rules" "$1")
	# Цикл по here-doc (не пайп) — в ТЕКУЩЕМ шелле, иначе PORT_RULES не пережил бы пайп.
	while IFS="$_lpt" read -r _psrc _ppro _ppts _pdir; do
		[ -n "$_pdir" ] || continue
		if [ "$_psrc" = any ]; then PORT_ANY=true; else PORT_DEV=true; fi
		PORT_RULES="$PORT_RULES $_ppro:$_ppts:$_pdir"
	done <<EOF_PR
$_lprows
EOF_PR
}

# port_hit <список портов> <порт> → 0, если порт попадает в список («all» или «N,M-K»).
# Без форков: список режем через IFS, а не `tr` — на 50 соединений это полсотни лишних процессов.
# `set --` внутри функции меняет ЕЁ позиционные параметры, поэтому $1/$2 читаем в свои переменные
# ДО него.
port_hit() {
	[ "$1" = all ] && return 0
	_hl=$1; _hp=$2; _hI=$IFS; IFS=','
	set -- $_hl
	IFS=$_hI
	for _ht in "$@"; do
		case "$_ht" in
			*-*) _ha=${_ht%-*}; _hb=${_ht#*-}
			     if [ "$_hp" -ge "$_ha" ] 2>/dev/null && [ "$_hp" -le "$_hb" ] 2>/dev/null; then return 0; fi ;;
			*)   [ "$_ht" = "$_hp" ] && return 0 ;;
		esac
	done
	return 1
}

# port_route <proto> <порт> → PORT_VERDICT = vpn|direct|block|sN («» = правила нет).
# Переменной, а не печатью: ip_route зовут для КАЖДОГО соединения, и `$( )` стоил бы форка на
# каждое (замер в шапке ip_route: 200 форков ≈ 0.21 с — бюджет окна и так занят ipset test).
port_route() {
	PORT_VERDICT=""
	[ -n "$PORT_RULES" ] || return 0
	case "$1" in udp|tcp) ;; *) return 0 ;; esac   # icmp и прочее правилами по портам не ловится
	case "$2" in ''|0|*[!0-9]*) return 0 ;; esac
	for _pr in $PORT_RULES; do
		_ppr=${_pr%%:*}; _pdr=${_pr##*:}; _ppl=${_pr#*:}; _ppl=${_ppl%:*}
		[ "$_ppr" = both ] || [ "$_ppr" = "$1" ] || continue
		port_hit "$_ppl" "$2" || continue
		PORT_VERDICT=$_pdr
		return 0
	done
	return 0
}

# desync_via <ip> → DESYNC_VIA = «десинк устройства» | «десинк» | «» (пусто = десинка нет).
# Десинк — НЕ маршрут: трафик всё равно идёт напрямую, ломают только рукопожатие. Поэтому он
# всегда лишь ИСТОЧНИК — и спрашивают о нём ТРИ разные ветки ip_route (мёртвая маркировка, прямое
# правило по портам, общий низ). Держим ОДНУ копию: забыть спросить в одной из них — значит снова
# писать «просто напрямую» там, где десинк работает.
# Переменной, а не печатью: ip_route зовут на КАЖДОЕ соединение, `$( )` стоил бы форка на каждое.
desync_via() {   # $1 = ip назначения, $2 = порт назначения
	DESYNC_VIA=""
	[ -n "$2" ] || return 0                 # порта нет (icmp) — nfqws такой пакет не видит
	# Правила ПО ИСТОЧНИКУ («устройство целиком в десинк») — первыми: они специфичнее пула.
	case " $DESYNC_WIRED " in *" @src:$2 "*)
		[ "$DESYNC_SRC" = 1 ] && { DESYNC_VIA="десинк устройства"; return 0; } ;;
	esac
	for _dw in $DESYNC_WIRED; do
		case "$_dw" in @src:*) continue ;; esac
		[ "${_dw##*:}" = "$2" ] || continue      # правило заведено на ДРУГОЙ порт
		if ipset test "${_dw%:*}" "$1" >/dev/null 2>&1; then DESYNC_VIA=десинк; return 0; fi
	done
	return 0
}

# dom_route <домен> → R_* (маршрут, источник, намерение, десинк) и R_OWN. Пустой R_ROUTE = явного
# правила НЕТ (домен поедет по общему списку/напрямую — по IP, а это уже видно в соединениях; врать
# «напрямую» тут нельзя). R_OWN=1 → у САМОГО этого имени есть наше одиночное правило (domain.sh) ⇒ панель
# предлагает его СНЯТЬ. Только у самого имени: правило родителя снимается по родителю, и ✕ под поддоменом
# ответил бы «такого правила нет». Правило группы снимать поштучно нельзя (это состав группы) — панель
# вместо этого называет группу.
#
# ДОМЕН НАПОЛНЯЕТ НАБОРЫ СВОИХ ПРАВИЛ И ПРАВИЛ РОДИТЕЛЕЙ: dns-merge.sh склеивает строку конфликтного домена
# с унаследованными от родителя (`ipset=/cdn.youtube.com/zapret_dom,grp_vpn_s2`), а кто из наборов главнее,
# решают цепочки ядра. Поэтому сперва собираем, в какие наборы домен попадает на ЛЮБОМ уровне имени
# (ближний уровень — первым: у него и имя группы), и лишь потом решаем — в порядке ядра. Прежде проход
# останавливался на первом совпавшем уровне и отвечал «в VPN» по правилу поддомена там, где «мимо» родителя
# обрывало его ACCEPT'ом.
# СУФФИКСНОЕ сравнение, а не точное: dnsmasq-правило `ipset=/youtube.com/…` ловит И все поддомены, а в
# query-log устройство светит именно ПОДдомен. Поднимаемся к родителю ДО ЗОНЫ одним словом: groups.sh пускает в
# группу и зону (`ru` — импорт `domain:ru`, «весь рунет напрямую»), и строка `ipset=/ru/grp_out` ловит yandex.ru — домен
# говорил «нет правила», а его адрес ниже — «мимо · группа» (ревью шага 4b, круг 3). Форков нет, кроме имени группы у итога: совпадения уже собраны (load_dom_hits), здесь — case.
# Набор считается, только если его правило в ядре ЕСТЬ (MARK_SETS/ZAP_SETS из load_walk, «мимо» — обход WALK): пул
# десинка на AmneziaWG правил не получает, и домен из него идёт как обычный — страница раздела так и пишет.
dom_route() {   # $1 = домен, $2 = порт (опц.; пусто = 443, как было у `view`)
	_dq=$1; _d=$1; R_OWN=0; _dp=${2:-443}
	_hb=""; _hdev=""; _hoo=""; _hog=""; _hoe=""; _hkeep=""; _hzap=""; _hzs=""; _hslot=""; _hvpn=""
	while [ -n "$_d" ]; do
		# Блок по DNS отвечает про само запрошенное имя: dnsmasq пишет в журнал ответ на то, что спросили.
		on "$DOM_HITS" "$_d:B:blk " && _hb=1
		if [ -z "$_hdev" ]; then case "$DEV_DOMS" in *" $_d="*) _hdev=${DEV_DOMS#*" $_d="}; _hdev=${_hdev%% *} ;; esac; fi
		_ow=0
		if on "$DOM_HITS" "$_d:C:enodia_bypass "; then _ow=1; _hoo=1; fi
		if on "$DOM_HITS" "$_d:C:enodia_list "; then
			_ow=1
			if [ -z "$_hkeep" ] && on "$KEEP_ON" "enodia_list:"; then _hkeep=own; fi
			if [ -z "$_hvpn" ] && on "$MARK_SETS" "enodia_list:"; then _hvpn=own; fi
		fi
		[ "$_d" = "$_dq" ] && R_OWN=$_ow
		if [ -z "$_hog" ] && on "$DOM_HITS" "$_d:G:grp_out "; then _hog=$_d; fi
		on "$DOM_HITS" "$_d:E:geo_out " && _hoe=1
		# Набор ЗАПОМИНАЕМ: «десинк» обещает не пул сам по себе, а NFQUEUE на ЭТОМ наборе и ЭТОМ порту.
		if on "$DOM_HITS" "$_d:E:geo_zapret " && on "$ZAP_SETS" "geo_zapret "; then _hzap=1; [ -n "$_hzs" ] || _hzs=geo_zapret; fi
		if on "$DOM_HITS" "$_d:Z:zapret_dom " && on "$ZAP_SETS" "zapret_dom "; then _hzap=1; [ -n "$_hzs" ] || _hzs=zapret_dom; fi
		for _dn in 2 3 4; do
			for _dt in G:grp_vpn_s E:geo_vpn_s; do
				on "$DOM_HITS" "$_d:$_dt$_dn " || continue
				# Группа ZAPRET-выхода — не метка, а пул десинка: ACCEPT в ENODIA_ZAPRET, метки нет (mark-core).
				if on "$ZAP_SETS" "${_dt#?:}$_dn "; then _hzap=1; [ -n "$_hzs" ] || _hzs="${_dt#?:}$_dn"
				elif [ -z "$_hslot" ] && on "$MARK_SETS" "${_dt#?:}$_dn:"; then _hslot="$_dn:$_d"; fi
			done
		done
		if on "$DOM_HITS" "$_d:G:grp_vpn "; then
			if [ -z "$_hkeep" ] && on "$KEEP_ON" "grp_vpn:"; then _hkeep="grp:$_d"; fi
			if [ -z "$_hvpn" ] && on "$MARK_SETS" "grp_vpn:"; then _hvpn="grp:$_d"; fi
		fi
		if [ -z "$_hvpn" ] && on "$DOM_HITS" "$_d:E:geo_vpn " && on "$MARK_SETS" "geo_vpn:"; then _hvpn=geo; fi
		case "$_d" in *.*) _d="${_d#*.}" ;; *) break ;; esac
	done
	# Десинк поверх прямого пути: домен в заведённом пуле (по адресу назначения) или само устройство «в десинк»
	# (по источнику). У домена нет порта — называем то, что стоит на 443 (zapret.sh вешает NFQUEUE только туда).
	# ПОРТ НАЗВАН ВСЛУХ — по нему и судим: nfqws висит на КОНКРЕТНОМ порту (zapret.sh вешает NFQUEUE
	# только на 443), и «десинк» у имени на порту 80 был бы обещанием, которого ядро не даёт. У `view`
	# порта нет вовсе (у домена его и не бывает) — там прежнее поведение, 443.
	_zd=""
	if [ "$_hzap" = 1 ]; then case " $DESYNC_WIRED " in *" $_hzs:$_dp "*) _zd='десинк' ;; esac; fi
	if [ -z "$_zd" ] && [ "$DESYNC_SRC" = 1 ]; then case " $DESYNC_WIRED " in *" @src:$_dp "*) _zd='десинк устройства' ;; esac; fi
	# Порядок ниже = порядок ядра. Блок по DNS — не маршрут, а ответ: домен резолвится в ноль, куда бы его ни вели.
	if [ -n "$_hb" ]; then res block 'список блокировки' '' ''; return; fi
	case "$_hdev" in                                   # VPN_DEV
		block)  res block 'правило устройства' '' ''; return ;;
		bypass) res_direct bypass 'правило устройства' '' '' '' "$_zd"; return ;;
		vpn)    res_mark 0x1 'правило устройства' '' '' "$_zd"; return ;;
		slot[234])
			# Выход выключен или zapret — rebuild_dev ставит основную метку: судим по меткам цепочки, а не по выбору.
			_dm="0x${_hdev#slot}"; on "$DEV_MARKS" "$_dm " || _dm=0x1
			res_mark "$_dm" 'правило устройства' '' '' "$_zd"; return ;;
	esac
	case "$_hkeep" in                                  # VPN_KEEP — исключения из «мимо VPN»
		own)   res_mark 0x1 'свой домен' '' '' "$_zd"; return ;;
		grp:*) res_mark 0x1 "$(grp_name "${_hkeep#grp:}" 0)" '' '' "$_zd"; return ;;
	esac
	# VPN_EXCLUDE — В ПОРЯДКЕ ЯДРА (WALK): «мимо» по адресу (наборы) и по источнику (устройство, сеть) лежат в ОДНОЙ цепочке,
	# а порядок их правил зависит от того, кто и когда их применял (замер BE7000 18.09.2026: после ребута grp_out и geo_out
	# ушли ниже `-s` и physdev). Итог один — напрямую, но подпись обязана назвать сработавшее правило — ту же, что у строки
	# соединения на этом экране. Правило `-d` — адрес, у домена его нет; набор без правила в цепочке в WALK не попадает.
	_wI=$IFS; IFS='
'
	for _wl in $WALK; do
		IFS=$_wI
		set -- $_wl
		[ "$1" = VPN_EXCLUDE ] && [ "$6" = ACCEPT ] || continue
		case "$5" in
			enodia_bypass) [ -n "$_hoo" ] || continue; res_direct bypass 'свой домен' '' '' '' "$_zd" ;;
			grp_out)       [ -n "$_hog" ] || continue; res_direct bypass "$(grp_name "$_hog" 0)" '' '' '' "$_zd" ;;
			geo_out)       [ -n "$_hoe" ] || continue; res_direct bypass 'гео' '' '' '' "$_zd" ;;
			-)             [ "$3" = - ] || continue
			               if [ "$4" != - ]; then res_direct direct 'режим сети' '' '' '' "$_zd"
			               elif [ "$DESYNC_SRC" = 1 ]; then res direct "${_zd:-режим устройства}" '' ''
			               else res_direct direct 'режим устройства' '' '' '' "$_zd"; fi ;;
			*)             continue ;;
		esac
		IFS=$_wI; return
	done
	IFS=$_wI
	if [ -n "$SRC_FORCE" ]; then res_mark "$SRC_FORCE" "$SRC_FVIA" '' '' "$_zd"; return; fi   # VPN_FORCE
	# ENODIA_ZAPRET ведёт напрямую ЛЮБОЙ порт, а ломает рукопожатие только там, где стоит NFQUEUE:
	# на другом порту это не десинк, а просто прямой путь. Зеркало ветки `zap` в ip_route.
	if [ "$_hzap" = 1 ]; then res direct "${_zd:-пул десинка}" '' ''; return; fi              # ENODIA_ZAPRET
	case "$_hslot" in ?:*) res_mark "0x${_hslot%%:*}" "$(grp_name "${_hslot#*:}" "${_hslot%%:*}")" '' '' "$_zd"; return ;; esac
	case "$_hvpn" in                                   # маркировка mark-core
		own)   res_mark 0x1 'свой домен' '' '' "$_zd"; return ;;
		geo)   res_mark 0x1 'гео' '' '' "$_zd"; return ;;
		grp:*) res_mark 0x1 "$(grp_name "${_hvpn#grp:}" 0)" '' '' "$_zd"; return ;;
	esac
	# Явного правила на домен нет — но гостевая «мимо» ведёт напрямую всё, а устройство «целиком в десинк»
	# (без своей пары в VPN_EXCLUDE, чего быть не должно) десинкает всё, что спрашивает.
	if [ "$GUEST_MAIN" = 1 ]; then res direct 'гостевая сеть' '' "$_zd"; return; fi
	if [ -n "$_zd" ] && [ "$DESYNC_SRC" = 1 ]; then res direct "$_zd" '' ''; return; fi
	res '' '' '' ''
}
# ip_route <адрес> [proto] [порт] → R_*. Порядок = порядок ядра: блок-листы (filter, после маршрутизации —
# потому и первыми), правила по портам (VPN_PORTS, из хранилища: у правила есть порт), обход цепочек и
# маркировки (walk), куда ведёт метка (mark_go) и гостевая «мимо» поверх всех меток. Форки ipset test
# НЕОБХОДИМЫ: наборы держат подсети (iplist_set = 3.5k CIDR), строкой их не сматчить; пустые наборы
# пропускаем, пару MARK+ACCEPT по одному набору спрашиваем один раз. Замер прежней лестницы на железе —
# 200 форков ≈ 0.21 с, для окна на 50 соединений приемлемо.
ip_route() {
	_ia=$1; _ipr=$2; _ipt=$3
	for _ib in $BLK_SETS; do
		ipset test "$_ib" "$_ia" >/dev/null 2>&1 || continue
		_ibok=0
		for _iba in $BLK_ALLOW; do ipset test "$_iba" "$_ia" >/dev/null 2>&1 && { _ibok=1; break; }; done
		[ "$_ibok" = 1 ] && break
		case "$_ib" in geo_*) res block 'гео' '' '' ;; *) res block 'список блокировки' '' '' ;; esac
		return
	done
	# ПОРТ-ПРАВИЛА ПЕРВЫМИ — цепочка VPN_PORTS стоит выше выреза, правил устройства и маркировки (см. блок
	# load_port_rules). Порт-правило на выключенный выход ставит метку без гейта (rebuild_ports, fail-open):
	# `ip rule` под неё нет, и mark_go честно ответит «напрямую».
	port_route "$_ipr" "$_ipt"
	case "$PORT_VERDICT" in
		block)  res block 'правило по портам' '' ''; return ;;
		direct) if [ "$GUEST_MAIN" = 1 ]; then res_direct direct 'гостевая сеть' "$_ia" "$_ipt" '' ''
		        else res_direct direct 'правило по портам' "$_ia" "$_ipt" '' ''; fi; return ;;
		vpn)    res_mark 0x1 'правило по портам' "$_ia" "$_ipt" ''; return ;;
		s[234]) res_mark "0x${PORT_VERDICT#s}" 'правило по портам' "$_ia" "$_ipt" ''; return ;;
	esac
	walk "$_ia"; walk_via
	if [ "$W_T" = drop ]; then res block "$W_VIA" '' ''; return; fi
	if [ -n "$W_M" ]; then res_mark "$W_M" "$W_VIA" "$_ia" "$_ipt" ''; return; fi
	if [ "$W_T" = accept ]; then
		if [ "$GUEST_MAIN" = 1 ]; then res_direct direct 'гостевая сеть' "$_ia" "$_ipt" '' ''; return; fi
		case "$W_KIND" in
			src)  res_direct direct "$W_VIA" "$_ia" "$_ipt" '' '' ;;
			dsrc) desync_via "$_ia" "$_ipt"; res direct "${DESYNC_VIA:-режим устройства}" '' '' ;;
			# Пул десинка ведёт напрямую ЛЮБОЙ порт, а NFQUEUE стоит только на заведённом: на другом порту это
			# не десинк, а просто прямой путь — ровно то «десинк на UDP 7600», от которого лечили источник.
			zap)  desync_via "$_ia" "$_ipt"; if [ -n "$DESYNC_VIA" ]; then res direct 'десинк' '' ''; else res direct 'пул десинка' '' ''; fi ;;
			*)    res_direct bypass "$W_VIA" "$_ia" "$_ipt" '' '' ;;
		esac
		return
	fi
	# Никто не решил: метки нет — прямой путь.
	if [ "$GUEST_MAIN" = 1 ]; then res_direct direct 'гостевая сеть' "$_ia" "$_ipt" '' ''; return; fi
	res_direct direct '' "$_ia" "$_ipt" '' ''
}

emit_domains() {  # emit_domains <ip>
	ip="$1"; LIMIT=50
