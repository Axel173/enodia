# КЭШ «ПОСЛЕДНИЙ РАБОЧИЙ АДРЕС server-host» ------------------------------------------------
# ЗАЧЕМ (жалоба тестера 13.08.2026 «минуту подключается к vless по имени», разобрана на железе
# 14.08). Подъём несущей по ИМЕНИ упирался в сеть: нет резолва — шесть ожиданий подряд и честный
# отказ. При этом прошлый УСПЕШНЫЙ адрес лежал рядом — строкой `address=/host/IP` в seed-файле, —
# но взять его было неоткуда: seed живёт в /etc/dnsmasq.d (ramfs) и в /tmp, ОБЕ копии гибнут на
# ребуте, а на /data персиста не было ни одного файла. То есть в самом горячем сценарии (бут,
# failover) фолбэк отсутствовал именно тогда, когда он и нужен.
#
# ПОЧЕМУ «СТАРЫЙ АДРЕС» ЛУЧШЕ «НИКАКОГО». Худший случай кэша — сервер сменил IP (DDNS/переезд):
# несущая встанет на мёртвый адрес, health не пройдёт, и сторож уведёт на резерв — ровно то же,
# что происходит при отказе подъёма, только на два тика позже. Лучший случай — DNS лёг, а сервер
# на месте: несущая поднимается СРАЗУ вместо «минуты» и работает. Кэш — производное, не настройка:
# в бэкап не входит (см. `# EXCLUDE:` в web/cgi-bin/backup), первый же удачный резолв его чинит.
#
# Пишем ТОЛЬКО когда адрес РЕАЛЬНО сменился: /data — UBIFS на 20 МБ, а зовут нас на каждый подъём.
# Отметка времени в третьей колонке — для человека с дампом; ВОЗРАСТ по ней НЕ считаем (файл
# переживает ребут ⇒ age_since тут неприменим, см. границу в clock-lib.sh).
# СОСТОЯНИЕ — в $ENODIA_STATE, не в каталоге кода: тот заменяется обновлением ЦЕЛИКОМ (C46). Вложенная
# форма `${ENODIA_DIR:-…}/файл` при переезде 30.08.2026 ускользнула от проверки — файл жил в коде до
# 05.09.2026; старую копию подбираем один раз (кэш последнего рабочего адреса дорог ровно на буте).
ENODIA_STATE=${ENODIA_STATE:-/data/usr/app/enodia-state}
SEED_CACHE="${SEED_CACHE:-$ENODIA_STATE/.dns-seed-cache}"
if [ ! -f "$SEED_CACHE" ] && [ -f "${ENODIA_DIR:-/data/usr/app/enodia}/.dns-seed-cache" ] && [ -d "$ENODIA_STATE" ]; then   # migrate: см. mv ниже
    mv "${ENODIA_DIR:-/data/usr/app/enodia}/.dns-seed-cache" "$SEED_CACHE" 2>/dev/null || true   # migrate: код → состояние, один раз
fi
SEED_TRIES=${SEED_TRIES:-6}                  # ожиданий сети, когда прошлого адреса НЕТ (прежнее поведение)
SEED_TRIES_CACHED=${SEED_TRIES_CACHED:-2}    # ...и когда ЕСТЬ: дальше поднимаемся на нём

# seed_cache_get <host> — прошлый рабочий IPv4 или пусто. Поле ищем по ПЕРВОЙ колонке (busybox awk
# без index()/split(), но сравнение полей есть).
seed_cache_get() {
    [ -f "$SEED_CACHE" ] || return 1
    awk -v h="$1" '$1==h{print $2; exit}' "$SEED_CACHE" 2>/dev/null
}

# seed_cache_put <host> <ip> — переписать строку хоста (атомарно через .tmp + mv).
seed_cache_put() {
    _scp_h="$1"; _scp_i="$2"
    [ -n "$_scp_h" ] && [ -n "$_scp_i" ] || return 0
    _scp_t="$SEED_CACHE.tmp"
    if [ -f "$SEED_CACHE" ]; then
        awk -v h="$_scp_h" '$1!=h' "$SEED_CACHE" > "$_scp_t" 2>/dev/null
    else
        : > "$_scp_t" 2>/dev/null
    fi
    printf '%s\t%s\t%s\n' "$_scp_h" "$_scp_i" "$(date +%s)" >> "$_scp_t" 2>/dev/null   # clock-raw: отметка для дампа, возраст по ней не считаем
    mv -f "$_scp_t" "$SEED_CACHE" 2>/dev/null
    return 0
}

# seed_host_dns <host> <seed-файл> — «посеять» ответ для server-host в ЛОКАЛЬНЫЙ dnsmasq
# (address=/host/IP), чтобы демон несущей (xray/hysteria) резолвил имя САМ, мгновенно и
# локально, НЕ уходя в ещё-не-поднятый туннель. Конфиг пользователя НЕ трогаем: имя в нём
# остаётся источником истины (из него же демон берёт SNI). Резолвим на КАЖДЫЙ старт → смена
# IP сервера подхватывается. Seed-файл ИЗОЛИРОВАННЫЙ (создаём/удаляем только его; директива
# address= с валидным IP не способна уронить dnsmasq) ⇒ положить интернет вызов не может.
# Возврат 1 = host не зарезолвлен: вызывающий ЧЕСТНО не поднимает несущую (демон по имени
# упал бы FATAL, а панель/установщик рапортовали бы «всё ок» при мёртвом туннеле).
#
# ЗАЧЕМ В ЭТОМ ФАЙЛЕ: сев нужен ОБОИМ socks-транспортам (xray, hy2) и каждому их ДОП-ВЫХОДУ
# (Ф3: свой сервер → свой seed-файл 02-altserver-s<id>.conf). Копия на плагин = гарантированное
# расхождение (ровно поэтому сюда переехал resolve_ipv4). Файл сева задаёт ВЫЗЫВАЮЩИЙ.
#
# ДВЕ КОПИИ ФАЙЛА (грабля adblock/zapret, поймана на железе 2026-07-25). Стоковый init.d dnsmasq
# на КАЖДОМ рестарте копирует /etc/dnsmasq.d → /tmp/dnsmasq.d АДДИТИВНО, без чистки, а читает
# dnsmasq ОБА каталога. Значит запись в /etc доезжает, а УДАЛЕНИЕ из /etc — НЕТ: копия в /tmp
# переживает снятие несущей, и `address=/host/IP` продолжает жить до ребута. Для сида это хуже,
# чем для доменных списков: при смене IP сервера (DDNS, другой VPS с тем же именем) в dnsmasq
# оказываются ДВА address= для одного имени, он отдаёт ОБА адреса — и демон несущей может уйти
# дозваниваться на мёртвый. Поэтому пишем и сносим ОБЕ копии (снятие — seed_host_clear ниже).
_seed_live() { case "$1" in /etc/dnsmasq.d/*) echo "/tmp/dnsmasq.d/${1##*/}" ;; esac; }

# ---- ТРЕТЬЯ КОПИЯ ОТВЕТА: /etc/hosts ------------------------------------------------------
# ЗАЧЕМ (разобрано и ЗАМЕРЕНО на живом отказе BE7000 14.08.2026 — жалоба тестера «влесски по имени
# подключаются минуту, а xhttp+udp сразу»). Сида в dnsmasq НЕДОСТАТОЧНО, и вот почему:
#   - `address=/host/IP` авторитетен только для запроса A и только для тех, кто спрашивает dnsmasq;
#   - демоны несущих — Go (xray, hysteria), а Go спрашивает A и AAAA, и AAAA для того же имени
#     dnsmasq ФОРВАРДИТ upstream (проверено: `ping6 <host>` = 5 с при живом сиде);
#   - при «Шифрованном DNS» upstream ровно один — локальный прокси, а его :443 форс-маркой уходит
#     в table 1000, то есть в ЕЩЁ НЕ ПОДНЯТУЮ несущую. Круг замкнулся: чтобы поднять несущую, нужен
#     DNS, а DNS заперт в этой несущей. Голый IP-литерал круг не замыкает — потому и «сразу».
# ЗАМЕР НА ОТКАЗЕ: DNS мёртв → reality/trojan-grpc/xhttp НЕ встают вовсе; с одной строкой здесь и
# тем же мёртвым DNS — 295/412/347 мс. Работает потому, что Go читает hosts ДО резолвера
# (files→dns) ⇒ в сеть не уходит НИ ОДНОГО запроса, ни A, ни AAAA.
# Владелец строки — seed-файл (у каждого доп-выхода свой) ⇒ метка несёт его имя: снятие одного
# сида не трогает чужие. /etc — ramfs, строка гибнет на ребуте и переигрывается heal'ом, как сид.
SEED_HOSTS="${SEED_HOSTS:-/etc/hosts}"
_seed_tag() { echo "# awg-seed ${1##*/}"; }

# seed_hosts_put <host> <ip…> <seed-файл> — поставить/обновить наши строки (идемпотентно). Адресов бывает
# НЕСКОЛЬКО (через пробел) — строка на адрес: закреплению имени DoH-резолвера (doh-lib.sh::doh_pin_hosts) нужны
# оба якоря, иначе прокси потерял бы запасной адрес. Сид несущей даёт один — прежняя одна строка байт-в-байт.
seed_hosts_put() {
    _shp_h="$1"; _shp_i="$2"
    { [ -n "$_shp_h" ] && [ -n "$(printf '%s' "$_shp_i" | tr -d ' ')" ]; } || return 0
    _shp_t=$(_seed_tag "$3")
    _shp_w=$(for _shp_a in $_shp_i; do printf '%s\t%s\t%s\n' "$_shp_a" "$_shp_h" "$_shp_t"; done)
    [ -f "$SEED_HOSTS" ] || : > "$SEED_HOSTS" 2>/dev/null
    # Уже стоят РОВНО эти строки (и ничего сверх) — файл не трогаем: на AX3600 /etc — флеш, а зовут нас на каждый подъём.
    [ "$(grep -F "$_shp_t" "$SEED_HOSTS" 2>/dev/null)" = "$_shp_w" ] && return 0
    _shp_p="$SEED_HOSTS.enodiatmp"
    grep -vF "$_shp_t" "$SEED_HOSTS" > "$_shp_p" 2>/dev/null      # busybox: код 1 при пустом выводе — не судим по нему
    printf '%s\n' "$_shp_w" >> "$_shp_p" 2>/dev/null
    [ -s "$_shp_p" ] && mv -f "$_shp_p" "$SEED_HOSTS" 2>/dev/null
    rm -f "$_shp_p" 2>/dev/null
    return 0
}

# seed_hosts_clear <seed-файл> — снять свою строку. Код 0 = что-то удалили.
seed_hosts_clear() {
    _shc_t=$(_seed_tag "$1")
    grep -qF "$_shc_t" "$SEED_HOSTS" 2>/dev/null || return 1
    _shc_p="$SEED_HOSTS.enodiatmp"
    grep -vF "$_shc_t" "$SEED_HOSTS" > "$_shc_p" 2>/dev/null
    # Гарда `-s` тут быть НЕ ДОЛЖНО (в отличие от seed_hosts_put, где своя строка в остатке всегда
    # есть): пустой остаток — законный случай «наша строка была в файле единственной», и гард
    # оставил бы файл С НЕЙ, вернув при этом «удалили» — вызывающий зря рестартнул бы dnsmasq, а
    # имя осталось прибитым к старому адресу. Читаемость исходника уже доказана grep -qF выше.
    if [ -f "$_shc_p" ]; then mv -f "$_shc_p" "$SEED_HOSTS" 2>/dev/null; fi
    rm -f "$_shc_p" 2>/dev/null
    return 0
}

# seed_host_clear <seed-файл> — снять сид ЦЕЛИКОМ (обе копии). Код 0 = что-то реально удалили
# ⇒ вызывающему нужен рестарт dnsmasq (SIGHUP конфиг не перечитывает); 1 = сида не было.
# Снятое ОТМЕЧАЕМ (DNS_RELOAD_MARK) — для тех, кто рестарт доверяет DNS-сеттеру следом (снятие несущей xray/hy2, сервер
# IP-литералом ниже): сеттер теперь идёт через doh-lib.sh::dns_upstream_put, а тот при том же upstream лишь шлёт HUP — и снятый
# `address=` жил бы в памяти демона до чужого рестарта, иногда сутками (ревью с.95). Отметка велит ему перезапустить.
DNS_RELOAD_MARK=${DNS_RELOAD_MARK:-/tmp/enodia-dns-reload}
seed_host_clear() {
    _sc_f="$1"; [ -n "$_sc_f" ] || return 1
    _sc_l=$(_seed_live "$_sc_f"); _sc_hit=1
    [ -f "$_sc_f" ] && _sc_hit=0
    [ -n "$_sc_l" ] && [ -f "$_sc_l" ] && _sc_hit=0
    rm -f "$_sc_f" 2>/dev/null
    [ -n "$_sc_l" ] && rm -f "$_sc_l" 2>/dev/null
    if seed_hosts_clear "$_sc_f"; then _sc_hit=0; fi    # третья копия (форма `if` — она безразлична к позиции под set -e)
    if [ "$_sc_hit" = 0 ]; then : > "$DNS_RELOAD_MARK" 2>/dev/null; fi
    return $_sc_hit
}

seed_host_dns() {   # $1 = host ; $2 = seed-файл
    _sh_host="$1"; _sh_file="$2"
    [ -n "$_sh_host" ] && [ -n "$_sh_file" ] || return 1
    if is_ipv4 "$_sh_host"; then
        seed_host_clear "$_sh_file"; return 0          # server уже IP — сеять нечего, чистим прошлый сид (обе копии)
    fi
    # Прошлый рабочий адрес читаем ДО цикла: он решает, сколько ждать сеть. Есть кэш — ждём две
    # попытки и поднимаемся на нём (несущая живёт, резолв догоним на следующем подъёме); нет кэша —
    # прежние шесть ожиданий и честный отказ, потому что подставить нечего.
    _sh_ip=""; _sh_n=0; _sh_from_cache=0
    _sh_cached=$(seed_cache_get "$_sh_host")
    while [ "$_sh_n" -lt "$SEED_TRIES" ]; do
        _sh_ip=$(resolve_ipv4 "$_sh_host"); [ -n "$_sh_ip" ] && break
        _sh_n=$((_sh_n+1))
        if [ -n "$_sh_cached" ] && [ "$_sh_n" -ge "$SEED_TRIES_CACHED" ]; then
            _sh_ip="$_sh_cached"; _sh_from_cache=1
            _dnslib_log "резолв '$_sh_host' не удался ($_sh_n) → поднимаюсь на ПРОШЛОМ рабочем адресе $_sh_ip (кэш)"
            break
        fi
        _dnslib_log "резолв server-host '$_sh_host' попытка $_sh_n не удалась — повтор через 2с…"; sleep 2
    done
    [ -n "$_sh_ip" ] || { _dnslib_log "НЕ зарезолвил server-host '$_sh_host' за $SEED_TRIES попыток → несущая не встанет (честно)"; return 1; }
    is_ipv4 "$_sh_ip" || { _dnslib_log "резолв вернул не-IP '$_sh_ip' — не сею"; return 1; }
    # Свежий резолв запоминаем; адрес из кэша (и повтор того же значения) НЕ переписываем — /data
    # это флеш, а зовут нас на каждый подъём несущей.
    if [ "$_sh_from_cache" = 0 ] && [ "$_sh_ip" != "$_sh_cached" ]; then seed_cache_put "$_sh_host" "$_sh_ip"; fi
    # /etc/hosts — ДО быстрого выхода ниже: именно эта строка и разрывает круг «DNS через несущую,
    # несущая через DNS» (разбор в шапке блока). Идемпотентна ⇒ на горячем пути бесплатна.
    seed_hosts_put "$_sh_host" "$_sh_ip" "$_sh_file"
    # Сид УЖЕ стоит и dnsmasq его РЕАЛЬНО отдаёт → не переписываем и не рестартим dnsmasq.
    # ЗАЧЕМ: рестарт = секундный провал DNS для ВСЕХ клиентов, а зовут нас на каждый подъём
    # несущей; с тех пор как restart_xray/restart_hy2 резолвят кандидата ДО остановки демона
    # (анти-«чёрная дыра»), на один старт приходится ДВА сева подряд — второй обязан быть
    # бесплатным. Проверяем ФАКТ выдачи, а не только содержимое файла: /etc/dnsmasq.d — ramfs,
    # а живая копия лежит в /tmp/dnsmasq.d (init копирует /etc→/tmp только на старте) ⇒ «файл
    # на месте» само по себе не значит «dnsmasq отвечает».
    # Сверяем ОБЕ копии: совпадения одной мало — вторая (живая, в /tmp) могла остаться от прежнего
    # IP, и тогда nslookup вернёт ДВА адреса, среди которых наш новый найдётся, а демон несущей
    # с равным успехом возьмёт старый (мёртвый). Расхождение копий ⇒ переписываем обе.
    _sh_want="address=/$_sh_host/$_sh_ip"
    _sh_live=$(_seed_live "$_sh_file")
    if [ "$(cat "$_sh_file" 2>/dev/null)" = "$_sh_want" ] \
       && { [ -z "$_sh_live" ] || [ "$(cat "$_sh_live" 2>/dev/null)" = "$_sh_want" ]; } \
       && timeout -t "${RESOLVE_NS_TIMEOUT:-2}" nslookup "$_sh_host" 2>/dev/null | awk '/^Name:/{f=1;next} f&&/Address/{print $NF}' | grep -qx "$_sh_ip"; then
        _dnslib_log "локальный DNS: $_sh_host → $_sh_ip (сид уже стоит — dnsmasq не трогаю)"
        return 0
    fi
    mkdir -p /etc/dnsmasq.d
    printf '%s\n' "$_sh_want" > "$_sh_file"
    if [ -n "$_sh_live" ]; then mkdir -p /tmp/dnsmasq.d 2>/dev/null; printf '%s\n' "$_sh_want" > "$_sh_live"; fi
    /etc/init.d/dnsmasq restart >/dev/null 2>&1 || killall -HUP dnsmasq 2>/dev/null
    _sh_k=0                                            # дождаться, что dnsmasq реально отдаёт сид (до старта демона)
    while [ "$_sh_k" -lt 6 ]; do
        timeout -t "${RESOLVE_NS_TIMEOUT:-2}" nslookup "$_sh_host" 127.0.0.1 2>/dev/null | awk '/^Name:/{f=1;next} f&&/Address/{print $NF}' | grep -qx "$_sh_ip" && break
        _sh_k=$((_sh_k+1)); sleep 1
    done
    _dnslib_log "локальный DNS: $_sh_host → $_sh_ip (демон резолвит имя сам; конфиг по имени не трогаем)"
    return 0
}
# Лог библиотеки: если вызывающий определил свой log() (все плагины транспортов — да), пишем
# его префиксом; иначе просто на stdout. Не заводим здесь собственный формат — сообщения о
# севе исторически шли в лог плагина, и диагностика их там ищет.
_dnslib_log() { if command -v log >/dev/null 2>&1; then log "$@"; else echo "[dns-lib] $*"; fi; }
