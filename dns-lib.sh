#!/bin/sh
# dns-lib.sh — общий резолв имени в IPv4 для транспортов (единственный источник истины).
#
# ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ: одна и та же функция нужна ТРЁМ несущим, и все три ловят одну и ту
# же граблю «имя сервера резолвится через ещё-не-поднятый туннель»:
#   - xray/hysteria — демон резолвит server-host при старте и падает FATAL без ретрая
#     (лечится seed_server_dns: address=/host/IP в локальный dnsmasq);
#   - AmneziaWG — `awg setconf` резолвит Endpoint-домен и при осечке отвергает ВЕСЬ конфиг
#     (awg0 встаёт ПУСТЫМ: private-key-set=0 peers=0 — проверено на железе 2026-07-15),
#     лечится подстановкой IP в Endpoint (см. awg_setup.sh).
# Раньше функция была продублирована в xray-transport.sh и transport-hy2.sh («зеркало»);
# третья копия под awg сделала бы расхождение неизбежным. Идиома source — как lists-lib.sh.
#
# ГРАБЛЯ (железо): busybox `nslookup HOST SERVER` ИГНОРИРУЕТ аргумент SERVER и всегда бьёт в
# системный resolver (=dnsmasq). Прежний цикл «nslookup @WAN/ISP/public» ДУМАЛ, что обходит
# dnsmasq, а шёл через тот же (возможно дохлый) dnsmasq и НЕ работал. Рабочий обход на этом
# busybox — только DoH ПО IP-ЛИТЕРАЛУ (curl 8.4.0 TLS; у 1.1.1.1/8.8.8.8 валидный IP-SAN-
# сертификат, DNS в цепочке нет). Идиома — iplist-update.sh fetch_url.
#
# ГРАБЛЯ №2 (лог живого роутера 01.08.2026): САМ DoH-фолбэк был заперт в ту же мёртвую несущую,
# ради обхода которой написан — и потому не срабатывал НИ РАЗУ, когда был нужен. Оба его
# резолвера роутер заворачивает в туннель собственными руками: 1.1.1.1/8.8.8.8 получают
# `mangle OUTPUT -j MARK 0x1` от set_xray_dns/set_hy2_dns (снимается лишь на релинквише, т.е.
# ПОСЛЕ перебора резервов), в awg-режиме DNS из конфига получает ещё и `ip route <dns>/32 dev
# awg0`, а 8.8.8.8 вдобавок лежит в iplist_set. Итог: подъём резервного сервера ПО ИМЕНИ
# невозможен ровно тогда, когда failover и нужен (кэш dnsmasq спасал лишь уже резолвленные
# имена) → «пул исчерпан» → cross/fail-open, и по кругу. Лечится bind'ом пробы к WAN-интерфейсу:
# SO_BINDTODEVICE (`--interface`) ходит МИМО fwmark-роутинга и мимо маршрута-по-адресу. Тот же
# приём уже несут subs-lib.sh::sub_fetch, web/cgi-bin/ping и status.sh.
# С 04.08.2026 лечение общее: сам цикл DoH вынесен в `doh_ips` (ниже), и через него ходят ВСЕ
# фолбэк-резолверы роутера — notify.sh (SMTP-хост), lists-lib.sh и iplist-update.sh (закачка
# списков по --resolve). Раньше bind получила только эта функция, а три копии остались с багом.

# dom_ok <строка> — ЕДИНСТВЕННЫЙ ответ «годится ли это как ДОМЕН в строке dnsmasq»
# (`ipset=/дом/сет`, `address=/дом/IP`). Код 0 = годится.
#
# ЗАЧЕМ ОБЩИМ И ПОЧЕМУ ИМЕННО 63. Строку в conf-dir пишут ПЯТЬ подсистем (domain.sh, groups.sh,
# geo.sh, пулы списков, dns-hosts.sh), и у каждой был свой регекс «на глаз» — чаще всего
# `^[A-Za-z0-9._-]+\.[A-Za-z]{2,}$`, то есть форма БЕЗ ЕДИНОГО ПОТОЛКА. ЗАМЕРЕНО (dnsmasq 2.80,
# AX3600, `--test` в песочнице /tmp, 15.08.2026): демон отвергает ВЕСЬ конфиг, если хоть одна
# МЕТКА длиннее 63 символов (63 — ещё ok, 64 — уже `error at line N`). Всё прочее он глотает
# молча: `.`, `..`, `-`, `a..b`, `.com`, домен без TLD, общая длина 300. То есть единственное,
# что реально роняет DNS ВСЕЙ сети, ровно никто и не проверял.
# ЦЕНА ПРОМАХА НЕСИММЕТРИЧНА, и это главное: строка ложится в ЖИВОЙ conf-dir и в персист, а
# стреляет ПОЗЖЕ — гард `dns-merge.sh` откажется перезапускать демона (значит человек увидит
# «правило сохранено»), но на ближайшем ребуте heal вернёт персист, и dnsmasq не поднимется
# ВООБЩЕ (воспроизведено на AX3600: `error at line 4 of /etc/dnsmasq.d/enodia-custom.conf`).
# Потолок ИМЕНИ 253 — из стандарта DNS, а не из замера (dnsmasq берёт и 300): длиннее имя не
# резолвится никогда, значит правило заведомо мёртвое, а поле панели без потолка пишет в конфиг
# строку любого размера.
# TLD здесь НЕ требуем: пачке доменов он нужен, группам нужен и голый хост — это ПОЛИТИКА
# вызывающего, а не синтаксис строки dnsmasq. Потребители дописывают свой `\.[A-Za-z]{2,}$` сами.
#
# БЕЗ ФОРКОВ — сознательно, и это ЗАМЕР, а не вкус (AX3600, 500 вызовов): вариант через
# `printf | grep -qE` стоил 7 с (14 мс на вызов — два форка и пайп), проход по меткам средствами
# самого шелла — 1 с. Нас зовут ПО ЧЛЕНУ на пачке: мастер импорта и `add-many` легко дают тысячу
# доменов за прогон, то есть 14 с ожидания против 2 на ровном месте. Вердикты обоих вариантов
# сверены на железе — совпали на всех 16 случаях, включая `com.`, `a..b`, `xn--p1ai` и `-x.com`.
# Поэтому же шимы у потребителей оставлены КОРОТКИМ grep-однострочником: это путь «либа не
# доехала» (редкий), там дороже лишние восемь строк в каждом файле, чем два форка на вызов.
dom_ok() {
    # Быстрый отсев одним `case`: пусто · ведущая/хвостовая точка · пустая метка · чужой знак.
    case "$1" in ''|.*|*.|*..*|*[!A-Za-z0-9._-]*) return 1 ;; esac
    [ "${#1}" -le 253 ] || return 1
    _do_rest="$1"
    while : ; do
        case "$_do_rest" in
            *.*) _do_lab=${_do_rest%%.*}; _do_rest=${_do_rest#*.} ;;
            *)   _do_lab=$_do_rest;       _do_rest='' ;;
        esac
        [ "${#_do_lab}" -le 63 ] || return 1     # длина ≥1 гарантирована отсевом пустых меток выше
        [ -n "$_do_rest" ] || return 0
    done
}

# resolve_ipv4 <host> — печатает IPv4, код 1 если не вышло.
#
# ПОРЯДОК (системный резолвер → DoH через WAN → DoH как есть) ВЫБРАН СОЗНАТЕЛЬНО, не по инерции:
# резолв стоит на ГОРЯЧЕМ пути подъёма несущей (watchdog/failover/boot), каждый мимо-проход стоит
# секунд, а вызывающий (seed_host_dns) ретраит ШЕСТЬ раз. Локальный dnsmasq отвечает мгновенно и
# в 99% случаев верно — он и первый. WAN-bound DoH идёт ВТОРЫМ, а не последним: если мы вообще
# дошли до DoH, значит upstream dnsmasq не ответил, а это почти всегда «несущая мертва / ещё не
# поднята» — тот самый случай, где путь через туннель заведомо пуст (ГРАБЛЯ №2 выше). Небайндовый
# проход остаётся ТРЕТЬИМ ради зеркального случая: dnsmasq лёг, а туннель жив (или провайдер
# режет прямой путь к 1.1.1.1 — тогда до резолвера дотянется как раз туннель).
# `--connect-timeout 3` держит цену промаха: на заблэкхоленном маршруте отказ приходит за 3 с, а
# не за --max-time 8 ⇒ худший реальный случай функции ~4×3 с против прежних 2×8 с — при вдвое
# большем числе путей общее время НЕ выросло.
# Риск «ISP подменил ответ на домен VPS» осознан и принят: подмена даёт ОТКАЗ, а не утечку —
# ключи/сертификаты не сойдутся (WG-пир аутентифицируется ключом, Reality/TLS — сертификатом),
# несущая честно не встанет и watchdog уйдёт на резерв. Провайдеры травят блок-домены, а не
# произвольные VPS. Если понадобится доверенный резолв — добавлять DoH-first ОТДЕЛЬНОЙ
# функцией для конкретного вызова, а не менять порядок здесь (сломает время failover).
resolve_ipv4() {
    _h="$1"
    # 1) системный резолвер (dnsmasq) — работает, когда его upstream жив.
    # ТАЙМАУТ ОБЯЗАТЕЛЕН (замерено на железе 14.08.2026): «локальный резолвер» отвечает мгновенно,
    # только пока жив его upstream. При «Шифрованном DNS» upstream РОВНО ОДИН — 127.0.0.1#5053, и
    # прокси ходит к резолверу :443 форс-маркой в table 1000, то есть в ту самую несущую, которую мы
    # и поднимаем. Тогда dnsmasq не отвечает НИКАК, а nslookup ждёт свой полный бюджет: замер на
    # мёртвом DNS дал 5 с на КАЖДЫЙ вызов (платит и обратный резолв самого 127.0.0.1). Нас зовут из
    # цикла seed_host_dns до шести раз ⇒ безграничное ожидание здесь и есть та самая «минута».
    # 2 с достаточно: живой dnsmasq отвечает за миллисекунды, а обрезанный промах доберёт DoH-проход
    # через WAN (0 с на замере) — тем же ответом, только быстрее.
    _ip=$(timeout -t "${RESOLVE_NS_TIMEOUT:-2}" nslookup "$_h" 2>/dev/null | awk '/^Name:/{f=1;next} f&&/Address/{x=$NF; if(x ~ /^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$/){print x; exit}}')
    [ -n "$_ip" ] && { echo "$_ip"; return 0; }
    # 2+3) DoH: сперва через WAN, потом как есть — порядок и обоснование внутри doh_ips.
    _ip=$(doh_ips "$_h" "" | head -1)
    [ -n "$_ip" ] && { echo "$_ip"; return 0; }
    return 1
}

# ns_ips <домен> [секунд] — ВСЕ A-записи имени ОТ НАШЕГО dnsmasq, по одной в строке (пусто = имя
# адресов не дало). Пара к doh_ips (те же A-записи, но через DoH) и ЕДИНСТВЕННЫЙ владелец РАЗБОРА
# вывода busybox nslookup: копий было две (domain.sh::dom_ips — прогрев правила, slots.sh::cmd_route —
# «едет ли домен через десинк»), и третья просилась в проверялку «что победит». Разбор нетривиален:
#   • секция ОТВЕТА начинается со строки `Name:` — всё, что выше, это адрес САМОГО СЕРВЕРА;
#   • busybox печатает и «Address 1: IP», и «Address: IP имя» ⇒ `$NF` в одном из форматов отдал бы
#     ИМЯ, поэтому IPv4-токен ищем перебором полей (в busybox-awk нет split()/index()).
# ВОПРОС ЗДЕСЬ ДРУГОЙ, ЧЕМ У resolve_ipv4 (тот добывает адрес сервера несущей ЛЮБЫМ путём и потому
# доберёт DoH): нам нужно ровно то, «что отвечает НАШ резолвер», — и именно этот вызов ЗАОДНО
# наполняет наборы по `ipset=/дом/сет` (`nslookup HOST SERVER` аргумент SERVER игнорирует, см. шапку
# файла, так что ходим всегда в свой dnsmasq). У прогрева это цель, а не побочка; DoH-фолбэк сюда
# добавлять НЕЛЬЗЯ — он вернёт адреса, которых в наборах нет, и мёртвое правило считалось бы живым.
# Второй аргумент — потолок ожидания: пусто = ждём столько, сколько ждёт nslookup (прогреву обрыв
# вреден — оборванный резолв оставляет мёртвое правило), число = `timeout -t` для тех, кто отвечает
# человеку в панели и не может висеть на запертом резолвере.
ns_ips() {
    if [ -n "${2:-}" ]; then timeout -t "$2" nslookup "$1" 2>/dev/null
    else nslookup "$1" 2>/dev/null; fi | awk '/^Name:/{f=1}
        f{for(i=1;i<=NF;i++) if ($i ~ /^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$/) print $i}'
}

# doh_ips <host> [доп-аргументы curl] — ВСЕ A-записи хоста через DoH, по одной в строке; код 1 =
# ни один резолвер не ответил. ПУБЛИЧНЫЙ примитив: кроме resolve_ipv4 (ему нужен один адрес) им
# ходят потребители, которым нужны ВСЕ адреса для `curl --resolve` — lists-lib.sh::_fetch_try и
# iplist-update.sh::fetch_url.
#
# ЗАЧЕМ ОБЩИМ: ГРАБЛЯ №2 (шапка файла) — про ЛЮБОЙ DoH-фолбэк на этом роутере, а не только про
# резолв endpoint'а. Копий цикла было ЧЕТЫРЕ (здесь, notify.sh, lists-lib.sh, iplist-update.sh);
# bind к WAN 01.08.2026 получила ровно одна, а остальные три остались заперты в мёртвую несущую —
# то есть «фолбэк, который не выполняется» размножился ровно так, как и предсказывал разбор.
# Порядок «WAN → как есть» тот же, что у resolve_ipv4: bind нужен, когда несущая мертва (обычный
# случай для фолбэка), небайндовый проход остаётся ради зеркального (dnsmasq лёг, туннель жив, или
# провайдер режет прямой путь к 1.1.1.1).
# $2 НАМЕРЕННО без кавычек — это набор слов («-k», «--max-time 15») либо пустота.
#
# ВТОРОЙ ПРОХОД — ТОЛЬКО КОГДА ПЕРВЫЙ МОЛЧАЛ (замерено на BE7000 14.08.2026). Проход «как есть»
# ходит к тем же 1.1.1.1/8.8.8.8, которые роутер сам заворачивает в туннель (оба лежат в
# iplist_set — проверено `ipset test`), поэтому при мёртвой несущей он не добывает НИЧЕГО, зато
# стоит 3–5 с на каждом промахе: разложение по ступеням дало nslookup 0 с · DoH через WAN 0 с ·
# DoH «как есть» 5 с. Шесть попыток seed_host_dns превращали это в 32 с при ЗДОРОВОМ WAN. Если
# WAN-проход ОТВЕТИЛ (код 2 = «нет такого имени»), ответ уже получен — идти в блэкхол незачем.
# Код 1 (никто не ответил) оставляет прежний путь байт-в-байт: зеркальный случай «dnsmasq лёг,
# туннель жив / провайдер режет прямой путь к 1.1.1.1» по-прежнему лечится вторым проходом.
doh_ips() {
    _dq_h="$1"; _dq_a="$2"
    _dq_w=$(_dnslib_wan)
    if [ -n "$_dq_w" ]; then
        _dq_r=$(_dnslib_doh_all "$_dq_h" "$_dq_a --interface $_dq_w"); _dq_c=$?
        if [ -n "$_dq_r" ]; then echo "$_dq_r"; return 0; fi
        if [ "$_dq_c" = 2 ]; then return 1; fi
    fi
    _dq_r=$(_dnslib_doh_all "$_dq_h" "$_dq_a")
    if [ -n "$_dq_r" ]; then echo "$_dq_r"; return 0; fi
    return 1
}

# WAN-интерфейс = dev дефолта MAIN-таблицы (туннельный дефолт живёт в table 1000 → сюда не
# попадёт). Именно `ip route show default`, а НЕ `ip route get 8.8.8.8`: ответ последнего сам
# искажён тем, что мы чиним (awg-режим ставит `ip route <dns>/32 dev awg0`, 8.8.8.8 ∈ iplist_set).
# Пусто (или дефолт вдруг смотрит в туннель) → вызывающий идёт без bind, как раньше.
# Владелец ответа с 05.09.2026 — ip-lib.sh::wan_iface (тот же дефолт main + тот же гард на свои
# несущие); эта библиотека ip-lib не сорсит, потому шим той же строки — на случай, если у
# вызывающего владельца нет (сорсит ли он ip-lib ПОСЛЕ нас — не важно: его определение победит).
command -v wan_iface >/dev/null 2>&1 || wan_iface() { ip route show default 2>/dev/null | awk '/^default/{d=""; for(i=1;i<=NF;i++) if($i=="dev") d=$(i+1); if(d!="" && d !~ /^(awg|xtun)/){print d; exit}}'; }
_dnslib_wan() { wan_iface; }

# --- ЧЕМ ЭТОМУ curl ДОВЕРЯТЬ — ЕДИНСТВЕННЫЙ ответ на роутер --------------------------------
# ЗАМЕРЕНО на AX3600 15.08.2026: ЛЮБОЙ `curl https://` даёт rc=60 «unable to get local issuer
# certificate», хотя нужный корень (ISRG Root X1 — им подписан и raw.githubusercontent) лежит в
# `/etc/ssl/certs/ca-certificates.crt`, и с `--cacert` на ЭТОТ ЖЕ файл всё проходит. Значит дело
# НЕ в протухшем бандле, а в ПУТИ: curl собран с CApath `/etc/ssl/certs`, а хешированных симлинков
# (`c_rehash`) там нет вовсе — в каталоге ровно один файл-бандл, издателя не найти НИКОГДА.
# Отдаём опцию, которой это лечится БЕЗ отключения проверки. Пусто = системного доверия хватает:
# обычный роутер сюда не заходит и ни одного лишнего запроса не делает.
# Ответ КЭШИРУЕМ на бут — он про РОУТЕР, а не про хост, и меняется только с прошивкой.
# НО КЭШИРУЕМ ТОЛЬКО ОТВЕТ, А НЕ МОЛЧАНИЕ: «ни один бандл не помог» и «никуда не дозвонились» —
# РАЗНЫЕ вещи, а по http_code они одинаковы (000). Зовут нас как раз тогда, когда сеть плохая
# (мёртвый DNS, подъём несущей, бут), и запиши мы «не помогло» после обычной недоступности —
# на роутере, которому фолбэк НУЖЕН, он до самого ребута больше не включится: gh-update снова
# «GitHub недоступен», а DoH-цикл ниже молча проваливается со ступени 2 (проверка сохранена) на
# ступень 3 (`-k`), то есть резолвер перестаёт проверять сертификат — ровно то, от чего лечили.
# Признак НАСТОЯЩЕГО «не помогло» — curl rc=60: до TLS дошли, издателя не нашли. Прочие коды
# (6/7/28 — не резолвится/не коннектится/таймаут) = мы ничего не узнали ⇒ не пишем ничего и
# спросим в следующий раз. Потребители — DoH-цикл ниже и `gh-update.sh`; ВТОРОЙ КОПИИ НЕ
# ЗАВОДИТЬ (следит C26).
CURL_CA_CAP="${CURL_CA_CAP:-/tmp/.enodia-curl-cafile}"
CURL_CA_CANDIDATES="${CURL_CA_CANDIDATES:-/etc/ssl/certs/ca-certificates.crt /etc/ssl/cert.pem /usr/share/ca-certificates/ca-certificates.crt}"
curl_ca_opt() {   # $1 = URL пробы; $2… = доп-аргументы curl (напр. --resolve); без URL — только известный ответ
    if [ -f "$CURL_CA_CAP" ]; then
        [ -s "$CURL_CA_CAP" ] && printf -- '--cacert %s' "$(cat "$CURL_CA_CAP" 2>/dev/null)"
        return 0
    fi
    [ -n "$1" ] || return 0
    _ccu="$1"; shift
    _cc60=0
    # БЮДЖЕТ ЗАМЕРЕН, А НЕ НАЗНАЧЕН (15.08.2026, оба роутера): коннект везде ~0.06 с, а вот ОТВЕТ
    # 1.1.1.1 на AX3600 приходит за 4.5–4.7 с стабильно (известный сталл TLS к части узлов
    # Cloudflare через VPS), 8.8.8.8 и raw.github — за 0.2–0.35 с. С прежними 2/4 проба падала по
    # таймауту (rc=28) ровно на первом резолвере — то есть фолбэк включался ЛОТЕРЕЕЙ, смотря чей
    # URL попался вызывающему. Отсюда 5/10: вдвое выше замеренного худшего.
    # Судим по ЛЮБОМУ валидному HTTP-коду: 400/404 значит, что TLS уже прошёл.
    for _cca in $CURL_CA_CANDIDATES; do
        [ -s "$_cca" ] || continue
        _ccc=$(curl -s -o /dev/null -w '%{http_code}' --cacert "$_cca" --connect-timeout 5 --max-time 10 "$@" "$_ccu" 2>/dev/null)
        _ccr=$?
        case "$_ccc" in
            # rc=60 = «этот бандл не подошёл» ⇒ есть смысл в следующем. ЛЮБАЯ ДРУГАЯ осечка
            # (6/7/28 — не резолвится/не коннектится/таймаут) — про ПУТЬ, а не про бандл: другой
            # файл её не вылечит, а платить за него ещё одним таймаутом на горячем пути незачем.
            ''|000) if [ "$_ccr" = 60 ]; then _cc60=1; else break; fi ;;
            *) printf '%s' "$_cca" > "$CURL_CA_CAP" 2>/dev/null
               printf -- '--cacert %s' "$_cca"; return 0 ;;
        esac
    done
    [ "$_cc60" = 1 ] && : > "$CURL_CA_CAP" 2>/dev/null   # это ОТВЕТ «бандлы не помогают» — помним до ребута
    return 0
}

# _dnslib_doh_all <host> <аргументы curl> — A-записи из DoH-json (по одной в строке), код 1 если
# не вышло. Аргументы вызывающего идут ПОСЛЕ наших таймаутов, чтобы их можно было перебить
# (`--max-time` у закачки списков честно длиннее, чем на горячем пути подъёма несущей).
# JSON DoH (application/dns-json): Answer[].data = адрес для type=A; шаблон `"data":"[0-9.]*"`
# отсекает CNAME и AAAA сам (в них data не числовой). Пайплайн ОБЯЗАН кончаться командой,
# возвращающей 0 (`cut`): под `set -e` присваивание из $() с ненулевым кодом убило бы вызывающего.
# КОД 2 = «резолвер ОТВЕТИЛ, но A-записи нет» — отдельно от кода 1 «никто не ответил». Разница не
# теоретическая: doh_ips на коде 1 обязан пробовать второй проход (без bind'а), а на коде 2 — НЕТ,
# и это ровно та секунда, которую платил каждый промах. Признак ответа — ключ "Status" в теле
# (NOERROR/NXDOMAIN — оба ответы), тело поэтому кладём в переменную, а не гоним сразу в grep.
_dnslib_doh_all() {
    _dda_ans=0
    for _dq in 'https://1.1.1.1/dns-query' 'https://8.8.8.8/resolve'; do
        # `|| true` — не украшение: curl тут ШТАТНО возвращает ненулевой код (28 таймаут, 7 отказ в
        # соединении), а это присваивание из $() и есть та самая последняя команда, о которой речь
        # выше. Без него под `set -e` подоболочка умирала бы на ПЕРВОМ промахе: второй резолвер
        # (8.8.8.8) не пробовался бы вовсе, а наружу уходил бы код curl вместо наших 1/2.
        _dda_b=$(curl -s --connect-timeout 3 --max-time 8 $2 "$_dq?name=$1&type=A" -H 'accept: application/dns-json' 2>/dev/null || true)
        # СТРОГИЙ ПРОХОД НЕ ОТВЕТИЛ — идём ступенями, теряя проверку КАК МОЖНО ПОЗЖЕ.
        # Замерено на AX3600 (ядро 4.4): оба резолвера дают rc=60 «unable to get local issuer
        # certificate», `doh_ips ya.ru` возвращает ПУСТО. Отказывал резолвер ровно там, ради чего
        # заведён (системный DNS мёртв: бут, подъём несущей по имени, закачка списков, notify), и
        # молча — вызывающий видел «имя не резолвится».
        # СТУПЕНЬ 2 — системный бандл явно (`curl_ca_opt`): на таких сборках это чинит ВСЁ, а
        # проверка сертификата СОХРАНЯЕТСЯ. Для резолвера это не косметика: его ответами сидится
        # адрес сервера несущей, и заверять их некому, кроме TLS.
        # СТУПЕНЬ 3 — `-k`, последняя надежда: бывает и по-настоящему негодный бандл, а мёртвый
        # DNS хуже незаверенного (то же fail-open, что и везде в проекте). Раньше эта ступень
        # была ВТОРОЙ, то есть платили проверкой там, где платить не требовалось.
        case "$_dda_b" in
            *'"Status"'*) ;;
            *) _dda_ca=$(curl_ca_opt "$_dq?name=$1&type=A")
               if [ -n "$_dda_ca" ]; then
                   _dda_b=$(curl -s $_dda_ca --connect-timeout 3 --max-time 8 $2 "$_dq?name=$1&type=A" -H 'accept: application/dns-json' 2>/dev/null || true)
               fi
               case "$_dda_b" in
                   *'"Status"'*) ;;
                   *) _dda_b=$(curl -sk --connect-timeout 3 --max-time 8 $2 "$_dq?name=$1&type=A" -H 'accept: application/dns-json' 2>/dev/null || true) ;;
               esac ;;
        esac
        case "$_dda_b" in *'"Status"'*) _dda_ans=1 ;; esac
        _di=$(printf '%s' "$_dda_b" | grep -o '"data":"[0-9.]*"' | cut -d'"' -f4)
        case "$_di" in *.*.*.*) echo "$_di"; return 0 ;; esac
    done
    if [ "$_dda_ans" = 1 ]; then return 2; fi
    return 1
}

# is_ipv4 <строка> — «это уже голый IPv4?» (тогда резолвить нечего).
is_ipv4() { echo "$1" | grep -Eq '^([0-9]{1,3}\.){3}[0-9]{1,3}$'; }

