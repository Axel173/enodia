#!/bin/sh
#
# dns-merge.sh — ЕДИНЫЙ АГРЕГАТОР `ipset=`-строк dnsmasq (и единственная точка рестарта для тех,
# кто эти строки пишет).
#
# ЗАЧЕМ. Правило «домен → набор» у нас пишут ПЯТЬ независимых подсистем, каждая в свой conf:
#   10-groups.conf     — группы и правила устройств (groups.sh)
#   11-geo.conf        — гео-категории (geo.sh)
#   07-zapret-dom.conf — доменный пул десинка (lists-update.sh)
#   enodia-custom.conf    — одиночные правила домена (domain.sh)
#   enodia-domains.conf   — большой список re-filter (установщик/крон)
# А dnsmasq применяет к домену РОВНО ОДНУ строку из всех: сеты разных строк НЕ складываются.
# Значит домен, названный дважды, наполнял бы ОДИН набор, а второе правило было бы видно в
# панели и МЕРТВО. Это не теория: у пользователя ровно так «не работал» ютуб в доп-выходе, если
# тот же домен лежал в гео-категории.
#
# ЧЬЯ СТРОКА ВЫИГРЫВАЕТ (ЗАМЕРЕНО НА ЖЕЛЕЗЕ 03.08.2026, dnsmasq 2.86 — сперва изолированным
# инстансом, потом на живом):
#   1. Длиннее домен — тот и выигрывает: своя строка `m.youtube.com` ОТМЕНЯЕТ `youtube.com`.
#   2. При РАВНОЙ длине выигрывает ПЕРВАЯ прочитанная строка, а не последняя (в коде проекта была
#      записана обратная грабля — из неё следовал бы прямо противоположный вывод).
#   3. КАТАЛОГОВ ДВА, И ЧИТАЮТСЯ ОНИ НЕ ВПЕРЕМЕШКУ: генерённый конфиг стока второй строкой тянет
#      `conf-file=/etc/dnsmasq.conf`, а тот объявляет `conf-dir=/etc/dnsmasq.d` — значит ВЕСЬ /etc
#      читается РАНЬШЕ строки `conf-dir=/tmp/dnsmasq.d`. Внутри каждого каталога — по алфавиту.
#      Проверено прямо: файл `zz-*` из /etc побил файл `00-*` из /tmp.
# Отсюда МЕСТО и ИМЯ нашего файла: `/etc/dnsmasq.d/00-ipset-merge.conf` — первый в первом
# каталоге, значит его строка перебивает все источники. Ошибиться тут дёшево и незаметно: файл
# лежал в /tmp, честно собирался, а dnsmasq молча предпочитал ему /etc/dnsmasq.d/enodia-custom.conf.
# ПОБОЧНЫЙ ВЫВОД, важный сам по себе: одиночные правила домена (enodia-custom.conf в /etc) и сейчас
# бьют группы, гео и пулы (все они в /tmp) — просто потому, что лежат в другом каталоге.
#
# ЧТО ДЕЛАЕМ. Собираем пары «домен→набор» из ВСЕХ conf'ов и пишем в свой файл строки ТОЛЬКО для
# КОНФЛИКТНЫХ доменов — тех, у кого набор не один либо есть правило у РОДИТЕЛЬСКОГО домена:
#   ipset=/youtube.com/grp_vpn_s2,geo_vpn      (оба правила действуют)
#   ipset=/cdn.youtube.com/zapret_dom,grp_vpn_s2   (+ унаследовано от родителя)
# Остальные домены нас не касаются: их обслуживает та подсистема, что и раньше. Поэтому файл
# крошечный (на синтетике 83 тыс. строк источников он вышел в 250 строк), а источники остаются
# авторитетными — мы НЕ становимся вторым владельцем правил, только снимаем взаимное затирание.
#
# ПОЧЕМУ «ЗОНТ», А НЕ ЕДИНЫЙ ГЕНЕРАТОР ВСЕХ СТРОК. Единый генератор пришлось бы звать на каждый
# чих, и он переписывал бы ВЕСЬ пул (у zapret-dom это ~80 тыс. доменов) — секунды на ровном месте
# и новый единый источник отказа. Здесь стоимость — один линейный проход, и она платится только
# тогда, когда что-то реально изменилось (штамп по содержимому пар).
#
# ЧТО ЗНАЧИТ «ОБА ПРАВИЛА ДЕЙСТВУЮТ». Домен попадает в ОБА набора, а кто из них главнее, решают
# цепочки iptables — тот же порядок, что описан в панели лестницей приоритетов (вырез ACCEPT'ом
# обрывает mangle, значит «мимо VPN» перебивает «в VPN»). Это ЧЕСТНЕЕ прежнего: раньше побеждал
# тот, чей файл оказался раньше по алфавиту, — то есть массовый пул бил личное правило человека.
#
# ГРАНИЦА. Мы владеем рестартом dnsmasq только для писателей ipset=-строк (groups/geo/domain/
# lists/zapret/heal). DNS-сеттеры транспортов (`set_*_dns`) рестартят сами — через своего владельца
# doh-lib.sh::dns_upstream_put, и только при смене upstream (или отметке снятого сида): агрегат им не
# нужен, а платить лишним проходом в аварийном failover нельзя.
#
# ГРАБЛЯ ФАЙЛА-ЧЕРНОВИКА: conf-dir `/tmp/dnsmasq.d` объявлен БЕЗ маски `*.conf` ⇒ dnsmasq читает
# в нём ВСЁ. Черновик поэтому пишем ВНЕ каталога (в /tmp) и вносим готовым `mv`.
#
# Использование:
#   dns-merge.sh sync [-f]     — пересобрать агрегат (печатает число строк)
#   dns-merge.sh reload [-f]   — sync + перечитать dnsmasq (это и есть «применить правила доменов»)
#   dns-merge.sh status        — что сейчас склеено (диагностика)
#   dns-merge.sh clear         — снять агрегат (uninstall/deactivate)

ENODIA_DIR=${ENODIA_DIR:-/data/usr/app/enodia}
LIVE=/tmp/dnsmasq.d          # второй conf-dir (RAM); сток копирует сюда /etc при рестарте
ETC=/etc/dnsmasq.d           # ПЕРВЫЙ conf-dir по порядку чтения (см. шапку) — здесь и живёт агрегат
OUT_BASE=00-ipset-merge.conf
OUT="$ETC/$OUT_BASE"
OUT_COPY="$LIVE/$OUT_BASE"   # копия, которую сделает стоковый init: снимаем вместе с оригиналом
# Черновик и пары — С ПИД В ИМЕНИ. Зовут нас ШЕСТЬ независимых мест (groups/geo/domain/lists/
# zapret/heal), общего лока у них нет, и на общих именах два прохода топтали бы файлы друг друга:
# один пишет `aggregate > DRAFT`, второй в этот момент делает `mv DRAFT OUT` — в /etc уезжает
# обрывок, а обрывок ipset=-строки роняет dnsmasq целиком (DNS у нас единая точка отказа).
DRAFT=/tmp/.enodia-dns-merge.draft.$$ # ВНЕ conf-dir: там читается всё подряд, а не только *.conf
PAIRS=/tmp/.enodia-dns-merge.pairs.$$
STAMP=/tmp/.enodia-dns-merge.stamp    # RAM ⇒ после ребута штамп пуст и агрегат пересобирается заново
LOCK=/tmp/.enodia-dns-merge.lock      # КАТАЛОГ (mkdir атомарен), внутри pid — как do_update в lists-lib
DIRTY=/tmp/.enodia-dns-merge.dirty    # «пока ты собирал, состав изменился» — держатель лока идёт на второй круг
TAB=$(printf '\t')

# Источники — В ТОМ ЖЕ ПОРЯДКЕ, В КАКОМ ИХ ЧИТАЕТ dnsmasq (по ИМЕНИ файла): от порядка зависит,
# чья строка выигрывает при равной длине домена, а значит и наш ответ «беднее ли победитель».
# Файл из /etc ПРЕДПОЧТИТЕЛЬНЕЕ одноимённого из /tmp — из-за порядка событий: domain.sh пишет
# правило в /etc и лишь потом рестартит dnsmasq, а копию в /tmp обновляет сам рестарт. Читая
# /tmp, мы собрали бы агрегат по ПРОШЛОМУ состоянию и отстали бы на один шаг.
src_files() {
	# Порядок ИМЕННО такой: сперва весь /etc, потом /tmp (см. шапку — так их читает dnsmasq).
	# Шелл выдаёт результат маски уже отсортированным, значит внутри каталога порядок совпадает.
	for _f in "$ETC"/*.conf; do
		[ -f "$_f" ] || continue
		[ "$(basename "$_f")" = "$OUT_BASE" ] && continue   # свой же файл (иначе агрегат самозаклинится)
		echo "$_f"
	done
	for _f in "$LIVE"/*; do
		[ -f "$_f" ] || continue
		_b=$(basename "$_f")
		[ "$_b" = "$OUT_BASE" ] && continue          # копия нашего файла, сделанная init'ом
		case "$_b" in *.new|*.tmp) continue ;; esac  # чужие черновики
		# Одноимённый файл из /etc уже взят — и он ЖЕ решает: /etc читается раньше, а копия в /tmp
		# к этому моменту может быть устаревшей (её обновляет только рестарт).
		[ -f "$ETC/$_b" ] && continue
		echo "$_f"
	done
}

# Тройки «домен⇥набор⇥номер строки». Строка dnsmasq может нести НЕСКОЛЬКО доменов
# (`ipset=/a.com/b.com/set`) и НЕСКОЛЬКО наборов через запятую — раскладываем и то, и другое.
# НОМЕР СТРОКИ (сквозной, в порядке чтения) нужен, чтобы отличить победителя от проигравших:
# все файлы отдаём ОДНОМУ awk, поэтому счётчик один на всех. Домен — в нижний регистр: dnsmasq
# сравнивает имена без учёта регистра, а у нас ключ обычная строка.
extract_pairs() {
	: > "$PAIRS"
	# xargs не годится (пробелы в путях), а цикл с одним awk на файл сбил бы сквозной счётчик —
	# собираем список аргументов в переменную: имена наших conf'ов без пробелов по построению.
	_args=$(src_files | tr '\n' ' ')
	[ -n "$_args" ] || return 0
	# ПРЕФИЛЬТР: awk с -F/ режет на поля КАЖДУЮ строку, а рядом лежит 11-МБ конф гео-блокировки
	# из одних address=-строк — на нём один этот разбор и съедал почти всю секунду прохода. grep
	# отсеивает файлы без ipset=-строк на порядок дешевле и СОХРАНЯЕТ порядок аргументов
	# (а порядок = чья строка выигрывает).
	_args=$(grep -l '^ipset=/' $_args 2>/dev/null | tr '\n' ' ')
	[ -n "$_args" ] || return 0
	# shellcheck disable=SC2086 # список путей должен разъехаться по аргументам
	awk -F/ -v OFS="$TAB" '
		/^ipset=\// {
			ln++
			s = $NF
			while (1) {
				p = s; sub(/,.*/, "", p)
				if (p != "") for (i = 2; i < NF; i++) if ($i != "") print tolower($i), p, ln
				if (s ~ /,/) sub(/^[^,]*,/, "", s); else break
			}
		}' $_args 2>/dev/null > "$PAIRS"
	sort -u "$PAIRS" > "$PAIRS.s" 2>/dev/null && mv "$PAIRS.s" "$PAIRS"
}

# Агрегация. КРИТЕРИЙ ОДИН: строку пишем, только если ПОБЕДИТЕЛЬ БЕДНЕЕ ОБЪЕДИНЕНИЯ.
# Победитель — та строка, которую применит dnsmasq: у домена со своей строкой это его ПЕРВАЯ по
# порядку чтения (длина домена у своих строк одинакова). Объединение — все наборы этого домена
# + наборы РОДИТЕЛЬСКИХ доменов (своя строка отменяет родительскую, значит родительский набор
# надо внести явно).
# ПОЧЕМУ НЕ «домен назван дважды»: groups.sh склеивает наборы ВНУТРИ своего файла сам, и такой
# домен уже обслужен — писать его сюда значило бы плодить строки-дубли и врать детектору
# конфликтов в панели. Разница именно в потере, а не в повторе.
# ПРАВИЛО-ПЕРЕХВАТЧИК `ipset=/#/набор` (в dnsmasq «любой домен») СОЗНАТЕЛЬНО ИГНОРИРУЕМ: честное
# объединение потребовало бы дописать этот набор КАЖДОМУ домену, то есть переписать весь пул
# (на 80 тыс. доменов это агрегат размером с сам пул — лекарство хуже болезни). Наши подсистемы
# такого правила не пишут; если его завёл человек руками — оно работает ровно как в dnsmasq.
# Ни split(), ни index(), ни своих функций: на роутерах со старым busybox их может не быть.
aggregate() {
	awk -F"$TAB" '
		$1 == "#" { next }
		{
			d = $1; t = $2; n = $3 + 0
			if (!(d in first) || n < first[d]) first[d] = n
			if (!((d SUBSEP t) in have)) { have[d SUBSEP t] = 1; nset[d]++; sets[d] = sets[d] "," t }
			# сколько наборов несёт КОНКРЕТНАЯ строка n (дедуп не нужен: тройки уже sort -u)
			lcnt[d SUBSEP n]++
		}
		END {
			for (d in first) {
				# наборы предков, которых нет у самого домена
				extra = ""; nex = 0; p = d
				while (sub(/^[^.]+\./, "", p)) {
					if (p in first) {
						s = sets[p]
						while (sub(/^,/, "", s)) {
							t = s; sub(/,.*/, "", t)
							if (!((d SUBSEP t) in have)) { have[d SUBSEP t] = 1; extra = extra "," t; nex++ }
							if (s ~ /,/) sub(/^[^,]*/, "", s); else s = ""
						}
					}
				}
				# победитель применит lcnt[d,first] наборов, а действовать должны nset+nex
				if (nset[d] + nex > lcnt[d SUBSEP first[d]]) {
					out = ""; s = sets[d] extra
					while (sub(/^,/, "", s)) {
						t = s; sub(/,.*/, "", t)
						out = (out == "" ? t : out "," t)
						if (s ~ /,/) sub(/^[^,]*/, "", s); else s = ""
					}
					if (out != "") print "ipset=/" d "/" out
				}
			}
		}' "$PAIRS" 2>/dev/null | sort
}

# Лок — КАТАЛОГ (mkdir атомарен; тот же приём, что у do_update в lists-lib.sh). Ждём КОРОТКО:
# вызывающему нужен не столько наш агрегат, сколько РЕСТАРТ dnsmasq под его собственную правку,
# и вешать его на минуты нельзя. Не дождались — молча уходим: заявка `DIRTY` уже стоит, держатель
# лока увидит её и пересоберёт за нас, а рестарт вызывающий получит своим чередом.
# Протухший лок (процесс убит, каталог остался) снимаем по отсутствию /proc/<pid> — иначе одна
# смерть заперла бы склейку до перезагрузки. Снимать ТОЛЬКО `rm -rf`: внутри pid-файл.
lock_take() {
	_i=0; _empty=0
	while [ "$_i" -lt 15 ]; do
		if mkdir "$LOCK" 2>/dev/null; then printf '%s' "$$" > "$LOCK/pid" 2>/dev/null; return 0; fi
		_p=$(cat "$LOCK/pid" 2>/dev/null)
		case "$_p" in
			# Пустой pid — ЕЩЁ НЕ ПРОТУХШИЙ лок: между `mkdir` и записью pid у держателя есть
			# окно, и «снять и занять» в этот момент дало бы ДВУХ писателей — то самое, от чего
			# лок и заведён. Ждём подтверждения: пусто три тика подряд = держателя действительно нет.
			''|*[!0-9]*) _empty=$((_empty + 1)); [ "$_empty" -ge 3 ] && rm -rf "$LOCK" 2>/dev/null ;;
			*) _empty=0; [ -d "/proc/$_p" ] || rm -rf "$LOCK" 2>/dev/null ;;
		esac
		_i=$((_i + 1)); sleep 1
	done
	return 1
}
lock_drop() { rm -rf "$LOCK" 2>/dev/null; }

# Штамп — по СОДЕРЖИМОМУ пар, а не по mtime: `ls -l` на busybox даёт минуты, и правка внутри
# одной минуты с тем же размером прошла бы незамеченной, а протухший агрегат ХУЖЕ отсутствующего
# (он перебивает источники). Дешёвый шаг (извлечение пар) платим всегда, дорогой (агрегацию) —
# только когда пары изменились. `-f` форсит пересборку.
sync_pass() {
	mkdir -p "$ETC" "$LIVE" 2>/dev/null
	extract_pairs
	_new=$(md5sum "$PAIRS" 2>/dev/null | cut -d' ' -f1)
	# Штамп читаем ЗДЕСЬ, а не при загрузке: на втором круге (dirty) он уже наш собственный.
	_old=$(cat "$STAMP" 2>/dev/null)
	# Штамп пишется ТОЛЬКО после удачной сборки ⇒ совпал = агрегат соответствует источникам,
	# в том числе когда конфликтов нет и файла нет вовсе.
	[ "$1" != "-f" ] && [ -n "$_new" ] && [ "$_new" = "$_old" ] && return 0
	aggregate > "$DRAFT"
	# Копию в /tmp снимаем ВСЕГДА: её делает стоковый init (копирует /etc→/tmp аддитивно и без
	# чистки), и пережившая правку старая копия продолжала бы наполнять снятые наборы — ровно та
	# грабля «две копии сниппета», на которой уже ловились adblock и zapret. Оригинал в /etc
	# читается раньше, поэтому отсутствие копии ничего не ломает: рестарт её и восстановит.
	rm -f "$OUT_COPY" 2>/dev/null
	if [ -s "$DRAFT" ]; then
		# `mv` из /tmp в /etc — это РАЗНЫЕ ФС (замерено на BE7000: /etc своя ramfs, /tmp tmpfs),
		# то есть копирование с последующим unlink, а НЕ атомарный rename: dnsmasq, перечитанный
		# в этот момент чужим вызовом, прочитал бы файл наполовину. Поэтому промежуточная ступень
		# лежит В САМОМ /etc и с именем МИМО маски conf-dir (`conf-dir=/etc/dnsmasq.d,*.conf` —
		# хвост `.tmp` демон не подхватит), а rename внутри одной ФС уже атомарен.
		if cp "$DRAFT" "$OUT.tmp" 2>/dev/null && mv "$OUT.tmp" "$OUT" 2>/dev/null; then _ok=0; else _ok=1; fi
		rm -f "$DRAFT" "$OUT.tmp" 2>/dev/null
	else
		# Конфликтов нет — файла быть не должно: пустой перехватчик только путал бы диагностику.
		rm -f "$DRAFT" "$OUT" 2>/dev/null
		_ok=0
	fi
	# ШТАМП — ТОЛЬКО после УДАЧНОЙ выкладки. `/etc` — ramfs, и её переполнение вполне реально: при
	# провале `cp`/`mv` штамп означал бы «агрегат соответствует источникам», следующий проход ушёл бы
	# в ветку «ничего не менялось», и протухшая склейка (по нашему же определению — хуже отсутствующей,
	# она перебивает источники) залипла бы до следующей смены пар.
	[ "$_ok" = 0 ] || { echo "[dns-merge] не удалось выложить $OUT (нет места в /etc?) — штамп не пишу, повторю на следующем вызове" >&2; return 1; }
	printf '%s' "$_new" > "$STAMP" 2>/dev/null
	return 0
}

# Заявка + лок + цикл по dirty (калька do_apply в geo.sh): держатель, начавший проход ДО нашей
# правки, её бы не увидел — поэтому заявку ставим ДО взятия лока, а внутри снимаем её ПЕРЕД
# чтением источников. Так «пропустить чужое изменение» становится невозможно.
do_sync() {
	: > "$DIRTY" 2>/dev/null
	lock_take || return 0
	trap 'rm -f "$PAIRS" "$DRAFT" 2>/dev/null; lock_drop' EXIT
	trap 'exit 1' INT TERM HUP PIPE
	while :; do
		rm -f "$DIRTY" 2>/dev/null
		sync_pass "$1"
		[ -f "$DIRTY" ] || break
	done
	trap - EXIT INT TERM HUP PIPE
	rm -f "$PAIRS" "$DRAFT" 2>/dev/null
	lock_drop
}
out_count() { _c=$(grep -c '^ipset=/' "$OUT" 2>/dev/null); case "$_c" in ''|*[!0-9]*) _c=0 ;; esac; printf '%s' "$_c"; }

# Конфиг, с которым РЕАЛЬНО запущен демон (`-C` в его cmdline): только он тянет ОБА conf-dir, и
# только на нём видны межфайловые конфликты. Демон не бежит (бут) — берём стоковый путь: проверка
# выйдет беднее (виден лишь /etc/dnsmasq.d), но это лучше, чем никакой.
dns_cfg_real() {
	for _dp in /proc/[0-9]*; do
		case "$(tr '\0' ' ' 2>/dev/null < "$_dp/cmdline")" in
			*dnsmasq*-C\ *)
				_dc=$(tr '\0' '\n' 2>/dev/null < "$_dp/cmdline" | awk '$0=="-C"{f=1;next} f{print;exit}')
				[ -f "$_dc" ] && { printf '%s' "$_dc"; return 0; } ;;
		esac
	done
	printf '/etc/dnsmasq.conf'
}

# Судим ПО ВЫВОДУ, а не по коду возврата: у dnsmasq есть классы, где он печатает «syntax check OK»
# и возвращает 0 на заведомо негодном значении (ЗАМЕРЕНО 15.08.2026 на BE7000 и AX3600: так ведут
# себя дубль MAC и битый IP в `dhcp-host`). Проверить нечем (нет бинаря) ⇒ не блокируем.
dns_cfg_ok() {
	[ -x /usr/sbin/dnsmasq ] || return 0
	_dt=$(/usr/sbin/dnsmasq --test -C "$(dns_cfg_real)" 2>&1)
	case "$_dt" in
		*"syntax check OK"*) return 0 ;;
		"") return 0 ;;
	esac
	printf '%s' "$_dt" | tail -2 >&2
	return 1
}

# «Демон жив» ≠ «резолвит» (общий закон проекта). Спрашиваем имя, которое dnsmasq отдаёт из своих
# же данных и которому не нужен аплинк.
dns_resolves() {
	pidof dnsmasq >/dev/null 2>&1 || return 1
	nslookup localhost 2>/dev/null | grep -q '^Address'
}

# Рестарт, а не SIGHUP: ipset=-строки dnsmasq по HUP не перечитывает (та же грабля, что с
# address=). Была скопирована в пяти файлах — теперь живёт здесь одна.
#
# ГАРД (15.08.2026). Мы — единственная точка рестарта для ШЕСТИ подсистем, а DNS у нас единая точка
# отказа всей сети: демон, не поднявшийся из-за одной битой строки, оставляет дом без резолва до
# похода по SSH. Замерено: `address=` со значением вроде `deadbeef` валит старт, и такая строка
# приезжала из панели без единой проверки (см. dns-hosts.sh). Отсюда три правила:
#   1. спрашиваем демона о ЦЕЛОМ конфиге ДО рестарта — живой демон со слегка устаревшими правилами
#      лучше мёртвого;
#   2. если демон БЫЛ жив, а после рестарта резолва нет — снимаем СВОЙ агрегат (единственное, чем
#      владеем) и поднимаем обратно. Гард «был жив» ОБЯЗАТЕЛЕН: на буте нас зовёт heal.sh, когда
#      демона ещё нет, и без него мы сносили бы агрегат на КАЖДОЙ загрузке;
#   3. **возвращаем 0 всегда, когда решение принято НАМИ** — включая осознанный отказ перезапускать.
#      Это не косметика: ВСЕ ДЕСЯТЬ вызывающих написаны как `dns-merge.sh reload || /etc/init.d/
#      dnsmasq restart`, и ненулевой код заставил бы каждого немедленно сделать голый рестарт в тот
#      самый битый конфиг — гард оказался бы ХУЖЕ своего отсутствия. Ненулевой код у нас значит
#      ровно «меня нет/не смог запуститься», для чего фолбэк и заводился.
dns_restart() {
	_dwas=0; pidof dnsmasq >/dev/null 2>&1 && _dwas=1
	if ! dns_cfg_ok; then
		echo "[dns-merge] dnsmasq забраковал итоговый конфиг — рестарт ПРОПУЩЕН (живой демон важнее свежих правил)" >&2
		return 0
	fi
	/etc/init.d/dnsmasq restart >/dev/null 2>&1 || killall -HUP dnsmasq 2>/dev/null
	[ "$_dwas" = 1 ] || return 0
	_dwk=0
	while [ "$_dwk" -lt 8 ]; do
		dns_resolves && return 0
		_dwk=$((_dwk + 1)); sleep 1
	done
	echo "[dns-merge] после рестарта DNS не резолвит — снимаю свой агрегат и поднимаю демона обратно" >&2
	rm -f "$OUT" "$OUT_COPY" 2>/dev/null
	/etc/init.d/dnsmasq restart >/dev/null 2>&1
	return 0
}

case "$1" in
	sync)
		do_sync "$2"
		printf '[dns-merge] склеено доменов: %s\n' "$(out_count)"
		;;
	reload)
		# ПОРЯДОК ВАЖЕН: сперва агрегат, потом рестарт — dnsmasq читает конфиги на старте, и
		# обратный порядок означал бы, что свежая склейка доедет только со следующим рестартом.
		do_sync "$2"
		dns_restart
		;;
	status)
		_n=$(out_count)
		printf 'агрегат: %s (доменов: %s)\n' "$OUT" "$_n"
		[ "$_n" = 0 ] || head -20 "$OUT"
		printf 'источники:\n'
		src_files | while read -r _f; do
			_c=$(grep -c '^ipset=/' "$_f" 2>/dev/null); case "$_c" in ''|*[!0-9]*) _c=0 ;; esac
			[ "$_c" = 0 ] || printf '  %s\t%s\n' "$_c" "$_f"
		done
		;;
	clear)
		# Маской, а не поимённо: черновики/пары носят ПИД в имени, а лок — каталог (`rm -rf`).
		rm -f "$OUT" "$OUT_COPY" "$STAMP" /tmp/.enodia-dns-merge.pairs.* /tmp/.enodia-dns-merge.draft.* "$DIRTY" 2>/dev/null
		rm -rf "$LOCK" 2>/dev/null
		printf '[dns-merge] агрегат снят\n'
		;;
	*)
		cat <<EOF
dns-merge.sh — склейка ipset=-правил доменов из всех подсистем.

  dns-merge.sh sync [-f]    пересобрать агрегат ($OUT)
  dns-merge.sh reload [-f]  пересобрать + перечитать dnsmasq
  dns-merge.sh status       что сейчас склеено и из каких файлов
  dns-merge.sh clear        снять агрегат
EOF
		;;
esac
