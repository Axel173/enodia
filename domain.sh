#!/bin/sh
#
# domain.sh — ПРАВИЛО МАРШРУТА для отдельного домена: в туннель, мимо туннеля или никак.
#
# Использование:
#   domain.sh add <домен>       — домен идёт В VPN (туннель)
#   domain.sh add-many          — ПАЧКА доменов «в VPN» из stdin, ОДНО применение (печатает число)
#   domain.sh bypass <домен>    — домен идёт МИМО VPN (напрямую), перебивая общий список
#   domain.sh remove <домен>    — СНЯТЬ правило: домен снова «как все» (общий список/напрямую)
#   domain.sh list              — показать пользовательские правила
#   domain.sh search <строка>   — найти, есть ли строка в любом списке
#   domain.sh apply             — пересобрать сеты/правила из конфига (boot, heal.sh)
#   domain.sh restore           — вернуть живой enodia-custom.conf из персиста на /data (boot, импорт)
#   domain.sh warm              — прогреть наборы резолвом (boot ПОСЛЕ рестарта dnsmasq, свип сторожа)
#   domain.sh reload            — перечитать все списки (после ручной правки)
#
# ТРИ СОСТОЯНИЯ, ОДНА СТРОКА. У домена ровно одна строка в enodia-custom.conf, и её ipset решает
# направление; нет строки = НЕТ правила (домен едет как обычный трафик — по общему CIDR-списку
# или напрямую). Поэтому `remove` — это честный откат «в исходную точку», а не третий режим:
#   ipset=/дом/enodia_list    → в VPN    (сет метит mark-core.sh → MARK 0x1 → table 1000)
#   ipset=/дом/enodia_bypass  → мимо VPN (сет = ACCEPT в цепочке VPN_EXCLUDE, apply-bypass.sh)
#   (строки нет)           → правила нет
# add/bypass СНАЧАЛА снимают прежнюю строку домена → смена направления, а не два правила разом.
#
# ПОЧЕМУ «мимо VPN» ЧЕРЕЗ dnsmasq, А НЕ СНИМКОМ РЕЗОЛВА. Прежняя кнопка панели «→ мимо VPN»
# резолвила домен ОДИН РАЗ и клала полученные A-записи в плоский .bypass-dst. Это фотография:
# CDN крутит адреса — снимок протухает, новые IP снова уезжают в туннель, а отменить «по домену»
# было нечем (в списке лежали безымянные IP). Пишем `ipset=/дом/enodia_bypass` — dnsmasq САМ кладёт
# в сет каждый свежерезолвленный адрес. Это динамика и это симметрично «в VPN» (тот же файл, тот
# же персист, та же отмена). Ровно та же логика, что у доменов-членов групп (groups.sh).
#
# ГРАБЛИ:
#  - ПЕРЕСБОРКА сета стирает IP, которые dnsmasq туда уже положил → после любого флаша ПРОГРЕВАЕМ
#    резолвом (warm), иначе домен поедет не туда, пока клиент не перерезолвит (с DoH/кэшем — может
#    и никогда). Та же грабля ловилась на add (флаш enodia_list без прогрева).
#  - enodia_bypass — сет с ОДНИМ хозяином (этот скрипт), поэтому его можно честно пересобирать с нуля
#    (flush+warm) на каждое изменение. enodia_list — ОБЩИЙ с re-filter, его флашим только на remove
#    (стухшие IP снятого домена висеть не должны) и сразу прогреваем свои домены обратно.
#  - NSS/ECM-offload держит УЖЕ установленные соединения на старом маршруте до таймаута → без
#    conntrack -F смена направления «не применяется», пока сайт не отвиснет сам.
#
# Где живут списки:
#   /etc/dnsmasq.d/enodia-domains.conf  — большой список re-filter (обновляется
#                                        автоматически кроном, не трогать!)
#   /etc/dnsmasq.d/enodia-custom.conf   — твой ручной список (этим файлом
#                                        управляет этот скрипт)
#
# Версия 2.0 / июль 2026 (1.0 — май 2026, только «в туннель»)

DNSMASQ_DIR="/etc/dnsmasq.d"
CUSTOM_FILE="$DNSMASQ_DIR/enodia-custom.conf"
MAIN_FILE="$DNSMASQ_DIR/enodia-domains.conf"
IPSET_NAME="enodia_list"
BYPASS_SET="enodia_bypass"

# ПЕРСИСТ на /data. КРИТИЧНО: /etc = ramfs → enodia-custom.conf стирается на КАЖДОМ ребуте,
# а восстанавливать было нечем (юзер: «очистился список, который я вчера добавлял»). Держим
# зеркало на /data (переживает ребут) — heal.sh кладёт его обратно в /etc на буте (секция 2b).
# Окружение ПЕРВЕЕ собственного каталога: запускатель (boot.sh) экспортирует пути, когда код
# живёт на внешнем накопителе, и спорить с ним скрипту не о чем. Нет окружения — прежнее
# поведение: каталог, из которого нас запустили, иначе литерал.
if [ -z "$ENODIA_DIR" ]; then
    ENODIA_DIR=$(cd "$(dirname "$0")" 2>/dev/null && pwd); [ -d "$ENODIA_DIR" ] || ENODIA_DIR=/data/usr/app/enodia   # flash-lit: последний фолбэк, когда и $0 не дал каталога
fi
ENODIA_STATE=${ENODIA_STATE:-/data/usr/app/enodia-state}
# Сброс УЖЕ УСТАНОВЛЕННЫХ соединений — только через ct-lib.sh: на ядре 4.4 (AX3600/BE3600)
# утилиты conntrack в прошивке НЕТ ВООБЩЕ, и прежний `conntrack -F || true` был тихим no-op —
# правило стояло, а поток шёл по-старому через NSS/ECM. Шим = прежнее поведение (частичный
# apply-scripts не должен падать), полноценный сброс живёт в самой библиотеке.
if [ -f "$ENODIA_DIR/ct-lib.sh" ]; then . "$ENODIA_DIR/ct-lib.sh"; fi
command -v ct_flush >/dev/null 2>&1 || ct_flush()      { conntrack -F >/dev/null 2>&1 || true; }

# Общий слой пересборки наборов (set-lib.sh): у enodia_bypass ЕДИНСТВЕННЫЙ источник — dnsmasq, и
# прежний безусловный flush на каждую правку ЛЮБОГО домена ронял уже накопленные адреса СОСЕДЕЙ
# (прогрев возвращает лишь то, у чего есть A-запись, — у апексов CDN её нет). Сорсим только под
# `[ -f ]`: провалившийся `.` в ash фатален. Нет файла → шим = прежнее поведение (flush+прогрев).
if [ -f "$ENODIA_DIR/set-lib.sh" ]; then . "$ENODIA_DIR/set-lib.sh"; fi
if ! command -v set_sync >/dev/null 2>&1; then
	set_sync() { ipset flush "$1" 2>/dev/null; }
fi

# Проверка ДОМЕНА (dns-lib.sh::dom_ok, там же замер): метка длиннее 63 символов роняет ВЕСЬ конфиг
# dnsmasq, а строка к тому моменту уже лежит и в живом conf-dir, и в персисте ⇒ сеть остаётся без
# DNS на ближайшем ребуте, при живом роутере и зелёной панели. Шим ОБЯЗАН повторять правило, а не
# «прежнее поведение»: прежнее поведение и есть баг (как у clock-lib).
if [ -f "$ENODIA_DIR/dns-lib.sh" ]; then . "$ENODIA_DIR/dns-lib.sh"; fi
if ! command -v dom_ok >/dev/null 2>&1; then
	dom_ok() { [ -n "$1" ] && [ "${#1}" -le 253 ] || return 1
	           printf '%s' "$1" | grep -qE '^[A-Za-z0-9_-]{1,63}(\.[A-Za-z0-9_-]{1,63})*$'; }
fi
PERSIST_FILE="$ENODIA_STATE/.enodia-custom.conf"
persist_save() { cp "$CUSTOM_FILE" "$PERSIST_FILE" 2>/dev/null; }

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

mkdir -p "$DNSMASQ_DIR"
[ ! -f "$CUSTOM_FILE" ] && {
    echo "# Пользовательские домены, идущие через AWG-туннель." > "$CUSTOM_FILE"
    echo "# Управляется через domain.sh. Можно редактировать руками." >> "$CUSTOM_FILE"
    echo "" >> "$CUSTOM_FILE"
}

reload_dnsmasq() {
    # $1=flush → дополнительно сбросить ipset enodia_list. Нужно только при УДАЛЕНИИ домена
    # (стухшие IP убранного домена не должны висеть). При ДОБАВЛЕНИИ НЕ флашим:
    # enodia_list — ОБЩИЙ ipset и для re-filter, и для кастомных доменов. Глобальный flush
    # на каждое добавление стирал уже резолвленные IP ВСЕХ доменов → трафик к ним уходил
    # НАПРЯМУЮ (мимо VPN), пока клиент не перерезолвит — а с DoH/кэшем на клиенте вообще
    # никогда. Именно поэтому свежедобавленный домен «не шёл через VPN». (Железо 2026-07-14.)
    # Рестарт, а не SIGHUP: ipset=-строки dnsmasq по HUP не перечитывает. Идём через агрегатор
    # (dns-merge.sh): один и тот же домен может быть назван и здесь, и в группе/гео/пуле десинка,
    # а dnsmasq применяет к домену РОВНО ОДНУ строку — без склейки чьё-то правило молча умирает
    # (и наше личное проигрывало бы массовому пулу: его файл читается раньше по алфавиту).
    # Агрегатора нет → прежний путь байт-в-байт.
    sh "$ENODIA_DIR/dns-merge.sh" reload 2>/dev/null \
        || /etc/init.d/dnsmasq restart >/dev/null 2>&1 || killall -HUP dnsmasq 2>/dev/null
    [ "$1" = flush ] && ipset flush "$IPSET_NAME" 2>/dev/null
}

# Сеты должны СУЩЕСТВОВАТЬ до рестарта dnsmasq: на несуществующий сет ipset=-правило молча не
# сработает (адреса никуда не лягут). enodia_list создаёт установщик/mark-core, enodia_bypass — наш,
# поэтому создаём оба (идемпотентно). hash:net — сеты держат и одиночные адреса, и подсети.
#
# ПОТОЛОК enodia_list ОБЯЗАН СОВПАДАТЬ с heal.sh и установщиком (maxelem 1000000), и это не
# косметика. `ipset create` идемпотентен по СУЩЕСТВОВАНИЮ набора ⇒ параметры задаёт тот, кто
# создал ПЕРВЫМ, а на буте первыми оказываемся мы: heal зовёт `domain.sh apply` РАНЬШЕ, чем сам
# доходит до `ipset create enodia_list`. Со прежним maxelem=65536 набор, ОБЩИЙ с массовым re-filter,
# получал потолок в 15 раз ниже задуманного — а упёршись в него, dnsmasq МОЛЧА перестаёт класть
# новые адреса: доменные правила умирают разом у ВСЕХ устройств, при живом правиле по IP (у того
# свой набор). Расхождение параметров у двух создателей одного набора = мина, а не деталь.
ensure_sets() {
    ipset list -n 2>/dev/null | grep -qx "$IPSET_NAME" || \
        ipset create "$IPSET_NAME" hash:net family inet hashsize 1024 maxelem 1000000 2>/dev/null
    # enodia_bypass наполняем ТОЛЬКО мы (правила пользователя) ⇒ 65536 хватает с запасом. Менять
    # нельзя ещё и потому, что set-lib.sh создаёт набор-двойник под `ipset swap` с ЭТИМ потолком.
    ipset list -n 2>/dev/null | grep -qx "$BYPASS_SET" || \
        ipset create "$BYPASS_SET" hash:net hashsize 1024 maxelem 65536 2>/dev/null
}

# Домены наших правил: dom_list [сет] — все, либо только едущие в указанный сет.
dom_list() {
    [ -f "$CUSTOM_FILE" ] || return 0
    if [ -n "$1" ]; then sed -n "s|^ipset=/\([^/]*\)/$1\$|\1|p" "$CUSTOM_FILE" 2>/dev/null
    else sed -n 's|^ipset=/\([^/]*\)/.*|\1|p' "$CUSTOM_FILE" 2>/dev/null; fi
}

# ПРОГРЕВ: nslookup бьёт в свой же dnsmasq → тот резолвит и СРАЗУ кладёт адреса в нужный сет по
# ipset=-правилу. Без прогрева правило начинает действовать только со следующего запроса клиента
# (а клиент с DoH/кэшем может не спросить никогда). Доменов у пользователя единицы — форки терпим.
#
# ПОЧЕМУ ПРОГРЕВ ОБЯЗАН БЫТЬ ЧЕСТНЫМ. Здесь стоял ОДИН заход `nslookup … || true`: сразу за
# ПОЛНЫМ рестартом dnsmasq и без проверки результата. На роутере с крупными списками демон
# поднимается секунды — резолв бил в ещё не слушающий :53, `|| true` промах глушил, и панель
# рапортовала успех о правиле, которого в ядре нет. Обычно это сходит с рук: следующий же запрос
# КЛИЕНТА наполняет набор. Но если клиенты спрашивают НЕ наш dnsmasq (свой AdGuard Home на NAS,
# DoH в браузере, DNS вписан руками), второго наполнителя у набора НЕТ — и правило остаётся
# мёртвым навсегда, на ВСЕХ устройствах разом, при живом правиле по IP. Ровно эту грабку уже
# лечили в heal.sh (5.16: пауза + прогрев после подъёма транспорта), здесь она оставалась.
# Поэтому: ждём демона, повторяем и судим по ФАКТУ В ЯДРЕ, а не по коду возврата nslookup.

# Демон снова отвечает? Спрашиваем localhost: его dnsmasq отдаёт из /etc/hosts, upstream для
# этого не нужен ⇒ проба меряет РОВНО «демон поднялся», а не здоровье туннеля. Возвращаемся сразу
# по первому успеху, поэтому в штатном случае это ~секунда, а не потолок.
dns_up() {
    _du=0
    while [ "$_du" -lt 10 ]; do
        nslookup localhost >/dev/null 2>&1 && return 0
        _du=$((_du + 1)); sleep 1
    done
    return 1
}

# A-записи домена спрашивает dns-lib.sh::ns_ips — ЕДИНСТВЕННЫЙ владелец разбора вывода busybox
# nslookup (тот же вопрос задают slots.sh::cmd_route и проверялка «что победит» в devwatch.sh; три
# копии разъехались бы на первом же новом формате вывода). ПОТОЛКА ОЖИДАНИЯ ТУТ НЕТ СОЗНАТЕЛЬНО:
# оборванный резолв оставил бы правило мёртвым, а прогрев ради этого и существует.
# Шим — прежний путь байт-в-байт, на случай частично доехавшего apply-scripts.
if ! command -v ns_ips >/dev/null 2>&1; then
    ns_ips() {
        nslookup "$1" 2>/dev/null | awk '/^Name:/{f=1}
            f{for(i=1;i<=NF;i++) if ($i ~ /^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$/) print $i}'
    }
fi

# Набор упёрся в потолок? Это самая тихая из причин промаха: dnsmasq просто перестаёт добавлять.
# `ipset list -t` печатает ТОЛЬКО заголовок — полный `list` на десятках тысяч записей стоит секунд.
set_full() {
    ipset list -t "$1" 2>/dev/null | awk '
        /^Number of entries:/{n=$NF}
        /maxelem/{for(i=1;i<=NF;i++) if ($i=="maxelem") m=$(i+1)}
        END{if (m!="" && n!="" && n+0 >= m+0) exit 0; exit 1}'
}

# Прогреть ОДИН домен. Коды: 0 = адрес лёг в набор · 1 = резолв ЕСТЬ, а в наборе адреса нет (вот
# это авария) · 2 = у домена нет A-записи (штатно: апексы CDN живут на AAAA/CNAME, класть нечего).
# Один nslookup служит обеим целям сразу: он же заставляет dnsmasq наполнить набор, он же отдаёт
# нам адреса для проверки.
#
# Повтор с паузой делаем ТОЛЬКО в одном случае: адреса пришли, а в наборе их нет — это настоящая
# гонка, и вторая попытка её лечит. Если резолв не дал НИ ОДНОГО адреса, повторять бессмысленно:
# так выглядит апекс без A-записи, и секунда сна на каждый такой домен превращала бы `add-many`
# из тридцати доменов в полминуты ожидания у CGI панели, а свип сторожа — в задержку тика.
# WARM_TRIES=1 убирает и этот единственный повтор: им ходит периодический свип, которому нужно
# лишь освежить адреса, а не дождаться только что стартовавшего демона.
warm_one() {
    _wo_s="$1"; _wo_d="$2"; _wo_t=0
    while :; do
        _wo_any=0
        for _wo_ip in $(ns_ips "$_wo_d"); do
            _wo_any=1
            ipset test "$_wo_s" "$_wo_ip" >/dev/null 2>&1 && return 0
        done
        [ "$_wo_any" = 1 ] || return 2          # A-записи нет — класть в набор нечего, это штатно
        _wo_t=$((_wo_t + 1))
        [ "$_wo_t" -ge "${WARM_TRIES:-2}" ] && return 1
        sleep 1
    done
}

# Прогреть весь набор. Печатаем ТОЛЬКО когда есть настоящий промах — тишина в штатном случае.
warm() {
    _w_s="$1"; _w_miss=0
    for _w_d in $(dom_list "$_w_s"); do
        warm_one "$_w_s" "$_w_d"
        case $? in 1) _w_miss=$((_w_miss + 1)) ;; esac
    done
    [ "$_w_miss" = 0 ] && return 0
    printf "${YELLOW}[ ! ] %s: доменов с резолвом, но без адреса в наборе — %s.${NC}\n" "$_w_s" "$_w_miss"
    if set_full "$_w_s"; then
        printf "${RED}      Набор %s ПЕРЕПОЛНЕН — dnsmasq больше не добавляет в него адреса.${NC}\n" "$_w_s"
    else
        printf "${YELLOW}      Обычная причина: домен заявлен ещё где-то (группа/гео/пул), а dnsmasq${NC}\n"
        printf "${YELLOW}      кладёт адрес РОВНО В ОДИН набор на домен.${NC}\n"
    fi
    return 1
}

# --- ПРОГРЕВ ЧУЖИХ НАБОРОВ ПРАВИЛ (группы, гео, слоты) --------------------------------
# Прогрева у них не было НИ У КОГО: ни heal, ни свип сторожа сюда не заглядывали — грелись только
# `enodia_list`/`enodia_bypass`. А наполняет их ТОТ ЖЕ dnsmasq по тем же `ipset=`-строкам, значит и
# мертвы они ровно так же: в сети со СВОИМ резолвером (AdGuard на NAS, DoH на клиентах) второго
# наполнителя набора не существует, и доменные члены группы не работают НИКОГДА, при живом
# правиле по IP. Замерено у владельца: `grp_vpn_s2` = 162 адреса, но положил их резолв ЕГО
# клиентов — у того, чьи клиенты ходят мимо роутера, там ноль.
#
# ГРЕЕМ ТОЛЬКО ПУСТЫЕ НАБОРЫ, и это главное решение. Непустой набор = dnsmasq в него кладёт,
# греть нечего; а гнать nslookup по гео-категории в тысячи доменов на КАЖДОМ тике сторожа —
# дороже любой пользы. Отсюда же кап: пустая гео-категория (158к доменов у владельца!) не должна
# съесть тик целиком. Кап честный — что не влезло, доедет резолвом клиентов.
#
# ИСТОЧНИК — сами `ipset=`-строки живых conf, а не внутренности groups.sh/geo.sh: греем ровно то,
# что ЗАЯВЛЕНО демону, и новая подсистема со своим набором попадает сюда без единой правки.
WARM_SETS_CAP=${WARM_SETS_CAP:-40}
# Счёт членов набора: «Number of entries:» печатают НЕ все ядра (на 4.4 у AX3600/BE3600 её нет),
# поэтому берём общий ipset_count из lists-lib. Сорсим ТОЛЬКО под `[ -f ]` (инвариант: провалившийся
# `.` в ash — фатальная ошибка спецбилтина), шим повторяет обе ступени — без него на установке без
# библиотеки мы считали бы пустыми ВСЕ наборы и грели их каждый тик.
if [ -f "$ENODIA_DIR/lists-lib.sh" ]; then . "$ENODIA_DIR/lists-lib.sh"; fi
command -v ipset_count >/dev/null 2>&1 || ipset_count() {
    _ic=$(ipset list "$1" 2>/dev/null | sed -n 's/^Number of entries:[[:space:]]*//p' | head -1)
    case "$_ic" in ''|*[!0-9]*) _ic=$(ipset list "$1" 2>/dev/null | grep -cE '^[0-9]') ;; esac
    case "$_ic" in ''|*[!0-9]*) _ic=0 ;; esac
    printf '%s' "$_ic"
}
# ЕСТЬ ЛИ ВООБЩЕ ЧТО ГРЕТЬ. Дешёвый предикат для верба `warm`: свои правила (строки `ipset=` в
# нашем персисте — сам файл существует всегда, в нём шапка-комментарий, поэтому судим по строкам,
# а не по размеру) ИЛИ чужие наборы правил (группы/гео/слоты кладут свои `ipset=` в NN-*.conf).
warm_have_work() {
    # ОБА conf-dir и наш файл в КАЖДОМ из них: живой конфиг демона — `/tmp/dnsmasq.d`, а копия в
    # `/etc` может отстать (её кладёт heal на буте). Спросить только `/etc` значило бы «греть
    # нечего» при живых правилах в /tmp — то есть выключить прогрев там, где он и нужен.
    for _wh_dir in /etc/dnsmasq.d /tmp/dnsmasq.d; do
        for _wh_f in "$_wh_dir"/enodia-custom.conf "$_wh_dir"/[0-9][0-9]-*.conf; do
            [ -f "$_wh_f" ] || continue
            grep -q '^ipset=' "$_wh_f" 2>/dev/null && return 0
        done
    done
    return 1
}

warm_rule_sets() {
    _ws_confs=""
    for _ws_dir in /etc/dnsmasq.d /tmp/dnsmasq.d; do
        for _ws_f in "$_ws_dir"/[0-9][0-9]-*.conf; do
            [ -f "$_ws_f" ] && _ws_confs="$_ws_confs $_ws_f"
        done
    done
    [ -n "$_ws_confs" ] || return 0
    # Имена наборов: ПОСЛЕДНИЙ сегмент строки, их может быть несколько через запятую.
    for _ws_s in $(sed -n 's|^ipset=/.*/\([^/]*\)$|\1|p' $_ws_confs 2>/dev/null | tr ',' '\n' | sort -u); do
        case "$_ws_s" in ''|"$IPSET_NAME"|"$BYPASS_SET") continue ;; esac
        ipset list -n 2>/dev/null | grep -qx "$_ws_s" || continue     # набора нет — не наше дело
        [ "$(ipset_count "$_ws_s")" = 0 ] || continue                 # живой набор прогрева не просит
        # Домены этого набора: первый сегмент строки, если набор есть в её списке (точный матч
        # по запятым — иначе `grp_vpn` цеплял бы `grp_vpn_s2`).
        _ws_doms=$(sed -n 's|^ipset=/||p' $_ws_confs 2>/dev/null | while IFS= read -r _ws_l; do
                case ",${_ws_l##*/}," in *",$_ws_s,"*) echo "${_ws_l%%/*}" ;; esac
            done | sort -u | head -n "$WARM_SETS_CAP")
        [ -n "$_ws_doms" ] || continue
        _ws_n=0
        for _ws_d in $_ws_doms; do warm_one "$_ws_s" "$_ws_d"; _ws_n=$((_ws_n + 1)); done
        printf "[domain] %s: набор был пуст, прогрето доменов %s (лимит %s)\n" "$_ws_s" "$_ws_n" "$WARM_SETS_CAP"
    done
    return 0
}

# Пересобрать сет «мимо VPN» с нуля: у него ОДИН хозяин (этот скрипт), значит содержимое обязано
# в точности соответствовать списку правил. Иначе IP домена, снятого с «мимо VPN», остались бы в
# сете и продолжали бы его выводить мимо туннеля (ACCEPT в VPN_EXCLUDE бьёт раньше маркировки) —
# «убрал правило, а ничего не изменилось».
rebuild_bypass_set() {
    ensure_sets
    # Через set_sync, а не голым flush: список доменов не изменился (правили СОСЕДНЕЕ правило,
    # звал heal, переигрывал boot) ⇒ набор не трогаем вовсе и накопленные адреса живут. Изменился —
    # честная пересборка, как и требует инвариант выше, а прогрев наполняет заново.
    # Статики (CIDR) у набора нет по построению: его наполняет ТОЛЬКО dnsmasq.
    _rb_c="/tmp/.enodia-dom-bypass-cidr.$$"; _rb_d="/tmp/.enodia-dom-bypass-dom.$$"
    : > "$_rb_c"; dom_list "$BYPASS_SET" > "$_rb_d" 2>/dev/null
    set_sync "$BYPASS_SET" "$_rb_c" "$_rb_d"
    rm -f "$_rb_c" "$_rb_d" 2>/dev/null
    # Правило по сету ставит хозяин цепочки VPN_EXCLUDE; идемпотентно, он же переигрывает на boot.
    sh "$ENODIA_DIR/apply-bypass.sh" set-dst-ensure "$BYPASS_SET" >/dev/null 2>&1 || true
    # $1=nowarm — пропустить прогрев. Нужно ровно одному вызывающему: верб `apply` на буте бежит
    # ДО рестарта dnsmasq, ipset=-правила ещё не загружены, и резолв заведомо никуда не ляжет.
    # Раньше это было безобидно (прогрев молчал и не ждал), а теперь он честный: отрапортовал бы
    # промах по КАЖДОМУ домену «мимо» на каждой загрузке и добавил бы паузу на ровном месте.
    [ "$1" = nowarm ] || warm "$BYPASS_SET"
}

# Снять ЛЮБОЕ прежнее правило домена (независимо от направления) — общий шаг add/bypass/block/remove.
# Домен держит ЛИБО ipset=-строку (в VPN / мимо), ЛИБО две address=-строки (блок 0.0.0.0 + ::) — режем оба.
drop_rule() { sed -i "/^ipset=\/$1\/.*/d; /^address=\/$1\/.*/d" "$CUSTOM_FILE" 2>/dev/null; }

# Установить правило «домен → сет». Общее тело add и bypass (DRY): единственная разница — сет.
set_rule() {
    _dom="$1"; _set="$2"
    if grep -q "^ipset=/$_dom/$_set\$" "$CUSTOM_FILE" 2>/dev/null; then
        printf "${YELLOW}Домен %s уже %s.${NC}\n" "$_dom" "$([ "$_set" = "$IPSET_NAME" ] && echo 'в VPN' || echo 'мимо VPN')"
        exit 0
    fi
    drop_rule "$_dom"                       # смена направления = замена строки, а не вторая строка
    ensure_sets
    echo "ipset=/$_dom/$_set" >> "$CUSTOM_FILE"
    persist_save
    reload_dnsmasq
    # Ждём демона ДО любого прогрева — в том числе до rebuild_bypass_set, тот греет набор «мимо»
    # внутри себя. Раньше резолв шёл СЛЕДУЮЩЕЙ строкой после полного рестарта и промахивался.
    dns_up || printf "${YELLOW}[ ! ] dnsmasq не ответил за 10 с — правило записано, адреса подъедут позже.${NC}\n"
    rebuild_bypass_set                      # сет «мимо» всегда = точный слепок правил (см. шапку)
    warm_one "$_set" "$_dom"; _sr_rc=$?
    case "$_sr_rc" in
        1) printf "${RED}[ ! ] Адрес %s НЕ попал в набор %s — правило записано, но пока не действует.${NC}\n" "$_dom" "$_set"
           if set_full "$_set"; then
               printf "${RED}      Набор переполнен: dnsmasq больше не добавляет в него адреса.${NC}\n"
           else
               printf "${YELLOW}      Проверьте, не заявлен ли домен ещё где-то (группа/гео/пул):${NC}\n"
               printf "${YELLOW}      dnsmasq кладёт адрес РОВНО В ОДИН набор на домен.${NC}\n"
           fi ;;
        2) printf "${YELLOW}[ i ] У %s нет A-записи — маршрутизировать по IPv4 пока нечего.${NC}\n" "$_dom" ;;
    esac
    # Смена маршрута на живых соединениях без этого не применится (NSS/ECM-offload) — как в groups.sh.
    ct_flush
    return "$_sr_rc"
}

case "$1" in
    add)
        domain="$2"
        if [ -z "$domain" ]; then
            printf "${RED}Укажите домен:${NC} domain.sh add chatgpt.com\n"
            exit 1
        fi
        # Убираем www., http://, https://, всё лишнее
        domain=$(echo "$domain" | sed -E 's|^https?://||; s|^www\.||; s|/.*$||')
        dom_ok "$domain" || { printf "${RED}[ ! ]${NC} Недопустимый домен: %s\n" "$domain"; exit 1; }
        # Проверим в основном списке тоже (информационно)
        if grep -q "/$domain/" "$MAIN_FILE" 2>/dev/null; then
            printf "${BLUE}Кстати, %s уже есть в основном re-filter списке.${NC}\n" "$domain"
            printf "${BLUE}Но всё равно добавлю в ваш пользовательский — на всякий.${NC}\n"
        fi
        # Прогрев внутри set_rule: резолвим домен через системный резолвер (=dnsmasq), чтобы его
        # текущие IP попали в enodia_list, не дожидаясь запроса с клиента. Маркировка идёт по dst-IP
        # (match-set enodia_list dst), поэтому в туннель попадёт ДАЖЕ клиент с DoH — лишь бы он
        # резолвил домен в тот же IP, что и роутер.
        # Статус берём у set_rule: он проверяет ФАКТ в ядре. Прежняя безусловная зелёная строка
        # (плюс совет «открой сайт в браузере») печаталась и тогда, когда в наборе не было ничего.
        if set_rule "$domain" "$IPSET_NAME"; then
            printf "${GREEN}[ + ]${NC} %s теперь идёт В VPN.\n" "$domain"
        else
            printf "${YELLOW}[ + ]${NC} Правило для %s сохранено, но пока НЕ действует — причина выше.\n" "$domain"
        fi
        ;;

    # Зеркало add: тот же файл, тот же персист, тот же прогрев — другой сет. Домен, выведенный
    # сюда, перебивает и общий CIDR-список, и re-filter: ACCEPT в VPN_EXCLUDE стоит ПЕРВЫМ в
    # mangle PREROUTING и рвёт обход раньше любых MARK-правил.
    bypass|out)
        domain="$2"
        if [ -z "$domain" ]; then
            printf "${RED}Укажите домен:${NC} domain.sh bypass mi.com\n"
            exit 1
        fi
        domain=$(echo "$domain" | sed -E 's|^https?://||; s|^www\.||; s|/.*$||')
        dom_ok "$domain" || { printf "${RED}[ ! ]${NC} Недопустимый домен: %s\n" "$domain"; exit 1; }
        if set_rule "$domain" "$BYPASS_SET"; then
            printf "${GREEN}[ → ]${NC} %s теперь идёт МИМО VPN (напрямую).\n" "$domain"
        else
            printf "${YELLOW}[ → ]${NC} Правило для %s сохранено, но пока НЕ действует — причина выше.\n" "$domain"
        fi
        ;;

    # add-many — ПАЧКА доменов «в VPN» из stdin ОДНИМ применением (по домену на строку; схема/путь/
    # www/ведущая «*.» режутся здесь же). Печатает ЧИСЛО добавленных — машинный ответ для панели.
    # Зачем отдельный верб: `add` на КАЖДЫЙ домен делает полный цикл применения (персист → рестарт
    # dnsmasq → пересборка сета «мимо» → прогрев → `conntrack -F`), а он стоит ЧЕТЫРЕ секунды
    # (замерено на BE7000). Пачка из 30 доменов = две минуты, тридцать обрывов DNS у ВСЕЙ сети и
    # таймаут CGI панели — при том что тяжёлый хвост нужен ОДИН раз на всю пачку. Здесь цикл идёт
    # только по строкам файла правил, а хвост выполняется однажды.
    # `|| [ -n "$_l" ]` обязателен: busybox `read` теряет последнюю строку без хвостового \n, а
    # текст сюда приезжает из формы/файла пользователя.
    add-many)
        _n=0; _added="/tmp/.enodia-dom-many.$$"; : > "$_added"
        ensure_sets
        while read -r _l || [ -n "$_l" ]; do
            _d=$(printf '%s' "$_l" | tr -d ' \t\r' | sed -E 's|^https?://||; s|^\*\.||; s|^www\.||; s|/.*$||')
            [ -n "$_d" ] || continue
            # dom_ok = синтаксис строки dnsmasq (метка ≤63), хвост `\.[A-Za-z]{2,}` = политика
            # ИМЕННО пачки: в неё вставляют текст из браузера, и голое слово там почти всегда мусор.
            dom_ok "$_d" || continue
            echo "$_d" | grep -qE '\.[A-Za-z]{2,}$' || continue
            grep -q "^ipset=/$_d/$IPSET_NAME\$" "$CUSTOM_FILE" 2>/dev/null && continue
            drop_rule "$_d"                     # смена направления = замена строки, а не вторая
            echo "ipset=/$_d/$IPSET_NAME" >> "$CUSTOM_FILE"
            echo "$_d" >> "$_added"
            _n=$((_n + 1))
        done
        if [ "$_n" -gt 0 ]; then
            persist_save
            reload_dnsmasq
            dns_up || echo "[domain] dnsmasq не ответил за 10 с — адреса подъедут позже" >&2
            rebuild_bypass_set                  # сет «мимо» = точный слепок правил (см. шапку)
            # Прогрев — ТОЛЬКО добавленных: warm() гоняет nslookup по ВСЕМУ сету, а он бывает в сотни
            # доменов, и пачка из десяти превратилась бы в сотни резолвов.
            # stdout этого верба — КОНТРАКТ с панелью (одно число, его парсят) ⇒ жалобы в stderr.
            _miss=0
            while read -r _wd || [ -n "$_wd" ]; do
                warm_one "$IPSET_NAME" "$_wd"
                case $? in 1) _miss=$((_miss + 1)) ;; esac
            done < "$_added"
            [ "$_miss" = 0 ] || echo "[domain] адрес не попал в набор у доменов: $_miss" >&2
            ct_flush
        fi
        rm -f "$_added" 2>/dev/null
        echo "$_n"
        ;;

    # Блок ОДИНОЧНОГО домена: dnsmasq address=/дом/0.0.0.0 + /:: (ОБЕ семьи — только 0.0.0.0 режет
    # лишь A, dnsmasq форвардит AAAA и домен открывается по IPv6; грабля adblock). Строки — в том же
    # enodia-custom.conf → персист на /data и heal-переигрывание на буте получаем даром (как vpn/мимо).
    # Как add/bypass — сперва снимаем прежнее правило домена (одно состояние на домен).
    block)
        domain="$2"
        if [ -z "$domain" ]; then
            printf "${RED}Укажите домен:${NC} domain.sh block ads.example.com\n"
            exit 1
        fi
        domain=$(echo "$domain" | sed -E 's|^https?://||; s|^www\.||; s|/.*$||')
        dom_ok "$domain" || { printf "${RED}[ ! ]${NC} Недопустимый домен: %s\n" "$domain"; exit 1; }
        drop_rule "$domain"                     # смена состояния = замена строк, не добавка
        printf 'address=/%s/0.0.0.0\naddress=/%s/::\n' "$domain" "$domain" >> "$CUSTOM_FILE"
        persist_save
        reload_dnsmasq                          # address= по SIGHUP не перечитывается → полный рестарт
        rebuild_bypass_set                      # если домен был «мимо» — убрать его IP из enodia_bypass
        ct_flush            # NSS/ECM-offload: живые соединения иначе не переключатся
        printf "${GREEN}[ x ]${NC} %s ЗАБЛОКИРОВАН (не открывается на всех устройствах).\n" "$domain"
        ;;

    remove|rm|del)
        domain="$2"
        if [ -z "$domain" ]; then
            printf "${RED}Укажите домен:${NC} domain.sh remove instagram.com\n"
            exit 1
        fi
        domain=$(echo "$domain" | sed -E 's|^https?://||; s|^www\.||; s|/.*$||')
        # Снимаем строку — ЛЮБОГО направления: это откат «в исходную точку», а не «убрать из VPN».
        # Дальше домен едет как обычный трафик: попадает под общий CIDR-список — значит в туннель,
        # не попадает — напрямую. Именно так было до того, как правило появилось.
        if grep -qE "^(ipset|address)=/$domain/" "$CUSTOM_FILE" 2>/dev/null; then
            # was = имя сета (в VPN/мимо), либо пусто у заблокированного (address=-строки) → else-ветка reload без flush.
            was=$(sed -n "s|^ipset=/$domain/\(.*\)$|\1|p" "$CUSTOM_FILE" 2>/dev/null | head -1)
            drop_rule "$domain"
            persist_save
            # Флашим enodia_list ТОЛЬКО если домен ехал в VPN: его стухшие IP не должны там висеть,
            # иначе «правило снял, а трафик всё ещё в туннеле». Сет общий с re-filter → сразу
            # прогреваем свои VPN-домены обратно, чтобы флаш не сбил ИХ маршрут (у re-filter IP
            # подъедут со следующего резолва клиента — это его штатный режим наполнения).
            if [ "$was" = "$IPSET_NAME" ]; then reload_dnsmasq flush; warm "$IPSET_NAME"; else reload_dnsmasq; fi
            rebuild_bypass_set          # ушёл из «мимо» → его IP обязаны уйти из enodia_bypass
            ct_flush
            printf "${GREEN}[ - ]${NC} правило для %s снято — домен снова «как все».\n" "$domain"
            if grep -q "/$domain/" "$MAIN_FILE" 2>/dev/null; then
                printf "${BLUE}Он есть в основном re-filter → продолжит идти через VPN оттуда.${NC}\n"
            fi
        else
            printf "${YELLOW}%s не было в пользовательском списке.${NC}\n" "$domain"
            if grep -q "/$domain/" "$MAIN_FILE" 2>/dev/null; then
                printf "${YELLOW}Но он есть в основном re-filter — он туда автоматом${NC}\n"
                printf "${YELLOW}возвращается при обновлении. Чтобы увести его мимо VPN,${NC}\n"
                printf "${YELLOW}используйте: domain.sh bypass %s${NC}\n" "$domain"
            fi
        fi
        ;;

    # Вернуть ЖИВОЙ /etc/dnsmasq.d/enodia-custom.conf из персиста на /data — ЕДИНСТВЕННЫЙ владелец
    # этой копии. Раньше строка `cp` жила внутри heal.sh (секция 2b) и работала ТОЛЬКО на буте,
    # под локом 1×/boot. Из-за этого импорт бэкапа возвращал персист и не трогал живой файл: панель
    # читает /etc и показывала ПУСТОЙ список правил, человек добавлял домен заново — а persist_save
    # копировал пустой живой файл ПОВЕРХ персиста, и восстановленные правила пропадали насовсем.
    # Гард `-s` обязателен: пустой или отсутствующий персист не должен обнулять живой файл.
    restore)
        if [ -s "$PERSIST_FILE" ]; then
            # ФИЛЬТР «строка, которую dnsmasq не примет» — здесь, в единственном владельце копии.
            # До 15.08.2026 домен с меткой >63 символов проходил в персист (валидатора не было
            # ни в одном звене), а на буте heal кладёт персист в живой conf-dir ⇒ демон не
            # поднимается ВООБЩЕ и вся сеть остаётся без DNS. Гард в dns-merge.sh (де-факто
            # отказ перезапускать) спасает только текущий сеанс — мина срабатывает на ребуте.
            # Поэтому строку выкидываем и НАЗЫВАЕМ (в stderr, его видно и в логе heal, и в панели),
            # а очищенную копию кладём обратно в персист — иначе мина вернётся на следующем буте.
            # ЗДЕСЬ ЖЕ — ИМЕНА НАБОРОВ ДО РЕБРЕНДИНГА. Направление правила живёт в ИМЕНИ набора (`ipset=/дом/<набор>`), а
            # до 29.08.2026 наборы звались `awg_list`/`awg_bypass`. Таких наборов в ядре больше нет ⇒ dnsmasq кладёт адреса в
            # никуда, а панель (`data?section=sites`: всё, что не `enodia_bypass`, — «в VPN») рисует правило рабочим, бывшее
            # «мимо» — ещё и с чужим направлением. Приезжают они с архивом старой сборки: импорт переименовывает ФАЙЛ, а
            # строки внутри — нет (замер BE7000 04.10.2026, архив dev124). Чиним у владельца, а не в импорте: restore бежит
            # первым шагом цепочки импорта, на каждом буте и при обновлении (install.sh → `heal.sh replay`) ⇒ лечит и
            # роутеры, где старый архив УЖЕ восстановлен.
            # Набор в строке один и стоит последним (так domain.sh писал и тогда) ⇒ сравнение с якорем на конец строки.
            _rs_t="/tmp/.enodia-dom-restore.$$"; : > "$_rs_t"; _rs_bad=0; _rs_mig=0
            while IFS= read -r _rl || [ -n "$_rl" ]; do
                case "$_rl" in
                    ipset=/*|address=/*)
                        _rd=$(printf '%s' "$_rl" | sed -E 's|^[a-z]+=/([^/]*)/.*|\1|')
                        if ! dom_ok "$_rd"; then
                            _rs_bad=$((_rs_bad + 1))
                            printf "[domain] выкинул правило, с которым dnsmasq не стартует: %s\n" "$_rd" >&2
                            continue
                        fi ;;
                esac
                # Перевод имён — ПОСЛЕ отбраковки: в счёт «заменено» не должна попасть выкинутая строка.
                case "$_rl" in
                    ipset=/*/awg_list)   _rl="${_rl%/awg_list}/$IPSET_NAME";  _rs_mig=$((_rs_mig + 1)) ;;
                    ipset=/*/awg_bypass) _rl="${_rl%/awg_bypass}/$BYPASS_SET"; _rs_mig=$((_rs_mig + 1)) ;;
                esac
                printf '%s\n' "$_rl" >> "$_rs_t"
            done < "$PERSIST_FILE"
            # СЧЁТНАЯ сверка перед подменой: /tmp — это ОЗУ, и оборванная запись (нет места) дала бы
            # усечённый файл, который мы бы молча положили ПОВЕРХ живых правил, да ещё и записали
            # обратно в персист. Строк должно стать ровно «было минус выкинутые»; не сходится —
            # ведём себя как раньше (прямая копия персиста), фильтр в этом прогоне просто не сработал.
            # Считаем `grep -c ''`, а не `wc -l`: у файла с /data может не быть хвостового
            # перевода строки (его правили руками, дописывал busybox), и `wc -l` тогда занижает
            # на единицу — сверка не сошлась бы ВСЕГДА, то есть фильтр молча стал бы мёртвым кодом.
            _rs_want=$(( $(grep -c '' "$PERSIST_FILE" 2>/dev/null) - _rs_bad ))
            _rs_got=$(grep -c '' "$_rs_t" 2>/dev/null)
            if [ "${_rs_got:-0}" = "$_rs_want" ]; then
                cp "$_rs_t" "$CUSTOM_FILE" 2>/dev/null
                # Переименованное — тоже обратно в персист: иначе старые имена уедут в следующий экспорт.
                if [ "$_rs_bad" != 0 ] || [ "$_rs_mig" != 0 ]; then cp "$_rs_t" "$PERSIST_FILE" 2>/dev/null; fi
                [ "$_rs_mig" = 0 ] || printf "[domain] имена наборов до ребрендинга заменены на текущие: %s\n" "$_rs_mig" >&2
            else
                printf "[domain] фильтр не сошёлся по строкам (%s вместо %s) — кладу персист как есть\n" \
                    "${_rs_got:-0}" "$_rs_want" >&2
                cp "$PERSIST_FILE" "$CUSTOM_FILE" 2>/dev/null
            fi
            rm -f "$_rs_t" 2>/dev/null
            printf "[domain] правила восстановлены из персиста: %s\n" "$(grep -c '^ipset=\|^address=' "$CUSTOM_FILE" 2>/dev/null)"
        else
            printf "[domain] персиста нет или он пуст — живой файл не трогаем\n"
        fi
        ;;

    # Пересобрать эфемерное из конфига: сеты (RAM, стираются на ребуте) + правило по enodia_bypass +
    # прогрев. Зовёт heal.sh на буте — ПОСЛЕ восстановления enodia-custom.conf из персиста и ДО
    # рестарта dnsmasq (иначе ipset=-строки лягут в несуществующий сет и адреса никуда не попадут).
    apply)
        ensure_sets
        # Набор «мимо VPN» приводим в соответствие списку правил: у него ОДИН хозяин — этот скрипт,
        # а после ребута он пуст (ipset в RAM). Через set_sync ⇒ на неизменившемся составе набор не
        # трогается вовсе, лишним не будет.
        # ПРОГРЕВА ЗДЕСЬ НЕТ СОЗНАТЕЛЬНО: heal зовёт `apply` ДО рестарта dnsmasq (ipset=-правила ещё
        # не загружены), и резолв в этот момент никуда бы не лёг. Прогрев вынесен в отдельный верб
        # `warm` — его heal зовёт ПОСЛЕ рестарта. `nowarm` доносит это до пересборки набора «мимо»:
        # она грела внутри себя и тем самым нарушала правило, ради которого прогрев отсюда убрали.
        rebuild_bypass_set nowarm
        sh "$ENODIA_DIR/apply-bypass.sh" set-dst-ensure "$BYPASS_SET" >/dev/null 2>&1 || true
        n_vpn=$(dom_list "$IPSET_NAME" | grep -c .); n_out=$(dom_list "$BYPASS_SET" | grep -c .)
        printf "[domain] правила доменов: в VPN %s, мимо VPN %s\n" "${n_vpn:-0}" "${n_out:-0}"
        ;;

    list|ls)
        printf "${BLUE}Ваши домены (через AWG):${NC}\n"
        if [ -s "$CUSTOM_FILE" ]; then
            grep "^ipset=" "$CUSTOM_FILE" | sed -E 's|ipset=/([^/]+)/.*|  \1|'
            grep -E "^address=/[^/]+/0\.0\.0\.0$" "$CUSTOM_FILE" | sed -E 's|address=/([^/]+)/.*|  \1 (заблокирован)|'
        else
            printf "  ${YELLOW}(пусто, используется только основной re-filter)${NC}\n"
        fi
        echo ""
        # ВАЖНО про grep -c без '|| echo 0': busybox grep -c при НУЛЕ совпадений
        # печатает "0" И выходит с кодом 1. Старое '... || echo 0' тогда дописывало
        # ВТОРОЙ "0" → значение становилось "0\n0" → busybox printf '%d' ругался
        # "invalid number '0\n0'" и возвращал код 1, а вызывающий be7000.ps1
        # принимал это за ошибку SSH и рисовал ложный [FAIL]. grep -c и так всегда
        # выводит число — берём как есть, ${var:-0} лишь страхует пустой вывод.
        if [ -f "$MAIN_FILE" ]; then
            main_count=$(grep -c "^ipset=" "$MAIN_FILE" 2>/dev/null)
            printf "${BLUE}Основной re-filter:${NC} %s правил\n" "${main_count:-0}"
            printf "  (обновляется ежедневно в 5:00, файл $MAIN_FILE)\n"
        fi
        ipset_cnt=$(ipset list "$IPSET_NAME" 2>/dev/null | grep -c '^[0-9]')
        printf "${BLUE}Сейчас в ipset (резолвлено IP):${NC} %d записей\n" "${ipset_cnt:-0}"
        ;;

    search|find|grep)
        needle="$2"
        if [ -z "$needle" ]; then
            printf "${RED}Укажите что искать:${NC} domain.sh search openai\n"
            exit 1
        fi
        printf "${BLUE}Поиск '%s' в всех списках:${NC}\n" "$needle"
        echo ""
        # ВАЖНО: busybox grep НЕ знает '--color' (v1.25.1: "unrecognized option:
        # color") — старый 'grep -i --color' молча падал, 2>/dev/null глушил ошибку,
        # и поиск ВСЕГДА возвращал пусто. Убрали --color. И берём вывод grep в
        # переменную: раньше 'grep | sed || echo "(нет)"' никогда не печатал "(нет)",
        # т.к. код выхода пайпа = код sed (0), даже когда grep ничего не нашёл.
        echo "В вашем списке (enodia-custom.conf):"
        res=$(grep -i "$needle" "$CUSTOM_FILE" 2>/dev/null)
        if [ -n "$res" ]; then printf '%s\n' "$res" | sed 's/^/  /'; else echo "  (нет)"; fi
        echo ""
        echo "В основном re-filter (enodia-domains.conf):"
        res=$(grep -i "$needle" "$MAIN_FILE" 2>/dev/null | head -20)
        if [ -n "$res" ]; then printf '%s\n' "$res" | sed 's/^/  /'; else echo "  (нет)"; fi
        echo ""
        # И покажем сразу, какие IP в ipset из этих доменов
        echo "Текущие IP в ipset:"
        ipset list "$IPSET_NAME" 2>/dev/null | grep -E '^[0-9]' | head -10 | sed 's/^/  /'
        ;;

    # Прогреть ОБА направления: после ребута сеты пусты, и до первого резолва КЛИЕНТА домен «в VPN»
    # едет мимо туннеля, а домен «мимо VPN» — в туннель. Клиент с DoH/длинным кэшем может не
    # спросить очень долго, поэтому спрашиваем сами. Зовёт heal.sh ПОСЛЕ рестарта dnsmasq —
    # раньше нельзя: без загруженных ipset=-правил резолв никуда не ляжет.
    warm)
        # ГРЕТЬ НЕЧЕГО — отдельный ответ, а не «выполнено». На установке «только панель» доменных
        # правил нет вовсе, и бутовый лог (его присылают в отчётах) двумя строками ниже честного
        # «правил нет — сеты не развожу» рапортовал «прогрев доменных правил выполнен». Заодно не
        # ждём dnsmasq десять секунд ради нулевой работы. Признак — наш персист: чужие наборы
        # (группы/гео/слоты) греются из своих conf, их проверяет warm_rule_sets ниже.
        if ! warm_have_work; then
            printf "[domain] доменных правил нет — греть нечего\n"
            exit 0
        fi
        # Ждём демона здесь, а не у вызывающего: верб зовут и heal на буте, и сторож по троттлу,
        # и импорт бэкапа — пауза нужна всем троим, а знание о ней должно быть в одном месте.
        dns_up || printf "[domain] dnsmasq не ответил за 10 с — прогрев может не лечь\n"
        warm "$IPSET_NAME"; warm "$BYPASS_SET"
        # Группы, гео и слоты — тем же заходом: набор у них наполняет ТОТ ЖЕ dnsmasq, и в сети со
        # своим резолвером они мертвы ровно так же. Дорогого тут нет — греются только ПУСТЫЕ.
        warm_rule_sets
        printf "[domain] прогрев доменных правил выполнен\n"
        ;;

    reload)
        reload_dnsmasq flush
        dns_up || printf "${YELLOW}[ ! ] dnsmasq не ответил за 10 с — прогрев может не лечь.${NC}\n"
        # Сет только что обнулён — прогреваем СВОИ домены сразу, как это делает remove. Иначе после
        # ручного reload трафик своих доменов идёт мимо туннеля до следующего резолва КЛИЕНТА, а тот
        # с кэшем/DoH может не случиться очень долго. Домены re-filter подъедут своим чередом.
        warm "$IPSET_NAME"; warm "$BYPASS_SET"
        printf "${GREEN}[ OK ]${NC} dnsmasq перечитан, ipset сброшен и прогрет.\n"
        printf "IP доменов из основного re-filter подъедут при следующих DNS-запросах с клиентов.\n"
        ;;

    *)
        cat <<EOF
Управление списком доменов, идущих через AWG-туннель:

  domain.sh add <домен>       — добавить домен в туннель
  domain.sh add-many          — пачка доменов в туннель из stdin (по домену на строку)
  domain.sh remove <домен>    — убрать домен из пользовательского списка
  domain.sh list              — показать все ваши добавления + статистику
  domain.sh search <строка>   — найти строку во всех списках
  domain.sh reload            — перезагрузить dnsmasq после ручной правки

Примеры:
  domain.sh add chatgpt.com
  domain.sh add my-personal-site.net
  domain.sh remove instagram.com
  domain.sh search youtube
EOF
        ;;
esac
