def _router_host():
    try:
        h = b.load_router_host()
        if h:
            return h
    except Exception:
        pass
    return getattr(b, "DEFAULT_ROUTER_IP", None) or "192.168.31.1"


def main():
    dry = ("--dry-run" in sys.argv) or ("-n" in sys.argv)
    mode = "dryrun" if dry else ""
    host = _router_host()
    print("Router: " + host + ("  [DRY-RUN: nothing deleted]" if dry else ""))

    router = b.Router(host, password_provider=b.get_stored_password)
    print("Cleaning /data ..." if not dry else "Inspecting /data (dry-run)...")
    cmd = "printf '" + BEGIN + "\\n'; base64 -d | sh -s " + mode + " | base64; printf '" + END + "\\n'"
    res = router.run(cmd, stdin_data=CLEAN_B64, silent=True)
    out = getattr(res, "out", "") or ""
    if not out:
        print("Empty reply from router (link / SSH / password?).")
        return 1

    import re
    mm = re.search(r'(?s)' + BEGIN + r'(.*?)' + END, out)
    b64out = re.sub(r'\s', '', mm.group(1)) if mm else re.sub(r'\s', '', out)
    try:
        data = base64.b64decode(b64out).decode("utf-8", "replace")
    except Exception:
        print("Failed to decode base64 reply - link dropped / old busybox.")
        return 1

    print()
    print(data)
    return 0


if __name__ == "__main__":
    sys.exit(main())
