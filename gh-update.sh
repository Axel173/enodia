#!/bin/sh
# gh-update.sh — апдейтер с GitHub (Ф4). Скачивает код и бинари из ПУБЛИЧНОГО репо
# Axel173/enodia (дефолт и его история — в блоке REPO ниже). На роутере НЕТ
# ПК-источника бинарей, поэтому смена набора протоколов (proto-install.sh) и обновление кода
# идут отсюда.
#
# ДВА ПУТИ, И ОНИ РАЗНЫЕ. Бинари протоколов — поштучно из папки `bin/` (fetch-bin, «Компоненты»).
# Код — ОДНИМ ПОДПИСАННЫМ ПАКЕТОМ (`apply`, блок «ПАКЕТНОЕ ОБНОВЛЕНИЕ» ниже): проверить подпись,
# скачать, сверить, распаковать в ОЗУ и отдать установщику ИЗ ПАКЕТА. Пофайлового обновления кода
# (94 запроса, удаления не приезжали, апдейтер обновлял сам себя) больше нет.
#
# ПОЧЕМУ так / грабли:
#   * curl -fsSL к raw.githubusercontent.com на роутере РАБОТАЕТ (установщик так же качает
#     RE_FILTER_URL). При живом VPN запрос идёт через туннель (Fastly-IP в iplist), при
#     мёртвом — напрямую (safety_off делает DNS публичным). Сетевой сбой не фатален.
#   * Замена файла НЕ роняет демоны (они в RAM) и НЕ перезапускает их — после apply нужен
#     repair/ребут. Авто-switch НЕ делаем.
#   * Защита от ДАУНГРЕЙДА: публичный репо может ОТСТАВАТЬ от рантайма роутера (на роутере
#     бывают НЕвыпущенные dev-скрипты). apply обновляет ТОЛЬКО если CODE релиза > local CODE;
#     нет описания релиза → отказ (не «обновляем в ноль»).
#   * Бинарь качаем в .dl, проверяем (ELF-magic + размер + sha256 из ПОДПИСАННОГО манифеста — он едет
#     в пакете кода), atomic mv — обрыв закачки не оставит полу-файл вместо рабочего бинаря.
#   * rm живёт ЗДЕСЬ, в .sh на роутере (PS-guard ложно блокирует литерал rm в SSH-командах).
#   * busybox этого роутера БЕЗ od/hexdump → ELF-magic сверяем через printf '\177ELF' + cmp.

ENODIA_DIR=${ENODIA_DIR:-/data/usr/app/enodia}
ENODIA_BIN=${ENODIA_BIN:-/data/usr/app/enodia-bin}
ENODIA_STATE=${ENODIA_STATE:-/data/usr/app/enodia-state}
# Резидентный бутстрап — цель всех cron-строк. Апдейтеру он нужен ровно затем, чтобы передать его
# путь установщику пакета (тот пересобирает бутстрап из свежего кода через install.sh).
ENODIA_BOOT=${ENODIA_BOOT:-/data/usr/app/enodia-boot}
# Репозиторий-источник. Override: строка `владелец/репо` в $ENODIA_STATE/.gh-repo — ею тестовый
# роутер переключается на черновой репозиторий, не трогая код. Форму ПРОВЕРЯЕМ: кривая строка
# построила бы URL, который просто не резолвится, и отказ читался бы как «нет сети».
# Обрезаем ТОЛЬКО обрамляющие пробелы, а не все подряд (у соседних `.gh-ref`/`.gh-bin-tag` стоит
# `tr -d ' \r\n'`, и здесь это ловушка): «Axel173/enodia test» склеилось бы в «Axel173/enodiatest»
# — синтаксически верное, но ЧУЖОЕ имя, и опечатка увела бы источник кода молча. Пробел внутри
# обязан отвергаться гардом ниже, а не исправляться.
REPO=$(cat "$ENODIA_STATE/.gh-repo" 2>/dev/null | tr -d '\r\n' | sed 's/^[ 	]*//; s/[ 	]*$//')
# `..` отвергаем отдельно: точки в именах GitHub законны, но `../x` проходит проверку формы и
# строит URL, который сервер РАЗЫМЕНУЕТ в чужой путь — то есть код приехал бы не из того места,
# что написано в файле, и по логу это выглядело бы нормально.
case "$REPO" in ''|*[!A-Za-z0-9._/-]*|/*|*/|*/*/*|*..*) REPO= ;; */*) : ;; *) REPO= ;; esac
# Дефолт — `Axel173/enodia` с релиза 1.0.0. Из этой переменной живёт НЕ ТОЛЬКО проверка обновлений: по ней же
# `fetch-bin` тянет бинари, то есть «Компоненты» в панели ⇒ дефолт переключали ОДНОЙ строкой в момент публикации, когда в
# репо уже лежат `bin/` и релиз (замер AX3600 30.08.2026: с пустым репо в дефолте `fetch-bin awg` получал 404 и протокол
# не ставился вовсе), вместе с пользовательскими ссылками в README/notify.sh/панели.
[ -n "$REPO" ] || REPO="Axel173/enodia"
# Ветка/тег источника. Override: положить строку в $ENODIA_STATE/.gh-ref (напр. v0.4.0).
GH_REF=$(cat "$ENODIA_STATE/.gh-ref" 2>/dev/null | tr -d ' \r\n'); [ -n "$GH_REF" ] || GH_REF=main
RAW="https://raw.githubusercontent.com/$REPO/$GH_REF"
# --- ОТКУДА БЕРЁМ БИНАРИ: из папки `bin/` через raw; ассет релиза — РЕЗЕРВНЫЙ канал. ---------
# Байты у всех каналов ОДНИ И ТЕ ЖЕ — файл `bin/<арка>/<имя>.user` этого репозитория; а КАКИЕ байты верны, решает
# не канал, а sha256 из манифеста бинарей в ПОДПИСАННОМ пакете кода (разбор — у BM_FILE ниже). Каналы по очереди:
# дерево репо НА ТЕГЕ установленного релиза (TAG= в VERSION пакета: неизменно, там ровно подписанные сборки), ветка
# источника $GH_REF (на ней те же, пока бинарь не пересобрали к следующему релизу) и ассет тега `bin` — плоское имя
# `<арка>-<файл>.user` (в релизах нет папок); тег `bin` переносится при обновлении бинарей, к версии кода он
# отношения не имеет.
#
# ПОПРАВКА 30.08.2026 — чтобы не решить это второй раз неверно. Здесь стояло «ассет ОСНОВНОЙ,
# raw защищается от массовой закачки бинарей», со ссылкой на замер 17.08.2026 (AX3600: raw дал
# 429 на `bin/arm64/amneziawg-go.user`, тот же файл ассетом приехал за 1.05 с). ЗАМЕРЕН был
# только сам факт; ПРИЧИНА была ДОГАДКОЙ, и она неверна: в тот день шла глобальная авария
# GitHub (13:28–21:15 UTC, ~7.5 ч), при которой загрузка raw-контента и архивов шла с ~50%
# ошибок. То есть 429 — почти наверняка сброс нагрузки во время аварии, а не наш «скрейпинг».
# КОНТРЗАМЕР 30.08.2026: десять бинарей подряд (16 МБ) с raw — ВСЕ 200, суммарно 5.6 с, ни
# одного 429. Рейт-лимита на такой объём у raw нет.
# ⇒ Порядок вернулся к прежнему: сперва raw, ассет — резерв на случай аварии (в тот день
# работал именно он). Ассеты при этом можно НЕ ЗАЛИВАТЬ вовсе: отсутствующий ассет = 404, а
# отказом (`gh_code_refused`) считаются только 429/403 ⇒ цикл спокойно уходит дальше. Понадобится
# запасной канал — залил тег `bin`, и он включился сам, без обновления роутеров.
GH_BIN_TAG=$(cat "$ENODIA_STATE/.gh-bin-tag" 2>/dev/null | tr -d ' \r\n'); [ -n "$GH_BIN_TAG" ] || GH_BIN_TAG=bin
GH_REL="https://github.com/$REPO/releases/download/$GH_BIN_TAG"
# Надёжная закачка с raw.githubusercontent ЧЕРЕЗ VPN. ВАЖНО (поймано на железе 2026-06-16):
# у raw.githubusercontent.com 4 anycast-IP (185.199.108-111.133), ВСЕ в iplist_set → идут через
# VPN/VPS. Часть anycast-узлов через VPS «мёртвая»: TCP-connect к ним УСПЕШЕН и быстрый
# (t_connect≈0.03с), но дальше соединение МОЛЧИТ (данные не идут). Поэтому --connect-timeout НЕ
# спасает (connect-то прошёл!), curl коммитится на мёртвый IP и висит до --max-time, не пробуя
# живые, а --retry переснимает тот же набор → закачка «то идёт, то нет» (лотерея, какой IP DNS
# отдал первым; замер: .110.133 мёртв, .108/.109/.111 живы). Решение — gh_get(): ЯВНО перебираем
# известные IP (--resolve) до первого живого + рубим «молчащее» соединение через --speed-time.
CURL_TIMEOUT=150
# Опции ОДНОЙ попытки. --speed-limit/--speed-time — главное: рубит соединение, которое
# подключилось, но отдаёт <4 КБ/с дольше 8с (мёртвый узел = 0 Б/с → обрыв за 8с). connect-timeout
# на случай реально недоступного узла. БЕЗ --retry: перебор IP делает gh_get сам (curl --retry
# переснял бы тот же набор и мог снова сесть на мёртвый IP).
CURL_OPTS="--connect-timeout 8 --speed-limit 4096 --speed-time 8 --max-time $CURL_TIMEOUT"
GH_RAW_HOST=raw.githubusercontent.com
GH_RAW_IPS="185.199.108.133 185.199.109.133 185.199.110.133 185.199.111.133"
# Хосты, на которые уезжает РЕДИРЕКТ за ассетом релиза (сам запрос идёт на github.com по DNS).
# Замерено: они резолвятся в ТЕ ЖЕ четыре anycast-адреса, что и raw, — значит и болезнь та же
# («узел подключился и молчит»), и лечится тем же списком. Имён два: GitHub отдаёт то одно, то
# другое; пиним оба, незадействованное просто не встретится.
GH_ASSET_HOSTS="release-assets.githubusercontent.com objects.githubusercontent.com"

# --- ЧТО ИМЕННО ОТВЕТИЛ GITHUB. Отдельный слой, потому что вопрос «почему не скачалось» имеет
# РАЗНЫЕ ответы с разными действиями человека, а раньше все они схлопывались в одну строку
# «не скачался (сеть/нет места?)». Поймано на железе AX3600 17.08.2026: raw.githubusercontent
# ответил 429 (ограничение по частоте — за день сделали десяток чистых установок с одного
# внешнего адреса), панель написала «Часть компонентов не установилась», и в логе не было НИ
# ОДНОГО намёка, что ждать надо минут десять, а не чинить сеть.
# Состояние держим В ФАЙЛЕ, а не в переменной: закачку fetch_bin гоняет в ФОНОВОЙ подоболочке
# (`gh_get … &` ради строк прогресса), а присваивание оттуда наружу не возвращается.
# ЛИЧНЫЙ РАБОЧИЙ КАТАЛОГ ПРОЦЕССА для мелких времянок (этот код ответа, суммы, пробы, сверка) — `mktemp -d`: 0700 и
# непредсказуемое имя. Прежние `/tmp/.enodia-gh-*.$$` угадывались по pid: процесс nobody (dnsmasq, пробы десинка) мог
# заранее положить туда СВОЙ файл сумм и переписать его после закачки (бинарь-подмена при «сумма сошлась») или симлинк,
# по которому root обрезал бы чужой файл (класс закрыт у подписи и пакета в ревью ветки pkg-update, круг 2; здесь — его
# соседи). Создаём СРАЗУ: закачку гоняет фоновая подоболочка, каталог обязан быть до неё. Убирает его конец файла, не
# trap (EXIT срабатывает и в фоновой подоболочке). Не создался — путь под /dev/null: любая запись туда откажет, и
# проверка, которой нужна времянка, откажет вместе с ней — предсказуемого имени нет.
GH_TMP=$(mktemp -d /tmp/enodia-gh.XXXXXX 2>/dev/null) || GH_TMP=""
[ -n "$GH_TMP" ] || GH_TMP=/dev/null/enodia-gh
GH_CODE_FILE="$GH_TMP/code"
gh_code_reset() { : > "$GH_CODE_FILE" 2>/dev/null; }
gh_code_note() {
    case "$1" in ''|000) return 0 ;; esac   # 000 = не соединились, это не ответ сервера
    # УСПЕШНЫЙ код причиной ОТКАЗА не бывает, а попасть сюда может: `--speed-time` рубит закачку,
    # которая началась (заголовок 200 уже пришёл) и замолчала на середине — curl отдаёт rc=28 и
    # http_code=200. Запиши мы его, и оборванный на полпути бинарь объяснялся бы человеку строкой
    # «GitHub ответил HTTP 200». Молчим — пусть говорит вызвавший («нет связи/нет места»).
    case "$1" in [123]??) return 0 ;; esac
    # Отказ ПО ЧАСТОТЕ старше прочих кодов: перебор anycast-IP и второго пути даёт после него
    # 404/000, и «последний увиденный код» затёр бы единственный, который что-то объясняет.
    case "$(cat "$GH_CODE_FILE" 2>/dev/null)" in 429|403) return 0 ;; esac
    printf '%s' "$1" > "$GH_CODE_FILE" 2>/dev/null
}
gh_code_get() { cat "$GH_CODE_FILE" 2>/dev/null; }
# Человеческая причина по коду; пусто = сказать нечего (обычный сетевой сбой, пусть говорит вызвавший).
gh_code_reason() {
    case "$1" in
        429) echo "GitHub ограничил скачивание с вашего внешнего адреса (HTTP 429, слишком много обращений) — подождите 10-15 минут и повторите" ;;
        403) echo "GitHub отказал в выдаче файла (HTTP 403) — как правило, то же ограничение по частоте; подождите и повторите" ;;
        404) echo "на GitHub нет файла по этому пути (HTTP 404)" ;;
        5??) echo "GitHub отвечает ошибкой $1 — это на его стороне, повторите позже" ;;
        ''|000) echo "" ;;
        *)   echo "GitHub ответил HTTP $1" ;;
    esac
}
# «Сеть жива, но качать не дадут» — вердикт, которого не обойти ни другим доверием TLS, ни
# десинком (внешний адрес тот же). Отдельный предикат, потому что спрашивают его ДВОЕ.
gh_code_refused() { case "$(gh_code_get)" in 429|403) return 0 ;; *) return 1 ;; esac; }

# --- ДОВЕРИЕ TLS НА СБОРКАХ, ГДЕ curl НЕ НАХОДИТ СИСТЕМНОГО ХРАНИЛИЩА -----------------------
# ЗАМЕРЕНО на AX3600 15.08.2026: ЛЮБОЙ `curl https://` падал rc=60 «unable to get local issuer
# certificate», хотя нужный корень в бандле ЕСТЬ и с `--cacert` на ЭТОТ ЖЕ файл всё проходит —
# curl собран с CApath, где нет хешированных симлинков. Цена: на таких прошивках канал обновления
# закрыт целиком (панель пишет «обновление недоступно», proto-install отказывается менять набор).
# Разбор и сам примитив — В `dns-lib.sh::curl_ca_opt`: вопрос «чем ЭТОМУ curl доверять» про
# РОУТЕР, а не про GitHub, и ответ на него в проекте ОДИН (им же ходит DoH-цикл). Здесь только
# шим: старая установка без свежей библиотеки обязана вести себя ровно как раньше, а не падать.
if [ -f "$ENODIA_DIR/dns-lib.sh" ]; then . "$ENODIA_DIR/dns-lib.sh"; fi
command -v curl_ca_opt >/dev/null 2>&1 || curl_ca_opt() { return 0; }

# Опция доверия для ЭТОГО роутера. Пусто = системного доверия хватает (обычный случай).
gh_ca_opt() { curl_ca_opt; }

# Выяснить рабочий бандл. Зовётся ТОЛЬКО после провала обычного пути; 0 = нашли (и запомнили).
# ПРОБА ОБЯЗАНА ХОДИТЬ ТЕМ ЖЕ ПУТЁМ, ЧТО И ЗАКАЧКА. Для raw.githubusercontent это `--resolve` на
# известный anycast-IP: сюда попадают ровно тогда, когда DNS роутера мёртв (бут, несущая не встала,
# upstream заперт в туннель) — а проба «по имени» в этот момент не дозвонится никуда, вернёт
# «не помогло» и (до фикса в curl_ca_opt) запомнила бы это на весь бут, закрыв канал обновления
# насовсем. Один IP достаточно: вопрос не «жив ли GitHub», а «чем доверять сертификату».
gh_ca_probe() {   # $1 = URL, на котором споткнулись
    case "$1" in
        https://$GH_RAW_HOST/*) _capr="--resolve $GH_RAW_HOST:443:${GH_RAW_IPS%% *}" ;;
        *) _capr="" ;;
    esac
    _cap=$(curl_ca_opt "$1" $_capr)
    [ -n "$_cap" ] || return 1
    log "TLS: системное хранилище curl пусто — доверяю системному бандлу"
    return 0
}

log() { printf '%s\n' "$*"; }

# Надёжно скачать $1 → $2. Для raw.githubusercontent перебираем известные anycast-IP по очереди
# (--resolve), останавливаемся на ПЕРВОМ живом; __dns__ в конце — фолбэк через обычный DNS (вдруг
# GitHub сменил IP). Прочие хосты — одиночная попытка. Код 0 = успех. НЕ печатает (фон/прогресс
# наружи — в fetch_bin).
# Круг попыток (все anycast-IP либо одиночный хост) с ЗАДАННОЙ опцией доверия. Код 60 от curl =
# «не проверить сертификат» — его отличаем от прочих, чтобы знать, есть ли смысл во втором круге.
# ВЕРДИКТ КРУГА — ПО ВСЕМ ПОПЫТКАМ, А НЕ ПО ПОСЛЕДНЕЙ. Попытки идут в порядке «anycast-IP …, потом
# __dns__ по имени», а зовут этот круг как раз при мёртвом DNS ⇒ последняя попытка штатно падает
# с rc=6 («не резолвится») и ЗАТИРАЛА бы код 60 от всех предыдущих. Итог был бы ровно тот, от
# которого фикс и заведён: на роутере со сломанным CApath второй круг по доверию не запускается
# никогда, канал обновления закрыт. Поэтому 60, увиденный ХОТЬ РАЗ, и есть вердикт круга.
# `-w %{http_code}` пишет В STDOUT, поэтому забираем его подстановкой, а не отпускаем наружу:
# gh_get зовут внутри `$( )`, и лишняя строка ушла бы в разбор ответа.
# Какие ИМЕНА пришпиливаем к перебираемому anycast-адресу. У raw это он сам; у ассета релиза —
# хосты РЕДИРЕКТА (запрос уходит на github.com по DNS, а файл отдают они). Пусто = хост нам
# незнаком, перебирать нечего, одна честная попытка.
gh_pin_hosts() {
    case "$1" in
        https://$GH_RAW_HOST/*) echo "$GH_RAW_HOST" ;;
        https://github.com/*)   echo "$GH_ASSET_HOSTS" ;;
        *)                      echo "" ;;
    esac
}
gh_get_round() {   # $1=url $2=out $3=опция доверия («» = системная)
    _gr=1; _g60=0
    _pin=$(gh_pin_hosts "$1")
    if [ -n "$_pin" ]; then
        for _ipx in $GH_RAW_IPS __dns__; do
            _res=""
            if [ "$_ipx" != __dns__ ]; then
                for _ph in $_pin; do _res="$_res --resolve $_ph:443:$_ipx"; done
            fi
            _c=$(curl -fsSL $CURL_OPTS $3 $_res -w '%{http_code}' -o "$2" "$1" 2>/dev/null); _gr=$?
            gh_code_note "$_c"
            [ "$_gr" = 0 ] && return 0
            [ "$_gr" = 60 ] && _g60=1
            # Отказ по частоте одинаков на ВСЕХ anycast-узлах (лимит на клиентский адрес, не
            # на узел) — перебирать остальные незачем, это только время на экране установки.
            gh_code_refused && break
            rm -f "$2"
        done
    else
        _c=$(curl -fsSL $CURL_OPTS $3 -w '%{http_code}' -o "$2" "$1" 2>/dev/null); _gr=$?
        gh_code_note "$_c"
        [ "$_gr" = 0 ] && return 0
        [ "$_gr" = 60 ] && _g60=1
    fi
    rm -f "$2"
    [ "$_g60" = 1 ] && return 60
    return "$_gr"
}
gh_get() {
    _ghu="$1"; _gho="$2"
    gh_code_reset          # вердикт — про ЭТОТ URL, а не про предыдущий
    _cao=$(gh_ca_opt)
    gh_get_round "$_ghu" "$_gho" "$_cao" && return 0
    _grc=$?
    # ВТОРОЙ КРУГ — только если споткнулись именно о ПРОВЕРКУ СЕРТИФИКАТА (60) и рабочий бандл
    # ещё не найден. На здоровом роутере сюда не заходят вовсе: там первый круг либо успешен,
    # либо провалился по другой причине (сеть, 404), и лишнего запроса не делается.
    if [ "$_grc" = 60 ] && [ -z "$_cao" ] && gh_ca_probe "$_ghu"; then
        _cao=$(gh_ca_opt)
        gh_get_round "$_ghu" "$_gho" "$_cao" && return 0
        # Вердикт ПЕРЕЗАПИСЫВАЕМ: дальше по коду решается, стоит ли будить десинк, а решает это
        # `_grc`. Оставь тут код ПЕРВОГО круга (60 = «сертификат не проверить») — и HTTP-ошибка,
        # полученная уже со здоровым бандлом, полетела бы в аварийный канал мимо отсечки ниже.
        _grc=$?
    fi
    # ТРЕТИЙ КРУГ — АВАРИЙНЫЙ КАНАЛ ЧЕРЕЗ ДЕСИНК (см. gh_socks_try). НО НЕ НА HTTP-ОШИБКЕ: `curl
    # -f` отдаёт 22 на 4xx/5xx, а это «сервер ответил», то есть сеть в порядке и десинку пробивать
    # нечего. Разница не теоретическая: `check` КАЖДЫЙ раз качает VERSION, которого в публичном
    # репо нет by design (404) — без этой отсечки любая проверка обновлений на любом роутере
    # поднимала бы ciadpi, ждала порт, повторяла запрос и получала тот же 404.
    [ "$_grc" = 22 ] && return 1
    # …и то же самое, когда вердикт круга затёрт кодом 60 от СОСЕДНЕГО узла (у одного не сошёлся
    # сертификат, другой ответил 429): решение принимает не `_grc`, а сам ответ GitHub.
    gh_code_refused && return 1
    gh_socks_round "$_ghu" "$_gho" "$_cao"
}

# --- АВАРИЙНЫЙ КАНАЛ: raw.github через локальный десинк (ciadpi) ------------------------------
# ЗАЧЕМ. Роутер теперь добирает ВСЕ протоколы сам, с GitHub — и упирается ровно в то, ради чего
# его и ставят: у части провайдеров raw.githubusercontent душится по SNI (соединение встаёт и
# молчит — тот самый случай, что рубит `--speed-time`). Раньше это лечилось заливкой бинарей с
# ПК; после реформы «ставим только панель» ПК из цепочки ушёл, и единственный оставшийся ответ —
# пробить блокировку тем, что уже лежит на роутере: ciadpi (0.13 МБ, кладётся вместе с панелью).
# Он тут НЕ транспорт: ни tun, ни правил, ни `.transport` — только socks на время закачки.
#
# Порядок кругов сознателен: сперва обычный путь (на здоровом провайдере он и работает), потом
# доверие, и лишь затем десинк. Обратный порядок гнал бы ВЕСЬ трафик обновлений через прокси,
# который на 176-МБ моделях стоит памяти, а на здоровой сети не нужен вовсе.
GH_SOCKS=""        # "" = ещё не пробовали · "-" = не вышло (второй раз не дёргаем) · адрес = есть
GH_SOCKS_MINE=0    # 1 = демон подняли МЫ и обязаны погасить
BYEDPI_SH="$ENODIA_DIR/transport-byedpi.sh"
gh_socks_try() {
    [ "$GH_SOCKS" = "-" ] && return 1
    [ -n "$GH_SOCKS" ] && return 0
    GH_SOCKS="-"
    [ -f "$BYEDPI_SH" ] || return 1
    # Код 2 = старая копия плагина не знает верба ⇒ канала нет, ведём себя как раньше.
    # Метка `$$` — наш pid для ref-счёта на стороне плагина: прокси РАЗДЕЛЯЕМЫЙ (нас могут
    # запустить в двух процессах сразу — «Обновить скрипты» и установка компонента), и без метки
    # закончивший первым гасил бы демона посреди чужой закачки. Старый плагин лишний аргумент
    # игнорирует, поэтому передаём его безусловно.
    _sa=$(sh "$BYEDPI_SH" socks-up "$$" 2>/dev/null | tail -n1 | tr -d ' \r')
    case "$_sa" in
        [0-9]*.[0-9]*.[0-9]*.[0-9]*:[0-9]*) : ;;
        *) return 1 ;;
    esac
    GH_SOCKS="$_sa"; GH_SOCKS_MINE=1
    log "GitHub напрямую не отвечает — пробую через локальный десинк ($GH_SOCKS)"
    return 0
}
# Гасим за собой ВСЕГДА: демон нужен ровно на время закачки, а на 176-МБ модели забытый ciadpi —
# это память, отнятая у несущей. Основную несущую byedpi (если она и была socks'ом) плагин не
# трогает — там свой пидфайл.
# СПРАШИВАЕМ ПЛАГИН ВСЕГДА, а не по своей переменной. `GH_SOCKS_MINE` живёт в ПАМЯТИ ТОГО шелла,
# который поднял прокси, — а поднимаем мы его сплошь и рядом внутри КОМАНДНОЙ ПОДСТАНОВКИ
# (`x=$(…)` в вербах-вопросах). Из `$( )` присваивание наружу не возвращается,
# родитель видит 0, ловушка молчит, и ciadpi переживает процесс — на 176-МБ моделях это память,
# отнятая у несущей, и висит она до ребута. Поймано на железе AX3600 15.08.2026: после `check`
# порт 10809 остался слушать. Состояние, которое ПЕРЕЖИВАЕТ подоболочку, — не переменная, а файл,
# и владеет им плагин; `$$` в `$( )` тот же, что у родителя, значит метка совпадает. Лишний вызов
# безвреден: `socks-down` считает пользователей и чужого демона не трогает.
gh_socks_release() {
    [ -f "$BYEDPI_SH" ] && sh "$BYEDPI_SH" socks-down "$$" >/dev/null 2>&1
    GH_SOCKS_MINE=0
}
# Ловушка, а не строка в конце: закачку бинаря панель гоняет в фоне и может оборвать (человек
# закрыл экран, `-K` из CGI), а брошенный ciadpi остался бы жить до ребута, отнимая память у
# несущей. На busybox EXIT-ловушка по сигналу НЕ срабатывает — её зовёт `exit` сигнальной; без него
# ловушка лишь гасила смерть, и закачка шла дальше без socks (C121).
# ФОНОВАЯ ЗАКАЧКА (fetch_bin_one) — ТОЖЕ в уборке выхода: сигнал теперь выходит (C121), а `curl` — внук, подоболочку gh_get
# переживает и докачивал бы в ОЗУ/на флеш уже ничей `.dl`. Потомков — ВСЕХ уровней (у socks-ветки `sh socks-up` — правнук) —
# собираем, ПОКА жив родитель: после его смерти их PPid = 1. `.dl` снимаем и без живого фона: файл лежит рядом с местом установки
# до самого `mv` (проверки размера, ELF и суммы — секунды), а это пик 20-МБ /data.
gh_bg_stop() {
    if [ -n "$GH_BGPID" ] && command -v proc_tree >/dev/null 2>&1; then   # the walk's owner — daemon-lib.sh
        kill $(proc_tree "$GH_BGPID") 2>/dev/null
    elif [ -n "$GH_BGPID" ]; then   # an older daemon-lib.sh without proc_tree: the former walk, byte for byte
        _gbk="$GH_BGPID"; _gbq="$GH_BGPID"
        while [ -n "$_gbq" ]; do
            _gbn=""
            for _gbp in $_gbq; do
                for _gbf in /proc/[0-9]*/status; do
                    grep -q "^PPid:[[:space:]]*$_gbp\$" "$_gbf" 2>/dev/null || continue
                    _gbc=${_gbf#/proc/}; _gbn="$_gbn ${_gbc%/status}"
                done
            done
            _gbk="$_gbk$_gbn"; _gbq=$_gbn
        done
        kill $_gbk 2>/dev/null
    fi
    [ -n "$GH_BGDL" ] && rm -f "$GH_BGDL" 2>/dev/null
    GH_BGPID=; GH_BGDL=
    return 0
}
gh_exit() { gh_bg_stop; gh_socks_release; }
trap 'gh_exit' EXIT
trap 'exit 1' INT TERM HUP PIPE
# ОДНА попытка через socks. `--resolve` здесь не нужен и не работает: имя резолвит прокси
# (--socks5-hostname), в этом половина смысла — DNS-путь тоже не наш.
gh_socks_round() {   # $1=url $2=out $3=опция доверия
    gh_socks_try || return 1
    curl -fsSL $CURL_OPTS $3 --socks5-hostname "$GH_SOCKS" -o "$2" "$1" 2>/dev/null && return 0
    rm -f "$2"
    return 1
}

# --- ДОСТИЖИМОСТЬ raw.githubusercontent (НЕ наличие файла). Для pre-check в proto-install:
#     цель — убедиться, что сетевой путь к GitHub жив ПЕРЕД сносом рабочего альта, а НЕ что
#     конкретный файл существует. Публичный репо может НЕ содержать пробный файл (напр. VERSION
#     туда не публикуется) → raw отдаёт HTTP 404, а `gh dl` c `curl -f` считал это «GitHub
#     недоступен» и блокировал смену набора (хотя bin/*.user на месте и качаются). Здесь
#     перебираем те же anycast-IP, но принимаем ЛЮБОЙ валидный HTTP-код (2xx/3xx/4xx/5xx) как
#     «сеть до GitHub жива»; только 000/пусто (нет коннекта) = недоступен. Пробный путь дешёвый
#     (тело отбрасываем в /dev/null), файл может и не существовать. Поймано на железе 2026-07-11.
#     ВТОРОЙ ПРОХОД ПО ДОВЕРИЮ (замерено на AX3600, разбор — в шапке gh_ca_probe): на сборках,
#     где curl не находит системного хранилища, КАЖДЫЙ IP отвечает `000` при живой сети, и проба
#     сообщала «GitHub недоступен» ВСЕГДА. Поэтому: не нашли путь обычным доверием — выясняем
#     рабочий бандл и пробуем ещё раз. Проверку сертификата НЕ отключаем (`-k` здесь больше нет):
#     раз проверяемый путь существует, пользоваться непроверяемым незачем.
#     ОТКАЗ ПО ЧАСТОТЕ — НЕ «доступен» (AX3600, 17.08.2026). Приняв ЛЮБОЙ код, проба зеленела на
#     429 «Too Many Requests»: пре-чек говорил «GitHub доступен», packages.sh шёл СНОСИТЬ старый
#     компонент, а закачка нового валилась на том же 429 — то есть ровно та авария («роутер без
#     транспорта»), ради которой пре-чек и написан. 429/403 значат «сеть до GitHub жива, но файла
#     он не даст», а вопрос здесь именно «дадут ли скачать».
gh_reach_round() {   # $1 = путь, $2 = опция доверия
    for _ipx in $GH_RAW_IPS __dns__; do
        if [ "$_ipx" = __dns__ ]; then _res=""; else _res="--resolve $GH_RAW_HOST:443:$_ipx"; fi
        _c=$(curl -s -o /dev/null -w '%{http_code}' $2 --connect-timeout 8 --max-time 12 $_res "$RAW/$1" 2>/dev/null)
        gh_code_note "$_c"
        case "$_c" in
            ''|000)  : ;;             # не соединились — пробуем следующий узел
            429|403) return 1 ;;      # лимит навешен на КЛИЕНТСКИЙ адрес ⇒ соседние узлы ответят тем же
            *)       return 0 ;;
        esac
    done
    return 1
}
# Печатает ПРИЧИНУ отказа в stdout (успех молчит): вызывающие — packages.sh/proto-install.sh —
# показывают её человеку вместо своего «GitHub недоступен», за которым он идёт чинить сеть.
gh_reachable() {
    _p="$1"
    _pgiven="$1"      # спрашивали КОНКРЕТНЫЙ путь? ниже `_p` уже подменён дефолтом VERSION
    gh_code_reset
    # ПРОБУЕМ ТОТ КАНАЛ, КОТОРЫМ ПОТОМ КАЧАЕМ — а качаем из папки `bin/` через raw (разбор
    # порядка в шапке файла). Значит первым спрашиваем raw, и только если он отшил ПО ЧАСТОТЕ —
    # второй канал: у ассетов другой хост и лимиты СВОИ. Обратный порядок стоил бы полного круга
    # на 404 при КАЖДОЙ проверке: ассетов в репозитории может не лежать вовсе, это норма.
    [ -n "$_p" ] || _p=VERSION
    gh_reach_round "$_p" "$(gh_ca_opt)" && return 0
    # Развилка. Ни второй круг (доверие TLS), ни третий (десинк) отказа ПО ЧАСТОТЕ не обойдут:
    # соединение состоялось, сертификат проверен, внешний адрес у десинка ТОТ ЖЕ. Поэтому при
    # 429/403 идём во второй канал, а круги доверия и десинка — только при ИНОМ отказе. Это не
    # осторожность, а экономия полуминуты на экране установки и честный текст вместо «недоступен».
    if gh_code_refused; then
        # Проба дешёвая: SHA256SUMS ассетом — 4 КБ, и это ровно тот путь (github.com → редирект).
        # Через gh_get, а не своим curl: у него перебор anycast-узлов и круг доверия — одиночный
        # запрос сел бы на молчащий узел и отчитался «канала нет».
        # Код raw ЗАПОМИНАЕМ и возвращаем при неудаче: иначе поверх «ограничил по частоте» ляжет
        # 404 от ненайденного ассета, и человек вместо «подождите 10-15 минут» прочтёт безликое
        # «GitHub недоступен» — то есть пойдёт чинить сеть.
        # ТОЛЬКО для общей пробы (`reachable` без аргумента): SHA256SUMS — это ДРУГОЙ файл, и
        # выдавать его доступность за доступность запрошенного пути нельзя. Спрашивали про
        # конкретный путь — про него и отвечаем, пусть даже отказом.
        _ru=$(rel_flat_url "$SUMS_REL")
        if [ -z "$_pgiven" ] && [ -n "$_ru" ]; then
            _rc=$(gh_code_get)
            _rt="$GH_TMP/reach"
            gh_get "$_ru" "$_rt"; _rr=$?
            rm -f "$_rt"
            [ "$_rr" = 0 ] && return 0
            gh_code_note "$_rc"
        fi
    else
        # рабочий бандл уже известен — значит дело не в доверии, но десинк попробовать ОБЯЗАНЫ
        if [ -z "$(gh_ca_opt)" ] && gh_ca_probe "$RAW/$_p"; then
            gh_reach_round "$_p" "$(gh_ca_opt)" && return 0
        fi
        # Аварийный канал спрашиваем и ЗДЕСЬ, а не только в закачке: `reachable` — это пре-чек, на
        # котором packages.sh/proto-install останавливаются ДО удаления и закачки. Отвечай он «нет»,
        # пока канал через десинк жив, — установка компонентов из панели была бы закрыта наглухо,
        # причём с формулировкой «GitHub недоступен», которая для человека означает «ждите».
        if gh_socks_try; then
            _c=$(curl -s -o /dev/null -w '%{http_code}' $(gh_ca_opt) --connect-timeout 8 --max-time 12 \
                 --socks5-hostname "$GH_SOCKS" "$RAW/$_p" 2>/dev/null)
            gh_code_note "$_c"
            case "$_c" in ''|000) : ;; 429|403) : ;; *) return 0 ;; esac
        fi
    fi
    _why=$(gh_code_reason "$(gh_code_get)")
    [ -n "$_why" ] || _why="GitHub недоступен — ни один канал не ответил"
    printf '%s\n' "$_why"
    return 1
}

# --- ELF-magic (7f 45 4c 46). printf '\177ELF' даёт ровно эти 4 байта. Без od/hexdump. ---
# Сверяем два РЕАЛЬНЫХ файла (не stdin '-' — busybox cmp с ним капризен). Если cmp нет
# или эталон не создать — НЕ блокируем (size-проверка в fetch_bin страхует от обрыва).
elf_ok() {
    f="$1"
    command -v cmp >/dev/null 2>&1 || return 0
    m="$GH_TMP/elfmagic"; t="$GH_TMP/elfhead"
    printf '\177ELF' > "$m" 2>/dev/null || { rm -f "$m" "$t"; return 0; }
    head -c 4 "$f" > "$t" 2>/dev/null
    cmp -s "$m" "$t"; rc=$?
    rm -f "$m" "$t"
    return $rc
}

# --- СУММЫ РЕПО (SHA256SUMS) — ТОЛЬКО ДЛЯ СВЕРКИ КОДА ПРЕЖНИХ УСТАНОВОК ---------------------------------
# Формат — coreutils: «<64hex>␠␠<репо-путь>» (на ПК/Linux его читает `sha256sum -c SHA256SUMS`). Суммы едут ТЕМ ЖЕ каналом, что и
# файлы, — это защита от битой закачки, не от подмены. Ставить по ним больше нечего: код едет подписанным пакетом, бинарь
# сверяется только с bin-manifest.txt из него. Верб `dl` (файл репо «по суммам репо», а без файла сумм — вовсе без сверки)
# снят вместе с verify_file и строгим режимом `.gh-strict` (ревью ветки релиза, круг 2): вызывателей не было, а открытая дверь
# клала бинарь мимо подписанного манифеста. Суммы репо читает только «Целостность» у кода, поставленного не пакетом.
# ЧЕМ СЧИТАЕМ: `sha256sum` на стоке Xiaomi НЕТ (busybox несёт только md5sum — замер на BE7000
# 30.07.2026), считает стоковый openssl 1.1.1l, который уже вендорится ради notify.sh/panel-tls/
# totp.sh. Цена незаметна: 8-МБ xray хешируется меньше секунды.
SUMS_REL=SHA256SUMS
SUMS_CACHE="$GH_TMP/sums"
SUMS_STATE=            # ''=ещё не пробовали · ok=скачали · no=в репо нет

# sha256 файла (64 hex) или пусто, если считать нечем. `openssl dgst` печатает «SHA256(f)= hex»
# — тот же разбор, что в totp.sh (одна идиома на проект).
file_sha256() {
    _fh=""
    if command -v sha256sum >/dev/null 2>&1; then _fh=$(sha256sum "$1" 2>/dev/null | awk '{print $1; exit}'); fi
    if [ "${#_fh}" != 64 ]; then _fh=$(openssl dgst -sha256 "$1" 2>/dev/null | sed 's/.*= *//' | awk '{print $1; exit}'); fi
    case "$_fh" in *[!0-9a-f]*) _fh="" ;; esac
    [ "${#_fh}" = 64 ] || _fh=""
    printf '%s\n' "$_fh"
}

# Скачать SHA256SUMS ОДИН раз на процесс. Всегда 0 — вердикт живёт в $SUMS_STATE.
# Канонический источник сумм — репо (оттуда же едет код), ассет релиза — РЕЗЕРВ. Без резерва
# мёртвый raw означал бы «бинарь по второму каналу скачали, а проверить нечем» — то есть
# установку без сверки ровно в той аварии, ради которой второй канал и заведён.
sums_load() {
    [ -z "$SUMS_STATE" ] || return 0
    SUMS_STATE=no
    for _su in "$RAW/$SUMS_REL" "$(rel_flat_url "$SUMS_REL")"; do
        [ -n "$_su" ] || continue
        if gh_get "$_su" "$SUMS_CACHE" && [ -s "$SUMS_CACHE" ]; then SUMS_STATE=ok; return 0; fi
        rm -f "$SUMS_CACHE"
    done
    return 0
}

# --- Арка роутера для выбора набора bin/<арка>/ на GitHub. --------------------------
# Бинари в репозитории разложены по аркам (bin/arm64/, bin/armv7/) — качать надо СВОЙ
# набор, иначе ENOEXEC и busybox печатает «syntax error» вместо версии (BE3600, лог
# тестера 2026-07-15). Опознаём по e_machine (байты 18-19 ELF) заведомо рабочего
# /bin/busybox, а НЕ по `uname -m`: при 64-битном ядре с 32-битным userspace uname
# говорит aarch64, но исполнять придётся armv7. Тот же критерий, что у гарда
# bin_arch_matches в install.sh. `od` в busybox НЕТ (грабля) → dd + cmp с
# эталоном из printf. Не опознали → пусто, fetch_bin уйдёт на легаси-путь (fail-open).
bin_arch() {
    [ -r /bin/busybox ] || return 0
    command -v dd >/dev/null 2>&1 || return 0
    command -v cmp >/dev/null 2>&1 || return 0
    _m="$GH_TMP/arch"
    dd if=/bin/busybox of="$_m" bs=1 skip=18 count=2 2>/dev/null || { rm -f "$_m"; return 0; }
    printf '\267\000' > "$_m.a64" 2>/dev/null   # 0xB7 0x00 = EM_AARCH64
    printf '\050\000' > "$_m.a32" 2>/dev/null   # 0x28 0x00 = EM_ARM
    _r=""
    if cmp -s "$_m" "$_m.a64"; then _r=arm64
    elif cmp -s "$_m" "$_m.a32"; then _r=armv7
    fi
    rm -f "$_m" "$_m.a64" "$_m.a32"
    echo "$_r"
}

# --- МАНИФЕСТ БИНАРЕЙ: сколько займёт, что за версия и КАКИЕ БАЙТЫ ставить -----------
# ЗАЧЕМ: «размер» и «версия» бинаря не были известны роутеру НИОТКУДА. Размеры жили хардкодом
# (need=$((need+8)) в proto-install, minsize в восьми вызовах fetch-bin) и врали при каждой
# пересборке, а версию нельзя было даже показать: UPX-сжатый бинарь её не отдаёт (`go version -m`
# на паке не работает, у amneziawg-go к тому же const Version не меняется между тегами). Панель
# à la carte обязана сказать «Hysteria2 v2.10.0, 4.55 МБ, после установки останется 0.5 МБ» ПЕРЕД
# тем, как что-то качать — отсюда bin-manifest.txt (генерит dev/build-bin-manifest.ps1).
# Формат — TSV «имя⇥арка⇥байты⇥версия⇥sha256» (пятая колонка — с 29.09.2026, ею `bin-status` судит «свежий ли стоящий»).
# ПОД ПОДПИСЬЮ (с 30.09.2026, решение пользователя). Манифест едет В ПОДПИСАННОМ ПАКЕТЕ КОДА (update-manifest.txt) и
# лежит в каталоге кода рядом с этим файлом — копии с GitHub больше нет. Прежде он качался из репо и сверялся по
# SHA256SUMS оттуда же: бинарь, который исполняет root, проверялся суммой, которую взявший аккаунт GitHub подменил бы
# вместе с ним, — при том что код уже был под подписью. Теперь подпись пакета покрывает и бинари: СУММА — только
# отсюда, БАЙТЫ — откуда угодно (каналы выше, загрузка с компьютера), и чужие не встанут ни одним путём. Цена —
# сборки ПРИВЯЗАНЫ К ВЕРСИИ КОДА: новая сборка бинаря приезжает с обновлением кода, а не сама по себе (код версии N
# знает, с какими бинарями он проверен). Отсюда же: манифест всегда под рукой, сеть за ним не нужна никогда, и
# «сверено с GitHub N назад» на экране «Компоненты» отмечать больше нечего.
BM_REL=bin-manifest.txt
BM_FILE="$ENODIA_DIR/$BM_REL"

# bm_field <имя> <3=байты|4=версия> [min|max] — поле из кэша для СВОЕЙ арки.
# Арку опознать не вышло (fail-open bin_arch) → берём крайнее значение по всем аркам, и какое
# именно — зависит от вопроса: «сколько займёт» = MAX (гард места должен ошибаться в запас),
# «порог обрыва закачки» = MIN (иначе 563-КБ armv7-сборка https-dns-proxy забракует законные
# 21 КБ arm64). Одна функция, режим параметром — двух копий разбора не заводим.
bm_field() {
    [ -s "$BM_FILE" ] || return 0
    # Арку спрашиваем ОДИН раз на срез (`bin_status` кладёт её в BA_VAL): опознание — это dd+cmp по busybox, а срез
    # зовёт bm_field дважды на КАЖДЫЙ бинарь. Присваивание из `$(…)` наружу не возвращается ⇒ память — в вызывающем.
    if [ "$BA_DONE" = 1 ]; then _bf_a=$BA_VAL; else _bf_a=$(bin_arch); fi
    awk -F'\t' -v n="$1" -v c="$2" -v a="$_bf_a" -v m="${3:-max}" '
        $1 != n { next }
        a != "" && $2 == a { print $c; found=1; exit }
        a == "" { s=$3+0
                  if (best=="" || (m=="max" && s>best) || (m=="min" && s<best)) { best=s; val=$c } }
        END { if (!found && best!="") print val }
    ' "$BM_FILE"
}

# Публичные хелперы (их же зовут proto-install.sh и панель через вербы bin-size/bin-ver).
bin_size() { _bs=$(bm_field "$1" 3 "${2:-max}"); case "$_bs" in ''|*[!0-9]*) _bs=0 ;; esac; echo "$_bs"; }
bin_ver()  { bm_field "$1" 4 max; }
# Тег релиза, из которого стоит код: TAG= пишет сборщик в VERSION пакета (dev/build-release.py). Пусто — код поставлен
# не пакетом релиза (рабочая копия, старый пакет): тогда бинари ищем только в ветке источника и в резерве.
local_tag() {
    # Снимаем только CR: пробел внутри — повод ОТКАЗАТЬ гардом формы, а не склеить «a b» в чужое, но законное «ab» (та же
    # ловушка, что у `.gh-repo` выше; поймал стенд, ревью ветки круг 1).
    _lt=$(sed -n 's/^TAG=//p' "$ENODIA_DIR/VERSION" 2>/dev/null | head -n 1 | tr -d '\r')
    case "$_lt" in ''|.*|*[!A-Za-z0-9._-]*) : ;; *) echo "$_lt" ;; esac
}

# --- СВЕЖ ЛИ СТОЯЩИЙ БИНАРЬ — БЕЗ СЕТИ (`bin-status`) ---------------------------------------------
# ЗАЧЕМ (29.09.2026): версию УСТАНОВЛЕННОГО бинаря не знал никто. `bin-ver` отвечает про ОПУБЛИКОВАННЫЙ, а обновление кода
# (пакет кода) бинарей не касается вовсе ⇒ исправленная сборка (dot-proxy 1.2: срок рукопожатия через VPS) доезжала до
# человека только снятием и повторной установкой компонента, о которой ему никто не говорил, — старый бинарь продолжал уводить
# DoT на DoH. «Какой стоит» ЗАПИСЬЮ ПРИ УСТАНОВКЕ не решается: бинарь кладут четыре дороги (движок компонентов, установщик с ПК
# `--push-bin`, переезд на накопитель, руки), и запись одной из них врала бы про остальные три. Судим ПО ФАКТУ: sha256 самого
# файла против пятой колонки манифеста (хеш опубликованного `bin/<арка>/<имя>.user`); манифест — под подписью пакета кода.
# ЦЕНА ФАКТА — чтение бинаря (замер BE7000 29.09.2026 с накопителя: все десять — 0.6 с, 8-МБ xray — 0.45 с; на флешке тестера
# с 448 КБ/с это десятки секунд) ⇒ хеш КЭШИРУЕМ по «путь + размер + mtime»: замена файла любой дорогой меняет хотя бы
# одно из них, и хеш считается заново — один раз. Закачка кладёт свой хеш сразу (`bs_seed`).
# INODE В КЛЮЧЕ НЕТ СОЗНАТЕЛЬНО (ревью ветки, круг 1): на exFAT/vfat номер inode выдаётся заново при каждой загрузке inode
# в память (iunique) — после ребута кэш промахивался бы на КАЖДОМ бинаре накопителя, и первый показ экрана перечитывал бы их
# все в синхронном CGI (флешка тестера — 448 КБ/с, ~30 с). Цена — подмена ДРУГОЙ сборкой того же размера в ту же секунду
# мимо закачки (своя закачка сеет хеш сама); у UPX-сборок разных версий размер практически всегда разный.
# ВЕРСИЯ СТОЯЩЕГО — та, чей хеш хоть раз совпал с манифестом (запоминаем её рядом с хешем): после выхода новой сборки манифест
# про старую молчит, а человеку надо сказать «стоит A, доступна B», а не «стоит ?».
# «РАБОТАЕТ ЛИ ПРЕЖНЯЯ» — тоже по факту: замена файла под живым демоном его НЕ перезапускает (он исполняет старый inode, и
# `/proc/<pid>/exe` показывает путь с « (deleted)» — замер BE7000 29.09.2026, у UPX-бинаря так же). Переезд на накопитель даёт тот
# же « (deleted)» при ТОЙ ЖЕ сборке ⇒ сверяем содержимое: размер (у разных сборок он почти всегда разный), при равном — хеш через
# сам `/proc/<pid>/exe` (удалённый inode читается).
# Кэш — в $ENODIA_STATE (переживает обновление кода); пишем ТОЛЬКО при изменении — /data смонтирован sync.
BS_CACHE="$ENODIA_STATE/.bin-sha"
# Ключ файла «размер mtime»; пусто — файла нет. Путь — отдельным полем строки кэша.
bs_key() { stat -c '%s %Y' "$1" 2>/dev/null; }
# Строка кэша: имя⇥путь⇥ключ⇥sha⇥версия — ОДНА на имя (путь у бинаря один, его даёт bin_path). Атомарно, рядом + `mv`.
bs_put() {
    _bpt="$BS_CACHE.$$.new"   # хвост .new — под маской мусора clean.sh (оборванная запись не копится)
    if { [ -f "$BS_CACHE" ] && awk -F'\t' -v n="$1" '$1 != n' "$BS_CACHE"; printf '%s\t%s\t%s\t%s\t%s\n' "$1" "$2" "$3" "$4" "$5"; } > "$_bpt" 2>/dev/null; then
        mv -f "$_bpt" "$BS_CACHE" 2>/dev/null || rm -f "$_bpt" 2>/dev/null
    else rm -f "$_bpt" 2>/dev/null; fi
    return 0
}
# sha256 стоящего файла: из кэша, если ключ тот же, иначе считаем и запоминаем. Версию при НОВОМ содержимом забываем, а при
# том же хеше (сменился только ключ: переезд на накопитель, сдвиг mtime) — держим: иначе «стоит A» пропадало бы на ровном месте.
bs_sha() {   # $1 = имя, $2 = путь
    _bk=$(bs_key "$2"); [ -n "$_bk" ] || return 0
    _bh=$(awk -F'\t' -v n="$1" -v p="$2" -v k="$_bk" '$1 == n && $2 == p && $3 == k && length($4) == 64 { print $4; exit }' "$BS_CACHE" 2>/dev/null)
    if [ -z "$_bh" ]; then
        _bh=$(file_sha256 "$2"); [ -n "$_bh" ] || return 0
        bs_put "$1" "$2" "$_bk" "$_bh" "$(bs_ver_known "$1" "$_bh")"
    fi
    printf '%s\n' "$_bh"
}
# Версия, запомненная при ЭТОМ хеше (пусто — не знаем).
bs_ver_known() { awk -F'\t' -v n="$1" -v h="$2" '$1 == n && $4 == h { print $5; exit }' "$BS_CACHE" 2>/dev/null; }
# Запомнить версию при хеше — только если она изменилась (иначе каждый показ экрана писал бы флеш).
bs_ver_note() {   # $1 = имя, $2 = путь, $3 = sha, $4 = версия
    [ "$(bs_ver_known "$1" "$3")" = "$4" ] && return 0
    bs_put "$1" "$2" "$(bs_key "$2")" "$3" "$4"
}
# Версия опубликованной сборки с ЭТИМ хешем — своей арки (чужая арка у нас не исполнится); арка не опознана — любой.
bm_ver_of() {   # $1 = имя, $2 = sha
    [ -s "$BM_FILE" ] || return 0
    awk -F'\t' -v n="$1" -v h="$2" -v a="$BA_VAL" '$1 == n && $5 == h && $4 != "" && (a == "" || $2 == a) { print $4; exit }' "$BM_FILE"
}
# Где лежат бинари — у владельца ответа (store-lib.sh::bin_path), ОДНИМ заходом в библиотеку на весь срез: «имя путь» построчно.
bs_paths() {
    if [ -f "$ENODIA_DIR/store-lib.sh" ]; then
        ( . "$ENODIA_DIR/store-lib.sh" >/dev/null 2>&1; for _n in "$@"; do printf '%s %s\n' "$_n" "$(bin_path "$_n")"; done )
    else for _n in "$@"; do printf '%s %s\n' "$_n" "$ENODIA_BIN/$_n"; done; fi
}
# 0 = живой процесс исполняет ДРУГУЮ сборку этого бинаря (файл заменили под ним). Список — из $BS_DEL.
# «Та же сборка» по хешу удалённого exe запоминаем В ОЗУ (`$BS_RUN_SAME`, ключ «pid размер mtime + sha стоящего»): после переезда
# на накопитель демон работает с удалённого файла до перезапуска, и без памяти КАЖДЫЙ показ экрана и каждый клик плана заново
# читал 8 МБ xray на каждый экземпляр (ревью ветки, круг 2). Ключ с pid — перезапуск даёт новый; файл гибнет с ребутом.
BS_RUN_SAME=/tmp/enodia-bin-run.same
# The pids themselves (one per line), not just "is there one": the restart in Components has to know WHICH processes, so it can
# hand each to its owner (packages.sh::rst_unit). One loop serves both answers, so "flagged stale" and "restarted" can't disagree.
bs_stale_pids() {   # $1 = имя, $2 = путь стоящего, $3 = его sha
    [ -n "$BS_DEL" ] || return 0
    _brs=$(stat -c %s "$2" 2>/dev/null)
    printf '%s\n' "$BS_DEL" | while read -r _bpid _bpath; do
        [ "${_bpath##*/}" = "$1" ] || continue
        _bps=$(stat -L -c '%s %Y' "/proc/$_bpid/exe" 2>/dev/null) || continue
        [ "${_bps% *}" = "$_brs" ] || { echo "$_bpid"; continue; }
        _brk="$_bpid $_bps $3"
        grep -qxF "$_brk" "$BS_RUN_SAME" 2>/dev/null && continue
        if [ "$(file_sha256 "/proc/$_bpid/exe")" = "$3" ]; then echo "$_brk" >> "$BS_RUN_SAME" 2>/dev/null; else echo "$_bpid"; fi
    done
    return 0
}
bs_run_old() { [ -n "$(bs_stale_pids "$1" "$2" "$3" | head -n 1)" ]; }
# bin-status [имя…] — строка на бинарь: имя⇥состояние⇥стоит⇥доступна⇥работает.
#   состояние: absent (файла нет) · current (хеш совпал с опубликованной сборкой своей арки) · outdated (манифест знает хеш
#   своей арки, и он другой — новая сборка приехала с обновлением кода) · unknown (сверять не с чем: в коде нет манифеста);
#   стоит — версия стоящего, если её удалось узнать; доступна — версия в манифесте; работает — `old`, когда живой процесс
#   исполняет сборку, которую уже заменили. Без имён — все бинари манифеста.
# В СЕТЬ НЕ ХОДИТ: манифест лежит в каталоге кода (его зовут синхронно экран «Компоненты», план движка и дамп).
bm_names() { [ -s "$BM_FILE" ] && awk -F'\t' '$1 !~ /^#/ && NF >= 4 { print $1 }' "$BM_FILE" | sort -u; }
bs_pick() { printf '%s\n' "$_bsp" | awk -v n="$1" '$1 == n { sub(/^[^ ]* /, ""); print; exit }'; }   # из bs_paths — путь имени $1
bin_status() {
    BA_VAL=$(bin_arch); BA_DONE=1
    BS_DEL=$(exe_deleted)   # процессы, исполняющие удалённый файл, — у владельца (daemon-lib.sh; сорсится ниже, до разбора вербов)
    _bsn="$*"
    [ -n "$_bsn" ] || _bsn=$(bm_names)
    _bsp=$(bs_paths $_bsn)
    for _n in $_bsn; do
        _p=$(bs_pick "$_n")
        _av=$(bm_field "$_n" 4 max)
        if [ -z "$_p" ] || [ ! -f "$_p" ]; then printf '%s\tabsent\t\t%s\t\n' "$_n" "$_av"; continue; fi
        _h=$(bs_sha "$_n" "$_p"); _st=unknown; _cv=""; _run=""
        if [ -n "$_h" ]; then
            _cv=$(bm_ver_of "$_n" "$_h")
            if [ -n "$_cv" ]; then
                _st=current; bs_ver_note "$_n" "$_p" "$_h" "$_cv"
            else
                _cv=$(bs_ver_known "$_n" "$_h")
                _bx=$(bm_field "$_n" 5 max); [ "${#_bx}" = 64 ] && _st=outdated
            fi
            bs_run_old "$_n" "$_p" "$_h" && _run=old
        fi
        printf '%s\t%s\t%s\t%s\t%s\n' "$_n" "$_st" "$_cv" "$_av" "$_run"
    done
    return 0
}
# bin-stale [имя…] — WHO runs a replaced build: one line `pid⇥имя` per process. Same judgement as bin-status's `old` (bs_stale_pids),
# for the restart in Components. Empty output = nothing to restart. No network, like bin-status.
bin_stale() {
    BS_DEL=$(exe_deleted)
    [ -n "$BS_DEL" ] || return 0
    _bsn="$*"
    [ -n "$_bsn" ] || _bsn=$(bm_names)
    _bsp=$(bs_paths $_bsn)
    for _n in $_bsn; do
        _p=$(bs_pick "$_n")
        [ -n "$_p" ] && [ -f "$_p" ] || continue
        _h=$(bs_sha "$_n" "$_p"); [ -n "$_h" ] || continue
        bs_stale_pids "$_n" "$_p" "$_h" | while read -r _sp; do printf '%s\t%s\n' "$_sp" "$_n"; done
    done
    return 0
}
# Закачка кладёт хеш того, что положила, сразу: следующему показу экрана читать восемь мегабайт заново незачем. Версию — только
# если хеш совпал с манифестом ЭТОЙ арки (иначе молчим: «стоит ?» честнее выдуманного).
bs_seed() {   # $1 = имя, $2 = куда легло, $3 = путь по репо (bin/<арка>/<имя>.user), [$4 = хеш, уже посчитанный сверкой]
    _bsh=$4; [ -n "$_bsh" ] || _bsh=$(file_sha256 "$2"); [ -n "$_bsh" ] || return 0
    _bsa=""; case "$3" in bin/*/*) _bsa=${3#bin/}; _bsa=${_bsa%%/*} ;; esac
    _bsv=""; [ -s "$BM_FILE" ] && _bsv=$(awk -F'\t' -v n="$1" -v h="$_bsh" -v a="$_bsa" '$1 == n && $5 == h && $4 != "" && (a == "" || $2 == a) { print $4; exit }' "$BM_FILE")
    bs_put "$1" "$2" "$(bs_key "$2")" "$_bsh" "$_bsv"
}

# --- Скачать бинарь bin/<арка>/<name>.user в dst (рабочее имя без .user) с проверкой.
#     fetch-bin <name> <dst> [minsize]. Используется packages.sh, proto-install.sh, zapret.sh.
#     ЯКОРЬ — строка СВОЕЙ арки в подписанном манифесте (размер + sha256, разбор у BM_FILE): её нет — не ставим ничего,
#     ни скачанного, ни загруженного. minsize можно не передавать: размер своей сборки — из той же строки (FB_SIZE), и
#     файл ДРУГОГО размера, скачанный целиком, — другая сборка, а не обрыв (обрыв curl отдаёт кодом ≠ 0).
#     КАНАЛЫ — по очереди (bin_srcs). Сборка по адресу не та — это не подмена и не повод стоп: на ветке к следующему
#     релизу лежит уже другая сборка, а верную держит тег. Не сошлось нигде — «на GitHub другая сборка, обновите систему».
# URL каналов построчно, без повторов (тег может совпасть с $GH_REF при пришпиленном `.gh-ref`).
bin_srcs() {
    _bst=$(local_tag)
    { [ -n "$_bst" ] && echo "https://raw.githubusercontent.com/$REPO/$_bst/$1"
      echo "$RAW/$1"
      bin_asset_url "$1"; } | awk 'NF && !s[$0]++'
}
fetch_bin() {
    name="$1"; dst="$2"; minsz="$3"
    case "$minsz" in ''|*[!0-9]*|0) minsz="" ;; esac
    # Файл, загруженный с компьютера (bin-stage), — первым: человек положил его именно потому, что GitHub недоступен. Затем — скачанный
    # заранее движком (bin-prefetch). Чужой каталог — мимо, не трогая его файлов (разбор у bstage_ok). Закачка заранее сама локальные
    # источники не спрашивает (FB_NOLOCAL).
    if [ "$FB_NOLOCAL" != 1 ]; then
        if bstage_ok && [ -f "$BIN_STAGE/$name" ] && fetch_bin_staged "$name" "$dst"; then return 0; fi
        if bstage_ok "$BIN_PREFETCH" && [ -f "$BIN_PREFETCH/$name" ] && fetch_bin_staged "$name" "$dst" "$BIN_PREFETCH"; then return 0; fi
    fi
    BA_VAL=$(bin_arch); BA_DONE=1
    if [ -z "$BA_VAL" ]; then log "[fetch-bin] FAIL: архитектуру роутера опознать не вышло — какую сборку $name ставить, неизвестно"; return 1; fi
    _fbl=$(bm_line "$name"); FB_WANT=${_fbl#* }; FB_SIZE=${_fbl%% *}
    if [ "${#FB_WANT}" != 64 ]; then
        if [ -s "$BM_FILE" ]; then log "[fetch-bin] FAIL: «$name» ($BA_VAL) нет в манифесте бинарей установленной версии — ставить нечего"
        else log "[fetch-bin] FAIL: в установленном коде нет манифеста бинарей ($BM_REL) — сверить сборку не с чем; обновите систему"; fi
        return 1
    fi
    case "$FB_SIZE" in ''|*[!0-9]*) FB_SIZE="" ;; esac
    _rel="bin/$BA_VAL/$name.user"
    # ИТОГ — ПЕРВАЯ причина, которая не «файла нет» (404) и не «другая сборка»: поверх настоящего «накопитель без exec» или
    # «не ELF» последней строкой FAIL (её берут движок компонентов и Zapret) выходило бы «на GitHub нет файла по этому пути» от
    # резервного канала (ревью шага 6c, круг 3). И только ДО первой «другой сборки»: адрес с другой сборкой уже сказал, что GitHub
    # жив и файл там есть, — сбой следующего канала (сеть, 429 резерва) перебил бы честное «обновите систему» (ревью ветки, круг 1).
    _fbw=""; _fbo=0; _bref=0; _brc=
    for _bsrc in $(bin_srcs "$_rel"); do
        if fetch_bin_one "$_bsrc" "$_rel" "$name" "$dst" "$minsz"; then return 0; fi
        [ "$FB_OTHER" = 1 ] && _fbo=1
        [ "$_fbo" = 1 ] && continue
        [ "$FB_404" = 1 ] || [ -n "$_fbw" ] || _fbw=$FB_WHY
        gh_code_refused && { _bref=1; _brc=$(gh_code_get); }
    done
    # Отказ ПО ЧАСТОТЕ (429/403) хотя бы от одного канала — главная причина: судим по ЛЮБОМУ каналу, а не по последнему
    # (последний может ответить 404 — ассет не залит — и «нас отшили» потерялось бы). Код отказа ВОЗВРАЩАЕМ: иначе поверх 429
    # остаётся 404 от ненайденного ассета, и первый же, кто покажет человеку gh_code_reason, отправит его чинить не то.
    if [ "$_bref" = 1 ]; then [ -n "$_brc" ] && gh_code_note "$_brc"; log "[fetch-bin] FAIL: не скачался $name — $(gh_code_reason "$_brc")"; return 1; fi
    if [ -n "$_fbw" ]; then log "[fetch-bin] FAIL: $_fbw"
    # Дорога — та, что есть ВСЕГДА (ревью ветки, круг 2): экран «Обновление» бывает скрыт (канал заморожен), а файл из архива
    # установщика ЭТОЙ версии — ровно та сборка, что знает её манифест.
    elif [ "$_fbo" = 1 ]; then _fbv=$(local_name); log "[fetch-bin] FAIL: на GitHub лежит другая сборка $name, чем та, что знает установленная версия — обновите систему или загрузите bin/$BA_VAL/$name.user из архива установщика${_fbv:+ $_fbv} («Файлы с компьютера»)"
    else log "[fetch-bin] FAIL: на GitHub нет $_rel ни на теге релиза, ни в ветке $GH_REF"; fi
    return 1
}

# --- ЗАГРУЗКА БИНАРЯ С КОМПЬЮТЕРА: установка без доступа к GitHub (решение пользователя 30.09.2026) --------------------------
# Человек с закрытым GitHub (или архивом проекта из Telegram/флешки) кладёт бинарь из архива (`bin/<арка>/<имя>.user`) через
# панель. Меняется ТОЛЬКО ИСТОЧНИК файла: ставит его тот же движок компонентов тем же fetch_bin, в то же место и с теми же
# проверками. ЯКОРЬ ДОВЕРИЯ — тот же подписанный манифест из пакета кода (BM_FILE): размер и sha256 сборки своей арки. Без
# суммы в манифесте загрузку не принимаем вовсе: «что-то исполняемое мимо сверки» — ровно то, от чего сверка заведена.
# ХРАНИЛИЩЕ — /tmp (ОЗУ: 8-МБ xray не должен ложиться на 20-МБ флеш дважды), каталог СВОЙ (наш uid, 0700, не симлинк). Он в
# общем /tmp, и процесс nobody мог бы завести его заранее и подменить файл после приёма ⇒ чужой каталог сносим и заводим
# заново, а fetch_bin сверяет ЕЩЁ РАЗ свою копию, уже лёгшую рядом с местом установки, а не файл в /tmp. До ребута: принятый,
# но не поставленный файл живёт в ОЗУ, пока его не заберёт установка (или ребут).
BIN_STAGE=/tmp/enodia-bin-stage
# ЗАКАЧКА ЗАРАНЕЕ (решение пользователя 01.10.2026): движок компонентов сперва кладёт СЮДА всё, что качает план, и лишь потом снимает
# и ставит — не скачалось хоть что-то ⇒ не тронуто ничего. Прежде снятия шли ДО закачки, а пре-чек спрашивал только сеть: «на GitHub
# другая сборка» (нет тега, чужой .gh-repo, дев-код) оставляла без обоих компонентов. Каталог — ОТДЕЛЬНЫЙ от загрузок с компьютера:
# перечень `bin-staged` (панель: «загружено с компьютера») его не видит; гарды — те же (bstage_ok/bstage_dir с каталогом аргументом),
# а установка сверяет копию с манифестом ещё раз — тем же fetch_bin_staged.
BIN_PREFETCH=/tmp/enodia-bin-prefetch
# «Каталог наш» (наш uid, 0700, не симлинк) — ТОЛЬКО ЧИТАЕТ, и спрашивают его ВСЕ потребители. Для перечня и установки чужой
# каталог = «ничего не загружено»: его файлы не в счёт и не трогаются. Прежде проверял только приём, и симлинк хранилища на каталог
# бинарей превращал установочное «не сошлось — убрать из хранилища» в удаление СТОЯЩЕГО бинаря (ревью с.88, подтверждено песочницей).
bstage_ok() {   # [$1 = каталог; по умолчанию — хранилище загрузок с компьютера]
    _bsd=${1:-$BIN_STAGE}; _bsd_me="$(id -u 2>/dev/null) 700"
    [ -d "$_bsd" ] && [ ! -L "$_bsd" ] && [ "$(stat -c '%u %a' "$_bsd" 2>/dev/null)" = "$_bsd_me" ]
}
# Приём: свой каталог. Чужой — НЕ СНОСИМ, а отодвигаем переименованием: `rm -rf` обходит дерево (lstat, потом opendir), и процесс
# nobody, подменив вложенный каталог симлинком в этом окне, увёл бы root сносить чужое, например настройки (ревью с.88, круг 2). `mv`
# дерево не обходит (симлинк переименовывается сам, цель не тронута); отодвинутое — мусор чужого процесса в /tmp, уйдёт с ребутом.
# КУДА отодвигать — в СВЕЖИЙ `mktemp -d` (0700, имя непредсказуемо), а не на имя `…foreign.<pid>` (ревью порции «закачка заранее»,
# находка 4): то имя nobody мог заготовить симлинком на каталог root, и `mv` положил бы его подложенный файл ВНУТРЬ цели (web/cgi-bin,
# hotplug) — а с закачкой заранее через этот гард идёт КАЖДАЯ установка компонента.
bstage_dir() {   # [$1 = каталог]
    _bdd=${1:-$BIN_STAGE}
    bstage_ok "$_bdd" && return 0
    if [ -e "$_bdd" ] || [ -L "$_bdd" ]; then
        _bdq=$(mktemp -d /tmp/enodia-foreign.XXXXXX 2>/dev/null) || return 1
        mv -f "$_bdd" "$_bdq/" 2>/dev/null || return 1
    fi
    mkdir -m 700 "$_bdd" 2>/dev/null
    bstage_ok "$_bdd"
}
# «байты sha256» опубликованной сборки СВОЕЙ арки (пусто — строки нет или арка не опознана: чужую арку не подставляем, она у нас
# не исполнится). Сеть не нужна — манифест лежит в каталоге кода.
bm_line() {
    [ -s "$BM_FILE" ] || return 0
    if [ "$BA_DONE" = 1 ]; then _bla=$BA_VAL; else _bla=$(bin_arch); fi
    [ -n "$_bla" ] || return 0
    awk -F'\t' -v n="$1" -v a="$_bla" '$1 == n && $2 == a { print $3 " " $5; exit }' "$BM_FILE"
}
# bin-stage <имя> <файл> — принять загруженный файл. 0 + «OK: …» — лёг в хранилище; 1 + «FAIL: причина». Источник — времянка
# вызывающего (CGI), убираем её в обоих исходах. Причину называем ПО ДЕЛУ: чужая арка, оборванный файл, чужой файл — у каждой
# своё действие человека.
cmd_bin_stage() {
    _sn="$1"; _sf="$2"
    case "$_sn" in ''|*[!a-z0-9-]*) rm -f "$_sf"; echo "FAIL: имя компонента не по форме"; return 1 ;; esac
    [ -f "$_sf" ] || { echo "FAIL: файл не получен"; return 1; }
    bstage_dir || { rm -f "$_sf"; echo "FAIL: не завести своё хранилище в /tmp (место в ОЗУ?)"; return 1; }
    _sl=$(bm_line "$_sn")
    if [ -z "$_sl" ]; then
        rm -f "$_sf"; echo "FAIL: «$_sn» нет в манифесте бинарей для этого роутера — это не файл проекта (или архитектура роутера не опознана)"; return 1
    fi
    _ssz=${_sl%% *}; _ssh=${_sl#* }
    if [ "${#_ssh}" != 64 ]; then
        rm -f "$_sf"; echo "FAIL: в манифесте нет суммы «$_sn» — проверить файл нечем (обновите систему)"; return 1
    fi
    _sgot=$(stat -c %s "$_sf" 2>/dev/null)
    _sh=$(file_sha256 "$_sf")
    if [ -z "$_sh" ]; then rm -f "$_sf"; echo "FAIL: нечем посчитать sha256 (нет openssl)"; return 1; fi
    if [ "$_sh" != "$_ssh" ]; then
        _soa=$(awk -F'\t' -v n="$_sn" -v h="$_sh" '$1 == n && $5 == h { print $2; exit }' "$BM_FILE" 2>/dev/null)
        rm -f "$_sf"
        # Самый частый случай с подписанным манифестом — файл из архива ДРУГОЙ версии (ревью ветки, круг 1): называем версию,
        # которую знает стоящий код, — её архив и нужен.
        if [ -n "$_soa" ]; then echo "FAIL: это «$_sn» для другой архитектуры ($_soa), а роутеру нужна $(bin_arch) — возьмите bin/$(bin_arch)/$_sn.user"
        else _slv=$(local_name); echo "FAIL: это не та сборка «$_sn», что знает установленная версия${_slv:+ $_slv} — файл из архива другой версии или оборван (у своей $_ssz байт, у этого $_sgot); возьмите bin/$(bin_arch)/$_sn.user из архива${_slv:+ $_slv}"; fi
        return 1
    fi
    # Уже стоит ЭТА сборка — принимать нечего: перечень убрал бы файл тут же, а «принят — его поставит установка» было бы неправдой
    # (ревью с.88, круг 2). Хеш стоящего — из кэша bin-status (bs_sha), тот же ответ, что у перечня.
    _sp=$(bs_paths "$_sn" | cut -d' ' -f2-)
    if [ -f "$_sp" ] && [ "$(bs_sha "$_sn" "$_sp")" = "$_ssh" ]; then
        rm -f "$_sf"; echo "FAIL: «$_sn» $(bm_field "$_sn" 4 max) уже стоит — загружать не нужно"; return 1
    fi
    # Сумма принятого — рядом, ДО самого файла (перечень видит файл только вместе с ней): по ней bin-staged дёшево, без чтения
    # мегабайт, узнаёт, что манифест с тех пор сменился и файл уже не та сборка.
    { printf '%s\n' "$_sh" > "$BIN_STAGE/$_sn.sha" && mv -f "$_sf" "$BIN_STAGE/$_sn"; } 2>/dev/null || {
        rm -f "$_sf" "$BIN_STAGE/$_sn.sha"; echo "FAIL: не положить файл в хранилище"; return 1; }
    echo "OK: $_sn $(bm_field "$_sn" 4 max) принят — его поставит установка компонента"
}
# Что принято и ЕЩЁ НУЖНО — имена построчно. Движок решает по ним, спрашивать ли GitHub (ДО удалений), панель — что загружено. Отсюда
# два фильтра, оба дешёвые: (1) сумма, записанная при приёме, равна сумме СЕГОДНЯШНЕГО манифеста — иначе он сменился (переустановка
# с ПК, «Проверить»), файл уже не та сборка, и движок пропустил бы проверку сети, снял бы старое и не поставил новое; (2) стоящий
# бинарь — не эта же сборка (хеш — из кэша bin-status): такой файл установка не заберёт никогда, а панель обещала бы «поставит
# „Применить“». Не прошедший фильтр убираем — он в ОЗУ и больше не пригодится. Чужой каталог — пусто (разбор у bstage_ok).
cmd_bin_staged() {
    bstage_ok || return 0
    BA_VAL=$(bin_arch); BA_DONE=1
    for _bf in "$BIN_STAGE"/*; do
        [ -f "$_bf" ] || continue
        _bn=${_bf##*/}
        case "$_bn" in ''|*[!a-z0-9-]*) continue ;; esac
        _bl=$(bm_line "$_bn"); _bm=${_bl#* }
        if [ "${#_bm}" != 64 ] || [ "$(cat "$_bf.sha" 2>/dev/null)" != "$_bm" ]; then rm -f "$_bf" "$_bf.sha"; continue; fi
        _bp=$(bs_paths "$_bn" | cut -d' ' -f2-)
        if [ -f "$_bp" ] && [ "$(bs_sha "$_bn" "$_bp")" = "$_bm" ]; then rm -f "$_bf" "$_bf.sha"; continue; fi
        echo "$_bn"
    done
    return 0
}
# Убрать всё принятое (кнопка панели «Убрать»): принятое живёт в ОЗУ до установки или ребута, и панель, показав «загружено», обязана
# уметь это снять — не заводим того, чего сами не снимем (ревью с.88, круг 2). Чужой каталог не трогаем (разбор у bstage_ok).
# С аргументом — тот же разбор для другого своего каталога (скачанное заранее: движок снимает его в начале операции и ловушкой выхода).
cmd_bin_unstage() {   # [$1 = каталог]
    _bud=${1:-$BIN_STAGE}
    bstage_ok "$_bud" || return 0
    for _bf in "$_bud"/*; do if [ -f "$_bf" ]; then rm -f "$_bf"; fi; done
    return 0
}
# bin-prefetch <имя> — скачать заранее в ОЗУ (разбор у BIN_PREFETCH): тот же fetch_bin с той же сверкой по подписанному манифесту, но
# в свой каталог, МИМО локальных источников (иначе он взял бы файл из самого этого каталога — перенос в себя кончается `rm` исходника)
# и без записи в кэш хеша (кэш — про файл на месте установки; его посеет установка из скачанного). Итог — последней строкой FAIL, как
# у закачки: её поднимает движок.
cmd_bin_prefetch() {
    case "$1" in ''|*[!a-z0-9-]*) log "[fetch-bin] FAIL: имя компонента не по форме"; return 1 ;; esac
    bstage_dir "$BIN_PREFETCH" || { log "[fetch-bin] FAIL: не завести каталог для закачки заранее в /tmp (место в ОЗУ?)"; return 1; }
    rm -f "$BIN_PREFETCH/$1"
    FB_NOLOCAL=1; FB_NOSEED=1
    fetch_bin "$1" "$BIN_PREFETCH/$1" ""
}
# Загруженный файл — ВМЕСТО СЕТИ. Сверяем СВОЮ копию (уже рядом с местом установки) с манифестом: файл в общем /tmp мог смениться
# после приёма. Прочее — как у закачки: ELF, право на исполнение, кэш хеша. Не сошлось — файл из хранилища убираем (второй раз он
# не сойдётся) и отдаём слово закачке с GitHub.
fetch_bin_staged() {   # $1 = имя, $2 = куда, [$3 = каталог-источник: по умолчанию — загрузки с компьютера; BIN_PREFETCH — скачанное заранее]
    _fsn="$1"; _fsd="$2"; _fsc=${3:-$BIN_STAGE}
    if [ "$_fsc" = "$BIN_PREFETCH" ]; then _fsw="скачанный заранее"; log "[fetch-bin] $_fsn <- скачан заранее (ОЗУ)"
    else _fsw="загруженный"; log "[fetch-bin] $_fsn <- файл, загруженный с компьютера"; fi
    _fsl=$(bm_line "$_fsn"); _fss=${_fsl#* }
    [ "${#_fss}" = 64 ] || { rm -f "$_fsc/$_fsn" "$_fsc/$_fsn.sha"; fb_fail "$_fsn: в манифесте нет суммы — $_fsw файл не проверить"; return 1; }
    GH_BGDL="$_fsd.dl"   # уборка выхода (gh_bg_stop) снимает копию, не доехавшую до `mv`
    cp "$_fsc/$_fsn" "$_fsd.dl" 2>/dev/null || { rm -f "$_fsd.dl"; fb_fail "не скопировать $_fsw $_fsn (место?)"; return 1; }
    _fsh=$(file_sha256 "$_fsd.dl")
    if [ "$_fsh" != "$_fss" ]; then rm -f "$_fsd.dl" "$_fsc/$_fsn" "$_fsc/$_fsn.sha"; fb_fail "$_fsw $_fsn не совпал с манифестом"; return 1; fi
    if ! elf_ok "$_fsd.dl"; then rm -f "$_fsd.dl" "$_fsc/$_fsn" "$_fsc/$_fsn.sha"; fb_fail "$_fsw $_fsn не ELF (не бинарь)"; return 1; fi
    chmod +x "$_fsd.dl"
    mv "$_fsd.dl" "$_fsd" || { rm -f "$_fsd.dl"; fb_fail "не смог поставить $_fsn"; return 1; }
    GH_BGDL=
    if [ ! -x "$_fsd" ]; then
        chmod +x "$_fsd" 2>/dev/null
        [ -x "$_fsd" ] || { rm -f "$_fsd"; fb_fail "$_fsn лёг без права на исполнение ($_fsd) — накопитель смонтирован без exec?"; return 1; }
    fi
    rm -f "$_fsc/$_fsn" "$_fsc/$_fsn.sha"
    bs_seed "$_fsn" "$_fsd" "bin/$(bin_arch)/$_fsn.user" "$_fsh"
    if [ "$_fsc" = "$BIN_PREFETCH" ]; then log "[fetch-bin] OK: $_fsn (скачан заранее) -> $_fsd"
    else log "[fetch-bin] OK: $_fsn (загружен с компьютера) -> $_fsd"; fi
}

# --- Путь по репо → URL ассета релиза. Пусто = ассета для него не бывает. ------------
# Пусто отдаём в двух случаях: путь не вида `bin/<арка>/<файл>` (в релизе лежат только бинари)
# ИЛИ источник пришпилен к своему тегу через `.gh-ref` — там бинари обязаны ехать ИЗ ЭТОГО
# СНИМКА, а тег `bin` несёт всегда свежие, и подменять одно другим нельзя.
bin_asset_url() {
    case "$1" in
        bin/*/*) _ba=${1#bin/}; _bn=${_ba#*/}; _ba=${_ba%%/*}; rel_flat_url "$_ba-$_bn" ;;
        *) : ;;
    esac
}
# URL ассета по ПЛОСКОМУ имени — для того, что лежит в релизе рядом с бинарями (SHA256SUMS,
# bin-manifest.txt). Пусто при пришпиленном `.gh-ref`: тег `bin` несёт всегда свежее, и
# подсовывать его снимку под чужим тегом нельзя.
rel_flat_url() { [ "$GH_REF" = main ] || return 0; echo "$GH_REL/$1"; }

# --- Одна попытка закачки конкретного пути. Возвращает 0 только при рабочем бинаре. --
# Отказ канала: строка журнала + причина в FB_WHY и «это 404» в FB_404 — ИТОГ выбирает fetch_bin (разбор там).
# FB_OTHER — «по адресу другая сборка» (sha не тот): не подмена и не сбой, а другой релиз — итог выбирает fetch_bin.
# Строки этой попытки — «[fetch-bin] мимо: …», а не FAIL: итог FAIL пишет fetch_bin, и движок берёт ПОСЛЕДНЮЮ такую строку.
fb_fail() { FB_WHY="$1"; if [ "$2" = 404 ]; then FB_404=1; else FB_404=0; fi; log "[fetch-bin] мимо: $1"; }
fetch_bin_one() {
    url="$1"; rel="$2"; name="$3"; dst="$4"; minsz="$5"; FB_OTHER=0
    log "[fetch-bin] $name <- $url"
    # Закачка В ФОНЕ (gh_get перебирает anycast-IP) + опрос размера .dl → прогресс/скорость в лог
    # (его опрашивает панель, показывая последнюю строку). Без HEAD за Content-Length (лишний
    # connect-цикл) — печатаем скачанные КБ и среднюю скорость. Быстрая закачка (<2с) проскочит
    # цикл без строк прогресса — норма. Мёртвый IP даст «0 КБ» на ≤8с, затем gh_get берёт живой.
    t0=$(date +%s)
    gh_code_reset          # чтобы ответ прошлого канала не выдали за причину этого
    gh_get "$url" "$dst.dl" &
    cpid=$!; GH_BGPID=$cpid; GH_BGDL="$dst.dl"
    while kill -0 "$cpid" 2>/dev/null; do
        sleep 2
        cur=$(stat -c%s "$dst.dl" 2>/dev/null || echo 0); case "$cur" in ''|*[!0-9]*) cur=0;; esac
        # clock-raw: не возраст отметки, а длительность ВНУТРИ одного прогона (t0 взят строкой выше) —
    # клампу по аптайму тут нечего делать.
    el=$(( $(date +%s) - t0 )); [ "$el" -gt 0 ] || el=1
        log "[fetch-bin] $name: $((cur/1024)) КБ ($((cur/1024/el)) КБ/с)"
    done
    wait "$cpid" 2>/dev/null; rc=$?; GH_BGPID=
    # ПРИЧИНУ НАЗЫВАЕМ, а не гадаем. «(сеть/нет места?)» стояло тут годом раньше и оба раза мимо:
    # на 429 сеть в порядке и места вдоволь, а человек по такой строке идёт чинить не то.
    if [ "$rc" != 0 ]; then
        rm -f "$dst.dl"
        _fbc=$(gh_code_get); _why=$(gh_code_reason "$_fbc")
        [ -n "$_why" ] || _why="нет связи с GitHub (или кончилось место)"
        fb_fail "не скачался $name — $_why" "$_fbc"
        return 1
    fi
    sz=$(stat -c%s "$dst.dl" 2>/dev/null || echo 0)
    if [ -n "$minsz" ] && [ "${sz:-0}" -lt "$minsz" ]; then rm -f "$dst.dl"; fb_fail "$name мал ($sz < $minsz) — обрыв закачки"; return 1; fi
    if ! elf_ok "$dst.dl"; then rm -f "$dst.dl"; fb_fail "$name не ELF (не бинарь)"; return 1; fi
    # Закачка целая (код curl 0), а размер не тот — это ДРУГАЯ СБОРКА (на ветке уже следующая), а не обрыв: «мал — обрыв»
    # звал бы человека жать «Применить» по кругу вместо «обновите систему» (ревью ветки, круг 1).
    if [ -n "$FB_SIZE" ] && [ "$sz" != "$FB_SIZE" ]; then
        rm -f "$dst.dl"; fb_fail "$name по этому адресу — другая сборка ($sz байт, а у своей $FB_SIZE)"; FB_OTHER=1; return 1
    fi
    # sha256 ПОСЛЕ размера/ELF (дешёвые отсевы первыми) и ДО chmod+mv — не пускаем на диск исполняемым то, чего
    # установленная версия не знает: сумма — из ПОДПИСАННОГО манифеста (FB_WANT ставит fetch_bin).
    _fbh=$(file_sha256 "$dst.dl")
    if [ -z "$_fbh" ]; then rm -f "$dst.dl"; fb_fail "нечем посчитать sha256 $name (нет openssl) — сверить сборку нечем"; return 1; fi
    if [ "$_fbh" != "$FB_WANT" ]; then
        rm -f "$dst.dl"; fb_fail "$name по этому адресу — другая сборка, не та, что знает установленная версия"; FB_OTHER=1; return 1
    fi
    chmod +x "$dst.dl"
    mv "$dst.dl" "$dst" || { rm -f "$dst.dl"; fb_fail "не смог поставить $name"; return 1; }
    GH_BGDL=
    # Исполняемость судим ПО ФАКТУ, а не по тому, что chmod отработал: с появлением внешнего
    # накопителя $dst бывает на exFAT/NTFS, где права задаёт МОНТИРОВАНИЕ (fmask), а chmod молча
    # не делает ничего. Файл, легший без +x, — это связка, которая навсегда осталась «не
    # установлена» после успешной закачки, без единой причины на экране. Лучше явный отказ.
    if [ ! -x "$dst" ]; then
        chmod +x "$dst" 2>/dev/null
        [ -x "$dst" ] || { rm -f "$dst"; fb_fail "$name лёг без права на исполнение ($dst) — накопитель смонтирован без exec?"; return 1; }
    fi
    [ "$FB_NOSEED" = 1 ] || bs_seed "$name" "$dst" "$rel" "$_fbh"
    log "[fetch-bin] OK: $name ($sz байт) -> $dst"
}

# --- Версии. CODE — целое для busybox-сравнения; VERSION — человекочитаемое имя. ----
local_code() { c=$(sed -n 's/^CODE=//p' "$ENODIA_DIR/VERSION" 2>/dev/null | head -1 | tr -d ' \r'); case "$c" in ''|*[!0-9]*) echo 0;; *) echo "$c";; esac; }
local_name() { sed -n 's/^VERSION=//p' "$ENODIA_DIR/VERSION" 2>/dev/null | head -1 | tr -d ' \r"\\'; }
# --- ПАКЕТНОЕ ОБНОВЛЕНИЕ КОДА -------------------------------------------------------------------------
# КОНТРАКТ (формат 1) — его держит КАЖДЫЙ установленный апдейтер, поэтому менять его НЕЛЬЗЯ; ПК-половина —
# dev/build-release.py, там же подробный разбор. Коротко:
#   * `release.txt` в корне ветки ($RAW): FORMAT=1 · VERSION · CODE · TAG · PKG · SIZE · SHA256 и
#     последней строкой SIG=<base64> — подпись ECDSA P-256/SHA-256 всех байтов ДО неё (DER);
#   * пакет — ассет релиза github.com/<репо>/releases/download/<TAG>/<PKG>, tar.gz ровно с путями
#     update-manifest.txt, внутри VERSION с тем же CODE и pkg-install.sh;
#   * вход установщика: `sh <корень>/pkg-install.sh install <корень>`, код 0 = успех.
# ЗАМОРОЖЕННАЯ ЧАСТЬ ЗДЕСЬ — только проверка и передача. Решений о файлах апдейтер НЕ принимает: как
# только он начнёт что-то решать, он снова станет тем, что придётся обновлять раньше всего остального.
# ПОЧЕМУ ПОДПИСЬ, А НЕ SHA256SUMS. Суммы едут тем же каналом, что и файлы, — это защита от битой закачки,
# а не от подмены: взявший аккаунт GitHub подменил бы и то и другое. Подпись ставится ключом, который
# на GitHub не бывает никогда; публичных ключей ДВА (основной и резервный): утрата основного лечится
# релизом, подписанным резервным и везущим новый набор ключей.
# ЧЕМ ПРОВЕРЯЕМ: стоковым `openssl dgst -sha256 -verify` — ECDSA P-256 умеют и 1.0.2q (AX3600), и
# 1.1.1l (BE7000); ed25519 в 1.0.2 нет. Без openssl обновление ОТКАЗЫВАЕТ: без проверки не ставим.
REL_REL=release.txt
REL_KEYS="1 2"
SNAP_DIR="$ENODIA_STATE/.gh-backup"
# Рабочие каталоги проверки подписи и пакета — `mktemp -d` (0700, имя непредсказуемо), а не `…$$` (ревью ветки pkg-update, круг 2):
# процесс с правами nobody (dnsmasq, пробы десинка) мог заранее занять `/tmp/enodia-pkg.<pid>` в окне между `rm -rf` и `mkdir -p`
# и после сверки sha256 подменить `root/pkg-install.sh`, который root затем исполняет. Пусто — каталога нет.
PKG_TMP=""
rel_key() {
    case "$1" in
        1) cat <<'EOF'
-----BEGIN PUBLIC KEY-----
MFkwEwYHKoZIzj0CAQYIKoZIzj0DAQcDQgAEYMy2nkBwcDrbrYINLqB++poqqwSj
5uwJDict7DbZ/MlZvfx3X5/BWyhXiKCIqDzclOMkfJS5lQKyGoG4n0XyDw==
-----END PUBLIC KEY-----
EOF
        ;;
        2) cat <<'EOF'
-----BEGIN PUBLIC KEY-----
MFkwEwYHKoZIzj0CAQYIKoZIzj0DAQcDQgAEVajsejkbpxbm9fFpMaITwkTpbhxv
yIwwQgUmGMWzDiCqqLNE6r1IXmjEgvr1nCk2WWwQyL9O1oymwC8zlkrUDw==
-----END PUBLIC KEY-----
EOF
        ;;
    esac
}
# rel_sig_ok <тело> <подпись DER> — 0: сходится хотя бы с одним вшитым ключом.
rel_sig_ok() {
    _rk="${2%/*}/key"; _rok=1          # рядом с подписью: это личный каталог rel_load
    for _ki in $REL_KEYS; do
        rel_key "$_ki" > "$_rk" 2>/dev/null || continue
        if openssl dgst -sha256 -verify "$_rk" -signature "$2" "$1" >/dev/null 2>&1; then _rok=0; break; fi
    done
    rm -f "$_rk"
    return "$_rok"
}
# rel_load — скачать и ПРОВЕРИТЬ описание релиза. Итог — в переменных REL_* и REL_STATE:
#   ok · none (404: этим каналом не публикуют) · refused (429/403) · fail (сеть; причина в REL_WHY,
#   если GitHub что-то ответил) · badsig · bad (поле вне правил) · newfmt (формат новее этого
#   апдейтера) · nossl (нечем проверить). Код 0 — только ok.
# Поля проверяем ФОРМОЙ даже под верной подписью: из них строится URL и путь в /tmp, и ошибка сборки
# не должна становиться запросом «куда-то не туда».
rel_load() {
    REL_STATE=fail; REL_WHY=""; REL_VERSION=""; REL_CODE=""; REL_TAG=""; REL_PKG=""; REL_SIZE=""; REL_SHA=""
    _rd=$(mktemp -d /tmp/enodia-pkg.XXXXXX 2>/dev/null) || _rd=""
    [ -n "$_rd" ] || { REL_WHY="не создать рабочий каталог в /tmp"; return 1; }
    _rt="$_rd/rel"
    if ! gh_get "$RAW/$REL_REL" "$_rt" || [ ! -s "$_rt" ]; then
        rm -rf "$_rd"
        _rc=$(gh_code_get)
        case "$_rc" in
            404)     REL_STATE=none ;;
            429|403) REL_STATE=refused; REL_WHY=$(gh_code_reason "$_rc") ;;
            *)       REL_STATE=fail; REL_WHY=$(gh_code_reason "$_rc") ;;
        esac
        return 1
    fi
    if ! command -v openssl >/dev/null 2>&1; then
        rm -rf "$_rd"; REL_STATE=nossl
        REL_WHY="на роутере нет openssl — подпись релиза проверить нечем, а без проверки не ставим; обновите с компьютера"
        return 1
    fi
    # Тело = файл без строки подписи, байт в байт (у сборщика каждая строка кончается LF).
    grep -v '^SIG=' "$_rt" > "$_rt.body" 2>/dev/null
    sed -n 's/^SIG=//p' "$_rt" | head -n 1 | tr -d ' \r\n' > "$_rt.b64"
    openssl base64 -d -A -in "$_rt.b64" -out "$_rt.sig" 2>/dev/null
    if [ ! -s "$_rt.sig" ] || ! rel_sig_ok "$_rt.body" "$_rt.sig"; then
        rm -rf "$_rd"; REL_STATE=badsig
        REL_WHY="подпись релиза на GitHub не сошлась — такой релиз не ставим (подмена или ошибка публикации)"
        return 1
    fi
    _rf() { sed -n "s/^$1=//p" "$_rt.body" | head -n 1; }
    _rfm=$(_rf FORMAT); REL_VERSION=$(_rf VERSION); REL_CODE=$(_rf CODE); REL_TAG=$(_rf TAG)
    REL_PKG=$(_rf PKG); REL_SIZE=$(_rf SIZE); REL_SHA=$(_rf SHA256)
    rm -rf "$_rd"
    if [ "$_rfm" != 1 ]; then
        REL_STATE=newfmt
        REL_WHY="релиз опубликован в формате «$_rfm», а этот апдейтер знает формат 1 — обновите с компьютера"
        return 1
    fi
    _rbad=""
    case "$REL_CODE" in ''|*[!0-9]*) _rbad=" CODE" ;; esac
    case "$REL_SIZE" in ''|*[!0-9]*) _rbad="$_rbad SIZE" ;; esac
    case "$REL_TAG" in ''|*[!A-Za-z0-9._-]*|.*) _rbad="$_rbad TAG" ;; esac
    case "$REL_VERSION" in ''|*[!A-Za-z0-9._+-]*) _rbad="$_rbad VERSION" ;; esac
    [ "${#REL_SHA}" = 64 ] || _rbad="$_rbad SHA256"
    case "$REL_SHA" in *[!0-9a-f]*) _rbad="$_rbad SHA256" ;; esac
    [ "$REL_PKG" = "enodia-$REL_CODE.tar.gz" ] || _rbad="$_rbad PKG"
    if [ -n "$_rbad" ]; then
        REL_STATE=bad; REL_WHY="описание релиза на GitHub вне правил (поле:$_rbad) — не ставим"
        return 1
    fi
    REL_STATE=ok
    return 0
}

cmd_check() {
    lc=$(local_code); ln=$(local_name); [ -n "$ln" ] || ln="?"
    rel_load
    case "$REL_STATE" in
        ok)
            if [ "$REL_CODE" -gt "$lc" ]; then
                log "локально: $ln (код $lc); на GitHub: $REL_VERSION (код $REL_CODE, подпись сошлась) → ЕСТЬ ОБНОВЛЕНИЕ"
            else
                log "локально: $ln (код $lc); на GitHub: $REL_VERSION (код $REL_CODE) → у вас актуальная версия"
            fi ;;
        none) log "локально: $ln (код $lc); на GitHub нет описания релиза ($GH_REF) → обновление НЕ предлагается" ;;
        *)    log "локально: $ln (код $lc); ${REL_WHY:-GitHub не ответил — нет связи}" ;;
    esac
}

# --- Обновление кода одним пакетом ------------------------------------------------------------------
# Порядок: описание релиза (подпись) → даунгрейд-гард → место в ОЗУ → пакет (размер, sha256 из
# ПОДПИСАННОГО описания) → состав архива → распаковка в /tmp → версия внутри = версия описания →
# установщик ИЗ ПАКЕТА. Всё до последнего шага ничего на роутере не меняет.
pkg_cleanup() { if [ -n "$PKG_TMP" ]; then rm -rf "$PKG_TMP" 2>/dev/null; fi; PKG_TMP=""; }
pkg_mkdir() {   # свой рабочий каталог (см. PKG_TMP); 1 — не создан
    PKG_TMP=$(mktemp -d /tmp/enodia-pkg.XXXXXX 2>/dev/null) || PKG_TMP=""
    [ -n "$PKG_TMP" ] && mkdir "$PKG_TMP/root" 2>/dev/null && return 0
    pkg_cleanup; return 1
}
# СМЕНА РАСКЛАДКИ ИДЁТ — ОБНОВЛЕНИЕ И ОТКАТ ОТКАЗЫВАЮТ (ревью ветки pkg-update, круг 1): переезд сносит каталог кода, в который
# они пишут, и на флеше вырастала вторая, пустая система. Ответ — у владельца (daemon-lib.sh::store_mode_alive; сорсится ниже, до
# разбора вербов); обратную сторону (переезд посреди обновления) держит usb-offload.sh::move_hold.
# Снятие системы — тот же отказ (ревью ветки, круг 2): установщик откажет и сам (pi_gate), но уже после закачки. Строка — со «СТОП:»:
# по ней `status-json` достаёт причину отказа (`upd_why`), без неё экран показывал FAIL без слов.
upd_store_busy() {
    if command -v store_mode_alive >/dev/null 2>&1 && store_mode_alive; then
        log "[$1] СТОП: идёт смена раскладки (перенос на накопитель или обратно) — отменено; дождитесь её конца и повторите"
        return 0
    fi
    if command -v uninstall_alive >/dev/null 2>&1 && uninstall_alive; then
        log "[$1] СТОП: идёт снятие системы (отключение или полное удаление) — отменено"
        return 0
    fi
    return 1
}
cmd_apply() {
    _force="$1"
    upd_store_busy apply && return 1
    lc=$(local_code)
    if ! rel_load; then
        case "$REL_STATE" in
            none) log "[apply] на GitHub нет описания релиза ($REL_REL, ветка $GH_REF) — обновление отменено" ;;
            *)    log "[apply] СТОП: ${REL_WHY:-не удалось получить описание релиза с GitHub (нет связи)} — обновление отменено" ;;
        esac
        return 1
    fi
    if [ "$_force" != "--force" ] && [ "$REL_CODE" -le "$lc" ]; then
        log "[apply] на GitHub код $REL_CODE <= локального $lc — это даунгрейд, отмена (--force чтобы всё равно)"; return 1
    fi
    # Пакет и его распаковка живут в ОЗУ (флеш 20 МБ, важен ПИК): текст жмётся примерно вчетверо.
    _tf=$(df -k /tmp 2>/dev/null | awk 'NR==2{print $4+0}'); case "$_tf" in ''|*[!0-9]*) _tf=0 ;; esac
    _tneed=$((REL_SIZE * 6 / 1024 + 2048))
    if [ "$_tf" -lt "$_tneed" ]; then
        log "[apply] СТОП: под распаковку пакета в /tmp свободно ${_tf} КБ, нужно ≥ ${_tneed} — обновление отменено"; return 1
    fi
    pkg_cleanup
    pkg_mkdir || { log "[apply] СТОП: не создать рабочий каталог в /tmp — обновление отменено"; return 1; }
    trap 'gh_exit; pkg_cleanup' EXIT
    trap 'exit 1' INT TERM HUP
    _pu="https://github.com/$REPO/releases/download/$REL_TAG/$REL_PKG"
    log "[apply] релиз $REL_VERSION (код $REL_CODE): подпись сошлась, качаю $REL_PKG ($REL_SIZE байт)"
    if ! gh_get "$_pu" "$PKG_TMP/pkg.tar.gz"; then
        _pr=$(gh_code_reason "$(gh_code_get)")
        log "[apply] СТОП: пакет не скачался: ${_pr:-нет связи с GitHub} — ничего не заменено"; pkg_cleanup; return 1
    fi
    _psz=$(wc -c < "$PKG_TMP/pkg.tar.gz" 2>/dev/null | tr -d ' ')
    if [ "$_psz" != "$REL_SIZE" ]; then
        log "[apply] СТОП: пакет пришёл не того размера (${_psz:-0} байт вместо $REL_SIZE) — ничего не заменено"; pkg_cleanup; return 1
    fi
    _ph=$(file_sha256 "$PKG_TMP/pkg.tar.gz")
    if [ -z "$_ph" ] || [ "$_ph" != "$REL_SHA" ]; then
        log "[apply] СТОП: sha256 пакета не совпал с подписанным описанием — ничего не заменено"; pkg_cleanup; return 1
    fi
    # Состав: только обычные файлы с безопасными путями. Пакет подписан, но распаковывает его root, и
    # эта проверка — последняя линия, если подпись когда-нибудь прикроет ошибку сборки (ссылка, «..»).
    if ! tar -tvzf "$PKG_TMP/pkg.tar.gz" > "$PKG_TMP/lsv" 2>/dev/null || ! tar -tzf "$PKG_TMP/pkg.tar.gz" > "$PKG_TMP/ls" 2>/dev/null; then
        log "[apply] СТОП: архив пакета не читается — ничего не заменено"; pkg_cleanup; return 1
    fi
    # ХАРДЛИНК busybox печатает с режимом ОБЫЧНОГО файла и стрелкой в конце (`-rw-r--r-- … ./a -> ./b`, замер BE7000 23.08.2026 —
    # тот же разбор у импорта бэкапа), и проверка по первой букве его пропускала; GNU tar стенда метит его `h` — стенд этого не видел
    # (ревью ветки pkg-update, круг 1). Признак обоих видов ссылок — стрелка; сборщик пишет только обычные файлы.
    if grep -qv '^-' "$PKG_TMP/lsv" || grep -q ' -> ' "$PKG_TMP/lsv"; then
        log "[apply] СТОП: в пакете есть не только обычные файлы — не ставим"; pkg_cleanup; return 1
    fi
    while IFS= read -r _pe || [ -n "$_pe" ]; do
        case "$_pe" in ''|/*|*..*|*[!A-Za-z0-9._/-]*) log "[apply] СТОП: в пакете путь вне правил: $_pe"; pkg_cleanup; return 1 ;; esac
    done < "$PKG_TMP/ls"
    if ! tar -xzf "$PKG_TMP/pkg.tar.gz" -C "$PKG_TMP/root" 2>/dev/null; then
        log "[apply] СТОП: пакет не распаковался (мало памяти?) — ничего не заменено"; pkg_cleanup; return 1
    fi
    rm -f "$PKG_TMP/pkg.tar.gz"
    _pvc=$(sed -n 's/^CODE=//p' "$PKG_TMP/root/VERSION" 2>/dev/null | head -n 1 | tr -cd '0-9')
    if [ "$_pvc" != "$REL_CODE" ]; then
        log "[apply] СТОП: версия внутри пакета (${_pvc:-нет}) не та, что в описании ($REL_CODE) — не ставим"; pkg_cleanup; return 1
    fi
    if [ ! -f "$PKG_TMP/root/pkg-install.sh" ]; then
        log "[apply] СТОП: в пакете нет установщика pkg-install.sh — не ставим"; pkg_cleanup; return 1
    fi
    log "[apply] пакет проверен (подпись, sha256, состав, версия) — передаю установщику из пакета"
    # Установщик ИЗ ПАКЕТА — в этом весь смысл: его правила приехали вместе с кодом. Пути — явно: нас
    # зовут и из CGI, и из cron-бутстрапа, и наследование окружения не должно решать, куда ставить.
    # PKG_NEED_PRIOR — обновление не ставит систему с нуля: пустой каталог кода у нас = он уехал (смена раскладки), а не «свежая».
    ENODIA_DIR="$ENODIA_DIR" ENODIA_STATE="$ENODIA_STATE" ENODIA_BIN="$ENODIA_BIN" ENODIA_BOOT="$ENODIA_BOOT" PKG_NEED_PRIOR=1 \
        sh "$PKG_TMP/root/pkg-install.sh" install "$PKG_TMP/root"
    _prc=$?
    pkg_cleanup
    return "$_prc"
}

# ОТКАТ ЧЕРЕЗ ГРАНИЦУ ФОРМЫ ВХОДА ЗАПРЕЩЁН — разбор внутри rb_guard(), там же и признаки.
rb_guard() {                     # 0 = откатывать можно; 1 = снимок СТАРЕЕ формы входа
    # ОТКАТ ЧЕРЕЗ ГРАНИЦУ ФОРМЫ ВХОДА ЗАПРЕЩЁН. Снимок, снятый ДО 03.09.2026, несёт totp.sh, который
    # ещё не знает пароля (`pw_verify` в нём нет), и CGI, у которых гейт был пропуском. Живой uhttpd
    # при этом уже поднят БЕЗ `-c` — то есть сразу после такого отката панель со всеми ДЕЙСТВИЯМИ
    # открыта любому в локалке, а после ближайшего ребута не поднимется вовсе: прежний `start`
    # требует `web/uhttpd.conf`, а тот при миграции удалён (в бэкап он не попадал — файла нет в
    # манифесте). Человек этого пути не выбирал: откат ему предлагает сам апдейтер после неудачи.
    #
    # СУДИМ ПО totp.sh, А ГЕЙТ В CGI — ТОЛЬКО ТАЙБРЕКЕР. Первая редакция проверяла гейт ПЕРВЫМ и
    # запрещала откат на СВЕЖИЙ снимок: ветка «нет totp.sh → 403» появилась той же правкой, значит
    # у снимка предыдущей версии её ещё нет, а форма входа там уже есть. Тайбрекер нужен для
    # другого случая: totp.sh в снимке нет ВООБЩЕ (до 03.09 он был опциональным и на свежих
    # установках не стоял) — тогда «доформенность» видно по однострочному гейту в `status`.
    _rg="$1/totp.sh"
    if [ -f "$_rg" ]; then
        grep -qE "^pw_verify *\(\)" "$_rg" && return 0
        log "[rollback] снимок СТАРЕЕ формы входа: в его totp.sh нет pw_verify."
    else
        # totp.sh в снимке нет: спрашиваем ЛЮБОЙ гейтованный CGI, какой найдётся (снимок бывает
        # собран и руками, и в нём может не оказаться именно `status`).
        _rs=""
        for _c in status action data list ip ping sysinfo traffic backup diag; do
            [ -f "$1/web/cgi-bin/$_c" ] && { _rs="$1/web/cgi-bin/$_c"; break; }
        done
        [ -n "$_rs" ] || return 0            # ни totp.sh, ни CGI — это частичный бэкап, откат безопасен
        grep -q "403 Forbidden" "$_rs" && return 0
        log "[rollback] снимок СТАРЕЕ формы входа: totp.sh в нём нет, а гейт в CGI — прежний, без отказа."
    fi
    log "[rollback] откат туда оставил бы панель открытой всей локалке до ребута, а после ребута"
    log "[rollback] она не поднялась бы вовсе (прежний start требует web/uhttpd.conf, а миграция"
    log "[rollback] его удалила). Отказываюсь. Нужен именно этот снимок — сначала верните файл"
    # СОВЕТ ПЕЧАТАЕМ В ОДИНАРНЫХ КАВЫЧКАХ. В двойных `$(uhttpd -m …)` выполнился бы ПРЯМО ЗДЕСЬ:
    # шелл подставил бы настоящий хэш слова «ПАРОЛЬ», и скопировавший строку задал бы панели
    # именно этот пароль (плюс лишний форк на каждом отказе отката).
    log '[rollback] Basic руками:  printf "/:admin:%s\n" "$(uhttpd -m ВАШПАРОЛЬ)" > <каталог кода>/web/uhttpd.conf'   # c38-text: это ТЕКСТ совета, а не запись файла
    # И СРАЗУ ОТКАТЫВАЙТЕСЬ: cron дёргает `web-ui.sh start` раз в пять минут, а тот (pw_migrate и
    # гард старта) снова снесёт этот файл — окно на выполнение совета случайное, 0…5 минут.
    log '[rollback] и СРАЗУ откатывайтесь: cron-овский web-ui.sh start снова снесёт этот файл (раз в 5 мин).'
    log '[rollback] setpass его НЕ создаёт — он пишет .panel-pass.'
    return 1
}
# Снимки — tar.gz по времени снятия (`ГГГГММДД-ЧЧММСС.tar.gz`), кладёт их pkg-install.sh перед заменой.
snap_list() { ls -1 "$SNAP_DIR" 2>/dev/null | grep '^[0-9]\{8\}-[0-9]\{6\}\.tar\.gz$' | sort; }
# Откат = установка из последнего снимка ТЕМ ЖЕ установщиком (pkg-install.sh rollback): та же проверка
# до первой замены, тот же самовозврат при сбое, удаление файлов, которых в снимке нет, и установщик
# ВОЗВРАЩЁННОЙ версии. Установщик берём УСТАНОВЛЕННЫЙ: в снимке его может не быть вовсе.
cmd_rollback() {
    upd_store_busy rollback && return 1
    last=$(snap_list | tail -n 1)
    [ -n "$last" ] || { log "[rollback] нет снимков в $SNAP_DIR"; return 1; }
    [ -f "$ENODIA_DIR/pkg-install.sh" ] || { log "[rollback] нет $ENODIA_DIR/pkg-install.sh — откатывать нечем; переустановите с компьютера"; return 1; }
    pkg_cleanup
    pkg_mkdir || { log "[rollback] СТОП: не создать рабочий каталог в /tmp"; return 1; }
    trap 'gh_exit; pkg_cleanup' EXIT
    trap 'exit 1' INT TERM HUP
    if ! tar -xzf "$SNAP_DIR/$last" -C "$PKG_TMP/root" 2>/dev/null; then
        pkg_cleanup; log "[rollback] не открыть снимок ${last%.tar.gz} (повреждён?)"; return 1
    fi
    rb_guard "$PKG_TMP/root" || { pkg_cleanup; return 1; }
    log "[rollback] откат к снимку ${last%.tar.gz}"
    ENODIA_DIR="$ENODIA_DIR" ENODIA_STATE="$ENODIA_STATE" ENODIA_BIN="$ENODIA_BIN" ENODIA_BOOT="$ENODIA_BOOT" \
        sh "$ENODIA_DIR/pkg-install.sh" rollback "$PKG_TMP/root"
    _prc=$?
    pkg_cleanup
    # Снимок, к которому откатились, — теперь ТЕКУЩИЙ набор: второй «Откатить» откатывал бы к тому, что уже стоит (ревью ветки, круг 1).
    if [ "$_prc" = 0 ]; then rm -f "$SNAP_DIR/$last" && log "[rollback] снимок ${last%.tar.gz} использован — снят"; fi
    return "$_prc"
}

# --- АУДИТ: что из установленного расходится с SHA256SUMS в репо (только ЧТЕНИЕ). ------
# Зачем отдельный верб: ровно этот вопрос раньше закрывался ручным md5-аудитом манифеста —
# «на роутере лежит файл не той версии» (дрейф деплоя ловится глазами очень плохо). Дев-сборка
# заведомо новее публичного снимка ⇒ расхождения здесь НОРМА, верб информационный.
# Бинарь в репо лежит как bin/<арка>/<имя>.user, а на роутере — ПЛОСКО $ENODIA_DIR/<имя>: чужую
# арку пропускаем, иначе получили бы «расхождение» на каждом бинаре.
# Обход сверки: считает nsame/ndiff/nmiss и кладёт пути расхождений и отсутствующих в <$1>.diff / <$1>.miss (по строке).
# Один обход на два вида ответа — текстовый (`verify`, консоль) и машинный (`verify-json`, экран «Обновление»): вторая копия
# правил «что сверять» (свой кэш манифеста, чужая арка) разъехалась бы с первой при первой же правке.
# Где лежит бинарь — у владельца ответа (store-lib.sh::bin_path: накопитель, если бинарь там). Библиотеку сорсим в ПОДОБОЛОЧКЕ:
# апдейтеру её переменные и шимы не нужны, а смешанная установка без неё — прежний путь.
bin_file_at() {
    if [ -f "$ENODIA_DIR/store-lib.sh" ]; then ( . "$ENODIA_DIR/store-lib.sh" >/dev/null 2>&1; bin_path "$1" )
    else printf '%s' "$ENODIA_BIN/$1"; fi
}
# КОД — ПО СУММАМ УСТАНОВЛЕННОГО ПАКЕТА, БИНАРИ — ПО ЕГО ЖЕ МАНИФЕСТУ БИНАРЕЙ. Пакет минифицирован (комментарии срезаны при
# сборке), и суммы репо к его файлам не подходят по построению — сверка с ними сказала бы «всё расходится». Поэтому пакет несёт
# суммы своих байтов, установщик кладёт их в $ENODIA_DIR/.pkg-sums, и код сверяется с ними БЕЗ СЕТИ; бинари — с подписанным
# манифестом (BM_FILE), тоже без сети. Нет .pkg-sums (код поставлен не пакетом) — всё как раньше, по суммам репо.
PKG_SUMS="$ENODIA_DIR/.pkg-sums"
vs_reset() { : > "$1.diff"; : > "$1.miss"; : > "$1.old"; nsame=0; ndiff=0; nmiss=0; nold=0; }
verify_scan() {   # $1 = префикс файлов-списков · $2 = подстрока пути (пусто = всё) · $3 = файл сумм · $4 = all|bin (только бинари)
    only="$2"; _vo="$1"; _vw="${4:-all}"
    _arch=$(bin_arch)
    while read -r _h _p; do
        case "$_h" in ''|\#*) continue ;; esac
        [ "${#_h}" = 64 ] || continue
        _p=${_p#\*}
        if [ "$_vw" = bin ]; then case "$_p" in bin/*) : ;; *) continue ;; esac; fi
        if [ -n "$only" ]; then case "$_p" in *"$only"*) : ;; *) continue ;; esac; fi
        # БИНАРИ — ДРУГИЕ ПРАВИЛА, ЧЕМ У КОДА (ревью шага 6c, круг 1): бинарь протокола лежит там, где его держит раскладка
        # (накопитель — `bin_file_at`), а не обязательно в $ENODIA_BIN; не установленный протокол — не «пропажа», а выбор
        # человека (компоненты à la carte), его в сверку не берём; плоская легаси-запись `bin/<имя>.user` — копия набора одной арки,
        # и при известной арке она учла бы каждый бинарь дважды (а на armv7 — как «расходится»).
        case "$_p" in
            bin/*/*.user)
                _pa=${_p#bin/}; _pa=${_pa%%/*}
                [ -z "$_arch" ] || [ "$_pa" = "$_arch" ] || continue
                _n=${_p##*/}; _l=$(bin_file_at "${_n%.user}"); [ -f "$_l" ] || continue ;;
            bin/*.user)
                [ -z "$_arch" ] || continue
                _n=${_p##*/}; _l=$(bin_file_at "${_n%.user}"); [ -f "$_l" ] || continue ;;
            *) _l="$ENODIA_DIR/$_p" ;;
        esac
        if [ ! -f "$_l" ]; then printf '%s\n' "$_p" >> "$_vo.miss"; nmiss=$((nmiss+1)); continue; fi
        _g=$(file_sha256 "$_l")
        if [ "$_g" = "$_h" ]; then nsame=$((nsame+1)); continue; fi
        # УСТАРЕЛА ≠ РАСХОДИТСЯ (ревью ветки, круг 2): сборка бинаря привязана к версии кода, и после обновления с новой сборкой
        # стоящая законно не совпадает с новым манифестом. Хеш, который хоть раз совпал с подписанным манифестом (его версию
        # помнит кэш `bs_ver_known`; перед заменой кода её записывает pkg-install.sh), — прежняя ПОДПИСАННАЯ сборка: новая ждёт
        # в «Компонентах». Прежде такую звали «правили на роутере или побился».
        if [ "$_vw" = bin ]; then
            _vv=$(bs_ver_known "${_n%.user}" "$_g")
            if [ -n "$_vv" ]; then printf '%s %s\n' "$_p" "$_vv" >> "$_vo.old"; nold=$((nold+1)); continue; fi
        fi
        printf '%s\n' "$_p" >> "$_vo.diff"; ndiff=$((ndiff+1))
    done < "$3"
    return 0
}
# Бинари — по подписанному манифесту: строки СВОЕЙ арки той же формой, что у файла сумм, и тем же обходом (стоящие — по месту
# раскладки; не установленный протокол — выбор человека, а не пропажа). Арка не опознана — бинари не сверяем вовсе.
VS_BINS=1         # 0 — бинари не сверяли (нет манифеста или арка не опознана): итог обязан это сказать
verify_bins() {   # $1 = префикс · $2 = подстрока пути
    VS_BINS=0
    [ -s "$BM_FILE" ] || return 0
    _vba=$(bin_arch); [ -n "$_vba" ] || return 0
    VS_BINS=1
    awk -F'\t' -v a="$_vba" '$1 !~ /^#/ && $2 == a && length($5) == 64 { print $5 "  bin/" a "/" $1 ".user" }' "$BM_FILE" > "$1.bm" 2>/dev/null
    verify_scan "$1" "$2" "$1.bm" bin
    rm -f "$1.bm"
}
# Весь обход: код по .pkg-sums + бинари по манифесту пакета (VS_SRC=pkg) либо, без .pkg-sums, всё по суммам репо (github).
verify_all() {   # $1 = префикс · $2 = подстрока пути
    vs_reset "$1"; VS_SRC=none
    if [ -s "$PKG_SUMS" ]; then
        VS_SRC=pkg
        verify_scan "$1" "$2" "$PKG_SUMS" all
        verify_bins "$1" "$2"
        return 0
    fi
    sums_load >/dev/null 2>&1
    [ "$SUMS_STATE" = ok ] || return 1
    VS_SRC=github
    verify_scan "$1" "$2" "$SUMS_CACHE" all
}
cmd_verify() {
    _vt="$GH_TMP/vf"
    verify_all "$_vt" "$1" || { rm -f "$_vt.diff" "$_vt.miss" "$_vt.old"; log "[verify] сумм установленного пакета нет, а в репо ($GH_REF) нет $SUMS_REL — сверять не с чем"; return 1; }
    while IFS= read -r _x || [ -n "$_x" ]; do [ -n "$_x" ] && log "[verify] нет на роутере: $_x"; done < "$_vt.miss"
    while IFS= read -r _x || [ -n "$_x" ]; do [ -n "$_x" ] && log "[verify] устарела (стоит прежняя подписанная сборка ${_x##* }, новая — в «Компонентах»): ${_x% *}"; done < "$_vt.old"
    while IFS= read -r _x || [ -n "$_x" ]; do [ -n "$_x" ] && log "[verify] РАСХОЖДЕНИЕ: $_x"; done < "$_vt.diff"
    rm -f "$_vt.diff" "$_vt.miss" "$_vt.old"
    case "$VS_SRC" in
        pkg) if [ "$VS_BINS" = 1 ]; then _vsw="код и бинари — по суммам установленного пакета"
             else _vsw="код — по суммам установленного пакета; бинари НЕ сверены (нет манифеста или арка не опознана)"; fi ;;
        *)   _vsw="по суммам репо $GH_REF" ;;
    esac
    _vso=""; [ "$nold" -gt 0 ] && _vso=", устарело $nold"
    log "[verify] совпало $nsame$_vso, расходится $ndiff, нет на роутере $nmiss ($_vsw, локально $(local_name))"
    [ "$ndiff" = 0 ]
}

# --- ОТВЕТЫ ДЛЯ ПАНЕЛИ (экран «Обновление», шаг 6c) -------------------------------------------------
# Те же вопросы, что у текстовых вербов (check · verify · что с обновлением и откатом), но словами для машины: экран по
# ВЕРДИКТУ решает, какую кнопку показать («Обновить» — только при коде новее), а разбор текстовой фразы в панели разъехался
# бы с ней при первой правке. Текстовые вербы остаются как были — их читают консоль и CLI. Строки — через json-lib.sh
# (одна копия экранирования на проект); без библиотеки ответ всё равно валиден, строки лишь беднее.
if [ -f "$ENODIA_DIR/json-lib.sh" ]; then . "$ENODIA_DIR/json-lib.sh"; fi
if [ -f "$ENODIA_DIR/daemon-lib.sh" ]; then . "$ENODIA_DIR/daemon-lib.sh"; fi
command -v pid_runs >/dev/null 2>&1 || pid_runs() { [ -n "$1" ] && [ -d "/proc/$1" ]; }
command -v exe_deleted >/dev/null 2>&1 || exe_deleted() { ls -l /proc/[0-9]*/exe 2>/dev/null | sed -n 's#^.* /proc/\([0-9][0-9]*\)/exe -> \(.*\) (deleted)$#\1 \2#p'; }
command -v jesc  >/dev/null 2>&1 || jesc()   { tr -d '\000-\037"\\' | cut -c1-"$1"; }   # диапазон первым — C111
command -v jlines >/dev/null 2>&1 || jlines() { cat >/dev/null; }
# ИДЁТ ЛИ ОБНОВЛЕНИЕ И ЧЕМ КОНЧИЛОСЬ ПОСЛЕДНЕЕ. Фон запускает CGI (`gh_apply_scripts`): состояние RUNNING → OK | FAIL (у
# прежних установок — DONE: итог тогда не записывался). Держатель — ЖИВОЙ ПРОЦЕСС по пидфайлу фона, а не строка в файле:
# перезагрузка посреди обновления оставляет RUNNING навсегда, и экран «идёт обновление» не кончился бы никогда.
GH_UPD_STATE="$ENODIA_STATE/.gh-update.state"
GH_UPD_LOG="$ENODIA_STATE/.gh-update.log"
GH_UPD_PID=/tmp/enodia-gh-update.pid
upd_running() {
    # RBRUN — идёт откат (CGI `gh_rollback` держит пидфайл своим pid на время отката): для гарда кнопок это то же «занято» —
    # обновление поверх отката и второй откат перемешали бы наборы (ревью шага 6c, круг 2).
    case "$(cat "$GH_UPD_STATE" 2>/dev/null | tr -cd 'A-Z')" in RUNNING|RBRUN) : ;; *) return 1 ;; esac
    # Держатель — ЖИВОЙ и НАШ: фон обновления (`sh -c "… gh-update.sh …"`) или CGI отката (`…/cgi-bin/action`). Сирота RBRUN/RUNNING
    # (CGI убит по таймауту uhttpd, обёртку убили) с переиспользованным pid иначе держала бы «идёт» и запертые кнопки, пока жив чужой
    # процесс (ревью шага 6c, круг 3; разбор у daemon-lib.sh::pid_runs).
    _up=$(cat "$GH_UPD_PID" 2>/dev/null | tr -cd '0-9')
    pid_runs "$_up" 'gh-update\.sh|cgi-bin/action' 
}
# check-json: {"local":{…},"remote":{…}|null,"verdict":"newer|current|none|refused|fail","why":"…","repo","ref"}.
# none — на GitHub НЕТ описания релиза (404: этим каналом не публикуют — штатно); fail — GitHub не ответил вовсе (сеть) ЛИБО
# описание есть, но ставить его нельзя (подпись не сошлась, формат новее, поле вне правил, нечем проверить) — тогда причина в
# `why` обязательна; refused — ответил, но не даст (429/403). `remote` — только у описания, чья подпись СОШЛАСЬ.
cmd_check_json() {
    lc=$(local_code); ln=$(local_name)
    rel_load
    _why="$REL_WHY"; _rem=null
    case "$REL_STATE" in
        ok)
            if [ "$REL_CODE" -gt "$lc" ]; then _v=newer; else _v=current; fi
            _rem="{\"name\":\"$(printf '%s' "$REL_VERSION" | jesc 60)\",\"code\":$REL_CODE}" ;;
        none)    _v=none ;;
        refused) _v=refused ;;
        *)       _v=fail ;;
    esac
    printf '{"local":{"name":"%s","code":%s},"remote":%s,"verdict":"%s","why":"%s","repo":"%s","ref":"%s"}\n' \
        "$(printf '%s' "$ln" | jesc 60)" "$lc" "$_rem" "$_v" "$(printf '%s' "$_why" | jesc 300)" \
        "$(printf '%s' "$REPO" | jesc 120)" "$(printf '%s' "$GH_REF" | jesc 60)"
}
# verify-json: {"state":"ok|nosums","src":"pkg|github","bins":true|false,"same":N,"diff":[…],"miss":[…],"old":[…],"ref":"…"} — что
# из установленного расходится. src=pkg — код сверен с суммами установленного пакета (расхождение = файл правили на роутере или
# он побился), src=github — с суммами репо (установка с компьютера; дев-сборка новее публичного снимка ⇒ расхождения тогда норма).
# bins=false — бинари НЕ сверяли (нет манифеста или арка не опознана): панель обязана это сказать, иначе «расходится 0» читается
# как «программы протоколов целы» (ревью ветки, круг 2). old — «путь версия» прежних подписанных сборок (см. verify_scan).
cmd_verify_json() {
    # Вывод `log` из сетевого круга (аварийный канал через десинк, «TLS: …» на сборках со сломанным CApath) — в stdout: без
    # перенаправления он вставал ПЕРЕД JSON, и панель читала «ответил не то» ровно на той сети, ради которой канал заведён
    # (ревью шага 6c, круг 1). Вердикт живёт в $SUMS_STATE — вывод не нужен.
    _vt="$GH_TMP/vf"
    if ! verify_all "$_vt" ""; then
        rm -f "$_vt.diff" "$_vt.miss" "$_vt.old"
        printf '{"state":"nosums","src":"none","bins":false,"same":0,"diff":[],"miss":[],"old":[],"ref":"%s"}\n' "$(printf '%s' "$GH_REF" | jesc 60)"; return 0
    fi
    _vjb=false; [ "$VS_SRC" = pkg ] && [ "$VS_BINS" = 1 ] && _vjb=true
    printf '{"state":"ok","src":"%s","bins":%s,"same":%s,"diff":[' "$VS_SRC" "$_vjb" "$nsame"; jlines 200 < "$_vt.diff"
    printf '],"miss":['; jlines 200 < "$_vt.miss"
    printf '],"old":['; jlines 200 < "$_vt.old"
    printf '],"ref":"%s"}\n' "$(printf '%s' "$GH_REF" | jesc 60)"
    rm -f "$_vt.diff" "$_vt.miss" "$_vt.old"
}
# ПОЧЕМУ ОБНОВЛЕНИЕ (ИЛИ ОТКАТ) НЕ УДАЛОСЬ — первая строка-отказ журнала: последняя строка там — совет («набор СМЕШАННЫЙ —
# повторите или откатитесь», «освободить место: …»), а не причина (ревью шага 6c, круг 1). Метку этапа снимаем — её экран не
# показывает. Пусто — отказа в журнале нет (или журнал прежнего формата).
upd_why() {
    [ -f "$GH_UPD_LOG" ] || return 0
    grep -E '^\[(apply|rollback)\] (СТОП:|FAIL |на GitHub нет|на GitHub код|нет снимков|нет .*pkg-install\.sh|не открыть|не создать|снимок СТАРЕЕ)' "$GH_UPD_LOG" 2>/dev/null \
        | head -n 1 | sed 's/^\[[a-z]*\] //'
}
# status-json: версия, источник, снимки отката, последнее обновление журналом.
# Без сети: экран «Обновление» спрашивает его на каждый показ и раз в две секунды, пока обновление идёт.
# `rb` — можно ли откатиться к последнему снимку. Гард формы входа (`rb_guard`) судит СОДЕРЖИМОЕ снимка, а снимки пакетного пути
# снимает только установщик, появившийся позже формы входа, ⇒ у них ответ заведомо «можно»; распаковывать архив на каждый опрос
# (раз в две секунды) ради заведомого ответа незачем. Сам откат гард всё равно проверяет.
cmd_status_json() {
    _sn=""; _last=""
    for _d in $(snap_list); do
        _sn="$_sn${_sn:+,}\"$(printf '%s' "${_d%.tar.gz}" | jesc 40)\""; _last="$_d"
    done
    _rb=null; [ -n "$_last" ] && _rb=true
    _st=$(cat "$GH_UPD_STATE" 2>/dev/null | tr -cd 'A-Z'); [ -n "$_st" ] || _st=IDLE
    _run=false; upd_running && _run=true
    _at=$(stat -c %Y "$GH_UPD_LOG" 2>/dev/null); case "$_at" in ''|*[!0-9]*) _at=0 ;; esac
    # СКОЛЬКО ФАЙЛОВ ОСТАЛОСЬ ЗАМЕНЁННЫМИ после прогона — от этого совет на экране: большинство отказов (нет сети, подпись,
    # даунгрейд, мало места) случаются ДО первой замены, сбой посреди замены установщик откатывает сам («итог: заменено 0»), и
    # «откатитесь» тогда унёс бы прошлое УДАЧНОЕ обновление (ревью шага 6c, круг 2). Число — из ПОСЛЕДНЕЙ строки итога.
    _rp=$(grep '^\[\(apply\|rollback\)\] итог: заменено [0-9]' "$GH_UPD_LOG" 2>/dev/null | tail -n 1 | sed 's/.*заменено \([0-9]*\).*/\1/')
    case "$_rp" in ''|*[!0-9]*) _rp=0 ;; esac
    printf '{"name":"%s","code":%s,"repo":"%s","ref":"%s","snaps":[%s],"rb":%s,"apply":{"state":"%s","running":%s,"at":%s,"now":%s,"replaced":%s,"why":"%s","log":[' \
        "$(printf '%s' "$(local_name)" | jesc 60)" "$(local_code)" "$(printf '%s' "$REPO" | jesc 120)" "$(printf '%s' "$GH_REF" | jesc 60)" \
        "$_sn" "$_rb" "$_st" "$_run" "$_at" "$(date +%s)" "$_rp" "$(printf '%s' "$(upd_why)" | jesc 600)"
    # Потолок строки 600: причина 429 весит ~310–330 байт (разбор у packages.sh::cmd_op_json).
    [ -f "$GH_UPD_LOG" ] && tail -n 60 "$GH_UPD_LOG" 2>/dev/null | jlines 600
    printf ']}}\n'
}

case "$1" in
    fetch-bin)     fetch_bin "$2" "$3" "$4" ;;
    # Загрузка бинаря с компьютера (разбор у cmd_bin_stage): принять файл · что принято · арка роутера (имя файла для двери панели).
    bin-stage)     cmd_bin_stage "$2" "$3" ;;
    bin-staged)    cmd_bin_staged ;;
    bin-unstage)   cmd_bin_unstage ;;
    bin-arch)      bin_arch ;;
    check)         cmd_check ;;
    apply)         cmd_apply "$2" ;;
    rollback)      cmd_rollback ;;
    verify)        cmd_verify "$2" ;;
    check-json)    cmd_check_json ;;
    verify-json)   cmd_verify_json ;;
    status-json)   cmd_status_json ;;
    upd-busy)      upd_running ;;
    why)           upd_why ;;       # причина отказа последнего обновления/отката одной строкой (итог кнопки «Откатить» в CGI)   # 0 = обновление идёт прямо сейчас (гард кнопки в cgi-bin/action)
    reachable)     gh_reachable "$2" ;;
    # Манифест бинарей установленной версии (он в пакете кода; сети не нужно). bin-size/bin-ver — ответы на «сколько займёт» и
    # «что за версия» одним словом, чтобы вызывающему не разбирать TSV.
    bin-manifest)  cat "$BM_FILE" 2>/dev/null ;;
    bin-size)      bin_size "$2" "$3" ;;
    bin-ver)       bin_ver "$2" ;;
    # bin-status — «стоит ли свежая сборка и какая работает» по факту, без сети (разбор у bin_status).
    bin-status)    shift; bin_status "$@" ;;
    bin-stale)     shift; bin_stale "$@" ;;
    # Закачка заранее (движок компонентов, разбор у BIN_PREFETCH): скачать в ОЗУ · убрать скачанное.
    bin-prefetch)  cmd_bin_prefetch "$2" ;;
    bin-unprefetch) cmd_bin_unstage "$BIN_PREFETCH" ;;
    *) echo "usage: $0 fetch-bin <name> <dst> [minsz] | check | apply [--force] | rollback | verify [путь] | check-json | verify-json | status-json | upd-busy | reachable [path] | bin-manifest | bin-size <имя> [min|max] | bin-ver <имя> | bin-status [имя…] | bin-stale [имя…] | bin-stage <имя> <файл> | bin-staged | bin-unstage | bin-prefetch <имя> | bin-unprefetch | bin-arch"; exit 2 ;;
esac
_rc=$?
# Кэш сумм — временный (свежий на каждый запуск): протухшая копия молча пропустила бы
# подменённый файл следующего релиза. Отметку кода GitHub убираем ЗДЕСЬ и только здесь: в
# trap её ставить нельзя — EXIT срабатывает и в ФОНОВОЙ подоболочке закачки, то есть стёр бы
# вердикт ровно перед тем, как родитель его прочтёт.
case "$GH_TMP" in /tmp/enodia-gh.*) rm -rf "$GH_TMP" 2>/dev/null ;; esac
exit $_rc
