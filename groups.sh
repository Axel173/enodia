#!/bin/sh
# groups.sh — ИМЕНОВАННЫЕ ГРУППЫ правил «в VPN / мимо VPN».
#
# ЗАЧЕМ. Плоские списки панели («Домены через VPN», «Сайты мимо VPN») не дают смысловых пачек:
# «bybit» = десяток доменов биржи, «игры» = свой набор. Такую пачку хочется ВКЛЮЧАТЬ/ВЫКЛЮЧАТЬ и
# СНОСИТЬ целиком, а не выковыривать по строке, и видеть, ЧТО это за набор, спустя полгода.
#
# АРХИТЕКТУРА — кладём на СУЩЕСТВУЮЩИЕ рельсы, нового слоя маршрутизации НЕ вводим:
#   группа = { имя, направление dir=vpn|bypass, вкл/выкл, члены (домены и/или IP/CIDR) }
#   Все ВКЛЮЧЁННЫЕ группы сводятся в ДВА ipset:
#     grp_vpn — «в VPN»:    его метит mark-core.sh тем же циклом, что enodia_list/iplist_set → MARK 0x1
#                           (добавление сета в цикл — одно слово; ветвление по mipctld там уже есть).
#     grp_out — «мимо VPN»: ACCEPT по dst в цепочке VPN_EXCLUDE (apply-bypass.sh set-dst-ensure).
#                           Цепочка стоит ПЕРВОЙ в mangle PREROUTING → ACCEPT рвёт обход mangle
#                           РАНЬШЕ mark-правил, т.е. группа «мимо VPN» перебивает общий CIDR-список.
#   Домены-члены НЕ резолвим в снимок IP (так делает старый dom_bypass — CDN крутит адреса, и снимок
#   протухает через час). Пишем dnsmasq `ipset=/дом/grp_vpn|grp_out` → dnsmasq САМ кладёт каждый
#   свежерезолвленный A-адрес в нужный set. Это динамика, а не фотография.
#
# ПОЧЕМУ ДВА ОБЩИХ СЕТА, А НЕ ПО СЕТУ НА ГРУППУ. Сет на группу дал бы точечную пересборку, но
# требовал бы ДИНАМИЧЕСКИХ iptables-правил (по правилу на группу, с логикой mipctld-вставки из
# mark-core) — это дубль ядра и рост числа правил на каждый чих пользователя. Два сета = два
# статичных правила, которые ставятся один раз и переигрываются heal/repair как всё остальное.
#
# --- ГРУППА, ПРИВЯЗАННАЯ К УСТРОЙСТВУ (поле src) ---------------------------------------
# ЗАЧЕМ. «Этому ТВ — ютуб через выход №3, остальным — как обычно». Общие сеты такое не выражают:
# они действуют на ВСЮ сеть. Значит правило обязано матчить источник, а адреса назначения держать
# в СВОЁМ сете — отсюда группа с непустым src: её члены едут в `grp_dev_<id>`, а правило
# `-s <ip> -m set --match-set grp_dev_<id> dst` ставит apply-bypass.sh в цепочке VPN_DEV (владелец
# цепочек mangle — он; мы отдаём ему машинный список вербом `dev-rules`). Направление у такой
# группы — vpn (в туннель/доп-выход), bypass (напрямую) или block (не выпускать вовсе).
#
# ПОЧЕМУ ЭТО ГРУППА, А НЕ СВОЯ ПОДСИСТЕМА. Не «DRY ради DRY»: домен устройства и домен глобального
# правила ОБЯЗАНЫ жить в одном dnsmasq-conf — см. следующий абзац. Заодно даром достаются
# нормализация членов, персист, бэкап, прогрев и переигрыш на буте.
#
# ГРАБЛЯ, ЗАДАЮЩАЯ ФОРМУ ФАЙЛА: dnsmasq кладёт адрес РОВНО В ОДИН сет на домен. При двух строках
# `ipset=/youtube.com/grp_vpn_s2` и `ipset=/youtube.com/grp_dev_g7` он не сливает их, а ВЫБИРАЕТ
# одну (2.86: выигрывает самый длинный домен, при равенстве — ПЕРВАЯ прочитанная строка, а файлы
# conf-dir читаются по алфавиту; замерено на железе 03.08.2026 изолированным инстансом) ⇒
# второй сет не наполнится НИКОГДА, и правило по нему станет вечно мёртвым. Поэтому conf пишется
# АГРЕГИРОВАННО: одна строка на домен, сеты через запятую (`ipset=/дом/a,b`), и в неё же
# подмешиваются сеты РОДИТЕЛЬСКИХ доменов — правило `/youtube.com/` дnsmasq применит к
# `m.youtube.com` только если у того нет своей, более длинной строки (то же «выигрывает длинный»).
# Читатели этого conf (devwatch.sh, slots.sh) обязаны разбирать СПИСОК через запятую, а не
# анкорить имя сета на конец строки.
# Здесь агрегируется только СВОЙ файл. Домены, названные ЕЩЁ И в чужих conf'ах (гео, одиночные
# правила, пул десинка), склеивает общий агрегатор dns-merge.sh — он же и перечитывает dnsmasq
# (см. dns_reload ниже); панель про такой домен лишь пишет «есть и в других списках».
#
# ГРАБЛИ (полностью — в карте проекта):
#  - conf пишем в ЖИВОЙ /tmp/dnsmasq.d (RAM!), НЕ в /etc/dnsmasq.d: стоковый init.d dnsmasq на
#    рестарте КОПИРУЕТ /etc/dnsmasq.d/* в /tmp АДДИТИВНО и НЕ чистит → выключенная группа
#    воскресала бы после каждого рестарта. /tmp стирается на ребуте → переигрывает heal.sh.
#  - ПЕРЕСБОРКА сета стирает уже резолвленные dnsmasq'ом IP. Прогрев резолвом (в конце do_apply)
#    закрывает это ЛИШЬ ЧАСТИЧНО — он знает только имена ИЗ СОСТАВА, а у CDN резолвятся не они, а
#    живые хосты, известные одним клиентам. Поэтому пересборкой ведает set_sync из set-lib.sh: состав не
#    менялся — сет не трогаем вовсе, домены те же — динамику возвращаем. Разбор — в его шапке.
#    Ровно эта грабля ловилась на domain.sh (флаш enodia_list без прогрева = «добавил домен, а он не
#    идёт через VPN», пока клиент не перерезолвит — а с DoH/кэшем он может не сделать этого никогда).
#  - apply_ipset() из lists-lib.sh тут НЕ годится: он СОЗНАТЕЛЬНО не трогает сет при нуле записей
#    (страховка от кривой закачки блоклиста). Здесь источник — воля пользователя, а не сеть:
#    «убрал все IP из группы» ДОЛЖНО означать пустой сет. Поэтому свой swap — set_fill() из set-lib.sh.
#
# Персист (переживает ребут): $ENODIA_STATE/groups/groups.tsv (реестр) + <id>.list (члены).
# Всё эфемерное (сеты, dnsmasq-conf, правила) собирается из персиста командой `apply`.

ENODIA_DIR=${ENODIA_DIR:-/data/usr/app/enodia}
ENODIA_STATE=${ENODIA_STATE:-/data/usr/app/enodia-state}
# Сброс УЖЕ УСТАНОВЛЕННЫХ соединений — только через ct-lib.sh: на ядре 4.4 (AX3600/BE3600)
# утилиты conntrack в прошивке НЕТ ВООБЩЕ, и прежний `conntrack -F || true` был тихим no-op —
# правило стояло, а поток шёл по-старому через NSS/ECM. Шим = прежнее поведение (частичный
# apply-scripts не должен падать), полноценный сброс живёт в самой библиотеке.
