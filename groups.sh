# Пересборка наборов живёт в ОБЩЕМ слое set-lib.sh (там же — почему нельзя просто пересобирать
# «с нуля из статики»): у наших наборов ДВА источника, CIDR состава и A-записи от dnsmasq.
# Сорсим ТОЛЬКО под `[ -f ]`: провалившийся `.` в ash — фатальная ошибка спецбилтина, шелл
# выходит НА МЕСТЕ (никакой `|| true` не спасает), а тут это означало бы «нет групп вообще».
if [ -f "$ENODIA_DIR/set-lib.sh" ]; then . "$ENODIA_DIR/set-lib.sh"; fi
# Шим на случай частичного apply-scripts (он льёт ПОФАЙЛОВО): группы продолжают работать, но
# ведут себя как до 03.08.2026 — динамика dnsmasq теряется на каждом apply. Это осознанная
# деградация, а не мёртвый код: без файла библиотека не сорснётся, и функций не будет.
if ! command -v set_sync >/dev/null 2>&1; then
	set_ensure() { ipset list -n 2>/dev/null | grep -qx "$1" || ipset create "$1" hash:net hashsize 1024 maxelem 65536 2>/dev/null; }
	set_fill() {
		_s="$1"; _f="$2"
		set_ensure "$_s"
		ipset destroy "${_s}_new" 2>/dev/null
		ipset create "${_s}_new" hash:net hashsize 1024 maxelem 65536 2>/dev/null || return 1
		if [ -s "$_f" ]; then
			awk -v s="${_s}_new" '/^[0-9]/{print "add " s " " $1}' "$_f" | ipset restore -exist 2>/dev/null
		fi
		ipset swap "${_s}_new" "$_s" 2>/dev/null
		ipset destroy "${_s}_new" 2>/dev/null
	}
	set_sync() { set_fill "$1" "$2"; }
fi

