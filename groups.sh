# grp_sync <сет> <файл CIDR> <файл пар «домен⇥сет»> — обёртка над общим set_sync: вытащить домены
# ИМЕННО ЭТОГО набора из общего файла пар (домен может числиться сразу за несколькими наборами —
# см. emit_dnsconf) и отдать их сигнатурой.
grp_sync() {
	_gs_d="/tmp/.enodia-grp-dom.$$"
	awk -F"$TAB" -v s="$1" '$2==s{print $1}' "$3" 2>/dev/null > "$_gs_d"
	set_sync "$1" "$2" "$_gs_d"; _gs_rc=$?
	rm -f "$_gs_d" 2>/dev/null
	return $_gs_rc   # код от set_sync, а не от `rm` (иначе провал заливки читался бы как успех)
}

set_count() {  # число членов ipset; фолбэк для ядра 4.4 (нет «Number of entries») — канон см. ipset_count в lists-lib.sh
	_n=$(ipset list "$1" 2>/dev/null | sed -n 's/^Number of entries:[[:space:]]*//p' | head -1)
	case "$_n" in ''|*[!0-9]*) _n=$(ipset list "$1" 2>/dev/null | grep -cE '^[0-9]') ;; esac
	case "$_n" in ''|*[!0-9]*) _n=0 ;; esac
	printf '%s' "$_n"
}

# --- dnsmasq-conf: ОДНА строка на домен ---------------------------------------
# emit_dnsconf <файл пар «домен⇥сет»> — собрать $DNSCONF из пар, агрегируя сеты домена.
#
# ПОЧЕМУ НЕЛЬЗЯ ПРОСТО ПИСАТЬ ПО СТРОКЕ НА ГРУППУ (грабля, ради которой всё это): dnsmasq выбирает
# для домена РОВНО ОДНУ ipset=-строку — самую длинную по домену, при равенстве первую прочитанную;
# сеты разных строк НЕ складываются. Значит домен, попавший в две группы (или в группу и в правило
# устройства), наполнял бы только один сет, а правило по второму молча не работало бы никогда.
#
# ДВЕ ЧАСТИ АГРЕГАЦИИ:
#  1) сеты ОДНОГО домена — через запятую (`ipset=/дом/a,b`);
#  2) сеты РОДИТЕЛЬСКИХ доменов подмешиваем в строку потомка: своя строка у `m.youtube.com`
#     ОТМЕНЯЕТ действие строки `youtube.com` (то же «выигрывает длинный»), и без подмешивания
#     родительское правило для этого поддомена молча перестало бы работать.
# Порядок перебора сетов задаёт awk-хеш — он стабилен для одного и того же ввода, поэтому conf не
# «дрожит» между пересборками. Ни split(), ни index() (busybox awk их не знает): вместо разбора
# строки-списка держим факты в карте have[домен,сет], а к родителю поднимаемся sub()'ом.
emit_dnsconf() {
	# Черновик с ПИДом в имени: без лока (шим-ветка) два прохода писали бы в один `.new` и
	# выложили бы половину чужой сборки. Маска conf-dir'а — `*.conf`, так что промежуточное имя
	# dnsmasq не подхватит, а mv в пределах /tmp атомарен.
	_ed_n="$DNSCONF.$$.new"
	: > "$_ed_n"
	if [ -s "$1" ]; then
		sort -u "$1" | awk -F"$TAB" '
			{ have[$1 SUBSEP $2] = 1; dom[$1] = 1; st[$2] = 1 }
			END {
				for (d in dom) {
					out = ""
					for (t in st) {
						hit = 0; p = d
						if ((d SUBSEP t) in have) hit = 1
						else while (sub(/^[^.]+\./, "", p)) if ((p SUBSEP t) in have) { hit = 1; break }
						if (hit) out = (out == "" ? t : out "," t)
					}
					if (out != "") print "ipset=/" d "/" out
				}
			}' | sort >> "$_ed_n"
	fi
	mv "$_ed_n" "$DNSCONF"
}

# dev_wire "<id групп устройств>" — переиграть правила групп, привязанных к устройству.
# Владелец цепочек mangle PREROUTING — apply-bypass.sh (порядок цепочек держит он один), поэтому
# правила ставит ОН, а мы лишь сообщаем, что состав изменился; сам список он читает вербом
# `dev-rules` (машинный TSV), а не парсит наш реестр.
# Зовём и когда групп НЕ осталось, но цепочка ещё стоит — иначе снятое правило жило бы до ребута.
# У того, кто фичей не пользуется, не происходит ничего (одна проверка -L и выход).
dev_wire() {
	if [ -n "$1" ] || iptables -t mangle -L VPN_DEV -n >/dev/null 2>&1; then
		sh "$ENODIA_DIR/apply-bypass.sh" dev-rebind >/dev/null 2>&1 || true
	fi
	# Сеты удалённых групп: сносим ПОСЛЕ переигрыша правил (сет, на который ссылается правило,
	# ipset destroy не отдаст) — иначе они копились бы в ОЗУ до перезагрузки.
	for _os in $(ipset list -n 2>/dev/null | grep '^grp_dev_'); do
		case " $1 " in *" ${_os#grp_dev_} "*) continue ;; esac
		ipset destroy "$_os" 2>/dev/null || true
	done
}

# --- правила ------------------------------------------------------------------
# Маркировку grp_vpn ставит mark-core.sh (там же логика «выше miwifi/NFQUEUE» — дублировать её
# здесь нельзя, это ядро). Сет создаётся ПОЗЖЕ mark-core (первая группа появляется в рантайме),
# а mark-core ставит правило только для СУЩЕСТВУЮЩЕГО сета → после создания сета правила ещё нет.
# Поэтому: правила нет → зовём mark-core (идемпотентен). Есть → не трогаем живой mangle зря.
wire_rules() {
	iptables -t mangle -C PREROUTING -m set --match-set "$SET_VPN" dst -j MARK --set-mark 0x1 2>/dev/null \
		|| iptables -t mangle -C PREROUTING -m set --match-set "$SET_VPN" dst -j ACCEPT 2>/dev/null \
		|| sh "$ENODIA_DIR/mark-core.sh" >/dev/null 2>&1 || true
	# ACCEPT по grp_out в VPN_EXCLUDE — хозяин цепочки apply-bypass.sh (идемпотентно, он же
	# переигрывает это на boot/repair в apply_all).
	sh "$ENODIA_DIR/apply-bypass.sh" set-dst-ensure "$SET_OUT" >/dev/null 2>&1 || true
}

# --- сборка -------------------------------------------------------------------
# ОДИН проход сборки: dnsmasq-conf + оба сета + правила + прогрев. Идемпотентен, безопасно звать
# сколько угодно раз (heal зовёт на каждом буте). Снаружи его дёргает СЕРИАЛИЗОВАННЫЙ do_apply.
# Рабочие файлы — с ПИДом в имени: раньше они звались фиксированно (/tmp/.grp-pairs и т.п. — legacy-name:
# так это выглядело ТОГДА, переписывать историю нельзя), и
# второй одновременный проход писал в них же ⇒ сеты собирались из полу-данных (ревью 04.08.2026).
# Лок ниже это и так закрывает, но у него есть шим-ветка «лока нет» — там имена остаются защитой.
_apply_pass() {
	mkdir -p /tmp/dnsmasq.d 2>/dev/null
	_tp="/tmp/.enodia-grp.$$"
	_cv="$_tp-vpn.cidr"; _co="$_tp-out.cidr"; _pairs="$_tp-pairs"
	: > "$_cv"; : > "$_co"; : > "$_pairs"
	# Доп-выходы (Ф1): члены группы «в VPN», привязанной к слоту N, идут в СВОЙ сет grp_vpn_s<N>
	# (его метит mark-core / врайрит zapret-слот), а не в общий grp_vpn. Свои CIDR-накопители на
	# слот; _any_slot взводится, если хоть одна включённая группа привязана к доп-выходу.
	for _n in 2 3 4; do : > "$_tp-vpn-s$_n.cidr"; : > "$_tp-vpn-s$_n.dom"; done
	_any_slot=0; _dev_ids=""
	# Список ВКЛЮЧЁННЫХ доп-выходов (slots.sh). Привязка к выключенному/удалённому слоту → группа
	# едет ОСНОВНЫМ выходом (grp_vpn), а не молча напрямую: слот = АЛЬТЕРНАТИВНЫЙ выход, его отказ
	# не должен ронять приватность «в VPN»-группы (семантика fallback=main).
	_en_slots=" "
	[ -f "$ENODIA_DIR/slots.sh" ] && _en_slots=" $(sh "$ENODIA_DIR/slots.sh" list-enabled 2>/dev/null | cut -f1 | tr '\n' ' ') "
	# Поля реестра разделены TAB (имя — последнее поле, может содержать пробелы) → IFS=TAB на
	# время разбора. Внутренний цикл по членам имеет СВОЙ редирект (< файл), поэтому за stdin
	# с внешним не дерётся; IFS внутри возвращаем в дефолтный — члены разделены переводом строки.
	_old_ifs="$IFS"; IFS="$TAB"
	while read -r _id _en _dir _slot _name _src; do
		[ -n "$_id" ] || continue
		[ "$_en" = 1 ] || continue
		_f=$(mfile "$_id"); [ -f "$_f" ] || continue
		case "$_slot" in 2|3|4) ;; *) _slot=0 ;; esac
		if [ -n "$_src" ]; then
			# Группа УСТРОЙСТВА: свой сет, общие пулы не трогаем. Гейт выключенного/zapret-выхода
			# держит apply-bypass (он же владелец правила) — сюда слот входит СЫРЫМ, иначе панель
			# не смогла бы показать, что человек выбрал, пока выход временно выключен.
			_set=$(dev_set "$_id"); _cf="$_tp-dev-$_id.cidr"; : > "$_cf"
			_dev_ids="$_dev_ids $_id"
		else
			# Слот должен существовать И быть включён — иначе группа падает на основной выход.
			[ "$_slot" != 0 ] && case "$_en_slots" in *" $_slot "*) ;; *) _slot=0 ;; esac
			# Целевой сет: bypass → grp_out (слот неприменим); vpn+slot>0 → grp_vpn_s<N>; иначе grp_vpn.
			if [ "$_dir" = bypass ]; then
				_set="$SET_OUT"; _cf="$_co"
			elif [ "$_slot" != 0 ]; then
				_set="grp_vpn_s$_slot"; _cf="$_tp-vpn-s$_slot.cidr"; _any_slot=1
			else
				_set="$SET_VPN"; _cf="$_cv"
			fi
		fi
		# Член = либо IP/CIDR (в сет напрямую), либо домен (в dnsmasq — пусть кладёт живые A-записи).
		IFS="$_old_ifs"
		while read -r _m; do
			[ -n "$_m" ] || continue
			if is_cidr "$_m"; then
				echo "$_m" >> "$_cf"
			elif is_dom "$_m"; then
				# В conf домен идёт НЕ строкой на группу, а парой «домен⇥сет» — строки собирает
				# emit_dnsconf, агрегируя все сеты домена в ОДНУ (см. шапку: dnsmasq выбирает
				# ровно одну строку на домен, поэтому две строки = один сет наполняется, второй
				# мёртв).
				printf '%s\t%s\n' "$_m" "$_set" >> "$_pairs"
				# Домен слота учитываем ОТДЕЛЬНО: сет слота ниже создаётся, только если у него
				# есть содержимое. dnsmasq сеты НЕ создаёт — он лишь кладёт A-записи в
				# СУЩЕСТВУЮЩИЙ; без этой отметки пул из ОДНИХ доменов на свежем выходе не
				# получал бы сета вовсе (правило ipset= молча впустую, трафик мимо выхода).
				[ -z "$_src" ] && [ "$_slot" != 0 ] && echo "$_m" >> "$_tp-vpn-s$_slot.dom"
			fi
		done < "$_f"
		IFS="$TAB"
	done < "$REG"
	IFS="$_old_ifs"
	emit_dnsconf "$_pairs"
	# Провалы заливки КОПИМ, а не глотаем: набор остался старым, и об этом обязан узнать человек.
	_fail=""
	grp_sync "$SET_VPN" "$_cv" "$_pairs" || _fail="$_fail $SET_VPN"
	grp_sync "$SET_OUT" "$_co" "$_pairs" || _fail="$_fail $SET_OUT"
	# Сеты групп устройств — по сету на группу (их адреса не смешиваются ни с общими пулами, ни
	# между устройствами). Домены наполнит dnsmasq, важно, что сет СОЗДАН (зеркало слот-сетов ниже).
	for _gid in $_dev_ids; do grp_sync "$(dev_set "$_gid")" "$_tp-dev-$_gid.cidr" "$_pairs" || _fail="$_fail $(dev_set "$_gid")"; done
	# Слот-сеты: заполняем те, что имеют членов ИЛИ уже существуют (иначе IP, потерянные при
	# отвязке группы от слота, залипли бы в старом сете). Пустой файл = пустой сет (воля юзера).
	for _n in 2 3 4; do
		_sf="$_tp-vpn-s$_n.cidr"; _df="$_tp-vpn-s$_n.dom"
		if [ -s "$_sf" ] || [ -s "$_df" ] || ipset list -n 2>/dev/null | grep -qx "grp_vpn_s$_n"; then
			grp_sync "grp_vpn_s$_n" "$_sf" "$_pairs" || _fail="$_fail grp_vpn_s$_n"   # домены наполнит dnsmasq — важно, что сет СОЗДАН (зеркало geo.sh)
		fi
	done
	wire_rules
	dev_wire "$_dev_ids"
	# Доп-выходы: есть привязки к слотам → переиграть слоты через ОРКЕСТРАТОР (zapret-слот ставит
	# ACCEPT+NFQUEUE на свои сеты, non-zapret — марку через mark-core). Идемпотентно. Нет привязок
	# → не зовём (панель без доп-выходов работает БАЙТ-В-БАЙТ как раньше).
	[ "$_any_slot" = 1 ] && [ -f "$ENODIA_DIR/transport.sh" ] && sh "$ENODIA_DIR/transport.sh" slots-up >/dev/null 2>&1
	dns_reload
	# ПРОГРЕВ: пересборка сетов стёрла IP, которые dnsmasq успел туда положить. Без прогрева домен
	# группы поедет НЕ ТУДА, пока клиент не перерезолвит (с DoH/кэшем — может и никогда). nslookup
	# бьёт в свой же dnsmasq → он резолвит и СРАЗУ кладёт адреса в сет по ipset=-правилу.
	# Список доменов берём из СОБРАННОГО conf — он уже дедуплицирован агрегацией (домен, лежащий в
	# трёх группах, прогревался бы трижды).
	sed -n 's|^ipset=/\([^/]*\)/.*|\1|p' "$DNSCONF" 2>/dev/null | while read -r _d; do
		[ -n "$_d" ] || continue
		nslookup "$_d" >/dev/null 2>&1 || true
	done
	rm -f "$_cv" "$_co" "$_pairs" 2>/dev/null
	for _gid in $_dev_ids; do rm -f "$_tp-dev-$_gid.cidr" 2>/dev/null; done
	for _n in 2 3 4; do rm -f "$_tp-vpn-s$_n.cidr" "$_tp-vpn-s$_n.dom" 2>/dev/null; done
	# NSS/ECM-offload держит УЖЕ установленные соединения на старом маршруте до таймаута —
	# без сброса conntrack изменение группы «не применяется», пока сайт не отвиснет сам.
	ct_flush
	# Провал ЗАЛИВКИ набора (нет памяти, набор занят) — не «успех с нулём адресов»: набор остался
	# СТАРЫМ, и молчать об этом значит показать человеку «применено» там, где ничего не менялось.
	if [ "$_fail" != "" ]; then
		printf 'группы применены ЧАСТИЧНО: не удалось залить наборы:%s (маршрут для них остался прежним)\n' "$_fail"
		return 1
	fi
	printf 'группы применены: в VPN %s, мимо VPN %s (адресов в сетах)\n' "$(set_count "$SET_VPN")" "$(set_count "$SET_OUT")"
}

# do_apply — СЕРИАЛИЗОВАННАЯ обёртка над _apply_pass (калька geo.sh do_build). Раньше лока не было
# вовсе: клик в панели, `dev-add` из CGI и heal на буте могли идти одновременно, писать в одни
# рабочие файлы и в один временный ipset `<набор>_new` — сеты собирались из полу-данных, а счётчики
# в UI врали. Конкурент помечает dirty и выходит; держатель после прохода переигрывает под свежий
# реестр, схлопывая N кликов в ОДИН доп. проход. Печатаем сводку ПОСЛЕДНЕГО прохода — панель кладёт
# stdout в .msg, и вторая строка сбила бы перевод.
do_apply() {
	if ! ls_lock_take "$GRP_LOCK" "$GRP_DIRTY" 1; then
		echo 'группы: сборка уже идёт — учту свежий состав в ней'
		return 0
	fi
	trap 'ls_lock_drop "$GRP_LOCK"' EXIT
	trap 'exit 1' INT TERM HUP PIPE
	_sum=''; _rc=0
	while :; do
		rm -f "$GRP_DIRTY" 2>/dev/null   # сброс ДО чтения реестра: пойманный dirty ⇒ реестр прочитан ПОСЛЕ мутации
		_sum=$(_apply_pass); _rc=$?
		[ -f "$GRP_DIRTY" ] || break
	done
	trap - EXIT INT TERM HUP PIPE
	ls_lock_drop "$GRP_LOCK"
	[ -z "$_sum" ] || echo "$_sum"
	return $_rc
}
# Перечитать dnsmasq — ЧЕРЕЗ АГРЕГАТОР (dns-merge.sh): он склеивает ipset=-строки одного домена
# из РАЗНЫХ подсистем (гео, пул десинка, одиночные правила) и только потом рестартит демона.
# Без него наша строка проиграла бы чужому файлу, который читается раньше по алфавиту, — правило
# было бы видно в панели и мертво. Агрегатора нет/упал → старый путь байт-в-байт: рестарт (не
# SIGHUP — ipset=-строки по HUP не перечитываются, та же грабля, что с address=).
dns_reload() { sh "$ENODIA_DIR/dns-merge.sh" reload 2>/dev/null \
	|| /etc/init.d/dnsmasq restart >/dev/null 2>&1 || killall -HUP dnsmasq 2>/dev/null; }

# --- JSON для панели ----------------------------------------------------------
# Члены отдаём вместе со списком: группы пользовательские (десятки строк), второй round-trip
# ради них не нужен, а редактор в панели открывается мгновенно.
emit_json() {
	printf '{"groups":['
	_first=1
	_old_ifs="$IFS"; IFS="$TAB"
	while read -r _id _en _dir _slot _name _src; do
		[ -n "$_id" ] || continue
		[ "$_first" -eq 1 ] || printf ','
		_first=0
		case "$_slot" in 2|3|4) ;; *) _slot=0 ;; esac
		_f=$(mfile "$_id"); _nd=0; _nc=0
		IFS="$_old_ifs"
		if [ -f "$_f" ]; then
			_nc=$(grep -cE '^[0-9]{1,3}(\.[0-9]{1,3}){3}(/[0-9]{1,2})?$' "$_f" 2>/dev/null)
			case "$_nc" in ''|*[!0-9]*) _nc=0 ;; esac
			# Доменов = строк − адресов: состав — только домены и адреса (его пишет `store_members`). Своя регулярка «домен» здесь
			# была второй копией политики `is_dom` и отстала от неё: зона одним словом (`ru`) и punycode-зона (.рф) считались
			# нулём — группа из одного .рф-домена показывала «0 доменов».
			_nl=$(grep -c . "$_f" 2>/dev/null)
			case "$_nl" in ''|*[!0-9]*) _nl=0 ;; esac
			_nd=$((_nl - _nc)); [ "$_nd" -ge 0 ] || _nd=0
		fi
		# src отдаём и панели: группу устройства она показывает НЕ в общем списке групп, а на
		# экране самого устройства (иначе у человека с тремя устройствами карточка групп
		# превратилась бы в список служебных пачек, которые он не заводил руками).
		printf '{"id":"%s","enabled":%s,"dir":"%s","slot":%s,"src":"%s","name":"%s","domains":%s,"cidrs":%s,"members":[' \
			"$_id" "$([ "$_en" = 1 ] && echo true || echo false)" "$_dir" "$_slot" "$_src" "$_name" "$_nd" "$_nc"
		_mf=1
		if [ -f "$_f" ]; then
			while read -r _m; do
				[ -n "$_m" ] || continue
				_m=$(printf '%s' "$_m" | tr -d '"\\')
				[ "$_mf" -eq 1 ] || printf ','
				_mf=0
				printf '"%s"' "$_m"
			done < "$_f"
		fi
		printf ']}'
		IFS="$TAB"
	done < "$REG"
	IFS="$_old_ifs"
	printf '],"set_vpn":%s,"set_out":%s}\n' "$(set_count "$SET_VPN")" "$(set_count "$SET_OUT")"
}

case "$1" in
	list) emit_json ;;

	add)  # add <vpn|bypass> <имя…>
		_dir="$2"; shift 2; _name=$(san "$*")
		case "$_dir" in vpn|bypass) ;; *) echo "направление: vpn|bypass"; exit 1 ;; esac
		[ -n "$_name" ] || { echo "нужно имя группы"; exit 1; }
		_id=$(next_id)
		printf '%s\t1\t%s\t0\t%s\n' "$_id" "$_dir" "$_name" >> "$REG"
		: > "$(mfile "$_id")"
		echo "группа «$_name» создана ($_id)"
		;;

	add-bound)  # add-bound <slot> <имя…> — создать «в VPN»-группу, СРАЗУ привязанную к доп-выходу
		# (шорткат «Свой пул…» на десинк-слоте: пул сайтов через этот выход одним действием).
		# dir всегда vpn (слот применим только к «в VPN»); группа пустая — домены юзер добавит в
		# редакторе. do_apply при непустом слоте зовёт slots-up (переиграть врайринг слота).
		_slot="$2"; shift 2; _name=$(san "$*")
		is_slot "$_slot" || { echo "слот: 0|2|3|4"; exit 1; }
		[ -n "$_name" ] || { echo "нужно имя группы"; exit 1; }
		_id=$(next_id)
		printf '%s\t1\tvpn\t%s\t%s\n' "$_id" "$_slot" "$_name" >> "$REG"
		: > "$(mfile "$_id")"
		# Сообщение собираем ДО do_apply: у busybox sh нет `local`, а do_apply гоняет
		# `while read … _id _slot _name` до EOF (обнуляет их) и `for _n in 2 3 4` — после него
		# _name/_id/_slot пусты, потому add (echo без промежуточного do_apply) не задет, а мы да.
		_msg="пул «$_name» создан ($_id), выход №$_slot"
		do_apply >/dev/null
		echo "$_msg"
		;;

	del)
		valid_id "$2" || { echo "битый id"; exit 1; }
		reg_del_line "$2"
		rm -f "$(mfile "$2")" 2>/dev/null
		do_apply >/dev/null
		echo "группа удалена"
		;;

	rename)
		valid_id "$2" || { echo "битый id"; exit 1; }
		_id="$2"; shift 2; _name=$(san "$*")
		[ -n "$_name" ] || { echo "нужно имя группы"; exit 1; }
		reg_get "$_id" >/dev/null || { echo "нет такой группы"; exit 1; }
		awk -F"$TAB" -v OFS="$TAB" -v id="$_id" -v nm="$_name" '$1==id{$5=nm} {print}' "$REG" | reg_write
		echo "переименована в «$_name»"
		;;

	dir)  # dir <id> <vpn|bypass> — сменить направление группы (bypass сбрасывает доп-выход в 0)
		valid_id "$2" || { echo "битый id"; exit 1; }
		case "$3" in vpn|bypass) ;; *) echo "направление: vpn|bypass"; exit 1 ;; esac
		reg_get "$2" >/dev/null || { echo "нет такой группы"; exit 1; }
		# Группа устройства собирается из ПОШТУЧНЫХ правил (dev-add/dev-del), и её направление —
		# часть ключа, по которому правило в неё попало. Смена направления «снизу» рассинхронила
		# бы группу с тем, что человек видит на экране устройства.
		[ -n "$(reg_get "$2" | cut -f6)" ] && { echo "это правило устройства — меняется на экране устройства (dev-add/dev-del)"; exit 1; }
		awk -F"$TAB" -v OFS="$TAB" -v id="$2" -v d="$3" '$1==id{$3=d; if(d=="bypass")$4=0} {print}' "$REG" | reg_write
		do_apply >/dev/null
		echo "направление: $([ "$3" = vpn ] && echo 'в VPN' || echo 'мимо VPN')"
		;;

	slot)  # slot <id> <0|2|3|4> — привязать группу к доп-выходу (0 = основной; только для «в VPN»)
		valid_id "$2" || { echo "битый id"; exit 1; }
		is_slot "$3" || { echo "слот: 0|2|3|4"; exit 1; }
		_line=$(reg_get "$2"); [ -n "$_line" ] || { echo "нет такой группы"; exit 1; }
		if [ "$3" != 0 ] && [ "$(printf '%s' "$_line" | cut -f3)" != vpn ]; then
			echo "доп-выход только для групп «в VPN»"; exit 1
		fi
		[ -n "$(printf '%s' "$_line" | cut -f6)" ] && { echo "это правило устройства — меняется на экране устройства (dev-add/dev-del)"; exit 1; }
		awk -F"$TAB" -v OFS="$TAB" -v id="$2" -v s="$3" '$1==id{$4=s} {print}' "$REG" | reg_write
		do_apply >/dev/null
		echo "выход: $([ "$3" = 0 ] && echo 'Основной' || echo "слот №$3")"
		;;

	toggle)  # toggle <id> <0|1>
		valid_id "$2" || { echo "битый id"; exit 1; }
		case "$3" in 0|1) ;; *) echo "нужно 0|1"; exit 1 ;; esac
		reg_get "$2" >/dev/null || { echo "нет такой группы"; exit 1; }
		# Зеркало гарда в `dir`/`slot`. Выключенная группа устройства — худший из исходов: движок
		# её не видит (`dev-rules` берёт только включённые), а карточка устройства показывает
		# правило как есть, и человек получает «правило вижу, эффекта нет». Снимается такое
		# правило вербом dev-del, а не тумблером.
		[ -n "$(reg_get "$2" | cut -f6)" ] && { echo "это правило устройства — снимается на экране устройства (dev-del)"; exit 1; }
		awk -F"$TAB" -v OFS="$TAB" -v id="$2" -v e="$3" '$1==id{$2=e} {print}' "$REG" | reg_write
		do_apply >/dev/null
		echo "группа $([ "$3" = 1 ] && echo включена || echo выключена)"
		;;

	set-members)  # set-members <id> < stdin (по записи на строку; домены и IP/CIDR вперемешку)
		valid_id "$2" || { echo "битый id"; exit 1; }
		reg_get "$2" >/dev/null || { echo "нет такой группы"; exit 1; }
		# Тот же гард: состав группы устройства ведут ПОШТУЧНЫЕ dev-add/dev-del — они же следят,
		# чтобы у значения было РОВНО одно направление. Оптовая замена состава мимо них завела бы
		# один и тот же домен в две группы устройства сразу.
		[ -n "$(reg_get "$2" | cut -f6)" ] && { echo "это правило устройства — состав меняется на экране устройства (dev-add/dev-del)"; exit 1; }
		# Счётчик берём ДО do_apply: тот переиспользует свои `_n`/`_id` (`for _n in 2 3 4`,
		# set_count) — busybox sh без `local` (та же грабля, что в add-bound выше).
		_added=$(store_members "$(mfile "$2")")
		do_apply >/dev/null
		echo "в группе записей: $_added"
		;;

	new)  # new <vpn|bypass> <slot> <имя…> < stdin(состав) — создать группу ВМЕСТЕ с составом
		# одним действием (мастер импорта routing-правил из подписки, Ф4: N групп за проход;
		# add + set-members двумя вызовами дали бы два do_apply и лишний пересбор сетов).
		# Печатает МАШИННУЮ строку «<id><TAB><членов>»: вызывающий (cgi grp_new) строит текст
		# сам — человеческое сообщение ещё и переводится в панели, парсить его нельзя.
		_dir="$2"; _slot="$3"; shift 3; _name=$(san "$*")
		case "$_dir" in vpn|bypass) ;; *) echo "направление: vpn|bypass"; exit 1 ;; esac
		is_slot "$_slot" || { echo "слот: 0|2|3|4"; exit 1; }
		[ "$_dir" = vpn ] || _slot=0    # доп-выход применим только к «в VPN» (зеркало верба dir)
		[ -n "$_name" ] || { echo "нужно имя группы"; exit 1; }
		# СОСТАВ — ДО СТРОКИ РЕЕСТРА: `new` обещает группу ВМЕСТЕ с составом, и ноль легших записей (всё отбросила проверка
		# is_dom/is_cidr, она строже панельной) — это отказ, а не пустая включённая группа. Прежде строка вставала первой,
		# и панель честно писала «группа не создана», а в «Группах правил» появлялась пустая группа с этим именем.
		# Состав пишем во ВРЕМЕННЫЙ файл, а номер берём прямо перед строкой реестра: разбор состава — секунды (процессы на
		# каждую запись), и номер, взятый до него, успел бы занять параллельный `new`/`dev-add` — две строки с одним id и
		# общий файл состава.
		_tm="$G/.new.$$"
		_added=$(store_members "$_tm")
		case "$_added" in ''|*[!0-9]*) _added=0 ;; esac
		if [ "$_added" -eq 0 ]; then
			rm -f "$_tm" 2>/dev/null
			echo "ни одного домена или адреса — группа не создана"; exit 1
		fi
		_id=$(next_id)
		mv "$_tm" "$(mfile "$_id")"
		printf '%s\t1\t%s\t%s\t%s\n' "$_id" "$_dir" "$_slot" "$_name" >> "$REG"
		_out=$(printf '%s\t%s' "$_id" "$_added")   # собрать ДО do_apply: он затирает _id
		do_apply >/dev/null
		printf '%s\n' "$_out"
		;;

	# --- ПРАВИЛА КОНКРЕТНОГО УСТРОЙСТВА (группы с непустым src) -----------------------------
	# Наружу (панель, CGI, человек) фича выглядит ПОШТУЧНО: «этот домен у этого устройства — в
	# выход №3». Группами это только ХРАНИТСЯ: под каждое сочетание (устройство, направление,
	# выход) заводится по группе, имя служебное. Заставлять человека сперва «создать группу», а
	# потом «привязать её к устройству» значило бы показать ему нашу внутреннюю кухню — для
	# устройства осмысленно ровно одно: список адресов и куда они идут.
	dev-add)   # dev-add <IP> <vpn|bypass|block> <0|2|3|4> <домен|CIDR>
		is_ip4 "$2" || { echo "нужен IPv4 устройства"; exit 1; }
		case "$3" in vpn|bypass|block) ;; *) echo "направление: vpn|bypass|block"; exit 1 ;; esac
		is_slot "$4" || { echo "выход: 0|2|3|4"; exit 1; }
		_dip="$2"; _ddir="$3"; _dsl="$4"; [ "$_ddir" = vpn ] || _dsl=0
		_val=$(norm_member "$5") || { echo "нужен домен или IP/CIDR"; exit 1; }
		# ZAPRET-выход правилу устройства не назначается — по той же причине, что и устройству
		# целиком (см. rebuild_force в apply-bypass.sh): он единственный работает БЕЗ марки
		# (ACCEPT + scoped NFQUEUE по адресам НАЗНАЧЕНИЯ), `ip rule` под 0xN для него нет ⇒
		# правило встало бы, а трафик уехал бы напрямую и БЕЗ десинка. Отказ с причиной — в
		# движке, а не только в панели: из CLI должно быть так же безопасно.
		if [ "$_dsl" != 0 ] && [ -f "$ENODIA_DIR/slots.sh" ] &&
		   sh "$ENODIA_DIR/slots.sh" list 2>/dev/null | awk -F"$TAB" -v i="$_dsl" '$1==i && $3=="zapret"{f=1} END{exit !f}'; then
			echo "выход №$_dsl — десинк (zapret): он работает по адресам назначения, направить в него правило устройства нельзя"; exit 1
		fi
		# Ключ группы = устройство + направление + выход. Совпал — дописываем член, нет — заводим.
		_gid=$(awk -F"$TAB" -v ip="$_dip" -v d="$_ddir" -v s="$_dsl" '$6==ip && $3==d && $4==s{print $1; exit}' "$REG" 2>/dev/null)
		if [ -z "$_gid" ]; then
			# Имя служебное (человек эти группы заводит НЕ руками и видит их на экране устройства,
			# а не в списке групп), но держим его КОРОТКИМ осознанно: san режет по 40 БАЙТАМ, а
			# кириллица — два байта на букву, и длинная подпись обрубилась бы посреди символа
			# (битый UTF-8 ломает JSON панели).
			case "$_ddir" in
				vpn)    _dnm="в VPN" ;;
				bypass) _dnm="напрямую" ;;
				*)      _dnm="блок" ;;
			esac
			[ "$_dsl" = 0 ] || _dnm="выход №$_dsl"
			_gid=$(next_id)
			printf '%s\t1\t%s\t%s\t%s\t%s\n' "$_gid" "$_ddir" "$_dsl" "$(san "$_dip · $_dnm")" "$_dip" >> "$REG"
			: > "$(mfile "$_gid")"
		fi
		# Направление у ОДНОГО значения ровно одно: перед добавлением вычищаем его из ОСТАЛЬНЫХ
		# групп этого устройства (зеркало port-add и domain.sh). Иначе у устройства оказались бы
		# два правила на один домен, и молча выигрывало бы то, что выше в цепочке.
		for _og in $(awk -F"$TAB" -v ip="$_dip" -v keep="$_gid" '$6==ip && $1!=keep{print $1}' "$REG" 2>/dev/null); do
			_omf=$(mfile "$_og"); [ -f "$_omf" ] || continue
			grep -qxF "$_val" "$_omf" 2>/dev/null || continue
			grep -vxF "$_val" "$_omf" > "$_omf.tmp" 2>/dev/null
			mv "$_omf.tmp" "$_omf"
			[ -s "$_omf" ] || { reg_del_line "$_og"; rm -f "$_omf" 2>/dev/null; }
		done
		grep -qxF "$_val" "$(mfile "$_gid")" 2>/dev/null || echo "$_val" >> "$(mfile "$_gid")"
		# Сообщение собираем ДО do_apply: он гоняет свои циклы до EOF и обнуляет общие имена
		# (та же грабля, что в add-bound — у busybox sh нет `local`).
		_msg="правило устройства $_dip: $_val"
		do_apply >/dev/null
		echo "$_msg"
		;;

	dev-del)   # dev-del <IP> <домен|CIDR> — снять правило (опустевшая группа удаляется целиком)
		is_ip4 "$2" || { echo "нужен IPv4 устройства"; exit 1; }
		_val=$(norm_member "$3") || { echo "нужен домен или IP/CIDR"; exit 1; }
		_hit=0
		for _gid in $(awk -F"$TAB" -v ip="$2" '$6==ip{print $1}' "$REG" 2>/dev/null); do
			_mf=$(mfile "$_gid"); [ -f "$_mf" ] || continue
			grep -qxF "$_val" "$_mf" 2>/dev/null || continue
			grep -vxF "$_val" "$_mf" > "$_mf.tmp" 2>/dev/null
			mv "$_mf.tmp" "$_mf"
			_hit=1
			# Пустая группа устройства — служебный мусор: человек её не заводил и в списке групп
			# не увидит, а строка реестра и сет остались бы навсегда.
			[ -s "$_mf" ] || { reg_del_line "$_gid"; rm -f "$_mf" 2>/dev/null; }
		done
		[ "$_hit" = 1 ] || { echo "такого правила у устройства нет"; exit 1; }
		do_apply >/dev/null
		echo "правило снято"
		;;

	dev-list)  # dev-list [IP] — TSV «ip⇥значение⇥dir⇥slot» для панели (человеческий текст парсить нельзя)
		_want="$2"
		_old_ifs="$IFS"; IFS="$TAB"
		while read -r _id _en _dir _slot _name _src; do
			[ -n "$_src" ] || continue
			[ -z "$_want" ] || [ "$_src" = "$_want" ] || continue
			_f=$(mfile "$_id"); [ -f "$_f" ] || continue
			IFS="$_old_ifs"
			while read -r _m; do
				[ -n "$_m" ] || continue
				printf '%s\t%s\t%s\t%s\n' "$_src" "$_m" "$_dir" "$_slot"
			done < "$_f"
			IFS="$TAB"
		done < "$REG"
		IFS="$_old_ifs"
		;;

	dev-rules) # машинный TSV для apply-bypass.sh: src⇥сет⇥dir⇥slot (по строке на ВКЛЮЧЁННУЮ группу).
		# Слот отдаём СЫРЫМ: гейт «выход выключен / выход — zapret» держит apply-bypass одним
		# местом (он же владелец правила), а панель показывает выбор человека как есть.
		awk -F"$TAB" -v OFS="$TAB" 'NF>=6 && $6!="" && $2==1 {print $6, "grp_dev_" $1, $3, $4}' "$REG" 2>/dev/null
		;;

	dev-purge) # dev-purge <IP> — снять ВСЕ правила устройства разом
		is_ip4 "$2" || { echo "нужен IPv4 устройства"; exit 1; }
		for _gid in $(awk -F"$TAB" -v ip="$2" '$6==ip{print $1}' "$REG" 2>/dev/null); do
			reg_del_line "$_gid"; rm -f "$(mfile "$_gid")" 2>/dev/null
		done
		do_apply >/dev/null
		echo "правила устройства сняты"
		;;

	apply|reapply) do_apply ;;

	*)
		echo "groups.sh — именованные группы правил «в VPN / мимо VPN»"
		echo "  list | add <vpn|bypass> <имя> | del <id> | rename <id> <имя>"
		echo "  dir <id> <vpn|bypass> | slot <id> <0|2|3|4> | toggle <id> <0|1> | set-members <id> < stdin | apply"
		echo "  new <vpn|bypass> <slot> <имя> < stdin  (создать группу с составом; печатает «id<TAB>членов»)"
		echo "  правила устройства: dev-add <IP> <vpn|bypass|block> <0|2|3|4> <домен|CIDR> | dev-del <IP> <значение>"
		echo "                      dev-list [IP] | dev-rules | dev-purge <IP>"
		exit 1
		;;
esac
