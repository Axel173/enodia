REG="$G/groups.tsv"
SET_VPN=grp_vpn
SET_OUT=grp_out
DNSCONF=/tmp/dnsmasq.d/10-groups.conf
TAB=$(printf '\t')

mkdir -p "$G" 2>/dev/null
[ -f "$REG" ] || : > "$REG"

# Проверка ДОМЕНА (dns-lib.sh::dom_ok, там же замер): члены группы едут в `ipset=`-строки, а
# dnsmasq отвергает ВЕСЬ конфиг из-за одной метки длиннее 63 символов — то есть один член группы
# оставлял без DNS всю сеть (и не сразу, а на ближайшем ребуте). Шим повторяет ПРАВИЛО, а не
# прежнее поведение: прежнее поведение и есть баг.
if [ -f "$ENODIA_DIR/dns-lib.sh" ]; then . "$ENODIA_DIR/dns-lib.sh"; fi
if ! command -v dom_ok >/dev/null 2>&1; then
	dom_ok() { [ -n "$1" ] && [ "${#1}" -le 253 ] || return 1
	           printf '%s' "$1" | grep -qE '^[A-Za-z0-9_-]{1,63}(\.[A-Za-z0-9_-]{1,63})*$'; }
fi

# --- реестр (TSV на /data): id<TAB>enabled<TAB>dir<TAB>slot<TAB>name[<TAB>src] -----
# Имя может содержать пробелы (TAB/CR/LF из него вырезаем — иначе поедет разбор строки; кавычки/
# бэкслеши тоже: JSON отдаём без эскейпа, как emit_wifi).
# slot — доп-ВЫХОД группы (мульти-транспорт, Ф1): 0 = основной (grp_vpn как раньше), 2..4 =
# доп-слот (grp_vpn_s<N>, метит mark-core / врайрит zapret-слот). Только для dir=vpn.
# src  — IPv4 УСТРОЙСТВА, для которого действует группа (нет поля = для всей сети, как было).
#        Непустой src уводит членов в СВОЙ сет grp_dev_<id> (см. шапку) и разрешает dir=block.
#
# ПОЧЕМУ src ДОПИСАН В КОНЕЦ, А НЕ ВСТАВЛЕН ПОСЛЕ slot (грабля, пойманная на первом же прогоне):
# TAB — это IFS-*whitespace*, и `read` с IFS=TAB схлопывает идущие подряд разделители, то есть
# ПУСТОЕ ПОЛЕ В СЕРЕДИНЕ строки просто исчезает и все следующие поля съезжают на одно влево
# (глобальные группы читались как группы устройства). Необязательное поле поэтому может быть
# только ПОСЛЕДНИМ: его отсутствие и его пустота — одно и то же. Заодно не нужна миграция —
# старые 5-колоночные строки читаются как «src нет».
# `cut -c` в busybox режет БАЙТАМИ (локалей нет), а кириллица — 2 байта на символ ⇒ имя ровно на
# границе обрубалось ПОСРЕДИ символа, и в JSON панели уезжал битый UTF-8. Поэтому после реза
# срезаем хвостовую НЕПОЛНУЮ последовательность: ведущий байт, которому не хватило продолжений,
# может стоять только в самом конце строки. Класс байтов собираем printf'ом — писать диапазоны
# прямо в sed-скрипт нельзя (busybox sed не обещает \NNN внутри скобок). Форма октали ровно `\300`
# (1–3 цифры, POSIX): `\0300` шелл читает как `\030` плюс символ «0», и класс разъезжается
# («Invalid range end» — проверено на стенде). Фигурных повторителей избегаем по той же причине:
# `\{` у printf не определён. LC_ALL=C — чтобы sed судил по БАЙТАМ и в UTF-8-локали тоже.
UTF8_TAIL=$(printf 's/[\300-\337]$//;s/[\340-\357]$//;s/[\340-\357][\200-\277]$//;s/[\360-\367]$//;s/[\360-\367][\200-\277]$//;s/[\360-\367][\200-\277][\200-\277]$//')
san() {
	# Управляющие символы — ВСЕ (`\033` из чужого тега): имя печатается в JSON как есть, и один такой байт ломал весь ответ
	# списка групп — панель не могла ни показать, ни снять группу.
	_sn=$(printf '%s' "$1" | tr -d "$TAB\"\\\\\r\n" | tr -d '\001-\037\177' | cut -c1-40)
	_sn2=$(printf '%s' "$_sn" | LC_ALL=C sed "$UTF8_TAIL" 2>/dev/null)
	[ -n "$_sn2" ] || _sn2="$_sn"   # страховка: sed без байтовых классов вернул бы пусто
	printf '%s' "$_sn2"
}
is_cidr() { echo "$1" | grep -qE '^[0-9]{1,3}(\.[0-9]{1,3}){3}(/[0-9]{1,2})?$'; }
is_ip4()  { echo "$1" | grep -qE '^([0-9]{1,3}\.){3}[0-9]{1,3}$'; }
dev_set() { printf 'grp_dev_%s' "$1"; }   # сет группы устройства (префикс grp_ — его знает uninstall)
# Домен ИЛИ зона одним словом: `ru`/`xn--p1ai` — это .ru и .рф целиком. Так пишут правила чужие
# конфиги (xray `domain:ru`), и dnsmasq матчит их так же, как обычный домен: `ipset=/ru/сет`
# ловит зону вместе с поддоменами. Без второй ветки мастер импорта терял ровно те правила, ради
# которых конфиг и брали («весь рунет — напрямую»). Голая цифра отсекается: это не имя.
# Первым делом — dom_ok (dns-lib.sh): он отвечает за СИНТАКСИС строки dnsmasq (метка ≤63 символов),
# и без него член группы с длинной меткой ронял конфиг демона у ВСЕЙ сети. Ниже — политика ИМЕННО
# групп: домен с TLD либо зона одним словом.
is_dom()  { dom_ok "$1" || return 1
            echo "$1" | grep -qE '\.([A-Za-z]{2,}|xn--[A-Za-z0-9-]{2,})$' || \
            { echo "$1" | grep -qE '^[A-Za-z0-9][A-Za-z0-9-]{1,62}$' && ! echo "$1" | grep -qE '^[0-9]+$'; }; }
is_slot() { case "$1" in 0|2|3|4) return 0 ;; *) return 1 ;; esac; }
valid_id() { echo "$1" | grep -qE '^g[0-9]+$'; }

# Миграция реестра 4-col → 5-col (добавлено поле slot после dir). Старый формат:
# id⇥enabled⇥dir⇥name. Имя санировано (san) от TAB, поэтому число полей (NF) надёжно
# различает форматы. Идемпотентно, атомарно (tmp+mv). Запускается один раз при непустом реестре
# старого формата — новые установки не задевает.
# Появление src миграции НЕ потребовало: поле дописано В КОНЕЦ (см. шапку реестра), и строка без
# него означает ровно «группа для всей сети» — то же, что пустое значение.
migrate_reg() {
	[ -s "$REG" ] || return 0
	awk -F"$TAB" 'NF>0 && NF!=5 && NF!=6{c=1} END{exit c?0:1}' "$REG" || return 0
	awk -F"$TAB" -v OFS="$TAB" 'NF==4{print $1,$2,$3,"0",$4; next} NF>0{print}' "$REG" > "$REG.mig" \
		&& mv "$REG.mig" "$REG"
}
migrate_reg
mfile() { printf '%s/%s.list' "$G" "$1"; }

reg_get() { grep "^$1$TAB" "$REG" 2>/dev/null | head -1; }
# Следующий id — max+1 (детерминированно; удалённые id не переиспользуем, чтобы старый
# .list-файл-сирота не «прилип» к новой группе). Идиома взята из reg_next_id lists-lib.sh.
next_id() {
	_m=$(cut -f1 "$REG" 2>/dev/null | sed -n 's/^g\([0-9][0-9]*\)$/\1/p' | sort -n | tail -1)
	case "$_m" in ''|*[!0-9]*) _m=0 ;; esac
	printf 'g%s' $((_m + 1))
}
reg_write() {  # stdin → реестр (атомарно: tmp+mv, чтобы обрыв записи не побил файл)
	cat > "$REG.new" && mv "$REG.new" "$REG"
}
reg_del_line() { grep -v "^$1$TAB" "$REG" 2>/dev/null | reg_write; }

# norm_member <запись> — нормализовать ОДНУ запись: режем схему/путь/www/порт, домены в нижний
# регистр. Печатает результат; пусто + код 1, если это ни домен, ни IP/CIDR. Вынесено из
# store_members, потому что правило устройства добавляется ПОШТУЧНО (верб dev-add), а вторая
# копия правил нормализации разошлась бы с первой (тогда «youtube.com/» и «youtube.com» стали бы
# разными записями, и снять правило по введённому тексту не удалось бы).
norm_member() {
	_nm=$(printf '%s' "$1" | sed 's|^[a-zA-Z][a-zA-Z0-9+.-]*://||; s|/$||; s|^www\.||')
	if is_cidr "$_nm"; then printf '%s' "$_nm"; return 0; fi
	_nm=$(printf '%s' "$_nm" | sed 's|/.*$||; s|:[0-9]*$||' | tr 'A-Z' 'a-z')
	is_dom "$_nm" && { printf '%s' "$_nm"; return 0; }
	return 1
}

# store_members <файл-членов> < stdin — нормализовать состав группы и записать; ПЕЧАТАЕТ число
# легших записей. Разделители — пробел/запятая/;/перевод строки; дедуп; мусор молча отбрасываем
# (валидный член = домен ИЛИ IP/CIDR).
# ОБЩАЯ для вербов `set-members` и `new` (мастер импорта routing-правил создаёт группу вместе с
# составом одним действием) — иначе появилась бы вторая копия правил нормализации и дедупа.
store_members() {
	_sm_f="$1"; _sm_n=0
	: > "$_sm_f.new"
	for _raw in $(tr ',;\r\n' '    '); do
		_v=$(norm_member "$_raw") || continue
		grep -qxF "$_v" "$_sm_f.new" 2>/dev/null && continue
		echo "$_v" >> "$_sm_f.new"
		_sm_n=$((_sm_n + 1))
	done
	mv "$_sm_f.new" "$_sm_f"
	echo "$_sm_n"
}

