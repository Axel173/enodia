# ============================================================================
# 4b. CIDR-СПИСКИ ОТ iplist.opencck.org (доп. к доменам)
# ============================================================================
# Доменный re-filter надёжен для крупных сайтов, но плохо ловит CDN с
# рандомными хостнеймами (Cloudflare, OpenAI, Discord). iplist.opencck.org
# отдаёт готовые CIDR-блоки крупнейших сервисов. Скрипт iplist-update.sh
# создаёт ipset iplist_set и маркирует трафик к этим подсетям тем же
# fwmark 0x1. Если iplist-update.sh не залит — пропустим.
# ----------------------------------------------------------------------------
if [ -f "$ENODIA_DIR/iplist-update.sh" ]; then
    log "Подгружаю CIDR от iplist.opencck.org..."
    chmod +x "$ENODIA_DIR/iplist-update.sh"
    sh "$ENODIA_DIR/iplist-update.sh" || warn "iplist-update вернул ошибку — см. /tmp/enodia-iplist-update.log"
    if ipset list -n 2>/dev/null | grep -qx iplist_set; then
        # «Number of entries:» нет на ядре 4.4 → фолбэк на подсчёт строк-членов (см. ipset_count в lists-lib.sh).
        ipl_count=$(ipset list iplist_set 2>/dev/null | sed -n 's/^Number of entries:[[:space:]]*//p' | head -1)
        # `|| true` ОБЯЗАТЕЛЕН (тот же класс, что в финальном отчёте): busybox `grep -c` на пустом
        # наборе возвращает 1, а под `set -e` присваивание из такой подстановки роняет установщик
        # ПРЯМО ЗДЕСЬ — до маркировки, транспорта и регистрации cron. Ветка эта не гипотетическая:
        # её берут ядра без «Number of entries:» (AX3600, 4.4), а пустой iplist на установке —
        # известная грабля проекта (dnsmasq заперт в ещё не поднятый туннель).
        case "$ipl_count" in ''|*[!0-9]*) ipl_count=$(ipset list iplist_set 2>/dev/null | grep -cE '^[0-9]' || true) ;; esac
        case "$ipl_count" in ''|*[!0-9]*) ipl_count=0 ;; esac
        ok "iplist_set наполнен: $ipl_count CIDR"
    fi
fi

# ============================================================================
# 5. МАРШРУТИЗАЦИЯ: ядро (mark-core) + активный транспорт (плагин)
# ============================================================================
# split-route.sh РЕТАЙРНУТ (июнь 2026): ЕДИНЫЙ источник правды — mark-core.sh (ядро:
# маркировка ipset->MARK + ip rule fwmark->table $ROUTE_TABLE) + плагины транспорта
# (несущую default в table $ROUTE_TABLE кладёт transport-awg.sh / xray-transport.sh).
# Отдельный awg0-генератор больше не нужен и НЕ создаётся; mark-core.sh и
# transport-awg.sh — REQUIRED payload. Раскладка ровно как heal.sh на boot.
CARRIER_UP=0
if [ "$PANEL_ONLY" = 1 ] && [ "$KEEP_TRANSPORT" = 1 ]; then
    # Переустановка ПОВЕРХ настроенной системы (см. KEEP_TRANSPORT в секции 2). Флаг, маркировку
    # и несущую не трогаем вовсе: чужой выбор — не наш, а снятый флаг при живых правилах и демонах
    # выключил бы сторожа на работающем роутере. Переигрывать нам тут НЕЧЕГО и НЕЧЕМ: сами мы
    # firewall не перезагружаем (секция 1 в панельном режиме пропущена целиком, `FW3_WIPED`
    # остаётся 0 ⇒ и repair в 5b не зовётся), а правила, смытые ЧУЖИМ reload'ом (вебморда Xiaomi),
    # вернёт сторож — он видит пропажу `FORWARD -o <dev>` и зовёт тот же `vpn-toggle.sh repair`.
    _kt_name=$(cat "$ENODIA_STATE/.transport" 2>/dev/null | tr -d ' \r\n')
    [ -n "$_kt_name" ] || _kt_name=awg
    log "Транспорт уже выбран ($_kt_name) — маршрутизацию не трогаю"
    ok "Обновлены скрипты, панель и cron; транспорт и его правила остались как были"
elif [ "$PANEL_ONLY" = 1 ]; then
    # Ни маркировки, ни несущей, ни флага `.transport`: пустой флаг + отсутствие awg.conf — и есть
    # признак «транспорта нет вовсе», по которому heal, сторож и repair понимают, что чинить
    # нечего. Записать сюда что-нибудь «на всякий случай» значило бы соврать им всем сразу.
    rm -f "$ENODIA_STATE/.transport"
    log "Только панель: маршрутизацию не трогаю — роутер работает как сток"
    ok "Транспорт не активирован (выбор за человеком, в панели)"
else
    log "Применяю ядро маршрутизации + активный транспорт ($ACTIVE_PROTO)..."
    echo "$ACTIVE_PROTO" > "$ENODIA_STATE/.transport"
    if [ -f "$ENODIA_DIR/mark-core.sh" ]; then
        sh "$ENODIA_DIR/mark-core.sh"
    else
        err "mark-core.sh отсутствует (payload неполон) — маркировка не применена"
    fi
    # Несущую активного транспорта поднимает ОРКЕСТРАТОР (transport.sh up <proto> — он же
    # идемпотентно переиграет mark-core). Добавить hysteria = расширить ACTIVE_PROTO-детект
    # (HAVE_*) + реестр transport.sh; этот вызов и heal/watchdog тогда не правятся.
    #
    # ВАЖНО (грабля, поправлено июнь 2026): подъём несущей НЕ должен быть фатальным под set -e.
    # Раньше тут было `[ -x … ] && transport.sh up …` — при неудачном подъёме (транзиентная
    # гонка сразу после установки/ребута: холодный QUIC у hysteria, гонка xtun у hev) эта строка
    # под `set -e` роняла ВЕСЬ установщик ДО регистрации cron (heal/watchdog/iplist). Итог:
    # роутер без сторожа и самовосстановления, несущая не встала бы и после ребута, а на экране
    # установка просто «мигала» (плагин при сбое не имел лога → причина была невидна). Теперь:
    #   (1) пробуем подъём дважды (транзиент обычно проходит со 2-й попытки);
    #   (2) при сбое показываем ЯВНО + дампим логи демонов (иначе причина прячется);
    #   (3) ПРОДОЛЖАЕМ установку (fail-open безопасен; cron поднимут несущую на boot/восстановлении).
    if [ -f "$ENODIA_DIR/transport.sh" ]; then
        n=1
        while [ "$n" -le 2 ]; do
            out=$(sh "$ENODIA_DIR/transport.sh" up "$ACTIVE_PROTO" 2>&1) && rc=0 || rc=$?
            [ -n "$out" ] && printf '%s\n' "$out"
            if [ "$rc" = 0 ]; then CARRIER_UP=1; break; fi
            warn "Попытка $n: транспорт $ACTIVE_PROTO не поднялся (код $rc). Повтор через 3с…"
            sleep 3; n=$((n+1))
        done
    else
        warn "transport.sh отсутствует (payload неполон) — несущая не поднята."
    fi
    if [ "$CARRIER_UP" = 1 ]; then
        ok "Маршрутизация + транспорт ($ACTIVE_PROTO) применены"
    else
        err "Несущая ($ACTIVE_PROTO) НЕ поднялась. VPN сейчас в ПРЯМОМ режиме (fail-open: интернет"
        err "работает, трафик идёт МИМО туннеля). Установка продолжается — см. логи демонов ниже."
        # Логи демонов — чтобы причина (сервер/sni/ключи/порт) была ВИДНА, а не пряталась.
        for L in /tmp/enodia-hysteria.log /tmp/xray.log /tmp/enodia-hev.log; do
            [ -s "$L" ] && { warn "--- последние строки $L ---"; tail -n 15 "$L"; }
        done
        warn "cron (heal/watchdog) будет зарегистрирован — несущую поднимут после ребута / при"
        warn "восстановлении. Либо проверьте конфиг в меню (Протокол) и повторите установку."
    fi
fi   # /PANEL_ONLY (конец секции 5: ядро маркировки + подъём несущей)

# 5b. ПЕРЕИГРЫШ ПОСЛЕ firewall reload из awg_setup.sh (см. FW3_WIPED в секции 1). mark-core выше
# вернул только ЯДРО маркировки, а снесено было ВСЁ: вырезы/порты/устройства/KEEP (apply-bypass),
# jump ENODIA_ZAPRET, FORWARD и маршруты доп-выходов, PANEL_WAN + hairpin, «доступ домой».
# Канонический переигрыш ОДИН — `vpn-toggle.sh repair`; своей копии списка тут не держим (тот же
# приём, что в proto-install.sh п.5b и transport-awg.sh::replay_fw3). Зовём ПОСЛЕ подъёма
# несущей: repair читает .transport и иначе поднял бы не тот транспорт. На ПЕРВОЙ установке
# переигрывать нечего — repair отработает как no-op.
if [ "$FW3_WIPED" = 1 ] && [ -f "$ENODIA_DIR/vpn-toggle.sh" ]; then
    log "awg_setup сделал firewall reload — переигрываю цепочки (vpn-toggle repair)…"
    sh "$ENODIA_DIR/vpn-toggle.sh" repair >/dev/null 2>&1 || true
    ok "Правила переиграны (вырезы, порты, устройства, десинк, доп-выходы, доступ снаружи)"
fi

# 5c. ПЕРЕИГРЫШ ПЕРСИСТА ПОДСИСТЕМ (`heal.sh replay`). `repair` выше чинит ПРАВИЛА, но
# наборы и dnsmasq-сниппеты групп/гео/списков/десинка он не пересобирает — их владельцы
# groups.sh/geo.sh/lists-update.sh, и зовёт их РОВНО heal. На буте это происходит само, а вот
# при УСТАНОВКЕ ПОВЕРХ бутовый лок уже взят ⇒ cron-тик heal вырождается в пустышку, и человек
# получал роутер, где настройки на месте, панель показывает группы и гео включёнными, а в ядре
# из 13 наших ipset живут 2. Замерено на железе 08.08.2026 (deactivate → установка поверх).
# На ПЕРВОЙ установке персиста нет — replay отработает как no-op. Нефатально: установка не
