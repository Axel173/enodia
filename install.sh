# ============================================================================
# 3. НАСТРОЙКА DNSMASQ
# ============================================================================
# Используем упрощённый upstream: no-resolv + server=1.1.1.1/8.8.8.8 (через
# туннель). Если нужен полноценный DoH — подними cloudflared или dnscrypt-proxy
# и укажи server=127.0.0.1#5053.
# ----------------------------------------------------------------------------
log "Настраиваю dnsmasq..."

mkdir -p "$DNSMASQ_DIR"

# Подключаем директорию conf-dir в основной конфиг
if ! grep -q "^conf-dir=$DNSMASQ_DIR" "$DNSMASQ_CONF" 2>/dev/null; then
    echo "" >> "$DNSMASQ_CONF"
    echo "# Подключение split-tunnel конфигов (добавлено Enodia)" >> "$DNSMASQ_CONF"
    echo "conf-dir=$DNSMASQ_DIR,*.conf" >> "$DNSMASQ_CONF"
    ok "conf-dir добавлен в $DNSMASQ_CONF"
else
    ok "conf-dir уже подключён"
fi

# DNS: подменяем upstream на DNS внутри VPN-туннеля.
# КРИТИЧНО: некоторые провайдеры подменяют DNS-ответы (DNS-спуфинг) для части
# доменов, возвращая адрес-заглушку. Прямые 1.1.1.1/8.8.8.8 не спасают —
# провайдер перехватит UDP/53 на пути. Поэтому DNS должен быть внутри туннеля
# и недоступен снаружи.
# У конфигов от Amnezia это обычно 172.29.172.254 — берём его из awg.conf.
DNS_OVERRIDE="$DNSMASQ_DIR/00-upstream.conf"
# ЖИВАЯ копия того же сниппета. Каталога ДВА, и демон читает ОБА всегда: стоковый init на КАЖДОМ
# рестарте делает `cp -a /etc/dnsmasq.d/* /tmp/dnsmasq.d` АДДИТИВНО, без чистки (грабля проекта).
# Значит удаление одной только /etc-копии НИЧЕГО не выключает: `no-resolv` + туннельный резолвер
# продолжают жить в /tmp до ребута, и «вернул стоковый» было бы неправдой ровно там, где сразу
# после нас замолкает сторож. Тот же обход, что в uninstall.sh::step_dnsmasq — по обоим каталогам.
DNS_OVERRIDE_LIVE="/tmp/dnsmasq.d/00-upstream.conf"
if [ "$PANEL_ONLY" = 1 ] && [ "$KEEP_TRANSPORT" = 1 ]; then
    # Переустановка поверх настроенной системы: upstream'ом владеет выбранный транспорт, а не мы.
    ok "DNS upstream: не трогаю — им владеет уже выбранный транспорт"
elif [ "$PANEL_ONLY" = 1 ]; then
    # «Только панель»: транспорта нет — значит нет и владельца upstream'а. Резолвер оставляем
    # СТОКОВЫМ (dnsmasq работает на серверах провайдера из resolv.conf): подменять его нашим
    # файлом означало бы менять поведение роутера ради VPN, которого ещё не настроили. Владелец
    # появится вместе с транспортом — его DNS-сеттер и напишет 00-upstream.conf. Прошлый файл
    # (переустановка поверх) снимаем: он мог указывать в туннель, которого уже нет.
    if [ -f "$DNS_OVERRIDE" ] || [ -f "$DNS_OVERRIDE_LIVE" ]; then
        rm -f "$DNS_OVERRIDE" "$DNS_OVERRIDE_LIVE"
        /etc/init.d/dnsmasq restart >/dev/null 2>&1 || killall -HUP dnsmasq 2>/dev/null || true
        ok "DNS upstream: вернул стоковый (снял 00-upstream.conf в /etc и /tmp от прошлой установки)"
    else
        ok "DNS upstream: стоковый (транспорта нет — не трогаю)"
    fi
elif [ "$ACTIVE_PROTO" = xray ] || [ "$ACTIVE_PROTO" = hy2 ] || [ "$ACTIVE_PROTO" = byedpi ]; then
    # Альт-транспорт (xray/hy2/byedpi) несёт DNS публичным резолвером. У xray/hy2 он
    # МАРКИРУЕТСЯ в туннель (<transport>.sh up ниже); у byedpi DNS идёт ПРЯМО (десинк без
    # туннеля) — плагин set_direct_dns это финализирует на up. Здесь — публичная заглушка,
    # чтобы dnsmasq резолвил и до подъёма транспорта. Внутренний Amnezia-DNS при альте недостижим.
    # upstream-own: легаси-путь полной установки (не PANEL_ONLY); рестарт ниже безусловный и обязателен — разбор под ним.
    printf 'no-resolv\nserver=1.1.1.1\nserver=8.8.8.8\n' > "$DNS_OVERRIDE"
    ok "DNS upstream: публичный 1.1.1.1/8.8.8.8 (альт-транспорт)"
    # КРИТИЧНО: dnsmasq держит СТАРЫЙ upstream в памяти, пока его не перезапустить.
    # На ПЕРЕустановке (был awg → ставим альт) в памяти остаётся туннельный DNS прошлого
    # awg (no-resolv; server=172.29.x) — туннель уже мёртв, и ЛЮБОЙ резолв через dnsmasq
    # падает. Тогда iplist-update в секции 4b НЕ может скачать список, а busybox-nslookup-
    # «фолбэк мимо dnsmasq» в iplist-update тоже бьёт в мёртвый dnsmasq (busybox nslookup
    # ИГНОРИРУЕТ аргумент сервера). Поэтому перезапускаем dnsmasq СЕЙЧАС: публичный upstream
    # (1.1.1.1/8.8.8.8) достижим напрямую (mark-core ещё не заворачивает их в туннель) →
    # резолв оживает ДО закачки списков. Поймано на железе 2026-06-25 (byedpi-only: iplist
    # пуст → десинку нечего заворачивать → YouTube не открывался, тесты стратегий пустые).
    /etc/init.d/dnsmasq restart >/dev/null 2>&1 || killall -HUP dnsmasq 2>/dev/null || true
    ok "dnsmasq перезапущен на публичный upstream (резолв для закачки списков до подъёма транспорта)"
else
    # AmneziaWG: upstream ВНУТРИ туннеля (адрес из awg.conf поля DNS=, fallback 172.29.172.254).
    VPN_DNS=$(grep -E '^DNS\s*=' "$AWG_CONF" 2>/dev/null | head -1 | awk -F'= *' '{print $2}' | awk -F',' '{print $1}' | tr -d ' ')
    [ -z "$VPN_DNS" ] && VPN_DNS="172.29.172.254"
    # upstream-own: легаси-путь полной установки (не PANEL_ONLY), файл с шапкой-комментарием для человека.
    cat > "$DNS_OVERRIDE" <<EOF
# DNS-сервер внутри VPN-туннеля (защита от подмен провайдером).
# Адрес взят из awg.conf поля DNS=. Если у вас другой — поправьте здесь
# и убедитесь, что heal.sh использует тот же (переменная VPN_DNS).
no-resolv
server=$VPN_DNS
EOF
    ok "DNS upstream настроен ($DNS_OVERRIDE → $VPN_DNS)"
    # Маршрут к VPN DNS через туннель — иначе dnsmasq до него не достучится
    if ip link show awg0 >/dev/null 2>&1; then
        # best-effort: на переустановке awg0 может быть DOWN (туннель ещё/уже не несёт) →
        # `ip route replace … dev awg0` отвечает «Network is down» ненулевым кодом, и под
        # set -e это роняло весь установщик с code 1 (маршрут к DNS — не критичен). || true.
        ip route replace "$VPN_DNS/32" dev awg0 2>/dev/null || true
        ok "Маршрут к $VPN_DNS прописан через awg0"
    fi
fi

