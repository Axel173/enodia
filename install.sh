#!/bin/sh
#
# install.sh
# Полная автоматическая настройка AmneziaWG + split-tunneling по доменам
# на стоковой прошивке Xiaomi BE7000 (CN).
#
# Что делает:
#   1) Скачивает и запускает официальный установщик AmneziaWG от @T7m
#      (github.com/alexandershalin/amneziawg-be7000)
#   2) Поднимает интерфейс awg0 на основе твоего awg.conf
#   3) Настраивает ipset + dnsmasq + ip rule для маршрутизации
#      ТОЛЬКО выбранных доменов через AWG.
#   4) Скачивает список доменов re-filter (itdoginfo/allow-domains)
#   5) Ставит автообновление списка по cron в 5 утра.
#   6) Регистрирует автозапуск в /etc/rc.local.
#
# Требования:
#   - Скрипт запущен от root на стоковой прошивке BE7000
#   - В /data/usr/app/enodia/ лежит файл awg.conf (от твоего VPS)
#   - Роутер имеет доступ в интернет
#
# Запуск:
#   chmod +x /data/usr/app/enodia/install.sh
#   /data/usr/app/enodia/install.sh
#
# Версия: 2.1 / май 2026
#
# Что нового в v2.1:
#   - ЛЕГАСИ-ПУТЬ re-filter УБРАН ЦЕЛИКОМ (был опционален, `ENABLE_REFILTER`,
#     и по умолчанию выключен). Он качал сырой список itdoginfo/allow-domains
#     прямо в `/etc/dnsmasq.d/enodia-domains.conf` и заводил рядом свой
#     `update-lists.sh` — то есть ВТОРОГО владельца «доменов в dnsmasq», мимо
#     всех гардов проекта: мимо `dom_ok` (метка >63 символов роняет DNS ВСЕЙ
#     сети на ребуте, а на AX3600/BE3600 `/etc` персистентен ⇒ навсегда), мимо
#     парной копии в `/tmp/dnsmasq.d`, мимо агрегатора `dns-merge.sh` и без
#     `--cacert` (на части прошивок ЛЮБОЙ `curl https://` = rc=60). Теперь
#     домены ведёт ОДИН движок — менеджер источников (`lists-update.sh`,
#     категория `tunnel-domains`) из панели: там и `dom_ok`, и DoH-фолбэк, и
#     оба conf-dir. Установщик стирает оставшийся от старых версий
#     `update-lists.sh` и его cron-строку; уже скачанный `enodia-domains.conf`
#     НЕ трогаем — это живой список человека, его снимет только удаление.
#
# Что нового в v2 (после реального прохождения 26 мая 2026):
#   - Чистим пустые I1..I5 из awg.conf (AmneziaVPN 4.8.12.9+ их добавляет
#     даже в Legacy-режим, старый awg-tools падает на них с
#     "Line unrecognized: I2=")
#   - Сами создаём amnezia_for_awg.conf из awg.conf (иначе вендорный
#     awg_setup.sh на ПЕРВОМ запуске падает с "File amnezia_for_awg.conf
#     not found")
#   - Уважаем пользовательские бинарники: если в $ENODIA_DIR/bin/ лежат
#     amneziawg-go.user и awg.user — они копируются на место и
#     вендорный awg_setup.sh их не перезатирает (он проверяет наличие)
#   - transport-awg.sh up идемпотентно держит FORWARD ACCEPT для awg0 — без
#     него на стоковой прошивке политика FORWARD DROP и весь LAN-трафик
#     к awg0 дропается (типа открываются только российские сайты).
#   - НЕ полагаемся на /etc/rc.local — он сбрасывается при ребуте на
#     стоковой BE7000. Автозапуск — через cron + heal.sh.
#
# ОБОСНОВАНИЕ:
#   Решения опираются на опыт сообщества BE7000 и проверки на живом
#   железе; «почему именно так» поясняется в комментариях к разделам.
#

set -e

# Цвета для красивого вывода
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color
# Из пакета обновления (pkg-install.sh) наш вывод уходит в журнал экрана «Обновление» — escape-коды там мусор.
if [ -n "$INSTALL_FROM_PKG" ]; then RED=''; GREEN=''; YELLOW=''; BLUE=''; NC=''; fi

log()  { printf "${BLUE}[INFO]${NC}  %s\n" "$1"; }
ok()   { printf "${GREEN}[ OK ]${NC}  %s\n" "$1"; }
warn() { printf "${YELLOW}[WARN]${NC}  %s\n" "$1"; }
err()  { printf "${RED}[FAIL]${NC}  %s\n" "$1" >&2; }

ENODIA_DIR=${ENODIA_DIR:-/data/usr/app/enodia}
ENODIA_STATE=${ENODIA_STATE:-/data/usr/app/enodia-state}
ENODIA_BIN=${ENODIA_BIN:-/data/usr/app/enodia-bin}
# ЧЕТВЁРТЫЙ каталог — резидентный бутстрап (boot.sh + библиотеки поиска накопителя + заглушка).
# Он и есть ЕДИНСТВЕННАЯ цель всех cron-строк: код может уехать на внешний накопитель целиком
# (режим `full`), и тогда прямой путь `$ENODIA_DIR/heal.sh` указывает в пустоту. Cron про это
# знать не должен, поэтому строку пишем через boot.sh — ВСЕГДА, в любом режиме (следит C58).
ENODIA_BOOT=${ENODIA_BOOT:-/data/usr/app/enodia-boot}
CRON_RUN="$ENODIA_BOOT/boot.sh"
# Где лежит бинарь и КУДА его класть (store-lib.sh). Установщику важны оба ответа: раскладка
# payload обязана попасть туда же, где его ищет рантайм, иначе переустановка при включённом
# внешнем накопителе положила бы свежий xray на /data, а bin_path продолжил бы отдавать СТАРЫЙ
# с накопителя. Шим — прежний плоский путь: без файла (или без накопителя) всё как раньше.
if [ -f "$ENODIA_DIR/store-lib.sh" ]; then . "$ENODIA_DIR/store-lib.sh"; fi
# Имя LAN-моста — у владельца (router-lib.sh::lan_if): им печатается адрес панели в итоге
# установки, а ошибиться тут = дать человеку ссылку, по которой ничего не откроется.
if [ -f "$ENODIA_DIR/router-lib.sh" ]; then . "$ENODIA_DIR/router-lib.sh"; fi
command -v lan_if >/dev/null 2>&1 || lan_if() { echo br-lan; }   # lan-lit: шим без router-lib.sh
# Имя WAN-интерфейса — у владельца (ip-lib.sh::wan_iface, следит C81): им биндится проба
# интернета «в обход туннеля» ниже. Шим = прежняя строка на случай payload без библиотеки.
if [ -f "$ENODIA_DIR/ip-lib.sh" ]; then . "$ENODIA_DIR/ip-lib.sh"; fi
command -v wan_iface >/dev/null 2>&1 || wan_iface() { ip route show default 2>/dev/null | awk '/^default/{d=""; for(i=1;i<=NF;i++) if($i=="dev") d=$(i+1); if(d!="" && d !~ /^(awg|xtun)/){print d; exit}}'; }
command -v bin_path    >/dev/null 2>&1 || bin_path()    { printf '%s' "$ENODIA_BIN/$1"; }
command -v bin_install >/dev/null 2>&1 || bin_install() { mv -f "$1" "$ENODIA_BIN/$2" && chmod +x "$ENODIA_BIN/$2"; }
: "${BIN_DIR:=$ENODIA_DIR}"
# Провал раскладки бинаря обязан быть ГРОМКИМ: `bin_install` возвращает 1 (нет места, файл занят,
# накопитель выдернули), а под `set -e` это роняло установщик БЕЗ ЕДИНОЙ СТРОКИ — «мигнуло и
# закрылось», причём ровно в момент, когда причина ещё известна.
put_bin() { bin_install "$1" "$2" || { err "Не удалось положить $2 на место (нет места на /data / накопителе? файл занят?)"; exit 1; }; }
AWG_CONF="$ENODIA_STATE/awg.conf"
INSTALL_SCRIPT_URL="https://github.com/alexandershalin/amneziawg-be7000/raw/refs/heads/main/awg_setup.sh"
RC_LOCAL="/etc/rc.local"
DNSMASQ_CONF="/etc/dnsmasq.conf"
DNSMASQ_DIR="/etc/dnsmasq.d"
ENODIA_LIST_NAME="enodia_list"
ROUTE_TABLE="1000"
FWMARK="0x1"

# ============================================================================
# Очистка НЕ оставляемых альт-транспортов. INSTALL_ALT (env от enodia.py / proto-install) =
# СПИСОК альтов, которые ОСТАВЛЯЕМ (через пробел или запятую): «xray» · «xray byedpi» · «none».
#   * АКТИВЕН один альт за раз (общий socks 10808 + hev), но УСТАНОВЛЕНЫ могут быть несколько:
#     «основной xray + byedpi как карриер выхода №2» — легальный сценарий, который был у автора
#     на роутере ещё когда код считал его невозможным. Отсюда список, а не одно слово: чистка
#     нужна ради МЕСТА на флеше, а не ради «взаимоисключения», и решает про место вызывающий
#     (packages.sh plan-ok) — здесь только исполнение.
#   * Удаляем БИНАРЬ неоставляемого альта (тяжёлый: xray ~8.2 МБ, hysteria ~5.2 МБ) — освобождаем
#     флеш и убираем «призрак» из меню (transport_ready без бинаря = false).
#   * Конфиги (xray-configs/ · hy2-configs/ · .xray-active · .hy2-active) НЕ трогаем —
#     лёгкие, дают вернуться переустановкой без повторной вставки ссылок.
#   * awg НИКОГДА здесь не удаляем (база/тёплый резерв; снос awg — только Uninstall).
#   * hev общий для xray/hy2/byedpi → снимаем, лишь когда не осталось НИ ОДНОГО его потребителя
#     (ни оставляемого альта, ни слота) — тот же ref-count, что в packages.sh.
#   * INSTALL_ALT пуст (старый ПК / прямой запуск без переменной) → НЕ чистим (обратная совместимость).
# Идемпотентно. ПК зовёт субкомандой `purge-alt` ДО заливки тяжёлых бинарей (чтобы пик
# флеша на свопе альта awg+xray->awg+hy2 не переполнил /data). rm живёт ЗДЕСЬ, в .sh на
# роутере (а не в команде с ПК) — обходит PS-guard на литерал rm.
INSTALL_ALT="${INSTALL_ALT:-}"
# ВАЖНО про `set -e` (вверху файла): хелперы чистки вызываются ПОСЛЕДОВАТЕЛЬНО (`A; B; C`)
# в ветках purge_unselected_alt. Идиома `[ -f x ] && { … }` возвращает 1, когда файла НЕТ
# (а это норма: пидфайл мог уже снять релинквиш, бинарь — прошлая чистка). Простая команда
# с кодом 1 под `set -e` РОНЯЕТ скрипт → следующий шаг не выполняется. Реальный баг: при
# свопе hy2<->xray релинквиш убивал демон и удалял пидфайл, затем _kill_alt_daemon на
# отсутствующем пидфайле возвращал 1 → set -e обрывал ветку ДО _purge_bin → бинарь старого
# альта НЕ удалялся, оба альта копились на флеше → переполнение /data. Поэтому хелперы
# ЯВНО возвращают 0 (best-effort чистка не должна валить установщик).
# Снимаем ОБЕ возможные копии — резидентную и на внешнем накопителе (имя берём из пути, каталог
# игнорируем). Инвариант «копия ровно одна»: bin_path предпочитает накопитель, и забытый там файл
# выдавал бы снятый бинарь за живой. Тот же довод, что в packages.sh do_remove.
# Ветки — явными `if`, а не `[ … ] && {…}`: в этом файле `set -e`, и страж-идиома уже роняла
# чистку (см. абзац выше). Явный `return 0` в конце — по той же причине.
_purge_bin() {
    _n=${1##*/}; _hit=0
    if [ -f "$ENODIA_BIN/$_n" ]; then rm -f "$ENODIA_BIN/$_n"; _hit=1; fi
    if [ "$BIN_DIR" != "$ENODIA_BIN" ] && [ -f "$BIN_DIR/$_n" ]; then rm -f "$BIN_DIR/$_n"; _hit=1; fi
    if [ "$_hit" = 1 ]; then ok "Снят бинарь $2 (оставляем: ${INSTALL_ALT})"; fi
    return 0
}
# ГАРД МУЛЬТИ-ТРАНСПОРТА: бинарь «невыбранного» альта может нести ДОП-ВЫХОД (слот, .slots) —
# кейс «основной awg, нейронки через xray-выход» или «byedpi поставлен только как слот-карриер».
# Альт-ось (какой протокол активен основным) и слоты — РАЗНЫЕ вопросы: снос бинаря по смене оси
# молча ломал бы выход, который юзер настроил в панели и в этом диалоге даже не упоминается.
# Считаем ВСЕ слоты, включая выключенные: выключенный слот = сохранённая настройка, а не мусор.
# Формат .slots: id<TAB>name_b64<TAB>transport<TAB>config<TAB>fallback<TAB>on|off (см. slots.sh).
_slot_carrier_in_use() {   # $1 = ключ транспорта (xray|hy2|byedpi); 0 = бинарь нужен выходу
    [ -s "$ENODIA_STATE/.slots" ] || return 1
    cut -f3 "$ENODIA_STATE/.slots" 2>/dev/null | grep -qx "$1"
}
# Обёртка _purge_bin со слот-гардом: пропускает снос, если транспорт несёт хотя бы один выход.
_purge_alt_bin() {   # $1 = путь бинаря ; $2 = метка ; $3 = ключ транспорта
    if _slot_carrier_in_use "$3"; then
        [ -f "$1" ] && warn "$2 оставлен: он несёт дополнительный выход (см. «Соединение → Дополнительные выходы»)."
        return 0
    fi
    _purge_bin "$1" "$2"
}
# hev (tun2socks) общий: его держат и альт-транспорты, и ЛЮБОЙ слот на socks-несущей
# (byedpi/xray/hy2 через slot-tun-lib.sh). Снимаем только когда не нужен никому.
_hev_in_use_by_slot() { _slot_carrier_in_use byedpi || _slot_carrier_in_use xray || _slot_carrier_in_use hy2; }
# Снять РАБОТАЮЩИЙ демон убираемого альта. ЗАЧЕМ: _purge_bin убирает лишь файл-бинарь,
# а ПРОЦЕСС остаётся жив и держит общий socks-порт 10808 (xray и hysteria делят и порт,
# и hev). При свопе альта (xray<->hy2) живой старый демон не даёт новому забиндить порт
# → новый транспорт молча не встаёт, hev продолжает гнать трафик через СТАРЫЙ протокол
# (egress чужого сервера). Бьём по пидфайлу + чистим его (плагин при старте тоже
# подстрахуется через free_foreign_socks, но тут снимаем зомби сразу + освобождаем RAM).
_kill_alt_daemon() { [ -f "$1" ] || return 0; start-stop-daemon -K -p "$1" 2>/dev/null || true; rm -f "$1"; return 0; }
# Если убираемый альт СЕЙЧАС несёт трафик (.transport == он) — СНАЧАЛА чисто отпустить его
# несущую через оркестратор (transport.sh down → fail-open в прямой). ЗАЧЕМ: _kill_alt_daemon
# гасит лишь демон-socks, но xtun с `default` в table 1000 ОСТАЁТСЯ → весь маркированный трафик
# (вкл. собственную интернет-пробу установщика и DNS роутера — оба замаркированы в туннель)
# блэкхолится → pre-flight «Нет интернета» → установка падает, причём В ПЕТЛЮ (каждая повторная
# упрётся в тот же осиротевший дохлый xtun). down флашит table 1000 + ставит прямой DNS → проба
# проходит; новую несущую поднимет основной проход установщика (transport.sh up). Зовётся ТОЛЬКО
# при cur==убираемый → awg-несущую (default dev awg0) не трогает.
# Гард — `-f` + запуск через `sh` (класс Б5-9), а не `-x` с прямым exec: снятый бит выполнения
# у оркестратора означал бы ТИХИЙ пропуск релинквиша, то есть ровно ту петлю, что описана выше.
_relinquish_if_active() {
    cur=$(cat "$ENODIA_STATE/.transport" 2>/dev/null | tr -d ' \r\n')
    [ "$cur" = "$1" ] || return 0
    [ -f "$ENODIA_DIR/transport.sh" ] && sh "$ENODIA_DIR/transport.sh" down "$1" >/dev/null 2>&1
    warn "Убираемый альт ($1) нёс трафик — несущая снята (релинквиш → прямой режим до подъёма новой)."
}
# Метаданные альта в ОДНОМ месте (ключ → бинарь · метка · пидфайл). Раньше тут стояли четыре
# почти одинаковые ветки case, и правка «забывала альт» ровно так же, как в других вилках
# проекта (см. грабли про byedpi в `case "$t"`): цикл по списку такого класса ошибок не имеет.
# Путь спрашиваем у bin_path: альт мог уехать на внешний накопитель, и «бинаря нет на /data» ≠
# «бинаря нет» — иначе чистка молча не находила бы то, что собирается снять.
_alt_bin()   { case "$1" in xray) bin_path xray ;; hy2) bin_path hysteria ;; byedpi) bin_path byedpi ;; esac; }
_alt_label() { case "$1" in xray) echo "Xray" ;; hy2) echo "Hysteria2" ;; byedpi) echo "ByeDPI" ;; esac; }
_alt_pid()   { case "$1" in xray) echo /tmp/enodia-xray.pid ;; hy2) echo /tmp/enodia-hysteria.pid ;; byedpi) echo /tmp/enodia-byedpi.pid ;; esac; }
purge_unselected_alt() {
    [ -n "$INSTALL_ALT" ] || return 0
    _keep=$(printf '%s' "$INSTALL_ALT" | tr ',' ' ')
    case " $_keep " in *" none "*) _keep="" ;; esac      # «none» = не оставляем ни одного
    for _a in xray hy2 byedpi; do
        case " $_keep " in *" $_a "*) continue ;; esac
        _relinquish_if_active "$_a"
        _kill_alt_daemon "$(_alt_pid "$_a")"
        _purge_alt_bin "$(_alt_bin "$_a")" "$(_alt_label "$_a")" "$_a"
    done
    # hev (tun2socks) общий: держится, пока на флеше остаётся хоть один альт-бинарь (в т.ч.
    # уцелевший по слот-гарду) или слот на socks-несущей. Проверяем ПОСЛЕ чистки — по факту
    # файлов, а не по намерению: так ref-count совпадает с packages.sh hev_needed_after().
    _hev_keep=0
    for _a in xray hy2 byedpi; do [ -f "$(_alt_bin "$_a")" ] && { _hev_keep=1; break; }; done
    _hev_in_use_by_slot && _hev_keep=1
    if [ "$_hev_keep" = 1 ]; then
        { [ -z "$_keep" ] && [ -f "$ENODIA_BIN/hev" ] && warn "hev (tun2socks) оставлен: его ещё держит установленный альт или дополнительный выход."; } || true
    else
        _purge_bin "$ENODIA_BIN/hev" "hev (tun2socks)"
    fi
    return 0
}
# Субкоманда от ПК: ТОЛЬКО очистка невыбранного альта и выход (до заливки тяжёлых бинарей).
if [ "${1:-}" = purge-alt ]; then purge_unselected_alt; exit 0; fi

# ============================================================================
# 0. ПРЕДВАРИТЕЛЬНЫЕ ПРОВЕРКИ
# ============================================================================
log "Проверяю окружение..."

if [ "$(id -u)" -ne 0 ]; then
    err "Скрипт должен запускаться от root. Текущий пользователь: $(whoami)"
    exit 1
fi

mkdir -p "$ENODIA_DIR" "$ENODIA_STATE" "$ENODIA_BIN"

# ИМЕНА ПРОШЛОЙ ЭПОХИ В /tmp — ДО ПЕРВОГО ШАГА. Переустановка идёт ПОВЕРХ работающей системы:
# демоны живы и держат пидфайлы под старыми именами, а код на диске уже новый и ищет новые
# (разбор — в шапке ram-lib.sh). Сорсим свою копию — она приехала вместе с этим файлом.
# В подоболочке: у этого файла `set -e`, а провалившийся `.` фатален и без него — перенос имён
# не тот повод, чтобы установка не началась вовсе (тот же довод в boot.sh).
if [ -f "$ENODIA_DIR/ram-lib.sh" ]; then ( . "$ENODIA_DIR/ram-lib.sh"; ram_migrate ) 2>/dev/null || true; fi
chmod 700 "$ENODIA_STATE" 2>/dev/null || true
chmod 755 "$ENODIA_BIN" 2>/dev/null || true
# Суммы пакета (.pkg-sums) описывают набор, который поставил ПАКЕТ. Установка НЕ из пакета (руками по SSH поверх `--push`)
# кладёт исходники с комментариями — сверка «Целостности» с прежними суммами сказала бы «всё расходится». Снимаем: без них
# сверка идёт по суммам репо. Из пакета (INSTALL_FROM_PKG: обновление и установка с ПК) суммы только что положил pkg-install.sh.
if [ -z "$INSTALL_FROM_PKG" ]; then rm -f "$ENODIA_DIR/.pkg-sums" 2>/dev/null || true; fi
# Кэш манифеста бинарей в настройках (`.bin-manifest`, качался с GitHub) — до 30.09.2026: манифест теперь едет в подписанном
# пакете кода и лежит в каталоге кода (разбор у gh-update.sh::BM_FILE). Прежний кэш больше никто не читает и не освежает.
rm -f "$ENODIA_STATE/.bin-manifest" 2>/dev/null || true
# …и то же самое ВГЛУБЬ. Двух chmod выше хватало ровно до появления накопителя: exFAT монтируется
# с `dmask=0000`, оттуда 0777 приезжает `cp -rp`-ом на любую ФС, которая права хранит, — и на
# ext4-флешку, и обратно на флеш роутера. На BE7000 02.09.2026 так стали 0777 каталоги `web` и
# `web/cgi-bin`, а CGI оттуда uhttpd запускает ОТ ROOT (проба из-под `nobody` создала там файл).
# Установщик бежит на каждом обновлении — значит это же и чинилка для тех, кто уже попробовал
# накопитель. Политика режимов живёт в store-lib.sh (harden_perms), второй копии тут нет.
# Гард по наличию: apply-scripts обновляет пофайлово, и новый install.sh рядом со старой
# библиотекой — штатно достижимое состояние (тогда просто остаётся прежнее поведение).
if command -v harden_perms >/dev/null 2>&1; then
    harden_perms "$ENODIA_DIR" "$ENODIA_STATE" "$ENODIA_BIN"
fi
cd "$ENODIA_DIR"

# …и та же роль чинилки — для ХРАНИЛИЩА xray-конфигов. Путь access-лога (`/tmp/xray-access.log`,
# то есть ОЗУ, ~15 МБ/сут) генераторы больше не пишут, но конфиги живут на /data и переживают
# обновление кода: у поставившихся раньше он лежит во ВСЕХ (замер 31.08.2026 — 137 штук), а
# лечился только тот, который поднимают. Разовый прогон дешевле, чем правка на каждом подъёме.
# Гард — по НАЛИЧИЮ файла, не по биту +x (chmod на exFAT = no-op, --push кладёт 644), и `|| true`
# обязателен: выше set -e, а чистка хранилища не повод ронять установку.
if [ -f "$ENODIA_DIR/xray-transport.sh" ]; then
    sh "$ENODIA_DIR/xray-transport.sh" access-purge >/dev/null 2>&1 || true
fi

# ЯЗЫК ПАНЕЛИ ПО УМОЛЧАНИЮ — из env INSTALL_LANG (его шлёт мастер установки, ru|en).
# Зачем: мастер двуязычен, и поставивший роутер английским мастером ждёт английскую панель.
# Язык панели живёт РОВНО в одном месте — строке `lang=` в .prefs (её читают cgi-bin/data →
# panel.js и nf-i18n.sh для писем), поэтому здесь мы лишь кладём НАЧАЛЬНОЕ значение.
# ТОЛЬКО ЕСЛИ ЕГО ЕЩЁ НЕТ: на обновлении человек мог выбрать язык в самой панели, и
# переустановка не имеет права его переучивать. Пусто или незнакомое — не пишем ничего:
# у всех читателей отсутствие строки и так значит ru.
case "$INSTALL_LANG" in
    ru|en)
        if ! grep -q '^lang=' "$ENODIA_STATE/.prefs" 2>/dev/null; then
            # ДОПИСЫВАЕМ, а не переписываем — значит обязаны начать со СВОЕЙ строки. Файл без
            # хвостового перевода строки склеил бы наш ключ с чужим (`theme=darklang=en`), и
            # потерялась бы ЧУЖАЯ настройка, а не наша. Свой писатель (cgi-bin/action set_pref)
            # хвост ставит всегда, но файл переживает бэкап, ручную правку и чужие версии.
            # `$(...)` съедает хвостовой перевод строки ⇒ непустой ответ = последним байтом НЕ он.
            if [ -s "$ENODIA_STATE/.prefs" ] && [ -n "$(tail -c 1 "$ENODIA_STATE/.prefs" 2>/dev/null)" ]; then
                printf '\n' >> "$ENODIA_STATE/.prefs"
            fi
            printf 'lang=%s\n' "$INSTALL_LANG" >> "$ENODIA_STATE/.prefs"
        fi
        ;;
esac

# Что ставим — AmneziaWG / Xray / оба — по наличию конфигов (+ опц. env INSTALL_PROTO
# от be7000.ps1). Это снимает ЖЁСТКОЕ требование awg.conf: возможна установка ТОЛЬКО
# Xray (без AmneziaWG). Гарды [ "$HAVE_AWG" = 1 ] ниже пропускают awg-секции при xray-only.
HAVE_AWG=0;  [ -f "$AWG_CONF" ] && HAVE_AWG=1
HAVE_XRAY=0; ls "$ENODIA_STATE"/xray-configs/*.json >/dev/null 2>&1 && HAVE_XRAY=1
[ -s "$ENODIA_STATE/xray.json" ] && HAVE_XRAY=1
HAVE_HY2=0;  ls "$ENODIA_STATE"/hy2-configs/*.yaml >/dev/null 2>&1 && HAVE_HY2=1
[ -s "$ENODIA_STATE/hysteria.yaml" ] && HAVE_HY2=1
# deferred-config: xray/hy2-ИНФРАСТРУКТУРУ можно поставить БЕЗ её конфига (vless/hy2
# добавят позже — веб-панель «Серверы» или меню «Протокол»). Тогда «есть» = наличие
# БИНАРЯ (стейдж bin/*.user ИЛИ уже установленный), симметрично HAVE_BYEDPI ниже.
# БЕЗОПАСНО без конфига: несущая чисто падает в fail-open (transport.sh up -> 1 -> default
# в table $ROUTE_TABLE НЕ ставится -> прямой режим), а DNS уводится на публичный резолвер
# (секция 3 keyed на ACTIVE_PROTO, не на HAVE_*). Без этого гейт «ничего не найдено» ниже
# блокировал бы установку инфры альта без сервера. HAVE_XRAY/HAVE_HY2 секции обработки
# конфига НЕ гейтят — только гейт-«ничего нет», ACTIVE_PROTO-детект и лог (проверено).
# Установленный бинарь ищем через bin_path: уехавший на внешний накопитель обязан считаться
# установленным, иначе повторная установка сочла бы альт отсутствующим.
{ [ -f "$ENODIA_DIR/bin/xray.user" ] || [ -x "$(bin_path xray)" ]; } && HAVE_XRAY=1
{ [ -f "$ENODIA_DIR/bin/hysteria.user" ] || [ -x "$(bin_path hysteria)" ]; } && HAVE_HY2=1
# ByeDPI (ciadpi) конфига НЕ имеет (DPI-десинк без VPS) — «есть» = бинарь, стейджинговый
# (bin/byedpi.user, ещё не перенесён) ИЛИ уже установленный. Иначе byedpi-only установка
# (нет ни одного конфига) ложно падала бы в гард «ничего не найдено» ниже.
HAVE_BYEDPI=0; { [ -f "$ENODIA_DIR/bin/byedpi.user" ] || [ -x "$(bin_path byedpi)" ]; } && HAVE_BYEDPI=1
# INSTALL_PROTO=none — установка «ТОЛЬКО ПАНЕЛЬ»: раскладываем скрипты, панель и cron, а протоколы
# человек добирает уже в браузере («Компоненты» качает их с GitHub). Транспорта в этот момент нет
# ВООБЩЕ, и это не аварийное состояние, а штатное: роутер работает ровно как сток, наших правил в
# ядре нет (см. transport.sh cmd_configured). Гейт «ничего не найдено» ниже для такой установки —
# ложный: искать нечего по замыслу.
PANEL_ONLY=0
# Форма `if`, а НЕ `[ … ] && PANEL_ONLY=1`: скрипт под `set -e`, и на ОБЫЧНОЙ установке (где
# INSTALL_PROTO пуст) такой страж возвращает 1. На ash роутера он в середине тела выживает, но
# ставить единственный путь всех не-панельных установок в зависимость от квирка незачем.
if [ "$INSTALL_PROTO" = none ]; then PANEL_ONLY=1; fi
# ...НО «только панель» ПОВЕРХ УЖЕ НАСТРОЕННОЙ системы — это НЕ установка с нуля. `enodia.py`
# зовёт нас и как «переустановить/починить», то есть типовой повод — обновить скрипты на рабочем
# роутере. Снять там чужой выбор транспорта значит уронить работающий VPN, причём ХУЖЕ, чем
# честным сносом: правила ядра и демоны остаются в живых, а `.transport` пропадает ⇒ сторож
# считает роутер ненастроенным и замолкает (не проверяет health, не делает failover, не уводит
# в fail-open), heal после ребута ничего не поднимает, а панель пишет «Протокол не выбран» при
# живом туннеле. Поэтому: транспорт выбран — не трогаем НИЧЕГО из его хозяйства (флаг, DNS,
# маркировку, несущую), ставим только скрипты, панель и cron. Владелец ответа один — оркестратор;
# код 2 (старая копия скрипта) = «настроен», то есть ведём себя осторожно.
KEEP_TRANSPORT=0
if [ "$PANEL_ONLY" = 1 ] && [ -f "$ENODIA_DIR/transport.sh" ]; then
    sh "$ENODIA_DIR/transport.sh" configured >/dev/null 2>&1 && _kt=0 || _kt=$?
    if [ "$_kt" != 1 ]; then KEEP_TRANSPORT=1; fi
fi
if [ "$PANEL_ONLY" = 0 ] && [ "$HAVE_AWG" = 0 ] && [ "$HAVE_XRAY" = 0 ] && [ "$HAVE_HY2" = 0 ] && [ "$HAVE_BYEDPI" = 0 ]; then
    err "Не найдено ни $AWG_CONF, ни xray-/hy2-конфигов, ни byedpi-бинаря."
    err "Положите awg.conf (AmneziaWG) и/или альт-конфиг (Xray/Hysteria2) либо bin/byedpi.user и запустите снова."
    err "Нужна установка без транспорта (только веб-панель) — запустите с INSTALL_PROTO=none."
    exit 1
fi
# Активный транспорт: awg (если awg.conf), иначе xray, иначе hy2, иначе byedpi. Переопределяется env INSTALL_PROTO.
if [ "$HAVE_AWG" = 1 ]; then ACTIVE_PROTO=awg; elif [ "$HAVE_XRAY" = 1 ]; then ACTIVE_PROTO=xray; elif [ "$HAVE_HY2" = 1 ]; then ACTIVE_PROTO=hy2; else ACTIVE_PROTO=byedpi; fi
[ -n "$INSTALL_PROTO" ] && ACTIVE_PROTO="$INSTALL_PROTO"
if [ "$PANEL_ONLY" = 1 ] && [ "$KEEP_TRANSPORT" = 1 ]; then
    ok "Режим: ТОЛЬКО ПАНЕЛЬ поверх настроенной системы — транспорт и его правила не трогаю"
elif [ "$PANEL_ONLY" = 1 ]; then
    ok "Режим: ТОЛЬКО ПАНЕЛЬ — транспорт не активируем, протоколы добираются в браузере"
else
    ok "Ставим: AmneziaWG=$HAVE_AWG, Xray=$HAVE_XRAY, Hysteria2=$HAVE_HY2, ByeDPI=$HAVE_BYEDPI; активный транспорт = $ACTIVE_PROTO"
fi
# Архитектура — в лог ВСЕГДА: чужие логи с других моделей (BE3600 и т.п.) приходят без неё,
# а это первое, что нужно знать, когда бинари не стартуют.
ok "Роутер: $(uname -m), ядро $(uname -r)"

# ============================================================================
# УСТАНОВКА ПРЕЖНЕЙ ВЕРСИИ РЯДОМ (до ребрендинга каталог звался /data/usr/app/awg)
# ============================================================================
# Мы поставим себя в ДРУГОЙ каталог и заведём СВОИ cron-строки — а прежние никуда не денутся и
# продолжат каждую минуту звать старый heal из старого каталога. Две копии системы разом дерутся
# за одни и те же iptables/ipset/dnsmasq: правила ставит одна, снимает другая, и разобрать это
# по логам почти невозможно — каждая половина уверена, что работает правильно.
# ОТКАЗЫВАЕМСЯ, А НЕ ЧИСТИМ САМИ. Снять прежнюю установку умеет только её собственный
# uninstall.sh: он знает свои имена цепочек, сетов и cron-строк, а мы — уже нет. Запускать чужой
# код из установщика — это выполнять то, чего мы в этой версии не выпускали; тихо оставить как
# есть — отдать человеку роутер с двумя хозяевами. Честный ответ здесь один: остановиться и
# сказать, чем это снимается.
# Признаков ДВА, и второй важнее. Вред создаёт не файл, а ЖИВАЯ cron-строка на старый каталог:
# именно она каждую минуту поднимает вторую копию. Каталог без uninstall.sh (частично удалённый
# руками, очень старая сборка) первый признак пропустил бы, а cron продолжил бы звать прежний
# heal — то есть гард молчал бы ровно в том случае, ради которого он и написан.
LEGACY_DIR=/data/usr/app/awg
_legacy=0
if [ -f "$LEGACY_DIR/uninstall.sh" ]; then _legacy=1; fi
if grep -qF "$LEGACY_DIR/" /etc/crontabs/root 2>/dev/null; then _legacy=1; fi
if [ "$LEGACY_DIR" != "$ENODIA_DIR" ] && [ "$_legacy" = 1 ]; then
    err "На роутере стоит ПРЕЖНЯЯ версия — $LEGACY_DIR (каталог переехал при ребрендинге)."
    err "Две копии разом дерутся за iptables и cron, поэтому ставить поверх нельзя."
    err "Снимите прежнюю — панель: «Настройки» → «Удаление» → «Удалить всё»,"
    err "либо по SSH:  sh $LEGACY_DIR/uninstall.sh purge"
    err "После этого запустите установку заново."
    exit 1
fi

# Проверяем интернет. TCP-проба (curl) надёжнее ICMP: ping не пройдёт, если трафик к
# 1.1.1.1 уже маркирован в туннель (xray несёт через SOCKS, а SOCKS не передаёт ICMP;
# при awg — через awg0), либо провайдер режет ICMP. Фолбэк на ping — для сетей, где
# curl к этим хостам закрыт.
# ВТОРОЙ ЗАХОД — С БИНДОМ К WAN, и без него проверка ВРЁТ (разбор со скрином тестера 14.08.2026).
# Все три пробы выше едут ровно теми путями, которые ломает ПРОШЛАЯ установка: 1.1.1.1 и 8.8.8.8
# лежат в iplist_set ⇒ маркируются в table 1000, то есть в туннель; имя gstatic резолвится нашим
# dnsmasq, а его upstream заперт туда же (при «Шифрованном DNS» — единственный, через прокси).
# Мёртвая несущая + живой провайдер = все три промаха, и человек читал «подключи WAN-кабель» при
# воткнутом кабеле, а установку, которая это и чинит, инсталлер отказывался начинать.
# Бинд к WAN обходит `ip rule` (SO_BINDTODEVICE решает раньше таблиц) — инвариант проекта: фолбэк
# «в обход туннеля» обязан биндиться, иначе он не в обход.
# ЗАХОД ОБЯЗАН БЫТЬ БЕЗ TLS-ВЕРИФИКАЦИИ (`-k`) И С ПИНГОМ-ФОЛБЭКОМ. Замерено на AX3600 (ядро 4.4,
# CA-бандл Feb 2023, OpenSSL 1.0.2q 2018): ЛЮБОЙ `curl https://…` там даёт rc=60 «unable to get
# local issuer certificate» — и по туннелю, и по WAN, при живом интернете. То есть на старых сборках
# обе прямые https-пробы выше бесполезны ВСЕГДА, а WAN-заход через https повторял бы их судьбу и
# «спасал» ровно там, где спасать не от чего. Мы проверяем ДОСТИЖИМОСТЬ, а не подлинность узла ⇒
# `-k` тут не ослабление (тот же приём уже у закачек списков), а `ping -I` закрывает случай, когда
# TCP/443 к 1.1.1.1 режет провайдер.
WAN_IF=$(wan_iface)   # владелец имени — ip-lib.sh (шим в шапке)
if curl -fsSk --max-time 5 -o /dev/null https://1.1.1.1 2>/dev/null || \
   curl -fsSk --max-time 5 -o /dev/null https://www.gstatic.com/generate_204 2>/dev/null || \
   ping -c 1 -W 3 1.1.1.1 >/dev/null 2>&1; then
    ok "Интернет на роутере есть"
elif [ -n "$WAN_IF" ] && { curl -fsSk --max-time 5 --interface "$WAN_IF" -o /dev/null https://1.1.1.1 2>/dev/null || \
                           ping -I "$WAN_IF" -c 1 -W 3 1.1.1.1 >/dev/null 2>&1; }; then
    warn "Интернет ЕСТЬ (проверено через $WAN_IF), но трафик роутера заворачивается в неработающий туннель"
    warn "— это следы прошлой установки. Продолжаю: установка их перезапишет."
elif [ -n "$INSTALL_FROM_PKG" ]; then
    # Из пакета (обновление с GitHub И установка с ПК — путь один) отказывать ПОЗДНО: файлы уже новые, и оборванный
    # установщик оставил бы cron и бутстрап прежними. И незачем: пакету сеть не нужна — ПК привёз его в архиве.
    warn "Нет интернета на роутере: панель встанет, но протоколы и списки ей качать будет неоткуда, пока не появится связь."
    warn "Кабель на месте, а связи нет? Похоже на правила прошлой установки — снимите её (панель → «Удаление») и повторите."
else
    err "Нет интернета на роутере. Подключите WAN-кабель/проверьте настройки."
    err "Кабель на месте? Тогда снимите прошлую установку (в панели «Удаление» либо enodia-setup.bat) и повторите:"
    err "её правила могли остаться и уводить трафик роутера в туннель, которого больше нет."
    exit 1
fi

# ============================================================================
# 0.1 ПОДГОТОВКА КОНФИГА — чистим пустые I1..I5
# ============================================================================
# AmneziaVPN 4.8.12.9+ добавляет в конфиг заготовки I1..I5 даже в Legacy.
# Если они пустые (I2 = ), awg-tools падает: "Line unrecognized: I2=".
# Заполненные I1 (например, I1 = <b 0xHEX...>) — НЕ трогаем.
# ----------------------------------------------------------------------------
if [ "$HAVE_AWG" = 1 ] && grep -qE '^I[1-5]\s*=\s*$' "$AWG_CONF"; then
    log "Чищу пустые поля I1..I5 в awg.conf..."
    sed -i '/^I[1-5]\s*=\s*$/d' "$AWG_CONF"
    ok "Пустые I-поля удалены"
fi

# ============================================================================
# 0.2 СОЗДАЁМ amnezia_for_awg.conf — вендорный awg_setup.sh его ждёт
# ============================================================================
# Без этого файла на ПЕРВОМ запуске awg_setup.sh падает с
# "File amnezia_for_awg.conf not found". На втором запуске сам бы его
# создал, но первый запуск выглядит для пользователя как FAIL.
# ----------------------------------------------------------------------------
if [ "$HAVE_AWG" = 1 ] && [ ! -f "$ENODIA_STATE/amnezia_for_awg.conf" ]; then
    cp "$AWG_CONF" "$ENODIA_STATE/amnezia_for_awg.conf"
    ok "amnezia_for_awg.conf создан из awg.conf"
fi

# ============================================================================
# 0.2b АРХИТЕКТУРА БИНАРЕЙ: наши bin/*.user vs этот роутер
# ============================================================================
# В $ENODIA_DIR/bin/ приезжает набор ОДНОЙ арки: ПК-сторона (enodia.py) опознаёт роутер и
# льёт bin/arm64/ или bin/armv7/ уже плоско, сюда — значит этот гард ловит не «набор один
# на всех», а РАССОГЛАСОВАНИЕ (лили не тем путём, ручная копия, старый снимок с одним
# набором). Если арка не та — execve отдаёт ENOEXEC, и busybox ash молча берётся читать
# ELF как СКРИПТ, печатая «line 0: syntax error: unexpected word». Раньше этот текст
# уезжал внутрь ok "... ($(бинарь --version))",
# т.е. установка РАПОРТОВАЛА УСПЕХ, гоняла полный fw3 reload и падала только через 30 с
# на ожидании awg0 — с ложным диагнозом «проверь awg.conf, ключи и endpoint VPS» (лог
# тестера на BE3600, 2026-07-15: два полных прогона, причина ни разу не названа).
# Отказываем СРАЗУ, до первого mv, и называем настоящую причину.
#
# КАК: сравниваем поле e_machine (байты 18-19 ELF-заголовка) нашего бинаря и заведомо
# рабочего /bin/busybox. Какой именно там код — знать не нужно, важно «совпало/нет».
# `od` в busybox НЕТ (грабля) → 2 байта достаём через dd и сравниваем cmp. Нет dd/cmp
# или busybox не читается — гард молча пропускаем (fail-open: не мешать установке там,
# где мы просто не смогли проверить).
_elf_machine() { dd if="$1" of="$2" bs=1 skip=18 count=2 2>/dev/null; }
bin_arch_matches() {
    _ref=/bin/busybox
    [ -r "$_ref" ] || return 0
    command -v dd >/dev/null 2>&1 || return 0
    command -v cmp >/dev/null 2>&1 || return 0
    # Все bin/*.user собраны под одну арх ⇒ достаточно первого попавшегося.
    _probe=""
    for _f in "$ENODIA_DIR"/bin/*.user; do
        if [ -f "$_f" ]; then _probe="$_f"; break; fi
    done
    [ -n "$_probe" ] || return 0
    _elf_machine "$_ref" /tmp/.enodia-arch-ref.$$ || return 0
    _elf_machine "$_probe" /tmp/.enodia-arch-bin.$$ || return 0
    if cmp -s /tmp/.enodia-arch-ref.$$ /tmp/.enodia-arch-bin.$$; then _rc=0; else _rc=1; fi
    rm -f /tmp/.enodia-arch-ref.$$ /tmp/.enodia-arch-bin.$$
    return $_rc
}
if ! bin_arch_matches; then
    err "Бинари bin/*.user НЕ подходят к архитектуре этого роутера — установка невозможна."
    err "Роутер: $(uname -m); в bin/ лежит набор под ДРУГУЮ арку."
    err "Ядро откажется их запускать (ENOEXEC), busybox напечатает «syntax error» вместо"
    err "версии, и туннель не поднимется. Наборы собраны под arm64 и armv7 — ПК-сторона"
    err "(enodia.py) выбирает нужный сама; сюда, похоже, приехал не тот. Переустановите с ПК."
    err "Пришлите разработчику: uname -a; cat /proc/cpuinfo"
    exit 1
fi

