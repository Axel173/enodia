# и потому переживает не только удаление, но и следующую установку: разбивка места считает всё, что
# не наш каталог, СТОКОВЫМ — в панели наш же файл висел под заголовком «Роутер · стоковое, не
# трогаем», а уборщик его не видел вовсе. Отчёт нужен ровно до переустановки: она и есть ответ на
