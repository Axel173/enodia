#!/bin/sh
# ip-lib.sh — общий примитив «внешний IPv4» (что видит удалённая сторона на заданном пути).
# ЕДИНЫЙ источник истины вместо россыпи разнобойных `curl … https://api.ipify.org` по проекту
# (cgi-bin/ip, status.sh, watchdog, диагностики). Только читает сеть, ничего не меняет.
#
# ГЛАВНАЯ ГРАБЛЯ (ядро 4.4 — AX3600/BE3600, поймано на железе 2026-07-16): hostname-проба
# `curl https://api.ipify.org` на ядре 4.4 молча возвращала ПУСТО — egress в шапке панели не
# отображался, status.sh писал «api.ipify.org не ответил», — при том что само имя РЕЗОЛВИЛОСЬ
# (nslookup ок) и туннель работал. IP-ЛИТЕРАЛ Cloudflare trace (`https://1.1.1.1/cdn-cgi/trace`,
# строка `ip=…`) НЕ зависит от DNS и отдаёт ответ на ОБОИХ ядрах (5.4 и 4.4) за ~0 с. Это тот же
# принцип «IP-литерал вместо хрупкого busybox-DNS», что и DoH в fetch_url движка списков.
# `-k`: на старом OpenSSL (1.0.2q, ядро 4.4) сертификат к 1.1.1.1 по IP не всегда валиден; из
# ответа берём ТОЛЬКО строку IP (не секрет), поэтому проверку сертификата тут можно опустить.

IP_PROBE_TRACE="https://1.1.1.1/cdn-cgi/trace"      # DNS-free дефолт; Cloudflare ∈ iplist_set
# ВТОРОЙ узел того же trace — ДОПОЛНИТЕЛЬНАЯ попытка, её просят четвёртым аргументом (tries=2).
# Нужна потому, что промах ОДНОЙ попытки бывает и на живом канале: замерено на AX3600 17.08.2026 —
# 3 пустых ответа из 10 с лимитом 7 с, ровно в минуты, когда dnsmasq грузил 300 тыс. строк гео
# (load 2.2); через полчаса на том же роутере 12/12 успехов за ~0 с. Бюджет съедает не сеть, а
# ЗАНЯТЫЙ роутер, и «пусто» тогда значит «не успели», а не «пути нет».
# ПОЧЕМУ НЕ ВСЕМ И НЕ ВСЕГДА — две границы, обе стоят дорого:
#   * `cmd_health` у xray/hy2 судит по ЭТОЙ пробе и зовётся в НЕОГРАНИЧЕННОМ цикле перебора
#     конфигов (у тестера их 102). Лишняя попытка на каждом мёртвом кандидате удлинила бы аварийный
#     failover на минуты — там дешевле промахнуться и дать сторожу перепроверить через 2 минуты;
#   * 1.1.1.1 ∈ iplist_set, а 1.0.0.1 — НЕТ (замерено) ⇒ у пробы БЕЗ bind'а смена адреса меняет и
#     ПУТЬ (первый уходит в туннель, второй напрямую) ⇒ ответ был бы про другой путь. Поэтому вторая
#     попытка возможна только при прибитом пути: --interface/--socks5.
# Итог: tries=1 по умолчанию (для всех прежних вызовов поведение БАЙТ-В-БАЙТ), tries=2 просит тот,
# чьё число читает человек и кто закрыт кэшем — панельный cgi-bin/ip.
IP_PROBE_TRACE2="https://1.0.0.1/cdn-cgi/trace"
IP_PROBE_URL="${IP_PROBE_URL:-$IP_PROBE_TRACE}"      # можно переопределить окружением/аргументом

# _ip_from_body <body> — выцепить IPv4 из ответа пробы. Сперва trace-строка `ip=1.2.3.4`; иначе
# тело целиком = «голый» IP (совместимость с api.ipify.org и подобными). Печатает IP или ничего.
# ВАЖНО: тело передаём АРГУМЕНТОМ, а не пайпом — иначе первая же стадия (`sed`) съест весь stdin,
# и ветка «голый IP» получит пусто (грабля busybox-пайпа, встречалась в проекте).
_ip_from_body() {
    _e=$(printf '%s\n' "$1" | sed -n 's/^ip=\([0-9.]*\).*/\1/p' | head -1)
    [ -n "$_e" ] || _e=$(printf '%s' "$1" | tr -d ' \t\r\n')
    printf '%s' "$_e" | grep -qE '^([0-9]{1,3}\.){3}[0-9]{1,3}$' && printf '%s' "$_e"
}

# probe_ext_ip <curl-bind-args> [timeout] [url] — IPv4, увиденный снаружи через заданный путь.
#   bind-args: ""                              — прямой выход роутера (как есть по маршрутам);
#              "--interface awg0"              — egress через awg-туннель;
#              "--socks5-hostname 127.0.0.1:10808" — egress через альт (xray/hy2/byedpi);
#              "--interface eth0"              — реальный WAN В ОБХОД собственного туннеля (bind к WAN-iface).
#   url: по умолчанию IP_PROBE_URL. Если задан кастомный (напр. сохранённый api.ipify.org) и он
#        промолчал — добиваем DNS-free trace'ом (фолбэк ниже). На успехе primary фолбэк не выполняется.
# Пусто на выходе = путь не ответил. Один сетевой вызов на успехе (цена фолбэка — только при пустом primary).
#   tries: 1 (умолчание) — как было; 2 — при пустом ответе добить ВТОРЫМ узлом trace (только с
#          bind'ом/socks, см. разбор у IP_PROBE_TRACE2). Цена — ещё один timeout, и только на промахе.
# Порядок попыток: кастомный URL (если задан) → trace 1.1.1.1 → [tries=2] trace 1.0.0.1.
probe_ext_ip() {
    _pa="$1"; _pt="${2:-7}"; _url="${3:-$IP_PROBE_URL}"; _pn="${4:-1}"
    [ -n "$_url" ] || _url="$IP_PROBE_TRACE"
    _body=$(curl -s -k $_pa --max-time "$_pt" "$_url" 2>/dev/null)   # $_pa НАМЕРЕННО без кавычек — сплит на аргументы
    _ip=$(_ip_from_body "$_body")
    [ -n "$_ip" ] && { printf '%s' "$_ip"; return 0; }
    if [ "$_url" != "$IP_PROBE_TRACE" ]; then                         # primary был кастомным — добиваем trace'ом
        _body=$(curl -s -k $_pa --max-time "$_pt" "$IP_PROBE_TRACE" 2>/dev/null)
        _ip=$(_ip_from_body "$_body")
        [ -n "$_ip" ] && { printf '%s' "$_ip"; return 0; }
    fi
    # Второй узел — по запросу И только с bind'ом/socks: у пробы «как решат маршруты» он измерил бы
    # ДРУГОЙ путь (1.0.0.1 вне iplist_set), а у health-цикла отнял бы минуты на переборе конфигов.
    if [ "$_pn" -gt 1 ] 2>/dev/null; then
        case "$_pa" in
            *--interface*|*--socks5*)
                _body=$(curl -s -k $_pa --max-time "$_pt" "$IP_PROBE_TRACE2" 2>/dev/null)
                _ip_from_body "$_body" ;;
        esac
    fi
    # КОД ВОЗВРАТА ВСЕГДА 0: контракт функции — «путь не ответил» это ПУСТАЯ СТРОКА, а не ошибка.
    # Без этой строки последней командой оставался бы grep внутри _ip_from_body, и rc зависел бы от
    # того, какой ветвью вышли (прежний код на дефолтном URL выходил через свой `return 0` ДО
    # фолбэка, а на кастомном — отдавал rc grep'а: разнобой на пустом ответе).
    # ЧЕСТНАЯ ГРАНИЦА (замерено, а не выведено): под `set -e` эта функция всё равно роняет скрипт, но
    # РАНЬШЕ — на `_body=$(curl …)`, потому что curl на таймауте выходит с 28. Сегодня из-под `set -e`
    # её не зовёт никто (только install.sh и build-byedpi.sh с `set -e`, и они её не зовут);
    # кто соберётся — обязан гасить сам (`|| true`), одним `return 0` тут не закрыться.
    return 0
}

# is_private_ip <ipv4> — 0, если адрес приватный/CGNAT/link-local/loopback (т.е. НЕ настоящий
# публичный WAN). Нужно, чтобы понять, стоит ли ради «реального WAN» делать сетевую пробу: если
# адрес WAN-интерфейса уже публичный (обычный роутер на границе), проба избыточна — берём его как есть.
# Диапазоны: 10/8, 172.16/12, 192.168/16, 100.64/10 (CGNAT), 169.254/16 (link-local), 127/8.
is_private_ip() {
    case "$1" in
        10.*|127.*|169.254.*|192.168.*) return 0 ;;
        172.1[6-9].*|172.2[0-9].*|172.3[0-1].*) return 0 ;;
        100.6[4-9].*|100.[7-9][0-9].*|100.1[0-1][0-9].*|100.12[0-7].*) return 0 ;;
    esac
    return 1
}

# wan_iface — имя интерфейса дефолт-маршрута (eth0 на BE7000, eth1 на AX3600), пусто = дефолта нет.
# ЖИВЁТ ЗДЕСЬ, а не в watchdog.sh, потому что нужен КАЖДОМУ, кто ходит в сеть МИМО туннеля
# (`curl --interface`): WAN-гейт сторожа, проба внешнего адреса, сверка часов (clock-lib.sh).
# ЕДИНСТВЕННЫЙ ВЛАДЕЛЕЦ трёх ответов по маршрутам (следит C81): «какой интерфейс WAN» (эта
# функция), «какой у WAN шлюз» (wan_gateway) и «какое устройство несёт туннель» (carrier_iface).
# До 05.09.2026 awk-строка «dev у дефолта main» жила ЧЕТЫРНАДЦАТЬЮ копиями (status, support,
# traffic-acct, install, dump, lists-lib, четыре CGI, web-ui…), и половина копий разошлась по
# смыслу: одни исключали свои несущие, другие нет, web-ui спрашивал uci и `ip route get`. Копия,
# которая не исключает awg0, при дефолте main в туннеле биндит «пробу мимо туннеля» в сам туннель.
# У потребителей остаются ШИМЫ на случай старой/частичной установки — ровно одной строкой и того же
# смысла; они не реализация, а страховка (C81 требует рядом с шимом и сорс этой библиотеки).
# Дефолт MAIN-таблицы, а НЕ `ip route get`: ответ последнего искажён тем, что мы чиним (awg-режим
# кладёт `/32 dev awg0`, 8.8.8.8 ∈ iplist_set). СВОИ НЕСУЩИЕ WAN-ом НЕ СЧИТАЕМ (гард из dns-lib.sh):
# дефолт в awg0/xtun ПРОПУСКАЕМ и берём СЛЕДУЮЩИЙ дефолт main (легаси-состояние «default dev awg0»
# рядом с настоящим), а нет другого — отвечаем ПУСТО, и вызывающий честно узнаёт «биндить некуда»,
# а не биндит пробу «мимо туннеля» в сам туннель. Шим у потребителей — ЭТА ЖЕ awk-строка, C81
# сверяет её текст с каноном (шим с иным телом = вторая реализация).
wan_iface() {
    ip route show default 2>/dev/null | awk '/^default/{d=""; for(i=1;i<=NF;i++) if($i=="dev") d=$(i+1); if(d!="" && d !~ /^(awg|xtun)/){print d; exit}}'
}

# wan_gateway — адрес шлюза дефолт-маршрута main (`via`), пусто = дефолта нет или он без via
# (PPPoE/point-to-point). Нужен allowlist'у ipblock (шлюз нельзя дропать), гарду отката
# ipblock (пинг до шлюза) и дампу. Тот же источник, что у wan_iface, — иначе «шлюз» и
# «интерфейс» могли бы прийти из разных маршрутов.
wan_gateway() {
    ip route show default 2>/dev/null | awk '/^default/{for(i=1;i<=NF;i++) if($i=="via"){print $(i+1); exit}}'
}

# carrier_iface — устройство несущей = dev у `default` в боевой table 1000 (awg0 / xtun). Ставит
# его ТОЛЬКО плагин несущей, поэтому это единственный честный признак «несущая держит маршрут»:
# пусто = lookup проваливается в main = трафик идёт ПРЯМО (ровно это и обещает fail-open, см.
# switch-vpn.sh safety_off). Доп-выходы живут в СВОИХ table 100N и сюда не попадают. Спрашивают
# сторож (carrier_route_dev) и карточка адаптеров панели (sysinfo).
carrier_iface() {
    ip route show table 1000 2>/dev/null | awk '/^default/{for(i=1;i<=NF;i++) if($i=="dev"){print $(i+1); exit}}'
}

# carrier_mtu — MTU НЕСУЩЕЙ, то есть ФАКТ из ядра, а не намерение `.tun-mtu`: у awg0 норма
# проекта 1376 (у нативного .conf строки MTU= нет никогда, а 1420 дают 36 КБ/с — замер
# [[awg-native-conf-mtu-default]]), у альтов несущая xtun с 8500, и это норма tun2socks.
# Спрашивает лента технического состояния «Обзора»: чип MTU висит ТОЛЬКО при отклонении, а
# отклонение видно лишь по живому интерфейсу — файл `.tun-mtu` при активном xray говорит про
# awg0, которого нет. Пусто (rc=1) = несущей нет вовсе, спрашивать нечего.
# Читаем sysfs, а не `ip link | sed`: это один файл без форка, и вопрос «какой у интерфейса MTU»
# ни во что больше не превращается.
# ПУСТО, А НЕ КОД ВОЗВРАТА: это функция-ЗНАЧЕНИЕ, как соседние wan_iface/carrier_iface, и
# «несущей нет» здесь ровно то же, что «нечего показывать». Ненулевой rc уронил бы вызывающего
# под `set -e` (`mtu=$(carrier_mtu)` — статус присваивания = статус подстановки), а соседи по
# файлу так не делают: две разные семантики у функций одного вида — это ловушка на будущее.
carrier_mtu() {
    _cmi=$(carrier_iface)
    if [ -n "$_cmi" ]; then cat "/sys/class/net/$_cmi/mtu" 2>/dev/null || true; fi
    return 0
}

# wan_up — 0, если аплинк ЖИВ по ЖЁСТКИМ ЛОКАЛЬНЫМ признакам: дефолт main есть И физлинк на его
# интерфейсе поднят. Намеренно БЕЗ пинга шлюза: провайдер вправе резать ICMP, а ложное «WAN мёртв»
# подавило бы ЗАКОННЫЙ перебор резервов у сторожа. Вопрос «есть ли интернет ВООБЩЕ» — ДРУГОЙ и
# дороже: на него отвечает wan_probe_ok ниже (реальная egress-проба с биндом к WAN; решение «гасить
# ли перебор» — у сторожа, inet_reachable), и путать их нельзя: авария у провайдера сюда не
# попадает НАМЕРЕННО.
# Копий было ДВЕ — watchdog.sh и его зеркало в support.sh с пометкой DRY; разойдись они, в аварии
# «жив ли аплинк» отвечалось бы по-разному тому, кто чинит, и тому, кто зовёт на помощь. Следит C81.
wan_up() {
    _wu=$(wan_iface)
    [ -n "$_wu" ] || return 1
    if [ -r "/sys/class/net/$_wu/carrier" ]; then
        [ "$(cat "/sys/class/net/$_wu/carrier" 2>/dev/null)" = "1" ] || return 1
    fi
    return 0
}

# wan_probe_ok — 0, если ИНТЕРНЕТ ЧЕРЕЗ WAN ЕСТЬ ПО ФАКТУ: реальная egress-проба, привязанная к WAN.
# Нужна там, где wan_up слеп: при аварии У ПРОВАЙДЕРА линк и дефолт на месте, а интернета нет.
# `--interface` ОБЯЗАТЕЛЕН: роутер сам заворачивает 1.1.1.1/8.8.8.8 в несущую (mangle OUTPUT MARK от
# set_*_dns + ip route dns/32 dev awg0 + оба ∈ iplist_set) ⇒ проба без бинда померяла бы ТУННЕЛЬ, а не
# аплинк. Цена — до двух curl по 4 с, когда WAN мёртв; при живом — доли секунды. Второй адрес другого
# оператора: у части провайдеров Cloudflare заворачивается/режется, и одна цель давала бы вечное
# «интернета нет»; тут важен ФАКТ соединения, а не тело — любой ответ (даже 404) = сеть жива.
# Жила у сторожа; переехала сюда 02.10.2026, когда её понадобилось спрашивать и ИЗНУТРИ перебора
# резервов (xray/hy2): аплинк умирает и посреди 20-минутного свипа, а сторож узнаёт об этом лишь после.
wan_probe_ok() {
    _wpi=$(wan_iface)
    [ -n "$_wpi" ] || return 1
    [ -n "$(probe_ext_ip "--interface $_wpi" 4)" ] && return 0
    curl -s -k -o /dev/null --interface "$_wpi" --max-time 4 https://8.8.8.8/ 2>/dev/null
}

# wan_recheck — ВТОРАЯ проба после промаха, через WAN_RECHECK секунд: «промах единичный?» решается
# В ТОМ ЖЕ проходе, а не следующим тиком сторожа. ГРАБЛЯ (BE7000, 02.10.2026): гистерезис считал
# промахи по ТИКАМ, а тик, начавший лестницу, сам длился 26 мин — восемь серверов AmneziaWG, cross на
# xray и ~70 его конфигов при лёгшем провайдере; подтверждающий промах пришёл только после всего
# этого. Пауза — чтобы вторая проба не легла в ту же секундную икоту, что и первая.
# 0 = вторая проба ПРОШЛА (промах был единичным), иначе аплинка нет.
WAN_RECHECK=${WAN_RECHECK:-10}
wan_recheck() {
    sleep "$WAN_RECHECK"
    wan_probe_ok
}
