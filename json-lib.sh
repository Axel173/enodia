#!/bin/sh
# json-lib.sh — ЕДИНСТВЕННЫЙ перевод «вывод скрипта → строка внутри JSON» на весь проект.
# СОРСИТСЯ (не исполняется): потребители — CGI панели (action/data/2fa), web-ui.sh, packages.sh и gh-update.sh (журналы для панели).
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Конвейер «обрезать и заэкранировать» переписывали в каждом месте, где
# сообщение роутера уезжает в панель, и копии РАЗОШЛИСЬ: батч 12 свёл шесть копий внутри
# cgi-bin/action в jesc(), но ровно тот же конвейер жил ещё в четырёх ветках cgi-bin/data, трёх
# ветках cgi-bin/2fa и в web-ui.sh — и там он остался в прежнем, дефектном виде (где-то кавычки
# ВЫРЕЗАЛИСЬ вместо экранирования, где-то обрезка шла ПОСЛЕ экранирования, нигде не снимался
# сырой TAB). Общего файла у этих четверых нет: action/data сорсят store-lib, 2fa — totp.sh,
# web-ui — nf-i18n. Поэтому дом у примитива свой.
#
# ТРИ ЛОВУШКИ, ради которых функция вообще существует (все замерены на железе):
#  - `cut -c` у busybox режет БАЙТАМИ (`printf 'абв' | cut -c1-3` → D0 B0 D0): обрыв приходится
#    на середину кириллической буквы, и хвост сообщения приезжает в панель «ромбиком». Недобитую
#    последовательность снимаем — и ТОЛЬКО её (целый символ на конце не трогаем, иначе каждое
#    короткое сообщение теряло бы последнюю букву);
#  - режем ДО экранирования: после него на границе мог остаться нечётный `\` от пары `\\`, а это
#    уже не «кривой хвост», а сломанный JSON — падает разбор ВСЕГО ответа, не одного поля;
#  - сырой TAB внутри JSON-строки невалиден, а TSV в проекте печатает половина скриптов.
#
# ШИМ У ПОТРЕБИТЕЛЕЙ ОБЯЗАТЕЛЕН: файл может не доехать на старую установку. Сорсить только
# `if [ -f "$lib" ]; then . "$lib"; fi` — провалившийся `.` в busybox ash фатален для шелла.

# jtrim — снять НЕДОБИТУЮ UTF-8 последовательность в конце. Ведущий байт без положенного числа
# продолжений: 2-байтовый C2..DF, 3-байтовый E0..EF, 4-байтовый F0..F4.
jtrim() { sed "s/[$(printf '\302-\337')]\$//; s/[$(printf '\340-\357')][$(printf '\200-\277')]\{0,1\}\$//; s/[$(printf '\360-\364')][$(printf '\200-\277')]\{0,2\}\$//"; }

# jtxt <лимит байт> — ДАННЫЕ со stdin (имя сети, имя устройства) → содержимое JSON-строки. То же, что jesc, но без вырезания
# ANSI-цветов: в имени сети «[m» и «[5m» — буквы, а не код терминала, и jesc уносил их (ключ «[mi] Home» уезжал в панель как
# «i] Home», и снять такое правило было уже нельзя — ревью шага 5b, круг 1). Сам ESC и CR снимаем: в JSON-строке им не место.
# И ЛЮБОЙ ДРУГОЙ управляющий байт (кроме TAB и LF — их меняем на пробел ниже): JSON запрещает их в строке сырыми, и один
# BS или BEL из вывода чужой программы ронял разбор ВСЕГО ответа, а не одного поля. Диапазон busybox tr понимает (замер
# BE7000 23.09.2026: `\001` и ESC сняты, TAB и DEL остались).
# Выкусываем, а не экранируем (\u00XX): имя с таким байтом потом не сверить по ключу, но это редкость, а битый JSON — отказ ВСЕГО
# ответа (ревью шага 6c, круг 1).
jtxt() { tr -d '\000-\010\013-\037' | tr '\n\t' '  ' | cut -c1-"$1" | jtrim | sed 's/\\/\\\\/g; s/"/\\"/g'; }
# jesc <лимит байт> — ВЫВОД СКРИПТА со stdin → безопасное содержимое JSON-строки (без обрамляющих кавычек).
# ХВОСТОВЫЕ ПРОБЕЛЫ СНИМАЕМ — только здесь, у вывода скрипта (ревью шага 7a, круг 2; поймал стенд panel-access-test.sh): `tail -n 1 |
# jesc` превращал перевод строки в конце в пробел, а правила перевода панели якорятся на конец строки (`…выберите другой$`) —
# под английским отказ роутера оставался русским. У ДАННЫХ (jtxt: имя сети с пробелом на конце — законный ключ) хвост не трогаем.
jesc() { tr -d '\033\r' | sed 's/\[[0-9;]*m//g' | jtxt "$1" | sed 's/ *$//'; }
# jlines <лимит байт на строку> — ЖУРНАЛ со stdin → элементы JSON-массива ("…","…" без скобок), по строке на элемент, пустые
# пропускаем. Тот же конвейер, что у jesc, но переводы строк ОСТАЮТСЯ границами элементов: журнал операции панель показывает
# строками, а jesc склеил бы его в одну. Обрезка и снятие недобитой буквы идут ПО СТРОКЕ (sed и cut построчны), экранирование —
# после обрезки (разбор ловушек — в шапке файла). Процессов — семь на весь журнал: по форку на строку вышло бы полсекунды.
jlines() { tr -d '\033\r' | sed 's/\[[0-9;]*m//g' | tr '\t' ' ' | tr -d '\000-\010\013-\037' | cut -c1-"$1" | jtrim | sed 's/\\/\\\\/g; s/"/\\"/g' | awk '$0!=""{printf "%s\"%s\"", (n++ ? "," : ""), $0}'; }
