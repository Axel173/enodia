#!/bin/sh
# mount-lib.sh — ЕДИНСТВЕННЫЙ ответ на вопрос «где сейчас наше хранилище на накопителе и как
# сделать его доступным». Третий в семье: store-lib.sh отвечает «где лежит бинарь»,
# usb-offload.sh делает так, чтобы ответ был правдой, а этот — находит и монтирует сам носитель.
#
# ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Потребителей стало ДВА, и живут они в РАЗНЫХ каталогах:
#   * usb-offload.sh — движок в $ENODIA_DIR (каталог кода, обновление заменяет его целиком);
#   * boot.sh — резидентный бутстрап на /data, который в режиме `full` обязан смонтировать
#     накопитель ДО того, как узнает, где вообще лежит код.
# Вторая копия перебора кандидатов и `try_mount` на /data была бы копией, которая разъедется
# при первой же правке, — ровно тот класс багов, что стоил трёх бинарей на живом BE7000
# 01.09.2026 (два ответа на «наш ли это каталог», см. store-lib.sh::store_is_ours).
#
# ЧТО ЗДЕСЬ НЕ ЖИВЁТ: маркер `.bin-store`, закрепления и переезд файлов — это движок. Здесь
# только «найти носитель и подать его смонтированным». Поиск НЕ пишет ничего, кроме самих
# монтирований: решение «считать ли это хранилищем навсегда» принимает вызыватель.
#
# СОРСИТЬ ПОСЛЕ store-lib.sh и ТОЛЬКО так:
#   if [ -f "$D/store-lib.sh" ]; then . "$D/store-lib.sh"; fi
#   if [ -f "$D/mount-lib.sh" ]; then . "$D/mount-lib.sh"; fi
# Провалившийся `.` в busybox ash — фатальная ошибка спецбилтина: шелл выходит НА МЕСТЕ, и
# `|| true` не спасает (замерено, см. шапку store-lib.sh).

# REQUIRED: без store-lib.sh нам неизвестны ни имя подкаталога, ни сентинел, ни своя точка
# монтирования — то есть неизвестно, ЧТО искать. Молча продолжать нельзя: поиск по пустому
# имени опознал бы «наше» хранилище в корне ЛЮБОЙ воткнутой флешки.
if ! command -v store_is_ours >/dev/null 2>&1 || [ -z "$STORE_SUB" ] || [ -z "$STORE_MNT" ]; then
    echo "mount-lib.sh: нет store-lib.sh (или он старый) — обновите скрипты" >&2
    return 1 2>/dev/null || exit 1
fi

MNT="$STORE_MNT"                        # СВОЯ точка монтирования (если сток не смонтировал сам)
# /proc/mounts и /proc/partitions — ЕДИНСТВЕННЫЙ источник «что уже смонтировано и что воткнуто».
# Вынесены в переменные не ради гибкости, а ради ПРОВЕРЯЕМОСТИ: без подменяемого списка
# монтирований ни одна ветка поиска хранилища (усыновление, свой монтаж, подсчёт накопителей)
# не гоняется вовсе — а именно там жил баг, стоивший трёх бинарей на живом BE7000 01.09.2026.
MOUNTS=${ENODIA_MOUNTS:-/proc/mounts}
PARTS=${ENODIA_PARTS:-/proc/partitions}

# /proc/mounts ЭКРАНИРУЕТ пробел как `\040`. Без обратной замены точка монтирования
# `/mnt/My Flash` (стоковый automount вполне способен её завести) приезжает строкой
# `/mnt/My\040Flash`, и каждая проверка по ней ложна: `[ -d "$1/bin" ]` не находит каталога,
# хранилище на такой флешке не опознаётся ВООБЩЕ, а в режиме `full` это «код на накопителе,
# накопителя нет» — заглушка вместо панели навсегда. Пробел в пути объявлен законным
# (store-lib.sh разбирает его правильно, сторожит store-pin-test.sh) — значит, и находить его
# обязаны мы.
#
# ЯДРО ЭКРАНИРУЕТ ЧЕТЫРЕ ЗНАКА, а не один: пробел (`\040`), табуляцию (`\011`), перевод строки
# (`\012`) и сам обратный слэш (`\134`). Разворачиваем ДВА — пробел и слэш, и это не лень:
#   * перевод строки развернуть здесь НЕЛЬЗЯ в принципе — строку мы уже прочитали `read`'ом,
#     то есть увидели ПОЛОВИНУ пути и никогда не узнаем о второй;
#   * табуляция в пути к точке монтирования не рождается ни у стокового automount (он зовёт
#     их `usb-<uuid>`), ни у нас ($STORE_MNT — литерал).
# ПОРЯДОК ОБЯЗАТЕЛЕН: слэш — ПОСЛЕДНИМ. Ядро кодирует сам слэш как `\134`, поэтому до его
# разворота ни одна другая последовательность внутри него не встречается (`\134040` не содержит
# `\040`), а после — новых экранирований появиться уже не может.
# Разворачиваем ТОЛЬКО подстановками параметров: функцию зовут в цикле по КАЖДОЙ строке
# /proc/mounts, и форк здесь стоил бы дороже самой задачи. Быстрый выход по `case` — чтобы
# строка без единого слэша (это все строки, кроме экзотики) стоила ровно одного сравнения.
unesc_mount() {         # $1 = поле из /proc/mounts; ответ — в $MNT_UNESC
    MNT_UNESC="$1"
    case "$MNT_UNESC" in *'\'*) ;; *) return 0 ;; esac
    while [ "${MNT_UNESC#*'\040'}" != "$MNT_UNESC" ]; do
        MNT_UNESC="${MNT_UNESC%%'\040'*} ${MNT_UNESC#*'\040'}"
    done
    while [ "${MNT_UNESC#*'\134'}" != "$MNT_UNESC" ]; do
        MNT_UNESC="${MNT_UNESC%%'\134'*}\\${MNT_UNESC#*'\134'}"
    done
}

# ФС точки монтирования — из /proc/mounts (третье поле). `mount` без аргументов на busybox
# печатает то же самое, но /proc/mounts не зависит от наличия /etc/mtab.
fs_of_mount() {
    while read -r _d _m _t _rest; do
        unesc_mount "$_m"
        [ "$MNT_UNESC" = "$1" ] && { printf '%s' "$_t"; return 0; }
    done < "$MOUNTS"
    return 1
}

# Точка монтирования, на которой лежит хранилище: путь МИНУС ПОСЛЕДНИЙ КОМПОНЕНТ, а не минус
# литерал $STORE_SUB. Усыновлённый каталог называется ПО-ПРЕЖНЕМУ (`be7000-store`), срез по
# нынешнему имени с ним не совпадал и оставлял весь путь ⇒ «ФС: ?» в статусе и пустое поле
# `fs` в json панели (замерено на BE7000 01.09.2026). Спрашивать ФС по каталогу ВНУТРИ точки
# бесполезно: /proc/mounts знает только сами точки.
# Пустой вход ⇒ ПУСТОЙ выход (rc=1), а не «/»: спросить ФС корня вместо ФС накопителя — это
# «ФС: squashfs» в статусе, то есть враньё уверенным тоном. `/` печатаем только тогда, когда
# хранилище и правда лежит в корне точки монтирования.
store_mp() { [ -n "$1" ] || return 1; _smp=${1%/*}; printf '%s' "${_smp:-/}"; }

# Каталог-хранилище внутри точки монтирования, если он НАШ (иначе пусто).
# ЗНАЕМ И ПРЕЖНЕЕ ИМЯ КАТАЛОГА (до ребрендинга 29.08.2026) — но только чтобы ПРИЗНАТЬ уже
# лежащее хранилище своим, не перенося его. Иначе на роутере, где накопитель включили ДО
# переименования, сканирование не нашло бы каталог, завело бы рядом пустой `enodia-store`, и
# бинари протоколов стали бы сиротами: маркер уехал бы на новый путь, а `bin_path` перестал их
# находить. Перенос именно поэтому не нужен — каталог работает под своим именем, а снятие знает
# оба (uninstall.sh).
# «НАШ ЛИ КАТАЛОГ» РЕШАЕТ store_is_ours ИЗ БИБЛИОТЕКИ, а не своё условие здесь: своё разошлось
# с библиотечным на прежнем сентинеле и удалило три бинаря (см. store-lib.sh::store_is_ours).
# Здесь остаётся только перебор ИМЁН подкаталога — то, чего библиотека не знает.
store_of_mount() {
    store_is_ours "$1/$STORE_SUB" && { printf '%s' "$1/$STORE_SUB"; return 0; }
    [ -n "$STORE_SUB_OLD" ] && store_is_ours "$1/$STORE_SUB_OLD" && { printf '%s' "$1/$STORE_SUB_OLD"; return 0; }
    return 1
}

# Уже смонтированное хранилище (обошли /proc/mounts). Стоковый automount отрабатывает раньше нас
# в большинстве загрузок — тогда своей точки не заводим вовсе.
find_mounted_store() {
    while read -r _d _m _t _rest; do
        case "$_d" in /dev/sd*) ;; *) continue ;; esac
        unesc_mount "$_m"
        _s=$(store_of_mount "$MNT_UNESC")
        [ -n "$_s" ] && { printf '%s' "$_s"; return 0; }
    done < "$MOUNTS"
    return 1
}

# Разделы-кандидаты, которые ЕЩЁ НЕ смонтированы. Разделы первыми, целое устройство — следом:
# ФС прямо на устройстве (без таблицы разделов) редка, но встречается, а неудачный mount дёшев.
# ENODIA_ONLY_DEV (имя, «sdb2») — только ЭТО устройство: так зовёт хук hotplug (boot.sh::cmd_hotplug). Сток монтирует раздел на
# ЕГО событии, раньше нашего хука, и соседний раздел того же диска, чьё событие ещё впереди, мы смонтировали бы первыми — тот же
# двойной монтаж, что был на событии диска (GPT-разметка: sdb1 — служебный EFI/MSR, данные — на sdb2; ревью, круг 1).
mount_candidates() {
    while read -r _maj _min _blk _name; do
        case "$_name" in sd[a-z][0-9]*) ;; *) continue ;; esac
        [ -z "$ENODIA_ONLY_DEV" ] || [ "$_name" = "$ENODIA_ONLY_DEV" ] || continue
        [ -b "/dev/$_name" ] || continue
        grep -q "^/dev/$_name " "$MOUNTS" && continue
        printf '/dev/%s\n' "$_name"
    done < "$PARTS"
    while read -r _maj _min _blk _name; do
        case "$_name" in sd[a-z]) ;; *) continue ;; esac
        [ -z "$ENODIA_ONLY_DEV" ] || [ "$_name" = "$ENODIA_ONLY_DEV" ] || continue
        [ -b "/dev/$_name" ] || continue
        grep -q "^/dev/$_name " "$MOUNTS" && continue
        printf '/dev/%s\n' "$_name"
    done < "$PARTS"
}

# Есть ли у диска разделы — по тому же списку разделов ядра, что и у кандидатов выше. Спрашивает хук hotplug
# (boot.sh::cmd_hotplug): событие ДИСКА, у которого есть разделы, — не его, работа ждёт события раздела.
dev_has_parts() {
    while read -r _dhp_maj _dhp_min _dhp_blk _dhp_name; do
        case "$_dhp_name" in "$1"[0-9]*) return 0 ;; esac
    done < "$PARTS"
    return 1
}

# ХРАНИТ ЛИ ЭТА ФС ПРАВА ДОСТУПА — ЕДИНСТВЕННЫЙ ответ на проект. Спрашивают двое, и оба
# фронты: карточка «О роутере» в панели и экран раскладки в мастере (там от ответа зависит,
# что человеку обещают про ключи). Своей таблицы ФС во фронте быть не должно — их две,
# panel.js и wizard/index.html, и разошлись бы они на первой же правке.
#
# СПИСОК БЕЛЫЙ, А НЕ ЧЁРНЫЙ, и это не осторожность ради осторожности: цена ошибок разная.
# Лишнее «прав нет» стоит одного предупреждения, которое можно было не показывать; ложное
# «права есть» — это обещание защиты, которой на носителе не будет. Поэтому неизвестная ФС
# (и `?` от cmd_detect у несмонтированного кандидата) отвечает «не хранит».
#
# ГРАНИЦА ТА ЖЕ, ЧТО У try_mount НИЖЕ: ext* монтируются без fmask/dmask именно потому, что
# права у них свои, — два места, где проходит одна и та же линия, обязаны читать её одинаково.
# ntfs3 сюда НЕ входит намеренно: права он показывает, но по умолчанию синтетические
# (из опций монтирования), а не хранимые — обещать по ним нечего.
#
# И ЧЕГО ЭТОТ ОТВЕТ НЕ ЗНАЧИТ: он про роутер, а не про сам носитель. Права защищают файлы от
# ДРУГИХ ПРОЦЕССОВ на роутере (у нас есть чужие: проба десинка бежит из-под nobody). Того, кто
# накопитель ВЫНУЛ, не останавливает ни одна ФС — это отдельный факт, и говорить его надо
# отдельно (см. экран раскладки в мастере).
fs_keeps_perms() {
    case "$1" in
        ext2|ext3|ext4) return 0 ;;
        *) return 1 ;;
    esac
}

# Смонтировать что угодно в $2. АВТОДЕТЕКТ ФС: сперва `-t auto` (busybox перебирает
# /proc/filesystems сам), затем явный перебор — на стоке есть exfat/ext4/vfat/ntfs3.
# fmask/dmask ставят FAT-семейству права 0777 (иначе бинарь на exFAT не исполняемый), а ext4
# такие опции ОТВЕРГАЕТ ⇒ каждый тип пробуем дважды: с опциями и без.
try_mount() {
    for _t in auto exfat ext4 vfat ntfs3 ntfs ext3 ext2; do
        case "$_t" in
            ext*) _o="rw,noatime" ;;
            *)    _o="rw,noatime,fmask=0000,dmask=0000" ;;
        esac
        mount -t "$_t" -o "$_o" "$1" "$2" 2>/dev/null && return 0
        mount -t "$_t" "$1" "$2" 2>/dev/null && return 0
    done
    return 1
}

# ПРОБА чужого накопителя — ТОЛЬКО на чтение. Нас зовёт cron: поиск перебирает кандидатов
# на КАЖДОМ тике сторожа (2 минуты), пока хранилища нет — то есть ровно тогда, когда в порт
# воткнута ЧУЖАЯ флешка. Монтировать чужие данные на запись 720 раз в сутки только чтобы
# прочитать сентинел — так нельзя: у exFAT/NTFS каждый rw-цикл ставит и снимает «грязный» бит
# тома, и обрыв питания в этот момент бьёт файлы пользователя, а не наши.
# Опознали своё — размонтируем и поднимем заново на запись через try_mount (перемонтировать
# `remount,rw` мало: fmask/dmask у FAT-семейства задаются только при монтировании, а без них
# бинарь на флешке не исполняемый).
try_mount_ro() {
    for _t in auto exfat ext4 vfat ntfs3 ntfs ext3 ext2; do
        mount -t "$_t" -o ro "$1" "$2" 2>/dev/null && return 0
    done
    return 1
}

# store_locate — НАЙТИ наше хранилище и подать его смонтированным на запись.
#
# РЕЗУЛЬТАТ — В ПЕРЕМЕННЫХ, а не в stdout, и это принципиально: вызыватель, пишущий
# `_s=$(store_locate)`, получил бы путь, но ПОТЕРЯЛ бы всё остальное — подстановка команды в ash
# это подоболочка, и присвоенные внутри переменные умирают вместе с ней. Заодно экономим форк
# на каждом тике cron у тех, у кого накопителя нет.
#   STORE_FOUND      — путь к каталогу-хранилищу (пусто, если не нашли)
#   STORE_FOUND_HOW  — `system` (носитель смонтировал сток) | /dev/sdX (смонтировали мы)
#   STORE_FOUND_WARN — накопитель с хранилищем нашли, но он не поднялся на запись
# Код 0 = хранилище доступно. Ничего НЕ пишет на диск и НЕ трогает маркер: «запомнить это
# хранилище» — решение вызывателя (движок пишет .bin-store, бутстрап не пишет ничего).
store_locate() {
    STORE_FOUND=; STORE_FOUND_HOW=; STORE_FOUND_WARN=
    STORE_FOUND=$(find_mounted_store)
    if [ -n "$STORE_FOUND" ]; then
        STORE_FOUND_HOW=system
        # НА ЗАПИСЬ ЛИ ОН СМОНТИРОВАН — спрашиваем ФАКТОМ, и только в этой ветке: своё
        # монтирование мы поднимаем сами и знаем, что оно rw, а ЧУЖОЕ бывает каким угодно.
        # «Грязный» после отключения питания exFAT/NTFS сток монтирует ТОЛЬКО НА ЧТЕНИЕ — и
        # тогда система поднимается как ни в чём не бывало, но не сохраняет НИЧЕГО: панель
        # принимает настройки и молча их теряет. Путь не отвергаем (код с него читается, VPN
        # работает), но вызыватель обязан иметь возможность сказать об этом человеку.
        if ! : > "$STORE_FOUND/.enodia-write-probe" 2>/dev/null; then
            STORE_FOUND_WARN="хранилище $STORE_FOUND смонтировано ТОЛЬКО НА ЧТЕНИЕ — настройки не сохранятся"
        fi
        rm -f "$STORE_FOUND/.enodia-write-probe" 2>/dev/null
        return 0
    fi
    mkdir -p "$MNT" 2>/dev/null
    for _ml_dev in $(mount_candidates); do
        try_mount_ro "$_ml_dev" "$MNT" || continue
        _ml_s=$(store_of_mount "$MNT")
        umount "$MNT" 2>/dev/null        # проба окончена: чужое не держим, своё поднимем на запись
        [ -n "$_ml_s" ] || continue
        if ! try_mount "$_ml_dev" "$MNT"; then
            STORE_FOUND_WARN="хранилище на $_ml_dev есть, но накопитель не монтируется на запись — пропускаю"
            continue
        fi
        _ml_s=$(store_of_mount "$MNT")
        if [ -n "$_ml_s" ]; then
            STORE_FOUND="$_ml_s"; STORE_FOUND_HOW="$_ml_dev"
            unset _ml_dev _ml_s
            return 0
        fi
        umount "$MNT" 2>/dev/null        # чужой накопитель — не держим его смонтированным
    done
    unset _ml_dev _ml_s
    return 1
}
