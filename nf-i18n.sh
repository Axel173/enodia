#!/bin/sh
# nf-i18n.sh — ОБЩИЙ выбор языка для СОБЫТИЙНЫХ уведомлений роутера (письма + записи
# «центра уведомлений» веб-панели). Язык — тот же pref, что у панели («Панель → Вид»):
# лежит в $ENODIA_STATE/.prefs строкой `lang=ru|en`, дефолт ru.
#
# ЗАЧЕМ отдельным файлом (не в панели): письмо и событие формируются на РОУТЕРЕ, а
# панель их НЕ перерисовывает — письмо уходит в почту, а событие панель показывает
# как есть (freeform-текст с числами не ложится на накладной ru→en перевод панели).
# Значит язык надо выбрать в МОМЕНТ ГЕНЕРАЦИИ. Пять скриптов шлют события
# (iplist-update, heal.sh, switch-vpn, xray-transport, transport-hy2) — им нужен один
# общий reader pref, а не пять копий grep-а по .prefs.
#
# КОНТРАКТ с вызывающими: русский текст уведомлений остаётся БАЙТ-В-БАЙТ прежним
# (ветка ru у каждого caller'а), en — параллельный перевод. Точно как накладной i18n
# панели: «русский режим прежний, en — отдельная ветка, дефолт при сомнении = ru».
#
# Сорсится (`. nf-i18n.sh`), сам ничего не печатает. У caller'а — ШИМ на случай
# установки/снимка без этого файла (обновление со старой версии):
#   if [ -f "$ENODIA_DIR/nf-i18n.sh" ]; then . "$ENODIA_DIR/nf-i18n.sh"; fi
#   command -v nf_lang >/dev/null 2>&1 || nf_lang() { echo ru; }
# (без файла деградируем в ru — прежнее поведение, ничего не ломается).
# ФОРМА `if [ -f ]` ОБЯЗАТЕЛЬНА, и все пять вызывающих написаны именно так: провалившийся `.` в
# busybox ash — фатальная ошибка спецбилтина, шелл выходит НА МЕСТЕ (rc=2, `|| true` не спасает),
# то есть у прежней формы `. файл 2>/dev/null` шим ниже не выполнился бы НИКОГДА, а вызывающий
# молча умирал бы на этой строке. Здесь была записана как раз она — исправлено ревью 04.08.2026.

ENODIA_DIR="${ENODIA_DIR:-/data/usr/app/enodia}"
ENODIA_STATE=${ENODIA_STATE:-/data/usr/app/enodia-state}

# nf_lang → ru|en. Панельный pref .prefs (key=value). Незнакомое/пусто → ru (дефолт панели).
nf_lang() {
	_nl=$(grep '^lang=' "$ENODIA_STATE/.prefs" 2>/dev/null | head -1 | cut -d= -f2- | tr -cd 'a-z')
	[ "$_nl" = en ] && echo en || echo ru
}
