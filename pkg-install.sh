#!/bin/sh
# pkg-install.sh — УСТАНОВЩИК ПАКЕТА ОБНОВЛЕНИЯ: ставит набор кода из распакованного пакета (или
# снимка) на место установленного. Едет ВНУТРИ каждого пакета, и запускается КОПИЯ ИЗ ПАКЕТА.
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Апдейтер (gh-update.sh) — то, что уже стоит на роутере, и завтрашних правил он
# не знает. Раньше он сам раскладывал 94 файла по одному — значит «сегодняшний» роутер был обязан уметь
# всё, что понадобится «завтрашнему» релизу (переименования, удаления, миграции), а удаления не
# приезжали вовсе. Теперь апдейтер только ПРОВЕРЯЕТ пакет (подпись, sha256) и зовёт установщик ИЗ
# ПАКЕТА — вся политика «что и как менять» приезжает вместе с кодом, которому она нужна.
# Контракт вызова (его держит апдейтер любой версии, менять НЕЛЬЗЯ): `sh <корень>/pkg-install.sh
# install <корень>`, окружение ENODIA_DIR/STATE/BIN/BOOT экспортировано, вывод — журнал, код 0 = успех.
# Необязательное PKG_NEED_PRIOR=1 (апдейтер ставит его с 30.09.2026; прежний — нет, и тогда всё как раньше): пустой каталог кода
# у обновления — аномалия, а не свежая установка, ⇒ отказ.
# Коды НЕ-успеха различают, ЧТО ОСТАЛОСЬ на роутере (их читает установка с ПК — чем убирать за собой; апдейтеру хватает «не 0»):
#   3 — файлы новой версии уже на месте, упал install.sh (снимать каталоги нельзя: он мог завести cron; лечит повтор);
#   прочие — ничего не заменено либо прежний набор возвращён (у свежей — снято положенное).
#
# ЧТО ДЕЛАЕТ (install):
#   1. ПРОВЕРКА ДО ПЕРВОЙ ЗАМЕНЫ: манифест пакета, каждый его файл на месте, пути в белом списке,
#      синтаксис всего исполняемого (`sh -n`). Отказ здесь не трогает НИЧЕГО.
#   2. СНИМОК установленного набора (по СТАРОМУ манифесту) — сжатым tar.gz в $ENODIA_STATE/.gh-backup,
#      ДО замены: пропало питание посреди замены — снимок уже на диске, откат доступен после ребута. Прежний
#      снимок снимается только ПОСЛЕ удачной замены, что-то поменявшей: неудача и «та же версия» точку отката не трогают,
#      а если набор не меняется вовсе (сухая сверка pi_changed), снимок не снимается — флеш не пишем.
#   3. ЗАМЕНА по файлу: копия рядом (`.new`) + `mv` (атомарно для каждого файла), одинаковые не
#      пишем вовсе (/data смонтирован sync — лишняя запись = износ флеша), web/index.html — ПОСЛЕДНИМ
#      (он ссылается на panel.* по `?v=`, и новая страница без новых ассетов — битая панель).
#   4. УДАЛЕНИЕ файлов, которые были в СТАРОМ манифесте и выпали из нового. Файлов вне манифеста не
#      касаемся НИКОГДА: в каталоге кода живут и чужие (zapret.sh пишет туда свои zapret-*.bin).
#   5. Сбой посреди 3–4 ⇒ СРАЗУ возвращаем снимок: смешанного набора после нас не бывает.
#   6. Установщик НОВОЙ версии (`install.sh`, режим «только панель»): cron, бутстрап, переигрыш
#      персиста, миграции. Ему и место для завтрашнего знания.
# rollback — то же самое с источником «распакованный снимок», без нового снимка.
#
# НАС ЗОВУТ ДВОЕ: апдейтер (gh-update.sh, пакет с GitHub) и установка с ПК (enodia.py, тот же пакет из
# архива) — путь установки кода ОДИН. У ПК роутер бывает ПУСТЫМ: прежнего набора нет ⇒ снимать нечего и
# откатываться не к чему (СВЕЖАЯ установка); сбой посреди замены тогда снимает положенное — роутер
# остаётся стоковым, а не с половиной системы.
#
# ГРАБЛИ, за которые уже платили:
#   * в busybox sh НЕТ `local` ⇒ имена переменных — со своим префиксом `_pi`;
#   * `grep -f <ПУСТОЙ файл>` у busybox совпадает со ВСЕМ ⇒ пустые списки разбираем отдельно;
#   * `while read` теряет последнюю строку без `\n` ⇒ `|| [ -n "$x" ]`;
#   * лок смены транспорта — чтобы сторож не читал «health провалился» посреди замены плагинов (тот же
#     приём, что был у пофайлового apply-scripts), но heal.sh replay с чужим локом ОТКАЗЫВАЕТ ⇒ лок
#     снимаем ДО запуска install.sh;
#   * свой лок установки держим ВЕСЬ прогон, обрыв канала (PIPE/HUP) не прерывает работу, рабочий
#     каталог — `mktemp -d` (разборы — у PI_LOCKD, pi_on_signal и T).

ENODIA_DIR=${ENODIA_DIR:-/data/usr/app/enodia}
ENODIA_STATE=${ENODIA_STATE:-/data/usr/app/enodia-state}
ENODIA_BIN=${ENODIA_BIN:-/data/usr/app/enodia-bin}
ENODIA_BOOT=${ENODIA_BOOT:-/data/usr/app/enodia-boot}
export ENODIA_DIR ENODIA_STATE ENODIA_BIN ENODIA_BOOT

MAN=update-manifest.txt
# Суммы УСТАНОВЛЕННЫХ байтов (пакет минифицирован, и суммы репо к нему не подходят): в пакете — pkg-sums.txt
# (кладёт ПК-сборщик), на роутере — $ENODIA_DIR/.pkg-sums; по ним «Целостность» сверяет без сети.
SUMS=.pkg-sums
# Снимки — в НАСТРОЙКАХ, а не в каталоге кода: каталог кода и есть то, что мы заменяем. Имя с
# точкой — как у прежних снимков пофайлового апдейтера (его знают clean.sh и «Место и накопитель»).
SNAP_DIR="$ENODIA_STATE/.gh-backup"
# Снимок ОДИН: откат умеет только к последнему, а снимок — уже сжатый tar.gz, и флеш (UBIFS) его не дожмёт.
LEGACY_SNAP="$ENODIA_DIR/.gh-backup"      # снимки пофайлового апдейтера: по 3 МБ несжатыми, откат к ним не умеем
INST_LOG="$ENODIA_STATE/.gh-update-install.log"   # вывод install.sh последнего обновления/отката (разбор у pi_run_installer)
SWITCH_LOCK=/tmp/enodia-switching.lock
LOCK_WAIT=${PKG_LOCK_WAIT:-60}
MINFREE_KB=${PKG_MINFREE_KB:-1024}
# РАБОЧИЙ КАТАЛОГ — СВОЙ И НЕПРЕДСКАЗУЕМЫЙ (ревью ветки pkg-update, круг 1): `/tmp/…$$` с `mkdir -p` мог заранее создать чужой
# процесс со своими правами, и root писал бы список замен по его симлинкам. `mktemp -d` создаёт каталог сам (0700) — в cmd_install.
T=""
# ЛОК УСТАНОВКИ — на ВЕСЬ прогон, а не на окно замены (тот же круг): две установки разом (кнопка панели и мастер с ПК) рвали друг
# другу снимок отката, а смена раскладки посреди установки сносила каталог, куда та писала. Путь знают двое — мы и
# daemon-lib.sh::pkg_install_alive (его спрашивает смена раскладки).
PI_LOCKD=${ENODIA_PKG_INST_LOCK:-/tmp/enodia-pkg-install.lock}
PI_OWN=0
PHASE=""

MODE="$1"
SRC="$2"
FRESH=0
SNAP=""         # снимок ЭТОГО прогона (pi_snapshot); пусто — не снимали или снят как лишний
NOSNAP=0        # набор не меняется — снимок не снимали (pi_changed)
ROTATED=0       # прежние снимки сняты ради места под новый — он теперь единственная точка отката
case "$MODE" in rollback) TAG=rollback ;; *) TAG=apply ;; esac
log()  { printf '%s\n' "[$TAG] $*"; }
stop() { printf '%s\n' "[$TAG] СТОП: $*"; }

# Путь из манифеста можно ставить на роутер: только относительный, без «..», только код и данные
# панели. Секреты и настройки (awg.conf, configs/…) в манифест не кладут — а здесь последний заслон,
# если положат. Это прежний `manifest_safe` пофайлового апдейтера, владелец теперь один.
pi_safe() {
    case "$1" in
        ''|/*|*..*|*[!A-Za-z0-9._/-]*) return 1 ;;
        awg.conf|notify.conf|xray.json|hysteria.yaml) return 1 ;;
        configs/*|xray-configs/*|hy2-configs/*) return 1 ;;
        *.sh|*.conf.example|VERSION|update-manifest.txt|hev.yaml|web/*) return 0 ;;
        geo-*-catalog.txt|bin-manifest.txt) return 0 ;;
        *) return 1 ;;
    esac
}
# Исполняемое на роутере — то же правило, что у ПК-сборщика (dev/build-release.py::is_exec).
pi_exec() { case "$1" in *.sh|web/cgi-bin/*|web/htmlwrap) return 0 ;; *) return 1 ;; esac; }

# Очищенный список путей манифеста: без CR, пробелов по краям, комментариев и пустых строк.
pi_list() {
    [ -f "$1" ] || return 0
    tr -d '\r' < "$1" | sed 's/^[[:space:]]*//; s/[[:space:]]*$//' | grep -v '^#' | grep -v '^$' || true
}
pi_code() { sed -n 's/^CODE=//p' "$1" 2>/dev/null | head -n 1 | tr -cd '0-9'; }
pi_name() { sed -n 's/^VERSION=//p' "$1" 2>/dev/null | head -n 1 | tr -d ' \r"\\'; }
# Свободно на томе ПУТИ, КБ. Путь может ещё не существовать (свежая установка) — меряем ближайшего существующего предка: `df` по
# несуществующему отдаёт один заголовок. Поле — от КОНЦА строки: busybox переносит длинное имя устройства на отдельную строку, и
# `NR==2{print $4}` давал 0 — гард места отказывал на пустом месте (ревью ветки, круг 1; тот же разбор, что у store-lib.sh::fs_*).
pi_free_kb() {
    _pfa="$1"; while [ -n "$_pfa" ] && [ ! -e "$_pfa" ]; do _pfa="${_pfa%/*}"; done
    df -k "${_pfa:-/}" 2>/dev/null | tail -n 1 | awk 'NF>=5 && $(NF-4)+0>0{print $(NF-2)+0}'
}

LOCK_MINE=0
pi_unlock() { [ "$LOCK_MINE" = 1 ] && rm -f "$SWITCH_LOCK" 2>/dev/null; LOCK_MINE=0; return 0; }
pi_cleanup() {
    pi_unlock
    [ -n "$T" ] && rm -rf "$T" 2>/dev/null
    [ "$PI_OWN" = 1 ] && rm -rf "$PI_LOCKD" 2>/dev/null
    PI_OWN=0
    return 0
}
# СИГНАЛЫ (ревью ветки, круг 1). Установку с ПК несёт канал SSH: закрыли консоль мастера, уснул ноутбук — первая же строка журнала
# давала SIGPIPE, и установщик выходил посреди замены или ДО install.sh (файлы новые, cron и бутстрап прежние; у свежей — сотня
# файлов без cron и панели). Обрыв канала — не повод бросать работу: PIPE и HUP ГЛУШИМ (строки журнала просто не дойдут; глушение
# наследуют и tar/cp/install.sh), а явное прерывание (INT/TERM) посреди замены возвращает снимок — смешанного набора после нас нет.
pi_on_signal() {
    if [ "$PHASE" = swap ]; then stop "прервано посреди замены — возвращаю прежний набор"; pi_restore; fi
    pi_cleanup
    exit 1
}
trap 'pi_cleanup' EXIT
trap '' PIPE HUP
trap 'pi_on_signal' INT TERM

# Кто ещё жив — у владельцев ответа (daemon-lib.sh рядом с нами: в пакете при установке, в каталоге кода при откате). Шимы — те же
# строки владельца: старый набор без них не должен лишать нас гарда.
PI_HERE=${0%/*}; [ "$PI_HERE" = "$0" ] && PI_HERE=.
if [ -f "$PI_HERE/daemon-lib.sh" ]; then . "$PI_HERE/daemon-lib.sh"; fi
command -v pid_runs >/dev/null 2>&1 || pid_runs() { [ -n "$1" ] && [ -r "/proc/$1/cmdline" ] && tr '\000' ' ' 2>/dev/null < "/proc/$1/cmdline" | grep -qE "$2"; }
command -v store_mode_alive >/dev/null 2>&1 || store_mode_alive() {
    _sma=$(cat /tmp/enodia-store-mode.pid 2>/dev/null | tr -cd '0-9'); pid_runs "$_sma" 'usb-offload\.sh.* mode'; }
command -v uninstall_alive >/dev/null 2>&1 || uninstall_alive() {
    _ual=$(cat /tmp/enodia-uninstall.pid 2>/dev/null | tr -cd '0-9'); pid_runs "$_ual" 'uninstall\.sh (deactivate|purge)'; }

# Лок установки + «не идёт ли смена раскладки / снятие системы». Свой лок ставим ДО вопросов, а переезд и снятие пишут свой
# пидфайл ДО вопроса о нас (usb-offload.sh::move_hold, uninstall.sh::un_gate) — из двух стартовавших разом хотя бы один видит
# другого. Мёртвый держатель лок не держит.
# ПЕРЕХВАТ ПРОТУХШЕГО ЛОКА — С ПРОВЕРКОЙ (ревью ветки, круг 2): два запуска над одним трупом оба читали мёртвый pid, и второй `rm -rf`
# сносил уже СВЕЖИЙ лок первого — держали вдвоём. Перехватившие пишут свой pid и через секунду смотрят, чей он: остаётся один.
# PI_OWN — только после этого: уборка на выходе не должна снести лок, который держит другой.
pi_gate() {
    _pgt=0
    if ! mkdir "$PI_LOCKD" 2>/dev/null; then
        _pgp=$(cat "$PI_LOCKD/pid" 2>/dev/null | tr -cd '0-9')
        [ -n "$_pgp" ] || { sleep 1; _pgp=$(cat "$PI_LOCKD/pid" 2>/dev/null | tr -cd '0-9'); }   # держатель только что взял лок
        if pid_runs "$_pgp" 'pkg-install\.sh'; then
            stop "другая установка кода уже идёт (pid $_pgp) — ничего не заменено; дождитесь её конца и повторите"; return 1
        fi
        rm -rf "$PI_LOCKD" 2>/dev/null
        mkdir "$PI_LOCKD" 2>/dev/null || { stop "не взять лок установки ($PI_LOCKD) — ничего не заменено"; return 1; }
        _pgt=1
    fi
    echo $$ > "$PI_LOCKD/pid"
    if [ "$_pgt" = 1 ]; then
        sleep 1
        if [ "$(cat "$PI_LOCKD/pid" 2>/dev/null | tr -cd '0-9')" != "$$" ]; then
            stop "другая установка кода перехватила лок одновременно с нами — ничего не заменено; дождитесь её конца и повторите"; return 1
        fi
    fi
    PI_OWN=1
    if store_mode_alive; then
        stop "идёт смена раскладки (перенос на накопитель или обратно) — ничего не заменено; дождитесь её конца и повторите"; return 1
    fi
    if uninstall_alive; then
        stop "идёт снятие системы (отключение или полное удаление) — ничего не заменено"; return 1
    fi
    # …и ОПЕРАЦИЯ С КОМПОНЕНТАМИ (установка, снятие, перезапуск): замена packages.sh, gh-update.sh и манифеста бинарей под живым движком
    # (его закачки сверяли бы другой манифест) и два пика на 20-МБ /data разом (ревью ветки bins-2026-10, круг 3). Ответ — у движка
    # (`packages.sh busy`, установленная копия); спрашиваем ПОСЛЕ своего лока — движок спрашивает нас после своего.
    if [ -f "$ENODIA_DIR/packages.sh" ] && sh "$ENODIA_DIR/packages.sh" busy >/dev/null 2>&1; then
        stop "идёт операция с компонентами (установка, снятие или перезапуск) — ничего не заменено; дождитесь её конца и повторите"; return 1
    fi
    return 0
}

# Лок смены транспорта: занят — ждём (смена идёт секунды); не освободился — идём дальше, как ходил
# и пофайловый апдейтер: записи о держателе у лока нет, и мёртвый держатель запер бы обновление до
# ребута. Чужой лок НЕ снимаем.
pi_lock() {
    _pw=0
    while [ -e "$SWITCH_LOCK" ] && [ "$_pw" -lt "$LOCK_WAIT" ]; do sleep 2; _pw=$((_pw + 2)); done
    if [ -e "$SWITCH_LOCK" ]; then
        log "ВНИМАНИЕ: лок смены транспорта занят дольше ${LOCK_WAIT} с — продолжаю без него"
        return 0
    fi
    # Свой ПИД в локе и метка держателя потомкам (daemon-lib.sh::switch_work_alive): пустой лок панель (cgi hold_switch) не ждёт —
    # «держатель без пида, дальше как раньше», — и смена сервера посреди замены шла поверх СМЕШАННОГО набора (новый ipt-lib.sh при
    # прежнем awg_setup.sh: перезагрузку фаервола такой awg_setup поколением не отмечает, правила не переигрываются до тика сторожа;
    # хвост ревью с.96). С пидом панель ждёт конца замены, а лок установщика, убитого посреди неё, сторож снимает по мёртвому пиду
    # сразу, а не через SWITCH_STALE.
    ( set -C; echo $$ > "$SWITCH_LOCK" ) 2>/dev/null && { LOCK_MINE=1; ENODIA_SWITCH_HOLDER=$$; export ENODIA_SWITCH_HOLDER; }
    return 0
}

# --- 1. проверка источника до первой замены --------------------------------------------------------
pi_check_src() {
    [ -n "$SRC" ] && [ -d "$SRC" ] || { stop "нет каталога источника «$SRC»"; return 1; }
    [ -f "$SRC/$MAN" ] || { stop "в источнике нет $MAN"; return 1; }
    [ -f "$SRC/VERSION" ] || { stop "в источнике нет VERSION"; return 1; }
    [ -n "$(pi_code "$SRC/VERSION")" ] || { stop "в VERSION источника нет кода"; return 1; }
    pi_list "$SRC/$MAN" > "$T/man"
    [ -s "$T/man" ] || { stop "манифест источника пуст"; return 1; }
    : > "$T/new"
    while IFS= read -r _r || [ -n "$_r" ]; do
        pi_safe "$_r" || { stop "путь вне белого списка в манифесте: $_r"; return 1; }
        if [ ! -f "$SRC/$_r" ]; then
            # Пакет обязан нести ВЕСЬ свой манифест (его собирал ПК). Снимок — нет: он хранит то, что
            # в тот момент лежало на диске, и пропажа файла тогда — не повод запирать откат.
            [ "$MODE" = rollback ] || { stop "в пакете нет файла из его же манифеста: $_r"; return 1; }
            log "в снимке нет $_r — оставляю текущий"
            continue
        fi
        if pi_exec "$_r"; then
            sh -n "$SRC/$_r" 2>/dev/null || { stop "синтаксическая ошибка в $_r — ничего не заменено"; return 1; }
        fi
        printf '%s\n' "$_r" >> "$T/new"
    done < "$T/man"
    [ -s "$T/new" ] || { stop "в источнике нет ни одного файла набора"; return 1; }
    return 0
}

# --- 2. снимок установленного набора ---------------------------------------------------------------
# Что стоит сейчас: $T/old — СТАРЫЙ манифест (его нет — пути нового), $T/have — те его файлы, что есть на диске.
pi_have() {
    pi_list "$ENODIA_DIR/$MAN" > "$T/old"
    [ -s "$T/old" ] || cp "$T/new" "$T/old"
    : > "$T/have"
    while IFS= read -r _r || [ -n "$_r" ]; do
        pi_safe "$_r" || continue
        [ -f "$ENODIA_DIR/$_r" ] && printf '%s\n' "$_r" >> "$T/have"
    done < "$T/old"
    return 0
}
# Кладёт путь снимка в SNAP.
pi_snapshot() {    # $1 = куда (файл) · $2 = quiet (провал без строки СТОП — вызывающий попробует ещё раз)
    pi_have
    [ -s "$T/have" ] || { stop "на роутере не нашлось ни одного файла установленного набора — снимать нечего"; return 1; }
    # Суммы установленного пакета едут в снимке: откат обязан вернуть и их, иначе «Целостность» сверяла бы
    # возвращённый набор с суммами того, от которого откатились.
    [ -f "$ENODIA_DIR/$SUMS" ] && printf '%s\n' "$SUMS" >> "$T/have"
    mkdir -p "$(dirname "$1")" 2>/dev/null
    if ! tar -czf "$1.part" -C "$ENODIA_DIR" -T "$T/have" 2>/dev/null || [ ! -s "$1.part" ]; then
        rm -f "$1.part"
        [ "$2" = quiet ] || stop "не удалось снять снимок установленного набора (нет места на $(dirname "$1")?) — ничего не заменено"
        return 1
    fi
    mv -f "$1.part" "$1" || { rm -f "$1.part"; stop "снимок не лёг на место — ничего не заменено"; return 1; }
    SNAP="$1"
    return 0
}

# Снять все снимки, кроме $1 (пусто — все). Не «N самых свежих по имени»: имя — время снятия, а часы на этих
# роутерах прыгают (RTC нет, на буте они стоят на mtime файла) — только что снятый снимок мог бы получить имя
# «старше» прежнего и уйти под ротацию вместо него.
pi_rotate() {
    [ -d "$SNAP_DIR" ] || return 0
    # Недописанный снимок (питание пропало или `kill -9` посреди tar) — ~1 МБ на флеше навсегда: регулярка ниже его не видит, а
    # clean.sh в каталог снимков не заглядывает (ревью ветки, круг 2). Лок установки держим мы — чужого `.part` здесь быть не может.
    rm -f "$SNAP_DIR"/*.tar.gz.part 2>/dev/null
    ls -1 "$SNAP_DIR" 2>/dev/null | grep '^[0-9]\{8\}-[0-9]\{6\}\.tar\.gz$' > "$T/snaps" || true
    while IFS= read -r _s || [ -n "$_s" ]; do
        [ -n "$_s" ] || continue
        [ "$SNAP_DIR/$_s" = "$1" ] && continue
        rm -f "$SNAP_DIR/$_s" && log "снят прежний снимок: ${_s%.tar.gz}"
    done < "$T/snaps"
    return 0
}

# Изменит ли установка ХОТЬ ЧТО-ТО? Та же сверка, что у замены (cmp по файлу) и у удалений (старый манифест против нового), —
# без записи. Не изменит (переустановка той же версии) — снимок не нужен вовсе: прежде его снимали и тут же стирали (~1 МБ записи на
# флеш, смонтированный `sync`), а при нехватке места ротация успевала унести прежнюю точку отката (ревью ветки, круг 2).
pi_changed() {
    while IFS= read -r _r || [ -n "$_r" ]; do
        { [ -f "$ENODIA_DIR/$_r" ] && cmp -s "$SRC/$_r" "$ENODIA_DIR/$_r" 2>/dev/null; } || return 0
    done < "$T/new"
    [ -s "$T/old" ] || return 1
    grep -vxF -f "$T/man" "$T/old" > "$T/gone0" || true
    while IFS= read -r _r || [ -n "$_r" ]; do
        [ -n "$_r" ] || continue
        pi_safe "$_r" || continue
        [ -f "$ENODIA_DIR/$_r" ] && return 0
    done < "$T/gone0"
    return 1
}

# --- 5. возврат снимка при сбое посреди замены -------------------------------------------------------
# Файлы, которых ДО нас не было, — убрать: снимок их не содержит и сам не снимет.
pi_drop_absent() {
    [ -s "$T/absent" ] || return 0
    while IFS= read -r _r || [ -n "$_r" ]; do
        pi_safe "$_r" && rm -f "$ENODIA_DIR/$_r"
    done < "$T/absent"
    return 0
}
pi_restore() {
    # Свежая установка: возвращать нечего — снимаем положенное, и роутер остаётся таким, каким был до нас.
    [ "$FRESH" = 1 ] && { pi_drop_absent; log "свежая установка не легла — положенное снято, роутер как до установки"; log "итог: заменено 0, удалено 0"; return 0; }
    log "возвращаю снимок ${SNAP##*/} — набор не должен остаться смешанным"
    # НОВЫЕ ФАЙЛЫ — СНАЧАЛА (ревью ветки, круг 1): типичная причина сбоя замены — кончилось место, а распаковка снимка переписывает
    # набор целиком, пока новые ещё его занимают, — tar падал, и оставался ровно смешанный набор.
    pi_drop_absent
    if tar -xzf "$SNAP" -C "$ENODIA_DIR" 2>/dev/null; then
        while IFS= read -r _r || [ -n "$_r" ]; do
            pi_exec "$_r" && chmod 755 "$ENODIA_DIR/$_r" 2>/dev/null
        done < "$T/have"
        log "снимок возвращён — работает прежняя версия"
        log "итог: заменено 0, удалено 0"
        return 0
    fi
    stop "снимок вернуть НЕ удалось — набор файлов смешанный; повторите обновление или переустановите с компьютера"
    return 1
}

# --- 3–4. замена и удаление ---------------------------------------------------------------------------
pi_swap() {
    NREP=0; NDEL=0
    : > "$T/absent"
    # Порядок: всё, кроме страницы, потом страница.
    grep -vxF 'web/index.html' "$T/new" > "$T/order" || true
    if grep -qxF 'web/index.html' "$T/new"; then printf '%s\n' 'web/index.html' >> "$T/order"; fi
    while IFS= read -r _r || [ -n "$_r" ]; do
        # Путь проверен при чтении манифеста, но между проверкой и записью список лежал файлом — перепроверка стоит ноль.
        pi_safe "$_r" || { stop "путь вне белого списка в списке замен: $_r"; return 1; }
        _s="$SRC/$_r"; _d="$ENODIA_DIR/$_r"
        _m=644; pi_exec "$_r" && _m=755
        if [ -f "$_d" ] && cmp -s "$_s" "$_d" 2>/dev/null; then
            chmod "$_m" "$_d" 2>/dev/null
            continue
        fi
        [ -f "$_d" ] || printf '%s\n' "$_r" >> "$T/absent"
        mkdir -p "$(dirname "$_d")" 2>/dev/null
        if cp "$_s" "$_d.new" 2>/dev/null && chmod "$_m" "$_d.new" 2>/dev/null && mv -f "$_d.new" "$_d" 2>/dev/null; then
            NREP=$((NREP + 1))
        else
            rm -f "$_d.new" 2>/dev/null
            stop "не записался $_r (нет места? накопитель пропал?)"
            return 1
        fi
    done < "$T/order"
    # Удаления: было в старом манифесте, нет в новом. Сверяем с манифестом ЦЕЛИКОМ, а не с тем, что
    # нашлось в источнике: файл, которого нет в снимке, остаётся прежним, а не исчезает. Манифест не пуст
    # (проверено выше) — `grep -f` с пустым файлом совпал бы со всем.
    if [ -s "$T/old" ]; then
        grep -vxF -f "$T/man" "$T/old" > "$T/gone" || true
        while IFS= read -r _r || [ -n "$_r" ]; do
            [ -n "$_r" ] || continue
            pi_safe "$_r" || continue
            [ -f "$ENODIA_DIR/$_r" ] || continue
            if rm -f "$ENODIA_DIR/$_r" 2>/dev/null; then NDEL=$((NDEL + 1)); log "снят файл прежней версии: $_r"
            else stop "не удалось снять $_r"; return 1; fi
        done < "$T/gone"
    fi
    return 0
}

pi_space_ok() {
    _pf=$(pi_free_kb "$ENODIA_DIR"); case "$_pf" in ''|*[!0-9]*) return 0 ;; esac
    # Самый крупный файл набора ложится рядом копией, прежде чем заменить старый.
    _pb=0
    while IFS= read -r _r || [ -n "$_r" ]; do
        _sz=$(wc -c < "$SRC/$_r" 2>/dev/null | tr -d ' '); case "$_sz" in ''|*[!0-9]*) _sz=0 ;; esac
        [ "$_sz" -gt "$_pb" ] && _pb=$_sz
    done < "$T/new"
    _pneed=$((_pb / 1024 + MINFREE_KB))
    if [ "$_pf" -lt "$_pneed" ]; then
        stop "на томе кода свободно ${_pf} КБ, нужно ≥ ${_pneed} — освободите место («Роутер» → «Место и накопитель») и повторите"
        return 1
    fi
    return 0
}

# --- 6. установщик новой версии ------------------------------------------------------------------------
pi_run_installer() {
    [ -f "$ENODIA_DIR/install.sh" ] || { log "ВНИМАНИЕ: в наборе нет install.sh — cron и бутстрап не пересобраны"; return 1; }
    log "запускаю установщик версии $(pi_name "$ENODIA_DIR/VERSION") (режим «только панель»: транспорт и его правила не трогает)…"
    ( cd "$ENODIA_DIR" && INSTALL_PROTO=none INSTALL_FROM_PKG=1 sh ./install.sh ) > "$T/inst" 2>&1
    _pir=$?
    # Вывод установщика — СВОИМ файлом, а не в журнал обновления: его ~40 строк вытеснили бы из журнала экрана (последние 60
    # строк) то, что человеку важно, — подпись, замены, итог. В журнал — одна строка, а при сбое — хвост с причиной. Цвета
    # старого установщика (он не знает INSTALL_FROM_PKG) — мусор, снимаем.
    tr -d '\033' < "$T/inst" | sed 's/\[[0-9;]*m//g' > "$INST_LOG" 2>/dev/null
    # Установка с ПК (PKG_INSTALL_VERBOSE) показывает его ЦЕЛИКОМ: там это не журнал экрана, а консоль человека, и его
    # строки (нет интернета, прежняя версия рядом) — ответ, а не шум.
    if [ -n "$PKG_INSTALL_VERBOSE" ]; then sed 's/^/  | /' "$INST_LOG" 2>/dev/null; fi
    if [ "$_pir" = 0 ]; then
        log "установщик отработал (его журнал: $INST_LOG)"
    elif [ -n "$PKG_INSTALL_VERBOSE" ]; then
        log "установщик кончился ошибкой (его журнал: $INST_LOG)"
    else
        log "последние строки установщика ($INST_LOG):"
        tail -n 8 "$INST_LOG" 2>/dev/null | sed 's/^/  | /'
    fi
    return "$_pir"
}

cmd_install() {
    T=$(mktemp -d /tmp/enodia-pkg-inst.XXXXXX 2>/dev/null) || T=""
    [ -n "$T" ] && [ -d "$T" ] || { T=""; stop "не создать рабочий каталог в /tmp"; return 1; }
    pi_gate || return 1
    pi_check_src || return 1
    _nn=$(pi_name "$SRC/VERSION"); _nc=$(pi_code "$SRC/VERSION")
    _on=$(pi_name "$ENODIA_DIR/VERSION"); _oc=$(pi_code "$ENODIA_DIR/VERSION")
    if [ -n "$_oc" ]; then
        log "ставлю ${_nn:-?} (код ${_nc:-?}) поверх ${_on:-?} (код ${_oc:-?})"
    else
        log "ставлю ${_nn:-?} (код ${_nc:-?}) — прежней версии на роутере нет"
    fi
    pi_space_ok || return 1
    if [ "$MODE" = rollback ]; then
        # Снимок текущего — только для самовозврата, в ОЗУ: сохранять его незачем, а ротация унесла
        # бы тот самый снимок, к которому откатываемся.
        pi_snapshot "$T/cur.tar.gz" || return 1
    else
        # Снимки пофайлового апдейтера — несжатые копии по ~3 МБ в каталоге кода, откатывать к ним
        # новый путь не умеет. Убираем ДО снимка: на 20-МБ флеше это и есть место под него.
        if [ -d "$LEGACY_SNAP" ]; then rm -rf "$LEGACY_SNAP" && log "сняты снимки прежнего апдейтера ($LEGACY_SNAP)"; fi
        pi_have
        if [ ! -s "$T/have" ]; then
            # ОБНОВЛЕНИЕ, НЕ НАШЕДШЕЕ НАБОРА, — АНОМАЛИЯ, а не свежая установка (ревью ветки, круг 1): каталог кода мог уехать
            # на накопитель, пока апдейтер качал пакет, — и мы поставили бы вторую, пустую систему на флеш. Свежую установку
            # делает только ПК; апдейтер (и откат) зовёт нас с PKG_NEED_PRIOR=1.
            if [ "$PKG_NEED_PRIOR" = 1 ]; then
                stop "в $ENODIA_DIR нет установленного набора — обновление не ставит систему с нуля; ничего не заменено"
                return 1
            fi
            # СВЕЖАЯ — ТОЛЬКО ЕСЛИ СИСТЕМА НЕ ЖИВЁТ В ДРУГОМ МЕСТЕ (ревью ветки, круг 2). Каталоги ПК называет ДО заливки, и смена
            # раскладки в это окно (панель во второй вкладке) оставляла прежний каталог кода пустым: мы ставили вторую, пустую систему,
            # install.sh переводил на неё cron и бутстрап, а настройки на накопителе сиротели. Где система — знает бутстрап.
            if [ -f "$ENODIA_BOOT/boot.sh" ]; then
                _pbd=$(sh "$ENODIA_BOOT/boot.sh" paths 2>/dev/null | sed -n 's/^dir=//p' | head -n 1)
                if [ -n "$_pbd" ] && [ "$_pbd" != "$ENODIA_DIR" ]; then
                    stop "система живёт в $_pbd, а ставят в $ENODIA_DIR — ничего не заменено; проверьте снова и повторите"
                    return 1
                fi
            fi
            # Прежние снимки (от удалённой системы) не трогаем: не наш набор — не наше решение.
            FRESH=1
            log "свежая установка: прежнего набора нет — снимать нечего, отката у неё не будет"
        elif ! pi_changed; then
            NOSNAP=1
            log "набор не изменился — снимок не нужен, точка отката прежняя"
        else
            # ВЕРСИИ СТОЯЩИХ БИНАРЕЙ — ПОКА МАНИФЕСТ ПРЕЖНИЙ (ревью ветки релиза, круг 2): новый пакет может везти новые сборки,
            # и после замены стоящая законно не совпадёт с его манифестом. «Прежнюю подписанную сборку» от «правили/побился»
            # отличает только память «этот хеш совпадал с манифестом» (кэш .bin-sha, gh-update.sh::verify_scan) — пишет её
            # bin-status ПРЕЖНЕГО кода, его и спрашиваем. Только чтение файлов и кэш, без сети; сбой — не повод не обновляться.
            if [ -f "$ENODIA_DIR/gh-update.sh" ]; then sh "$ENODIA_DIR/gh-update.sh" bin-status >/dev/null 2>&1 || true; fi
            mkdir -p "$SNAP_DIR" 2>/dev/null; chmod 700 "$SNAP_DIR" 2>/dev/null
            _pff=$(pi_free_kb "$SNAP_DIR"); case "$_pff" in ''|*[!0-9]*) _pff="" ;; esac
            if [ -n "$_pff" ] && [ "$_pff" -lt "$MINFREE_KB" ]; then
                stop "на томе настроек свободно ${_pff} КБ — снимок для отката не ляжет; освободите место и повторите"
                return 1
            fi
            # СНАЧАЛА новый снимок, прежние — ПОСЛЕ удачной замены (ревью ветки, круг 1): ротация ДО замены уничтожала
            # единственную точку отката у каждой установки, которая упала и вернулась сама или не поменяла ничего (та же
            # версия с ПК), — «Откатить» затем откатывал к тому, что уже стоит. Места на два впритык (20-МБ флеш) —
            # снимаем прежние сразу и пробуем ещё раз: снимок ТЕКУЩЕГО нужнее вчерашнего.
            _psn="$SNAP_DIR/$(date +%Y%m%d-%H%M%S).tar.gz"
            # Имя — время снятия с точностью до секунды: вторая установка в ту же секунду (или часы без RTC, шагнувшие назад)
            # переписала бы ПРЕЖНИЙ снимок своим, и её неудача затем сняла бы его вместе с точкой отката (поймано стендом).
            _pst=0
            while [ -e "$_psn" ]; do
                [ "$_pst" -ge 5 ] && { stop "не выбрать имя снимка (часы стоят?) — ничего не заменено"; return 1; }
                sleep 1; _pst=$((_pst + 1)); _psn="$SNAP_DIR/$(date +%Y%m%d-%H%M%S).tar.gz"
            done
            if ! pi_snapshot "$_psn" quiet; then
                pi_rotate ""
                ROTATED=1
                if ! pi_snapshot "$_psn"; then
                    log "ВНИМАНИЕ: прежние снимки сняты ради места, а новый не лёг — «Откатить» сейчас нечем; освободите место"
                    return 1
                fi
            fi
            log "снимок для отката: ${SNAP##*/}"
        fi
    fi
    pi_lock
    # Без снимка (набор не менялся) возвращать нечем — и незачем: замена свелась бы к правам. Сбой в такой замене — гонка с чужой
    # записью, и честнее сказать о ней, чем «вернуть» несуществующий снимок.
    [ "$NOSNAP" = 1 ] || PHASE=swap
    if ! pi_swap; then
        [ "$NOSNAP" = 1 ] || pi_restore
        PHASE=""
        pi_unlock
        # Возвращён прежний набор — новый снимок равен ему; точка отката остаётся прежней. Кроме случая, когда прежние снимки
        # сняты ради места: тогда новый — единственная точка отката (он и есть возвращённый набор).
        if [ "$MODE" != rollback ] && [ "$FRESH" = 0 ] && [ "$NOSNAP" = 0 ]; then
            if [ "$ROTATED" = 1 ]; then log "прежние снимки сняты ради места — точка отката: этот набор (${SNAP##*/})"
            else rm -f "$_psn" 2>/dev/null; fi
        fi
        return 1
    fi
    pi_unlock
    if [ "$MODE" != rollback ] && [ "$FRESH" = 0 ] && [ "$NOSNAP" = 0 ]; then
        if [ "$NREP" = 0 ] && [ "$NDEL" = 0 ] && [ "$ROTATED" = 0 ]; then
            # Сухая сверка сказала «изменится», а замена не тронула ничего — кто-то успел положить те же файлы: снимок лишний.
            rm -f "$_psn" 2>/dev/null; SNAP=""
            PHASE=""        # возвращать нечего — и нечем: снимок снят
            log "набор не изменился — точка отката прежняя"
        else
            pi_rotate "$_psn"
        fi
    fi
    # Суммы нового набора — из пакета (pkg-sums.txt) или из снимка (.pkg-sums); источник без них (установка с ПК в
    # снимке) — прежние снимаем: сверять новый набор со старыми суммами = «всё расходится» на ровном месте.
    if [ -f "$SRC/pkg-sums.txt" ]; then _ps="$SRC/pkg-sums.txt"; elif [ -f "$SRC/$SUMS" ]; then _ps="$SRC/$SUMS"; else _ps=""; fi
    if [ -n "$_ps" ]; then
        cp "$_ps" "$ENODIA_DIR/$SUMS.new" 2>/dev/null && mv -f "$ENODIA_DIR/$SUMS.new" "$ENODIA_DIR/$SUMS" 2>/dev/null \
            || { rm -f "$ENODIA_DIR/$SUMS.new"; log "ВНИМАНИЕ: суммы пакета не легли — «Целостность» будет сверять с GitHub"; }
    else
        rm -f "$ENODIA_DIR/$SUMS"
    fi
    if [ "$MODE" = rollback ]; then
        log "возвращено файлов: $NREP; снято: $NDEL (версия ${_nn:-?}, код ${_nc:-?})"
    fi
    log "итог: заменено $NREP, удалено $NDEL"
    PHASE=""
    if ! pi_run_installer; then
        if [ "$FRESH" = 1 ]; then
            stop "установщик версии ${_nn:-?} кончился ошибкой — файлы уже на месте; повторите установку"
        else
            stop "установщик версии ${_nn:-?} кончился ошибкой — файлы уже этой версии; повторите или откатитесь к снимку"
        fi
        return 3        # файлы новой версии уже на месте (контракт кодов — в шапке)
    fi
    if [ "$MODE" = rollback ]; then
        log "готово: работает ${_nn:-?} (код ${_nc:-?}). Правила примените: «Починить правила» или перезагрузка"
    elif [ "$FRESH" = 1 ]; then
        log "готово: ${_nn:-?} (код ${_nc:-?}) поставлен с нуля, файлов $NREP"
    elif [ -z "$SNAP" ]; then
        log "готово: ${_nn:-?} (код ${_nc:-?}): набор не изменился, точка отката прежняя"
    else
        log "готово: ${_nn:-?} (код ${_nc:-?}), заменено $NREP, удалено $NDEL, снимок ${SNAP##*/}. Правила примените: «Починить правила» или перезагрузка"
    fi
    return 0
}

case "$MODE" in
    install|rollback) cmd_install ;;
    *) echo "usage: $0 install <распакованный пакет> | rollback <распакованный снимок>" >&2; exit 2 ;;
esac
