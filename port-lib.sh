#!/bin/sh
# port-lib.sh — ЕДИНСТВЕННЫЙ разбор хранилища правил по портам (`.port-rules`, строка
# «src⇥proto⇥порты⇥куда»): какая строка ДЕЙСТВУЕТ и в каком ПОРЯДКЕ её проверяет ядро.
# Сорсится (`. port-lib.sh`), сам ничего не печатает и не меняет.
#
# ЗАЧЕМ ОТДЕЛЬНО. У хранилища три читателя: apply-bypass.sh::rebuild_ports ставит по нему цепочку
# VPN_PORTS, devwatch.sh::load_port_rules отвечает «что победит» и строки «Что запрашивает
# устройство», cgi-bin/data отдаёт строки панели. Пока фильтр и порядок жили копиями, они разошлись
# (ревью пачки 3, круг 1): цепочка отбрасывала строку «443,99999» (порт вне 1..65535), а индикатор
# проверял только набор символов и отвечал «в VPN» — панель рисовала правило с чипом пути, а в ядре
# его не было. Панель такую строку не заведёт (движок port-add её отвергнет), но её привозят импорт
# бэкапа и ручная правка файла.
#
# ПОРЯДОК. Выигрывает ПЕРВОЕ совпавшее правило цепочки, а цепочка встаёт в порядке, который отдаёт
# port_rules_in_order: сперва правила устройств, потом правила всего роутера (`any`), а ВНУТРИ каждого
# прохода — узкое раньше широкого (меньше портов покрывает — раньше; поровну — порядок файла). Частное
# сильнее общего — на обеих осях. Между источниками: общее «udp/443 — блок», заведённое раньше, иначе
# глушило бы правило телевизора на тот же порт. Внутри источника (ревью пачки 3, круг 2): заготовки
# панели «весь UDP → в VPN», а потом «погасить QUIC» (udp/443 → блок) по порядку файла давали МЁРТВЫЙ
# блок при зелёной строке — ключи у них разные (`all` и `443`), и вторая строку первой не заменяет.
# А ВСЯ цепочка стоит выше остальной лестницы (ensure_prerouting_order): правило всего роутера на порт
# сильнее режима устройства и его сайтов — это знают лестница и экран устройства в панели.
#
# ФОРМА СПИСКА ПОРТОВ одна у всех читателей — нормализованная (`port_list_norm`: без пробелов и ведущих
# нулей). Ручная правка «443, 80» или «0443» иначе делилась: iptables понимал 0443 как 443, а индикатор
# сравнивал строки и правила не видел; строку с пробелом CGI данных отсеивал вовсе (действует — и не видно).
#
# Имена переменных — СВОИ (`_pl*`): в busybox sh нет `local`, а зовут нас из циклов вызывающих.

# Поля строки. Валидация здесь, а не только в CGI: скрипт обязан быть безопасен и из CLI — в iptables
# уходит подстановка, мусор туда пускать нельзя.
# Источник: `any` или адрес — четыре числа 0..255 БЕЗ ведущих нулей (ревью пачки 3, круг 3: «300.1.1.1» проходил форму, получал
# `ok:true` и чип пути, а iptables такое правило не ставил; «192.168.031.5» ядро читает иначе, чем панель).
port_src_ok() {
	[ "$1" = any ] && return 0
	echo "$1" | grep -Eq '^(0|[1-9][0-9]{0,2})(\.(0|[1-9][0-9]{0,2})){3}$' || return 1
	_pli=$IFS; IFS=.; set -- $1; IFS=$_pli
	[ "$1" -le 255 ] && [ "$2" -le 255 ] && [ "$3" -le 255 ] && [ "$4" -le 255 ]
}
port_proto_ok() { case "$1" in udp|tcp|both) return 0 ;; *) return 1 ;; esac; }
port_dir_ok()   { case "$1" in vpn|direct|block|s2|s3|s4) return 0 ;; *) return 1 ;; esac; }
# Список портов: `all` или через запятую `N` / `N-M` (1..65535) — В НОРМАЛИЗОВАННОЙ форме (пробелов и ведущих
# нулей нет: сперва `port_list_norm`, это делают все вызывающие). Форма — строкой целиком: пустой элемент
# («443,,80») прежде проходил — разбор по пробелам его просто терял.
port_list_ok() {
	[ "$1" = all ] && return 0
	echo "$1" | grep -Eq '^[0-9]{1,5}(-[0-9]{1,5})?(,[0-9]{1,5}(-[0-9]{1,5})?)*$' || return 1
	for _plq in $(echo "$1" | tr ',' ' '); do
		# Диапазон проверяем ЧИСЛАМИ, а не только формой: 70000 или «500-100» iptables отвергнет,
		# правило молча не встанет — и в панели останется строка без эффекта. Ведущий нуль — не наша
		# форма (у арифметики шелла это ещё и восьмеричное число).
		_pla=${_plq%-*}; _plb=${_plq#*-}
		case "$_pla,$_plb" in 0*|*,0*) return 1 ;; esac
		[ "$_pla" -ge 1 ] && [ "$_pla" -le 65535 ] || return 1
		[ "$_plb" -ge 1 ] && [ "$_plb" -le 65535 ] || return 1
		[ "$_pla" -le "$_plb" ] || return 1
	done
	return 0
}
# Нормализация: убрать пробелы и ведущие нули («443, 80» → «443,80», «0443» → «443»). Форма одна у цепочки,
# индикатора, CGI и ключа удаления (apply-bypass.sh::ports_store_del сверяет нормализованным).
port_list_norm() { echo "$1" | tr -d ' \t\r' | sed -r 's/(^|[,-])0+([0-9])/\1\2/g'; }
# port_width <нормализованный список> — сколько портов покрывает (all = 65535): мерило «узкое раньше широкого».
port_width() {
	[ "$1" = all ] && { echo 65535; return 0; }
	_plw=0
	for _plq in $(echo "$1" | tr ',' ' '); do
		_pla=${_plq%-*}; _plb=${_plq#*-}
		_plw=$((_plw + _plb - _pla + 1))
	done
	echo "$_plw"
}
# Строка целиком: действует ли она в ядре.
port_line_ok()  { port_src_ok "$1" && port_proto_ok "$2" && port_list_ok "$3" && port_dir_ok "$4"; }

# port_rules_in_order <файл> [<src>] — ДЕЙСТВУЮЩИЕ строки хранилища в ПОРЯДКЕ ЦЕПОЧКИ (TSV, по строке
# на правило, порты — нормализованные). Со вторым аргументом — только правила этого устройства и всего
# роутера: так их видит ядро для одного клиента. Второй аргумент ЕСТЬ, но пуст — правил устройств нет
# ни одного (не «все»): индикатор без адреса не должен приписать клиенту чужие правила.
# Внутри прохода — узкое раньше широкого: ключ сортировки «ширина⇥номер строки» (оба с нулями слева) —
# у busybox `sort` нет `-k`/`-t`, поэтому ключ идёт ПЕРВЫМИ полями, а `cut -f3-` его снимает.
port_rules_in_order() {
	[ -s "$1" ] || return 0
	_plf=$1; _plo=""; [ "$#" -ge 2 ] && _plo="=$2"
	_plt=$(printf '\t'); _plc=$(printf '\r')
	for _plp in dev any; do
		_pln=0
		while IFS="$_plt" read -r _pls _plr _plx _pld || [ -n "$_pls" ]; do
			_pld=${_pld%"$_plc"}   # файл из Блокнота (CRLF): «block\r» иначе не узнаёт ни один словарь
			[ -n "$_pld" ] || continue
			if [ "$_plp" = any ]; then
				[ "$_pls" = any ] || continue
			else
				[ "$_pls" != any ] || continue
				[ -z "$_plo" ] || [ "=$_pls" = "$_plo" ] || continue
			fi
			_plx=$(port_list_norm "$_plx")
			port_line_ok "$_pls" "$_plr" "$_plx" "$_pld" || continue
			_pln=$((_pln + 1)); _plw=$(port_width "$_plx"); [ "$_plr" = both ] && _plw=$((_plw * 2))
			printf '%06d\t%05d\t%s\t%s\t%s\t%s\n' "$_plw" "$_pln" "$_pls" "$_plr" "$_plx" "$_pld"
		done < "$_plf" | sort | cut -f3-
	done
}
