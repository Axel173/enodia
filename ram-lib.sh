#!/bin/sh
# ram-lib.sh — ЕДИНСТВЕННЫЙ владелец ПЕРЕИМЕНОВАНИЯ наших файлов в /tmp. Сорсится
# (`. ram-lib.sh`), сам ничего не печатает; вся работа — в `ram_migrate`.
#
# ЗАЧЕМ. Правило проекта: вне наших каталогов имя обязано нести префикс `enodia-` — в /tmp
# namespace общий со стоком и с файлами человека. 02.09.2026 префикс получили логи, 03.09.2026 —
# всё остальное: локи, пидфайлы, отметки, кэши. Но переименование в ОБЩЕМ namespace — это не
# правка строки, а МИГРАЦИЯ, и цена ошибки здесь названа точно:
#
#   демоны мы гасим СТРОГО ПО ПИДФАЙЛУ (`start-stop-daemon -K -p`), а не по `killall` —
#   инстансов у нас по нескольку (awg0/awgN/awgs0, xray и его слоты). Обновление подменяет
#   скрипты ПОД ЖИВЫМИ демонами: xray вчерашнего кода держит `/tmp/xray.pid` (legacy-name: имя
#   прошлой эпохи, ровно то, что переносим),
#   а сегодняшний `down` ищет `/tmp/enodia-xray.pid`. Не найдя, он НЕ УБЬЁТ никого и доложит об
#   успехе, после чего `up` поднимет ВТОРОЙ инстанс на том же socks — и тот не встанет («порт
#   слушает, но это не наш pid»). Сирота при этом неубиваем до ребута.
#
# То же и мягче — у локов (лок, взятый под старым именем, новый код не видит ⇒ два прогона
# разом; `gh-update` берёт свой лок И ЖЕ подменяет скрипты — старое имя осталось бы запертым
# навсегда) и у отметок (одно ложное письмо, один лишний прогон).
#
# ПОЧЕМУ ОДИН СПИСОК, А НЕ ПРАВКА У КАЖДОГО ВЛАДЕЛЬЦА. Владельцев больше сорока, и забытый —
# это молчаливый отказ ровно того класса, что описан выше. Здесь же список ОДИН и он же
# документирует эпоху: из него растут легаси-маски снятия (uninstall.sh::RAM_GLOBS_LEGACY).
#
# ПРАВИЛО ПЕРЕИМЕНОВАНИЯ МЕХАНИЧЕСКОЕ, и таблицы «старое→новое» нет намеренно: новое имя ВСЕГДА
# получается вставкой `enodia-` после `/tmp/` (у скрытых — после точки). Таблица из двух колонок
# разъехалась бы половинами, а так вторая колонка вычисляется.
#
# ПОЧЕМУ БЕЗ ОТМЕТКИ «УЖЕ МИГРИРОВАЛИ». Отметку пришлось бы сбрасывать КАЖДОМУ, кто привозит
# новый код (обновление, установщик, переезд раскладки, `--push` разработчика) — забытый путь
# даёт роутер, который выглядит обновлённым и не мигрирован. ЗАМЕР на живом BE7000 (03.09.2026,
# 145 объектов в /tmp, 108 масок): 5.5 мс на прогон — сошлись два независимых замера, по 20 и по
# 200 повторов. Это дешевле развилки, которую пришлось бы сопровождать вечно. Зовут нас из
# boot.sh, то есть ~1.7 раза в минуту (heal раз в минуту, сторож раз в две, трафик раз в пять).
# ЦЕНА ПЕРВОГО ПРОГОНА — не тесты, а переименования, и их конечное число: на том же BE7000 из
# 145 объектов /tmp под старые имена подходил 31. Дальше каждый прогон находит ноль.
#
# АТОМАРНОСТЬ. `mv` внутри /tmp — переименование inode, лока не нужно. Двух мигрантов разом
# (heal раз в минуту и сторож раз в две — на чётной минуте они стартуют ВМЕСТЕ) это переживает
# само: проигравший упрётся либо в исчезнувший источник, либо в уже занятое имя, и в обоих
# случаях промолчит. Единственная опасность —
# `mv КАТАЛОГ КАТАЛОГ`, который кладёт источник ВНУТРЬ цели (`/tmp/enodia-lists/lists`), поэтому
# гард `[ ! -e "новое" ]` обязателен и стоит ДО mv. Он же решает спор эпох: если новое имя уже
# заведено сегодняшним кодом — оно и есть истина, вчерашний файл не трогаем (его подберёт
# `clean.sh`/`uninstall.sh` по легаси-маске).

# СТАРЫЕ ИМЕНА (относительно /tmp), globs допустимы. Порядок роли не играет.
# ДВА ИМЕНИ ЗДЕСЬ ГЕНЕРИЧЕСКИЕ — `geo` и `lists`, каталоги кэшей, — и это ЕДИНСТВЕННОЕ место, где
# мы трогаем имя, которое не обязано быть нашим. Довод, почему это допустимо: переносим мы только
# на роутере, где система УЖЕ стоит (нас зовут boot.sh, установщик и обновление), а гард «новое имя
# занято» не даёт затереть ничего. Худший случай — переименованный чужой КЭШ, который владелец
# заведёт заново; ЗАМЕР листинга /tmp на BE7000 (03.09.2026, 145 объектов) чужих `geo`/`lists`
# не нашёл. Не переносить их нельзя: в `lists` живут мегабайтные закачки, и брошенная копия
# держала бы ОЗУ до ребута — на 176-МБ моделях это и есть причина ребутов.
# ЛОГОВ ЗДЕСЬ НЕТ: лог — файл, в который ПИШУТ, а не читают; демон, переживший обновление,
# продолжает писать в старый путь по уже открытому fd, и переименование его не догонит.
# Их подбирают перечни `clean.sh` и маски `uninstall.sh`, знающие обе эпохи.
# legacy-name: ВЕСЬ список ниже — имена ДО префикса (02–03.09.2026); сами мы таких не заводим.
RAM_MIG_OLD='.bin-manifest.* .carrier-up.stamp .cpu-stat .curl-cafile .dns-merge.* .doh-*
.grp-apply.* .grp-pairs .ip6t-wait .ipt-wait .lists-reg.* .set-snap .set-snap-* .slots.lock
.support-* .totp-* .vpnsrv-* .zapret-* .05-dhcp-static.conf.stage
awg0.seen awgs0.conf byedpi.pid byedpi-fetch.pid byedpi-fetch.users byedpi-s*.pid
byedpi-sweep.lock byedpi-test-cand.lst byedpi-test-ciadpi.pid byedpi-test-pool.lst
byedpi-test-res byedpi-test.owneradded byedpi-test.pid devwatch-stop.*.pid doh.pid
geo geo.pid geo-fresh.pid geo-update.pid gh-update.lock gh-update.pid hev.pid hev-s*.pid
hysteria.pid hysteria-s*.pid iplist.txt iplist-restore.pid lists lists-*.pid
notify-event.*.stamp panel-pass.pid panel-reboot.pid panel-tls.pid ping-active-dead
proto-install.lock proto-install.pid subs-update.lock subs-update-cgi.pid support-tunnel.pid
traffic-acct.lock uhttpd-web.pid uninstall.pid xray.pid xray-s*.pid
xray-test.*.json xray-test.*.out xray-test.*.pid
zapret-migrate.pid zapret-nfqws.pid zapret-sweep.lock'

# ram_migrate — перенести всё, что осталось от прошлой эпохи. Идемпотентна, молчалива, всегда 0:
# зовут её ДО работы (boot.sh перед запуском цели, установщик и обновление сразу после заливки),
# и отказ переноса одного файла не повод не запускать цель.
ram_migrate() {
    for _rm_p in $RAM_MIG_OLD; do
        for _rm_f in /tmp/$_rm_p; do
            # Glob без совпадений ash возвращает САМИМ ШАБЛОНОМ — отсеиваем по факту наличия.
            [ -e "$_rm_f" ] || continue
            _rm_n=${_rm_f#/tmp/}
            case "$_rm_n" in
                .*) _rm_t="/tmp/.enodia-${_rm_n#.}" ;;
                *)  _rm_t="/tmp/enodia-$_rm_n" ;;
            esac
            # Форма `if`, а не `[ … ] && continue`: под `set -e` у вызывателя страж-«и»
            # роняет шелл, стоит ему оказаться последней командой тела (грабля проекта).
            if [ -e "$_rm_t" ]; then continue; fi
            mv "$_rm_f" "$_rm_t" 2>/dev/null || :
        done
    done
    return 0
}
