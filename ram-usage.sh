#!/bin/sh
#
# ram-usage.sh — ЕДИНСТВЕННАЯ истина «кто ест оперативную память»: сколько её всего, сколько
# занимает НАШ проект и что за процессы держат остальное.
#
# ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ, а не строкой в sysinfo. `cgi-bin/sysinfo` панель опрашивает КАЖДЫЕ 5
# секунд ради температуры и загрузки ЦП; обход всего `/proc` там означал бы полсотни лишних
# forks в этом же ритме. Здесь ответ считается ЛЕНИВО — по клику, как разбивка флеша.
# С `clean.sh` их роднит форма ответа («кто сколько занял»), но не предмет: тот меряет
# ФАЙЛЫ на флеше через `du` и умеет чистить, этот — ЖИВЫЕ процессы и не трогает ничего.
#
# ЧЕСТНАЯ ГРАНИЦА, которую обязана повторить панель: считаем RSS (resident set size) — сколько
# страниц процесса реально в памяти. Разделяемые страницы (libc, которую держат все) RSS
# засчитывает КАЖДОМУ, поэтому сумма по процессам — ОЦЕНКА СВЕРХУ, а не «столько освободится».
# Честнее было бы PSS из `/proc/<pid>/smaps`, но на ядре 5.4 стока его чтение по всем процессам
# стоит секунды и требует прохода по сотням строк на процесс — цена не стоит точности.
#
# КТО «НАШ» — определяем по ФАКТУ, а не по списку имён (тот же приём, что у бинарей в
# clean.sh): процесс наш, если его командная строка ведёт в наш каталог ($ENODIA_DIR) или в
# каталог-хранилище на внешнем накопителе. Список имён остаётся ВТОРЫМ ситом — nfqws и ciadpi
# запускаются с аргументами, в которых наших путей нет вовсе. Новый демон проекта попадёт в
# счёт сам, пока его зовут полным путём (а зовут его так всегда — короткие команды на роутере
# не работают).
#
# ВЕРБЫ:
#   json            — машинный срез для панели. Ничего не меняет.
#   (без аргумента) — текстовый отчёт (SSH/мессенджер).

ENODIA_DIR=${ENODIA_DIR:-/data/usr/app/enodia}
ENODIA_BIN=${ENODIA_BIN:-/data/usr/app/enodia-bin}

# Где лежат бинари (может быть внешний накопитель) — ответ даёт store-lib, своей копии разбора
# маркера тут нет. ГРАБЛЯ: сорсить ТОЛЬКО под `[ -f ]` — провалившийся `.` в busybox ash убивает
# шелл на месте, и `2>/dev/null` от этого не спасает.
BIN_DIR="$ENODIA_BIN"
if [ -f "$ENODIA_DIR/store-lib.sh" ]; then . "$ENODIA_DIR/store-lib.sh"; fi

# Второе сито: имена НАШИХ демонов, чья командная строка может не содержать наших путей.
OUR_BINS="amneziawg-go awg xray hysteria hev byedpi ciadpi nfqws panel-tls https-dns-proxy dot-proxy dns-filter"

TOPN=8            # столько чужих процессов показываем поимённо, остальные — одной строкой

meminfo_kb() {    # meminfo_kb <ключ> → КБ (0, если поля нет)
    _v=$(awk -v k="$1:" '$1==k{print $2; exit}' /proc/meminfo 2>/dev/null)
    case "$_v" in ''|*[!0-9]*) _v=0 ;; esac
    echo "$_v"
}

# --- ОБХОД ПРОЦЕССОВ ------------------------------------------------------------------------
# Печатает по строке на процесс: <RSS_КБ>⇥<our|other>⇥<подпись>.
#
# Стоимость намеренно ужата: `Name` и `VmRSS` берём ОДНИМ awk на процесс (два прохода по
# /proc/<pid>/status — это два fork'а на каждый из полусотни), а разбор строки делаем средствами
# самого shell. Процессы БЕЗ VmRSS — потоки ядра ([kworker] и прочие): у них нет адресного
# пространства, и в «занято» они не входят.
scan_procs() {
    for _d in /proc/[0-9]*; do
        [ -r "$_d/status" ] || continue
        _pl=$(awk '/^Name:/{n=$2} /^VmRSS:/{r=$2+0} END{if(r>0) print r" "n}' "$_d/status" 2>/dev/null)
        [ -n "$_pl" ] || continue
        _rss=${_pl%% *}; _nm=${_pl#* }
        case "$_rss" in ''|*[!0-9]*) continue ;; esac
        _cl=$(tr '\0' ' ' 2>/dev/null < "$_d/cmdline")

        _kind=other
        case "$_cl" in
            *"$ENODIA_DIR/"*|*"$ENODIA_BIN/"*) _kind=our ;;
        esac
        if [ "$_kind" = other ] && [ "$BIN_DIR" != "$ENODIA_BIN" ]; then
            case "$_cl" in *"$BIN_DIR/"*) _kind=our ;; esac
        fi
        if [ "$_kind" = other ]; then
            case " $OUR_BINS " in *" $_nm "*) _kind=our ;; esac
        fi

        _lbl="$_nm"
        if [ "$_kind" = our ]; then
            # amneziawg-go РАЗЛИЧАЕМ ПО ИНТЕРФЕЙСУ, и это не косметика: инстансов трое разных по
            # смыслу — awg0 (основной туннель), awgN (дополнительный выход), awgs0 («доступ
            # домой»). Свалив их в «amneziawg-go ×3», экран перестал бы отвечать на вопрос, ради
            # которого его открывают. Остальные демоны различать нечем (у второго инстанса xray
            # отличается лишь порт socks в конфиге) — их считаем количеством.
            case "$_nm" in
                amneziawg-go)
                    _if=${_cl#* }; _if=${_if%% *}
                    case "$_if" in awg*) _lbl="amneziawg-go $_if" ;; esac ;;
                # Наши sh-скрипты (heal/watchdog из cron, фоновые задачи панели) приходят как
                # «sh» — так их и подписываем одной строкой, иначе в списке демонов появлялся бы
                # безымянный «sh», непонятно чей.
                sh|ash|busybox) _lbl="скрипты проекта" ;;
                uhttpd) _lbl="uhttpd (панель)" ;;
            esac
            # CGI панели сворачиваем в ОДНУ строку — по ФАКТУ пути, а не по списку имён. Иначе в
            # разбивке появлялся загадочный «data» на мегабайт: это сам обработчик, отвечающий на
            # ЭТОТ запрос (экран мерил в том числе себя), а рядом при живой панели мелькают
            # `status`, `sysinfo`, `list`. Человек читает такую строку как чужой процесс.
            case "$_cl" in
                *"$ENODIA_DIR/web/cgi-bin/"*) _lbl="запросы панели" ;;
            esac
        fi
        # Подпись уезжает в JSON, а имя процесса приходит из ядра (comm) и теоретически может
        # нести кавычку или обратный слэш — экранировать в busybox нечем, поэтому вырезаем.
        # Fork платим ТОЛЬКО в этом редчайшем случае, а не на каждом из полусотни процессов.
        case "$_lbl" in
            *'"'*|*'\'*) _lbl=$(printf '%s' "$_lbl" | tr -d '"\\') ;;
        esac
        printf '%s\t%s\t%s\n' "$_rss" "$_kind" "$_lbl"
    done
    return 0
}

# Сворачивает одинаковые подписи в одну строку: <сумма КБ>⇥<число процессов>⇥<подпись>.
# Через sort + смену ключа, БЕЗ ассоциативных массивов awk: busybox-awk урезан (нет index(),
# split() и своих функций), и опираться на него лишний раз незачем. На вход — вывод scan_procs,
# уже отфильтрованный по виду.
#
# ГРАБЛЯ (замерено на BE7000, busybox v1.25.1): у здешнего `sort` НЕТ ни `-k`, ни `-t` —
# applet собран в урезанном виде, `sort --help` печатает ровно `sort [-nru]`. Неизвестные
# ключи он не отвергает, а МОЛЧА игнорирует, поэтому `sort -t<TAB> -k3,3` сортировал по ВСЕЙ
# строке, где первым полем идёт RSS: одинаковые подписи расходились по списку, между ними
# вставали чужие, и группировка не срабатывала НИКОГДА (в панели «скрипты проекта» приезжали
# двумя строками, «×N» не появлялось ни разу, а «топ-8 чужих» был топом ПРОЦЕССОВ, а не групп).
# Поэтому ключ ставим ПЕРВЫМ полем и сортируем обычным `sort` — он тут единственный, что есть.
group_by_label() {
    awk -F'\t' '{ print $3 "\t" $1 }' |
    sort |
    awk -F'\t' '
        { if($1!=k){ if(k!=""){ printf "%d\t%d\t%s\n", s, c, k } k=$1; s=0; c=0 } s+=$2; c++ }
        END{ if(k!=""){ printf "%d\t%d\t%s\n", s, c, k } }' |
    sort -rn
}

# --- НАШИ ФАЙЛЫ В /tmp — ЭТО ТОЖЕ ОЗУ -------------------------------------------------------
# Замерено на AX3600 17.08.2026 и это главная дыра прежнего экрана: он показывал «проект — 3.4 МБ»
# в момент, когда проект держал в памяти на порядок больше. `/tmp` — tmpfs, то есть каждый
# положенный туда байт занимает ОЗУ, но ни в чей RSS не входит (в `free` он виден как Shmem).
# После включения крупной гео-категории там лежало 10.4 МБ одних только dnsmasq-конфигов.
#
# ЧТО НАШЕ — спрашиваем ВЛАДЕЛЬЦЕВ, своих масок не заводим: список логов в ОЗУ знает clean.sh
# (верб `ramlogs-list`), а маска `/tmp/*.log` запрещена — рядом лежат стоковые логи Xiaomi. Для
# dnsmasq-сниппетов берём ровно те ТРИ глоба, которыми снимает их uninstall.sh (нумерованные,
# `enodia-*` и легаси `awg-*`): стоковый `filter_main_opt.conf` не подходит ни под один, то есть
# чужое не засчитаем. НАБОР ГЛОБОВ — ЧАСТЬ ИНВАРИАНТА: ребрендинг (29.08.2026) добавил `enodia-*`
# в снятие и забыл здесь — наш же `enodia-custom.conf` выпал из учёта ОЗУ, а комментарий рядом
# продолжал обещать «ровно те же глобы». Меняешь маски там — меняй тут (следит C55).
TMP_DNSQ=""            # наши конфиги dnsmasq в ОЗУ (их же отдельно приписываем dnsmasq ниже)
for _f in /tmp/dnsmasq.d/[0-9][0-9]-*.conf /tmp/dnsmasq.d/enodia-*.conf /tmp/dnsmasq.d/awg-*.conf; do   # legacy-name: awg-* — сниппеты прежних установок
    [ -f "$_f" ] && TMP_DNSQ="$TMP_DNSQ $_f"
done
TMP_OURS="$TMP_DNSQ"
# …и бинари, загруженные с компьютера, — до установки они лежат в ОЗУ (до ~17 МБ) вместе с времянками приёма (gh-update.sh bin-stage,
# cgi-bin/binup), — и скачанные движком заранее (gh-update.sh bin-prefetch: на время операции, до ~17 МБ).
for _d in /tmp/enodia-geo /tmp/enodia-lists /tmp/enodia-bin-stage /tmp/enodia-bin-prefetch /tmp/enodia-binup-*; do
    [ -d "$_d" ] && TMP_OURS="$TMP_OURS $_d"
done
if [ -f "$ENODIA_DIR/clean.sh" ]; then
    TMP_OURS="$TMP_OURS $(sh "$ENODIA_DIR/clean.sh" ramlogs-list 2>/dev/null | tr '\n' ' ')"
fi
# busybox du умеет только -s -k; `-x` держит нас внутри tmpfs. Пустой список = 0 (не зовём du).
# `$1` НАМЕРЕННО без кавычек: массивов в POSIX sh нет, список путей передаём одной строкой и
# полагаемся на её разбиение по пробелам. Пути тут наши и фиксированные — пробелов в них не
# бывает; du печатает строку на аргумент, awk их складывает.
du_k_of() {
    [ -n "$1" ] || { echo 0; return 0; }
    du -xsk $1 2>/dev/null | awk '{s+=$1} END{printf "%d", s+0}'
}
TMPFS_K=$(du_k_of "$TMP_OURS")
DNSQ_CONF_K=$(du_k_of "$TMP_DNSQ")

# --- НАБОРЫ ipset — ПАМЯТЬ ЯДРА, третья графа мимо экрана ------------------------------------
# ipset не лежит ни в чьём RSS (это не процесс) и не лежит в tmpfs (это не файл) — до сих пор
# «сколько занимает наш CIDR-пул» экран не отвечал вовсе. Размер знает сам ipset, и спрашиваем
# его `-terse`: без флага он выгружает ВСЕХ членов (у iplist_set их 3472, у geo_out 8121), а
# экран открывают по клику — платить дампом за одну цифру незачем.
# Замерено 17.08.2026 на AX3600: iplist_set 3472 подсети = 146 КБ, geo_out 8121 = 229 КБ, все
# наши наборы вместе 430 КБ. На фоне dnsmasq это мелочь — но графа обязана быть, иначе вопрос
# «а основной пул сколько ест» останется без ответа, а он ровно тот, который задают.
# Префиксы НАШИХ наборов — у владельца (uninstall.sh::SET_PREFIXES), своей копии не заводим:
# разъехавшись, она молча перестала бы считать новый набор (за единством следит C16).
SET_PREFIXES="enodia_ iplist_ grp_ geo_ zapret_ blocklist_ xiaomi_"
if [ -f "$ENODIA_DIR/uninstall.sh" ]; then
    _sp=$(sed -n 's/^SET_PREFIXES="\(.*\)"$/\1/p' "$ENODIA_DIR/uninstall.sh" 2>/dev/null | head -1)
    [ -n "$_sp" ] && SET_PREFIXES="$_sp"
fi
ipset_mem_b() {
    _im=0
    for _s in $(ipset list -n 2>/dev/null); do
        _ours=0
        for _p in $SET_PREFIXES; do
            case "$_s" in "$_p"*) _ours=1; break ;; esac
        done
        [ "$_ours" = 1 ] || continue
        _sz=$(ipset list "$_s" -terse 2>/dev/null | sed -n 's/^Size in memory: *\([0-9]*\).*/\1/p' | head -1)
        case "$_sz" in ''|*[!0-9]*) _sz=0 ;; esac
        _im=$((_im + _sz))
    done
    printf '%s' "$_im"
}
IPSET_B=$(ipset_mem_b)

SCAN=$(scan_procs)
OURS=$(printf '%s\n' "$SCAN" | awk -F'\t' '$2=="our"')
OTHERS=$(printf '%s\n' "$SCAN" | awk -F'\t' '$2=="other"')
sum_kb()  { awk -F'\t' '{s+=$1} END{printf "%d", s+0}'; }
count_n() { awk -F'\t' 'NF{c++} END{printf "%d", c+0}'; }

TOT_K=$(meminfo_kb MemTotal)
FREE_K=$(meminfo_kb MemFree)
AVAIL_K=$(meminfo_kb MemAvailable)
BUF_K=$(meminfo_kb Buffers)
CACHE_K=$(meminfo_kb Cached)
[ "$AVAIL_K" -gt 0 ] 2>/dev/null || AVAIL_K=$((FREE_K + BUF_K + CACHE_K))

OURS_K=$(printf '%s\n' "$OURS"   | sum_kb)
OURS_N=$(printf '%s\n' "$OURS"   | count_n)
OTH_K=$(printf '%s\n' "$OTHERS"  | sum_kb)
OTH_N=$(printf '%s\n' "$OTHERS"  | count_n)

# =====================================================================================
# РЕЖИМ json — срез для панели.
# =====================================================================================
if [ "${1:-}" = json ]; then
    kb() { echo $(( ${1:-0} * 1024 )); }
    printf '{"total_b":%s,"free_b":%s,"avail_b":%s,"buffers_b":%s,"cached_b":%s,' \
        "$(kb "$TOT_K")" "$(kb "$FREE_K")" "$(kb "$AVAIL_K")" "$(kb "$BUF_K")" "$(kb "$CACHE_K")"
    printf '"ours_b":%s,"ours_n":%s,"others_b":%s,"others_n":%s,' \
        "$(kb "$OURS_K")" "$OURS_N" "$(kb "$OTH_K")" "$OTH_N"
    # tmpfs_b — наши файлы в /tmp (ОЗУ, но не RSS); dnsmasq_conf_b — та их часть, что мы скормили
    # СТОКОВОМУ dnsmasq. Он не наш процесс и остаётся в «остальном», но растёт от наших списков,
    # и без этой цифры экран сваливал бы главного едока памяти на «прошивку, не трогаем».
    printf '"tmpfs_b":%s,"dnsmasq_conf_b":%s,"ipset_b":%s,"procs":[' \
        "$(kb "$TMPFS_K")" "$(kb "$DNSQ_CONF_K")" "$IPSET_B"
    _first=1
    # Пайп сюда НЕ годился бы (цикл ушёл бы в подоболочку и `_first` не пережил бы итерацию —
    # запятые в JSON поехали бы), поэтому кормим цикл здесь-строкой.
    while IFS="$(printf '\t')" read -r _b _n _l; do
        [ -n "$_l" ] || continue
        [ "$_first" = 1 ] || printf ','
        _first=0
        printf '{"name":"%s","n":%s,"rss_b":%s}' "$_l" "$_n" "$(kb "$_b")"
    done <<EOF
$(printf '%s\n' "$OURS" | group_by_label)
EOF
    printf '],"others":['
    # Чужое — ТОП по памяти, хвост одной строкой: список из полусотни системных процессов не
    # отвечает ни на один вопрос, а «сколько там ещё» — отвечает.
    _first=1; _rest_b=0; _rest_n=0; _i=0
    while IFS="$(printf '\t')" read -r _b _n _l; do
        [ -n "$_l" ] || continue
        _i=$((_i + 1))
        if [ "$_i" -le "$TOPN" ]; then
            [ "$_first" = 1 ] || printf ','
            _first=0
            printf '{"name":"%s","n":%s,"rss_b":%s}' "$_l" "$_n" "$(kb "$_b")"
        else
            _rest_b=$((_rest_b + _b)); _rest_n=$((_rest_n + _n))
        fi
    done <<EOF
$(printf '%s\n' "$OTHERS" | group_by_label)
EOF
    printf '],"rest_b":%s,"rest_n":%s}\n' "$(kb "$_rest_b")" "$_rest_n"
    exit 0
fi

# =====================================================================================
# РЕЖИМ text — отчёт для SSH/мессенджера.
# =====================================================================================
hum() { awk -v k="${1:-0}" 'BEGIN{ if(k<1024) printf "%d КБ", k; else printf "%.1f МБ", k/1024 }'; }

echo "=== Оперативная память ==="
printf 'всего %s · доступно %s · кэш и буферы %s\n' \
    "$(hum "$TOT_K")" "$(hum "$AVAIL_K")" "$(hum $((BUF_K + CACHE_K)))"
printf 'проект: %s в %s процессах + %s файлами в /tmp + %s наборами ipset · остальное: %s в %s\n' \
    "$(hum "$OURS_K")" "$OURS_N" "$(hum "$TMPFS_K")" "$(hum $((IPSET_B / 1024)))" "$(hum "$OTH_K")" "$OTH_N"
[ "$DNSQ_CONF_K" -gt 0 ] 2>/dev/null && printf 'из них %s — конфиги, которые мы отдали dnsmasq (он в «остальном», но растёт от них)\n' \
    "$(hum "$DNSQ_CONF_K")"
echo ""
echo "=== Наши процессы (RSS) ==="
printf '%s\n' "$OURS" | group_by_label |
    awk -F'\t' '{ printf "%9.1f МБ  %s%s\n", $1/1024, $3, ($2>1 ? "  ×"$2 : "") }'
echo ""
echo "=== Остальное на роутере (топ по памяти) ==="
printf '%s\n' "$OTHERS" | group_by_label | head -15 |
    awk -F'\t' '{ printf "%9.1f МБ  %s%s\n", $1/1024, $3, ($2>1 ? "  ×"$2 : "") }'
echo ""
# Не «оценка сверху»: на BE7000 сумма строк втрое МЕНЬШЕ «занято» (замер 22.09.2026) — память ядра и драйверов ничья.
echo "NB: сумма RSS с системным «занято» не сходится в обе стороны: общие страницы засчитаны КАЖДОМУ процессу, а память ядра и драйверов не принадлежит ни одному."
