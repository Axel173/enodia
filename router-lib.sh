#!/bin/sh
# router-lib.sh — «что это за роутер и как ему сейчас живётся»: ЕДИНЫЙ детект модели плюс
# мгновенная загрузка ЦП. Источник истины для:
#   - шапки веб-панели (cgi-bin/status → полное «Xiaomi AX3600»);
#   - префикса ТЕМ писем и записей журнала (notify.sh / events.sh → короткое «AX3600»);
#   - процента загрузки ЦП там, где можно потратить секунду (cgi-bin/sysinfo, dump.sh).
#
# ЗАЧЕМ (грабля): раньше детект жил ИНЛАЙНОМ в cgi-bin/status, а префикс писем был
# ЗАХАРДКОЖЕН строкой "BE7000:" в ~20 местах (switch-vpn/heal.sh/iplist-update/
# watchdog.sh/xray|hy2-transport). На AX3600/BE3600 письма и «центр уведомлений»
# панели врали моделью («BE7000», хотя роутер AX3600). Теперь одна копия детекта,
# а sink'и (notify.sh/events.sh) переписывают лидирующий код модели на реальный.
#
# Источник №1 — displayName из /etc/config/misc (есть на НОВОЙ прошивке, напр.
# «Xiaomi路由器BE7000» у RC06/BE7000): латинский лидирующий ран = бренд (Xiaomi),
# замыкающий = модель (BE7000); китайское «路由器» отсекается как не-ASCII.
# Фолбэк (СТАРАЯ прошивка, AX3600 ROM 1.1.21 — displayName НЕТ) — код HARDWARE из
# xiaoqiang_version с маппингом известных (R3600=AX3600, RC06=BE7000); неизвестное
# показываем как есть («Xiaomi <код>»).
#
# Только POSIX/busybox: sed/grep/head, без awk-функций. Сорсится (`. router-lib.sh`),
# сам ничего не печатает.

_RL_VER=/usr/share/xiaoqiang/xiaoqiang_version
_RL_MISC=/etc/config/misc

# Короткое имя модели БЕЗ бренда — для префикса тем писем/журнала: BE7000 / AX3600 / …
router_label() {
	_rl_dn=$(sed -n "s/.*option displayName '\([^']*\)'.*/\1/p" "$_RL_MISC" 2>/dev/null | head -1)
	_rl_out=""
	if [ -n "$_rl_dn" ]; then
		_rl_out=$(printf '%s' "$_rl_dn" | sed 's/.*[^A-Za-z0-9]//')   # замыкающий ASCII-ран: BE7000
	fi
	if [ -z "$_rl_out" ]; then
		_rl_hw=$(grep -E "option HARDWARE " "$_RL_VER" 2>/dev/null | sed "s/.*'\(.*\)'.*/\1/")
		case "$_rl_hw" in
			R3600) _rl_out="AX3600" ;;
			RC06)  _rl_out="BE7000" ;;
			'')    _rl_out="роутер" ;;
			*)     _rl_out="$_rl_hw" ;;
		esac
	fi
	printf '%s' "$_rl_out" | tr -d '"\\'
}

# Полное «Бренд Модель» — для шапки панели: Xiaomi AX3600
router_model() {
	_rm_dn=$(sed -n "s/.*option displayName '\([^']*\)'.*/\1/p" "$_RL_MISC" 2>/dev/null | head -1)
	_rm_out=""
	if [ -n "$_rm_dn" ]; then
		_rm_mdl=$(printf '%s' "$_rm_dn" | sed 's/.*[^A-Za-z0-9]//')   # замыкающий ASCII-ран: BE7000
		_rm_brd=$(printf '%s' "$_rm_dn" | sed 's/[^A-Za-z0-9].*//')   # лидирующий ASCII-ран: Xiaomi (пусто на CN-строке)
		[ -z "$_rm_brd" ] && _rm_brd=Xiaomi
		[ "$_rm_brd" = "$_rm_mdl" ] && _rm_brd=Xiaomi
		[ -n "$_rm_mdl" ] && _rm_out="$_rm_brd $_rm_mdl"
	fi
	if [ -z "$_rm_out" ]; then
		_rm_hw=$(grep -E "option HARDWARE " "$_RL_VER" 2>/dev/null | sed "s/.*'\(.*\)'.*/\1/")
		case "$_rm_hw" in
			R3600) _rm_out="Xiaomi AX3600" ;;
			RC06)  _rm_out="Xiaomi BE7000" ;;
			'')    _rm_out="Xiaomi" ;;
			*)     _rm_out="Xiaomi $_rm_hw" ;;
		esac
	fi
	printf '%s' "$_rm_out" | tr -d '"\\'
}

# Переписать ЛИДИРУЮЩИЙ код модели («BE7000:» и пр.) в теме письма / заголовке события
# на РЕАЛЬНУЮ модель этого роутера. Историческ callers хардкодят «BE7000:» в теме — на
# AX3600/BE3600 это врёт. Прогоняют текст сюда ТРОЕ: notify-event.sh на ВХОДЕ (чтобы письмо,
# журнал панели и его собственный лог говорили одно и то же) и оба sink'а — notify.sh и
# events.sh, которых зовут и напрямую, мимо notify-event. Функция ИДЕМПОТЕНТНА, поэтому
# двойной прогон безвреден. Известные коды перечислены явно (безопаснее glob'а [A-Z0-9]); не
# совпало — текст возвращается без изменений.
router_relabel() {
	case "$1" in
		BE7000:*|AX3600:*|BE3600:*|BE10000:*)
			printf '%s:%s' "$(router_label)" "${1#*:}" ;;
		*) printf '%s' "$1" ;;
	esac
}

# Загрузка ЦП в ПРОЦЕНТАХ — дельта занятых тиков /proc/stat за 1 секунду (как top).
# ЕДИНСТВЕННЫЙ владелец этого ответа для тех, кто может позволить себе секунду: cgi-bin/sysinfo
# и dump.sh. Шапка панели (cgi-bin/status) сюда НЕ ходит намеренно — она поллится каждые
# пару секунд и считает дельту МЕЖДУ ПОЛЛАМИ по снимку в /tmp, то есть не спит вовсе; это
# другая стратегия, а не копия. Установщик на ПК несёт свою инлайн-копию: шапка обязана
# показывать роутер, на котором наших файлов ещё нет.
#
# НЕ loadavg. Тот — средняя длина очереди задач за минуту (плюс D-state), а не «сколько занят
# процессор»: на этом железе фоновый демон держит её около 1.0, и формула (load1/ядра)*100
# печатала «~25%» на роутере, занятом на 0-1% — замерено 16.08.2026 ОДНОВРЕМЕННО на BE7000
# (реальные 1%) и AX3600 (0%). Ошибка не «в разы», а в двадцать пять раз, и врала она ровно
# там, где по ней принимают решение: в дампе, который присылают при разборе тормозов.
#
# busybox awk без split()/user-функций ⇒ два числа снимаем через `set --` (шелл-разбиение);
# внутри функции это безопасно — позиционные параметры вызвавшего POSIX-шелл восстановит сам.
# Печатает целое 0..100; не смог прочитать /proc/stat — не печатает НИЧЕГО (подставить «?» —
# дело вызвавшего, выдумывать за него ноль нельзя: ноль тут неотличим от правды).
cpu_busy_pct() {
	set -- $(awk '/^cpu /{s=0;for(i=2;i<=NF;i++)s+=$i; print s, $5+$6; exit}' /proc/stat 2>/dev/null)
	_cb_t0="$1"; _cb_i0="$2"
	sleep 1
	set -- $(awk '/^cpu /{s=0;for(i=2;i<=NF;i++)s+=$i; print s, $5+$6; exit}' /proc/stat 2>/dev/null)
	_cb_t1="$1"; _cb_i1="$2"
	if [ -z "$_cb_t0" ] || [ -z "$_cb_t1" ]; then return 0; fi
	awk -v t0="$_cb_t0" -v i0="$_cb_i0" -v t1="$_cb_t1" -v i1="$_cb_i1" 'BEGIN{
		dt=t1-t0; di=i1-i0;
		if(dt<=0){print 0; exit}
		v=(1-di/dt)*100; if(v<0)v=0; if(v>100)v=100; printf "%d", v+0.5 }'
}

# lan_if — ЕДИНСТВЕННЫЙ ответ «какой интерфейс держит ОСНОВНУЮ локальную сеть» (мост клиентов).
#
# ЗАЧЕМ (внешний аудит dev178): имя `br-lan` было вшито в шесть мест живого кода — LISTEN
# веб-панели, два гарда подъёма панели в heal.sh, финальная строка установщика, дамп и
# карточка адаптеров. На BE7000 мост действительно так и называется, но одна и та же строка
# в шести файлах — это шесть источников истины: на модели, где мост назван иначе, панель
# молча не поднимется (uhttpd не забиндится на пустой адрес), а heal не увидит причины.
#
# ЗАМЕРЕНО на живом BE7000 24.08.2026 — оба «очевидных» способа НЕ РАБОТАЮТ:
#   - `uci get network.lan.device` (форма новых сборок OpenWrt) на стоке ОТСУТСТВУЕТ (rc=1);
#   - `uci get network.lan.ifname` отдаёт не мост, а ПОРТЫ: `eth1 eth2 eth3`;
#   - «единственный мост с адресом» тоже мимо: мостов ЧЕТЫРЕ и у всех есть IPv4 —
#     br-lan 192.168.31.1, br-guest 192.168.33.1, br-miot 192.168.32.1 и br-docker 172.17.0.1.
# Работает третий путь: LAN-порты перечислены в uci, а их МАСТЕР и есть искомый мост
# (`/sys/class/net/eth1/master` → br-lan). Его и спрашиваем, сверяя каждый ответ с фактом
# в /sys — конфиг может называть интерфейс, которого в ядре уже нет.
#
# Фолбэк — литеральный `br-lan`: на роутере без uci (или с чужой схемой сети) поведение
# обязано остаться прежним БАЙТ-В-БАЙТ, иначе «улучшение» уронит панель там, где она работала.
# AX3600 на момент правки был выключен ⇒ ветка 2/3 на ядре 4.4 НЕ ЗАМЕРЕНА, и фолбэк — это
# ровно то, что делает правку безопасной без такого замера.
#
# Печатает ВСЕГДА одно имя и никогда пустое.
lan_if() {
	# 1) новые сборки: network.lan.device уже называет сам мост
	_rl_li=$(uci get network.lan.device 2>/dev/null)
	_rl_li=${_rl_li%% *}
	if [ -n "$_rl_li" ] && [ -d "/sys/class/net/$_rl_li" ]; then
		printf '%s\n' "$_rl_li"; return 0
	fi
	# 2) классическая форма: ifname = ЛИБО сам мост, ЛИБО список портов (BE7000 — порты)
	for _rl_p in $(uci get network.lan.ifname 2>/dev/null); do
		[ -d "/sys/class/net/$_rl_p" ] || continue
		if [ -d "/sys/class/net/$_rl_p/bridge" ]; then
			printf '%s\n' "$_rl_p"; return 0
		fi
		# 3) порт → его мастер и есть мост
		if [ -e "/sys/class/net/$_rl_p/master" ]; then
			_rl_m=$(readlink -f "/sys/class/net/$_rl_p/master" 2>/dev/null)
			_rl_m=${_rl_m##*/}
			if [ -n "$_rl_m" ] && [ -d "/sys/class/net/$_rl_m" ]; then
				printf '%s\n' "$_rl_m"; return 0
			fi
		fi
	done
	printf 'br-lan\n'   # lan-lit: владелец сам, дальше спрашивать некого
}
