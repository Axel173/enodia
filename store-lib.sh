#!/bin/sh
# store-lib.sh — ЕДИНСТВЕННЫЙ ответ на вопрос «где лежит бинарь».
#
# ЗАЧЕМ. На BE7000 /data = 20.6 МБ, и львиную долю занимают ДВА файла: xray 7.56 МБ и
# hysteria 4.55 МБ. Внешний накопитель снимает потолок «все протоколы разом». Но проект
# рассчитан на СТОКОВЫЙ роутер без доп-оборудования — у большинства пользователей флешки нет
# и не будет, — поэтому внешнее хранилище остаётся ОПЦИЕЙ, а вся его опциональность собрана
# ЗДЕСЬ, вместо россыпи проверок `[ -d /mnt/… ]` по транспортам, установщику и панели.
#
# ГЛАВНОЕ РЕШЕНИЕ: bin_path судит по ФАКТУ, а не по намерению. Нигде не записано «xray живёт
# на USB» — истина в том, где лежит исполняемый файл. Отсюда три свойства, за которые не
# пришлось платить ни одной новой веткой:
#   * РОУТЕР БЕЗ USB (основной сценарий) — маркера нет, BIN_DIR остаётся $ENODIA_BIN (каталог
#     бинарей на флеше). Ничего не «включается по умолчанию».
#   * ФЛЕШКУ ВЫДЕРНУЛИ — путь на ней перестаёт быть -x, возвращается резидентный, а его нет ⇒
#     transport_ready честно говорит «не установлен» ⇒ штатный fail-open и failover на
#     резидентную несущую. Отдельной обработки «а вдруг USB пропал» не существует.
#   * СМЕШАННАЯ раскладка бесплатна: тяжёлый xray на флешке, мелкий hev на /data — само собой,
#     без реестра «что где». Это и есть ожидаемая раскладка: выносить стоит только тяжёлое,
#     потому что каждый вынесенный бинарь — ещё одна вещь, умирающая вместе с флешкой.
#
# ИДЕНТИЧНОСТЬ ХРАНИЛИЩА — ПО СЕНТИНЕЛУ, не по устройству: `blkid` на роутере НЕТ, имя sdX
# динамическое (на переткычке ядро давало то sda, то sdb), серийник тома есть только у exFAT.
# Маркер хранит ПУТЬ к каталогу-хранилищу, а не устройство/точку монтирования — точка у
# стокового automount зовётся `/mnt/usb-<серийник>` и от флешки к флешке разная.
#
# ЕДИНСТВЕННАЯ КОПИЯ. bin_path предпочитает хранилище резиденту, поэтому движок оффлоада
# обязан держать ровно одну копию бинаря: ставим в одно место — сносим из другого. Иначе
# обновление версии запишет новый файл рядом со старым, и «где лежит» разойдётся с «что
# запускается». Копии одного и того же файла (момент миграции) безопасны — они идентичны.
#
# КАК ЭТОТ ФАЙЛ СОРСИТЬ (касается ВСЕХ библиотек проекта, не только этой):
#   if [ -f "$ENODIA_DIR/store-lib.sh" ]; then . "$ENODIA_DIR/store-lib.sh"; fi
# и ТОЛЬКО так. Провалившийся `.` в busybox ash — фатальная ошибка спецбилтина: шелл выходит
# НА МЕСТЕ, не выполнив ни следующей строки, ни шима (замерено на BE7000, busybox v1.25.1:
# `. /нет-файла 2>/dev/null` → rc=2 и тишина; `|| true` НЕ спасает — исключение поднимается
# мимо него). Прежняя форма `. "$ENODIA_DIR/store-lib.sh" 2>/dev/null` + `command -v … || шим`
# означала: файла нет ⇒ потребитель молча умирает, а шим ниже — мёртвый код. Для transport.sh
# и web-ui.sh это «нет VPN и нет панели» после частично доехавшего apply-scripts (тот
# обновляет ПОФАЙЛОВО и переживает провал отдельного файла).

: "${ENODIA_DIR:=/data/usr/app/enodia}"
: "${ENODIA_STATE:=/data/usr/app/enodia-state}"
: "${ENODIA_BIN:=/data/usr/app/enodia-bin}"

STORE_MARK="$ENODIA_STATE/.bin-store"        # путь к каталогу-хранилищу; пишет usb-offload.sh
STORE_SENTINEL=.enodia-bin-store        # им опознаём СВОЙ каталог на чужом накопителе
# Раскладка и точка монтирования — ЗДЕСЬ, а не в движке: их знает и uninstall.sh (сносит наш
# каталог на флешке и отпускает нашу точку), а три копии строки «enodia-store» разъехались бы
# на первой же правке. Движок эти имена только ИСПОЛЬЗУЕТ.
# ИМЕНА ОБЯЗАНЫ НЕСТИ ПРЕФИКС `enodia-`: накопитель и /mnt — ЧУЖОЙ namespace (там файлы человека
# и стоковые точки монтирования), а имя модели в имени каталога вдобавок врёт на всех остальных
# роутерах — на BE10000 наш каталог назывался «be7000-store». Следит C54.
STORE_SUB=enodia-store                  # подкаталог на накопителе (остальное там — файлы юзера)
STORE_MNT=/mnt/enodia-usb               # СВОЯ точка монтирования (если сток не смонтировал сам)
# ПРЕЖНИЕ имена (до ребрендинга 29.08.2026). Нужны РОВНО ОДНОМУ месту — снятию: каталог лежит на
# ЧУЖОМ диске и наше удаление его переживёт, если не назвать по-старому (тот же класс, что
# `awg-custom.conf`, переживший `purge`). Движок ими не пользуется и НИЧЕГО не переносит: прежнюю
# установку снимает её собственный uninstall.sh, который эти имена знал как свои.
STORE_SUB_OLD=be7000-store
STORE_SENTINEL_OLD=.be7000-bin-store
STORE_MNT_OLD=/mnt/be7000-usb
# Неснижаемый резерв /data. Живёт тут по той же причине: его сторожат ОБЕ стороны — packages.sh
# (план установки) и usb-offload.sh (возврат бинарей с накопителя), и разъехавшись, они начали
# бы спорить о том, влезет ли.
# 2.5 МБ (было 3) — РЕШЕНИЕ ПОЛЬЗОВАТЕЛЯ 18.08.2026 после жалобы «раньше xray+awg+zapret+byedpi
# вставали, теперь никак». Своего замера под это НЕТ: цифра и раньше бралась с запасом, а не из
# эксперимента, — резерв держится под ПИК установки (UBIFS пишет лениво, в момент `mv` файл живёт
# в двух местах, плюс журнал ФС), и полмегабайта из трёх этот пик не меняют. Ниже 2 МБ не опускать
# без замера: там начинается ENOSPC при живом df, ради чего резерв и заводили.
DATA_RESERVE_B=2621440                  # 2.5 МБ

# --- ПРАВА НА НАШИ КАТАЛОГИ: ВОССТАНАВЛИВАЕМ, А НЕ НАСЛЕДУЕМ ------------------------------
# ЕДИНСТВЕННЫЙ владелец ответа «какие права у наших каталогов»: зовут его установщик (на каждом
# прогоне) и движок накопителя (после каждого переезда). Двух ответов тут быть не должно —
# разъедутся, и разъедутся молча.
#
# ЗАЧЕМ. Права, приехавшие с ФС, которая их НЕ ХРАНИТ, — не права, а мусор, и на носителе,
# который их хранит, этот мусор становится настоящим. exFAT монтируется с `dmask=0000`, то есть
# КАЖДЫЙ каталог на нём 0777; `cp -rp` честно переносит этот режим дальше — и на ext4-флешку, и
# ОБРАТНО на флеш роутера, где права настоящие всегда.
#
# ЗАМЕР (BE7000, 02.09.2026, после переезда exFAT→флеш→ext4): каталоги `enodia`, `enodia/web`,
# `web/cgi-bin` и `web/assets` оказались 0777, и проба из-под `nobody` СОЗДАЛА файл в `cgi-bin`
# (rc=0, владелец nobody). А CGI оттуда запускает uhttpd ОТ ROOT, и свой файл `nobody` вправе
# сделать исполняемым — то есть это подъём привилегий, а не косметика. Ключи при этом уцелели
# ($ENODIA_STATE = 0700 от install.sh), но полагаться на один каталог-крышку нельзя.
# Свежая установка не затронута: `mkdir` под обычной umask даёт 0755 — беда приходит РОВНО через
# накопитель, поэтому чиним оба конца тракта, а не только тот, куда едем.
#
# ФАЙЛЫ КОДА НЕ ТРОГАЕМ: там 0755 у скриптов и CGI и 0644 у данных — это уже верно, а
# уравнять их одним режимом значило бы либо снять +x с CGI, либо раздать его картинкам.
# Каталоги — трогаем: именно они приехали 0777. У состояния наоборот, файлы важны: писатели
# секретов ставят 600 каждый сам (`action`, `totp.sh`), но файл, ОДНАЖДЫ приехавший с exFAT,
# второй раз никто не перезапишет — а панель обещает человеку, что на ext4 ключи закрыты.
#
# `find -exec` — не роскошь: путь к хранилищу законно содержит ПРОБЕЛ (`/mnt/My Flash/…`), а
# `for` по подстановке порвал бы его. Опция в белом списке C39 и проверена на ОБОИХ ядрах
# (5.4 BE7000 и 4.4 AX3600) — busybox молча игнорирует неизвестные опции, поэтому её нельзя
# было брать «по документации».
harden_tree() {     # $1 = корень, $2 = режим каталогов, $3 = режим файлов («-» = не трогать)
    [ -d "$1" ] || return 0
    find "$1" -type d -exec chmod "$2" {} ';' 2>/dev/null
    [ "$3" = "-" ] || find "$1" -type f -exec chmod "$3" {} ';' 2>/dev/null
    return 0
}

# …и САМА ПОЛИТИКА — тоже здесь, одной строкой на каталог. Вызывателей два (install.sh на каждом
# прогоне, usb-offload.sh после каждого переезда), и «какой режим у состояния» они обязаны знать
# одинаково: разъехавшись, один заботливо ставил бы 700, а второй возвращал 777 следующим шагом.
harden_perms() {    # $1 = каталог кода, $2 = каталог состояния, $3 = каталог бинарей
    harden_tree "$1" 755 -      # код: каталоги 755, файлы уже верны (0755 скрипты, 0644 данные)
    harden_tree "$2" 700 600    # состояние: секреты, читать их некому, кроме root
    # Бинари — 755 И КАТАЛОГ, И ФАЙЛЫ. Там лежат ТОЛЬКО исполняемые (проверено на железе
    # 02.09.2026: семь бинарей и ничего больше), и другого верного режима у них нет.
    # Сегодня они и так 755 — но лишь ПОБОЧНО: `move_verified` копирует без `-p`, и режим
    # источника (на exFAT это 0777) обрезает umask, а следом идёт `chmod +x`. Правильный
    # результат, полученный из семантики `cp` и umask, — не правило, а совпадение; для
    # файла, который root запускает как демона, «не world-writable» надо ЗАЯВЛЯТЬ.
    harden_tree "$3" 755 755
    return 0
}

# --- СКОЛЬКО МЕСТА НА ТОМЕ, КОТОРОМУ ПРИНАДЛЕЖИТ ПУТЬ ------------------------------------
# ЕДИНСТВЕННЫЙ ответ на «сколько у нас флеша» — и единственное место, где решается, У КОГО
# спрашивать. ГРАБЛЯ (BE10000/RC01, замер у тестера 30.08.2026): `df /data` — ЛИТЕРАЛ, а флеш
# там поделён на ТРИ ubifs: `/data` = стоковый cfg (4.7 МБ, забит Xiaomi), `/data/usr` = НАШ
# (18.6 МБ), `/userdisk` = plugin (29 МБ, пуст). Гард компонентов вычитал резерв 2.5 МБ из
# 708 КБ ЧУЖОГО тома и отказывал ЛЮБОМУ плану («не хватает 2.11 МБ») при 11 МБ свободных у
# нас. На BE7000/AX3600 `/data` и `/data/usr` — один том, поэтому грабля дремала полгода.
# Спрашивать место — ВСЕГДА по ПУТИ нашего каталога (следит C50).
# fs_line печатает ОДНОЙ строкой «<всего_КБ> <свободно_КБ> <точка монтирования>»: ТОЧКА ПОСЛЕДНЕЙ и
# ЦЕЛИКОМ — в ней бывает пробел («/mnt/My Flash»), а поля от конца (`$NF`, `$(NF-4)`) он сдвигал: точкой
# становилось «Flash», числами — слова (ревью ветки pkg-update, круг 2; ПК-сторону чинили раньше — `_dfl` в
# enodia.py). Опора — колонка «NN%»: ищем её справа, числа стоят за три и за одну колонку до неё. Длинное
# имя устройства busybox-df переносит на свою строку — `tail -1` берёт строку с числами, опора та же.
# Точку отдельно печатает fs_mount (своих разборов строки у потребителей нет).
# Байты считает awk (`%.0f`): целочисленный busybox-awk 32-битен, а КБ×1024 на 32-ГБ
# накопителе — это 3.4e10, то есть переполнение.
# СПРАШИВАЕМ О ПУТИ, КОТОРЫЙ СУЩЕСТВУЕТ. `df` по несуществующему пути печатает в stdout ОДИН
# ЗАГОЛОВОК («Filesystem 1K-blocks Used Available Use% Mounted on», rc=1), а `tail -1` честно
# отдаёт его как «строку данных»: NF=7, $NF="on". Отсюда `"mount":"on"` в json и «Флеш on» в
# панели, а `%.0f` от слова «Used» — ноль, то есть ещё и деление на ноль у потребителей.
# Путь может не существовать ЗАКОННО: ПК-установщик спрашивает место ДО заливки payload, а
# хранилище на флешке исчезает вместе с ней. Поэтому поднимаемся к ближайшему СУЩЕСТВУЮЩЕМУ
# предку: для /data/usr/app/enodia на свежем роутере это /data/usr — то есть НАШ том и на
# BE10000 тоже. Фолбэк на литерал /data был бы возвратом ровно к той грабле, от которой ушли.
fs_anchor()  { _fan="${1:-$ENODIA_DIR}"; while [ -n "$_fan" ] && [ ! -e "$_fan" ]; do _fan="${_fan%/*}"; done; printf '%s' "${_fan:-/}"; }
# ГАРД ЧИСЛОВОЙ (`~ /^[0-9]+$/` и `+0>0`), а не `>0`: у awk сравнение ПОЛЯ с числом идёт как СТРОКОВОЕ,
# когда поле не похоже на число, и "Used" > "0" лексикографически ИСТИННО (замерено на busybox
# awk 1.25.1 31.08.2026) — то есть прежний гард заголовок пропускал. Цикл и склейка — без функций awk
# (у busybox-awk нет пользовательских, а `m (…)` он читает вызовом — C118).
fs_line()    { df -k "$(fs_anchor "$1")" 2>/dev/null | tail -1 | awk '{for(i=NF;i>1;i--) if($i ~ /%$/) break; if(i>=4 && $(i-3) ~ /^[0-9]+$/ && $(i-1) ~ /^[0-9]+$/ && $(i-3)+0>0){m=""; for(j=i+1;j<=NF;j++){ if(j>i+1) m=m " "; m=m $j }; print $(i-3), $(i-1), m}}'; }
fs_free_b()  { _fsb=$(fs_line "$1" | awk '{printf "%.0f", $2*1024}'); case "$_fsb" in ''|*[!0-9]*) _fsb=0 ;; esac; printf '%s' "$_fsb"; }
fs_total_b() { _fst=$(fs_line "$1" | awk '{printf "%.0f", $1*1024}'); case "$_fst" in ''|*[!0-9]*) _fst=0 ;; esac; printf '%s' "$_fst"; }
fs_mount()   { _fsm=$(fs_line "$1"); printf '%s' "${_fsm#* * }"; }

# Раскладка хранилища: <store>/.enodia-bin-store (сентинел) + <store>/bin/<имя>.
#
# store_is_ours <каталог> — НАШ ли это каталог-хранилище. ЕДИНСТВЕННЫЙ ответ на вопрос, и
# спрашивают его ДВОЕ: разбор маркера ниже и сканирование накопителя (usb-offload.sh
# store_of_mount). Своя копия условия была у каждого, и они РАЗОШЛИСЬ на прежнем сентинеле:
# сканирование признавало легаси-каталог своим, маркер на него писался, а библиотека его
# отвергала ⇒ BIN_DIR оставался резидентным и «переезд» получал src == dst. Замерено на живом
# BE7000 01.09.2026: три бинаря были УДАЛЕНЫ (move_verified честно снёс исходник после того,
# как положил копию на его же место). Отсюда и правило: условие ОДНО, живёт у владельца имён.
# ПРЕЖНИЙ сентинел признаём тоже — ровно за этим он и заведён; каталог при этом работает под
# своим прежним ИМЕНЕМ, переносить его незачем (маркер несёт полный путь).
# Только builtin'ы: этот файл сорсят heal.sh (раз в минуту) и watchdog.sh (раз в две).
store_is_ours() {
    [ -n "$1" ] && [ -d "$1/bin" ] || return 1
    [ -f "$1/$STORE_SENTINEL" ] && return 0
    [ -n "$STORE_SENTINEL_OLD" ] && [ -f "$1/$STORE_SENTINEL_OLD" ]
}

# Разбор маркера — БЕЗ подоболочки И БЕЗ ФОРКОВ ВООБЩЕ: этот файл читают heal.sh (раз в минуту)
# и watchdog.sh (раз в две), а на роутере без USB не должно оставаться даже лишнего fork'а.
# `read` вместо `$(cat … | tr …)` не только дешевле на два форка у тех, у кого накопитель ЕСТЬ:
# `tr -d ' '` вырезал пробелы ВНУТРИ пути, то есть точку монтирования вида `/mnt/My Flash`
# молча превращал в чужой несуществующий путь. `read` с дефолтным IFS снимает ровно то, что
# и надо, — пробелы/табы по КРАЯМ и перевод строки. `|| :` обязателен: файл без хвостового
# перевода строки даёт rc=1, а этот файл сорсят скрипты под `set -e` (install.sh).
# CR в маркере (правка руками из Windows) не чиним: маркер пишет только mark_write, а честный
# ответ «каталог не опознан» тут лучше догадок — его теперь и печатают вербы.
STORE_DIR=
BIN_DIR="$ENODIA_BIN"
if [ -f "$STORE_MARK" ]; then
    _sr=
    read -r _sr < "$STORE_MARK" 2>/dev/null || :
    if store_is_ours "$_sr"; then
        STORE_DIR="$_sr"
        BIN_DIR="$_sr/bin"
    fi
    unset _sr
fi

# store_ready — доступно ли внешнее хранилище ПРЯМО СЕЙЧАС (смонтировано и наше).
# Отвечает на вопрос «есть ли куда предлагать переезд»: панель и движок спрашивают ЭТО, а не
# «воткнута ли флешка» — воткнутая, но не подготовленная нам не хранилище.
store_ready() { [ -n "$STORE_DIR" ]; }

# store_root — каталог-хранилище (пусто, если недоступно).
store_root() { printf '%s' "$STORE_DIR"; }

# store_state — ЕДИНСТВЕННЫЙ ответ «в каком состоянии внешнее хранилище»: `none` (не включали) ·
# `ok` (включено и доступно) · `lost` (включено, а каталога нет — флешку вынули, не смонтировалась,
# сменили разметку).
# ТРЕТЬЕ СОСТОЯНИЕ — НЕ РАЗНОВИДНОСТЬ «НЕТ»: при нём тяжёлые бинари мертвы (bin_path честно
# отдаёт резидентный путь, которого нет), то есть человеку надо СКАЗАТЬ, а не промолчать.
# Композиция «маркер есть, а хранилища нет» до 10.09.2026 жила КОПИЯМИ — в json движка и во
# фронте (siStoreFacts). Здесь она одна; спрашивающие берут готовое слово.
store_state() {
    if store_ready; then printf 'ok'
    elif [ -f "$STORE_MARK" ]; then printf 'lost'
    else printf 'none'; fi
}

# bin_path <имя> — путь, по которому бинарь НАДО ЗАПУСКАТЬ. Хранилище имеет приоритет; нет
# файла там (или хранилища вовсе) — резидентный путь, даже если и его нет: «нет бинаря» —
# это ответ, который вызывающие уже умеют обрабатывать.
#
# ГРАБЛЯ (set -e, install.sh): условие вынесено в `if`, а НЕ в `[ … ] && printf`.
# Цепочка `&&` как простая команда пробрасывает код 1 наружу и роняет вызывающего под set -e —
# ровно этим когда-то обрывался purge-alt.
bin_path() {
    if [ "$BIN_DIR" != "$ENODIA_BIN" ] && [ -x "$BIN_DIR/$1" ]; then
        printf '%s' "$BIN_DIR/$1"
    else
        printf '%s' "$ENODIA_BIN/$1"
    fi
}

# bin_where <имя> — `store` | `router` | пусто (бинаря нет вовсе). Для диагностики и панели:
# им нужен не путь, а место жительства. Отдельная функция, чтобы никто не парсил bin_path.
bin_where() {
    if [ "$BIN_DIR" != "$ENODIA_BIN" ] && [ -x "$BIN_DIR/$1" ]; then
        printf 'store'
    elif [ -x "$ENODIA_BIN/$1" ]; then
        printf 'router'
    fi
}

# bin_on_store <имя> — лежит ли бинарь на ВНЕШНЕМ НАКОПИТЕЛЕ (0 = да). Это НЕ то же, что
# bin_where, и разница поймана на живом BE7000 01.09.2026: bin_where отвечает «в каталоге-
# ХРАНИЛИЩЕ ли он», а в раскладке `full` на накопитель уехал САМ $ENODIA_BIN — каталоги там
# совпадают, и bin_where честно печатает «router» ПРО ФАЙЛ НА ФЛЕШКЕ. Кто спрашивает про
# НОСИТЕЛЬ (сроки старта демона — daemon-lib.sh: с накопителя 8-МБ бинарь читается 18 с), обязан
# спрашивать про ТОМ, а не про каталог.
# Метод тот же, что у packages.sh::disk_on_store (там вопрос соседний — «куда ляжет НОВЫЙ файл»):
# сравниваем точку монтирования с точкой БУТСТРАПА, а не с литералом `/data`, — на BE10000 `/data`
# и `/data/usr` РАЗНЫЕ тома, и сравнение с литералом объявило бы накопителем собственный флеш.
bin_on_store() {
    _bos_b=$(fs_mount "$(bin_path "$1")")
    _bos_r=$(fs_mount "${ENODIA_BOOT:-/data/usr/app/enodia-boot}")
    [ -n "$_bos_b" ] && [ -n "$_bos_r" ] && [ "$_bos_b" != "$_bos_r" ]
}

# ЧТО ВООБЩЕ МОЖНО выносить — БЕЛЫЙ список, а не «всё, кроме awg». Направление важно: новый
# бинарь по умолчанию РЕЗИДЕНТЕН, пока кто-то осознанно не решит, что он переживёт жизнь на
# съёмном носителе. Чёрный список молча уносил бы на флешку каждую новинку.
#
# Здесь ровно те пятеро, ради которых фича и затевалась: xray 8.2 + hysteria 5.2 = 13.4 МБ из
# 14.3, и все пятеро — «листья», чьё отсутствие уже обработано (transport_ready → fail-open).
# Остальные резидентны СОЗНАТЕЛЬНО, хотя технически съехали бы:
#   * amneziawg-go/awg — база: поднимается раньше любого монтирования, несёт awgs0 «доступа
#     домой», служит последним рубежом failover. Выдернул флешку — чиниться будет нечем;
#   * panel-tls — единственный вход снаружи (HTTPS). Выдернул флешку — и потерял доступ ровно
#     тогда, когда он нужнее всего, а выигрыш 0.28 МБ;
#   * https-dns-proxy/dot-proxy — 0.90 МБ на двоих (arm64 подорожал 0.02 → 0.58 МБ, когда ушёл
#     на статик): всё равно 6% набора, а лишняя точка отказа на пути DNS не нужна даже при том,
#     что doh_apply_dns умеет откатываться.
STORE_MOVABLE="xray hysteria hev byedpi nfqws"

store_movable() { case " $STORE_MOVABLE " in *" $1 "*) return 0 ;; esac; return 1; }

# --- КТО ИЗ НИХ ОСТАЁТСЯ НА РОУТЕРЕ — ПОИМЁННО ----------------------------------------------
# STORE_MOVABLE отвечает на вопрос ПРОЕКТА: «кого вообще допустимо селить на съёмный носитель».
# Здесь второй вопрос, ПОЛЬЗОВАТЕЛЬСКИЙ: «кого из них не выносить именно у меня». Глобальным
# тумблером он не выражался вовсе — маркер .bin-store один на всех, уезжали либо все пятеро,
# либо никто, и просьба «на флешку только xray» кнопкой не набиралась. Ручной обход тоже не
# работал: bin_prune держит инвариант «копия РОВНО одна», и следующее обновление снова клало
# файл на накопитель — снаружи это выглядело как «обновил, и настройка сама сбросилась».
#
# ФАЙЛ — НАМЕРЕНИЕ, А НЕ ФАКТ. «Где лежит» по-прежнему отвечает bin_path по наличию -x, поэтому
# закрепление законно записать и при выдернутой флешке: оно сработает при следующем включении.
# Ровно та же граница, что у transport.sh между «configured» и «ready».
#
# ЧИТАЕМ БЕЗ ФОРКОВ. Этот файл сорсят heal.sh (раз в минуту) и watchdog.sh (раз в две) — по той
# же причине, по которой ниже разбор STORE_MARK идёт без подоболочки. Отсюда builtin-цикл вместо
# $(cat) и гард «[ -f ]»: на роутере без закреплений не тратится ни одного форка.
# Хвост «|| [ -n "$_bk" ]» обязателен: busybox «while read» ТЕРЯЕТ последнюю строку, если её не
# завершает перевод строки (наш писатель его ставит, но файл могли поправить руками).
# CR внутри строки сделает имя непохожим на закреплённое ⇒ бинарь уедет на накопитель. Это отказ
# в сторону ПРЕЖНЕГО поведения, а не в сторону мёртвого пути, — так и задумано.
KEEP_MARK="$ENODIA_STATE/.bin-keep"     # по имени в строке; пишет usb-offload.sh place
BIN_KEEP=
if [ -f "$KEEP_MARK" ]; then
    while read -r _bk || [ -n "$_bk" ]; do
        case "$_bk" in ''|'#'*) continue ;; esac
        BIN_KEEP="$BIN_KEEP $_bk"
    done < "$KEEP_MARK"
    unset _bk
fi

# bin_pinned <имя> — закреплён ли бинарь за роутером ЯВНЫМ решением человека.
bin_pinned() { case " $BIN_KEEP " in *" $1 "*) return 0 ;; esac; return 1; }

# bin_deps <имя> — кто ОБЯЗАН жить рядом, иначе закрепление бессмысленно.
# hev (tun2socks) — общая несущая ВСЕХ трёх альтов: xray/hysteria/byedpi отдают socks, а
# tun-интерфейс поднимает hev, и закреплённый на роутере альт без hev всё равно не встанет
# тогда, когда флешки не окажется. Замер на BE7000 (20-МБ флеш): вернуть xray физически можно
# ТОЛЬКО вместе с hev и ТОЛЬКО в одиночку — после этого над резервом остаётся 192 КБ.
# Список ЖИВЁТ ЗДЕСЬ, рядом со STORE_MOVABLE: его спрашивают и движок оффлоада, и панель.
bin_deps() { case "$1" in xray|hysteria|byedpi) printf 'hev' ;; esac; }

# bin_dest <имя> — КУДА КЛАСТЬ новый бинарь (установка, обновление, миграция). Пара к bin_path:
# тот отвечает «откуда запускать» по факту, этот — «где место» по политике. Разные вопросы:
# хранилище может быть готово, а бинаря на нём ещё нет.
bin_dest() {
    if store_ready && store_movable "$1" && ! bin_pinned "$1"; then
        printf '%s' "$BIN_DIR/$1"
    else
        printf '%s' "$ENODIA_BIN/$1"
    fi
}

# bin_prune <имя> — снести копию, лежащую НЕ по bin_dest. Зовут все, кто положил бинарь сам
# (packages.sh после fetch-bin, установщик после mv): инвариант «копия РОВНО ОДНА» держится
# только так. Иначе обновление кладёт новый файл рядом со старым, а bin_path (он предпочитает
# накопитель) продолжает отдавать СТАРЫЙ — «обновил и ничего не изменилось».
bin_prune() {
    _bd=$(bin_dest "$1")
    if [ "$_bd" = "$ENODIA_BIN/$1" ]; then
        if [ "$BIN_DIR" != "$ENODIA_BIN" ]; then rm -f "$BIN_DIR/$1" 2>/dev/null; fi
    else
        rm -f "$ENODIA_BIN/$1" 2>/dev/null
    fi
    unset _bd
    return 0                    # best-effort: под set -e чистка не имеет права ронять вызывающего
}

# bin_install <откуда> <имя> — положить бинарь на его место одним движением (mv + exec-бит +
# prune). Для установщика, который раскладывает payload bin/*.user. mv, а не cp: на 20-МБ флеше
# важен ПИК, а не финальный размер. chmod best-effort — на exFAT/NTFS права задаёт монтирование
# (fmask=0000), и chmod там тихо не делает ничего.
bin_install() {
    _bd=$(bin_dest "$2")
    mkdir -p "${_bd%/*}" 2>/dev/null
    mv -f "$1" "$_bd" 2>/dev/null || { unset _bd; return 1; }
    chmod +x "$_bd" 2>/dev/null
    unset _bd
    bin_prune "$2"
    return 0
}
