#!/bin/sh
# subs-lib.sh — ОБЩИЙ слой подписок: реестр `.subs` + закачка тела + анти-SSRF.
#
# Зачем отдельным файлом. Раньше «скачать подписку» умела ровно одна точка — CGI `fetch_sub`
# (панель), потому что разбор тела жил в БРАУЗЕРЕ. С появлением headless-обновления по cron
# (`subs-update.sh`) потребителей стало два, а копировать гард от SSRF и детект gzip в оба —
# ровно та ситуация, из которой выросла грабля «stale lists-lib» (две копии разъехались).
# Поэтому: примитивы — здесь, потребители сорсят с шим-фолбэком (как ip-lib/dns-lib/router-lib).
#
# Формат реестра `$ENODIA_STATE/.subs` — строки «tag⇥url⇥label» (⇥=TAB, label последним: может
# содержать пробелы). URL = КРЕД: наружу (list/бэкап-без-секретов/diag) не отдаётся, работа
# с подпиской идёт по tag. Файл пишет только CGI (save_sub/rename_sub/edit_sub_url/remove_sub),
# здесь — только ЧТЕНИЕ: cron не должен трогать реестр (иначе гонка с панелью).

: "${ENODIA_STATE:=/data/usr/app/enodia-state}"
# Реестр подписок — ПЕРСИСТ, а прежнее имя переменной указывало на каталог КОДА. Алиас
# каталога — самая незаметная форма такой ошибки: слэша после него нет, поэтому его не
# видит ни grep по `$ENODIA_DIR/`, ни проверка C46. Имя теперь само говорит, где файл.
SUBS_STATE="$ENODIA_STATE"
# Имя WAN — у владельца (ip-lib.sh::wan_iface, следит C81): им биндится вторая попытка закачки
# подписки МИМО туннеля (sub_fetch). Шим = та же строка на случай частичной установки.
if [ -f "$ENODIA_DIR/ip-lib.sh" ]; then . "$ENODIA_DIR/ip-lib.sh"; fi
command -v wan_iface >/dev/null 2>&1 || wan_iface() { ip route show default 2>/dev/null | awk '/^default/{d=""; for(i=1;i<=NF;i++) if($i=="dev") d=$(i+1); if(d!="" && d !~ /^(awg|xtun)/){print d; exit}}'; }

SUBS_TAB=$(printf '\t')

# sub_ip_public <адрес> — ЛИТЕРАЛ адреса публичный? Вынесено из sub_host_public по двум
# причинам: тот же вердикт нужен КАЖДОМУ шагу редиректа (см. sub_get_once), и у IPv6 гарда
# не было вовсе — `http://[::1]:8088/…` проезжал мимо проверки целиком (имя с двоеточием шло
# в nslookup, тот литерал не резолвит, а «не зарезолвили» здесь трактуется как «пропускаем»).
sub_ip_public() {
	case "$1" in
		*:*)
			_l6=$(printf '%s' "$1" | tr 'A-Z' 'a-z')
			case "$_l6" in
				*::ffff:*.*.*.*) sub_ip_public "${_l6##*:}"; return $? ;;   # v4-mapped
				::|::1|0:0:0:0:0:0:0:1) return 1 ;;                         # loopback/unspecified
				fe8*:*|fe9*:*|fea*:*|feb*:*) return 1 ;;                    # link-local fe80::/10
				f[cd]*:*) return 1 ;;                                       # ULA fc00::/7
			esac
			return 0 ;;
	esac
	case "$1" in
		127.*|10.*|169.254.*|192.168.*|0.*|255.255.255.255) return 1 ;;
		172.16.*|172.17.*|172.18.*|172.19.*|172.2[0-9].*|172.3[0-1].*) return 1 ;;
	esac
	return 0
}

# sub_host_public <url> — хост URL публичный? Панель и cron ходят под root, поэтому ссылка
# подписки НЕ должна вести на внутренние сервисы (127.0.0.1:8088, роутер 192.168.31.1,
# cloud-metadata 169.254.169.254). Имя резолвим и проверяем полученный IP. 0 = публичный
# (можно), 1 = приватный/loopback/link-local (блок). Не зарезолвили — НЕ блокируем (curl всё
# равно не сходит; ложно отвергать легит-подписку при неготовом DNS не хотим).
sub_host_public() {
	_h=$(printf '%s' "$1" | sed -e 's|^[a-zA-Z][a-zA-Z0-9+.-]*://||' -e 's|[/?#].*$||' -e 's|^[^@]*@||' -e 's|\]:[0-9]*$|]|' -e 's|:[0-9]*$||' -e 's|^\[||' -e 's|\]$||')
	[ -n "$_h" ] || return 1
	case "$_h" in
		*:*)       _ip="$_h" ;;                       # IPv6-литерал (скобки уже сняты)
		*[!0-9.]*) _ip=$(nslookup "$_h" 2>/dev/null | awk '/^Name:/{f=1;next} f&&/Address/{x=$NF; if(x ~ /^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$/){print x; exit}}') ;;
		*)         _ip="$_h" ;;
	esac
	[ -n "$_ip" ] || return 0
	sub_ip_public "$_ip"
}

# Потолок тела подписки. Тело живёт в /tmp = ОЗУ, а 200 серверов — это десятки КБ: всё, что
# больше, либо не подписка, либо злой умысел. Ограничение НУЖНО в двух местах — на закачке и на
# РАСПАКОВКЕ: «1 КБ архива → гигабайт распакованного» кладёт роутер целиком, а gunzip мы зовём
# на любом теле (магию байтов не читаем — `od` в busybox нет).
SUB_MAXSIZE=${SUB_MAXSIZE:-4194304}

# --- ОСТАТОК ПОДПИСКИ: заголовок `subscription-userinfo` ---------------------------------------
# Сколько трафика осталось и когда кончается срок, провайдер сообщает РОВНО ОДНИМ способом —
# заголовком ОТВЕТА на ту же закачку: `subscription-userinfo: upload=…; download=…; total=…;
# expire=…` (де-факто стандарт v2board и совместимых панелей). В ТЕЛЕ подписки этих чисел нет
# вовсе, а отдельный запрос ради заголовка — это второй поход в сеть за тем же ответом, который у
# части провайдеров ещё и считается обращением. Поэтому ловим его ТУТ ЖЕ, на закачке тела.
# Цифры И потолок длины: число сюда пишет ЧУЖОЙ сервер, а арифметика у busybox 64-битная —
# «total=99999999999999999999999» дальше поехало бы в вычитание остатка и в JSON панели.
sub_ui_num() {
	case "$1" in ''|*[!0-9]*) printf '0'; return ;; esac
	[ "${#1}" -le 18 ] && printf '%s' "$1" || printf '0'
}

# sub_userinfo_read <файл-дампа-заголовков> — разобрать заголовок в SUB_UI_*.
# SUB_UI_HAVE=1 ТОЛЬКО когда заголовок ПРИШЁЛ: `total=0` у провайдера значит «трафик без лимита»,
# и отличить это от «провайдер лимитов не сообщает» можно ровно по ФАКТУ заголовка — иначе панель
# нарисовала бы «осталось 0» там, где ограничения нет вовсе.
sub_userinfo_read() {
	SUB_UI_HAVE=0; SUB_UI_UP=0; SUB_UI_DOWN=0; SUB_UI_TOTAL=0; SUB_UI_EXP=0
	[ -s "$1" ] || return 1
	# ПОТОЛОК НА ДАМП — по той же причине, что SUB_MAXSIZE на тело: заголовки пишет чужой сервер,
	# они лежат в /tmp (ОЗУ), и `--max-filesize` их НЕ ограничивает. Настоящий дамп — единицы
	# килобайт; всё, что крупнее, разбирать незачем (а сам файл вызыватель снимет сразу после).
	_uz=$(wc -c < "$1" 2>/dev/null); case "$_uz" in ''|*[!0-9]*) _uz=0 ;; esac
	[ "$_uz" -le 262144 ] || return 1
	# tail -1 — дамп несёт заголовки ВСЕХ ответов цепочки (у curl `-D` пишет и промежуточные 30x):
	# значение даёт последний, тот, чьё тело мы и взяли. `tr 'A-Z;' 'a-z '` разом снимает регистр
	# ключей и превращает разделитель в пробел — дальше хватает обычного разбиения на слова.
	_ui=$(grep -i '^subscription-userinfo:' "$1" 2>/dev/null | tail -1 | cut -d: -f2- | tr -d ' \r\n' | tr 'A-Z;' 'a-z ')
	[ -n "$_ui" ] || return 1
	SUB_UI_HAVE=1
	# Режем строку САМИ, а не `for _kv in $_ui`: неквотированное раскрытие проходит ГЛОББИНГ, и
	# звёздочка в заголовке (его пишет чужой сервер) превратилась бы в список файлов текущего
	# каталога. `set -f` здесь не годится — библиотеку сорсят чужие скрипты, и менять им режим
	# шелла мы не вправе.
	while [ -n "$_ui" ]; do
		_kv=${_ui%% *}; _ui=${_ui#"$_kv"}; _ui=${_ui# }
		case "$_kv" in
			upload=*)   SUB_UI_UP=$(sub_ui_num "${_kv#upload=}") ;;
			download=*) SUB_UI_DOWN=$(sub_ui_num "${_kv#download=}") ;;
			total=*)    SUB_UI_TOTAL=$(sub_ui_num "${_kv#total=}") ;;
			expire=*)   SUB_UI_EXP=$(sub_ui_num "${_kv#expire=}") ;;
		esac
	done
	return 0
}

# --- ЧТО ПОДПИСКА СООБЩИЛА О СЕБЕ: `$ENODIA_STATE/.sub-info` -----------------------------------
# Строки «tag⇥ok_ts⇥err_ts⇥have⇥upload⇥download⇥total⇥expire» (⇥=TAB).
#   ok_ts  — когда тело подписки скачалось В ПОСЛЕДНИЙ РАЗ; это возраст ЧИСЕЛ, а не строки;
#   err_ts — когда сорвалось последнее обновление (0 = последнее прошло);
#   have   — приходил ли заголовок вообще (см. sub_userinfo_read).
# ДВЕ ОТМЕТКИ, А НЕ ОДНА, и это не педантизм: числа провайдера стареют вместе с ЗАКАЧКОЙ, а сбой —
# событие другого дня. С одной отметкой карточка либо старила бы свежие числа («данные 3 дня
# назад» сразу после успешной закачки), либо выдавала месячной давности остаток за сегодняшний.
# ЧИСЛА ПЕРЕЖИВАЮТ СБОЙ НАМЕРЕННО: не скачалось — остаток не изменился, изменился лишь его
# возраст. А вот успешная закачка БЕЗ заголовка числа СНИМАЕТ: провайдер перестал их сообщать.
sub_info_put() {
	_pt="$1"; _ps="$2"
	case "$_pt" in ''|*[!a-z0-9-]*) return 1 ;; esac
	_pf="$SUBS_STATE/.sub-info"
	_pok=0; _perr=0; _phv=0; _pup=0; _pdn=0; _ptt=0; _pex=0
	# Прежнюю строку читаем ЦИКЛОМ ИЗ ФАЙЛА, а не `grep | read`: труба — подоболочка, и все семь
	# полей умерли бы вместе с ней (та же грабля, из-за которой mount-lib отдаёт итог переменными).
	if [ -f "$_pf" ]; then
		while IFS="$SUBS_TAB" read -r _pk _a1 _a2 _a3 _a4 _a5 _a6 _a7 || [ -n "$_pk" ]; do
			[ "$_pk" = "$_pt" ] || continue
			_pok=$_a1; _perr=$_a2; _phv=$_a3; _pup=$_a4; _pdn=$_a5; _ptt=$_a6; _pex=$_a7
		done < "$_pf"
	fi
	# Каждое поле — только цифры: файл переживает обновление, и одна битая строка (обрезанная
	# запись, правка руками) иначе уехала бы в JSON панели как есть.
	case "$_pok"  in ''|*[!0-9]*) _pok=0  ;; esac
	case "$_perr" in ''|*[!0-9]*) _perr=0 ;; esac
	case "$_phv"  in 0|1) : ;; *) _phv=0  ;; esac
	case "$_pup"  in ''|*[!0-9]*) _pup=0  ;; esac
	case "$_pdn"  in ''|*[!0-9]*) _pdn=0  ;; esac
	case "$_ptt"  in ''|*[!0-9]*) _ptt=0  ;; esac
	case "$_pex"  in ''|*[!0-9]*) _pex=0  ;; esac
	_pnow=$(date +%s 2>/dev/null | tr -cd '0-9'); [ -n "$_pnow" ] || _pnow=0
	if [ "$_ps" = ok ]; then
		_pok=$_pnow; _perr=0
		_phv=${SUB_UI_HAVE:-0}; _pup=${SUB_UI_UP:-0}; _pdn=${SUB_UI_DOWN:-0}
		_ptt=${SUB_UI_TOTAL:-0}; _pex=${SUB_UI_EXP:-0}
	else
		_perr=$_pnow
	fi
	{ [ -f "$_pf" ] && grep -v "^$_pt$SUBS_TAB" "$_pf" 2>/dev/null
	  printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$_pt" "$_pok" "$_perr" "$_phv" "$_pup" "$_pdn" "$_ptt" "$_pex"
	# ИМЯ ВРЕМЕННОГО — С ПИДОМ И С ХВОСТОМ `.new`, и оба нужны. Пид: писателей ДВА и без общего
	# лока (cron и CGI импорта), а с общим именем один успел бы сделать `mv` НЕДОПИСАННОГО файла
	# другого — это уже не потеря отметки, а битая строка. Хвост: `*.new` — то, что `clean.sh`
	# знает как мусор, а обрыв процесса ровно между записью и `mv` иначе оставил бы на флеше
	# файл, которого не опознаёт никто.
	} > "$_pf.$$.new" 2>/dev/null && mv "$_pf.$$.new" "$_pf" 2>/dev/null
	rm -f "$_pf.$$.new" 2>/dev/null
	return 0
}

# sub_info_drop <tag> — снять строку подписки (её удалили). Осиротевшая строка жила бы вечно и
# всплыла бы счётчиками чужой подписки, если тег когда-нибудь заведут заново.
sub_info_drop() {
	_dt="$1"; _df="$SUBS_STATE/.sub-info"
	case "$_dt" in ''|*[!a-z0-9-]*) return 1 ;; esac
	[ -f "$_df" ] || return 0
	grep -v "^$_dt$SUBS_TAB" "$_df" > "$_df.$$.new" 2>/dev/null
	mv "$_df.$$.new" "$_df" 2>/dev/null || rm -f "$_df.$$.new" 2>/dev/null
	return 0
}

# sub_get_once <url> <файл> [доп. опции curl] — одна попытка со следованием редиректам ВРУЧНУЮ.
# Почему не `-L --max-redirs 3`: короткая цепочка от подмены не защищает НИСКОЛЬКО — гард
# sub_host_public проверяет только ИСХОДНУЮ ссылку, а ОДНОГО хопа `Location: http://127.0.0.1:8088/…`
# довольно, чтобы root-curl сходил во внутренний сервис (комментарий тут прежде утверждал
# обратное). Теперь каждый хоп проходит тот же гард ДО перехода.
# `-f` намеренно НЕТ: тело ошибки провайдера («No keys available after processing») читает
# update_one и показывает человеку ЕГО СЛОВА вместо «не распознали серверов».
sub_get_once() {
	_gu="$1"; _go="$2"; shift 2
	_hop=0
	while [ "$_hop" -le 3 ]; do
		sub_host_public "$_gu" || return 1
		# Дамп заголовков — рядом с телом и на КАЖДОМ хопе заново: остаток подписки приезжает
		# заголовком того ответа, чьё тело мы взяли (см. sub_userinfo_read). Снимает файл
		# ВЫЗЫВАТЕЛЬ (sub_fetch) — он же и единственный, кто его читает.
		rm -f "$_go" "$_go.hdr" 2>/dev/null
		_loc=$(curl -s --max-time 25 --max-filesize "$SUB_MAXSIZE" -A "enodia-panel/1.0" \
			"$@" -D "$_go.hdr" -o "$_go" -w '%{redirect_url}' "$_gu" 2>/dev/null)
		[ -n "$_loc" ] || break
		_gu="$_loc"; _hop=$((_hop+1))
	done
	# --max-filesize молчит, когда сервер не сказал Content-Length (chunked), поэтому размер
	# сверяем и по факту: усечь по месту нечем (тело пишет сам curl), но принять — тем более.
	if [ -s "$_go" ]; then
		_sz=$(wc -c < "$_go" 2>/dev/null); case "$_sz" in ''|*[!0-9]*) _sz=0 ;; esac
		[ "$_sz" -gt "$SUB_MAXSIZE" ] && { rm -f "$_go" 2>/dev/null; return 1; }
	fi
	[ -s "$_go" ]
}

# sub_fetch <url> <файл> [доп. опции curl] — скачать тело подписки в файл. Возврат 0 = непустое тело.
# Доп. опции нужны НЕ подписке, а второму потребителю — пакетному импорту списка доменов/адресов из
# панели: там `-f` ОБЯЗАТЕЛЕН. Для подписки тело ошибки осмысленно (её показывают человеку словами
# провайдера), а для списка страница 404 — это «список», и её текст молча превращается в правила
# (замер: из типовой строки ошибки парсер достаёт ДВА «домена»). Один загрузчик, разная политика
# у вызывающего — вместо второй копии закачки.
# Тело качаем В ФАЙЛ, а не в переменную: часть панелей (durev) отдаёт gzip БЕЗУСЛОВНО, а
# NUL-байты обрезали бы shell-переменную. `od` в busybox НЕТ ⇒ магию байтов не читаем, а
# ПРОБУЕМ разжать (удалось + непусто ⇒ был gzip).
#
# ДВЕ ПОПЫТКИ, и это не перестраховка (замер на живом BE7000 29.07.2026): хост подписки часто
# сам лежит в `iplist_set` (opencck) ⇒ router-локальный curl метится в mangle OUTPUT и уходит
# ВНУТРЬ ТУННЕЛЯ, а VPS этот хост не отдаёт — `http=000` при живой подписке. Тот же корень, что
# у пинга серверов подписки. Порядок попыток осознан: сперва как есть (у кого подписка ЗАБЛОКИРОВАНА
# провайдером, её достаёт как раз туннель), затем принудительно через WAN (`--interface` = SO_BINDTODEVICE,
# мимо fwmark-роутинга).
sub_fetch() {
	_u="$1"; _o="$2"
	[ -n "$_u" ] && [ -n "$_o" ] || return 1
	shift 2
	rm -f "$_o" "$_o.gz" "$_o.hdr" 2>/dev/null
	SUB_FETCH_VIA=""
	SUB_UI_HAVE=0; SUB_UI_UP=0; SUB_UI_DOWN=0; SUB_UI_TOTAL=0; SUB_UI_EXP=0
	sub_get_once "$_u" "$_o" "$@"
	if [ ! -s "$_o" ]; then
		# Имя WAN — у владельца (ip-lib.sh::wan_iface, следит C81). До 05.09.2026 тут стояло
		# `ip route get 8.8.8.8`: в awg-режиме плагин кладёт `<DNS>/32 dev awg0`, и при `DNS = 8.8.8.8`
		# в конфиге «вторая попытка через WAN» биндилась В туннель — ровно в том случае, ради
		# которого заведена (хост подписки ∈ iplist_set, VPS его не отдаёт).
		_wan=$(wan_iface)
		if [ -n "$_wan" ]; then
			sub_get_once "$_u" "$_o" "$@" --interface "$_wan"
			[ -s "$_o" ] && SUB_FETCH_VIA="$_wan"
		fi
	fi
	# Заголовки разбираем ДО любого выхода и тут же снимаем файл: дамп лежит в /tmp, то есть в
	# ОЗУ, и уйти по `return`, оставив его, нельзя (та же причина, по которой у нас есть trap на
	# каталог прогона). Пустой/отсутствующий дамп = «заголовка не было» — SUB_UI_* уже обнулены.
	sub_userinfo_read "$_o.hdr"
	rm -f "$_o.hdr" 2>/dev/null
	[ -s "$_o" ] || { rm -f "$_o" 2>/dev/null; return 1; }
	if gunzip -c "$_o" 2>/dev/null | head -c "$SUB_MAXSIZE" > "$_o.gz" && [ -s "$_o.gz" ]; then
		mv "$_o.gz" "$_o"
	else
		rm -f "$_o.gz" 2>/dev/null
	fi
	[ -s "$_o" ]
}

# sub_tags — все теги реестра (по одному в строке).
sub_tags() { [ -f "$SUBS_STATE/.subs" ] && cut -d"$SUBS_TAB" -f1 "$SUBS_STATE/.subs" 2>/dev/null; }
# sub_url_of <tag> / sub_label_of <tag> — поля реестра (пусто = подписки нет).
sub_url_of()   { [ -f "$SUBS_STATE/.subs" ] && grep "^$1$SUBS_TAB" "$SUBS_STATE/.subs" 2>/dev/null | head -1 | cut -d"$SUBS_TAB" -f2; }
sub_label_of() { [ -f "$SUBS_STATE/.subs" ] && grep "^$1$SUBS_TAB" "$SUBS_STATE/.subs" 2>/dev/null | head -1 | cut -d"$SUBS_TAB" -f3-; }

# sub_owner_tag <имя-конфига> — ЧЬЯ это подписка. Теги бывают префиксами друг друга
# («liberty» ⊂ «liberty-vpn»), а «-» встречается и ВНУТРИ тега ⇒ голый префикс `sub-<tag>-`
# ловит чужие файлы. Владелец = ДЛИННЕЙШИЙ подходящий тег среди всех тегов реестра
# (зеркало ownerTag() в panel.js и del_sub_configs в cgi-bin/action).
sub_owner_tag() {
	_b="$1"; _own=""; _ol=-1
	for _g in $(sub_tags); do
		case "$_b" in sub-"$_g"-*) _gl=${#_g}; [ "$_gl" -gt "$_ol" ] && { _own="$_g"; _ol=$_gl; } ;; esac
	done
	printf '%s' "$_own"
}

# sub_names_keep_other <tag> [файл] — строки `.sub-names`, владелец которых НЕ <tag> (stdout).
# Голый `grep -v "^sub-<tag>-"` здесь ошибочен ровно по причине sub_owner_tag, и цена ошибки
# выше, чем у конфигов: `.sub-names` — КАРТА ИДЕНТИЧНОСТИ, по ней сервер находит СВОЙ файл.
# Потеряв строку, следующий прогон заводит серверу НОВЫЙ файл, а старый (если он активный —
# его prune_stale намеренно не трогает) остаётся сиротой и не обновляется больше никогда.
# Замерено на живом роутере: теги «liberty» и «liberty-vpn», активный `sub-liberty-vpn-12`
# без строки имени. Тег передаём явно — в remove_sub его в реестре уже нет.
# Строки с ЧУЖИМ/неопознанным владельцем сохраняем: чистим только своё.
sub_names_keep_other() {
	_kt="$1"; _nf="${2:-$SUBS_STATE/.sub-names}"
	[ -f "$_nf" ] || return 0
	_tl=$(sub_tags 2>/dev/null | tr '\n' ' ')
	case " $_tl " in *" $_kt "*) : ;; *) _tl="$_tl $_kt" ;; esac
	# read БЕЗ хвостового перевода строки теряет последнюю запись (busybox, замерено) ⇒ `|| [ -n ]`.
	while IFS= read -r _ln || [ -n "$_ln" ]; do
		[ -n "$_ln" ] || continue
		_nb=${_ln%%"$SUBS_TAB"*}; _own=""; _ol=-1
		for _g in $_tl; do
			case "$_nb" in sub-"$_g"-*) _gl=${#_g}; [ "$_gl" -gt "$_ol" ] && { _own="$_g"; _ol=$_gl; } ;; esac
		done
		[ "$_own" = "$_kt" ] && continue
		printf '%s\n' "$_ln"
	done < "$_nf"
	return 0
}

# sub_sum_cut <лимит байт> — сводка прогона (stdin) → строка для `.subs-last`, не длиннее лимита. РЕЖЕМ ПО ЗАПИСИ, А НЕ
# ПО БАЙТУ: сводка — цепочка ««метка»: …. » на КАЖДУЮ подписку, и прежний `cut -c1-300` на четвёртой подписке обрывал
# слово (««aps-test»: серверо»). Обрывок ещё и ломал перевод: правила панели берут запись целиком, и кириллический хвост
# возвращал под английским ВСЮ строку по-русски (приёмка 24.09.2026, живой BE7000). Что не влезло — многоточием, а не
# молча. Граница записи — «. «» (точка, пробел и кавычка следующей метки), а не любая «. »: точка с пробелом бывает и внутри
# записи — в метке («Mr. Proxy») и в причине сбоя, — и тогда висело бы начало записи с незакрытой «ёлочкой» (ревью приёмки,
# круг 1). Запись длиннее лимита (длинная причина сбоя) режем по последнему пробелу: он всегда стоит ПЕРЕД недобитой
# буквой, которую оставил бы `cut -c` (у busybox он режет байтами). Длину меряем арифметикой: `wc -c` у busybox
# печатает число с отступом, а `[` такое число числом не считает.
sub_sum_cut() {
	_sc=$(tr -d '\t\r\n')
	# Хвостовые пробелы — вон: записи сводки кончаются «. », и последний пробел уезжал в `.subs-last` (ревью приёмки, круг 3).
	_sc="${_sc%"${_sc##*[! ]}"}"
	_sn=$(printf '%s' "$_sc" | wc -c)
	[ $((_sn)) -le "$1" ] && { printf '%s' "$_sc"; return 0; }
	_sc=$(printf '%s' "$_sc" | cut -c1-$(($1 - 4)))
	case "$_sc" in
		*'. «'*) _sc="${_sc%. «*}." ;;
		*' '*)  _sc="${_sc% *}" ;;
		*)      _sc='' ;;
	esac
	printf '%s …' "$_sc"
}
