#!/bin/sh
# totp.sh — ВХОД В ПАНЕЛЬ: пароль (первый фактор), TOTP RFC 6238 (второй) и сессии панели.
#
# ЗАЧЕМ СВОЯ ФОРМА, А НЕ HTTP-Basic (03.09.2026). Basic проверял сам uhttpd, и это стоило трёх
# вещей: 1) перебор пароля НЕ ТОРМОЗИЛСЯ — 401 отдаёт uhttpd внутри одного keep-alive, до CGI
# попытка не доезжает, счётчику негде жить; 2) хэш обязан был быть `$1$` — сверял его musl-crypt
# панели, а с `$5$/$6$` uhttpd умирал на первом же входе (замер 23.08.2026); 3) «выйти» не бывает —
# браузер держит пароль до закрытия. Теперь пароль сверяем МЫ (cgi-bin/login → pw_verify), хэш
# считает и сверяет openssl, неудачи считает тот же totp_lock_*, что и у кода, а сессия —
# одна на оба фактора: у строки в .totp-sessions есть УРОВЕНЬ (1 = пароль принят, 2 = пароль +
# код). Второй фактор — код из приложения (Google Authenticator / Aegis / 1Password); он не рождает
# сессию, а ПОВЫШАЕТ парольную до уровня 2. Гейт: нет сессии → 403 need_login; уровень 1 при
# включённом TOTP → 403 need2fa. uhttpd к паролю больше не причастен — `-c` ему не давать (C38).
# WebAuthn/passkeys вместо TOTP невозможны без доменного имени (RP-ID по IP браузер не даёт),
# поэтому TOTP — не «промежуточный шаг», а единственный работающий по IP второй фактор.
#
# ПОЧЕМУ ГЕЙТ ГЛОБАЛЬНЫЙ, а не «только снаружи». Перед uhttpd стоит наш panel-tls, и до CGI
# доезжает REMOTE_ADDR терминатора (LAN-адрес роутера) — отличить «пришли из интернета» от
# «пришли из дома» панель НЕ МОЖЕТ ни при каких условиях. Поэтому 2FA либо включён для всех
# входов, либо выключен. НО СЧЁТЧИК НЕУДАЧ — ПЕР-АДРЕСНЫЙ, и это не противоречие: по голому HTTP
# в локалке REMOTE_ADDR настоящий, а за терминатором он один на всех — то есть адрес сам делит
# источники ровно там, где их вообще можно делить (см. totp_lock_key). Пер-адресный лимит
# СОЕДИНЕНИЙ снаружи живёт этажом ниже, в hashlimit цепочки PANEL_WAN (web-ui.sh).
#
# КРИПТО — БЕЗ НОВЫХ БИНАРЕЙ: HMAC-SHA1 считает стоковый openssl (1.1.1l), который уже
# вендорится ради notify.sh и сертификата panel-tls: `openssl dgst -sha1 -mac HMAC -macopt
# hexkey:<HEX>`. Ключ бинарный (в нём NUL-байты), поэтому строковый `-hmac` не годится, а
# 8-байтовый счётчик собираем восьмеричными escape'ами printf. Проверено вектором RFC 6238
# (секрет 12345678901234567890, T=59 → 287082) прямо на роутере.
#
# ЧАСЫ. RTC на роутере НЕТ: до ntpsetclock время = 1970 и код не сойдётся НИКОГДА. Врать
# «неверный код» в этом случае нельзя (человек начнёт сверять телефон) — verify возвращает
# отдельный код 2 «часы не синхронизированы», а панель показывает это прямым текстом.
# Коды восстановления от часов НЕ зависят и работают даже тогда.
#
# СЕССИИ — НА /data, А НЕ В /tmp. Иначе каждый ребут разлогинивал бы все устройства ровно в
# тот момент, когда часы ещё не синхронизированы (см. выше) — то есть войти было бы нечем,
# кроме кода восстановления. В файле лежит SHA-256 токена, а не сам токен: полный бэкап панели
# (cgi-bin/backup) собирается по whitelist и .totp* в него не входит, но и утечка файла не
# должна давать готовый ключ от панели. Строка: sha256⇥истекает⇥выдан⇥UA⇥адрес⇥уровень; строки
# БЕЗ уровня (до 03.09.2026) = 2: они рождались только после кода, а Basic к тому моменту был
# пройден браузером — обновление никого не разлогинивает. Пустые UA/адрес пишем как `-`: `read`
# схлопывает подряд идущие табы, и пустое поле В СЕРЕДИНЕ сдвинуло бы уровень на место адреса.
#
# ЕСЛИ ПОТЕРЯН ТЕЛЕФОН: 8 кодов восстановления (одноразовые, показываются один раз при
# включении) либо аварийный выключатель с роутера по SSH:  sh totp.sh disable --force

ENODIA_DIR=${ENODIA_DIR:-/data/usr/app/enodia}
ENODIA_STATE=${ENODIA_STATE:-/data/usr/app/enodia-state}

TOTP_SEC="$ENODIA_STATE/.totp"           # активный секрет: "hex b32 created"
TOTP_PEND="$ENODIA_STATE/.totp-pending"  # секрет в процессе привязки (до подтверждения кодом)
TOTP_REC="$ENODIA_STATE/.totp-recovery"  # sha256 кодов восстановления; использованный помечен '-'
TOTP_SESS="$ENODIA_STATE/.totp-sessions" # sha256(токен)⇥истекает⇥выдан⇥UA⇥адрес⇥уровень (см. «Сессии»)
TOTP_PASS="$ENODIA_STATE/.panel-pass"    # хэш пароля панели, ОДНА строка (см. «Первый фактор»)
TOTP_LEGACY_PASS="$ENODIA_DIR/web/uhttpd.conf"   # прежний файл Basic `/:admin:<хэш>` — только читаем и сносим
TOTP_UHTTPD=${UHTTPD:-/usr/sbin/uhttpd}  # ради `uhttpd -m`: бессолевые хэши старых установок и фолбэк без openssl
TOTP_COOKIE=enodia_session               # имя куки сессии; старую `panel2fa` гейт ещё читает (см. totp_cookie)
TOTP_LAST=/tmp/.enodia-totp-last         # анти-replay: последний ПРИНЯТЫЙ счётчик шагов
TOTP_FAIL=/tmp/.enodia-totp-fail         # "ключ неудач разблокировка отметка" на источник (RAM: ребут = чистый лист)
TOTP_CLOCK=/tmp/.enodia-clock-base   # момент загрузки по часам, какими они были ДО синхронизации (см. totp_sess_clock_fix)

TOTP_STEP=30                          # шаг TOTP, с (RFC 6238; менять нельзя — приложения ждут 30)
TOTP_WINDOW=1                         # ±1 шаг: покрывает расхождение часов телефона до 30 с
# СРОК СЕССИИ ВЫБИРАЕТ ЧЕЛОВЕК — галочкой «Запомнить меня» в форме входа (04.09.2026, ВКЛЮЧЕНА
# по умолчанию: панель домашняя, и до этой правки срок был безальтернативным). Отмечена — год,
# снята — 12 часов: «зашёл с чужого ноутбука, поправил, ушёл». Значения живут ЗДЕСЬ, а не в CGI:
# срок уходит в ДВА места сразу (строка сессии на роутере и Max-Age куки в браузере), и разъехаться
# им нельзя — браузер держал бы ключ от несуществующей сессии либо забывал живую.
TOTP_SESS_TTL=31536000                # год — «запомнить меня» (он же срок по умолчанию: галочка
                                      # включена, а панель из кэша браузера поля вовсе не пришлёт)
TOTP_SESS_TTL_SHORT=43200             # 12 часов — галочка снята
TOTP_SESS_MAX=32                      # потолок ЧИСЛА входов в файле (см. totp_sess_trim)
TOTP_REC_N=8                          # кодов восстановления
TOTP_MAX_FAILS=5                      # после стольких неудач подряд включается пауза
TOTP_LOCK_CAP=900                     # потолок паузы, с (15 мин): дальше удваивать бессмысленно
TOTP_LOCK_TTL=900                     # сколько помним источник ПОСЛЕ последней неудачи (см. totp_lock_put)
TOTP_LOCK_MAX=64                      # потолок строк в файле паузы: перебиратель со сменой адреса его не раздует

TOTP_B32A=ABCDEFGHIJKLMNOPQRSTUVWXYZ234567

totp_now() { date +%s 2>/dev/null; }

# Часы «настоящие»? Тот же порог, что у выписки сертификата в web-ui.sh: до синхронизации на
# роутере 1970 год, и любое время-зависимое решение в этот момент — ложь. Порог — у владельца
# (clock-lib.sh::clock_sane, следит C82); шим той же строки — на случай payload без библиотеки.
if [ -f "$ENODIA_DIR/clock-lib.sh" ]; then . "$ENODIA_DIR/clock-lib.sh"; fi
# …и аптайм оттуда же (uptime_s, следит C83). Шим ОБЯЗАТЕЛЕН: без него на payload без библиотеки
# `uptime_s` это «command not found», totp_clock_base возвращает 1 — и сдвиг сессий после скачка
# часов не делается ВООБЩЕ, то есть человек, вошедший сразу после ребута, выпадает на форму входа
# через десять минут. Ровно то, ради чего сдвиг написан (ревью 2, 06.09.2026).
command -v uptime_s >/dev/null 2>&1 || uptime_s() { _cl_u=$(awk '{print int($1)}' /proc/uptime 2>/dev/null); case "$_cl_u" in ''|*[!0-9]*) _cl_u=999999999 ;; esac; echo "$_cl_u"; }
command -v clock_sane >/dev/null 2>&1 || clock_sane() { _csn=${1:-$(date +%s 2>/dev/null)}; case "$_csn" in ''|*[!0-9]*) return 1 ;; esac; [ "$_csn" -gt 1700000000 ] 2>/dev/null && [ "$_csn" -lt 4102444800 ] 2>/dev/null; }
totp_clock_ok() { clock_sane "$(totp_now)"; }

totp_enabled() { [ -s "$TOTP_SEC" ]; }

# ЗАВЕРШАЮЩИЙ `echo` ОБЯЗАТЕЛЕН: `tr -cd` съедает перевод строки вместе со всем «лишним», и
# без него `totp_sha256 >> файл` склеивал все хеши В ОДНУ СТРОКУ — восемь кодов восстановления
# превращались в один нераспознаваемый огрызок (grep по `^хеш$` не находил ни одного, а панель
# рапортовала «осталось 1»). Потребителям через `$(...)` перевод строки не мешает — он срезается.
totp_sha256() { printf '%s' "$1" | openssl dgst -sha256 2>/dev/null | sed 's/.*= *//' | tr -cd 'a-f0-9'; echo; }

# HMAC-SHA1(ключ_hex, счётчик) → 40 hex. Счётчик уходит в openssl ВОСЬМЕРИЧНЫМИ escape'ами:
# в 8-байтовом big-endian представлении почти всегда есть NUL, а через переменную shell такой
# байт не пронести — printf пишет его прямо в пайп.
totp_hmac_hex() {
	_c=$2; _esc=""; _i=8
	while [ "$_i" -gt 0 ]; do
		_b=$((_c % 256)); _c=$((_c / 256))
		_esc="\\$(printf '%03o' "$_b")$_esc"
		_i=$((_i - 1))
	done
	printf "$_esc" | openssl dgst -sha1 -mac HMAC -macopt hexkey:"$1" -hex 2>/dev/null |
		sed 's/.*= *//' | tr -cd 'a-f0-9'
}

# Динамическая усечка (RFC 4226 §5.4): младший полубайт последнего байта = смещение,
# оттуда 4 байта, старший бит гасим (знак), остаток от 10^6.
totp_code() {
	_h=$(totp_hmac_hex "$1" "$2")
	[ "${#_h}" -eq 40 ] || return 1
	_off=$(( 0x$(printf '%s' "$_h" | cut -c40) * 2 + 1 ))
	_p=$(printf '%s' "$_h" | cut -c"$_off"-$((_off + 7)))
	_v=$(( 0x$_p & 0x7fffffff ))
	printf '%06d' $((_v % 1000000))
}

# 40 hex (160 бит) → 32 символа base32 БЕЗ паддинга: 160 кратно 5, ровно как ждёт otpauth.
# Идём пятёрками hex (20 бит = 4 символа), чтобы уместиться в арифметику shell.
totp_b32() {
	_h="$1"; _out=""; _i=1
	while [ "$_i" -le 40 ]; do
		_v=$(( 0x$(printf '%s' "$_h" | cut -c"$_i"-$((_i + 4))) ))
		for _s in 15 10 5 0; do
			_n=$(( (_v >> _s) & 31 ))
			_out="$_out$(printf '%s' "$TOTP_B32A" | cut -c$((_n + 1)))"
		done
		_i=$((_i + 5))
	done
	printf '%s' "$_out"
}

totp_secret_hex() { [ -s "$TOTP_SEC" ] || return 1; read _hx _rest < "$TOTP_SEC"; printf '%s' "$_hx"; }
totp_secret_b32() { [ -s "$TOTP_SEC" ] || return 1; read _hx _b3 _rest < "$TOTP_SEC"; printf '%s' "$_b3"; }

# --- Первый фактор: ПАРОЛЬ панели --------------------------------------------
# Хранилище — ОДНА строка с хэшем в $ENODIA_STATE (переживает обновление кода, в бэкап НЕ входит:
# бэкап не должен быть обходом входа, а хэш с бэкапа вскрывают офлайн). Прежний файл Basic лежал
# ВНУТРИ docroot и без Basic скачивался бы по `/uhttpd.conf` — потому миграция его СНОСИТ, а не
# оставляет «на всякий случай» (путь назад — `web-ui.sh setpass`, пароль хозяин знает).
# СХЕМА — ПО ФАКТУ, ЧТО УМЕЕТ OPENSSL ЭТОЙ ПРОШИВКИ, и она РАЗНАЯ (замер 03.09.2026: BE7000 —
# OpenSSL 1.1.1l, `passwd -6` есть; AX3600 — 1.0.2q, `-6`/`-5` НЕТ ВООБЩЕ, там остаётся `$1$`).
# Обещать `$6$` в доках и подсказках поэтому нельзя — правду печатает `dump.sh`. Порядок попыток:
# `$6$` (SHA-512, соль 16) → `$1$` (соль 8) →
# `uhttpd -m` (MD5 без соли — ровно то, что ставили старые установки). Сверка — той же командой с
# солью ИЗ хэша; бессолевой `$1$$` сверяем `uhttpd -m` (он детерминирован). ЛЮБОЙ не-`$6$` хэш
# ПЕРЕХЭШИРУЕМ при первом удачном входе (pw_upgrade): plaintext есть ровно в этот момент и больше
# никогда. Пароль — стдином, не argv (argv видна в /proc/<pid>/cmdline).
#
# ИМЯ ПОЛЬЗОВАТЕЛЯ У ПАНЕЛИ ОДНО И НЕ НАСТРАИВАЕТСЯ: учётных записей нет, вход — один пароль.
# Поле логина в форме существует РАДИ МЕНЕДЖЕРОВ ПАРОЛЕЙ: запись они ключуют парой «имя + адрес»,
# и поля со скрытым логином часть браузеров при сохранении игнорирует — поэтому оно ВИДИМОЕ
# (04.09.2026; до этого стояло 1×1 px и автосохранение срабатывало не везде). А раз поле видно и
# правится — мы обязаны его и ПРОВЕРЯТЬ: молча игнорировать введённое имя значит показывать
# человеку поле-обманку.
#
# НО ЭТО ЧЕСТНОСТЬ ЭКРАНА, А НЕ ЗАЩИТА, и разница видна в цене промаха: неудачной попыткой он
# НЕ считается (см. cgi-bin/login). Имя не секрет — его печатает сам отказ и оба README, — а
# перебиратель поле просто не пришлёт: ПУСТОЕ значение мы принимаем как своё, иначе не войдёт ни
# панель из браузерного кэша (у panel.js бампается только `?v=` сборки), ни ПК-скрипт прежней
# версии. Сверяем ПО БУКВАМ И ЦИФРАМ и без учёта регистра: `Admin` = `admin`. Значение к нам
# приходит уже РАСКОДИРОВАННЫМ (urldecode делает CGI) — иначе «admin » сравнивалось бы как
# «admin20» и отказ прилетал бы там, где имя верное.
#
# КОПИЙ ИМЕНИ ТРИ, и это не небрежность: истина и сверка здесь, `enodia.py` входит формой с ПК,
# `panel.js` подставляет имя в поле. Разъезд ловит проверка C76 (dev/check-consistency.ps1) —
# без неё смена имени в одном месте молча ломает вход с двух других.
PANEL_USER=admin
pw_user_ok() {                       # pw_user_ok <имя> → 0 если это логин панели (пусто = наш)
	[ -n "$1" ] || return 0
	# ОБЕ стороны через один конвейер. Приводили только введённое — и тогда `PANEL_USER=Admin`
	# (или `my.admin`) не проходил СОБСТВЕННУЮ сверку: вход становился невозможен ни из панели, ни
	# с ПК, а выглядело это как «пароль не тот». Имя тут не секрет, сравнение мягкое сознательно.
	_pu_u=$(printf '%s' "$1" | tr -cd 'A-Za-z0-9' | tr 'A-Z' 'a-z')
	_pu_o=$(printf '%s' "$PANEL_USER" | tr -cd 'A-Za-z0-9' | tr 'A-Z' 'a-z')
	[ -n "$_pu_o" ] && [ "$_pu_u" = "$_pu_o" ]
}
pw_salt() {                          # pw_salt <длина> — алфавит соли crypt `./0-9A-Za-z`
	_sl=$(dd if=/dev/urandom bs=12 count=1 2>/dev/null | openssl base64 2>/dev/null | tr -d '\n' | tr '+' '.' | cut -c1-"$1")
	case "$_sl" in *[!A-Za-z0-9./]*) _sl="" ;; esac
	[ "${#_sl}" -eq "$1" ] || _sl=""
	printf '%s' "$_sl"
}
pw_hash() {                          # pw_hash <пароль> → хэш (stdout); пусто = не вышло
	_ph_h=""; _ph_s=$(pw_salt 16)
	if [ -n "$_ph_s" ]; then
		_ph_h=$(printf '%s' "$1" | openssl passwd -6 -salt "$_ph_s" -stdin 2>/dev/null)
		case "$_ph_h" in '$6$'*'$'?*) : ;;
			*) _ph_h=$(printf '%s' "$1" | openssl passwd -1 -salt "$(printf '%s' "$_ph_s" | cut -c1-8)" -stdin 2>/dev/null) ;;
		esac
		case "$_ph_h" in '$6$'*'$'?*|'$1$'*'$'?*) : ;; *) _ph_h="" ;; esac
	fi
	[ -n "$_ph_h" ] || _ph_h=$("$TOTP_UHTTPD" -m "$1" 2>/dev/null)
	case "$_ph_h" in '$'?'$'*) printf '%s\n' "$_ph_h" ;; *) return 1 ;; esac
}
pw_stored() {                        # хэш из хранилища (пусто = пароля нет); легаси-файл — фолбэк
	if [ -s "$TOTP_PASS" ]; then head -1 "$TOTP_PASS" | tr -d '\r\n'
	elif [ -s "$TOTP_LEGACY_PASS" ]; then head -1 "$TOTP_LEGACY_PASS" | tr -d '\r\n' | cut -d: -f3-
	fi
}
pw_exists() { [ -n "$(pw_stored)" ]; }
pw_write() {                         # pw_write <хэш> — атомарно, 600
	[ -n "$1" ] || return 1
	mkdir -p "$ENODIA_STATE" 2>/dev/null
	( umask 077; printf '%s\n' "$1" > "$TOTP_PASS.tmp" ) && mv "$TOTP_PASS.tmp" "$TOTP_PASS" || return 1
	chmod 600 "$TOTP_PASS" 2>/dev/null
	return 0
}
pw_set() { pw_write "$(pw_hash "$1")"; }              # pw_set <пароль>
# ЛЕГАСИ-ФАЙЛ СНОСИТ ТОЛЬКО ЭТА ФУНКЦИЯ, и зовёт её РОВНО ОДИН вызыватель — `web-ui.sh start`, то
# есть код, который прямо сейчас поднимет uhttpd БЕЗ `-c`. Сносил его pw_write, а pw_write зовёт и
# вход по паролю: в смешанном обновлении (новый totp.sh + СТАРЫЙ web-ui.sh) живой uhttpd поднят с
# `-c web/uhttpd.conf`, и его `start` этот файл ТРЕБУЕТ — первый же вход удалял бы файл, а ближайший
# ребут оставлял роутер БЕЗ ПАНЕЛИ навсегда (чинится только по SSH). Пока Basic жив, файл и не
# утечёт: он лежит за самим Basic; а без Basic на него уже никто не смотрит.
pw_migrate() {                       # легаси uhttpd.conf → .panel-pass (зовёт web-ui.sh start); 0 = есть куда входить
	if [ -s "$TOTP_PASS" ]; then rm -f "$TOTP_LEGACY_PASS" 2>/dev/null; return 0; fi
	[ -s "$TOTP_LEGACY_PASS" ] || return 1
	pw_write "$(pw_stored)" || return 1
	rm -f "$TOTP_LEGACY_PASS" 2>/dev/null
	return 0
}
pw_verify() {                        # pw_verify <пароль> → 0 принят · 1 нет · 2 пароль не задан
	_pv_h=$(pw_stored); [ -n "$_pv_h" ] || return 2
	_pv_c=""
	case "$_pv_h" in
		'$1$$'*) _pv_c=$("$TOTP_UHTTPD" -m "$1" 2>/dev/null) ;;
		'$6$'*)  _pv_s=${_pv_h#\$6\$}; _pv_s=${_pv_s%%\$*}; _pv_c=$(printf '%s' "$1" | openssl passwd -6 -salt "$_pv_s" -stdin 2>/dev/null) ;;
		'$5$'*)  _pv_s=${_pv_h#\$5\$}; _pv_s=${_pv_s%%\$*}; _pv_c=$(printf '%s' "$1" | openssl passwd -5 -salt "$_pv_s" -stdin 2>/dev/null) ;;
		'$1$'*)  _pv_s=${_pv_h#\$1\$}; _pv_s=${_pv_s%%\$*}; _pv_c=$(printf '%s' "$1" | openssl passwd -1 -salt "$_pv_s" -stdin 2>/dev/null) ;;
	esac
	[ -n "$_pv_c" ] && [ "$_pv_c" = "$_pv_h" ]
}
# «ХЭШ ПОРА ПЕРЕПИСАТЬ?» — ВСЁ, ЧТО НЕ `$6$`: и бессолевой `$1$$` от `uhttpd -m`, и СОЛЁНЫЙ `$1$`,
# доставшийся миграцией из web/uhttpd.conf. Прежняя проверка знала только первый, и установка,
# пришедшая с Basic, оставалась на MD5-crypt НАВСЕГДА (замер на AX3600 03.09.2026: в .panel-pass
# лежал ровно `$1$<соль>$`). Момент перехэша единственный — успешный вход: plaintext есть только там.
pw_needs_upgrade() { case "$(pw_stored)" in ''|'$6$'*) return 1 ;; esac; return 0; }
# СЧИТАЕМ ТОЛЬКО СИЛЬНУЮ ФОРМУ, а не зовём pw_hash: у того ЦЕПОЧКА ФОЛБЭКОВ, и на прошивке без
# `openssl passwd -6` она кончается `uhttpd -m "<пароль>"` — паролем В ARGV, видной в /proc. Для
# разового setpass это осознанный компромисс, но здесь мы бежим на КАЖДОМ входе, и повторять
# засветку ради хэша ТОЙ ЖЕ стойкости не за что. Не вышло `$6$` — молча уходим (см. замер выше).
pw_upgrade() {                       # pw_upgrade <пароль> — 0 = переписали на $6$
	pw_needs_upgrade || return 1
	_pu_s=$(pw_salt 16); [ -n "$_pu_s" ] || return 1
	_pu_h=$(printf '%s' "$1" | openssl passwd -6 -salt "$_pu_s" -stdin 2>/dev/null)
	case "$_pu_h" in '$6$'*'$'?*) : ;; *) return 1 ;; esac
	pw_write "$_pu_h"
}

# --- Пауза после неудач ------------------------------------------------------
# Растёт удвоением от 60 с, потолок 15 мин: перебор становится безнадёжным, а хозяин теряет
# максимум четверть часа (и всегда может войти кодом восстановления).
#
# СЧЁТЧИК ПЕР-АДРЕСНЫЙ (03.09.2026). Общий на панель отдавал ЛЮБОМУ в домашней сети рубильник:
# `cgi-bin/token` открыт, пять неверных паролей — и хозяин не войдёт, а дальше один запрос в
# четверть часа держит панель закрытой сколько угодно (лечится только по SSH). С HTTP-Basic такого
# не было вовсе — тормозить перебор мы стали сами, вместе с формой входа, и вместе с ним завезли
# этот отказ в обслуживании.
# РАЗДЕЛЯЕТ ИСТОЧНИКИ САМ АДРЕС, БЕЗ ЕДИНОГО НОВОГО ДЕТЕКТОРА: по голому HTTP до CGI доезжает
# настоящий REMOTE_ADDR клиента, а за нашим panel-tls — адрес терминатора, ОДИН И ТОТ ЖЕ у всех,
# кто пришёл по HTTPS (в том числе снаружи). Значит внешние перебиратели по-прежнему делят один
# счётчик — ровно то, ради чего он и заводился, — а сосед по локалке запирает только себя.
# Пустой адрес (CLI по SSH) получает свой ключ: у хозяина с root-доступом паузе учить некого.
# ЧЕГО ЭТО НЕ ДАЁТ: определившийся перебиратель В ЛОКАЛКЕ меняет свой адрес сам, и от НЕГО
# пер-адресный счётчик не спасает — он спасает от того, что этот перебиратель запирает ХОЗЯИНА.
# Тормозить того, кто уже в локалке и волен менять адрес, нечем в принципе.
# И ВТОРОЕ, ЧЕГО НЕ ДАЁТ (поведение ПРЕЖНЕЕ, не регресс): счётчик читается и пишется двумя
# командами, поэтому ОДНОВРЕМЕННЫЕ неудачи считаются за одну. ЗАМЕР на железе 03.09.2026: шесть
# попыток парами дали 3 — то есть скидка равна тому, сколько запросов панель успевает обработать
# бок о бок; чему равен этот потолок, мы НЕ мерили. На 8–64-символьном пароле не решает ничего.
# Лока не заводим сознательно: он потребовал бы дробного sleep, а он в busybox опционален, и
# цена ошибки (вход, который ЖДЁТ) хуже скидки.
totp_lock_key() {
	_lk=$(printf '%s' "${REMOTE_ADDR:-}" | tr -cd '0-9A-Fa-f.:' | cut -c1-45)
	[ -n "$_lk" ] || _lk=cli
	printf '%s' "$_lk"
}

# ФОРМАТ ФАЙЛА (RAM, ребут = чистый лист): по строке на источник, "ключ неудач разблокировка
# отметка". Четвёртое поле — ВРЕМЯ ПОСЛЕДНЕЙ НЕУДАЧИ, и без него уборка чужих строк съедала бы
# сам счётчик: строку «четыре неудачи, паузы ещё нет» пришлось бы либо хранить вечно, либо
# выбрасывать — а выброшенная означает, что перебиратель, чередующий два адреса, до паузы не
# доходит НИКОГДА. Поэтому строка живёт, пока держится пауза ИЛИ пока с последней неудачи прошло
# меньше TOTP_LOCK_TTL. Побочный эффект полезен: тихие четверть часа прощают хозяину опечатки.
# Строки прежнего формата (две колонки), пережившие обновление скриптов без ребута, отсеются
# сами: ключом у них окажется число, с адресом оно не совпадёт, а уборка выбросит их по NF.
totp_lock_read() {                    # totp_lock_read <ключ> → "неудач разблокировка отметка"
	_lr_f=0; _lr_u=0; _lr_t=0
	if [ -s "$TOTP_FAIL" ]; then
		while read -r _lr_k _lr_a _lr_b _lr_c _lr_rest; do
			[ "$_lr_k" = "$1" ] || continue
			_lr_f=$_lr_a; _lr_u=$_lr_b; _lr_t=$_lr_c; break
		done < "$TOTP_FAIL"
	fi
	case "$_lr_f" in ''|*[!0-9]*) _lr_f=0 ;; esac
	case "$_lr_u" in ''|*[!0-9]*) _lr_u=0 ;; esac
	case "$_lr_t" in ''|*[!0-9]*) _lr_t=0 ;; esac
	printf '%s %s %s' "$_lr_f" "$_lr_u" "$_lr_t"
}

# Выкладка строки: своя заменяется, чужие протухшие выбрасываются, число строк ограничено сверху —
# иначе перебиратель, меняющий адрес, растил бы файл в /tmp без края. Ноль неудач означает «забудь
# этот источник» и своей строки не пишет.
# ВРЕМЕННОЕ ИМЯ — С $$ , А НЕ ОБЩЕЕ. Писателей у файла столько же, сколько одновременных запросов
# входа (каждый CGI — свой процесс), и на ОБЩЕМ имени две неудачи в одну секунду писали бы в один
# черновик вперемешку: `mv` опубликовал бы мешанину, она разобралась бы как «ноль неудач», и
# перебиратель, шлющий попытки парами, обнулял бы себе счётчик нарочно. С $$ хуже, чем «одна
# запись потерялась», не станет: `mv` внутри /tmp атомарен, и читатель видит либо прежний файл,
# либо целый новый. Разность «сейчас − отметка» здесь СЫРАЯ и это осознанно: файл живёт в /tmp,
# то есть рождается ПОСЛЕ загрузки, а скачок часов вперёд лишь укорачивает паузу — сторона
# безопасная (запереть хозяина скачком нельзя).   # clock-raw: отметка рождается после boot
totp_lock_put() {                     # totp_lock_put <ключ> <неудач> <разблокировка>
	_lp_n=$(totp_now); _lp_n=${_lp_n:-0}
	_lp_t="$TOTP_FAIL.$$"
	{
		[ "${2:-0}" -gt 0 ] 2>/dev/null && printf '%s %s %s %s\n' "$1" "$2" "$3" "$_lp_n"
		if [ -s "$TOTP_FAIL" ]; then
			# ПОТОЛОК РЕЖЕТ СНАЧАЛА ТО, ЧТО НЕ ЖАЛКО, И ЖАЛКО ЗДЕСЬ ДВА СОРТА СТРОК. Порядок вывода:
			#   1) запертые ($3 > сейчас) — выбросить значит снять чужую паузу;
			#   2) НАКОПИВШИЕ неудачи ($2 > 0, паузы ещё нет) — ровно те, ради которых заведено четвёртое
			#      поле: выбросить значит подарить перебирателю новые пять попыток;
			#   3) всё остальное.
			# Первая редакция печатала «пока не упёрлись в cap» по порядку файла (MRU) и снимала чужую
			# паузу 64 неудачами с подставных адресов; вторая чинила только (1) и делала (2) ПЕРВЫМ
			# кандидатом на вылет. Массивы и END у busybox-awk есть (проверено на железе, v1.25.1).
			awk -v k="$1" -v n="$_lp_n" -v ttl="$TOTP_LOCK_TTL" -v cap="$TOTP_LOCK_MAX" \
				'$1!=k && NF>=4 && ($3+0 > n || n - $4 < ttl) {
				   if ($3+0 > n) L[++nl]=$0; else if ($2+0 > 0) P[++np]=$0; else R[++nr]=$0 }
				 END { for(i=1;i<=nl;i++) if(++c < cap) print L[i];
				       for(i=1;i<=np;i++) if(++c < cap) print P[i];
				       for(i=1;i<=nr;i++) if(++c < cap) print R[i] }' "$TOTP_FAIL"
		fi
	} > "$_lp_t" 2>/dev/null && mv "$_lp_t" "$TOTP_FAIL" 2>/dev/null
	rm -f "$_lp_t" 2>/dev/null
	return 0
}

totp_lock_left() {
	_ll_u=$(totp_lock_read "$(totp_lock_key)" | cut -d' ' -f2)
	_n=$(totp_now)
	if [ "$_ll_u" -gt "${_n:-0}" ] 2>/dev/null; then echo $((_ll_u - _n)); else echo 0; fi
}

totp_lock_bump() {
	_lb_k=$(totp_lock_key)
	_lb_f=$(totp_lock_read "$_lb_k" | cut -d' ' -f1)
	_lb_f=$((_lb_f + 1)); _lb_u=0
	if [ "$_lb_f" -ge "$TOTP_MAX_FAILS" ]; then
		_d=60; _k=$((_lb_f - TOTP_MAX_FAILS))
		while [ "$_k" -gt 0 ] && [ "$_d" -lt "$TOTP_LOCK_CAP" ]; do _d=$((_d * 2)); _k=$((_k - 1)); done
		[ "$_d" -gt "$TOTP_LOCK_CAP" ] && _d=$TOTP_LOCK_CAP
		_lb_u=$(( $(totp_now) + _d ))
	fi
	totp_lock_put "$_lb_k" "$_lb_f" "$_lb_u"
}

# Сбрасываем ТОЛЬКО СВОЙ источник: успешный вход — свидетельство про него, а не про соседа.
totp_lock_reset() { totp_lock_put "$(totp_lock_key)" 0 0; return 0; }

# --- Проверка кода -----------------------------------------------------------
# Коды: 0 = принят · 1 = не подошёл · 2 = часы не синхронизированы · 3 = пауза после неудач.
# Анти-replay: принятый счётчик запоминаем и больше не принимаем — иначе подсмотренный код
# работал бы все 30 с окна ещё раз (и ещё раз в окне ±1 у соседнего запроса).
totp_check_code() {
	[ "$(totp_lock_left)" -gt 0 ] 2>/dev/null && return 3
	_in=$(totp_rec_norm "$1")
	# Код восстановления РАЗБИРАЕМ ПО ДЛИНЕ (10), а не по наличию букв: hex-код вполне может
	# выпасть чисто цифровым (шанс ~1%), и «есть буквы» отправило бы его в ветку TOTP, где он
	# не подойдёт никогда. Проверяем его ПЕРВЫМ — он не зависит от часов и остаётся единственным
	# входом, когда телефон потерян или время ещё не синхронизировано.
	if [ "${#_in}" -eq 10 ]; then
		if totp_check_recovery "$_in"; then totp_lock_reset; return 0; fi
		totp_lock_bump; return 1
	fi
	_in=$(printf '%s' "$1" | tr -cd '0-9')
	[ "${#_in}" -eq 6 ] || { totp_lock_bump; return 1; }
	totp_clock_ok || return 2
	_hex=$(totp_secret_hex) || return 1
	_base=$(( $(totp_now) / TOTP_STEP ))
	_last=$(cat "$TOTP_LAST" 2>/dev/null)
	case "$_last" in ''|*[!0-9]*) _last=0 ;; esac
	_d=$((0 - TOTP_WINDOW))
	while [ "$_d" -le "$TOTP_WINDOW" ]; do
		_c=$((_base + _d))
		if [ "$_c" -gt "$_last" ] && [ "$(totp_code "$_hex" "$_c")" = "$_in" ]; then
			echo "$_c" > "$TOTP_LAST" 2>/dev/null
			totp_lock_reset
			return 0
		fi
		_d=$((_d + 1))
	done
	totp_lock_bump
	return 1
}

# Проверка кода ВВОДИМОГО СЕКРЕТА (привязка): тот же алгоритм, но секрет ещё в .totp-pending.
totp_check_pending() {
	[ -s "$TOTP_PEND" ] || return 1
	totp_clock_ok || return 2
	read _hex _rest < "$TOTP_PEND"
	_in=$(printf '%s' "$1" | tr -cd '0-9')
	[ "${#_in}" -eq 6 ] || return 1
	_base=$(( $(totp_now) / TOTP_STEP ))
	_d=$((0 - TOTP_WINDOW))
	while [ "$_d" -le "$TOTP_WINDOW" ]; do
		[ "$(totp_code "$_hex" "$((_base + _d))")" = "$_in" ] && return 0
		_d=$((_d + 1))
	done
	return 1
}

# --- Коды восстановления -----------------------------------------------------
# Хранится SHA-256, а не сам код: файл на флеше, а код — это вход в панель. Соли нет
# намеренно: код случайный (40 бит), словарь по нему не построить.
#
# ГРАБЛЯ (железо): отдельного `tr -d '- '` тут быть НЕ МОЖЕТ — busybox видит ведущий дефис в
# наборе и падает «unrecognized option», функция возвращала ПУСТО, и код восстановления не
# подходил НИКОГДА (а именно он — единственный вход при потерянном телефоне). Дефисы и пробелы
# и так уходят в комплементарном `-cd`: он оставляет ровно [a-z0-9], всё прочее удаляет.
totp_rec_norm() { printf '%s' "$1" | tr 'A-Z' 'a-z' | tr -cd 'a-z0-9'; }

totp_check_recovery() {
	[ -s "$TOTP_REC" ] || return 1
	_n=$(totp_rec_norm "$1")
	[ "${#_n}" -eq 10 ] || return 1
	_h=$(totp_sha256 "$_n")
	grep -q "^$_h\$" "$TOTP_REC" 2>/dev/null || return 1
	# Одноразовость: помечаем строку дефисом (не удаляем — панель показывает, сколько осталось).
	sed "s/^$_h\$/-$_h/" "$TOTP_REC" > "$TOTP_REC.tmp" 2>/dev/null &&
		mv "$TOTP_REC.tmp" "$TOTP_REC" 2>/dev/null
	chmod 600 "$TOTP_REC" 2>/dev/null
	return 0
}

totp_rec_left() {
	_c=$(grep -c '^[0-9a-f]' "$TOTP_REC" 2>/dev/null)
	case "$_c" in ''|*[!0-9]*) _c=0 ;; esac
	echo "$_c"
}

# ГЕНЕРИМ В ЧЕРНОВИК, ВЫКЛАДЫВАЕМ ЦЕЛИКОМ. Прежняя форма ПЕРВЫМ делом обнуляла боевой файл
# (`: > "$TOTP_REC"`) и лишь потом набивала его в цикле: любой обрыв на середине (openssl не дал
# случайности, кончилось место на /data) оставлял человека БЕЗ ЕДИНОГО кода восстановления — а
# перевыпуск он затевал как раз потому, что коды нужны. Наружу при этом уходило честное «не
# удалось», то есть потерю никто бы не заметил до дня, когда телефон потерян. Теперь провал
# оставляет СТАРЫЕ коды в силе: они хуже новых только тем, что часть уже использована.
totp_rec_gen() {
	_tmp="$TOTP_REC.new"
	: > "$_tmp" 2>/dev/null || return 1
	chmod 600 "$_tmp" 2>/dev/null
	_i=0; _out=""
	while [ "$_i" -lt "$TOTP_REC_N" ]; do
		_c=$(openssl rand -hex 5 2>/dev/null | tr -cd 'a-f0-9' | cut -c1-10)
		[ "${#_c}" -eq 10 ] || { rm -f "$_tmp" 2>/dev/null; return 1; }
		totp_sha256 "$_c" >> "$_tmp" || { rm -f "$_tmp" 2>/dev/null; return 1; }
		_out="$_out $(printf '%s' "$_c" | cut -c1-5)-$(printf '%s' "$_c" | cut -c6-10)"
		_i=$((_i + 1))
	done
	# Сверяем ЧИСЛО строк, а не только код возврата: `>>` на переполненном /data может дать
	# короткую запись без ошибки, и файл с пятью кодами из восьми выглядел бы исправным.
	_n=$(grep -c '^[0-9a-f]' "$_tmp" 2>/dev/null); case "$_n" in ''|*[!0-9]*) _n=0 ;; esac
	[ "$_n" -eq "$TOTP_REC_N" ] || { rm -f "$_tmp" 2>/dev/null; return 1; }
	mv "$_tmp" "$TOTP_REC" 2>/dev/null || { rm -f "$_tmp" 2>/dev/null; return 1; }
	chmod 600 "$TOTP_REC" 2>/dev/null
	printf '%s\n' "${_out# }"
}

# --- Сессии ------------------------------------------------------------------
# ФОРМАТ СТРОКИ: sha256(токен)⇥истекает⇥выдан⇥UA⇥адрес. Две последние колонки добавлены позже
# ради экрана «устройства»; МИГРАЦИЯ НЕ НУЖНА и не пишется: `read`/`awk` по трёхколоночной
# строке просто отдают пустые UA и адрес, а сама строка продолжает работать как раньше. Ради
# двух подписей переписывать файл, в котором лежат ключи от панели, — лишний риск.
#
# ЧТО МЫ НЕ ПИШЕМ: «последний раз видели». Кука проверяется на КАЖДЫЙ запрос панели (поллинг
# шапки — раз в несколько секунд), и обновление отметки означало бы запись на флеш в том же
# ритме. Ради подписи, которую и так заменяет «вошли тогда-то», флеш не насилуем.
#
# АДРЕС СОХРАНЯЕМ КАК ЕСТЬ, но честно: за `panel-tls` до CGI доезжает REMOTE_ADDR терминатора,
# то есть LAN-адрес самого роутера (разбор — в шапке файла). Отличить «зашли из интернета» от
# «зашли из дома» нельзя в принципе, поэтому здесь мы не гадаем: панель сравнивает адрес со
# СВОИМ LAN-адресом (он у неё уже есть в срезе web-ui.sh) и подписывает такие входы «через
# HTTPS». Второй копии детектора LAN-адреса тут не заводим.

# Санитайзеры полей. Значения приходят из ЗАГОЛОВКОВ запроса, то есть полностью подконтрольны
# клиенту: в файл (TSV) не должны просочиться табы и переводы строк, а в JSON — кавычки и
# обратные слэши. Поэтому не «удаляем плохое», а оставляем ТОЛЬКО заведомо безопасное.
# ГРАБЛЯ busybox: дефис в наборе `tr` обязан стоять ПОСЛЕДНИМ — ведущий читается как опция
# («unrecognized option»), и функция вернула бы пусто.
totp_sess_ua()   { printf '%s' "$1" | tr -cd 'A-Za-z0-9 ().,;:/_-' | cut -c1-120; }
totp_sess_addr() { printf '%s' "$1" | tr -cd '0-9A-Fa-f.:' | cut -c1-45; }

totp_sess_trim() {                    # оставить последние TOTP_SESS_MAX строк (свежие — внизу)
	[ -s "$TOTP_SESS" ] || return 0
	_tt=$(grep -c . "$TOTP_SESS" 2>/dev/null || true); case "$_tt" in ''|*[!0-9]*) _tt=0 ;; esac
	[ "$_tt" -gt "$TOTP_SESS_MAX" ] 2>/dev/null || return 0
	( umask 077; tail -n "$TOTP_SESS_MAX" "$TOTP_SESS" > "$TOTP_SESS.$$" 2>/dev/null ) &&
		mv "$TOTP_SESS.$$" "$TOTP_SESS" 2>/dev/null || { rm -f "$TOTP_SESS.$$" 2>/dev/null; return 1; }
	chmod 600 "$TOTP_SESS" 2>/dev/null
	return 0
}
totp_sess_gc() {
	[ -s "$TOTP_SESS" ] || return 0
	# СНАЧАЛА ЧИНИМ ЧАСЫ, ПОТОМ УБИРАЕМ. Между скачком часов и ближайшим тиком cron строки,
	# выданные до скачка, выглядят истёкшими — и уборка выбрасывала их НАСОВСЕМ: человек, вошедший
	# заново, тем же входом стирал 12-часовые сессии телефона и планшета, и сдвигать потом было
	# нечего. Починка дешёвая (чтение /proc/uptime и одного числа) и идемпотентная.
	command -v totp_sess_clock_fix >/dev/null 2>&1 && totp_sess_clock_fix
	_n=$(totp_now)
	# СНАЧАЛА СПРАШИВАЕМ, ЕСТЬ ЛИ ЧТО ВЫБРАСЫВАТЬ. Раньше файл на ФЛЕШЕ переписывался безусловно,
	# а зовут уборку и вход, и список, и счётчик; при годовом сроке истёкших строк почти не бывает,
	# то есть записи были холостыми — и каждая ещё и окно для гонки с параллельной выдачей.
	awk -F'\t' -v n="${_n:-0}" '$2+0 <= n+0 {f=1} END{exit f?0:1}' "$TOTP_SESS" 2>/dev/null || return 0
	( umask 077; awk -F'\t' -v n="${_n:-0}" '$2+0 > n' "$TOTP_SESS" > "$TOTP_SESS.$$" 2>/dev/null ) &&
		mv "$TOTP_SESS.$$" "$TOTP_SESS" 2>/dev/null || { rm -f "$TOTP_SESS.$$" 2>/dev/null; return 1; }
	chmod 600 "$TOTP_SESS" 2>/dev/null
	return 0
}

# СКАЧОК ЧАСОВ УБИВАЕТ СЕССИЮ, ВЫДАННУЮ СРАЗУ ПОСЛЕ РЕБУТА. RTC нет: на буте сток ставит часы по
# mtime файла (замер в clock-lib.sh: −21.5 ч от реального времени), а настоящая синхронизация
# приходит примерно через 13.5 минуты и часы ПРЫГАЮТ ВПЕРЁД на всю ошибку. Строка сессии несёт
# АБСОЛЮТНУЮ метку «истекает», посчитанную от ложного «сейчас», — и в момент скачка сессия,
# выданная в это окно, протухает разом: 12 часов «Запомнить меня» сняли (43200 с) меньше шага
# (77 400 с), то есть человек, вошедший сразу после ребута, выбрасывается на форму входа минут
# через десять и без объяснения. У браузера часы верные, `Max-Age` тикает честно — кука жива,
# сессии нет.
#
# ЧИНИМ ПОСЛЕ, А НЕ ПРИ ВЫДАЧЕ: угадать будущий шаг нельзя, а формат строки трогать нельзя тем
# более (шесть полей читает `read` в трёх местах). Признак «эта строка написана ДО скачка, в эту
# же загрузку» — ОКНО, а не одно число: момент загрузки по СТАРЫМ часам мы запоминаем сами
# (`$TOTP_CLOCK` в /tmp, гибнет с ребутом), а строка этой загрузки обязана лежать между ним и
# «плюс аптайм». Строке из ПРОШЛОЙ жизни роутера в это окно не попасть — для этого её пришлось бы
# завести в те же тринадцать минут ровно сутки назад; и даже тогда сдвиг лишь ПРОДЛИТ её, а не
# укоротит. Сдвигаем ОБЕ метки на величину шага — остаток жизни сохраняется.
# Отметка «момент загрузки» — атомарно и не по чужому umask: перенаправление рождает файл
# 0644 у uhttpd, а после обрыва между `>` и записью остался бы ПУСТОЙ файл, который
# следующий тик прочитает как «первый запуск» (окно потеряно).
clock_mark_put() {                    # clock_mark_put <база>; 1 = не записали
	( umask 077; printf '%s\n' "$1" > "$TOTP_CLOCK.$$" ) 2>/dev/null &&
		mv "$TOTP_CLOCK.$$" "$TOTP_CLOCK" 2>/dev/null || { rm -f "$TOTP_CLOCK.$$" 2>/dev/null; return 1; }
	return 0
}
totp_clock_base() {                   # «момент загрузки» по ТЕКУЩИМ часам + аптайм; 1 = аптайм неизвестен
	_cb_n=$(totp_now); case "$_cb_n" in ''|*[!0-9]*) _cb_n=0 ;; esac
	_cb_u=$(uptime_s)   # владелец ответа — clock-lib.sh (сорсится в шапке; следит C83)
	# «НЕ ЗНАЮ АПТАЙМ» ≠ «АПТАЙМ НОЛЬ»: при нуле окно ниже схлопывается в точку, сдвиг не делается
	# НИ ДЛЯ ЧЕГО, а отметка при этом обновляется — второго шанса уже не будет. Поэтому отказ.
	# И РОВНО ТАК ЖЕ ОТКАЗ НА 999999999: это слово владельца «не прочитал /proc/uptime», а не
	# тридцать один год аптайма; приняв его за число, мы раздули бы окно «эта загрузка» на всю
	# историю и сдвинули ЧУЖИЕ строки — те, ради сохранности которых сдвиг и написан.
	case "$_cb_u" in ''|*[!0-9]*|999999999) return 1 ;; esac
	[ "$_cb_u" -gt 0 ] 2>/dev/null || return 1
	printf '%s %s' "$((_cb_n - _cb_u))" "$_cb_u"
}
totp_sess_clock_fix() {               # зовёт web-ui.sh start (cron раз в 5 минут; он же поднимает панель)
	# Без heredoc и без второго форка: одна строка «база аптайм» разбирается подстановкой.
	_cf_bu=$(totp_clock_base) || return 0
	_cf_base=${_cf_bu% *}; _cf_up=${_cf_bu#* }
	case "$_cf_up" in ''|*[!0-9]*) return 0 ;; esac
	[ "${_cf_base:-0}" -gt 0 ] 2>/dev/null || return 0
	_cf_old=$(cat "$TOTP_CLOCK" 2>/dev/null)
	case "$_cf_old" in ''|*[!0-9]*) clock_mark_put "$_cf_base"; return 0 ;; esac
	_cf_d=$((_cf_base - _cf_old))
	# Шаг меньше минуты — дрожание секундного округления, а не синхронизация. Шаг НАЗАД сдвигать
	# нечего, но ОТМЕТКУ ОБНОВИТЬ ОБЯЗАНЫ: иначе завышенная база живёт до ребута, и следующий
	# скачок вперёд меряется от неё — окно начинается раньше настоящей загрузки, а сессии, выданные
	# после обратного шага, в него не попадают и умирают ровно так, как до починки.
	if [ "$_cf_d" -le 60 ] 2>/dev/null; then
		[ "$_cf_d" -lt 0 ] 2>/dev/null && clock_mark_put "$_cf_base"
		return 0
	fi
	if [ -s "$TOTP_SESS" ]; then
		# `$2+0 > 0` — гард от битой строки: у неё `$2` нечисловой, и без гарда сдвиг записал бы
		# туда САМ ШАГ, то есть «истекла в 1970» вместо «строка битая».
		( umask 077; awk -F'\t' -v OFS='\t' -v lo="$_cf_old" -v hi="$((_cf_old + _cf_up))" -v d="$_cf_d" \
			'$3+0 >= lo && $3+0 <= hi && $2+0 > 0 { $2 = $2 + d; $3 = $3 + d } { print }' "$TOTP_SESS" > "$TOTP_SESS.$$" 2>/dev/null ) &&
			mv "$TOTP_SESS.$$" "$TOTP_SESS" 2>/dev/null || { rm -f "$TOTP_SESS.$$" 2>/dev/null; return 1; }
		chmod 600 "$TOTP_SESS" 2>/dev/null
	fi
	# ОТМЕТКУ СТАВИМ ПОСЛЕДНЕЙ. Поставленная раньше, она делала провал сдвига (нет места на /data)
	# необратимым: следующий тик увидел бы шаг ≈0 и не повторил попытку.
	clock_mark_put "$_cf_base"
	return 0
}
# «Запомнить меня» → срок. ВЛАДЕЛЕЦ СРОКОВ ОДИН, и это не CGI: тот лишь пересказывает галочку.
# Пустой/неизвестный флаг = «запомнить»: так входит панель, закэшированная браузером до появления
# галочки, и ПК-скрипт; галочка включена по умолчанию, значит и умолчание обязано быть длинным.
totp_sess_ttl() {                     # totp_sess_ttl [1|0] → срок в секундах (stdout)
	case "${1:-}" in 0) printf '%s' "$TOTP_SESS_TTL_SHORT" ;; *) printf '%s' "$TOTP_SESS_TTL" ;; esac
}
totp_sess_new() {                     # totp_sess_new [UA] [адрес] [уровень: 1 пароль · 2 пароль+код] [срок, с]
	_t=$(openssl rand -hex 32 2>/dev/null | tr -cd 'a-f0-9')
	[ "${#_t}" -eq 64 ] || return 1
	_sn_l=${3:-1}; case "$_sn_l" in 1|2) : ;; *) _sn_l=1 ;; esac
	_sn_ttl=${4:-}; case "$_sn_ttl" in ''|*[!0-9]*) _sn_ttl=$TOTP_SESS_TTL ;; esac
	_sn_u=$(totp_sess_ua "${1:-}"); [ -n "$_sn_u" ] || _sn_u=-
	_sn_a=$(totp_sess_addr "${2:-}"); [ -n "$_sn_a" ] || _sn_a=-
	totp_sess_gc
	printf '%s\t%s\t%s\t%s\t%s\t%s\n' "$(totp_sha256 "$_t")" "$(( $(totp_now) + _sn_ttl ))" \
		"$(totp_now)" "$_sn_u" "$_sn_a" "$_sn_l" >> "$TOTP_SESS" || return 1
	chmod 600 "$TOTP_SESS" 2>/dev/null
	# СТРОКА ОБЯЗАНА ЛЕЖАТЬ В ФАЙЛЕ. Без этой сверки при полном /data токен всё равно
	# печатался, cgi-bin/login ставил куку — и человек «входил», а следующий же запрос
	# отвечал «нужен вход в панель».
	totp_sess_check "$_t" || return 1
	# ПОТОЛОК ЧИСЛА ВХОДОВ. Пока срок был 30 суток, уборка по истечению держала файл маленьким
	# сама; с годовым сроком она не выбрасывает почти ничего, и каждый вход — новая строка на
	# ФЛЕШЕ (инкогнито-окно, второй браузер, телефон гостя). Режем СТАРЫЕ: файл дописывается в
	# конец, значит свежие — внизу, и своя строка переживёт обрезку всегда.
	totp_sess_trim
	printf '%s\n' "$_t"
}

# Уровень живой сессии по токену (stdout: 1 или 2; пусто и rc=1 — сессии нет). Строка без
# шестого поля — сессия до уровней, то есть подтверждённая кодом: 2.
totp_sess_level() {
	_lv_t=$(printf '%s' "$1" | tr -cd 'a-f0-9')
	[ "${#_lv_t}" -eq 64 ] || return 1
	[ -s "$TOTP_SESS" ] || return 1
	awk -F'\t' -v h="$(totp_sha256 "$_lv_t")" -v n="$(totp_now)" \
		'$1==h && $2+0 > n+0 { l=$6+0; if(l<1) l=2; print l; ok=1; exit } END{ if(!ok) exit 1 }' "$TOTP_SESS"
}

# Повышение до уровня 2 (код подошёл). Сессию НЕ пересоздаём: кука в браузере остаётся той же,
# «выдана» и устройство — те же, меняется одно поле.
totp_sess_upgrade() {                 # totp_sess_upgrade <токен>
	_up_t=$(printf '%s' "$1" | tr -cd 'a-f0-9')
	totp_sess_check "$_up_t" || return 1
	( umask 077; awk -F'\t' -v OFS='\t' -v h="$(totp_sha256 "$_up_t")" '$1==h { $6=2 } { print }' "$TOTP_SESS" > "$TOTP_SESS.$$" 2>/dev/null ) &&
		mv "$TOTP_SESS.$$" "$TOTP_SESS" 2>/dev/null || { rm -f "$TOTP_SESS.$$" 2>/dev/null; return 1; }
	chmod 600 "$TOTP_SESS" 2>/dev/null
	return 0
}

# Проверка НЕ трогает файл (её зовёт КАЖДЫЙ запрос панели) — чистка живёт в выдаче/логауте.
totp_sess_check() {
	_tg_t=$(printf '%s' "$1" | tr -cd 'a-f0-9')
	[ "${#_tg_t}" -eq 64 ] || return 1
	[ -s "$TOTP_SESS" ] || return 1
	awk -F'\t' -v h="$(totp_sha256 "$_tg_t")" -v n="$(totp_now)" \
		'$1==h && $2+0 > n+0 {ok=1} END{if(ok) exit 0; exit 1}' "$TOTP_SESS"
}

totp_sess_count() {
	totp_sess_gc
	_c=$(grep -c . "$TOTP_SESS" 2>/dev/null)
	case "$_c" in ''|*[!0-9]*) _c=0 ;; esac
	echo "$_c"
}

totp_sess_clear() { : > "$TOTP_SESS" 2>/dev/null; chmod 600 "$TOTP_SESS" 2>/dev/null; return 0; }

# Список сессий для панели. `id` = САМ ХЕШ токена, а не его кусок: сравнение потом идёт точным
# `$1==id` (у busybox awk нет ни index(), ни своих функций — на substr закладываться не хочется),
# а знание хеша входа не даёт: гейт считает sha256 от предъявленного токена, обратно не ходит.
# Своей сортировки нет — её делает панель: единственный порядок, который тут можно навязать,
# всё равно пришлось бы дублировать в UI при первом же «а покажи сначала текущую».
totp_sess_list() {                    # totp_sess_list [токен текущей сессии]
	totp_sess_gc
	_sl_h=""
	_sl_t=$(printf '%s' "${1:-}" | tr -cd 'a-f0-9')
	# Условия — через `if`, а НЕ цепочкой `[ … ] && var=…`: этот файл СОРСЯТ чужие CGI, и простая
	# команда, вернувшая 1, у вызывающего с `set -e` уронила бы весь запрос (та же грабля, из-за
	# которой в store-lib переписан bin_path).
	if [ "${#_sl_t}" -eq 64 ]; then _sl_h=$(totp_sha256 "$_sl_t"); fi
	printf '['
	if [ -s "$TOTP_SESS" ]; then
		_sl_first=1
		# Редирект, а НЕ пайп: в пайпе цикл ушёл бы в подоболочку и `_sl_first` не пережил бы
		# итерацию — запятые в JSON поехали бы (класс «busybox без local», уже ловленный).
		while IFS="$(printf '\t')" read -r _sl_id _sl_exp _sl_iss _sl_ua _sl_ad _sl_lv; do
			[ -n "$_sl_id" ] || continue
			case "$_sl_exp" in ''|*[!0-9]*) _sl_exp=0 ;; esac
			case "$_sl_iss" in ''|*[!0-9]*) _sl_iss=0 ;; esac
			case "$_sl_lv" in 1|2) : ;; *) _sl_lv=2 ;; esac
			[ "$_sl_ua" = - ] && _sl_ua=""
			[ "$_sl_ad" = - ] && _sl_ad=""
			_sl_cur=false
			if [ -n "$_sl_h" ] && [ "$_sl_id" = "$_sl_h" ]; then _sl_cur=true; fi
			[ "$_sl_first" = 1 ] || printf ','
			_sl_first=0
			printf '{"id":"%s","cur":%s,"issued":%s,"expires":%s,"ua":"%s","addr":"%s","level":%s}' \
				"$_sl_id" "$_sl_cur" "$_sl_iss" "$_sl_exp" "$_sl_ua" "$_sl_ad" "$_sl_lv"
		done < "$TOTP_SESS"
	fi
	printf ']'
}

# «Выйти на ОСТАЛЬНЫХ устройствах». Гард обязателен: если предъявленной сессии в файле нет
# (протухла между запросом и нажатием), пустой фильтр вычистил бы файл целиком — то есть
# кнопка «кроме текущей» сделала бы ровно «выйти везде», включая здесь.
totp_sess_keep_only() {               # totp_sess_keep_only <токен>
	_ko_t=$(printf '%s' "${1:-}" | tr -cd 'a-f0-9')
	totp_sess_check "$_ko_t" || return 1
	( umask 077; awk -F'\t' -v h="$(totp_sha256 "$_ko_t")" '$1==h' "$TOTP_SESS" > "$TOTP_SESS.$$" 2>/dev/null ) &&
		mv "$TOTP_SESS.$$" "$TOTP_SESS" 2>/dev/null || { rm -f "$TOTP_SESS.$$" 2>/dev/null; return 1; }
	chmod 600 "$TOTP_SESS" 2>/dev/null
	return 0
}

# Отзыв ОДНОЙ сессии по её id (= хеш из totp_sess_list). Возврат 1, если такой строки нет —
# иначе панель рапортовала бы «отвязано» о несуществующем устройстве.
totp_sess_revoke() {                  # totp_sess_revoke <id>
	_rv_i=$(printf '%s' "${1:-}" | tr -cd 'a-f0-9')
	[ "${#_rv_i}" -eq 64 ] || return 1
	[ -s "$TOTP_SESS" ] || return 1
	# Существование проверяем ТЕМ ЖЕ awk, а не grep'ом с табом в шаблоне: литеральный таб внутри
	# кавычек — первое, что теряется при копировании файла редактором.
	awk -F'\t' -v h="$_rv_i" '$1==h{f=1} END{exit f?0:1}' "$TOTP_SESS" 2>/dev/null || return 1
	( umask 077; awk -F'\t' -v h="$_rv_i" '$1!=h' "$TOTP_SESS" > "$TOTP_SESS.$$" 2>/dev/null ) &&
		mv "$TOTP_SESS.$$" "$TOTP_SESS" 2>/dev/null || { rm -f "$TOTP_SESS.$$" 2>/dev/null; return 1; }
	chmod 600 "$TOTP_SESS" 2>/dev/null
	return 0
}

# Хеш токена наружу — панели нужно понять, свою ли сессию отзывают (тогда надо гасить куку).
totp_sess_id() { totp_sha256 "$(printf '%s' "${1:-}" | tr -cd 'a-f0-9')"; }

# --- Гейт для CGI ------------------------------------------------------------
# Кука приходит в HTTP_COOKIE (uhttpd её пробрасывает — проверено на железе; в его whitelist
# заголовков HTTP_COOKIE есть). Флаг Secure НЕ ставим: панель работает и по обычному HTTP в
# домашней сети, а с Secure кука там просто не сохранилась бы. Утечки это не добавляет —
# по тому же каналу идёт и сам пароль при входе; снаружи же панель открывается ТОЛЬКО по HTTPS
# (web-ui.sh наружу голый порт не выставляет никогда). HttpOnly — чтобы её не достал XSS,
# SameSite=Strict — чтобы чужая страница не ходила ею в панель.
# Имя новое (enodia_session), старое `panel2fa` читаем ради сессий, выданных до переименования:
# они подтверждены кодом, разлогинивать их обновлением незачем. Ставим — только новое.
totp_cookie() {
	_tc=$(printf '%s' "${HTTP_COOKIE:-}" | tr ';' '\n' | sed 's/^ *//')
	_tc_v=$(printf '%s\n' "$_tc" | grep "^$TOTP_COOKIE=" | head -1 | cut -d= -f2 | tr -cd 'a-f0-9')
	[ -n "$_tc_v" ] || _tc_v=$(printf '%s\n' "$_tc" | grep '^panel2fa=' | head -1 | cut -d= -f2 | tr -cd 'a-f0-9')
	printf '%s' "$_tc_v"
}
# Значение заголовка Set-Cookie: выдать / погасить (ОДНА копия на login и 2fa).
totp_cookie_hdr()  {                  # totp_cookie_hdr <токен> [срок, с — ТОТ ЖЕ, что у строки сессии]
	_ch=${2:-}; case "$_ch" in ''|*[!0-9]*) _ch=$TOTP_SESS_TTL ;; esac
	printf '%s=%s; Path=/; Max-Age=%s; HttpOnly; SameSite=Strict' "$TOTP_COOKIE" "$1" "$_ch"
}
totp_cookie_gone() { printf '%s=; Path=/; Max-Age=0; HttpOnly; SameSite=Strict' "$TOTP_COOKIE"; }
# «Есть ли ХОТЬ КАКАЯ живая сессия» (парольная годится) — нужно 2fa op=login: код повышает её.
totp_has_session() { _hs_c=$(totp_cookie); [ -n "$_hs_c" ] && totp_sess_level "$_hs_c" >/dev/null; }

# Переменные гейта нарочно с префиксом `_tg_`: этот файл СОРСЯТ все CGI, а они держат свои
# «локальные» имена вида `_c`/`_t`/`_f` по соглашению — совпадение имён здесь означало бы порчу
# чужого состояния из совершенно другого файла, и искать такое пришлось бы очень долго.
# 0 = пропуск. 1 = отказ, причина в $_tg_need: `login` (сессии нет — нужен пароль) или `2fa`
# (сессия парольная, а TOTP включён — нужен код). Порядок проверок = порядок факторов.
# Идёт смена раскладки? Спрашиваем только в ветке отказа (редкой), поэтому библиотеку тянем здесь, а не на каждый запрос.
totp_layout_moving() {
	command -v store_mode_alive >/dev/null 2>&1 || { if [ -f "$ENODIA_DIR/daemon-lib.sh" ]; then . "$ENODIA_DIR/daemon-lib.sh"; fi; }
	command -v store_mode_alive >/dev/null 2>&1 && store_mode_alive
}

totp_gate() {
	_tg_need=login
	_tg_c=$(totp_cookie)
	[ -n "$_tg_c" ] || return 1
	_tg_l=$(totp_sess_level "$_tg_c") || return 1
	_tg_need=2fa
	totp_enabled || return 0
	[ "$_tg_l" -ge 2 ]
}

# Зовут CGI ОДНОЙ строкой (см. web/cgi-bin/*). Отдаём 403 + машинный признак (need_login /
# need2fa): фронт по нему поднимает форму входа или окно кода, а не «сбой запроса» на каждом
# поллинге. Два признака, а не один: экраны разные, и панель обязана знать, какой именно.
# ОТКАЗ ЦЕЛИКОМ (403 + причина). Зовут его ДЕСЯТЬ CGI одним блоком, и у блока есть вторая
# половина, которую легко потерять: НЕТ ЭТОГО ФАЙЛА — CGI обязан ОТКАЗАТЬ САМ. До 03.09.2026
# там стоял пропуск («установка старее фичи — ведём себя как раньше»), и это было безопасно:
# дверь держал HTTP-Basic самого uhttpd, а гейт лишь добавлял второй фактор. Теперь двери нет —
# uhttpd поднимается БЕЗ `-c`, вход проверяем мы, — и пропавший totp.sh (недоехавший деплой,
# ручной rm, битый носитель) отдал бы данные и ДЕЙСТВИЯ любому в локалке, включая ветку
# `console` в action. Штатной эта ветка не бывает: `web-ui.sh start` без totp.sh панель не
# поднимает вовсе, то есть попасть в неё можно только поломанным путём — и там отказ честнее.
totp_gate_deny() {
	totp_gate && return 0
	# ПАНЕЛЬ ПЕРЕЕЗЖАЕТ — «СЕССИИ НЕ НАШЁЛ» ≠ «СЕССИИ НЕТ» (замер BE7000 30.09.2026). Смена раскладки двигает каталог настроек, а с ним
	# `.totp-sessions`, и запрос, попавший в окно переезда, не находил живую сессию: панель рисовала форму входа, вылечивала её
	# перезагрузка страницы. Отказ остаётся отказом — меняется только признак: `moving` фронт не читает как выход. Факт — у
	# владельца (daemon-lib.sh::store_mode_alive, по argv живого движка); нет библиотеки — прежний `need_login`.
	if [ "$_tg_need" = login ] && totp_layout_moving; then
		echo "Status: 503 Service Unavailable"
		echo "Content-Type: application/json; charset=utf-8"
		echo "Cache-Control: no-store"
		echo "Retry-After: 5"
		echo ""
		printf '{"ok":false,"moving":true,"msg":"панель переезжает — повторите через несколько секунд"}\n'
		exit 0
	fi
	echo "Status: 403 Forbidden"
	echo "Content-Type: application/json; charset=utf-8"
	echo "Cache-Control: no-store"
	echo ""
	if [ "$_tg_need" = login ]; then printf '{"ok":false,"need_login":true,"msg":"нужен вход в панель"}\n'
	else printf '{"ok":false,"need2fa":true,"msg":"нужен код подтверждения"}\n'; fi
	exit 0
}

# `rec_n` — сколько кодов восстановления выпускается (экран «Второй фактор» пишет «осталось N из M»): своей восьмёрки у панели
# нет, иначе смена TOTP_REC_N развела бы экран с роутером молча.
totp_status_json() {
	_on=false; totp_enabled && _on=true
	_pd=false; [ -s "$TOTP_PEND" ] && _pd=true
	_ck=false; totp_clock_ok && _ck=true
	printf '{"engine":true,"on":%s,"pending":%s,"clock":%s,"recovery":%s,"rec_n":%s,"sessions":%s,"lock":%s}\n' \
		"$_on" "$_pd" "$_ck" "$(totp_rec_left)" "$TOTP_REC_N" "$(totp_sess_count)" "$(totp_lock_left)"
}

# Строка otpauth:// для QR и ручного ввода. Издатель — модель роутера (у кого несколько
# роутеров, записи в приложении различимы); пробелы в метке ломают часть сканеров ⇒ дефисы.
totp_uri() {
	_b3="$1"
	_lbl=$(command -v router_model >/dev/null 2>&1 && router_model)
	[ -n "$_lbl" ] || _lbl="Xiaomi"
	_lbl=$(printf '%s' "$_lbl" | tr ' ' '-' | tr -cd 'A-Za-z0-9._-')
	printf 'otpauth://totp/%s:admin?secret=%s&issuer=%s&algorithm=SHA1&digits=6&period=30\n' \
		"$_lbl" "$_b3" "$_lbl"
}

# --- Вербы -------------------------------------------------------------------
cmd_enroll() {
	_hex=$(openssl rand -hex 20 2>/dev/null | tr -cd 'a-f0-9')
	[ "${#_hex}" -eq 40 ] || { echo "не удалось сгенерировать секрет (нет openssl?)"; return 1; }
	_b3=$(totp_b32 "$_hex")
	printf '%s %s %s\n' "$_hex" "$_b3" "$(totp_now)" > "$TOTP_PEND" || return 1
	chmod 600 "$TOTP_PEND" 2>/dev/null
	echo "$_b3"
	totp_uri "$_b3"
}

# Включение = подтверждение кодом ИМЕННО из привязываемого секрета: без этого человек включил
# бы 2FA с неверно перенесённым секретом и запер сам себя (телефон показывает чужие цифры).
cmd_enable() {
	[ -s "$TOTP_PEND" ] || { echo "привязка не начата"; return 1; }
	totp_check_pending "$1"; _r=$?
	[ "$_r" = 2 ] && { echo "часы роутера не синхронизированы — подождите минуту и повторите"; return 2; }
	[ "$_r" = 0 ] || { echo "код не подошёл"; return 1; }
	mv "$TOTP_PEND" "$TOTP_SEC" || return 1
	chmod 600 "$TOTP_SEC" 2>/dev/null
	rm -f "$TOTP_LAST" 2>/dev/null
	totp_lock_reset
	cmd_recovery_new_raw
}

cmd_recovery_new_raw() {
	_codes=$(totp_rec_gen) || { echo "не удалось сгенерировать коды восстановления"; return 1; }
	printf '%s\n' "$_codes"
}

# ОТКАЗ ПО КОДУ СЛОВАМИ И КОДОМ — одна лестница на выключение и перевыпуск кодов (ревью шага 7a, круг 2): перевыпуск схлопывал паузу
# (3) и «часы не синхронизированы» (2) в «код не подошёл», и верный код во время паузы получал отказ как неверный.
totp_code_or_say() {   # $1 — код; 0 — подошёл, иначе печатает причину и возвращает 1|2|3
	totp_check_code "$1"; _tcs=$?
	case "$_tcs" in
		0) return 0 ;;
		3) echo "слишком много неудачных попыток — подождите"; return 3 ;;
		2) echo "часы роутера не синхронизированы"; return 2 ;;
		*) echo "код не подошёл"; return 1 ;;
	esac
}

cmd_disable() {
	case "$1" in
		--force) : ;;                       # аварийный путь с роутера (SSH), см. шапку
		*) totp_enabled || { echo "двухфакторный вход и так выключен"; return 0; }
		   totp_code_or_say "$1" || return $? ;;
	esac
	rm -f "$TOTP_SEC" "$TOTP_PEND" "$TOTP_REC" "$TOTP_LAST" 2>/dev/null
	# Сессии НЕ трогаем: они парольные (уровень 1 достаточен без TOTP), и «выключил второй
	# фактор» не должно значить «всем войти заново». До формы входа их чистили — тогда сессия
	# и была вторым фактором, а первый держал браузер.
	totp_lock_reset
	echo "двухфакторный вход выключен"
}

