	   # войти, и «какие вообще есть команды» человек читает здесь. Пароль у всех трёх — СТДИНОМ.
	   echo "              pass-set|pass-verify|pass-migrate — пароль стдином (штатно: sh ${ENODIA_BOOT:-/data/usr/app/enodia-boot}/boot.sh web-ui.sh setpass — пароль команда спросит сама)}"
