# 1. Правила. Каждый владелец снимает СВОЁ (второй копии teardown быть не должно): плагин
#    транспорта — несущую, slots.sh — слот-правила, zapret.sh — NFQUEUE, vpn-server.sh — «доступ
#    домой», mark-core.sh unwire — маркировку и гарды. Здесь остаются лишь цепочки, у которых
#    своего верба нет.
step_rules() {
    log "Снимаю правила…"
    run support.sh down                                   # удалённый доступ («режим поддержки»)
    for _id in 2 3 4; do
        run transport.sh slot-down "$_id"
        run slots.sh unwire "$_id"
    done
    run vpn-server.sh down                                # awgs0 + VPNSRV_* + правила пиров
    run zapret.sh src-clear                               # NFQUEUE устройств «целиком в десинк» (по источнику)
    run zapret.sh down                                    # nfqws + NFQUEUE + dnsmasq-сниппет
    _t=$(cat "$ENODIA_STATE/.transport" 2>/dev/null | tr -d ' \r\n')
    [ -n "$_t" ] && run transport.sh down "$_t"           # несущая: default/FORWARD/MASQ/DNS
