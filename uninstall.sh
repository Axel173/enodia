# 1b. ДОБОРКА ПО ФАКТУ — то, что владельцы не сняли. ЗАЧЕМ ОТДЕЛЬНЫМ ШАГОМ: шаг 1 зовёт ВЛАДЕЛЬЦЕВ
#     (`mark-core.sh unwire`, `transport.sh down`, `slots.sh unwire`), а `run` молча пропускает
#     ОТСУТСТВУЮЩИЙ файл. На РАННИХ версиях половины этих скриптов нет вовсе (маркировку ставил
#     легаси-генератор split-route.sh, слотов и zapret не существовало), и снос отрабатывал
#     «успешно», оставляя `ip rule` в table 1000 и MARK-правила в mangle: после «полного удаления»
#     трафик продолжал уходить в мёртвый туннель, а чинить было уже нечем — файлы стёрты.
#     Поэтому здесь мы не спрашиваем, КТО это поставил, а смотрим на СОСТОЯНИЕ ядра.
#     Критерий «наше» — ТОЛЬКО собственные имена: ipset'ы по префиксам, интерфейсы awg*/xtun*,
#     переходы в наши цепочки. По МАРКЕ (`--set-xmark 0x1`) не судим НИКОГДА: стоковый mipctld
#     метит пакеты тоже, и «снести все правила с маркой» унесло бы кусок фаервола Xiaomi.
#     Один и тот же критерий обслуживает и подсчёт для экрана подтверждения, и сам снос — иначе
#     план и результат разъехались бы первой же правкой.
# `-w 5` у КАЖДОГО вызова — не украшение: доборка бежит ДО снятия cron, то есть параллельно с
# тиком heal/сторожа, и занятый xtables-лок означал бы пустой `-S` ⇒ «артефактов ноль». А ноль
# здесь читают двое: экран подтверждения и ВЕРДИКТ снятия (step_verify) — оба сказали бы «чисто»
# ровно там, где проверить не вышло. Рядом, в проверке цепочек, этот же урок уже учтён.
sweep_chain() {      # $1=таблица $2=цепочка $3=ERE «наше» $4=count|del ; копит в $_n
    # Индекс правила = его номер СРЕДИ строк `-A` этой цепочки. Так удаление квотинг-безопасно:
    # спека может нести `--comment "…"` с пробелами, и `iptables -D $spec` разъехался бы по словам.
    # Удаляем СВЕРХУ ВНИЗ (sort -nr): удаление сдвигает номера идущих ниже.
    for _sc in $(iptables -t "$1" -S "$2" 2>/dev/null | grep '^-A' | grep -nE "$3" | cut -d: -f1 | sort -nr); do
        _n=$((_n+1))
        [ "$4" = del ] && iptables -t "$1" -D "$2" "$_sc" 2>/dev/null
    done
    return 0
}

# Снятие ОДНОГО `ip rule` по ТОЧНОМУ селектору. $1 = count|del · $2 = строка, как её печатает
# `ip rule show` · дальше — аргументы для `ip rule del`. Цикл: дубли реальны (прерванный прогон
# ставит правило второй раз), потолок 20 — страховка от вечного цикла, если `del` не понял селектор.
# Режим передаём АРГУМЕНТОМ, а не читаем `$1` вызывающего: у функции свои позиционные параметры, и
# «унаследовать» их нельзя — та же мина, что уже подрывали на `_id` в srv_rules. Счётчик `$_n`
# общий с sweep_run СОЗНАТЕЛЬНО (в busybox sh нет `local`): доборка обязана отчитаться одним числом.
rule_drop() {
    _rm="$1"; _rp="$2"; shift 2
    _ri=0
    while [ "$_ri" -lt 20 ] && ip rule show 2>/dev/null | grep -q "$_rp"; do
        _ri=$((_ri+1)); _n=$((_n+1))
        [ "$_rm" = del ] || break        # в режиме подсчёта хватает одного факта
        ip rule del "$@" 2>/dev/null || break
    done
    return 0
}

sweep_run() {        # $1 = count|del ; $2 = keep → цепочки ПАНЕЛИ не наши (deactivate, см. CRON_PANEL)
    _n=0
    _sp=$(echo $SET_PREFIXES | sed 's/  */|/g')
    _if=$(echo $IFACES | sed 's/  */|/g')
    # Критерий «наше» и область совпадения — ОДНА строка на подсчёт и на снос: разъедься они, и
    # план обещал бы одно, а снятие делало другое. PANEL_WAN* здесь ровно потому же, почему его
    # нет в CHAINS_FILTER, — а раз доборка судит по СОСТОЯНИЮ ядра, исключение обязано быть и у неё.
    _jump="AWG|VPN_|VPNSRV"
    [ "$2" = keep ] || _jump="$_jump|PANEL_WAN"
    _our="match-set ($_sp)|-[io] ($_if)|-j ($_jump)"
    # Цепочки-родители перечислены явно: `-S` без имени отдаёт и наши собственные цепочки, а их
    # содержимое снимается вместе с ними ниже — считать его дважды значит соврать в плане.
    for _pr in "mangle PREROUTING" "mangle OUTPUT" "mangle POSTROUTING" "nat PREROUTING" \
               "nat POSTROUTING" "filter INPUT" "filter FORWARD" "filter OUTPUT"; do
        sweep_chain "${_pr% *}" "${_pr#* }" "$_our" "$1"
    done
    # Цепочки НЕ из списков выше — наследие ранних версий (имена менялись). Переходы в них уже
    # сняты циклом выше, поэтому `-X` берёт их без «chain is not empty / in use».
    for _tb in mangle nat filter; do
        for _ch in $(iptables -t "$_tb" -S 2>/dev/null | awk '/^-N/{print $2}'); do
            if [ "$2" = keep ]; then case "$_ch" in PANEL_WAN*) continue ;; esac; fi
            case "$_ch" in
                AWG*|VPN_*|VPNSRV_*|PANEL_WAN*)
                    _n=$((_n+1))
                    if [ "$1" = del ]; then
                        iptables -t "$_tb" -F "$_ch" 2>/dev/null
                        iptables -t "$_tb" -X "$_ch" 2>/dev/null
                    fi ;;
            esac
        done
    done
    # `ip rule` в наши таблицы. Судим по НОМЕРУ таблицы: форм записи две (базовая fwmark 0x1 и
    # слотовые 0x2..0x4), а номер таблицы общий у обеих. Цикл — потому что дубли реальны
    # (прерванный прогон ставит правило второй раз); потолок 20 — страховка от вечного цикла,
    # если `ip rule del` в этой сборке не умеет селектор `table`.
    for _tb in $TABLES; do
        _i=0
        while [ "$_i" -lt 20 ] && ip rule show 2>/dev/null | grep -qE "lookup $_tb( |\$)"; do
            _i=$((_i+1)); _n=$((_n+1))
            [ "$1" = del ] || break                      # в режиме подсчёта хватает одного факта
            ip rule del table "$_tb" 2>/dev/null || break
        done
    done
    # ГОСТЕВЫЕ ПРАВИЛА (см. $GUEST_*_SHOW выше) — по номеру таблицы их не поймать, поэтому снимаем
    # ТОЧНЫМ селектором. Слепое `ip rule del table 200` (и тем более `table main`!) унесло бы чужую
    # строку, появись такая в прошивке: в стоке AX3600 ни 200, ни 192.168.33.0/24 не упоминаются —
    # проверено грепом по /etc, но полагаться на это у соседних моделей нельзя.
    rule_drop "$1" "$GUEST_RULE_SHOW"   $GUEST_RULE_DEL
    rule_drop "$1" "$GUEST_BYPASS_SHOW" $GUEST_BYPASS_DEL
    rule_drop "$1" "$GUEST_DNS_SHOW"    $GUEST_DNS_DEL
    echo "$_n"
}

