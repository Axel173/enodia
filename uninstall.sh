# 4b. RAM-СЛЕД. `/tmp` гибнет на ребуте, но «снёс и работаю дальше» — законный сценарий, а
#     пережившие удаление штамп/лок встречают ПЕРЕустановку: heal увидит свой бутовый лок и
#     пропустит первый прогон, склейка dnsmasq — штамп «пары не менялись» и пропустит сборку.
step_ram() {         # $1 = full → вместе с логами и снимками (только purge)
    [ "$1" = full ] || return 0
    # Логи спрашиваем у ВЛАДЕЛЬЦА списка (clean.sh ramlogs-list) — второй копии реестра не
    # заводим. Нет файла (старая установка) — не беда: маски ниже перекрывают то же самое.
    if [ -f "$ENODIA_DIR/clean.sh" ]; then
        for _rl in $(sh "$ENODIA_DIR/clean.sh" ramlogs-list 2>/dev/null); do rm -f "$_rl" 2>/dev/null; done
    fi
    _rn=0
    for _rg in $RAM_GLOBS $RAM_GLOBS_LEGACY; do
        for _rf in $_rg; do
            [ -e "$_rf" ] || continue
            [ "$_rf" = "$SELF" ] && continue     # мы ИЗ него сейчас и читаемся (busybox дочитывает по ходу)
            rm -rf "$_rf" 2>/dev/null; _rn=$((_rn+1))
        done
    done
    log "RAM: удалено объектов в /tmp $_rn (локи, штампы, снимки наборов, логи)."
}

# «Кто из наших ещё жив» — ОДИН матчер на ТРИ места (TERM, добивание KILL, проверка результата).
# Печатает PID'ы по одному в строке. Копий цикла быть не должно: список демонов и путей уже
# менялся дважды (BIN_DIR внешнего накопителя, panel-tls на purge), и третья копия разъехалась бы
# первой — а цена расхождения тут «демон пережил удаление, а отчёт бодро отрапортовал».
# Имена переменных СВОИ (`_dp/_db/_pp`): в busybox sh нет `local`, а зовут нас из циклов,
# которые крутят собственные `_d`/`_b`/`_p` (грабля проекта — та же, что была в srv_rules).
# ОДИН проход по /proc: cmdline процесса читается ОДИН раз, сверка со всеми каталогами и демонами — в самом шелле. Прежде `tr`
# форкался на каждую пару «каталог × демон» для каждого процесса — 18 форков на процесс, а снятие зовёт функцию до 12 раз: на
# роутере с полутора сотнями процессов это десятки тысяч форков, стенд под общей нагрузкой шёл 400 с вместо 46 (замер 24.09.2026).
# Критерий прежний — полный путь бинаря и пробел за ним; pid печатается один раз, даже если совпало несколько пар.
daemons_pids() {      # $1 = дополнительные демоны (только purge, см. DAEMONS_PURGE)
    for _pp in /proc/[0-9]*; do
        [ -r "$_pp/cmdline" ] || continue
        _cl="$(tr '\0' ' ' 2>/dev/null < "$_pp/cmdline") "
        _dh=0
        for _dp in $DAEMON_DIRS; do
            for _db in $DAEMONS $1; do
                case "$_cl" in *"$_dp/$_db "*) _dh=1 ;; esac
            done
        done
        [ "$_dh" = 1 ] && echo "${_pp#/proc/}"
    done
    return 0
}

# 1b. НАШИ ФОНОВЫЕ ЗАДАНИЯ — и это НЕ демоны. Демоны ниже — БИНАРИ (awg/xray/hev/nfqws…), а
#     параллельно у нас живут фоновые прогоны `sh`: докачка списков после импорта, гео-сборка,
#     iplist, прогрев доменов. Их запускают панель и импорт, и работают они МИНУТАМИ — то есть
#     легко переживают всё удаление целиком.
#     Замерено на AX3600 16.08.2026: удаление кончилось в 13:38:17 с вердиктом «не осталось», а в
#     13:38:19 доживавшая задача создала ЗАНОВО четыре пустых `geo_*`-набора и два пустых сниппета
#     в ЖИВОМ /tmp/dnsmasq.d. Скрипт к тому времени был стёрт, но busybox дочитывает его из
#     ОТКРЫТОГО ИНОДА, реестра гео уже не нашёл — и добросовестно выложил пустой результат.
#     Судим по ФАКТУ (cmdline ведёт в $ENODIA_DIR и это `.sh`), а НЕ по списку пидфайлов: их семь штук
#     в четырёх скриптах, и следующий забудут дописать — тот же приём, что у ram-usage.sh.
#     Себя и родителя не трогаем: `deactivate` бежит из $ENODIA_DIR и попал бы под свой же критерий.
#     Шаг стоит ПЕРВЫМ, до снятия правил: задача, убитая позже, успела бы их переиграть.
step_jobs() {
    _n=0
    for _pp in /proc/[0-9]*; do
        _jp=${_pp#/proc/}
        [ "$_jp" = "$$" ] && continue
        [ "$_jp" = "$PPID" ] && continue
        [ -r "$_pp/cmdline" ] || continue
        case "$(tr '\0' ' ' 2>/dev/null < "$_pp/cmdline")" in
            *"$ENODIA_DIR/"*.sh*) kill "$_jp" 2>/dev/null; _n=$((_n+1)) ;;
        esac
    done
    [ "$_n" = 0 ] || sleep 1        # шанс завершиться штатно и отпустить локи
    log "Фоновых заданий остановлено: $_n."
}

# 2. Демоны. TERM всем нашим, затем добиваем KILL и убираем интерфейсы: TUN переживает смерть
#    демона, а осиротевший xtun/awg0 с default в table 1000 блэкхолит трафик.
step_daemons() {      # $1 = дополнительные демоны (только purge, см. DAEMONS_PURGE)
    log "Гашу демоны…"
    _extra="$1"
    _n=0
    for _pid in $(daemons_pids "$_extra"); do kill "$_pid" 2>/dev/null; _n=$((_n+1)); done
    # Секунда на штатное завершение: TERM у наших демонов не декоративен (hev снимает свой tun,
    # amneziawg-go убирает UAPI-сокет). Без паузы цикл ниже добивал KILL-ом через миллисекунды,
    # то есть -9 доставался ВСЕМ и всегда, а осиротевшие сокеты приходилось чистить руками.
    # Никого не гасили — ждать некого (как у step_jobs).
    [ "$_n" = 0 ] || sleep 1
    _i=0
    while [ "$_i" -lt 10 ]; do
        _left=$(daemons_pids "$_extra")
        [ -n "$_left" ] || break
        for _pid in $_left; do kill -9 "$_pid" 2>/dev/null; done
        _i=$((_i+1))
    done
    for _if in $IFACES; do ip link del "$_if" 2>/dev/null; done
    rm -rf /var/run/amneziawg /var/run/wireguard 2>/dev/null   # stale UAPI-сокеты
    log "Демонов остановлено: $_n; интерфейсы сняты."
}

# 3. Cron. Наши строки узнаются по ПУТИ (`cron_ours`: бутстрап или каталог кода) — перечислять скрипты
#    поимённо нельзя (список менялся при каждой новой фиче: heal, watchdog, traffic-acct, web-ui,
#    iplist-update, subs-update…, и старый uninstall уже отставал на три штуки).
step_cron() {        # $1 = keep → строку панели оставляем, снятое помним (deactivate)
    _ct=/etc/crontabs/root
    _kept=""
    [ -f "$_ct" ] || return 0
    _was=$(cron_ours -c "$_ct" 2>/dev/null); [ -n "$_was" ] || _was=0
    # `&& mv` тут был ловушкой: busybox `grep -v`, не напечатав НИ ОДНОЙ строки, возвращает 1 —
    # а это ровно случай «в кроне только наши строки» (файл заводит наш же установщик через
    # `touch`, стоковых записей может не быть вовсе). Тогда `mv` не выполнялся, cron оставался
    # цел, отчёт рапортовал «снято строк N», и через минуту heal.sh переигрывал ВСЁ, что мы
    # только что сняли, — то есть деактивация не работала совсем. Судим по ФАКТУ: черновик
    # создан ⇒ выкладываем (пустой файл — законный результат).
    cron_ours -v "$_ct" > "$_ct.new" 2>/dev/null
    if [ "$1" = keep ]; then
        # Сперва ПОМНИМ, потом снимаем: `$_ct` ещё цел, и снятое можно будет вернуть.
        # Сколько снимаем — считаем по ЖИВОМУ крону, а не по снимку: снимок может и не записаться
        # (см. ниже), а «снято строк» обязано остаться правдой в любом случае.
        _was=$(cron_ours "$_ct" 2>/dev/null | grep -vcF "$CRON_PANEL")
        case "$_was" in ''|*[!0-9]*) _was=0 ;; esac
        # Пустым снимком прежний НЕ затираем — повторная деактивация (в кроне осталась одна
        # строка панели) иначе стёрла бы память о расписании, и возвращать было бы нечего.
        cron_ours "$_ct" 2>/dev/null | grep -vF "$CRON_PANEL" > "$CRON_SAVE.new" 2>/dev/null
        if [ -s "$CRON_SAVE.new" ]; then mv "$CRON_SAVE.new" "$CRON_SAVE"; else rm -f "$CRON_SAVE.new"; fi
        # Запомнить не вышло (нет места на 20-МБ /data, ФС в ro) — молчать нельзя: «включить»
        # вернёт правила и настройки подсистем, а расписание придётся возвращать переустановкой.
        if [ "$_was" != 0 ] && [ ! -s "$CRON_SAVE" ]; then
            log "ВНИМАНИЕ: расписание снято, но запомнить его не вышло ($CRON_SAVE) — после «включить» проверьте cron."
        fi
        cron_ours "$_ct" 2>/dev/null | grep -F "$CRON_PANEL" >> "$_ct.new" 2>/dev/null
        _kept=" (строка панели оставлена — ею панель поднимается после ребута)"
    fi
    [ -f "$_ct.new" ] && mv "$_ct.new" "$_ct"
    /etc/init.d/cron restart >/dev/null 2>&1 || /etc/init.d/crond restart >/dev/null 2>&1
    log "Cron: снято строк $_was$_kept."
}

# Вернуть расписание, снятое деактивацией. ЗАЧЕМ ОТДЕЛЬНЫЙ ВЕРБ: «включить обратно» (панель →
# тумблер → `vpn-toggle.sh on`) возвращает ПРАВИЛА (repair) и ПЕРСИСТ подсистем (heal replay), а
# cron-строки снимали МЫ — и без них роутер живёт без сторожа (мёртвый VPS = дом без интернета,
# fail-open сделать некому), без heal (ребут ничего не поднимет) и без обновления списков, причём
# панель показывает зелёное. Строки не сочиняем — возвращаем ровно те, что сняли (реестр задач
# принадлежит установщику, второй копии тут быть не должно).
cmd_cron_restore() {
    # «Доступ домой», включённый до деактивации, возвращается ТЕМ ЖЕ шагом, что и расписание (разбор у cmd_deactivate): намерение
    # снова становится флагом, поднимет сервер переигрыш вызывателя. Отдельно от cron-строк: их могло и не быть.
    if [ -f "$ENODIA_STATE/server/.on-deact" ]; then mv -f "$ENODIA_STATE/server/.on-deact" "$ENODIA_STATE/server/.on" 2>/dev/null; fi
    [ -s "$CRON_SAVE" ] || { echo "расписание не снималось — возвращать нечего"; return 0; }
    _ct=/etc/crontabs/root
    mkdir -p /etc/crontabs 2>/dev/null
    [ -f "$_ct" ] || : > "$_ct"
    _n=0
    # `|| [ -n "$_l" ]` — файл без хвостового \n иначе потерял бы ПОСЛЕДНЮЮ строку (грабля busybox).
    while IFS= read -r _l || [ -n "$_l" ]; do
        [ -n "$_l" ] || continue
        # Сверяем ПО СКРИПТУ, а не по строке целиком. Пока система стояла деактивированной, задачу
        # мог переписать её ВЛАДЕЛЕЦ (панель-то жива: `update-sched.sh` меняет расписание списков и
        # подписок прямо оттуда), и дословный возврат нашей копии дал бы ДВЕ строки на одну задачу —
        # обе тикающие. Чужая строка новее нашей по определению, поэтому уступаем ей.
        # Ключ — ИМЯ ЦЕЛИ (`heal.sh`), а не путь: cron-строка идёт ЧЕРЕЗ бутстрап
        # (`…/enodia-boot/boot.sh heal.sh`), и сверка по $ENODIA_DIR не нашла бы в ней ничего,
        # то есть вернула бы дубль к живой строке владельца. Имя ловит ОБЕ формы — и прежнюю
        # с полным путём, и нынешнюю.
        # `set -f` ОБЯЗАТЕЛЕН: в cron-строке есть `*` (расписание), и без запрета глоббинга шелл
        # раскрывает её по ТЕКУЩЕМУ каталогу — в каталоге кода это сотня файлов `*.sh`, и ключом
        # сверки становился чужой скрипт. Прежняя форма (сверка по $ENODIA_DIR/*) от этого не
        # страдала случайно: раскрытые имена под неё не подходили.
        _sc=""
        set -f
        for _w in $_l; do
            case "$_w" in
                */boot.sh) continue ;;
                *.sh) _sc="${_w##*/}"; break ;;
            esac
        done
        set +f
        [ -n "$_sc" ] || _sc="$_l"
        grep -qF "$_sc" "$_ct" 2>/dev/null && continue
        printf '%s\n' "$_l" >> "$_ct"
        _n=$((_n+1))
    done < "$CRON_SAVE"
    if [ "$_n" != 0 ]; then
        /etc/init.d/cron restart >/dev/null 2>&1 || /etc/init.d/crond restart >/dev/null 2>&1
    fi
    rm -f "$CRON_SAVE"
    echo "Расписание возвращено: строк $_n (сторож, самовосстановление, обновление списков)."
    return 0
}

# Пуст ли каталог наших сниппетов — ОДИН ответ на двоих (снятие строки conf-dir и вердикт), и он же
# граница безопасности: пока там лежит хоть что-то (в том числе ЧУЖОЕ), конфиг демона не трогаем.
# Глобом, а не `ls -A`: у части сборок busybox ls урезан, а несовпавший глоб `[ -e ]` отсеет сам.
dnsdir_empty() {
    for _dx in "$DNSMASQ_DIR"/* "$DNSMASQ_DIR"/.[!.]*; do
        [ -e "$_dx" ] && return 1
    done
    return 0
}
# Есть ли в конфиге демона НАШ след — строка conf-dir ЛИБО подпись установщика над ней. Два
# признака, а не один: пишутся они по отдельности (heal возвращает только строку), и половинчатый
# остаток — подпись без строки — иначе жил бы в «стоковом» конфиге вечно.
dnsconf_ours() {
    grep -qxF "$DNSMASQ_LINE" "$DNSMASQ_CONF" 2>/dev/null && return 0
    grep -qF -e "$DNSMASQ_MARK" -e "$DNSMASQ_MARK_OLD" "$DNSMASQ_CONF" 2>/dev/null
}

# 4. dnsmasq. НАШИ сниппеты = `NN-*.conf` (00-upstream, 04-zapret, 10-groups, 11-geo…),
#    `enodia-*.conf` (enodia-custom от domain.sh, enodia-domains от старого re-filter) и их
#    ДОРЕБРЕНДИНГОВЫЕ имена `awg-*.conf`; стоковый там один и зовётся иначе
#    (`filter_main_opt.conf` — проверено на железе). Три маски, а не две, — цена переименования:
#    ребрендинг сделал `awg-custom.conf` → `enodia-custom.conf`, а маска осталась прежней, и
#    файл ПЕРЕЖИВАЛ полное удаление (замерено на AX3600 31.08.2026 — причём вместе с ним
#    оставалась и строка conf-dir: каталог-то не пуст). На AX3600/BE3600 `/etc` = UBIFS, то
#    есть «само сотрётся» там неправда, а `verify` при этом печатал «сниппетов не осталось».
#    Каталога ДВА: /etc (персист) и /tmp (живой, init копирует /etc→/tmp аддитивно) —
#    чистка только одного оставляла правило в силе до ребута (грабля проекта).
#    Наш 00-upstream.conf ЗАПИРАЕТ upstream в туннель ⇒ его удаление и есть возврат к стоку:
#    dnsmasq снова берёт резолверы провайдера из /tmp/resolv.conf.d.
#    Маски — ОДИН ответ на троих (снятие, вердикт, диагностика ПК через `ours`): у ПК была своя
#    регулярка, и из шести живых сниппетов BE7000 она показывала два (замер 30.09.2026).
dnsmasq_ours() {     # пути НАШИХ сниппетов обоих каталогов, по одному на строку
    for _dd in /etc/dnsmasq.d /tmp/dnsmasq.d; do
        for _df in "$_dd"/[0-9][0-9]-*.conf "$_dd"/enodia-*.conf "$_dd"/awg-*.conf; do   # legacy-name: awg-* — сниппеты прежних установок
            if [ -f "$_df" ]; then echo "$_df"; fi
        done
    done
}
step_dnsmasq() {     # $1 = keep → сниппет закрепления адресов оставляем (deactivate, см. DNSMASQ_KEEP)
    # Чтение из heredoc, а не труба: цикл обязан бежать в ЭТОМ шелле (вердикт ниже копит `_left` так же).
    _dso=$(dnsmasq_ours)
    while IFS= read -r _f; do
        [ -n "$_f" ] || continue
        if [ "$1" = keep ] && [ "${_f##*/}" = "$DNSMASQ_KEEP" ]; then continue; fi
        rm -f "$_f" 2>/dev/null
    done <<EOF
$_dso
EOF
    # Рабочее состояние склейки ipset=-строк (dns-merge.sh): файл-агрегат снесён маской выше
    # (он тоже `NN-*.conf`), но штамп «пары не менялись» пережил бы удаление и заставил
    # переустановленную систему пропустить первую сборку. Всё в /tmp — просто убираем.
    # `-rf`, а не `-f`: лок склейки — КАТАЛОГ (`.dns-merge.lock`), файловое удаление его не возьмёт.
    rm -rf /tmp/.enodia-dns-merge.* 2>/dev/null
    # …и НАША СТРОКА В САМОМ КОНФИГЕ ДЕМОНА. `conf-dir=/etc/dnsmasq.d` дописывает установка (и
    # каждый бут — heal), а снятие о ней не знало. На BE7000 это самолечится: `/etc` = ramfs. Но на
    # AX3600/BE3600 `/etc` — UBIFS, и след оставался НАВСЕГДА (замерено 16.08.2026: после полного
    # удаления строка от дня установки на месте, каталог пуст). Обещание «роутер вернулся к
    # стоковому состоянию» на этих моделях было неполным.
    # УСЛОВИЕ ЖЁСТКОЕ — каталог ПУСТ. Чужой файл в нём значит, что conf-dir нужен не нам одному, и
    # трогать строку нельзя ни при каком раскладе (у части прошивок она может быть и стоковой).
    # Пустой каталог убираем следом: кто заведёт его снова, тот и вернёт строку.
    # В `keep` не лезем вовсе: система остаётся установленной, сниппеты вернёт heal на ближайшем
    # буте, а без conf-dir они легли бы в каталог, который демон не читает.
    if [ "$1" != keep ] && dnsdir_empty && dnsconf_ours; then
        # Ступень В ТОМ ЖЕ КАТАЛОГЕ: `/tmp` — ДРУГАЯ ФС, оттуда `mv` не атомарен (грабля проекта),
        # а обрыв на записи конфига демона = сеть без DNS до ручного вмешательства. Плюс проверка
        # результата ПЕРЕД подменой: файл непустой и строк в нём стало МЕНЬШЕ, чем было.
        # Снимаем ОБЕ строки: установщик пишет ещё и шапку-комментарий над conf-dir, и без неё в
        # стоковом конфиге остаётся подпись установщика — замерено на AX3600.
        _dnstmp="${DNSMASQ_CONF%/*}/.dnsmasq.conf.uninst.$$"
        _dn0=$(wc -l < "$DNSMASQ_CONF" 2>/dev/null)
        grep -vxF "$DNSMASQ_LINE" "$DNSMASQ_CONF" | grep -vF -e "$DNSMASQ_MARK" -e "$DNSMASQ_MARK_OLD" > "$_dnstmp" 2>/dev/null
        _dn1=$(wc -l < "$_dnstmp" 2>/dev/null)
        case "$_dn0" in ''|*[!0-9]*) _dn0=0 ;; esac
        case "$_dn1" in ''|*[!0-9]*) _dn1=0 ;; esac
        if [ -s "$_dnstmp" ] && [ "$_dn1" -lt "$_dn0" ]; then
            mv "$_dnstmp" "$DNSMASQ_CONF" 2>/dev/null
            log "dnsmasq: убрал нашу строку $DNSMASQ_LINE (каталог пуст) — конфиг демона стоковый."
        fi
        rm -f "$_dnstmp" 2>/dev/null
        rmdir "$DNSMASQ_DIR" 2>/dev/null
    fi
    /etc/init.d/dnsmasq restart >/dev/null 2>&1
    log "dnsmasq: наши сниппеты удалены, служба перезапущена (резолверы провайдера вернулись)."
}

# 4b. Зона firewall в uci — ТОЛЬКО на purge. В `deactivate` система остаётся установленной, и
#     зона ей ещё понадобится: снеся её там, мы заставили бы «включить обратно» чинить то, чего
#     оно не ломало.
#     ПОРЯДОК ВНУТРИ ОБЯЗАТЕЛЕН: forwarding-секции ПЕРВЫМИ и С КОНЦА. Они безымянные
#     (`@forwarding[N]`), и удаление любой из них СДВИГАЕТ номера всех, что ниже, — проход сверху
#     вниз снёс бы вторую нашу и чужую вместо неё. Зону — последней: пока на неё ссылается
#     forwarding, uci оставил бы висячую ссылку.
#     ЗАПИСЬ И ПЕРЕЗАГРУЗКА РАЗВЕДЕНЫ ПО РАЗНЫМ ШАГАМ, и это не косметика. `fw3 reload` СМЫВАЕТ ВСЕ
#     iptables (грабля проекта), а между ними стоит `step_verify` — единственное место, где мы
#     судим о снятии ПО ФАКТУ. Сделай reload раньше вердикта — и он читал бы чистое ядро всегда,
#     то есть печатал бы «снято» и тогда, когда шаг снятия правил на самом деле провалился. Так
#     мы теряем ровно ту диагностику, ради которой step_verify и написан. Поэтому здесь только
#     uci (её вердикт как раз проверяет), а перезагрузка — `fwzone_reload` ПОСЛЕ вердикта.
step_fwzone() {
    FW_RELOAD=0
    command -v uci >/dev/null 2>&1 || { log "firewall: uci не найден — зону не трогаю."; return 0; }
    _fwn=0
    # `grep -E` + два простых `sed`, а не одно выражение с `\|`: BRE-альтернация у busybox sed
    # необязательна, а ошибиться тут значит молча не найти НИ ОДНОЙ секции и отчитаться «чисто».
    _fwi=$(uci show firewall 2>/dev/null \
        | grep -E "^firewall\.@forwarding\[[0-9]+\]\.(src|dest)='$FW_ZONE'\$" \
        | sed 's/^firewall\.@forwarding\[//' | sed 's/\].*$//' | sort -nr | uniq)
    for _fi in $_fwi; do
        uci delete "firewall.@forwarding[$_fi]" 2>/dev/null && _fwn=$((_fwn+1))
    done
    if uci get "firewall.$FW_ZONE" >/dev/null 2>&1; then
        uci delete "firewall.$FW_ZONE" 2>/dev/null && _fwn=$((_fwn+1))
    fi
    if [ "$_fwn" = 0 ]; then
        log "firewall: нашей зоны '$FW_ZONE' нет — конфиг не трогаю."
        return 0
    fi
    # Судим по КОДУ commit, а не по факту delete. Незакоммиченное удаление живёт дельтой в /tmp, и
    # `uci get` из следующего процесса её УЖЕ видит — то есть вердикт ниже сказал бы «следа нет»,
    # а reload поднял бы зону обратно из непереписанного конфига. Такое бывает на забитом флеше.
    if uci commit firewall 2>/dev/null; then
        FW_RELOAD=1
        log "firewall: снята зона '$FW_ZONE' и её forwarding (секций: $_fwn)."
    else
        log "firewall: зону '$FW_ZONE' снять не вышло — uci не записал конфиг (флеш занят?). Убрать вручную: uci delete firewall.$FW_ZONE && uci commit firewall."
    fi
}
# Записи в uci больше нет, но РАЗВЁРНУТЫЕ ею цепочки живут в ядре до перезагрузки firewall — без
# этого сразу после «полного удаления» в `iptables -S` ещё видны zone_awg_*. Зовётся ПОСЛЕ вердикта
# (почему — в шапке шага); сам reload — ТОЛЬКО если мы правда что-то сняли: на стоковой установке
# («только панель») набор правил обязан остаться байт-в-байт прежним, а reload там был бы
# вмешательством на ровном месте. Свои правила к этому моменту сняты шагами выше — смывать нечего.
#
# ЗАМЕРЕНО НА ЖИВОМ AX3600 (16.08.2026): `fw3 reload` снимает ПРАВИЛА зоны, но ПУСТЫЕ ЦЕПОЧКИ от
# неё оставляет — после полного удаления в ядре продолжали висеть восемь штук (`zone_awg_input`,
# `forwarding_awg_rule`, `prerouting_awg_rule`, …). Они инертны (ни одного правила, ни одного
# перехода) и гибнут на ребуте, но отчёт обещал «цепочки убраны», а `iptables -S` их показывал —
# то есть врал ровно там, где мы обещаем возврат к стоку. Добираем их сами.
# `-X` — САМ СЕБЕ ГАРД: непустую цепочку и цепочку, на которую есть переход, он не удалит вовсе
# ⇒ ошибиться маской и снести что-то живое нельзя в принципе. Имена строит fw3 из имени зоны
# (`zone_<имя>_*`, `<хук>_<имя>_rule`), поэтому и критерий выводим из `$FW_ZONE`, а не литералами:
# наши собственные цепочки — В ВЕРХНЕМ регистре (`AWG_*`), их снял `sweep_run` задолго до этого.
# Проход НЕ гейтим на FW_RELOAD: сироты переживают саму запись (её могли снять руками или прошлым
# прогоном), а на стоковом роутере под маску не попадает ничего и ни одного вызова не случится.
fwzone_reload() {
    if [ "$FW_RELOAD" = 1 ]; then
        /etc/init.d/firewall reload >/dev/null 2>&1
    fi
    _fwx=0
    for _tb in filter nat mangle; do
        for _ch in $(iptables -t "$_tb" -S 2>/dev/null | awk '/^-N/{print $2}'); do
            case "$_ch" in
                zone_"$FW_ZONE"|zone_"$FW_ZONE"_*|*_"$FW_ZONE"_rule)
                    iptables -t "$_tb" -X "$_ch" 2>/dev/null && _fwx=$((_fwx+1)) ;;
            esac
        done
    done
    if [ "$FW_RELOAD" = 1 ]; then
        log "firewall: перезагружен, цепочек зоны '$FW_ZONE' убрано: $_fwx."
    elif [ "$_fwx" != 0 ]; then
        log "firewall: убрано осиротевших цепочек зоны '$FW_ZONE': $_fwx."
    fi
}
# Остался ли наш след в uci — ОДИН ответ на двоих (шаг выше и вердикт), как dnsconf_ours.
fwzone_ours() {
    command -v uci >/dev/null 2>&1 || return 1
    uci get "firewall.$FW_ZONE" >/dev/null 2>&1 && return 0
    uci show firewall 2>/dev/null | grep -qE "^firewall\.@forwarding\[[0-9]+\]\.(src|dest)='$FW_ZONE'\$"
}

# 5. Панель — ПОСЛЕДНЕЙ. Порядок внутри тоже важен: сперва закрыть вход снаружи и HTTPS
#    (иначе останется правило на WAN к порту, за которым уже никого нет), потом сам uhttpd.
step_panel() {
    log "Снимаю панель…"
    run web-ui.sh wan-off
    run web-ui.sh tls-off
    run web-ui.sh stop
    # ЗАГЛУШКА — второй uhttpd на том же порту (её поднимает boot.sh, когда код на накопителе, а
    # накопителя нет). `web-ui.sh stop` о ней не знает: у неё свой pidfile. Не сняв её, мы оставили
    # бы порт 8088 занятым процессом без единого файла за спиной — ровно тот исход, ради которого
    # RAM-след чистится ПОСЛЕ панели, а не до.
    if [ -f /tmp/enodia-stub.pid ]; then
        start-stop-daemon -K -p /tmp/enodia-stub.pid -x /usr/sbin/uhttpd >/dev/null 2>&1
        rm -f /tmp/enodia-stub.pid 2>/dev/null
        log "Заглушка накопителя остановлена."
    fi
    log "Панель остановлена."
}

# 5b. HOTPLUG-ХУК. Только на purge: при деактивации система остаётся стоять, и хук ей не мешает
#     (он лишь зовёт boot.sh). Снимаем ЯВНО, потому что /etc персистентен на AX3600 и BE3600 —
#     тот же класс, что `awg-custom.conf`, переживший переименование и оставшийся навсегда.
step_hotplug() {
    _hn=0
    for _hf in "$HOTPLUG_HOOK" $ETC_LEFTOVERS; do
        # Симлинк проверяем через -e ИЛИ -L: у битого симлинка (цель уже снесли строкой выше)
        # `-e` ложен, и файл пережил бы удаление — ровно тот случай, ради которого шаг заведён.
        { [ -e "$_hf" ] || [ -L "$_hf" ]; } || continue
        rm -f "$_hf" 2>/dev/null
        if [ -e "$_hf" ] || [ -L "$_hf" ]; then log "ВНИМАНИЕ: $_hf удалить не вышло."; else _hn=$((_hn+1)); fi
    done
    [ "$_hn" = 0 ] && return 0
    log "Следы в /etc сняты: $_hn (hotplug-хук, ранний старт, проба персистентности)."
    return 0
}

# 6. ipset'ы — ПОСЛЕ правил (сет, на который ссылается правило, не удаляется).
step_sets() {
    _n=0
    for _s in $(ipset list -n 2>/dev/null); do
        for _pref in $SET_PREFIXES; do
            case "$_s" in "$_pref"*) ipset destroy "$_s" 2>/dev/null && _n=$((_n+1)); break ;; esac
        done
    done
    log "ipset: удалено сетов $_n."
}

# 7. ВНЕШНИЙ НАКОПИТЕЛЬ — только на purge и только СВОЙ подкаталог. Флешка чужая: на ней лежат
#    файлы человека, и «полное удаление» роутера не даёт нам права трогать что-то, кроме
#    enodia-store. Идём ДО `rm -rf $ENODIA_DIR`: путь к хранилищу знает маркер, который лежит внутри
#    каталога — снесём каталог первым и потеряем адрес, оставив 13 МБ бинарей сиротами.
#    Накопителя нет (выдернут) — молча пропускаем: удаление роутера не должно упираться в флешку.
#    Имя подкаталога и своей точки монтирования берём из store-lib.sh ($STORE_SUB/$STORE_MNT), а не
#    литералами: их же знает движок, и третья копия строки «enodia-store» разъехалась бы первой.
#    ПРЕЖНИЕ ИМЕНА ЗНАЕМ ТОЖЕ ($STORE_SUB_OLD/$STORE_MNT_OLD): каталог лежит на ЧУЖОМ диске, и
#    переименование, не доехавшее до масок снятия, оставляет его там навсегда — ровно то, что уже
#    случилось с `awg-custom.conf`, пережившим `purge`. Флешку не форматируем: сносим ТОЛЬКО тот
#    каталог, на который смотрит маркер, и только если он назван одним из ДВУХ наших имён.
step_store() {
    store_ready || { log "Внешний накопитель: не подключён — на нём ничего не трогаю."; return 0; }
    _sr=$(store_root)
    _ssub=
    case "$_sr" in */"$STORE_SUB") _ssub="$STORE_SUB" ;; esac
    if [ -z "$_ssub" ] && [ -n "$STORE_SUB_OLD" ]; then
        case "$_sr" in */"$STORE_SUB_OLD") _ssub="$STORE_SUB_OLD" ;; esac
    fi
    [ -n "$_ssub" ] || { log "Внешний накопитель: неожиданный путь ($_sr) — не трогаю."; return 0; }
    _mp=${_sr%/$_ssub}
    rm -rf "$_sr" 2>/dev/null
    if [ -d "$_sr" ]; then log "Внешний накопитель: $_sr удалить не вышло — удалите его вручную."
    else log "Внешний накопитель: хранилище $_sr удалено, остальное на флешке не тронуто."; fi
    # Свою точку монтирования отпускаем, стоковую (/mnt/usb-*) не трогаем: её монтировали не мы.
    # Своих имён два — прежнее оставленное монтирование держало бы ФС занятой и после удаления.
    # Пустой $STORE_MNT_OLD (нет store-lib.sh, работает шим) даёт пустой шаблон: он не совпадёт
    # с непустым $_mp никогда, отдельного гарда не нужно. `return 0` — чтобы итог шага не зависел
    # от кода `umount` (точку могли размонтировать раньше нас): шаги снятия best-effort и
    # намеренно молчаливы, вердикт даёт step_verify ПО ФАКТУ, а не по их кодам.
    case "$_mp" in
        "$STORE_MNT"|"$STORE_MNT_OLD") umount "$_mp" 2>/dev/null ;;
    esac
    return 0
}

# 8. ПРОВЕРКА ПО ФАКТУ — сняли ли на самом деле. Раньше `deactivate` ВСЕГДА писал `OK` и
#    возвращал 0, а `FAIL` не писался нигде и никогда: любой провал (cron не переписался, демон
#    пережил KILL, сниппет dnsmasq не удалился) доезжал до человека как бодрое «VPN снят, интернет
#    идёт напрямую» — и он шёл искать причину куда угодно, только не сюда. Судим НЕ по кодам шагов
#    (они best-effort и намеренно молчаливы — упавший шаг не должен обрывать снятие), а по
#    состоянию системы ПОСЛЕ них: что из нашего ещё живо.
#    Список проверок — зеркало списков сноса выше; новая цепочка/сет/сниппет добавляется ТАМ и
#    проверяется здесь автоматически, отдельного перечня заводить не нужно.
step_verify() {      # $1 = дополнительные демоны (как у step_daemons) ; $2 = keep → см. CRON_PANEL
    _left=""
    # Цепочки. Код `-C`/`-L` у iptables трёхзначен (грабля проекта): 0 = цепочка есть, 1 = нет,
    # прочее (4 = xtables-лок) = «не смог проверить» — и молчать об этом нельзя, иначе занятый
    # лок читался бы как «всё чисто». `-w 5` даёт шанс дождаться лока прежде, чем сдаться.
    for _c in $CHAINS_MANGLE; do
        iptables -t mangle -n -L "$_c" >/dev/null 2>&1
        case $? in 0) _left="$_left mangle/$_c" ;; 1) ;; *) _left="$_left mangle/$_c(?)" ;; esac
    done
    for _c in $CHAINS_FILTER; do
        iptables -n -L "$_c" >/dev/null 2>&1
        case $? in 0) _left="$_left filter/$_c" ;; 1) ;; *) _left="$_left filter/$_c(?)" ;; esac
    done
    # Маркировка без цепочек так же смертельна: живое `ip rule` в нашу таблицу = трафик уходит
    # в несуществующую несущую (чёрная дыра вместо «прямого режима»).
    ip rule show 2>/dev/null | grep -q 'lookup 100[0-4]' && _left="$_left ip-rule"
    # Гостевые правила (см. $GUEST_*_SHOW) вердикт тоже касаются: доборка их снимает, значит
    # уцелевшее = снятие отработало не до конца, а не «так и было».
    ip rule show 2>/dev/null | grep -q "$GUEST_RULE_SHOW" && _left="$_left ip-rule/guest"
    ip rule show 2>/dev/null | grep -q "$GUEST_BYPASS_SHOW" && _left="$_left ip-rule/guest-bypass"
    ip rule show 2>/dev/null | grep -q "$GUEST_DNS_SHOW" && _left="$_left ip-rule/guest-dns"
    for _if in $IFACES; do ip link show "$_if" >/dev/null 2>&1 && _left="$_left iface/$_if"; done
    # `_dl`, а НЕ `_dp`: этим именем крутит цикл внутри daemons_pids. Подстановка команды бежит в
    # субшелле и нас бы не задела, но имя, совпадающее с внутренним у callee, — та самая мина,
    # которую в busybox sh (нет `local`) уже подрывали в srv_rules.
    _dl=$(daemons_pids "$1")
    [ -n "$_dl" ] && _left="$_left демоны($(echo "$_dl" | tr '\n' ',' | sed 's/,$//'))"
    # Строку панели, оставленную намеренно, считать «не снятым» нельзя: иначе честная деактивация
    # подписывалась бы вердиктом FAIL, а человек шёл искать несуществующий недоснятый хвост.
    if [ "$2" = keep ]; then _cn=$(cron_ours /etc/crontabs/root 2>/dev/null | grep -vcF "$CRON_PANEL")
    else _cn=$(cron_ours -c /etc/crontabs/root 2>/dev/null); fi
    case "$_cn" in ''|*[!0-9]*) _cn=0 ;; esac
    [ "$_cn" = 0 ] || _left="$_left cron($_cn)"
    # Сниппеты dnsmasq — самое дорогое из уцелевшего: наш 00-upstream.conf ЗАПИРАЕТ upstream в
    # туннель, которого больше нет, то есть «деактивация» оставила бы сеть вообще без DNS.
    _dso=$(dnsmasq_ours)
    while IFS= read -r _f; do
        [ -n "$_f" ] || continue
        if [ "$2" = keep ] && [ "${_f##*/}" = "$DNSMASQ_KEEP" ]; then continue; fi
        _left="$_left dnsmasq/$_f"
    done <<EOF
$_dso
EOF
    # Уцелевший ipset — это не «лишние килобайты в ядре», а СЛЕД: сет не удаляется, пока на него
    # ссылается хоть одно правило, значит правило пережило снятие.
    for _s in $(ipset list -n 2>/dev/null); do
        for _pref in $SET_PREFIXES; do
            case "$_s" in "$_pref"*) _left="$_left ipset/$_s"; break ;; esac
        done
    done
    # Тем же критерием, каким доборка сносила, спрашиваем «осталось ли». Цепочки выше проверяются
    # ПОИМЁННО и ловят только известные имена — а доборка берёт и наследие ранних версий, и
    # одиночные правила в стоковых цепочках, у которых своей цепочки нет вовсе.
    _sw=$(sweep_run count "$2")
    case "$_sw" in ''|0) ;; *) _left="$_left правила($_sw)" ;; esac
    # Строка сида в /etc/hosts переживает всё остальное и продолжает прибивать домен к нашему
    # старому адресу для КАЖДОГО процесса на роутере (Go читает hosts раньше резолвера).
    grep -qF "$HOSTS_TAG" /etc/hosts 2>/dev/null && _left="$_left /etc/hosts"
    # Наша строка conf-dir в конфиге демона — ОТДЕЛЬНОЙ строкой лога, а НЕ в `_left`, и это не
    # мягкотелость. `_left` = «часть ОБВЯЗКИ пережила снятие»: он печатает совет перезагрузиться и
    # отдаёт код 1, который панель и программа на ПК читают как «удаление не удалось». Здесь же
    # остаток КОСМЕТИЧЕСКИЙ — каталог пуст, демон читает пустоту, ничего не сломано, — а ребут его
    # на UBIFS-моделях и не уберёт. Случиться это может от забитого флеша (перезапись не прошла) или
    # от heal, успевшего дописать строку обратно; в обоих случаях честнее назвать факт, чем
    # объявлять чистое удаление провалившимся. Спрашиваем тем же критерием, что и снятие: непустой
    # каталог значит, что строку держит не наш файл, и оставить её ПРАВИЛЬНО. В `keep` не задаём —
    # там она нужна и остаётся намеренно.
    if [ "$2" != keep ] && dnsdir_empty && dnsconf_ours; then
        log "Мелочь: наша строка в $DNSMASQ_CONF осталась (перезапись не прошла). Ничего не ломает; убрать вручную: grep -v '$DNSMASQ_LINE'."
    fi
    # Зона firewall — по той же мерке и ОТДЕЛЬНОЙ строкой, а не в `_left`: остаток косметический
    # (зона указывает на несуществующий awg0, трафика не трогает), ребут его не уберёт, а объявлять
    # из-за него удаление провалившимся значило бы врать в другую сторону. В `keep` не спрашиваем —
    # там зона остаётся намеренно.
    if [ "$2" != keep ] && fwzone_ours; then
        log "Мелочь: зона '$FW_ZONE' в /etc/config/firewall осталась (uci не отдал запись). Трафика не трогает; убрать вручную: uci delete firewall.$FW_ZONE && uci commit firewall."
    fi
    if [ -n "$_left" ]; then
        log "НЕ СНЯТО:$_left"
        return 1
    fi
    log "Проверка: правил, марок, демонов, cron-строк и сниппетов dnsmasq не осталось."
    return 0
}

