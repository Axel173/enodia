# СНЯТИЕ И УСТАНОВКА КОДА ВЗАИМОИСКЛЮЧАЮТСЯ (ревью ветки pkg-update, круг 2). Установщик посреди purge пересоздаёт снесённые
# каталоги (замена кладёт файл с `mkdir -p`) и, успей его install.sh, возвращает cron, бутстрап и панель: половина дерева кода на
# роутере, про который отчёт сказал «стоковый»; посреди деактивации install.sh будит сторожа и heal на «снятом» роутере.
# Ответ «идёт ли» — у владельцев (daemon-lib.sh::pkg_install_alive, апдейтер `upd-busy`); печатает причину, код 0 = занят.
un_busy() {
    if pkg_install_alive; then echo "идёт установка кода"; return 0; fi
    if [ -f "$ENODIA_DIR/gh-update.sh" ] && sh "$ENODIA_DIR/gh-update.sh" upd-busy >/dev/null 2>&1; then
        echo "идёт обновление или откат кода"; return 0
    fi
    return 1
}
# Гард снятия. Свой пид — ПЕРВЫМ, вопрос — ВТОРЫМ: установщик делает то же в обратном порядке сторон (лок, потом вопрос про нас),
# и из двух стартовавших разом хотя бы один видит другого — дойти до конца вдвоём они не могут. У снятия из панели пидфайл уже
# записал CGI (тем же pid), у снятия с ПК его иначе не было вовсе. Отказ — КОДОМ 4 у вербов снятия (не 1 «сняли не всё»): по нему
# ПК говорит «роутер занят», а не советует перезагрузку посреди живой установки (ревью ветки, круг 3).
un_gate() {   # $1 — имя снятия для отчёта
    echo $$ > "$UN_PID" 2>/dev/null
    _ubw=$(un_busy) || return 0
    rm -f "$UN_PID" 2>/dev/null
    : > "$REPORT"
    set_state FAIL
    log "ОТМЕНЕНО ($1): $_ubw — снятие посреди неё оставило бы половину системы. Ничего не тронуто; дождитесь конца и повторите."
    return 1
}

cmd_deactivate() {
    un_gate "деактивация" || return 4
    : > "$REPORT"
    set_state RUNNING
    # НАМЕРЕНИЕ — ТЕМ ЖЕ ФЛАГОМ, ЧТО У ТУМБЛЕРА (`vpn-toggle.sh off` пишет его так же и так же первым). Без
    # него после деактивации шапка панели не знала, что VPN выключили НАМЕРЕННО: правил и демона нет,
    # флага нет ⇒ «VPN включён, но не везёт» — поломка там, где человек сам всё снял. С флагом шапка
    # говорит «выключен вами», а её тумблер — это `vpn_on`, то есть и есть обещанное «включить обратно
    # отсюда же» (он же возвращает расписание: `cron-restore`). Сторож и heal с флагом тоже молчат.
    mkdir -p "$ENODIA_STATE" 2>/dev/null
    date +%s > "$ENODIA_STATE/.vpn-off" 2>/dev/null
    # «ДОСТУП ДОМОЙ» ВКЛЮЧЁН — ЭТО НАСТРОЙКА, А НЕ ОБВЯЗКА. `vpn-server.sh down` гасит сервер и стирает флаг `server/.on` (для
    # тумблера панели это и есть «выключить»), а «включить обратно» (`heal.sh replay`) поднимает сервер только по флагу — после
    # деактивации телефон больше не заходил домой и после включения (ревью шага 6d). Демон и правила снимаем, флаг возвращаем.
    # …в том числе ОТЛОЖЕННЫЙ прошлой деактивацией (`.on-deact`): «Повторить» после FAIL снимал бы его `vpn-server.sh down`, и после
    # «Включить VPN» телефон домой больше не заходил (ревью шага 6d, круг 3).
    _srv_on=0; if [ -f "$ENODIA_STATE/server/.on" ] || [ -f "$ENODIA_STATE/server/.on-deact" ]; then _srv_on=1; fi
    log "=== ДЕАКТИВАЦИЯ: снимаю обвязку VPN, файлы и настройки ОСТАВЛЯЮ ==="
    step_jobs           # ПЕРВЫМ: фоновая задача, убитая позже, успела бы переиграть снятое
    step_rules
    # `keep` — область снятия: панель (её цепочки, её cron-строка) и закрепление адресов в локалке
    # к обвязке VPN не относятся, см. CRON_PANEL. Тот же аргумент обязан дойти до ВЕРДИКТА, иначе
    # оставленное намеренно вернулось бы строкой «НЕ СНЯТО».
    step_sweep keep     # то, что владелец не снял (его может не быть — ранние версии)
    step_daemons
    step_sets
    step_cron keep
    step_dnsmasq keep
    step_hosts          # ДО вердикта: он про hosts спрашивает
    # Намерение — ПОД ДРУГИМ ИМЕНЕМ (`server/.on-deact`): под `.on` его видят сторож и heal, и первое же горячее подключение
    # накопителя (hotplug-tick → тик сторожа, в `full` — heal целиком) поднимало сервер с портом наружу на роутере, про который экран
    # сказал «снято»; план и экран «Доступ домой» при этом звали его включённым (ревью шага 6d, круг 2). Обратно в `.on` его
    # превращает только «включить обратно» — `cron-restore` (зовут `vpn-toggle on` и `transport switch`), а поднимает `heal.sh replay`.
    if [ "$_srv_on" = 1 ] && [ -d "$ENODIA_STATE/server" ]; then : > "$ENODIA_STATE/server/.on-deact"; fi
    # RAM-след при деактивации НЕ чистим СОЗНАТЕЛЬНО: система остаётся установленной, логи и штампы
    # ещё нужны для разбора. Единственное, что снималось тут раньше, — сид в /etc/hosts, и у него
    # теперь свой шаг выше; вызов `step_ram` без `full` стал бы пустым, а читался бы как работа.
    if ! step_verify "" keep; then
        set_state FAIL
        log "ДЕАКТИВАЦИЯ НЕ ЗАВЕРШЕНА: часть обвязки пережила снятие (перечень — в строке выше)."
        log "Интернет может идти всё ещё через VPN или не идти вовсе. Повторите деактивацию;"
        log "не помогло — перезагрузите роутер (правила живут в RAM и на буте их ставит cron, который снят)."
        return 1
    fi
    set_state OK
    log "Готово. VPN снят, интернет идёт напрямую через провайдера."
    log "Файлы и настройки на месте ($ENODIA_DIR), панель работает (и переживёт ребут) — вернуть всё"
    log "можно оттуда же: «включить» вернёт правила, настройки подсистем и расписание."
    return 0
}

cmd_purge() {
    # Гард — и до прыжка в /tmp (копия не нужна, если снимать нельзя), и после: exec сохраняет pid, а пидфайл перепишется тем же.
    un_gate "полное удаление" || return 4
    # Перепрыгиваем в /tmp: дальше мы стираем каталог, в котором лежим (busybox sh дочитывает
    # скрипт по ходу выполнения — снести файл из-под себя = оборвать удаление на середине).
    if [ "$0" != "$SELF" ]; then
        cp "$0" "$SELF" 2>/dev/null && chmod +x "$SELF" 2>/dev/null
        # `-s`, а не `-x`: запускаем себя через `sh "$SELF"` (бит не нужен), а проверить надо
        # ровно то, о чём говорит сообщение — что копия ДОЕХАЛА и не пуста. С `-x` провалившийся
        # chmod отменял бы полное удаление при целой копии, и человек читал бы «не смог
        # скопировать» про файл, который на месте.
        [ -s "$SELF" ] || { log "не смог скопировать себя в $SELF — полное удаление отменено"; return 1; }
        exec sh "$SELF" purge
    fi
    : > "$REPORT"
    set_state RUNNING
    log "=== ПОЛНОЕ УДАЛЕНИЕ: обвязка + панель + файлы ==="
    step_jobs           # ПЕРВЫМ: иначе доживающая задача пересоздаёт сеты и сниппеты ПОСЛЕ нас
    step_rules
    step_sweep          # то, что владелец не снял (его может не быть — ранние версии)
    step_daemons "$DAEMONS_PURGE"
    step_sets
    step_cron
    step_dnsmasq
    step_fwzone         # ДО вердикта: он про uci-след спрашивает (и только purge — см. шаг 4b)
    step_hosts          # ДО вердикта: RAM-след ниже идёт последним, а вердикт про hosts спрашивает
    # Проверяем ДО стирания каталога: `set_state` пишет ВНУТРЬ $ENODIA_DIR, после rm писать будет
    # некуда, а отметка «снялось не всё» нужна ровно тому, кто потом придёт разбираться.
    _vr=0
    step_verify "$DAEMONS_PURGE" || { _vr=1; set_state FAIL; }
    fwzone_reload       # ПОСЛЕ вердикта: reload смывает iptables и сделал бы его слепым
    step_panel
    step_hotplug
    # ВТОРОЙ проход по фоновым заданиям — и он не дубль. Первый бежит ДО снятия правил, но панель
    # живёт до `step_panel` выше, а снятие длится десятки секунд: человек, нажавший «Удалить», в
    # это время волен открыть гео-экран или «Обновить списки», и CGI родит фоновый прогон уже
    # ПОСЛЕ первой зачистки. Итог был бы ровно тот, что чинит этот шаг: задача переживает удаление
    # и пересоздаёт сеты и сниппеты. Здесь панель уже мертва — породить новое некому.
    step_jobs
    step_store
    # RAM-след — ПОСЛЕДНИМ из чисток и обязательно ПОСЛЕ step_panel: пидфайл панели лежит в /tmp,
    # и снеси мы его раньше, `web-ui.sh stop` не нашёл бы, кого гасить, — uhttpd пережил бы
    # «полное удаление» и держал порт 8088 без единого файла за спиной.
    step_ram full
    # Порядок: настройки и бинари ПЕРЕД кодом. Скрипт исполняется из каталога кода, и снеся
    # его первым, мы рискуем остаться без собственного продолжения; заодно провал на любом
    # из каталогов виден до того, как чинить станет нечем.
    for _od in "$ENODIA_STATE" "$ENODIA_BIN" "$ENODIA_BOOT" "$ENODIA_DIR"; do
        rm -rf "$_od" 2>/dev/null
        if [ -d "$_od" ]; then
            log "ВНИМАНИЕ: $_od удалить не вышло (занят?). Повторите: rm -rf $_od"
            return 1
        fi
    done
    # РОДИТЕЛЬСКИЙ каталог тоже наш: `/data/usr/app` заводит установщик (`mkdir -p $ENODIA_DIR`), в
    # стоке этого пути нет — проверено грепом по `/usr/sbin`, `/usr/bin`, `/etc/init.d` на AX3600
    # 16.08.2026. Пустая папка на ФЛЕШЕ переживает ребут, то есть «вернулся к стоковому» было
    # неправдой ровно на один каталог. `rmdir` — сам себе гард: непустой он не возьмёт, поэтому
    # ошибиться и снести чужое нельзя. ВЫШЕ НЕ ЛЕЗЕМ: рядом в `/data/usr` лежит стоковый `log/`
    # (тот самый `/data/usr/log/messages`, единственный лог, переживающий ребут) — там `rmdir`
    # честно провалится, но и пробовать незачем.
    # В РАСКЛАДКЕ «ВСЁ НА НАКОПИТЕЛЕ» ФЛЕШ ДЕРЖИТ НЕ КАТАЛОГ КОДА: родитель $ENODIA_DIR там — хранилище на флешке
    # (его уже снял step_store), а на флеше рядом с бутстрапом лежат пустые двойники прежних путей
    # (`enodia-state`, `enodia-bin` — заводит установщик до переезда; замер BE7000 23.09.2026). Их `rm -rf` выше не
    # видит (переменные смотрят на накопитель), и «вернулся к стоковому» оставалось неправдой на три каталога. Снимаем
    # их `rmdir` — только ПУСТЫЕ: наполненный двойник чужим не станет, но и сносить вслепую то, что мы не клали, нельзя.
    _bpar=${ENODIA_BOOT%/*}
    for _par in "$_bpar/enodia" "$_bpar/enodia-state" "$_bpar/enodia-bin" "$_bpar" "${ENODIA_DIR%/*}"; do
        case "$_par" in
            ''|/|/data|/data/usr|/*/) ;;              # страховка от обрезки до корня системных путей
            *) [ -d "$_par" ] && rmdir "$_par" 2>/dev/null && log "Пустой каталог $_par убран." ;;
        esac
    done
    log "Каталоги $ENODIA_DIR, $ENODIA_STATE, $ENODIA_BIN и $ENODIA_BOOT удалены. Роутер вернулся к стоковому состоянию."
    log "Отчёт: $REPORT (панели уже нет — читать по SSH)."
    # Файлы стёрты, а правила/демоны пережили снятие — самый неприятный исход: чинить их уже
    # нечем (скриптов нет), и единственный честный совет — ребут, после которого RAM-правила
    # исчезнут сами, а поднять их будет некому (cron снят).
    [ "$_vr" = 0 ] || { log "НО: часть обвязки пережила снятие (см. «НЕ СНЯТО» выше) — ПЕРЕЗАГРУЗИТЕ роутер."; return 1; }
    return 0
}

# «Zapret будет снят» — вопрос НЕ про бинарь на диске. Судили по `-x nfqws`, а его кладёт
# бутстрап ПК на КАЖДОЙ установке (десинк — ещё и аварийный канал до GitHub), поэтому экран
# подтверждения обещал снять Zapret даже там, где его не включали ни разу, — и на AX3600, где
# ядро 4.4 без NFQUEUE и десинк невозможен ВООБЩЕ. Человек читает это как «у меня стояло».
# Владелец ответа один — `zapret.sh wired`. Код 2 = копия скрипта СТАРШЕ верба (не «нет»!) ⇒
# только тогда судим сами, по следу в ядре: наш jump в mangle и флаг транспорта.
zapret_live() {
    if [ -f "$ENODIA_DIR/zapret.sh" ]; then
        sh "$ENODIA_DIR/zapret.sh" wired >/dev/null 2>&1
        _zrc=$?
        [ "$_zrc" = 0 ] && return 0
        [ "$_zrc" = 1 ] && return 1
    fi
    [ -f "$ENODIA_STATE/.zapret-on" ] && return 0
    iptables -t mangle -S PREROUTING 2>/dev/null | grep -q ENODIA_ZAPRET
}

# Наше на роутере, что человек ищет глазами, — для «Диагностики установки» ПК (enodia.py): cron-строки и
# сниппеты dnsmasq ТЕМИ ЖЕ ответами, какими их снимает удаление. Свои регулярки ПК не знали строки подписок
# и сниппетов гео/групп (замер BE7000 30.09.2026: пять строк cron из шести, два сниппета из шести). Только ЧТЕНИЕ.
cmd_ours() {
    echo "cron:"
    _oc=$(cron_ours /etc/crontabs/root 2>/dev/null)
    if [ -n "$_oc" ]; then printf '%s\n' "$_oc"; else echo "  (пусто — после ребута ничего не поднимется)"; fi
    echo "dnsmasq:"
    _od=$(dnsmasq_ours)
    [ -n "$_od" ] || echo "  (наших сниппетов нет — на установке «только панель» это норма)"
    while IFS= read -r _f; do
        [ -n "$_f" ] || continue
        ls -la "$_f" 2>/dev/null
    done <<EOF
$_od
EOF
    return 0
}

# Что будет снято — для экрана подтверждения в панели. Только ЧТЕНИЕ, ничего не трогаем.
cmd_plan() {
    _t=$(cat "$ENODIA_STATE/.transport" 2>/dev/null | tr -d ' \r\n')
    _slots=0
    [ -s "$ENODIA_STATE/.slots" ] && _slots=$(grep -c . "$ENODIA_STATE/.slots" 2>/dev/null)
    case "$_slots" in ''|*[!0-9]*) _slots=0 ;; esac
    _cron=0
    [ -f /etc/crontabs/root ] && _cron=$(cron_ours -c /etc/crontabs/root 2>/dev/null)
    case "$_cron" in ''|*[!0-9]*) _cron=0 ;; esac
    # `-x` обязателен (инвариант проекта, clean.sh): без него чужая ФС, смонтированная
    # внутрь каталога, попадает в счёт и экран подтверждения обещает освободить не своё.
    _size=$(du -xsk "$ENODIA_DIR" 2>/dev/null | awk '{printf "%.0f", $1*1024}')
    case "$_size" in ''|*[!0-9]*) _size=0 ;; esac
    _sets=0
    for _s in $(ipset list -n 2>/dev/null); do
        for _pref in $SET_PREFIXES; do
            case "$_s" in "$_pref"*) _sets=$((_sets+1)); break ;; esac
        done
    done
    # ЗАНЯТО НА ФЛЕШЕ РОУТЕРА — не то же, что «весит каталог кода»: в раскладке «всё на накопителе» код лежит на
    # флешке, а экран подписывал его вес «Занято на флеше» (7 МБ при бутстрапе в полмегабайта). Наш след на флеше —
    # это ВСЁ под родителем бутстрапа (`/data/usr/app`: его заводит установщик, в стоке пути нет) в любой раскладке;
    # `-x` не пускает счёт на смонтированное внутрь. `size_b` остаётся прежним (панель старше поля читает его).
    _fl=$(du -xsk "${ENODIA_BOOT%/*}" 2>/dev/null | awk '{printf "%.0f", $1*1024}')
    case "$_fl" in ''|*[!0-9]*) _fl=$_size ;; esac
    printf '{"engine":true,"dir":"%s","size_b":%s,"flash_b":%s,"transport":"%s","slots":%s,"cron":%s,"sets":%s' \
        "$ENODIA_DIR" "$_size" "$_fl" "$_t" "$_slots" "$_cron" "$_sets"
    printf ',"server":%s'    "$([ -f "$ENODIA_STATE/server/.on" ] && echo true || echo false)"
    printf ',"zapret":%s'    "$(zapret_live && echo true || echo false)"
    # Накопитель — отдельной строкой экрана подтверждения: «полное удаление» унесёт и хранилище
    # на флешке, а это единственное, что удаление трогает ВНЕ роутера. Размер считаем ОТДЕЛЬНО и
    # с проверкой: пустой ответ du (путь исчез между проверкой и замером) внутри printf дал бы
    # `"store_b":,` — сломанный JSON вместо экрана подтверждения.
    _stb=0
    if store_ready; then
        _stb=$(du -xsk "$(store_root)" 2>/dev/null | awk '{printf "%.0f", $1*1024}')
        case "$_stb" in ''|*[!0-9]*) _stb=0 ;; esac
    fi
    printf ',"store":%s,"store_b":%s' "$(store_ready && echo true || echo false)" "$_stb"
    # Артефакты, которые снимет доборка по факту. Для экрана подтверждения это единственная цифра,
    # честная на ЛЮБОЙ версии: остальные поля читают наши файлы, а их на ранней установке может не
    # быть вовсе — при том, что правила в ядре стоят.
    _swp=$(sweep_run count); case "$_swp" in ''|*[!0-9]*) _swp=0 ;; esac
    printf ',"rules":%s' "$_swp"
    printf ',"hosts_seed":%s' "$(grep -qF "$HOSTS_TAG" /etc/hosts 2>/dev/null && echo true || echo false)"
    # Зона firewall в uci — ОТДЕЛЬНЫМ полем, а не внутри "rules": те правила ставит fw3 по нашей
    # записи, доборка их не видит и не должна (они помечены `!fw3:` и снимаются перезагрузкой
    # firewall, а не iptables -D). Без этого поля экран обещал «rules: 0» на роутере, где зона
    # разворачивает полтора десятка строк.
    printf ',"fwzone":%s' "$(fwzone_ours && echo true || echo false)"
    printf ',"panel_tls":%s' "$([ -f "$ENODIA_STATE/.panel-tls" ] && echo true || echo false)"
    printf ',"twofa":%s'     "$([ -f "$ENODIA_STATE/.totp" ] && echo true || echo false)"
    # Вердикт ПРОШЛОГО снятия (RUNNING|OK|FAIL|IDLE) — тем же срезом, что и факты экрана. Иначе
    # честный код возврата некуда девать: `deactivate` запускается ОТВЯЗАННО (панель гасят на
    # purge, и ответ CGI обязан уехать раньше), а значит узнать, чем всё кончилось, можно только
    # спросив состояние потом. Панель опрашивает эту строку после запуска деактивации.
    _st=$(cat "$STATE" 2>/dev/null | tr -d ' \r\n'); [ -n "$_st" ] || _st=IDLE
    printf ',"state":"%s"' "$_st"
    # ИДЁТ ЛИ СНЯТИЕ СЕЙЧАС — по ЖИВОМУ держателю, а не по строке: RUNNING лежит на флеше и переживает ребут посреди
    # снятия, и экран, открытый потом, ждал бы конца операции, которой нет. Держатель — процесс ИМЕННО uninstall.sh
    # (pid переиспользуется; тот же вопрос, что у движка компонентов — `pid_runs`, шим без библиотеки — «жив»).
    # Шаблон — со СНЯТИЕМ в argv: короткоживущие `uninstall.sh plan` и `cron-restore` (последний зовёт каждый `transport switch`) на
    # переиспользованном pid сироты отвечали бы «идёт» (ревью шага 6d, круг 2).
    _run=false
    if [ "$_st" = RUNNING ] && uninstall_alive; then _run=true; fi
    printf ',"running":%s' "$_run"
    # КАКОЕ снятие идёт — его знает только тот, кто его запустил (CGI пишет режим рядом с пидфайлом). Экран, открытый посреди снятия
    # из другой вкладки, без этого не отличал отключение от полного удаления, и мигнувший Wi-Fi превращался в «Панель удалена».
    _um=""
    if [ "$_run" = true ]; then _um=$(cat /tmp/enodia-uninstall.mode 2>/dev/null | tr -d ' \r\n'); fi
    case "$_um" in deactivate|purge) : ;; *) _um="" ;; esac
    printf ',"mode":"%s"' "$_um"
    printf '}\n'
}

case "$1" in
    plan)         cmd_plan ;;
    ours)         cmd_ours ;;
    deactivate)   cmd_deactivate ;;
    purge)        cmd_purge ;;
    cron-restore) cmd_cron_restore ;;
    state)        cat "$STATE" 2>/dev/null || echo IDLE ;;
    busy)         un_busy ;;
    *) echo "usage: $0 plan | ours | deactivate | purge | cron-restore | state | busy"
       echo "  ours         — наши cron-строки и сниппеты dnsmasq (для диагностики; только чтение)"
       echo "  deactivate   — снять VPN (правила/демоны/cron/dnsmasq), файлы и панель ОСТАВИТЬ"
       echo "  purge        — то же + панель + снос каталогов кода/настроек/бинарей (роутер станет стоковым)"
       echo "  cron-restore — вернуть расписание, снятое деактивацией (зовёт vpn-toggle.sh on)"
       echo "  busy         — снимать сейчас нельзя? (идёт установка/обновление кода: печатает причину, код 0)"
       exit 2 ;;
esac
