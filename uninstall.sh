#!/bin/sh
# uninstall.sh — ЕДИНСТВЕННАЯ ИСТИНА «как снять систему с роутера».
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Логика удаления жила ТЕКСТОМ внутри enodia.py (action_uninstall) и по
# определению отставала от роутера: там нет ни слотов, ни awgs0 («доступ домой»), ни zapret/
# NFQUEUE, ни byedpi/xray/hev, ни второго uhttpd с panel-tls, ни цепочек PANEL_WAN/VPNSRV_*, ни
# /tmp/dnsmasq.d, ни 2FA — зато есть `killall amneziawg-go` (ровно тот баг, что вычищен из
# проекта: инстансов НЕСКОЛЬКО, killall уносит VPN-сервер и слот-выходы вместе с awg0) и
# `iptables -t mangle -F PREROUTING`, который сносит и СТОКОВЫЕ правила Xiaomi. Теперь удаление
# живёт РЯДОМ с тем, что удаляет, а панель и ПК-скрипт его ЗОВУТ.
#
# ТРИ УРОВНЯ (третий = второй + стирание файлов):
#   1. компонент      — packages.sh remove (карточка «Компоненты»), сюда не относится;
#   2. `deactivate`   — снять ВСЮ обвязку VPN: правила, демоны, cron, dnsmasq. ФАЙЛЫ И НАСТРОЙКИ
#                       НА МЕСТЕ, панель работает ⇒ можно вернуть всё обратно;
#   3. `purge`        — то же + панель + снос ВСЕХ ТРЁХ наших каталогов (код $ENODIA_DIR,
#                      настройки $ENODIA_STATE, бинари $ENODIA_BIN). Роутер становится стоковым.
# Бэкап настроек (`cgi-bin/backup ?secrets=0|1`) предлагает ВЫЗЫВАЮЩИЙ (панель/ПК) — здесь его
# нет намеренно: сохранять секреты «на всякий случай» без спроса нельзя.
#
# ПОРЯДОК ШАГОВ — не косметика:
#   правила → демоны → cron → dnsmasq → файлы → ПАНЕЛЬ ПОСЛЕДНЕЙ.
#   * правила раньше демонов: снятая несущая с живыми правилами = чёрная дыра (default в
#     table 1000 на мёртвый iface), а не «прямой режим»;
#   * cron раньше файлов: иначе heal.sh успеет переиграть то, что мы только что сняли;
#   * панель последней: она — единственный способ увидеть, чем кончилось, и из неё же нас
#     обычно и запускают.
#
# ПЕРЕЖИВАЕТ СМЕРТЬ СВОЕГО uhttpd И СОБСТВЕННОГО ФАЙЛА: `purge` копирует себя в /tmp и
# продолжает ОТТУДА (busybox sh дочитывает скрипт по ходу — снести файл из-под себя = оборвать
# удаление на середине). Панель зовёт нас через `start-stop-daemon -b`, так что смерть uhttpd
# нас не уносит, а отчёт мы пишем в ФАЙЛ (`$REPORT`) — показать его в панели будет уже некому.
#
# rm живёт ЗДЕСЬ (PS-guard на литерал rm). set -e НЕ используем — шаги best-effort: упавший шаг
# не должен оставить систему в полуснятом виде.

ENODIA_DIR=${ENODIA_DIR:-/data/usr/app/enodia}
ENODIA_BIN=${ENODIA_BIN:-/data/usr/app/enodia-bin}
# ЧЕТВЁРТЫЙ каталог — резидентный бутстрап: на него ссылаются ВСЕ cron-строки, и в режиме
# полной установки на накопитель он единственное, что от нас лежит на флеше роутера.
ENODIA_BOOT=${ENODIA_BOOT:-/data/usr/app/enodia-boot}
# Наши следы в /etc: hotplug-хук (вставка накопителя на ходу), init-скрипт раннего подъёма
# шифрованного DNS с его симлинком в rc.d и файл-проба «переживает ли /etc ребут».
# На BE7000 /etc — ramfs (всё исчезнет само), а на AX3600/BE3600 он ПЕРСИСТЕНТЕН ⇒ не снятые
# явно, они переживут удаление навсегда и будут звать пустой путь. Тот же класс, что
# `awg-custom.conf`, переживший ребрендинг.
HOTPLUG_HOOK=/etc/hotplug.d/block/99-enodia-usb
ETC_LEFTOVERS="/etc/init.d/enodia-early /etc/rc.d/S20enodia-early /etc/enodia-persist"
ENODIA_STATE=${ENODIA_STATE:-/data/usr/app/enodia-state}
# Сброс УЖЕ УСТАНОВЛЕННЫХ соединений — только через ct-lib.sh: на ядре 4.4 (AX3600/BE3600)
# утилиты conntrack в прошивке НЕТ ВООБЩЕ, и прежний `conntrack -F || true` был тихим no-op —
# правило стояло, а поток шёл по-старому через NSS/ECM. Шим = прежнее поведение (частичный
# apply-scripts не должен падать), полноценный сброс живёт в самой библиотеке.
if [ -f "$ENODIA_DIR/ct-lib.sh" ]; then . "$ENODIA_DIR/ct-lib.sh"; fi
# Ожидание xtables-лока: ipt-lib.sh подменяет команду `iptables` и добавляет `-w`. Лок занят
# чужим кроном ⇒ без ожидания правило МОЛЧА не встаёт. Нет файла — прежний путь байт-в-байт.
if [ -f "$ENODIA_DIR/ipt-lib.sh" ]; then . "$ENODIA_DIR/ipt-lib.sh"; fi
command -v ct_flush >/dev/null 2>&1 || ct_flush()      { conntrack -F >/dev/null 2>&1 || true; }
# «Жив ли держатель и тот ли это процесс» — единственный ответ у daemon-lib.sh (план спрашивает, идёт ли снятие). Шим —
# прежнее «жив» (частичный apply-scripts не должен ронять план).
if [ -f "$ENODIA_DIR/daemon-lib.sh" ]; then . "$ENODIA_DIR/daemon-lib.sh"; fi
command -v pid_runs >/dev/null 2>&1 || pid_runs() { [ -n "$1" ] && kill -0 "$1" 2>/dev/null; }
command -v pkg_install_alive >/dev/null 2>&1 || pkg_install_alive() { return 1; }
command -v uninstall_alive >/dev/null 2>&1 || uninstall_alive() {
    _ual=$(cat /tmp/enodia-uninstall.pid 2>/dev/null | tr -cd '0-9'); pid_runs "$_ual" 'uninstall\.sh (deactivate|purge)'; }
SELF=/tmp/enodia-uninstall.sh              # копия для purge (см. выше)
UN_PID=/tmp/enodia-uninstall.pid           # «идёт снятие» для установщика кода (daemon-lib.sh::uninstall_alive)
# ОТЧЁТ — НА НАШЕМ ТОМЕ И ВНЕ ВСЕГО, ЧТО СНОСИТ purge. Три условия разом:
#  * вне $ENODIA_DIR — purge стирает каталог вместе с логами;
#  * вне $ENODIA_DIR/.. (`/data/usr/app`) — его purge добивает `rmdir`, и файл внутри либо
#    погиб бы, либо помешал каталогу убраться («вернулся к стоку» стало бы неправдой);
#  * на НАШЕМ томе. Прежний `/data/…` — литерал, и на BE10000 (RC01) это ЧУЖОЙ стоковый cfg-том
#    (4.7 МБ, забит Xiaomi, свободно ~700 КБ): отчёт об удалении писался бы туда, где может не
#    оказаться места, ровно тогда, когда он единственный источник правды. `/data/usr` — корень
#    тома, на котором живёт весь наш код (на BE7000/AX3600 это тот же том, что `/data`).
# Префикс `enodia-` обязателен: namespace там общий со стоком (рядом лежит его `log/`).
REPORT=/data/usr/enodia-uninstall.log
STATE="$ENODIA_STATE/.uninstall.state"       # RUNNING|OK|FAIL — панель опрашивает, пока жива

# store-lib.sh — ЕСТЬ ЛИ внешний накопитель и где он: «полное удаление» уносит и хранилище на
# флешке — единственное, что удаление трогает ВНЕ роутера, и экран подтверждения обязан назвать его
# отдельной строкой. Шим (как у всех потребителей): старый роутер без библиотеки отвечает прежним
# путём байт-в-байт. `bin_path` отсюда ушёл вместе с проверкой «стоит ли zapret» ПО ФАКТУ БИНАРЯ:
# про десинк теперь отвечает его владелец (см. `zapret_live`).
if [ -f "$ENODIA_DIR/store-lib.sh" ]; then . "$ENODIA_DIR/store-lib.sh"; fi
command -v store_ready >/dev/null 2>&1 || store_ready() { return 1; }
command -v store_root >/dev/null 2>&1 || store_root() { printf ''; }

log() { printf '[%s] %s\n' "$(date '+%H:%M:%S')" "$*" >> "$REPORT"; echo "$*"; }
# Итог — АТОМАРНО (рядом + `mv`): `>` сперва обрезает, и гард «удаление уже идёт» в CGI, попав в это окно, читал пусто и пускал
# второе снятие поверх первого (разбор у packages.sh::set_state; следит C105).
set_state() { [ -d "$ENODIA_DIR" ] && { echo "$1" > "$STATE.new" 2>/dev/null && mv -f "$STATE.new" "$STATE" 2>/dev/null; }; return 0; }
# Гард — `-f`, а НЕ `-x`, и запуск через `sh`: снятый бит выполнения (дрейф деплоя, ручная
# копия, распаковка чужим архиватором) означал бы ТИХИЙ пропуск teardown его владельца при
# бодром «Правила сняты» в отчёте. Для `purge` цена особенно велика: файлы мы сотрём, а
# правила и демоны останутся жить, и чинить их будет уже нечем — скриптов нет.
run() { [ -f "$ENODIA_DIR/$1" ] || return 0; _s="$1"; shift; sh "$ENODIA_DIR/$_s" "$@" >> "$REPORT" 2>&1; return 0; }

# --- ЧТО СНОСИМ: списки в ОДНОМ месте ------------------------------------------------
# Новая цепочка/сет/сниппет в проекте = ОДНО слово здесь (тот же приём, что у ZAPRET_SETS и
# BYPASS_SETS). Иначе забытый артефакт переживает удаление и всплывает как «роутер ведёт себя
# странно после того, как я всё снёс».
# Цепочки БЕЗ своего верба-teardown (у кого верб есть — зовём владельца, см. step_rules).
# PANEL_WAN/PANEL_WAN_DNAT здесь НЕТ намеренно: это цепочки ПАНЕЛИ, а не VPN — при деактивации
# панель остаётся жить вместе со входом снаружи; на полном удалении их снимает `web-ui.sh wan-off`.
CHAINS_MANGLE="VPN_EXCLUDE VPN_FORCE VPN_PORTS VPN_KEEP VPN_DEV ENODIA_ZAPRET"
CHAINS_FILTER="ENODIA_BLK ENODIA_GEOBLK VPNSRV_IN VPNSRV_FWD VPNSRV_WAN"
# Родители, из которых вызываются наши filter-цепочки: штатные INPUT/FORWARD + пустой хук fw3
# `input_wan_rule` (в него вешаются правила «снаружи» — панели и «доступа домой»).
CHAIN_PARENTS="INPUT FORWARD input_wan_rule"
# ipset'ы сносим ПО ПРЕФИКСУ: их имена генерятся (grp_vpn_s3, geo_vpn_s2, *_new от прерванного
# swap) и перечислить их поимённо = гарантированно отстать. Проверено на живом BE7000: чужие
# сеты там только `mwan3_*` (стоковый multi-wan) — наши префиксы с ними не пересекаются.
SET_PREFIXES="enodia_ iplist_ grp_ geo_ zapret_ blocklist_ xiaomi_"
# Демоны: матчим по /proc/*/cmdline с ПОЛНЫМ путём. НИКАКИХ killall: инстансов amneziawg-go
# несколько (awg0 · awgN слотов · awgs0 «доступа домой»).
# ПУТЕЙ ДВА, и это не паранойя: с внешним накопителем xray/hysteria/hev/byedpi/nfqws запускаются
# из `$BIN_DIR` (= <хранилище>/bin), и матч только по каталогу кода не находил их вовсе.
# Резидентно они лежат в `$ENODIA_BIN` — это ТРЕТИЙ путь, и он обязателен: каталог кода
# не содержит ни одного бинаря с тех пор, как состояние и бинари уехали из него. Штатно их
# гасят владельцы по пидфайлу (step_rules выше), но этот шаг — страховка «владелец не сработал»,
# а на `purge` она последняя: каталог с пидфайлами через несколько строк исчезнет, и убивать
# переживший демон будет уже нечем.
DAEMON_DIRS="$ENODIA_DIR $ENODIA_BIN"
[ "${BIN_DIR:-$ENODIA_BIN}" != "$ENODIA_BIN" ] && DAEMON_DIRS="$DAEMON_DIRS $BIN_DIR"
DAEMONS="amneziawg-go xray hysteria byedpi hev nfqws https-dns-proxy dot-proxy"
# panel-tls — инфраструктура ПАНЕЛИ, а не VPN. `deactivate` обещает «панель работает», а вход в
# неё мог идти по HTTPS: убив терминатор, мы рвём сессию человеку ровно в тот момент, когда он
# нажал кнопку, и вернёт его только cron `web-ui.sh start` (до 5 минут). На `purge` панель и так
# снимается, поэтому там он остаётся в списке — страховкой на случай, если web-ui.sh не отработал.
DAEMONS_PURGE="panel-tls"
# Интерфейсы: awg0/awgN/awgs0 (amneziawg) + xtun/xtunN (tun2socks). Свои таблицы — 1000 и 100N.
IFACES="awg0 awg2 awg3 awg4 awgs0 xtun xtun2 xtun3 xtun4"
TABLES="1000 1002 1003 1004"
# НАШИ `ip rule` ВНЕ $TABLES — их доборка по номеру таблицы не видит В ПРИНЦИПЕ: одно смотрит в
# table 200, второе вообще в СТОКОВУЮ main. Обе строки пережили полное удаление на живом AX3600
# (16.08.2026), при том что отчёт обещал «роутер вернулся к стоковому состоянию», а доборка
# насчитала «0 артефактов». Каждое правило — ДВЕ записи, потому что формы РАЗНЫЕ: `ip rule show`
# печатает «lookup», а `ip rule del` понимает «table … pref …».
#   1) гостевая ЦЕЛИКОМ в туннель — ставил вендоренный `awg_setup.sh` (оттуда уже убрано, но у
#      обновившихся роутеров живёт в RAM до ребута);
#   2) гостевая МИМО VPN — ставит `apply-bypass.sh` по флагу `.bypass-guest`, и владельца этого
#      правила удаление не звало НИКОГДА: чужих таблиц у него нет, чужих цепочек тоже.
# В шаблоне ОБЯЗАТЕЛЕН приоритет («^90:»): без него `grep` поймал бы любую чужую строку с той же
# подсетью, а `ip rule del … pref 90` её не снял бы — цикл вышел бы по `|| break`, но счётчик уже
# вырос, и вердикт вечно рапортовал бы «снято не всё» на роутере, где всё чисто.
GUEST_RULE_SHOW="^200:.*from 192.168.33.0/24 lookup 200"
GUEST_RULE_DEL="from 192.168.33.0/24 table 200 pref 200"
GUEST_BYPASS_SHOW="^90:.*from 192.168.33.0/24 lookup main"
GUEST_BYPASS_DEL="from 192.168.33.0/24 lookup main pref 90"
#   3) гостевой DNS мимо туннеля — тоже `awg_setup.sh`, и он ОСТАЁТСЯ в рабочем режиме (без него
#      запрос гостя к 192.168.33.1 уехал бы в туннель), но после удаления он такой же сирота.
#      Замерено на живом BE7000: все три строки стоят одновременно.
GUEST_DNS_SHOW="^100:.*from 192.168.33.0/24 to 192.168.33.1 dport 53 lookup main"
GUEST_DNS_DEL="from 192.168.33.0/24 to 192.168.33.1 dport 53 table main pref 100"
# Наше рантайм-состояние в /tmp (гибнет на ребуте, но «снёс и работаю дальше» — законный сценарий,
# а протухший штамп/лок переживает удаление и встречает ПЕРЕустановку). Список ЯВНЫЙ и по нашим
# префиксам: в /tmp рядом лежат стоковые `messages`, `luci-*`, `TunnelService.*`, `miqos*` —
# маска вроде `/tmp/*.log` унесла бы их (та же грабля, что у RAM_LOGS в clean.sh). Проверено
# по живому листингу BE7000 14.08.2026 и по ПОСТ-PURGE листингу AX3600 16.08.2026 (в `/tmp` из
# точечных файлов остался ровно один чужой — стоковый `.uci`): под эти маски не попадает НИ ОДНОГО
# чужого файла.
# КЭШИ ПРОБ — отдельным поводом дописать сюда, а не «ещё четыре файла». Прогон purge на AX3600
# показал, что список пропускал `.zapret-nfq-cap` (умеет ли ядро NFQUEUE), `.curl-cafile` (нужен ли
# `--cacert`), `.vpnsrv-ext` (внешний IPv4 «доступа домой») и `.cpu-stat` (снимок счётчиков ЦП).
# Это не мусор, а ЗАПОМНЕННЫЕ ОТВЕТЫ: пережив удаление, они встречают ПЕРЕустановку уже готовыми,
# и свежая система принимает их за свои, ничего не перемеряв. `.vpnsrv-ext` вдобавок хранит
# публичный адрес — единственный из четырёх, что несёт данные.
# Сюда же попадает `/tmp/enodia-uninstall.pid` — пидфайл ТЕКУЩЕГО прогона (пишут `spawn_bg` в cgi-bin/action
# и сам un_gate). Читают его панель и установщик кода (`uninstall_alive`: «идёт снятие» — не ставить); снять его
# на ходу безопасно: панели к этому моменту уже нет (step_ram идёт ПОСЛЕ step_panel), а установке ставить некуда —
# тот же шаг сносит пакет ПК в /tmp, а каталоги кода уже сняты. В `deactivate` шаг не работает вовсе.
# СПИСОК СВЕРЕН МАШИННО (01.09.2026) и с тех пор сторожится C61: она вытаскивает ВСЕ литералы
# `/tmp/...` из наших скриптов и CGI и требует, чтобы каждый попадал под маску. Первый же прогон
# нашёл 42 непокрытых имени — локи, пидфайлы и запомненные ответы, которые переживали `purge` и
# встречали ПЕРЕустановку готовыми (свежая система принимала их за свои и ничего не перемеряла).
# А 03.09.2026 список СХЛОПНУЛСЯ до двух масок — и это не упрощение, а следствие: с того дня
# КАЖДОЕ наше имя в /tmp несёт префикс (следит C74), так что перечислять семейства больше нечего.
# Исключение ровно одно и названо в C72 — четыре пути логов xray: они лежат ВНУТРИ
# пользовательских конфигов на /data, и переименование там было бы миграцией хранилища.
RAM_GLOBS="/tmp/enodia-* /tmp/.enodia-*
/tmp/xray.log* /tmp/xray-access.log /tmp/xray-s*.log /tmp/xray-test.*.log"
# Метка НАШИХ строк в /etc/hosts (dns-lib.sh::seed_hosts_put). Третья копия ответа для server-host
# появилась позже этого файла, и снимать её обязаны МЫ: Go-демоны читают hosts ДО резолвера, то
# есть пережившая удаление строка прибивает домен к нашему старому адресу для ВСЕГО роутера.
# ПРЕЖНИЕ ИМЕНА в /tmp — отдельной переменной, а не строкой внутри RAM_GLOBS: внутри строки
# комментарий не поставить, а пометка обязательна (C54 иначе читает это как ЖИВОГО писателя
# под старым именем). Подбираем и забываем: сами мы таких имён больше не заводим.
RAM_GLOBS_LEGACY="/tmp/.awg-* /tmp/awg-uninstall.sh* /tmp/panel-token /tmp/hev*.yaml
/tmp/doh.log /tmp/notify.log /tmp/support.log /tmp/iplist-update.log /tmp/switch-vpn-setup.log
/tmp/notify-event.log /tmp/transport-awg-setup.log /tmp/panel-tls.log /tmp/xiaomi-bypass.log
/tmp/subs-update.log /tmp/byedpi.log /tmp/byedpi-fetch.log /tmp/byedpi-test-run.log
