# detect — что роутер видит ПРЯМО СЕЙЧАС, без монтирования: dev, ФС, точка, наш ли.
# Несмонтированное честно печатается с «?» вместо ФС: узнать её без монтирования нечем
# (blkid на роутере нет), а монтировать в информационном вербе — побочный эффект.
cmd_detect() {
    # ЦЕЛОЕ УСТРОЙСТВО ПРЯЧЕМ, если его раздел уже в списке: физически это ОДНА флешка, а
    # панель по этому списку предлагает выбор («перенести на какой?») — две строки на один
    # носитель читались бы как два накопителя. Разделы у mount_candidates идут первыми, поэтому
    # к моменту разбора sdX список их дисков уже полон.
    _seen=""
    while read -r _d _m _t _rest; do
        case "$_d" in /dev/sd*) ;; *) continue ;; esac
        _o=no; [ -n "$(store_of_mount "$_m")" ] && _o=yes
        _n=${_d#/dev/}
        case "$_n" in sd[a-z][0-9]*) _seen="$_seen ${_n%%[0-9]*}" ;; esac
        printf '%s\t%s\t%s\t%s\n' "$_d" "$_t" "$_m" "$_o"
    done < "$MOUNTS"
    for _dev in $(mount_candidates); do
        _n=${_dev#/dev/}
        case "$_n" in
            sd[a-z]) case " $_seen " in *" $_n "*) continue ;; esac ;;
            *)       _seen="$_seen ${_n%%[0-9]*}" ;;
        esac
        printf '%s\t?\t-\t?\n' "$_dev"
    done
}

# Взять лок. Аргумент — СКОЛЬКО СЕКУНД ЖДАТЬ, и он разный по смыслу вызова: кнопке панели ждать
# нормально (перенос 8-МБ xray на медленной флешке — это секунды), а тику cron ждать НЕЛЬЗЯ:
# ждущие тики копятся, и через полчаса их десяток. Тик просто уходит — он идемпотентен и
# повторится через 2 минуты.
# ПРОТУХШИЙ ЛОК СНИМАЕМ ПО ФАКТУ СМЕРТИ ДЕРЖАТЕЛЯ (`/proc/<pid>`), а не по возрасту: перенос
# бывает и правда долгим. Пустой pid — это ОКНО между `mkdir` и записью pid, а не протухший
# лок: снять его сразу значило бы завести двух писателей, то есть ровно то, от чего лок и
# заведён. Ждём подтверждения — пусто три тика подряд (идиома dns-merge.sh::lock_take).
# СНЯЛИ ПРОТУХШИЙ ЛОК — ТУТ ЖЕ И ПРОБУЕМ СНОВА (`continue`), не тратя бюджет ожидания: бюджет
# про то, «сколько ждать ЖИВОГО держателя», а мёртвого ждать нечего. Замерено на BE7000: без
# этого тик cron честно снимал лок и всё равно уходил ни с чем, то есть накопитель поднимался
# только следующим тиком — через 2 минуты. Число снятий ограничено (`_ulb`): если mkdir падает
# по ДРУГОЙ причине (в /tmp кончилось место, на месте каталога лежит файл), цикл обязан
# кончиться отказом, а не крутиться вечно.
usb_lock() {
    _ulw=${1:-0}; _uli=0; _ule=0; _ulb=0
    while :; do
        if mkdir "$USB_LOCK" 2>/dev/null; then printf '%s' "$$" > "$USB_LOCK/pid" 2>/dev/null; return 0; fi
        _ulp=$(cat "$USB_LOCK/pid" 2>/dev/null)
        case "$_ulp" in
            # Пусто — ОКНО между mkdir и записью pid, а не протухший лок: ждём подтверждения
            # (пусто три ОПРОСА подряд, между ними sleep), иначе заведём двух писателей.
            ''|*[!0-9]*)
                _ule=$((_ule + 1))
                if [ "$_ule" -ge 3 ] && [ "$_ulb" -lt 3 ]; then
                    rm -rf "$USB_LOCK" 2>/dev/null; _ulb=$((_ulb + 1)); _ule=0; continue
                fi ;;
            # Держатель мёртв — свидетельство окончательное, снимаем и идём на второй заход.
            *)
                _ule=0
                if [ ! -d "/proc/$_ulp" ] && [ "$_ulb" -lt 3 ]; then
                    rm -rf "$USB_LOCK" 2>/dev/null; _ulb=$((_ulb + 1)); continue
                fi ;;
        esac
        [ "$_uli" -ge "$_ulw" ] && return 1
        _uli=$((_uli + 1)); sleep 1
    done
}
usb_unlock() { rm -rf "$USB_LOCK" 2>/dev/null; }
# Снять лок, ТОЛЬКО ЕСЛИ ОН НАШ. Нужно продолжению переезда: `exec` сохраняет PID, но
# ловушку EXIT — нет, поэтому лок в новый образ приезжает «висящим», и снять его обязан
# он же. Слепой `rm -rf` тут был бы кражей чужого лока при вызове верба руками.
usb_unlock_mine() {
    _ulm=
    [ -f "$USB_LOCK/pid" ] && read -r _ulm < "$USB_LOCK/pid" 2>/dev/null
    [ "$_ulm" = "$$" ] && rm -rf "$USB_LOCK" 2>/dev/null
    return 0
}

