# switching-лок. Перенос двигает бинари, которыми они судят о несущей и поднимают её. Замер на BE7000 28.09.2026: тик сторожа
# пришёлся на смену раскладки full → bins, `awg` в этот момент не было ни на старом месте, ни на новом — «VPS МЁРТВ (handshake
# 999999с) → прямой режим», две минуты мимо VPN при живом туннеле. Своего гейта сторожу не заводим: switching-лок — его ПЕРВЫЙ
# гейт, его же знают вердикт панели и heal, а протухание судит сторож (`SWITCH_STALE`).
# ПОРЯДОК (ревью ветки, круг 1): СПЕРВА дождаться, что несущую не ведёт НИКТО — ни тик сторожа (`wd_tick_alive`, daemon-lib.sh), ни
# чужая смена (switching-лок уже лежит), — и ЛИШЬ ПОТОМ взять лок самим и исключительно (noclobber). Лок, взятый до ожидания,
# обрывал тику перебор резервов xray/hy2 (плагин проверяет лок на каждой итерации и уходит в эскалацию), а «прокатиться» на чужом
# локе нельзя: держатель снимет его посреди переноса, и следующий тик попадёт внутрь. Взяв, переспрашиваем тик через секунду: между
# его гейтом и записью пида есть щель, и проскочившего в неё дожидаемся уже с локом в руках (новых он не пустит). Потолок
# MOVE_TICK_WAIT — ради синхронной кнопки панели (uhttpd режет долгий CGI); не дождались — отказ ДО первого движения.
MOVE_TICK_WAIT=${MOVE_TICK_WAIT:-30}
MOVE_MODE_WAIT=${MOVE_MODE_WAIT:-300}         # смена раскладки — фоном, ей ждать можно дольше (cmd_mode)
MOVE_GAP_WAIT=${MOVE_GAP_WAIT:-1}
MOVE_LISTS_WAIT=${MOVE_LISTS_WAIT:-300}       # смена раскладки ждёт сборку списков/гео (cmd_mode; разбор там)
if [ -f "$ENODIA_DIR/daemon-lib.sh" ]; then . "$ENODIA_DIR/daemon-lib.sh"; fi
command -v lists_work_alive >/dev/null 2>&1 || lists_work_alive() { return 1; }   # старая библиотека — не ждём, как раньше
command -v wd_tick_alive >/dev/null 2>&1 || wd_tick_alive() { return 1; }   # старая библиотека — тика не ждём, как раньше
