command -v exe_deleted >/dev/null 2>&1 || exe_deleted() { ls -l /proc/[0-9]*/exe 2>/dev/null | sed -n 's#^.* /proc/\([0-9][0-9]*\)/exe -> \(.*\) (deleted)$#\1 \2#p'; }
command -v store_mode_alive >/dev/null 2>&1 || store_mode_alive() {   # старая библиотека — прежнее «жив ли pid»
    _sma=$(cat /tmp/enodia-store-mode.pid 2>/dev/null | tr -cd '0-9'); [ -n "$_sma" ] && [ -d "/proc/$_sma" ]; }
# Несущую ведёт тик сторожа ЛИБО прогон heal: heal проверяет switching-лок один раз, на старте, и начатый до переноса прогон идёт
# насквозь — поднимает несущую бинарём, которого в эту секунду нет ни на одном месте (ревью ветки, круг 2).
command -v carrier_busy >/dev/null 2>&1 || carrier_busy() { wd_tick_alive || heal_alive; }   # старая библиотека — тот же ответ
move_hold() {
    [ "$ENODIA_MOVE_SW" = 1 ] && return 0          # продолжение смены раскладки: лок уже наш
    _mhw=0
    while :; do
        if ! carrier_busy && ( set -C; : > "$SWITCH_LOCK" ) 2>/dev/null; then
            ENODIA_MOVE_SW=1
            sleep "$MOVE_GAP_WAIT"
            while carrier_busy && [ "$_mhw" -lt "$MOVE_TICK_WAIT" ]; do sleep 1; _mhw=$((_mhw + 1)); done
            carrier_busy || break
            move_release
        fi
        if [ "$_mhw" -ge "$MOVE_TICK_WAIT" ]; then
            echo "роутер сейчас проверяет или поднимает туннель — ничего не переносил, повторите через минуту" >&2
            return 1
        fi
        sleep 1; _mhw=$((_mhw + 1))
    done
    # Установка компонентов могла начаться, пока мы ждали: диспетчер спросил её лок ДО ожидания.
    if [ -d "$PKG_LOCK" ]; then
        move_release
        echo "идёт установка компонентов — дождитесь её окончания (экран «Компоненты») и повторите" >&2
        return 1
    fi
    # …и установка КОДА (обновление, откат, установка с ПК) или обновление, ещё качающее пакет (ревью ветки pkg-update, круг 1):
    # переезд сносит каталог, в который они пишут, — на флеше вырастала вторая, пустая система. Ответы — у владельцев
    # (daemon-lib.sh::pkg_install_alive, gh-update.sh upd-busy); спрашиваем ПОСЛЕ своего лока и пидфайла — хотя бы один из двух
    # увидит другого (обратную сторону держит pkg-install.sh::pi_gate и gh-update.sh::upd_store_busy).
    if pkg_install_alive || { [ -f "$ENODIA_DIR/gh-update.sh" ] && sh "$ENODIA_DIR/gh-update.sh" upd-busy >/dev/null 2>&1; }; then
        move_release
        echo "идёт обновление кода — дождитесь его окончания и повторите" >&2
        return 1
    fi
    return 0
}

# Хранилище нашли, а резолвер его НЕ ПРИНЯЛ: сентинел исчез, ФС ушла в ro, флешку выдернули
# между сканированием и записью маркера. Говорим ОДИН раз на загрузку — ТЕМ ЖЕ штампом, что и
# «накопитель не найден» (беда одного класса: бинарей на месте нет). Без штампа это тик cron
# каждые 2 минуты = 720 строк в сутки в watchdog-лог, который лежит в /tmp и не ротируется.
# МАРКЕР НЕ СНИМАЕМ: «забыть накопитель» — решение человека, а у нас, скорее всего, временная
# беда; честный ответ «хранилища сейчас нет» и так возвращает всех к резидентным путям.
# И СВОЙ МОНТАЖ НЕ ОТПУСКАЕМ (если монтировали мы): следующий тик найдёт его быстрым путём
# через /proc/mounts и, если сентинел вернулся, поднимет хранилище без второго монтажа.
store_rejected() {
    if [ ! -f "$MISS_STAMP" ]; then
        : > "$MISS_STAMP" 2>/dev/null
        echo "usb-offload: каталог $1 больше не опознаётся как хранилище — бинари ищутся на флеше роутера"
    fi
    return 1
}

# mount-ensure — сделать хранилище доступным. Зовут heal.sh (ДО подъёма несущей на буте) и
# watchdog.sh (переткнули флешку на ходу). Молчит, когда делать нечего: в норме это тик cron.
# Код 0 = хранилище доступно, 1 = нет (в т.ч. «оффлоад не включали» — самый частый случай).
cmd_mount_ensure() {
    [ -f "$STORE_MARK" ] || return 1        # маркера нет ⇒ накопитель не наш сценарий, no-op
    store_ready && { rm -f "$MISS_STAMP" 2>/dev/null; resolve_dups; seen_note; return 0; }   # уже на месте
    # Сам ПОИСК носителя живёт в mount-lib.sh — его же зовёт резидентный boot.sh. Здесь остаётся
    # то, чего бутстрап не делает: маркер, разбор дублей и сообщения движка.
    # Предупреждение печатаем ДО вердикта: накопитель, не поднявшийся на запись, — единственная
    # причина отказа, которую человек может починить сам (перевоткнуть, размонтировать начисто).
    if store_locate; then
        [ -n "$STORE_FOUND_WARN" ] && echo "usb-offload: $STORE_FOUND_WARN"
        mark_write "$STORE_FOUND" || { store_rejected "$STORE_FOUND"; return 1; }
        rm -f "$MISS_STAMP" 2>/dev/null
        if [ "$STORE_FOUND_HOW" = system ]; then
            echo "usb-offload: хранилище $STORE_FOUND (смонтировано системой)"
        else
            echo "usb-offload: хранилище $STORE_FOUND ($STORE_FOUND_HOW, $(fs_of_mount "$MNT"))"
        fi
        resolve_dups
        seen_note
        return 0
    fi
    [ -n "$STORE_FOUND_WARN" ] && echo "usb-offload: $STORE_FOUND_WARN"
    # «Накопитель включён, но выдернут» — ШТАТНОЕ состояние (панель показывает его третьим),
    # а зовут нас с cron каждые 2 минуты: без штампа это 720 строк в сутки в watchdog-лог,
    # который лежит в /tmp (=ОЗУ) и не ротируется, да ещё и ломает инвариант «в здоровом NORMAL
    # watchdog молчит». Говорим ОДИН раз на загрузку (штамп тоже в /tmp ⇒ после ребута скажем
    # снова), а вернулся накопитель — штамп снимаем, чтобы следующая пропажа не осталась немой.
    if [ ! -f "$MISS_STAMP" ]; then
        : > "$MISS_STAMP" 2>/dev/null
        echo "usb-offload: накопитель с хранилищем не найден — бинари ищутся на флеше роутера"
    fi
    return 1
}

# Выбрать накопитель под НОВОЕ хранилище. Явный аргумент (устройство или готовая точка) главнее
# всего; без аргумента годится РОВНО ОДИН кандидат — при нескольких отказываемся и показываем
# список: угадывать, на какую из двух флешек селиться, движок не вправе.
prepare_store() {   # $1 = /dev/sdX1 | точка монтирования | пусто
    _mp=""
    if [ -n "$1" ]; then
        case "$1" in
            /dev/*) _dev="$1" ;;
            /*)     [ -d "$1" ] || { echo "нет такого каталога: $1" >&2; return 1; }
                    _mp="$1"; _dev="" ;;
            *)      _dev="/dev/$1" ;;
        esac
        if [ -n "$_dev" ]; then
            [ -b "$_dev" ] || { echo "нет такого устройства: $_dev" >&2; return 1; }
            _mp=""
            while read -r _d _m _t _rest; do
                [ "$_d" = "$_dev" ] && { _mp="$_m"; break; }
            done < "$MOUNTS"
            if [ -z "$_mp" ]; then
                mkdir -p "$MNT" 2>/dev/null
                try_mount "$_dev" "$MNT" || { echo "не смонтировался $_dev (ФС не опознана?)" >&2; return 1; }
                _mp="$MNT"
            fi
        fi
    else
        # Считаем ФИЗИЧЕСКИЕ накопители, а не узлы: у одной флешки видны И раздел (sda1,
        # смонтирован стоком), И целое устройство (sda, свободно) ⇒ подсчёт по узлам объявлял
        # единственную воткнутую флешку «несколькими» и требовал указать её руками.
        _n=0; _disks=""; _cand=""
        while read -r _d _m _t _rest; do
            case "$_d" in /dev/sd*) ;; *) continue ;; esac
            _dsk=${_d#/dev/}; _dsk=${_dsk%%[0-9]*}
            case " $_disks " in *" $_dsk "*) ;; *) _disks="$_disks $_dsk"; _n=$((_n+1)) ;; esac
            [ -z "$_mp" ] && _mp="$_m"     # смонтированное предпочтительнее: второй монтаж того же не нужен
        done < "$MOUNTS"
        for _dev in $(mount_candidates); do
            _dsk=${_dev#/dev/}; _dsk=${_dsk%%[0-9]*}
            case " $_disks " in *" $_dsk "*) ;; *) _disks="$_disks $_dsk"; _n=$((_n+1)) ;; esac
            [ -z "$_cand" ] && _cand="$_dev"
        done
        if [ "$_n" = 0 ]; then
            echo "накопитель не найден: воткните флешку в USB-порт роутера" >&2; return 1
        fi
        if [ "$_n" -gt 1 ]; then
            echo "накопителей несколько — укажите нужный явно (usb-offload.sh enable /dev/sdX1):" >&2
            cmd_detect >&2
            return 1
        fi
        if [ -z "$_mp" ]; then
            mkdir -p "$MNT" 2>/dev/null
            try_mount "$_cand" "$MNT" || { echo "не смонтировался $_cand (ФС не опознана?)" >&2; return 1; }
            _mp="$MNT"
        fi
    fi
    # Готовим раскладку. Запись ПРОВЕРЯЕМ: ФС могла смонтироваться read-only (грязный размонтаж
    # NTFS/exFAT — штатное поведение ядра), и тогда «хранилище создано» было бы враньём.
    mkdir -p "$_mp/$STORE_SUB/bin" 2>/dev/null
    # СОЗДАЁМ хранилище и проверяем СВОЮ ЖЕ запись — это не опознание чужого каталога (им занят
    # один store_is_ours в store-lib.sh; следит C57).
    printf 'enodia bin store\n' > "$_mp/$STORE_SUB/$STORE_SENTINEL" 2>/dev/null   # sentinel-write:
    if [ ! -f "$_mp/$STORE_SUB/$STORE_SENTINEL" ] || [ ! -d "$_mp/$STORE_SUB/bin" ]; then   # sentinel-write:
        echo "на накопителе не пишется ($_mp) — смонтирован только для чтения?" >&2; return 1
    fi
    printf '%s' "$_mp/$STORE_SUB"
    return 0
}

cmd_enable() {
    if ! store_ready; then cmd_mount_ensure >/dev/null 2>&1; fi
    if store_ready; then
        _store=$(store_root)
        echo "Хранилище: $_store (уже подготовлено)"
    else
        # Маркера нет, но на воткнутом накопителе УЖЕ лежит наш сентинел (переустановка, снесённый
        # маркер, флешка от прошлой машины) — это то же хранилище: усыновляем. Иначе выбор диска
        # пошёл бы общим путём и мог сесть на ДРУГОЙ накопитель, оставив прежние бинари сиротами.
        _store=$(find_mounted_store) || _store=""
        if [ -n "$_store" ] && [ -z "$1" ]; then
            mark_write "$_store"
            echo "Хранилище: $_store (найдено на накопителе)"
        else
            _store=$(prepare_store "$1") || return 1
            mark_write "$_store"
            echo "Хранилище: $_store (создано)"
        fi
        # ГАРД НА ОБЕ ВЕТКИ: маркер записан, но резолвер его ПРИНЯЛ ли? Пока хранилище не
        # опознано, BIN_DIR = резидентный каталог, и цикл ниже «переселял» бы каждый бинарь
        # в самого себя. Отказ ДО первого движения — то же правило, что у гарда места.
        store_ready || { echo "хранилище $_store не опознано (нет сентинела или каталога bin?) — ничего не переношу" >&2; return 1; }
    fi
    drop_stale_new
    echo "Переселяю тяжёлые бинари:"
    _moved=0; _failed=0; _had=0; _kept=0; _back=0
    for _b in $STORE_MOVABLE; do
        # Общее включение накопителя НЕ отменяет поштучного решения человека: закреплённый бинарь
        # остаётся на роутере. Иначе кнопка «включить» молча стирала бы настройку, ради которой
        # закрепление и заводили.
        if bin_pinned "$_b"; then
            # И наоборот: закреплённый, который ЛЕЖИТ В ХРАНИЛИЩЕ, здесь ЗАБИРАЕМ. Так бывает
            # после импорта чужого бэкапа (закрепления приехали, файлы уже на флешке) и после
            # неудавшегося переноса. Без этого шага `place` обещает «учтётся при включении
            # накопителя», а включение ничего не делает — то есть обещание ложное, и человек
            # видит «накопитель · закреплён» бесконечно. Гард места тот же, что у place.
            # ТОЛЬКО когда резидентной копии НЕТ. Если есть обе — это случай дублей, и там
            # права РЕЗИДЕНТНАЯ (её положил писатель, пока хранилища не было; так же судит
            # resolve_dups). Слепой перенос затёр бы более новый файл более старым — то есть
            # «обновил, и вернулась прошлая версия».
            if [ "$BIN_DIR" != "$ENODIA_BIN" ] && [ -f "$BIN_DIR/$_b" ] && [ ! -f "$ENODIA_BIN/$_b" ]; then
                if fits_router "$_b" && move_verified "$BIN_DIR/$_b" "$ENODIA_BIN/$_b" "$_b"; then
                    _back=$((_back+1))
                else
                    echo "  $_b: закреплён, но забрать с накопителя не вышло (место? битая копия?) — остаётся там"
                    _failed=$((_failed+1))
                fi
            elif [ -f "$ENODIA_BIN/$_b" ]; then
                echo "  $_b: закреплён за роутером — оставляю на месте"
            fi
            _kept=$((_kept+1)); continue
        fi
        [ -f "$ENODIA_BIN/$_b" ] || continue
        _had=$((_had+1))
        if move_verified "$ENODIA_BIN/$_b" "$BIN_DIR/$_b" "$_b"; then _moved=$((_moved+1)); else _failed=$((_failed+1)); fi
    done
    if [ "$_had" = 0 ] && [ "$_kept" = 0 ]; then echo "  (переселять нечего — тяжёлых бинарей на флеше роутера нет)"; fi
    # Снимок — сразу, а не ближайшим тиком: флешку могут выдернуть через минуту после переезда, и
    # «что на ней было» обязано быть известно уже тогда.
    seen_note
    echo "Переселено: $_moved, забрано обратно: $_back, не вышло: $_failed, закреплено за роутером: $_kept"
    free_line
    # Несущую НЕ трогаем: запущенный демон продолжает работать со СВОЕГО (уже удалённого) inode,
    # а следующий подъём — хоть watchdog'ом, хоть ребутом — возьмёт копию с накопителя. Рвать
    # рабочий туннель ради проверки, которую только что сделал exec_ok, незачем. Но место этот
    # inode держит до перезапуска — о нём говорит итоговая строка (free_line → old_place_names).
    if [ "$_failed" -gt 0 ]; then
        # ПРИЧИНА — ПОСЛЕДНЕЙ СТРОКОЙ. Панель берёт у этого верба `tail -1`, а последней до сих
        # пор была «Свободно на /data: N МБ»: под красным тостом стояла ПОЛОЖИТЕЛЬНАЯ фраза, по
        # которой невозможно понять, что именно не поехало. Подробности остаются выше.
        echo "Не переехало файлов: $_failed — причина у каждого строкой выше (место? битая копия? не запускается с этой ФС?)" >&2
        return 1
    fi
    return 0
}

cmd_disable() {
    if ! store_ready; then
        cmd_mount_ensure >/dev/null 2>&1
        if ! store_ready; then
            # Пропавший накопитель, на котором НАШЕГО не было (снимок пуст): возвращать нечего и
            # терять нечего — «вернуть на роутер» здесь и есть «забыть». Ровно случай тестера
            # (02.09.2026): компоненты с накопителя сняли, потом сменили диск. Снимка нет — не
            # знаем, что там лежало, и молча забывать не вправе: отказ с дверью к forget.
            if seen_read && [ -z "$SEEN_NAMES" ]; then cmd_forget; return $?; fi
            echo "хранилище недоступно — воткните накопитель, иначе возвращать нечего; если он потерян насовсем — забудьте его (usb-offload.sh forget)" >&2
            return 1
        fi
    fi
    _store=$(store_root)
    drop_stale_new      # ДО гарда места: хвост прошлого прогона на /data сам по себе решал бы «не влезет»
    # Гард места СНАЧАЛА и целиком: вернуть половину бинарей и упереться в ENOSPC — худший из
    # исходов (часть транспортов на /data, часть на флешке, места нет ни на что).
    _need=0
    for _b in $STORE_MOVABLE; do
        [ -f "$BIN_DIR/$_b" ] && _need=$((_need + $(size_b "$BIN_DIR/$_b")))
    done
    _free=$(df_free_b "$ENODIA_DIR"); case "$_free" in ''|*[!0-9]*) _free=0 ;; esac
    if [ "$((_free - _need))" -lt "$DATA_RESERVE_B" ]; then
        echo "не влезет: вернуть надо $(mb "$_need") МБ, свободно $(mb "$_free") МБ при резерве $(mb "$DATA_RESERVE_B") МБ." >&2
        echo "Снимите лишние компоненты в «Компонентах» и повторите." >&2
        return 1
    fi
    echo "Возвращаю бинари на роутер:"
    _moved=0; _failed=0
    for _b in $STORE_MOVABLE; do
        [ -f "$BIN_DIR/$_b" ] || continue
        if move_verified "$BIN_DIR/$_b" "$ENODIA_BIN/$_b" "$_b"; then _moved=$((_moved+1)); else _failed=$((_failed+1)); fi
    done
    if [ "$_failed" -gt 0 ]; then
        echo "Часть бинарей осталась на накопителе — маркер НЕ снимаю (иначе они стали бы недоступны)." >&2
        return 1
    fi
    _mp="$_store"
    mark_drop
    # «Больше не используется» — только если с него не исполняется НИЧЕГО: демон, запущенный до возврата, держит файл на накопителе
    # до перезапуска, и выдернутый накопитель его уронит (разбор у old_place_names).
    if [ -n "$(old_place_names)" ]; then echo "Переселено обратно: $_moved."
    else echo "Переселено обратно: $_moved. Накопитель больше не используется."; fi
    free_line drive
    # Свою точку отпускаем, стоковую не трогаем: её монтировал не мы.
    case "$_mp" in "$MNT"/*) umount "$MNT" 2>/dev/null ;; esac
    return 0
}

# forget — ЗАБЫТЬ ПРОПАВШИЙ НАКОПИТЕЛЬ. Выход из состояния «включён, но не найден», в которое
# система входит САМА (флешку вынули, сменили разметку, диск умер), а выхода из него не было
# вовсе: disable требует живого хранилища (возвращать неоткуда), mount-ensure усыновляет только
# каталог с НАШИМ сентинелом, а маркер переживает и ребут, и обновление. Итог — переустановка
# (баг тестера 02.09.2026: сменил диск, и панель «наотрез» не видела новый). Решение «забыть»
# принадлежит человеку (store_rejected маркер не снимает намеренно) — верб его руки, не автомата.
# ЧТО ЗНАЧИТ «ЗАБЫТЬ»: снять маркер со снимком и отпустить СВОЮ точку монтирования. Файлов не
# трогаем нигде: на пропавшем накопителе они недостижимы, на флеше роутера — рабочие. Вернётся
# прежний накопитель — его сентинел цел, и `enable` усыновит его вместе со всем, что на нём лежит.
# СМЕНА НАКОПИТЕЛЯ отдельного верба не требует: `enable <dev>` в этом состоянии сам перезаписывает
# маркер (prepare_store) — прежний забывается тем же движением.
# ОТКАЗЫВАЕМ, когда забывать опасно или незачем:
#   * хранилище на месте (в том числе нашлось прямо сейчас) — бинари на нём живые, и забыть его
#     значит молча потерять их; путь человека тут — disable («Вернуть на роутер»);
#   * раскладка `full` — на накопителе КОД И НАСТРОЙКИ, и «забыть» = остаться без системы. Живьём
#     сюда не попасть (без накопителя этот верб нечему исполнить), гард — от вызова руками.
# ИТОГ — ПОСЛЕДНЕЙ СТРОКОЙ (панель берёт `tail -1`), и в нём ЦЕНА: что стало неустановленным.
cmd_forget() {
    if [ ! -f "$STORE_MARK" ]; then echo "Накопитель и так не используется — забывать нечего."; return 0; fi
    if mode_load 2>/dev/null && [ "$M_MODE" = full ]; then
        echo "в раскладке «всё на накопителе» забыть его нельзя: там код и настройки" >&2
        return 1
    fi
    if ! store_ready; then cmd_mount_ensure >/dev/null 2>&1; fi
    if store_ready; then
        echo "накопитель на месте ($(store_root)) — забывать его незачем; чтобы перестать им пользоваться, верните бинари на роутер (usb-offload.sh disable)" >&2
        return 1
    fi
    _fw=
    read -r _fw < "$STORE_MARK" 2>/dev/null || :
    if seen_read; then _fk=1; else _fk=0; fi
    _fj=
    for _fx in $SEEN_NAMES; do _fj="${_fj:+$_fj, }$_fx"; done
    mark_drop
    rm -f "$MISS_STAMP" 2>/dev/null
    # Свою точку отпускаем (стоковую не трогаем — её монтировали не мы): запись о выдернутом диске
    # держала бы $MNT занятой, и следующий накопитель на неё бы не сел.
    case "$_fw" in "$MNT"/*) umount "$MNT" 2>/dev/null ;; esac
    echo "Снят маркер хранилища: ${_fw:-?}"
    if [ "$_fk" = 0 ]; then
        echo "Накопитель забыт. Что на нём лежало, роутер не знает — сверьте «Компоненты»."
    elif [ -z "$_fj" ]; then
        echo "Накопитель забыт. Нашего на нём не было — терять нечего."
    else
        echo "Накопитель забыт. Не установлено то, что лежало на нём: $_fj. Поставьте заново в «Компонентах»."
    fi
    unset _fw _fk _fj _fx
    return 0
}

# place <имя> router|store — ГДЕ ЖИТЬ ОДНОМУ бинарю. Второй вопрос поверх «включён ли накопитель»:
# тот глобальный, этот поимённый. Просьба «на флешку только xray» выражается ровно здесь.
#
# ПОРЯДОК: сперва пишем НАМЕРЕНИЕ (закрепление), и лишь потом двигаем файл. Не наоборот: между
# перемещением и записью маркера bin_dest ещё указывал бы на прежнее место, и ближайший
# resolve_dups утащил бы файл обратно. Перенос может не удаться (нет места, битая копия) — тогда
# намерение остаётся записанным, а bin_path честно продолжает запускать то, что реально лежит:
# «где лежит» и «где должно лежать» у нас разные вопросы с самого начала.
# Имена локальных — СВОИ (_p*): в busybox нет `local`, а по пути отсюда лежит
# cmd_mount_ensure, под которым функции читают /proc/mounts в `while read -r _d _m _t _rest`.
# Сегодня все они вызываются под $( ) и ничего не затирают, но направление, лежащее в
# общем `_t`, однажды подменилось бы типом чужой ФС — и «на роутер» стало бы «на накопитель».
cmd_place() {
    _pn="$1"; _pt="$2"
    if [ -z "$_pn" ] || [ -z "$_pt" ]; then echo "usage: $0 place <имя> router|store" >&2; return 2; fi
    case "$_pt" in router|store) ;; *) echo "куда: router или store" >&2; return 2 ;; esac
    if ! store_movable "$_pn"; then
        echo "«$_pn» резидентен по замыслу проекта, на накопитель не селится (можно: $STORE_MOVABLE)" >&2
        return 2
    fi
    # Хранилище поднимаем, но его отсутствие НЕ повод отказать: закрепление — намерение, его
    # законно записать и при выдернутой флешке. Сработает при следующем включении.
    if ! store_ready; then cmd_mount_ensure >/dev/null 2>&1; fi

    if [ "$_pt" = router ]; then
        # Зависимости едут ВМЕСТЕ. Закрепить xray без hev значит закрепить неработающее: hev —
        # общая несущая tun2socks, и без флешки альт всё равно не поднимется.
        # Набор = сам бинарь + ВСЕ его зависимости, БЕЗ фильтра «уже закреплён». Фильтр был
        # ошибкой: зависимость, закреплённую прошлым прогоном, у которого не удался перенос,
        # он выкидывал из набора — и она навсегда оставалась в хранилище при закреплённом альте,
        # то есть ровно в том состоянии, от которого зависимость и защищает. Повторное
        # закрепление безвредно: keep_add сам пропускает то, что уже в списке.
        _pset="$_pn $(bin_deps "$_pn")"
        # Гард места — ЦЕЛИКОМ и ДО первого движения: вернуть половину набора и упереться в
        # ENOSPC хуже, чем не начинать (часть на /data, часть на флешке, места нет ни на что).
        if store_ready && ! fits_router "$_pn"; then
            echo "не влезет: вернуть надо $(mb "$(need_router_b "$_pn")") МБ, свободно $(mb "$(df_free_b "$ENODIA_DIR")") МБ при резерве $(mb "$DATA_RESERVE_B") МБ." >&2
            echo "Снимите лишние компоненты в «Компонентах» или оставьте этот бинарь на накопителе." >&2
            return 1
        fi
        if ! keep_add $_pset; then echo "не смог записать закрепление" >&2; return 1; fi
        printf 'Закреплено за роутером:'
        for _px in $_pset; do printf ' %s' "$_px"; done
        echo
        _pfail=0
        if store_ready; then
            for _px in $_pset; do
                if [ -f "$BIN_DIR/$_px" ]; then
                    if ! move_verified "$BIN_DIR/$_px" "$ENODIA_BIN/$_px" "$_px"; then _pfail=$((_pfail+1)); fi
                fi
            done
        fi
        if [ "$_pfail" -gt 0 ]; then
            echo "Часть файлов осталась в хранилище — закрепление записано, но запускается пока копия оттуда." >&2
            return 1
        fi
        if ! store_ready; then
            echo "Накопителя сейчас нет — переносить нечего, закрепление учтётся при его включении."
        fi
    else
        # Отпускаем — но не из-под тех, кто на нём держится: иначе закреплённый xray остался бы
        # на роутере без hev, то есть закреплённым и неработающим.
        _pblk=
        for _px in $STORE_MOVABLE; do
            if [ "$_px" = "$_pn" ]; then continue; fi
            if ! bin_pinned "$_px"; then continue; fi
            case " $(bin_deps "$_px") " in *" $_pn "*) _pblk="$_pblk $_px" ;; esac
        done
        if [ -n "$_pblk" ]; then
            echo "«$_pn» держат закреплённые:$_pblk — сперва отпустите их" >&2
            return 1
        fi
        if ! keep_del "$_pn"; then echo "не смог снять закрепление" >&2; return 1; fi
        # Говорим ровно то, что произошло. «Отпущен на накопитель» при выдернутой флешке — ложь:
        # файл никуда не уехал, и человек уходит в уверенности, что место освободилось.
        if store_ready && [ -f "$ENODIA_BIN/$_pn" ]; then
            if ! move_verified "$ENODIA_BIN/$_pn" "$BIN_DIR/$_pn" "$_pn"; then
                echo "Перенести не вышло — файл пока остаётся на роутере." >&2
                return 1
            fi
            echo "Отпущен на накопитель: $_pn"
        elif store_ready; then
            echo "Закрепление снято: $_pn (на роутере такого файла нет — переносить нечего)"
        else
            echo "Закрепление снято: $_pn. Накопителя сейчас нет — файл уедет на него, когда он появится."
        fi
    fi
    seen_note
    if [ "$_pt" = router ]; then free_line drive; else free_line; fi
    return 0
}

cmd_status() {
    if store_ready; then
        _store=$(store_root)
        _mp=$(store_mp "$_store")
        echo "Внешний накопитель: ВКЛЮЧЁН"
        echo "  хранилище: $_store"
        echo "  ФС: $(fs_of_mount "$_mp" || echo '?'), свободно $(mb "$(df_free_b "$_store")") МБ из $(mb "$(df_total_b "$_store")")"
        echo "  занимаем: $(mb "$(du_b "$_store")") МБ (остальное занятое на накопителе — не наше)"
    elif [ -f "$STORE_MARK" ]; then
        echo "Внешний накопитель: ВКЛЮЧЁН, но НЕДОСТУПЕН (маркер есть, хранилища нет)"
        echo "  ожидался: $(cat "$STORE_MARK" 2>/dev/null)"
        if seen_read; then echo "  лежало на нём: ${SEEN_NAMES:-ничего нашего}"; else echo "  что лежало на нём — неизвестно (снимка нет)"; fi
        echo "  бинари ищутся на флеше роутера; транспорт, чей бинарь уехал, считается неустановленным."
        echo "  потерян насовсем — забыть его: usb-offload.sh forget"
    else
        echo "Внешний накопитель: выключен (всё на флеше роутера)"
    fi
    echo "  $(our_mp): свободно $(mb "$(df_free_b "$ENODIA_DIR")") МБ из $(mb "$(df_total_b "$ENODIA_DIR")") МБ"
    echo "Тяжёлые бинари:"
    for _b in $STORE_MOVABLE; do
        _w=$(bin_where "$_b")
        # НОСИТЕЛЬ ВАЖНЕЕ КАТАЛОГА. `bin_where` отвечает «в резидентном ли он каталоге», а в
        # раскладке `full` резидентный каталог САМ на накопителе — и строка печатала «роутер»
        # про файл на флешке. Тот же вопрос и тот же ответ, что в dump.sh и в json панели.
        if [ -n "$_w" ] && bin_on_store "$_b"; then _w=store; fi
        if bin_pinned "$_b"; then _p='  <- закреплён за роутером'; else _p=''; fi
        case "$_w" in
            store)  printf '  %-12s накопитель  %s МБ%s\n' "$_b" "$(mb "$(size_b "$(bin_path "$_b")")")" "$_p" ;;
            router) printf '  %-12s роутер      %s МБ%s\n' "$_b" "$(mb "$(size_b "$(bin_path "$_b")")")" "$_p" ;;
            *)      printf '  %-12s не установлен%s\n' "$_b" "$_p" ;;
        esac
    done
}

# json — ЕДИНЫЙ срез для панели (Ф3). Второй копии «что где лежит» во фронте быть не должно.
cmd_json() {
    _store=$(store_root)
    _mp=$(store_mp "$_store")
    # РЕЖИМ РАСКЛАДКИ — у бутстрапа (он владелец ответа «где сейчас код»). Не ответил (бутстрап
    # не собран: установка старее фичи либо `boot.sh sync` не прошёл) — отдаём ПУСТО, а не
    # «data». Разница видна на кнопке: при `data` панель предложила бы «перенести всё на
    # накопитель», а движок отказал бы («бутстрап не собран») уже в фоне — то есть человек
    # нажимал бы кнопку, которая молчит. Пусто ⇒ раздел выбора раскладки не рисуется вовсе.
    _jm=
    if mode_load 2>/dev/null; then _jm="$M_MODE"; fi
    # Переключение идёт прямо сейчас — фронт обязан знать: кнопки на это время гасятся, а
    # «панель исчезла» получает объяснение. Ответ — у владельца (daemon-lib.sh::store_mode_alive,
    # по живому процессу: pid-файл в /tmp переживает убитый движок, и кнопка залипла бы до ребута).
    _jb=false
    store_mode_alive && _jb=true
    printf '{"mode":"%s","switching":%s,' "$_jm" "$_jb"
    # store_used_b — НАШЕ на накопителе (du хранилища). Занятое ВСЕГО панель берёт как
    # total−free, чужое = разность: так «разбивка накопителя» сходится с df без обхода чужих
    # файлов. Нет хранилища ⇒ нули, и блок разбивки во фронте просто не рисуется.
    # data_* — это ФЛЕШ РОУТЕРА, и якорь тут ОБЯЗАН быть бутстрапом, а не $ENODIA_DIR:
    # в режиме `full` каталог кода лежит на НАКОПИТЕЛЕ, и оба поля повторяли бы store_*,
    # то есть панель рисовала бы флешку под подписью «флеш роутера». Бутстрап резидентен
    # на /data по определению, а в обычной раскладке это тот же том, что и код.
    # fs_perm — «хранит ли эта ФС права доступа». Считает РОУТЕР (mount-lib.sh::fs_keeps_perms):
    # у фронтов своей таблицы файловых систем нет и быть не должно. Без хранилища отдаём false —
    # это же значение и у неизвестной ФС, а панель в обоих случаях просто не обещает защиты.
    _jfs=$([ -n "$_store" ] && fs_of_mount "$_mp")
    # `state` — ГОТОВОЕ СЛОВО про хранилище (none|ok|lost) от владельца (store-lib.sh::store_state).
    # `on`/`ready` рядом остаются: это СЫРЬЁ, и экран хранилища показывает их по отдельности. А вот
    # КОМПОЗИЦИЯ «маркер есть, а каталога нет = потерян» обязана быть ОДНА — она жила копиями здесь
    # и во фронте (siStoreFacts), и разъехалась бы при первой правке любой из них.
    printf '"on":%s,"ready":%s,"state":"%s","store":"%s","fs":"%s","fs_perm":%s,"store_free_b":%s,"store_total_b":%s,"store_used_b":%s,"data_free_b":%s,"data_total_b":%s' \
        "$([ -f "$STORE_MARK" ] && echo true || echo false)" \
        "$(store_ready && echo true || echo false)" \
        "$(store_state)" \
        "$_store" "$_jfs" \
        "$(fs_keeps_perms "$_jfs" && echo true || echo false)" \
        "$([ -n "$_store" ] && df_free_b "$_store" || echo 0)" \
        "$([ -n "$_store" ] && df_total_b "$_store" || echo 0)" \
        "$([ -n "$_store" ] && du_b "$_store" || echo 0)" \
        "$(df_free_b "$ENODIA_BOOT")" "$(df_total_b "$ENODIA_BOOT")"
    # `seen` — что из наших бинарей лежало в хранилище при последней встрече с ним (снимок seen_note),
    # `seen_known:false` — снимка нет, и «ничего» тут было бы выдумкой. Нужно ровно пропавшему
    # накопителю: панель называет цену «забыть» и «сменить» поимённо, а не «что-то пропадёт».
    # Имена прошли фильтр формы [a-z0-9-] в seen_read — экранировать нечего.
    if seen_read; then printf ',"seen_known":true,"seen":"%s"' "$SEEN_NAMES"
    else printf ',"seen_known":false,"seen":""'; fi
    # `old_place` — наши демоны, до перезапуска работающие с ПРЕЖНЕГО места (разбор у old_place_names): у них «где лежит» уже
    # новое, а место (или сам накопитель) держит удалённый файл. Имена любые наши, не только $STORE_MOVABLE: раскладка `full`
    # увозит и базу AmneziaWG, и HTTPS панели. Форма имён [a-z0-9-] — экранировать нечего.
    printf ',"old_place":"%s"' "$(old_place_names)"
    printf ',"bins":['
    _f=1
    for _b in $STORE_MOVABLE; do
        [ "$_f" = 1 ] || printf ','
        _f=0
        # fits_router считает РОУТЕР: своей арифметики места во фронте нет, он лишь рисует отказ.
        # `where` — про КАТАЛОГ (резидентный или хранилище), `on_store` — про ТОМ. В раскладке
        # `full` это РАЗНЫЕ ответы: резидентный каталог САМ уехал на накопитель, и `where` честно
        # печатает «router» про файл, лежащий на флешке. Ярлык в панели отвечает на вопрос «на
        # чём он лежит» — значит спрашивать обязан про том (та же развилка, что у daemon-lib.sh).
        printf '{"name":"%s","where":"%s","on_store":%s,"size_b":%s,"pinned":%s,"deps":"%s","fits_router":%s}' \
            "$_b" "$(bin_where "$_b")" \
            "$(bin_on_store "$_b" && echo true || echo false)" \
            "$(size_b "$(bin_path "$_b")")" \
            "$(bin_pinned "$_b" && echo true || echo false)" \
            "$(bin_deps "$_b")" \
            "$(fits_router "$_b" && echo true || echo false)"
    done
    printf '],"cands":['
    _f=1
    # Ёмкость кандидата отдаём, ТОЛЬКО если он уже смонтирован (стоком или нами): монтировать
    # чужую флешку ради красивой цифры в информационном срезе — побочный эффект, а `blkid`,
    # который сказал бы размер без монтирования, на роутере нет. Не смонтирован ⇒ нули, и
    # панель просто не показывает размер — это честнее выдуманного «≈ 32 ГБ».
    cmd_detect | while IFS="$(printf '\t')" read -r _d _t _m _o; do
        [ "$_f" = 1 ] || printf ','
        _f=0
        # `perm` — про ЭТОГО кандидата, а не про действующее хранилище: мастер спрашивает
        # согласие ДО переезда, то есть про накопитель, которого система ещё не касалась.
        # У несмонтированного ФС неизвестна (`?`) ⇒ false — обещать права мы не вправе.
        printf '{"dev":"%s","fs":"%s","perm":%s,"mnt":"%s","ours":%s,"free_b":%s,"total_b":%s}' \
            "$_d" "$_t" "$(fs_keeps_perms "$_t" && echo true || echo false)" \
            "$_m" "$([ "$_o" = yes ] && echo true || echo false)" \
            "$([ -d "$_m" ] && df_free_b "$_m" || echo 0)" \
            "$([ -d "$_m" ] && df_total_b "$_m" || echo 0)"
    done
    printf ']}\n'
}

# --- РЕЖИМЫ РАСКЛАДКИ: data | bins | full ------------------------------------------------------
#
# ЧТО ГДЕ ЛЕЖИТ:
#   data — всё на флеше роутера (дефолт: накопителя у большинства нет и не будет);
#   bins — на накопителе только тяжёлые бинари (сегодняшний оффлоад: enable/disable/place);
#   full — на накопителе КОД, НАСТРОЙКИ и бинари, на /data остаётся резидентный бутстрап.
#
# ЗАЧЕМ full, если на BE7000 места хватает: размер /data на ЧУЖИХ роутерах неизвестен (бывает
# 10–15 МБ), плюс «ничего лишнего на роутере» как принцип и место под гео-списки, которые в
# /data не влезают. Решение пользователя 31.08.2026; там же принято, что секреты (ключи awg,
# TOTP, хэш пароля панели, пароль SMTP) на съёмном exFAT — приемлемо: «это домашние устройства».
#
# ПУТИ ФЛЕША СПРАШИВАЕМ У БУТСТРАПА, а не пишем литералами: владелец этого знания ОДИН —
# boot.sh (тот же довод, что у store-lib.sh для имён хранилища). Литерала здесь нет ни одного.
#
# ПЕРЕЕЗД КОНЧАЕТСЯ ПЕРЕЗАПУСКОМ СЕБЯ С ЦЕЛЕВОЙ СТОРОНЫ: сносить каталог, из которого
# исполняешься, — риск, которого можно не брать (тот же приём, что у uninstall.sh purge).
# Cron-таблицу мы только ЧИТАЕМ (гард «строки идут через бутстрап»): пишут её install.sh и
# update-sched.sh, переводит прежние — boot.sh. Отдельной переменной она ради ПРОВЕРЯЕМОСТИ:
# без подменяемого пути ветка гарда не гоняется стендом вовсе (тот же довод, что у списков
# монтирований в mount-lib.sh).
CRON=/etc/crontabs/root
PATHS_TMP=/tmp/enodia-usb-paths.$$
FIND_TMP=/tmp/enodia-usb-files.$$      # список файлов дерева: `for f in $(find …)` рвёт путь с пробелом

# mode_load — спросить бутстрап, где что лежит. Ответ в M_*.
# Через ФАЙЛ, а не через `|`: конвейер в ash крутит цикл в подоболочке, и переменные умерли бы
# вместе с ней. `IFS='='` режет только ПЕРВЫЙ знак равенства — путь со знаком «=» переживёт.
mode_load() {
    M_MODE=; M_DIR=; M_STATE=; M_BIN=; M_STORE=; M_DDIR=; M_DSTATE=; M_DBIN=
    if [ ! -f "$ENODIA_BOOT/boot.sh" ]; then
        echo "нет $ENODIA_BOOT/boot.sh — бутстрап не собран, режимы недоступны (обновите скрипты)" >&2
        return 1
    fi
    sh "$ENODIA_BOOT/boot.sh" paths > "$PATHS_TMP" 2>/dev/null
    while IFS='=' read -r _mk _mv; do
        case "$_mk" in
            mode)       M_MODE="$_mv" ;;
            dir)        M_DIR="$_mv" ;;
            state)      M_STATE="$_mv" ;;
            bin)        M_BIN="$_mv" ;;
            store)      M_STORE="$_mv" ;;
            data_dir)   M_DDIR="$_mv" ;;
            data_state) M_DSTATE="$_mv" ;;
            data_bin)   M_DBIN="$_mv" ;;
        esac
    done < "$PATHS_TMP"
    rm -f "$PATHS_TMP" 2>/dev/null
    [ -n "$M_MODE" ] && [ -n "$M_DDIR" ]
}

# tree_bytes — сколько дерево ЗАНИМАЕТ ПО СОДЕРЖИМОМУ (байты), а не по выделенным блокам.
#
# ЗАМЕРЕНО НА ЖИВОМ BE7000 01.09.2026, и цена ошибки — запертая на накопителе установка. `du`
# считает ВЫДЕЛЕННЫЕ блоки, а на exFAT кластер 128 КБ: 105 наших файлов (в основном по 5–40 КБ)
# дали 16.3 МБ вместо 5.8, и возврат кода на флеш отказал «не хватает места» при 14.1 МБ
# свободных. Обратно человеку было бы не вернуться вовсе — а это единственная дорога назад.
# `du --apparent-size` в busybox НЕТ, поэтому считаем tar'ом: один проход по дереву, оверхед
# заголовков (512 Б на файл + хвостовые блоки) играет в БЕЗОПАСНУЮ сторону — оценка чуть
# завышена. Направление «на накопитель» от этого тоже честнее: на exFAT копия РАЗБУХНЕТ по
# кластерам, но там гигабайты, а на 20-МБ флеше важен каждый мегабайт.
tree_bytes() {      # $1 = каталог
    _tb=$(tar cf - -C "${1%/*}" "${1##*/}" 2>/dev/null | wc -c)
    case "$_tb" in ''|*[!0-9]*) _tb=0 ;; esac
    printf '%s' "$_tb"
}

# copy_tree_verified <откуда> <куда> — копия дерева со СВЕРКОЙ КАЖДОГО ФАЙЛА по md5.
# Почему не «скопировали и ладно»: накопитель монтируется без sync, и оборванная на середине
# копия выглядит как удавшаяся. Сверяем ПОСЛЕ sync и по СОДЕРЖИМОМУ — это единственный честный
# ответ на «доехало ли», а цена (md5 по 4.5 МБ) платится один раз за переезд.
copy_tree_verified() {
    rm -rf "$2" 2>/dev/null
    mkdir -p "$2" 2>/dev/null || { echo "  не создался $2" >&2; return 1; }
    # `cp -rp` на exFAT возвращает ошибку, скопировав ВСЁ (права там не хранятся) ⇒ его код
    # возврата не вердикт: вердикт выносит сверка ниже. Без `-p` повторяем на всякий случай.
    cp -rp "$1/." "$2/" 2>/dev/null || cp -r "$1/." "$2/" 2>/dev/null || true
    sync
    _ctv_n=0; _ctv_bad=0; _ctv_moving=0; _ctv_gone=0
    # СПИСОК — В ФАЙЛ, а не в `$(find …)`: подстановка режет вывод по IFS, и путь с ПРОБЕЛОМ
    # («/mnt/My Flash/enodia-store» — законная точка стокового automount, ради неё же в boot.sh
    # нет ни одного `set -- $строка`) разъехался бы на два несуществующих. Сверка тогда не
    # находит ни одного файла и объявляет удавшуюся копию битой. Не в конвейер `find | while`:
    # цикл ушёл бы в подоболочку вместе со счётчиками, и вердикт был бы всегда «сошлось».
    find "$1" -type f 2>/dev/null > "$FIND_TMP"
    while IFS= read -r _ctv_f || [ -n "$_ctv_f" ]; do
        [ -n "$_ctv_f" ] || continue
        _ctv_r=${_ctv_f#"$1"/}
        _ctv_n=$((_ctv_n+1))
        # ИСЧЕЗ — не то же, что «не сошёлся». Список файлов снят `find`-ом заранее, и за время
        # копирования 232 файлов чужой временный файл (или наш `.new` от соседнего процесса)
        # успевает родиться и умереть. Его отсутствие в копии — ПРАВИЛЬНЫЙ итог, а не порча;
        # без этой ветки повтор ниже трижды не смог бы его скопировать и уронил бы весь переезд.
        if [ ! -e "$_ctv_f" ]; then
            _ctv_gone=$((_ctv_gone+1))
            _ctv_n=$((_ctv_n-1))
            continue
        fi
        if [ "$(md5_of "$_ctv_f")" != "$(md5_of "$2/$_ctv_r")" ]; then
            # «НЕ СОШЛОСЬ» ≠ «КОПИЯ БИТАЯ»: источник мог измениться ПОД НАМИ, и тогда бита не
            # копия, а само сравнение. Это не теория — ЗАМЕР на BE7000 02.09.2026: переезд
            # full→data отказал на 232 файлах настроек из-за ОДНОГО, `.srv-checks`. Его пишет
            # панель (кэш проверок серверов, `action save_checks`), и меняется он каждые 2–5
            # секунд. А переезд человек запускает ИЗ ПАНЕЛИ — то есть она открыта ПО
            # ОПРЕДЕЛЕНИЮ, и её же тик рушил операцию, которую она же и начала.
            # Отличаем ДВИЖУЩУЮСЯ ЦЕЛЬ от ПОРЧИ: копируем файл заново и сверяем с тем md5
            # источника, который был НА МОМЕНТ этой копии. Источник продолжает меняться ⇒ это
            # кэш (проект и сам считает его расходным: `# EXCLUDE: .srv-checks` в бэкапе) —
            # берём последнюю версию и идём дальше. Источник СТОИТ, а копия всё равно другая ⇒
            # вот это порча, и вот тогда отказ.
            _ctv_try=0
            while [ "$_ctv_try" -lt 3 ]; do
                _ctv_try=$((_ctv_try+1))
                _ctv_was=$(md5_of "$_ctv_f")
                cp -p "$_ctv_f" "$2/$_ctv_r" 2>/dev/null || cp "$_ctv_f" "$2/$_ctv_r" 2>/dev/null
                sync
                [ "$(md5_of "$2/$_ctv_r")" = "$_ctv_was" ] && break
            done
            if [ "$(md5_of "$2/$_ctv_r")" = "$_ctv_was" ]; then
                :   # копия сошлась с источником на момент копии — файл доехал целым
            elif [ "$(md5_of "$_ctv_f")" != "$_ctv_was" ]; then
                _ctv_moving=$((_ctv_moving+1))
                [ "$_ctv_moving" -le 3 ] && echo "  меняется на ходу, взята последняя версия: $_ctv_r" >&2
            else
                _ctv_bad=$((_ctv_bad+1))
                [ "$_ctv_bad" -le 3 ] && echo "  не сошёлся: $_ctv_r" >&2
            fi
        fi
    done < "$FIND_TMP"
    rm -f "$FIND_TMP" 2>/dev/null
    if [ "$_ctv_n" = 0 ]; then echo "  нечего копировать из $1" >&2; return 1; fi
    if [ "$_ctv_bad" != 0 ]; then echo "  файлов не сошлось: $_ctv_bad из $_ctv_n" >&2; return 1; fi
    # Про движущиеся цели говорим ВСЛУХ, а не молчим: переезд удался, но один-два файла уехали
    # в той версии, какая была в момент копии. Для кэша это норма, а для человека — разница
    # между «всё сошлось» и «сошлось, кроме вот этого».
    if [ "$_ctv_moving" != 0 ]; then echo "  менялись во время копии, взята последняя версия: $_ctv_moving" >&2; fi
    # Исчезнувшие тоже называем: «сверено 231 из 232» без объяснения читается как потеря.
    if [ "$_ctv_gone" != 0 ]; then echo "  исчезли во время копии (временные, копировать нечего): $_ctv_gone" >&2; fi
    echo "  скопировано и сверено файлов: $_ctv_n"
    return 0
}

# swap_in <ступень .new> <боевой путь> — поставить подготовленную копию на место.
# Окно между двумя rename — единственный момент, когда каталога нет вовсе; чинит его БУТСТРАП
# (boot.sh::store_repair), потому что чинить изнутри исчезнувшего каталога некому.
swap_in() {
    if [ -d "$2" ]; then
        rm -rf "$2.old" 2>/dev/null
        mv "$2" "$2.old" 2>/dev/null || { echo "  не отодвинулся прежний $2" >&2; return 1; }
    fi
    if ! mv "$1" "$2" 2>/dev/null; then
        [ -d "$2.old" ] && mv "$2.old" "$2" 2>/dev/null      # вернуть как было
        echo "  не встал на место $2" >&2; return 1
    fi
    sync
    rm -rf "$2.old" 2>/dev/null
    return 0
}

# exec_probe_store — ЗАПУСКАЕТСЯ ли скрипт с этой файловой системы. В режиме `full` с накопителя
# исполняется всё, включая CGI панели, и бит `+x` нужен по-настоящему: на exFAT права даёт
# монтирование (fmask=0000), на ext4-флешке — chmod, а на смонтированной с `noexec` не даст
# ничто. Узнать это можно ТОЛЬКО пробой: «chmod прошёл» на exFAT не значит ничего (там он no-op).
exec_probe_store() {
    _eps="$1/.enodia-exec-probe"
    printf '#!/bin/sh\nexit 0\n' > "$_eps" 2>/dev/null || return 1
    chmod +x "$_eps" 2>/dev/null
    sync
    if [ ! -x "$_eps" ]; then rm -f "$_eps" 2>/dev/null; return 1; fi
    ( "$_eps" >/dev/null 2>&1 )
    _eprc=$?
    rm -f "$_eps" 2>/dev/null
    [ "$_eprc" = 0 ]
}

# bins_carry <откуда> <куда> — перенести бинари ЦЕЛИКОМ, без разбора имён.
#
# ЗАЧЕМ ОТДЕЛЬНО ОТ cmd_enable. Тот уносит на накопитель РОВНО пятерых «тяжёлых»
# (STORE_MOVABLE), а рядом с ними на флеше лежат резидентные СОЗНАТЕЛЬНО — база AmneziaWG,
# panel-tls, прокси шифрованного DNS — и поимённо закреплённые человеком (.bin-keep). В режиме
# `full` резидентного каталога НЕТ ВООБЩЕ: $ENODIA_BIN сам указывает на накопитель, и снос
# каталога на флеше стёр бы их насовсем — второй копии нет нигде, а вернуть их можно только
# закачкой из интернета. Поэтому переезд режима забирает ВЕСЬ каталог, а «кому можно на съёмный
# носитель» решает сам режим, а не белый список.
# Код 1 = хоть один не переехал: следом идёт удаление источника, и «часть потерялась» тут
# недопустима. Пустой источник — законный успех.
bins_carry() {      # $1 = откуда, $2 = куда
    [ -d "$1" ] || return 0
    [ "$1" = "$2" ] && return 0
    mkdir -p "$2" 2>/dev/null
    _bc_n=0; _bc_bad=0
    for _bc_f in "$1"/*; do
        [ -f "$_bc_f" ] || continue          # пустой каталог даёт саму маску — её отсекает -f
        case "${_bc_f##*/}" in *.new) continue ;; esac   # ступень прерванного переезда — не бинарь
        _bc_b=${_bc_f##*/}
        if move_verified "$_bc_f" "$2/$_bc_b" "$_bc_b"; then _bc_n=$((_bc_n+1)); else _bc_bad=$((_bc_bad+1)); fi
    done
    [ "$_bc_n" != 0 ] && echo "Бинарей перенесено: $_bc_n"
    [ "$_bc_bad" = 0 ]
}

# bins_carry_home <откуда (накопитель)> <куда (флеш роутера)> — ОБРАТНО, но не всех.
# Возвращаем тех, кого политика проекта держит на роутере (не из STORE_MOVABLE) и кого человек
# закрепил поимённо; «тяжёлые» незакреплённые остаются на накопителе — это и есть режим `bins`.
# Для режима `data` остаток заберёт прежний движок (cmd_disable): у него свой гард места и своя
# отчётность, второй копии этой логики не нужно.
bins_carry_home() {
    [ -d "$1" ] || return 0
    [ "$1" = "$2" ] && return 0
    mkdir -p "$2" 2>/dev/null
    _bh_n=0; _bh_bad=0
    for _bh_f in "$1"/*; do
        [ -f "$_bh_f" ] || continue
        case "${_bh_f##*/}" in *.new) continue ;; esac   # ступень прерванного переезда — не бинарь
        _bh_b=${_bh_f##*/}
        if store_movable "$_bh_b" && ! bin_pinned "$_bh_b"; then continue; fi
        # «Резидентный» — это про ПРОГРАММЫ, которые политика держит на роутере; файл данных (чужой, положенный руками) на
        # флеш роутера не тащим — он остаётся с накопителем, и это не отказ переезда (is_program).
        is_program "$_bh_f" || continue
        if move_verified "$_bh_f" "$2/$_bh_b" "$_bh_b"; then _bh_n=$((_bh_n+1)); else _bh_bad=$((_bh_bad+1)); fi
    done
    [ "$_bh_n" != 0 ] && echo "Бинарей возвращено на роутер: $_bh_n"
    [ "$_bh_bad" = 0 ]
}

# ТИХИЙ ОТКАЗ В ФОНЕ — худший исход у кнопки панели. Она честно сказала «переезд запущен», а
# движок упёрся в место, битую копию или чужой лок — и человек видит РОВНО НИЧЕГО: карточка та
# же, тост уже погас, отчёт лежит в /tmp/enodia-store-mode.log, о котором он не знает. Событие
# кладём тем же путём, что и весь проект (notify-event.sh): он и в журнал панели пишет, и письмо
# шлёт, и троттлит. Ключ несёт «fail» ⇒ events.sh покажет его КРАСНЫМ (level_of), а не новостью.
# Троттл 0: смену раскладки жмут руками, спама быть не может по определению.
# Язык писем сорсим ВНУТРИ функции, а не на верхнем уровне: этот файл зовёт cron вербом
# mount-ensure (heal раз в минуту, сторож раз в две), и лишний разбор библиотеки на КАЖДОМ
# тике — плата ни за что у тех, у кого накопителя нет и не будет.
mode_event_fail() {     # $1 = режим, в который не переехали
    [ -f "$ENODIA_DIR/notify-event.sh" ] || return 0
    if [ -f "$ENODIA_DIR/nf-i18n.sh" ]; then . "$ENODIA_DIR/nf-i18n.sh"; fi
    if command -v nf_lang >/dev/null 2>&1; then _mef_l=$(nf_lang); else _mef_l=ru; fi
    if [ "$_mef_l" = en ]; then
        sh "$ENODIA_DIR/notify-event.sh" store-mode-fail 0 \
            "Storage layout switch failed" \
            "Switching to the «$1» layout did not go through; the layout is unchanged. Details: /tmp/enodia-store-mode.log (it is also in the diagnostics archive)." >/dev/null 2>&1
    else
        sh "$ENODIA_DIR/notify-event.sh" store-mode-fail 0 \
            "Смена раскладки не удалась" \
            "Переезд в режим «$1» не прошёл, раскладка осталась прежней. Подробности — /tmp/enodia-store-mode.log (он же лежит в диагностическом архиве)." >/dev/null 2>&1
    fi
    return 0
}

cmd_mode() {        # $1 = пусто (показать) | data | bins | full; $2 = устройство (как у enable)
    mode_load || return 1
    if [ -z "$1" ]; then
        case "$M_MODE" in
            data) echo "Режим: data — всё на флеше роутера" ;;
            bins) echo "Режим: bins — тяжёлые бинари на накопителе, код и настройки на флеше роутера" ;;
            full) echo "Режим: full — код, настройки и бинари на накопителе ($M_STORE)" ;;
            *)    echo "Режим: full, но накопитель НЕ НАЙДЕН — панели нет, поднята заглушка" ;;
        esac
        return 0
    fi
    case "$1" in data|bins|full) ;; *) echo "режим бывает data, bins или full" >&2; return 2 ;; esac
    [ "$1" = "$M_MODE" ] && { echo "Режим уже $1 — ничего не делаю"; return 0; }
    [ "$M_MODE" = none ] && { echo "накопитель с кодом не найден — сперва верните флешку, потом меняйте режим" >&2; return 1; }
    # Смена раскладки идёт ФОНОМ (CGI и мастер зовут её отвязанно): потолка uhttpd у неё нет, а тик с перебором резервов и прогон heal
    # длятся минуты — ждём дольше синхронной кнопки, иначе «переезд запущен» кончался ложным «не удалось» (ревью ветки, круг 2).
    _mtw=$MOVE_TICK_WAIT; MOVE_TICK_WAIT=$MOVE_MODE_WAIT
    move_hold; _mhr=$?; MOVE_TICK_WAIT=$_mtw
    [ "$_mhr" = 0 ] || { mode_event_fail "$1"; return 1; }
    # СБОРКА СПИСКОВ ИЛИ ГЕО ИДЁТ — её процессы держат ПРЕЖНИЕ пути и после переезда допишут результат на флеш (на BE7000 30.09.2026
    # вырос пустой двойник `enodia-state/lists/…/blob`, в худшем случае туда уезжает и РЕЗУЛЬТАТ). Ждём с локом в руках (новые тики
    # не придут), потолок — MOVE_LISTS_WAIT: гео у больших категорий собирается минутами; не дождались — отказ ДО первого движения.
    _mlw=0
    while lists_work_alive && [ "$_mlw" -lt "$MOVE_LISTS_WAIT" ]; do sleep 1; _mlw=$((_mlw + 1)); done
    if lists_work_alive; then
        move_release
        echo "идёт сборка списков или гео-категорий — раскладку не меняю, повторите, когда она закончится" >&2
        mode_event_fail "$1"; return 1
    fi
    case "$1" in
        full)      mode_to_full "$2" ;;
        data|bins) mode_to_router "$1" ;;
    esac
    # Успех сюда НЕ ВОЗВРАЩАЕТСЯ: обе ветки кончаются `exec` с целевой стороны, и отчитывается
    # уже она (вербы mode-drop-*). Значит всё, что дошло до этой строки, — отказ ДО первого
    # движения, и о нём надо сказать.
    _cm_rc=$?
    [ "$_cm_rc" = 0 ] || mode_event_fail "$1"
    return "$_cm_rc"
}

mode_to_full() {   # $1 = устройство/точка (как у enable), необязательно
    # 0. CRON ОБЯЗАН ИДТИ ЧЕРЕЗ БУТСТРАП. После переезда каталога кода на флеше НЕ БУДЕТ, а
    #    установка, обновлённая из панели, живёт с прежними строками — прямым путём в него
    #    (install.sh на такой роутер не приезжал). Оставь мы их — роутер после ребута поднимется
    #    стоковым: ни heal, ни сторожа, ни панели, которой это чинят. Сперва пробуем перевести
    #    сами (владелец перевода — бутстрап, `boot.sh sync`), и только если не вышло — отказ.
    if grep -q "$M_DDIR/" "$CRON" 2>/dev/null; then
        sh "$ENODIA_BOOT/boot.sh" sync "$M_DIR" >/dev/null 2>&1
    fi
    if grep -q "$M_DDIR/" "$CRON" 2>/dev/null; then
        echo "cron всё ещё зовёт код напрямую ($M_DDIR/…) — после переезда роутер не поднимется" >&2
        echo "обновите установку (панель → «Обновление» либо установщик с ПК) и повторите" >&2
        return 1
    fi
    # 1. ПОДГОТОВКА НАКОПИТЕЛЯ И БИНАРЕЙ — прежним движком: у него уже есть и усыновление чужого
    #    хранилища, и выбор диска, и сверка md5, и проба запуска, и уважение к закреплениям.
    #    Своей копии этой логики здесь быть не должно. Заодно это делает `full` надмножеством
    #    `bins`: не вышло ничего дальше — раскладка остаётся рабочей, просто прежней.
    cmd_enable "$1" || { echo "накопитель не подготовлен — режим не меняю" >&2; return 1; }
    store_ready || { echo "хранилище не опознано — режим не меняю" >&2; return 1; }
    _mf_store=$(store_root)
    echo "Переезд кода и настроек на накопитель: $_mf_store"
    # 2. ПРОБА ИСПОЛНЕНИЯ — ДО единого копирования. ФС, которая не отдаёт бит +x, оставила бы
    #    роутер без панели, и вернуть его было бы нечем.
    if ! exec_probe_store "$_mf_store"; then
        echo "с этого накопителя скрипты не запускаются (смонтирован noexec или не хранит права) — режим full невозможен" >&2
        echo "раскладка осталась прежней: бинари на накопителе, код и настройки на флеше (режим bins)" >&2
        return 1
    fi
    # 3. МЕСТО. Оценка по du завышена (UBIFS сжимает) — для гарда это верная сторона ошибки.
    _mf_need=$(( $(tree_bytes "$M_DIR") + $(tree_bytes "$M_STATE") ))
    _mf_free=$(df_free_b "$_mf_store")
    if [ "$_mf_free" -lt "$((_mf_need + 1048576))" ]; then
        echo "на накопителе не хватает места: нужно $(mb "$_mf_need") МБ + запас, свободно $(mb "$_mf_free") МБ" >&2
        return 1
    fi
    # 4. КОД и НАСТРОЙКИ — через ступень `.new`, со сверкой каждого файла.
    echo "Копирую код:"
    copy_tree_verified "$M_DIR" "$_mf_store/enodia.new" || { rm -rf "$_mf_store/enodia.new" 2>/dev/null; return 1; }
    echo "Копирую настройки:"
    copy_tree_verified "$M_STATE" "$_mf_store/enodia-state.new" || { rm -rf "$_mf_store/enodia.new" "$_mf_store/enodia-state.new" 2>/dev/null; return 1; }
    swap_in "$_mf_store/enodia-state.new" "$_mf_store/enodia-state" || return 1
    swap_in "$_mf_store/enodia.new" "$_mf_store/enodia" || return 1
    # Права — ПОСЛЕ постановки на место, а не до: swap_in двигает подготовленную ступень, и
    # выставленное на `.new` пережило бы переезд, но не пережило бы падение на полпути.
    # Владелец режимов один — store-lib.sh::harden_tree (там же и замер, из-за которого это есть).
    harden_perms "$_mf_store/enodia" "$_mf_store/enodia-state" "$_mf_store/bin"
    # 5. БУТСТРАП пересобираем ИЗ КОПИИ НА НАКОПИТЕЛЕ: с этой секунды cron обязан идти туда.
    sh "$_mf_store/enodia/boot.sh" sync "$_mf_store/enodia" >/dev/null 2>&1 \
        || echo "ВНИМАНИЕ: бутстрап не пересобрался — проверьте $ENODIA_BOOT" >&2
    # 6. ФИНАЛ — уже С НАКОПИТЕЛЯ.
    echo "Убираю копию с флеша роутера…"
    ENODIA_DIR="$_mf_store/enodia" ENODIA_STATE="$_mf_store/enodia-state" ENODIA_BIN="$_mf_store/bin" ENODIA_MOVE_SW="$ENODIA_MOVE_SW" \
        exec sh "$_mf_store/enodia/usb-offload.sh" mode-drop-router
}

# Внутренний верб (в usage не печатается): снести раскладку на флеше роутера. Зовётся ТОЛЬКО из
# mode_to_full и только после удавшегося обмена — но проверяет это САМ, потому что вызов руками
# уничтожил бы рабочую установку.
cmd_mode_drop_router() {
    # Лок УЖЕ НАШ (PID переезд не менял — `exec` его сохраняет), а ловушка EXIT после exec
    # потеряна: ставим свою, иначе лок останется висеть до следующего захода. То же со switching-локом
    # переноса: владение приехало в ENODIA_MOVE_SW (move_hold), снимаем его здесь.
    set_traps 'usb_unlock_mine; move_release'
    mode_load || return 1
    # ПРЕДПОСЫЛКУ ПРОВЕРЯЕМ ПО СЕБЕ, а не по вопросу «какой сейчас режим»: режим считается ПО
    # ФАКТУ наличия кода на флеше, а этот код ещё лежит — его мы и собираемся снести. Значит
    # спрашивать надо другое: исполняемся ли мы УЖЕ с накопителя и полна ли там копия.
    [ -n "$M_DDIR" ] || { echo "бутстрап не сказал, где флеш роутера — ничего не трогаю" >&2; return 1; }
    [ "$ENODIA_DIR" != "$M_DDIR" ] || { echo "исполняемся с флеша роутера — сносить его нельзя" >&2; return 1; }
    store_ready || { echo "хранилище недоступно — раскладку на флеше НЕ трогаю" >&2; return 1; }
    [ "$ENODIA_DIR" = "$(store_root)/enodia" ] || { echo "исполняемся не из копии на накопителе ($ENODIA_DIR) — ничего не трогаю" >&2; return 1; }
    # totp.sh — В СПИСКЕ НЕ ЗА КОМПАНИЮ: с 03.09.2026 `web-ui.sh start` без него панель не
    # поднимает вовсе, то есть «копия на накопителе работоспособна» без этого файла НЕ ВЕРНО.
    for _dr in heal.sh web-ui.sh totp.sh transport.sh VERSION store-lib.sh boot.sh; do
        [ -f "$ENODIA_DIR/$_dr" ] || { echo "в копии на накопителе нет $_dr — раскладку на флеше НЕ трогаю" >&2; return 1; }
    done
    [ -d "$ENODIA_STATE" ] || { echo "на накопителе нет копии настроек — раскладку на флеше НЕ трогаю" >&2; return 1; }
    # БИНАРИ, ЖИВУЩИЕ ТОЛЬКО НА ФЛЕШЕ, ЗАБИРАЕМ С СОБОЙ — ДО удаления и с правом всё отменить.
    bins_carry "$M_DBIN" "$ENODIA_BIN" || {
        echo "часть бинарей с флеша не переехала — раскладку на флеше НЕ трогаю (причина строкой выше)" >&2
        return 1
    }
    # ПАНЕЛЬ СЛУЖИТ ИЗ КАТАЛОГА, КОТОРЫЙ МЫ СЕЙЧАС СНЕСЁМ. uhttpd держит docroot ПУТЁМ
    # ($ENODIA_DIR/web), а `web-ui.sh start` при живом pid — no-op: cron её не перезапустит, и
    # снаружи это «панель пропала навсегда» при обещании «поднимется на новом месте». Поэтому
    # гасим ДО удаления и поднимаем ПОСЛЕ — уже с накопителя (ENODIA_DIR у нас уже новый).
    [ -f "$ENODIA_DIR/web-ui.sh" ] && sh "$ENODIA_DIR/web-ui.sh" stop >/dev/null 2>&1
    _dr_n=0
    for _dr in "$M_DSTATE" "$M_DBIN" "$M_DDIR"; do
        [ -d "$_dr" ] || continue
        rm -rf "$_dr" 2>/dev/null
        if [ -d "$_dr" ]; then echo "ВНИМАНИЕ: $_dr удалить не вышло (занят?) — уберите руками" >&2; else _dr_n=$((_dr_n+1)); fi
    done
    sync
    if [ -f "$ENODIA_DIR/web-ui.sh" ]; then
        sh "$ENODIA_DIR/web-ui.sh" start >/dev/null 2>&1 \
            || echo "ВНИМАНИЕ: панель не поднялась с накопителя — поднимите вручную: sh $ENODIA_BOOT/boot.sh web-ui.sh start" >&2
    fi
    echo "Готово: режим full. С флеша убрано каталогов: $_dr_n, остался только бутстрап ($ENODIA_BOOT)."
    return 0
}

mode_to_router() {   # $1 = data (забрать и бинари) | bins (бинари оставить на накопителе)
    if [ "$M_MODE" != full ]; then
        # bins <-> data при коде на флеше — это прежние enable/disable, второй реализации им не нужно.
        case "$1" in
            data) cmd_disable; return $? ;;
            bins) cmd_enable;  return $? ;;
        esac
    fi
    echo "Возврат кода на флеш роутера (режим $1)"
    # МЕСТО НА /data — с неснижаемым резервом и ДО первого движения: вернуть половину и упереться
    # в ENOSPC хуже, чем не начинать (то же правило, что у гарда бинарей).
    _mr_need=$(( $(tree_bytes "$M_DIR") + $(tree_bytes "$M_STATE") ))
    _mr_free=$(df_free_b "$M_DDIR")
    if [ "$_mr_free" -lt "$((_mr_need + DATA_RESERVE_B))" ]; then
        echo "на флеше роутера не хватает места: нужно $(mb "$_mr_need") МБ + резерв $(mb "$DATA_RESERVE_B") МБ, свободно $(mb "$_mr_free") МБ" >&2
        echo "освободите место (экран «Компоненты» → снять лишние протоколы) и повторите" >&2
        return 1
    fi
    echo "Копирую код:"
    copy_tree_verified "$M_DIR" "$M_DDIR.new" || { rm -rf "$M_DDIR.new" 2>/dev/null; return 1; }
    echo "Копирую настройки:"
    copy_tree_verified "$M_STATE" "$M_DSTATE.new" || { rm -rf "$M_DDIR.new" "$M_DSTATE.new" 2>/dev/null; return 1; }
    swap_in "$M_DSTATE.new" "$M_DSTATE" || return 1
    swap_in "$M_DDIR.new" "$M_DDIR" || return 1
    # …и на ОБРАТНОМ пути тоже: 0777 с exFAT приезжает на флеш роутера, где права настоящие
    # всегда. Чинить только ту сторону, куда едем, значило бы оставить дыру ровно у того, кто
    # накопитель попробовал и передумал.
    harden_perms "$M_DDIR" "$M_DSTATE" "$M_DBIN"
    # Бутстрап — ИЗ КОПИИ НА ФЛЕШЕ: cron с этой секунды обязан идти туда.
    sh "$M_DDIR/boot.sh" sync "$M_DDIR" >/dev/null 2>&1 \
        || echo "ВНИМАНИЕ: бутстрап не пересобрался — проверьте $ENODIA_BOOT" >&2
    echo "Убираю копию с накопителя…"
    ENODIA_DIR="$M_DDIR" ENODIA_STATE="$M_DSTATE" ENODIA_BIN="$M_DBIN" ENODIA_MOVE_SW="$ENODIA_MOVE_SW" \
        exec sh "$M_DDIR/usb-offload.sh" mode-drop-store "$1"
}

# Внутренний верб: снести код и настройки с накопителя после возврата на флеш. $1 = целевой режим.
cmd_mode_drop_store() {
    set_traps 'usb_unlock_mine; move_release'
    mode_load || return 1
    # Зеркально предыдущему вербу: спрашиваем не «какой режим», а «исполняемся ли мы уже с
    # флеша и полна ли там копия». Вызов руками в режиме full упрётся ровно в это.
    [ -n "$M_DDIR" ] || { echo "бутстрап не сказал, где флеш роутера — ничего не трогаю" >&2; return 1; }
    [ "$ENODIA_DIR" = "$M_DDIR" ] || { echo "код не вернулся на флеш — с накопителя ничего не сношу" >&2; return 1; }
    # totp.sh — и здесь тоже: верб ЗЕРКАЛЬНЫЙ предыдущему, а список отстал на одну правку.
    # Без него «копия на флеше полна» — неправда: web-ui.sh start панель не поднимет.
    for _ds in heal.sh web-ui.sh totp.sh transport.sh VERSION store-lib.sh boot.sh; do
        [ -f "$M_DDIR/$_ds" ] || { echo "на флеше нет $_ds — с накопителя ничего не сношу" >&2; return 1; }
    done
    # И ПАРНЫЙ ГАРД на настройки — у зеркального верба он был, у этого нет: «копия полна» без
    # каталога состояния неправда, а верб кончается удалением другой стороны.
    [ -d "$M_DSTATE" ] || { echo "на флеше роутера нет копии настроек — накопитель НЕ трогаю" >&2; return 1; }
    # Панель служит из каталога на накопителе — его мы сейчас снесём (см. разбор в парном
    # вербе). Гасим ДО удаления, поднимаем ПОСЛЕ — уже с флеша.
    [ -f "$M_DDIR/web-ui.sh" ] && sh "$M_DDIR/web-ui.sh" stop >/dev/null 2>&1
    if ! store_ready; then cmd_mount_ensure >/dev/null 2>&1; fi
    if store_ready; then
        _ds_s=$(store_root)
        # РЕЗИДЕНТНЫХ ЗАБИРАЕМ ОБРАТНО. В режиме full на накопителе лежали ВСЕ бинари, включая
        # базу AmneziaWG, panel-tls и прокси шифрованного DNS: политика проекта держит их на
        # роутере, а `cmd_disable` знает только пятерых «тяжёлых» и до остальных не дошёл бы
        # никогда — они остались бы на съёмном носителе, то есть панель по HTTPS и VPN умирали
        # бы вместе с ним.
        bins_carry_home "$_ds_s/bin" "$M_DBIN" \
            || echo "часть бинарей осталась на накопителе (причина выше) — воткните его и повторите смену режима" >&2
        rm -rf "$_ds_s/enodia" "$_ds_s/enodia-state" 2>/dev/null
        sync
    else
        echo "ВНИМАНИЕ: накопителя нет — бинари остались на нём. Воткните его и повторите смену режима." >&2
    fi
    # Бинари в режим data забирает прежний движок: у него сверка, проба запуска и гард места.
    if [ "$1" = data ]; then
        cmd_disable || echo "код вернулся, а бинари остались на накопителе — повторите «выключить накопитель»" >&2
    fi
    if [ -f "$M_DDIR/web-ui.sh" ]; then
        sh "$M_DDIR/web-ui.sh" start >/dev/null 2>&1 \
            || echo "ВНИМАНИЕ: панель не поднялась с флеша — поднимите вручную: sh $M_DDIR/web-ui.sh start" >&2
    fi
    echo "Готово: режим ${1:-bins}. Код и настройки снова на флеше роутера."
    return 0
}

# ЛОК БЕРЁМ ЗДЕСЬ, а не внутри вербов: cmd_enable сам зовёт cmd_mount_ensure, и лок внутри
# обоих сцепился бы сам с собой. Читающие вербы (detect/status/json) лока не берут вовсе —
# панель опрашивает их часто, а испортить ими нечего.
# Ловушка снимает лок и на СИГНАЛЕ: EXIT в busybox ash по сигналу не срабатывает (инвариант
# проекта — в trap нужны HUP PIPE), а нас зовут из CGI, то есть смерть по сигналу — штатный
# исход. Невозвращённый лок заперт бы движок до ребута: /tmp это ОЗУ, а сам себя лок не снимет
# — только следующий заход, увидев мёртвого держателя.
case "$1" in
    mount-ensure|enable|disable|forget|place|mode)
        # ЧУЖАЯ установка компонентов идёт — уходим сразу (см. PKG_LOCK). Тик молчит, человеку
        # говорим ПОЧЕМУ и куда смотреть: «занят» без причины читается как поломка кнопки.
        if [ -d "$PKG_LOCK" ]; then
            [ "$1" = mount-ensure ] && exit 1
            echo "идёт установка компонентов — дождитесь её окончания (экран «Компоненты») и повторите" >&2
            exit 1
        fi
        # РОУТЕР БЕЗ НАКОПИТЕЛЯ НЕ ПЛАТИТ НИЧЕГО. Инвариант этого файла: «без маркера .bin-store
        # каждый верб — no-op, роутер работает как прежде», а лок стоит mkdir+rm, то есть ДВА
        # форка. Тик сторожа раз в 2 минуты на роутере, где флешки нет и не будет, — плата ни за
        # что (той же меркой install.sh не заводит нам cron-строку). Уходим ДО лока.
        # ...но РЕЖИМ спрашивают и без маркера: «в каком мы режиме» — законный вопрос на
        # роутере без накопителя, и ответ на него «data».
        [ "$1" = mount-ensure ] && [ ! -f "$STORE_MARK" ] && exit 1
        [ "$1" = mode ] && [ -z "$2" ] && { cmd_mode; exit $?; }
        # СКОЛЬКО ЖДАТЬ. Кнопке панели — 20 с (перенос 8-МБ xray на медленной флешке измеряется
        # секундами). Тику — НЕМНОГО, но НЕ НОЛЬ: на буте heal.sh и watchdog.sh зовут нас
        # ВПЕРЕМЕШКУ (у сторожа этот вызов стоит ДО boot-grace), и нулевое ожидание означало бы,
        # что heal уходит ни с чем, поднимает несущую БЕЗ хранилища и транспорт, чей бинарь
        # уехал на флешку, считается неустановленным — до следующего тика, то есть 2 минуты
        # фолбэка на пустом месте. 8 с покрывают чужой монтаж (проба ro + umount + монтаж на
        # запись), а копиться ждущие тики не могут: интервал 120 с.
        case "$1" in mount-ensure) _uw=8 ;; *) _uw=20 ;; esac
        if ! usb_lock "$_uw"; then
            [ "$1" = mount-ensure ] && exit 1        # молча: перенос идёт, тик повторится через 2 минуты
            echo "накопитель занят другой операцией (идёт перенос) — повторите через минуту" >&2
            exit 1
        fi
        set_traps 'usb_unlock; move_release'
        # Перенос бинарей закрывает окно от сторожа и heal (move_hold). `mode` берёт его сам — после проверки «режим уже тот»,
        # чтобы пустая смена не ждала тика; `forget` и `mount-ensure` бинарей не двигают.
        case "$1" in enable|disable|place) move_hold || exit 1 ;; esac
        ;;
esac
case "$1" in
    detect)       cmd_detect ;;
    mount-ensure) cmd_mount_ensure ;;
    enable)       cmd_enable "$2" ;;
    disable)      cmd_disable ;;
    forget)       cmd_forget ;;
    place)        cmd_place "$2" "$3" ;;
    mode)             cmd_mode "$2" "$3" ;;
    # Вторая половина переезда идёт УЖЕ ПОСЛЕ `exec`, и её отказ до cmd_mode не доходит —
    # сообщаем отсюда, иначе «панель исчезла и не вернулась» осталось бы без единой строки.
    mode-drop-router) cmd_mode_drop_router; _drc=$?; [ "$_drc" = 0 ] || mode_event_fail full; exit "$_drc" ;;
    mode-drop-store)  cmd_mode_drop_store "$2"; _drc=$?; [ "$_drc" = 0 ] || mode_event_fail "${2:-bins}"; exit "$_drc" ;;
    status|"")    cmd_status ;;
    json)         cmd_json ;;
    *) echo "usage: $0 detect | mount-ensure | enable [dev|точка] | disable | forget | place <имя> router|store | mode [data|bins|full] | status | json"; exit 2 ;;
esac
