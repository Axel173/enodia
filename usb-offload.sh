#!/bin/sh
# usb-offload.sh — ДВИЖОК внешнего накопителя: смонтировать «наше» хранилище и переселить на
# него тяжёлые бинари (и вернуть обратно). Пара к store-lib.sh: тот ОТВЕЧАЕТ, где лежит бинарь,
# этот — ДЕЛАЕТ так, чтобы ответ был правдой.
#
# ЗАЧЕМ. /data на BE7000 = 20.6 МБ, и 13.4 из 14.3 МБ бинарей — это ДВА файла (xray 8.2 +
# hysteria 5.2). Отсюда весь блок «альты взаимоисключающи»: три транспорта разом просто не
# влезают. Накопитель снимает потолок, но остаётся ОПЦИЕЙ: у большинства флешки нет и не будет,
# поэтому без маркера .bin-store каждый верб здесь — no-op, а роутер работает как прежде.
#
# ГРАНИЦА «что уезжает» ЖИВЁТ НЕ ЗДЕСЬ, а в store-lib.sh ($STORE_MOVABLE): движок обязан
# двигать ровно то, что резолвер потом найдёт. Два списка разъехались бы на первой же правке.
#
# ИДЕНТИЧНОСТЬ НАКОПИТЕЛЯ — ПО СЕНТИНЕЛУ, не по устройству и не по точке монтирования:
# `blkid` на роутере НЕТ, имя sdX динамическое (на переткычке ядро давало то sda, то sdb),
# серийник тома есть только у exFAT. Ищем каталог с $STORE_SENTINEL — это работает при любой
# ФС, любой букве и нескольких воткнутых накопителях.
#
# СВОЙ МОНТАЖ НУЖЕН В ЛЮБОМ СЛУЧАЕ, хотя сток монтирует флешку сам (/mnt/usb-<серийник>,
# hotplug.d/block): /mnt — ramfs, стоковый automount асинхронен нашему cron, и рассчитывать на
# то, что к первому тику heal.sh флешка уже смонтирована, нельзя. Порядок такой: сперва ищем
# УЖЕ смонтированное (не плодим второй монтаж того же устройства — на FAT/exFAT два писателя
# = битая ФС), и только если не нашли — монтируем сами в $MNT.
#
# МАРКЕР — СЛЕД, А НЕ КОНФИГ. Точка монтирования от загрузки к загрузке может меняться, поэтому
# mount-ensure ПЕРЕПИСЫВАЕТ .bin-store фактическим путём. Протухший маркер безопасен: store-lib
# на каждом source проверяет сентинел и молча возвращается к резидентным путям.
#
# ПЕРЕЕЗД — С ПРОВЕРКОЙ, А НЕ `mv`. Бинарь, который несёт трафик, нельзя потерять из-за битой
# копии: сперва копия + md5 + запуск («ELF реально исполняется с этой ФС» — ровно то, что
# проверял спайк), и только потом удаление исходника. Не сошлось — файл остаётся резидентным,
# остальные едут дальше: СМЕШАННАЯ раскладка законна (store-lib судит по факту, не по реестру).
#
# ДВИЖУЩИЕ ВЕРБЫ СЕРИАЛИЗОВАНЫ. Источников вызова два, и оба двигают одни и те же файлы:
# кнопки панели и тик watchdog'а раз в 2 минуты (mount-ensure → resolve_dups). Гонка кончается
# ПОТЕРЕЙ БИНАРЯ: в окне между `mv` и `rm` внутри move_verified копии две и они одинаковы —
# ровно условие, по которому resolve_dups сносит «лишнюю». Лок берётся в ДИСПЕТЧЕРЕ (cmd_enable
# сам зовёт cmd_mount_ensure — лок внутри обоих сцепился бы сам с собой), читающие вербы его не
# берут вовсе, а на чужой лок установки компонентов мы только СМОТРИМ (см. PKG_LOCK).
#
# rm живёт ЗДЕСЬ (PS-guard на литерал rm). НЕ используем set -e — шаги best-effort.
#
# Вербы:
#   usb-offload.sh detect            — какие накопители видит роутер (TSV: dev fs точка наш?)
#   usb-offload.sh mount-ensure      — идемпотентно сделать хранилище доступным (boot/hotplug)
#   usb-offload.sh enable [dev|точка] — подготовить хранилище и переселить на него тяжёлые бинари
#   usb-offload.sh disable           — вернуть всё на /data и забыть накопитель
#   usb-offload.sh forget            — забыть ПРОПАВШИЙ накопитель, ничего не перенося (возвращать неоткуда)
#   usb-offload.sh place <имя> router|store — где жить ОДНОМУ бинарю (поштучно)
#   usb-offload.sh mode [data|bins|full]   — РАСКЛАДКА ЦЕЛИКОМ: что именно живёт на накопителе
#                                            (без аргумента — показать нынешнюю)
#   usb-offload.sh status            — человеку: где что лежит и сколько где свободно
#   usb-offload.sh json              — то же машине (панель)

ENODIA_DIR=${ENODIA_DIR:-/data/usr/app/enodia}
ENODIA_BIN=${ENODIA_BIN:-/data/usr/app/enodia-bin}
# Бутстрап — ЗДЕСЬ, рядом с остальными путями, а не в разделе режимов ниже. Он и раньше был
# нужен только тем функциям, которые лежат под своим объявлением, но json-срез (cmd_json)
# спрашивает у него ФЛЕШ РОУТЕРА, а определён на 80 строк выше — работало бы лишь потому, что
# диспетчер идёт последним. Пустой $ENODIA_BOOT молча дал бы df по «/» (squashfs) вместо /data.
ENODIA_BOOT=${ENODIA_BOOT:-/data/usr/app/enodia-boot}

# SWITCHING-ЛОК ПЕРЕНОСА (move_hold ниже) — ЗДЕСЬ, выше загрузки библиотек, ради ПРОДОЛЖЕНИЯ смены раскладки: `exec` ловушек не
# переносит, владение лока приезжает в ENODIA_MOVE_SW, и умри продолжение раньше своей ловушки (на старой библиотеке в копии, на
# сигнале) — лок провисел бы до SWITCH_STALE (30 мин) с выключенными сторожем и heal. Переменную ОТВЯЗЫВАЕМ от окружения: иначе
# «лок наш» унаследовал бы любой наш потомок, позвавший движок сам.
SWITCH_LOCK=/tmp/enodia-switching.lock
_mvsw=$ENODIA_MOVE_SW; unset ENODIA_MOVE_SW
case "$_mvsw" in 1) ENODIA_MOVE_SW=1 ;; *) ENODIA_MOVE_SW=0 ;; esac
move_release() { [ "$ENODIA_MOVE_SW" = 1 ] && rm -f "$SWITCH_LOCK" 2>/dev/null; ENODIA_MOVE_SW=0; return 0; }
# ЛОВУШКИ — ОДНОЙ ФОРМОЙ НА ФАЙЛ: локи снимает EXIT, а сигнал только ВЫХОДИТ (его `exit` и зовёт EXIT). Ловушка без `exit` лишь
# гасила смерть, и шелл шёл дальше — переносил бинари уже без обоих локов, окно от сторожа открыто (ревью ветки, круг 2). Уборка в
# самой сигнальной ловушке звалась бы ДВАЖДЫ — второй `rm` снимал бы лок конкурента, успевшего его взять (C121). SIGPIPE — не смерть:
# uhttpd, убив CGI, оставляет нас писать в мёртвую трубу, и перенос, начатый под локами, обязан ими и кончиться (`echo` не дойдёт).
set_traps() { trap "$1" EXIT; trap 'exit 1' INT TERM HUP; trap '' PIPE; }
[ "$ENODIA_MOVE_SW" = 1 ] && set_traps 'move_release'

# store-lib.sh — REQUIRED: без него у движка нет ни маркера, ни списка «что можно выносить».
# Шима тут быть не может (в отличие от потребителей bin_path): нечего было бы двигать.
# Гард `if [ -f ]` обязателен: провалившийся `.` в busybox ash убивает шелл НА МЕСТЕ (см. шапку
# store-lib.sh) — без гарда сообщение ниже не напечаталось бы никогда, а панель получила бы
# пустой ответ CGI, то есть «сбой запроса» вместо «обнови скрипты».
if [ -f "$ENODIA_DIR/store-lib.sh" ]; then . "$ENODIA_DIR/store-lib.sh"; fi
# `bin_pinned` в списке НЕ для красоты: apply-scripts обновляет ПОФАЙЛОВО и переживает провал
# отдельного файла, то есть новый движок рядом со старой библиотекой — штатно достижимое
# состояние. Без этой проверки `place` дошёл бы до keep_write с пустым KEEP_MARK и насорил бы
# файлом `.new` в текущем каталоге, а bin_pinned молча возвращал бы «не закреплён» (rc=127).
if ! command -v bin_dest >/dev/null 2>&1 || ! command -v bin_pinned >/dev/null 2>&1 \
   || ! command -v store_is_ours >/dev/null 2>&1 || ! command -v store_state >/dev/null 2>&1 \
   || [ -z "$STORE_SUB" ] || [ -z "$STORE_MNT" ] || [ -z "$DATA_RESERVE_B" ] || [ -z "$KEEP_MARK" ]; then
    echo "нет store-lib.sh (или он старый) — обновите скрипты" >&2
    exit 1
fi

# mount-lib.sh — REQUIRED: поиск и монтирование носителя. Отдельным файлом он живёт потому, что
# ровно та же логика нужна резидентному boot.sh на /data (режим `full` обязан смонтировать
# накопитель ДО того, как узнает, где лежит код), а вторая копия перебора кандидатов разъехалась
# бы с этой при первой правке. Сорсить ПОСЛЕ store-lib.sh: mount-lib спрашивает у него сентинел.
if [ -f "$ENODIA_DIR/mount-lib.sh" ]; then . "$ENODIA_DIR/mount-lib.sh"; fi
if ! command -v store_locate >/dev/null 2>&1 || ! command -v try_mount >/dev/null 2>&1; then
    echo "нет mount-lib.sh (или он старый) — обновите скрипты" >&2
    exit 1
fi
# …а вот `fs_keeps_perms` в этот REQUIRED-список НЕ добавлен, и это осознанно: он выбирает ФРАЗУ
# («хранит ли накопитель права доступа»), а не двигает файлы. Ронять из-за него весь движок —
# несоразмерно: человек остался бы без раскладки, кнопок и статуса ради одной подсказки.
# Поэтому шим-фолбэк, как у router-lib/ip-lib/json-lib. Отвечает «НЕ хранит» — тот же
# консервативный ответ, что у самой функции на неизвестной ФС: лишнее предупреждение стоит
# предупреждения, а обещанная и не выданная защита стоит ключей.
# ЗАМЕР 02.09.2026 (BE7000): новый движок рядом со старой библиотекой — состояние ШТАТНО
# достижимое (apply-scripts обновляет пофайлово и переживает провал отдельного файла, точечный
# `--push` — тем более). Без шима json молча отдавал `"fs_perm":false` и сыпал
# `fs_keeps_perms: not found` в stderr: ответ верный, способ — нет.
if ! command -v fs_keeps_perms >/dev/null 2>&1; then
    fs_keeps_perms() { return 1; }
fi
# …и `harden_perms` (store-lib.sh) — ПО ТОЙ ЖЕ ПРИЧИНЕ, что и сосед выше, но с ГРОМКИМ отказом:
# он не выбирает фразу, а восстанавливает права после переезда, и молчаливое «нет функции» —
# это ровно та дыра, ради которой он написан (0777 с exFAT приезжает на ФС, где права настоящие;
# замер 02.09.2026: `web/cgi-bin` стал world-writable, а CGI оттуда uhttpd запускает от root).
# Ронять движок всё равно нельзя — человек остался бы на полпути между двумя раскладками, — но и
# делать вид, что права выставлены, мы не вправе: пишем в лог переезда, его читает панель.
# Состояние «новый движок рядом со старой библиотекой» штатно достижимо (apply-scripts обновляет
# пофайлово), поэтому это не «на всякий случай». Ревью 02.09.2026.
if ! command -v harden_perms >/dev/null 2>&1; then
    harden_perms() {
        echo "ВНИМАНИЕ: store-lib.sh старый (нет harden_perms) — права на каталоги НЕ выставлены;" >&2
        echo "          обновите скрипты и повторите переезд, иначе на флеше могут остаться права 0777 с накопителя" >&2
        return 0
    }
fi

# Раскладка ($STORE_SUB) и резерв /data ($DATA_RESERVE_B) приходят из store-lib.sh, своя точка
# монтирования ($MNT) и списки монтирований — из mount-lib.sh: эти имена знает не только движок,
# но и uninstall.sh с packages.sh, а теперь ещё и бутстрап.
# ИМЕНА С ПРЕФИКСОМ: /tmp — ОБЩИЙ namespace со стоком, и наше там ищут ПО ИМЕНИ (уборка
# uninstall.sh по маске /tmp/enodia-*, дамп — своими масками). Прежние `.usb-offload-*` под маски
# не попадали вовсе: purge их не снимал, и переустановка В ТУ ЖЕ ЗАГРУЗКУ видела чужой штамп
# «дубли уже разбирали» и пропускала разбор. Миграции не нужно — /tmp это ОЗУ.
MISS_STAMP=/tmp/enodia-usb-missing     # «уже говорили, что накопителя нет» — /tmp=RAM, живёт до ребута
DEDUP_STAMP=/tmp/enodia-usb-dedup      # «дубли уже разбирали в эту загрузку» (см. resolve_dups)
# ЛОК НА ДВИЖУЩИЕ ВЕРБЫ. У нас ДВА независимых источника вызовов, и оба двигают ОДНИ И ТЕ ЖЕ
# файлы: кнопки панели (enable/disable/place) и тик watchdog'а раз в 2 минуты (mount-ensure →
# resolve_dups). Гонка не теоретическая и кончается ПОТЕРЕЙ БИНАРЯ: move_verified удаляет
# исходник ПОСЛЕ того, как копия встала на место, и в это окно обе копии существуют и
# одинаковы — ровно условие, по которому resolve_dups сносит «лишнюю». Снесёт он ту, что
# осталась целью (при возврате на роутер — резидентную), а move_verified следом штатно снимет
# вторую. Итог тот же, что у бага 01.09: бинаря нет нигде.
# Каталог (mkdir атомарен) + pid внутри — идиома do_update/dns-merge. /tmp = ОЗУ ⇒ ребут снимает.
USB_LOCK=/tmp/enodia-usb.lock
# ЧУЖОЙ лок — установки компонентов (packages.sh и proto-install.sh делят его между собой).
# Они качают и раскладывают ТЕ ЖЕ бинари (bin_dest/bin_prune) и так же считают место, поэтому
# в их окно мы не лезем. Смотрим на него ОДНОСТОРОННЕ и просто отказываемся: захватывать оба
# лока значило бы заводить порядок захвата и риск взаимной блокировки в самом дорогом пути
# проекта, а установка идёт МИНУТАМИ против нашей секунды — ждать должен тот, кто короче.
# ВЛАДЕЛЕЦ ПУТИ — packages.sh, мы его только ЧИТАЕМ (`-d`), и потому не заводим его сами и не
# снимаем: захват и снятие — дело владельца. Внутри каталога с 03.09.2026 лежит pid держателя,
# нам он не нужен — сам факт каталога и есть ответ «установка идёт».
PKG_LOCK=/tmp/enodia-proto-install.lock
# ЧТО ЛЕЖИТ В ХРАНИЛИЩЕ — снимок имён на флеше роутера, рядом с маркером. Нужен ровно тогда, когда
# хранилища НЕТ: пропавший накопитель про себя не расскажет, а «забыть его» — решение с ЦЕНОЙ
# (бинари на нём станут неустановленными), и назвать её обязан тот, кто предлагает решение.
# Отсутствие файла = «не знаем» (снимка ещё не было), пустой файл = «знаем: нашего там нет» —
# это разные ответы, и второй делает забывание безопасным. Имя производное от маркера: владелец
# имён — store-lib.sh, своего литерала пути здесь нет. Пишет ТОЛЬКО seen_note (ниже).
STORE_SEEN="$STORE_MARK-seen"

# --- примитивы --------------------------------------------------------------------------

# Свободно/всего байт на ФС, которой принадлежит путь. df -k: busybox печатает 1К-блоки,
# у разных сборок разное число колонок ⇒ считаем от КОНЦА строки (NF), как в packages.sh.
# ВСЕГДА печатаем число: пустой ответ df (нет пути, чужой формат) уходил бы в json панели
# как `"data_free_b":,` — синтаксически битый JSON, то есть «карточка не открылась».
num()        { case "$1" in ''|*[!0-9]*) printf '0' ;; *) printf '%s' "$1" ;; esac; }
# Считает store-lib.sh (fs_*) — он же владелец знания «у КАКОГО тома спрашивать» (на BE10000
# `/data` чужой). Своей формулы тут нет: остаётся имя, под которым этот файл её знает, и гард
# num() на пустой ответ df. У кого ещё есть своё выражение с df — у clean.sh, dump.sh и трёх
# CGI: они библиотеку не сорсят, форму им сторожит C50.
df_free_b()  { num "$(fs_free_b "$1")"; }
df_total_b() { num "$(fs_total_b "$1")"; }
# Точка монтирования НАШЕГО тома — ею подписаны все строки «свободно» ниже. Пустой ответ df
# (нет пути, чужой формат) не имеет права оставить подпись пустой: «Свободно на : 0 МБ»
# читается как поломка вывода, а не как «не смогли спросить».
our_mp()     { _omp=$(fs_mount "$ENODIA_DIR"); printf '%s' "${_omp:-/data}"; }
size_b()     { _n=$(stat -c%s "$1" 2>/dev/null); case "$_n" in ''|*[!0-9]*) _n=0 ;; esac; printf '%s' "$_n"; }
mb()         { _v=${1:-0}; echo "$((_v/1048576)).$(( (_v%1048576)*10/1048576 ))"; }

# Сколько на накопителе занимаем МЫ — du по каталогу-хранилищу, а не сумма size_b бинарей:
# на FAT/exFAT кластер крупный, и «сколько файл весит» расходится с «сколько он занял» тем
# сильнее, чем мельче файл. ЧУЖОЕ (файлы юзера) НЕ обходим ни здесь, ни где-либо ещё: его
# объём панель считает разностью с df — гулять по чужой файлопомойке ради цифры незачем, да
# и du по гигабайтам чужого добра стоил бы секунд на каждом открытии карточки.
du_b() {
    _k=$(du -xsk "$1" 2>/dev/null | awk 'NR==1{print $1}')
    case "$_k" in ''|*[!0-9]*) _k=0 ;; esac
    printf '%s' "$((_k * 1024))"
}

# Записать/снять маркер и ПЕРЕСЧИТАТЬ резолвер: store-lib вычисляет STORE_DIR/BIN_DIR при
# source, поэтому после смены маркера его надо перечитать — иначе bin_dest в этом же процессе
# продолжит указывать на старое место.
# Гард `if [ -f ]` и здесь: файл проверен на старте, но исчезни он к этому моменту (обновление
# скриптов ровно в этот миг) — без гарда мы умерли бы ПОСРЕДИ переезда, а так просто доработаем
# со старым резолвером.
# Код возврата — ВЕРДИКТ БИБЛИОТЕКИ, а не факт записи: перечитав себя, она маркер может и
# ОТВЕРГНУТЬ (каталог без сентинела, флешку выдернули между проверкой и записью). Молчаливый
# rc=0 в этом месте означал бы «хранилище есть» при BIN_DIR = резидентный каталог — то самое
# состояние, в котором переезд превращается в удаление (см. move_verified).
mark_write() {
    printf '%s\n' "$1" > "$STORE_MARK"
    if [ -f "$ENODIA_DIR/store-lib.sh" ]; then . "$ENODIA_DIR/store-lib.sh"; fi
    store_ready
}
# Снимок уходит ВМЕСТЕ с маркером: без маркера хранилища нет, и «что лежало на нём» остался бы
# ответом про накопитель, которого система больше не ждёт.
mark_drop()  { rm -f "$STORE_MARK" "$STORE_SEEN"; if [ -f "$ENODIA_DIR/store-lib.sh" ]; then . "$ENODIA_DIR/store-lib.sh"; fi; }

# seen_note — записать снимок «какие наши бинари лежат в хранилище», если он РАЗОШЁЛСЯ с прежним.
# Зовут её тик (mount-ensure, раз в 2 минуты) и движущие вербы: писатели файлов в хранилище —
# ещё и packages.sh с апдейтером, и снимок догоняет их ближайшим тиком, а не своей копией в
# каждом. Сравнение — ДО записи: /data смонтирован `sync`, и перезапись одинакового снимка раз в
# 2 минуты — это 720 записей на флеш в сутки ради нуля информации. Только builtin'ы и одна
# запись на изменение: у роутера без накопителя сюда не доходит (store_ready).
# Ступень — без ведущей точки и в ТОМ ЖЕ каталоге (разбор у keep_write): метла clean.sh её видит,
# а mv атомарен только внутри одной ФС.
seen_note() {
    store_ready || return 0
    _ssn=
    for _ssb in $STORE_MOVABLE; do
        if [ -f "$BIN_DIR/$_ssb" ]; then _ssn="${_ssn:+$_ssn }$_ssb"; fi
    done
    if [ -f "$STORE_SEEN" ]; then
        _sso=
        read -r _sso < "$STORE_SEEN" 2>/dev/null || :
        if [ "$_sso" = "$_ssn" ]; then unset _ssn _ssb _sso; return 0; fi
    fi
    _sst="${STORE_SEEN%/*}/bin-store-seen.new"
    if printf '%s\n' "$_ssn" > "$_sst" 2>/dev/null && mv -f "$_sst" "$STORE_SEEN" 2>/dev/null; then :; else rm -f "$_sst" 2>/dev/null; fi
    unset _ssn _ssb _sso _sst
    return 0
}
# seen_read — снимок в SEEN_NAMES; код 0 = снимок есть (пусто — «нашего там нет»), 1 = не знаем.
# ВХОД НЕДОВЕРЕННЫЙ, хотя пишем его только мы (та же мера, что у keep_write): файл правится руками,
# а имена уезжают в JSON панели и в вопрос человеку — мусорное слово не проходит фильтр по форме.
seen_read() {
    SEEN_NAMES=
    [ -f "$STORE_SEEN" ] || return 1
    _srr=
    read -r _srr < "$STORE_SEEN" 2>/dev/null || :
    set -f
    for _srx in $_srr; do
        case "$_srx" in ''|*[!a-z0-9-]*) ;; *) SEEN_NAMES="${SEEN_NAMES:+$SEEN_NAMES }$_srx" ;; esac
    done
    set +f
    unset _srr _srx
    return 0
}

# --- ЗАКРЕПЛЕНИЯ («этот бинарь держать на роутере») -------------------------------------------
# Читает их store-lib.sh (BIN_KEEP/bin_pinned), ПИШЕТ только этот файл — ровно как с .bin-store:
# резолвер отвечает «где лежит», движок делает так, чтобы ответ был правдой.
# После записи ОБЯЗАТЕЛЬНО перечитываем библиотеку: иначе bin_dest в ЭТОМ ЖЕ процессе ответит
# по-старому и move_verified поедет не в ту сторону (та же причина, что у mark_write выше).
# ВХОД НЕДОВЕРЕННЫЙ, хотя пишем файл только мы: его можно поправить руками, и он приезжает в
# бэкапе. Отсюда две меры, обе на разделении `$1` по словам:
#   * `set -f` — иначе `*` в файле РАСКРЫЛСЯ БЫ по текущему каталогу, и в список закреплений
#     попали бы имена посторонних файлов;
#   * фильтр по ФОРМЕ (та же форма, что у CGI) — мусорная строка не должна пережить перезапись.
keep_write() {      # $1 = имена через пробел; пустой список = файл снимаем
    set -f
    _kn=0
    for _kw in $1; do case "$_kw" in ''|*[!a-z0-9-]*) continue ;; esac; _kn=1; break; done
    if [ "$_kn" = 0 ]; then
        rm -f "$KEEP_MARK" 2>/dev/null
    else
        mkdir -p "${KEEP_MARK%/*}" 2>/dev/null
        # СТУПЕНЬ БЕЗ ВЕДУЩЕЙ ТОЧКИ, и это не косметика: метла мусора в clean.sh идёт по
        # "$_d"/*.new, а шелловский `*` ведущую точку НЕ матчит. `.bin-keep.new` от писателя,
        # убитого между записью и mv, не подмела бы ни одна маска — и осталась бы в персисте
        # навсегда ($ENODIA_STATE переживает и ребут, и обновление).
        # В ТОМ ЖЕ каталоге: mv атомарен только внутри одной ФС, а /tmp это другая.
        _kt="${KEEP_MARK%/*}/bin-keep.new"
        rm -f "$_kt" 2>/dev/null
        for _kw in $1; do
            case "$_kw" in ''|*[!a-z0-9-]*) continue ;; esac
            echo "$_kw" >> "$_kt"
        done
        if ! mv -f "$_kt" "$KEEP_MARK" 2>/dev/null; then
            rm -f "$_kt" 2>/dev/null; unset _kn _kw _kt; set +f; return 1
        fi
        unset _kt
    fi
    unset _kn _kw
    set +f
    if [ -f "$ENODIA_DIR/store-lib.sh" ]; then . "$ENODIA_DIR/store-lib.sh"; fi
    return 0
}
keep_add() { _ka="$BIN_KEEP"; for _kx in "$@"; do if ! bin_pinned "$_kx"; then _ka="$_ka $_kx"; fi; done; keep_write "$_ka"; _kr=$?; unset _ka _kx; return "$_kr"; }
keep_del() { _kd=; for _kx in $BIN_KEEP; do if [ "$_kx" != "$1" ]; then _kd="$_kd $_kx"; fi; done; keep_write "$_kd"; _kr=$?; unset _kd _kx; return "$_kr"; }

# need_router_b <имя> — СКОЛЬКО БАЙТ придётся вернуть на роутер, чтобы закрепить <имя>: он сам
# плюс его зависимости (bin_deps), которые сейчас ФИЗИЧЕСКИ лежат в хранилище. Судим по наличию
# файла, а не по намерению: уже закреплённая, но ещё не переехавшая зависимость место всё равно
# займёт.
need_router_b() {
    _nb=0
    if [ "$BIN_DIR" != "$ENODIA_BIN" ]; then
        for _nx in "$1" $(bin_deps "$1"); do
            if [ -f "$BIN_DIR/$_nx" ]; then _nb=$((_nb + $(size_b "$BIN_DIR/$_nx"))); fi
        done
    fi
    printf '%s' "$_nb"
    unset _nx
}
# fits_router <имя> — влезет ли возврат, не съев неснижаемый резерв /data. Считает РОУТЕР, а не
# панель: своей арифметики во фронте нет. Место спрашиваем по ПУТИ каталога (C50), не по /data.
fits_router() {
    _fr=$(df_free_b "$ENODIA_DIR")
    _fn=$(need_router_b "$1")
    [ "$((_fr - _fn))" -ge "$DATA_RESERVE_B" ]
}

# Запускается ли файл С ЭТОЙ ФС. Коды 126 (не исполняемый) и 127 (не найден) — единственные
# «нет»; всё прочее, включая ошибку самого бинаря и таймаут, означает «ядро его запустило».
# Универсально по бинарям: у каждого свои ключи, и таблица «чем проверять xray, а чем nfqws»
# протухла бы на первой новой связке. Снятый риск — не exec-бит (его даёт fmask), а
# самораспаковка UPX: ей нужен анонимный исполняемый маппинг.
#
# ЗАВЕДОМО НЕВЕРНЫЙ АРГУМЕНТ ОБЯЗАТЕЛЕН, и это не косметика. Без аргументов ciadpi не «стартует
# и выходит», а штатно поднимает SOCKS на СВОИХ дефолтах — 0.0.0.0:1080, и здесь ещё и от root
# (весь остальной проект зовёт его `-c nobody -i 127.0.0.1`). При стоковой политике INPUT=ACCEPT
# это открытый прокси, видимый из LAN и гостевой, на каждом enable/disable. Getopt/cobra у всех
# пятерых отвергают неизвестный ключ и выходят сразу, а exec и распаковка UPX к этому моменту
# уже случились — то есть проба меряет ровно то же, но ничего не слушает.
# cd /tmp: демоны без аргументов читают конфиг из текущего каталога, и делать это в $ENODIA_DIR
# незачем; 3 с — потолок на случай бинаря, который неизвестный ключ проглотит.
exec_ok() {
    ( cd /tmp 2>/dev/null && timeout -t 3 "$1" --enodia-exec-probe >/dev/null 2>&1 )
    _rc=$?
    [ "$_rc" != 126 ] && [ "$_rc" != 127 ]
}

# ПРОГРАММА ЛИ ЭТО (ELF или сценарий с `#!`). Проба запуска после копии имеет смысл ТОЛЬКО у программы: файл данных в каталоге
# бинарей (на BE7000 там лежал `awg3.conf`, положенный руками) проба объявляла «с этой ФС не запускается (noexec?)», файл
# оставался на месте, а смена раскладки советовала «воткните накопитель и повторите» — повторять было нечего (замер 28.09.2026);
# в обратную сторону (переезд в full) тот же файл заваливал бы весь переезд. Данные везём как данные: md5 сверяет и их.
is_program() {
    _ipm=$(head -c 4 "$1" 2>/dev/null)
    case "$_ipm" in "$(printf '\177ELF')"|'#!'*) return 0 ;; esac
    return 1
}

md5_of() { md5sum "$1" 2>/dev/null | cut -d' ' -f1; }

# Хвосты прерванного переезда (питание, выдернутая флешка). Сами они не рассосутся: clean.sh
# знает про `*.new` ТОЛЬКО в $ENODIA_DIR, а на накопителе это до 8.2 МБ, которые du_b честно запишет
# в «наше» — и человек увидит, что хранилище занимает вдвое больше, чем в нём лежит. Метём ИМЕНА
# ИЗ СПИСКА, а не маску `*.new`: рядом ходит apply-scripts, который пишет `<скрипт>.sh.new`, и
# снести его на полпути — уже наша поломка, а не уборка.
drop_stale_new() {
    for _sn in $STORE_MOVABLE; do
        rm -f "$ENODIA_BIN/$_sn.new" 2>/dev/null
        [ "$BIN_DIR" != "$ENODIA_BIN" ] && rm -f "$BIN_DIR/$_sn.new" 2>/dev/null
    done
    return 0
}

# Переселить ОДИН бинарь: копия → sync → сверка md5 → проба запуска → и только потом удаление
# исходника. Порядок именно такой: до последнего шага рабочий файл на месте, а прервись мы в
# любой точке — хуже некуда не станет (две одинаковые копии безопасны, bin_path возьмёт любую).
move_verified() {   # $1 = откуда, $2 = куда, $3 = имя для лога
    # ПЕРЕЕЗД САМОГО В СЕБЯ — ОТКАЗ, и громкий. Ниже стоит `rm -f "$1"` ПОСЛЕ того, как копия
    # встала на место: при src == dst он сносит РОВНО ТОТ ФАЙЛ, который только что «перенесли»,
    # а вызыватель слышит «переселено». Так на живом BE7000 (01.09.2026) исчезли hev, byedpi и
    # nfqws — при зелёном выводе «Переселено: 3». Причина была выше по стеку (хранилище не
    # опознали, BIN_DIR остался резидентным), но последний рубеж — здесь: функция, которая
    # ПЕРЕНОСИТ файл, не имеет права его УДАЛИТЬ, о чём бы её ни попросили.
    # Сверяем и строки, и УСТРОЙСТВО:INODE — путь к одному файлу пишется по-разному (лишний
    # слэш в $ENODIA_BIN, свой монтаж поверх стокового); пустой ответ stat (нет файла, чужой
    # busybox) в сравнение не идёт, иначе «нет обоих» читалось бы как «один и тот же».
    # Имя СВОЁ (`_mvid`), а не `_sid`: в этом проекте `_sid` занят «номером слота» (slots.sh,
    # zapret.sh, apply-bypass.sh). В busybox нет `local`, и однажды позаимствованное имя
    # подменяется у вызывателя — на этом уже погорели с `_t` (направление против типа ФС).
    _mvid=$(stat -c '%d:%i' "$1" 2>/dev/null)
    if [ "$1" = "$2" ] || { [ -n "$_mvid" ] && [ "$_mvid" = "$(stat -c '%d:%i' "$2" 2>/dev/null)" ]; }; then
        echo "  $3: источник и цель — ОДИН файл ($2), хранилище не опознано — не двигаю"
        return 1
    fi
    _sz=$(size_b "$1")
    _dstdir=${2%/*}
    mkdir -p "$_dstdir" 2>/dev/null
    _free=$(df_free_b "$_dstdir"); case "$_free" in ''|*[!0-9]*) _free=0 ;; esac
    if [ "$_free" -lt "$((_sz + 262144))" ]; then
        echo "  $3: не хватает места в $_dstdir ($(mb "$_free") МБ) — пропускаю"
        return 1
    fi
    rm -f "$2.new" 2>/dev/null
    if ! cp "$1" "$2.new" 2>/dev/null; then
        echo "  $3: не скопировался — пропускаю"; rm -f "$2.new" 2>/dev/null; return 1
    fi
    chmod +x "$2.new" 2>/dev/null      # на exFAT/NTFS права даёт монтирование, chmod там no-op
    sync
    if [ "$(md5_of "$1")" != "$(md5_of "$2.new")" ]; then
        echo "  $3: копия не сошлась по md5 — оставляю на месте"; rm -f "$2.new" 2>/dev/null; return 1
    fi
    if is_program "$1" && ! exec_ok "$2.new"; then
        echo "  $3: с этой ФС не запускается (noexec?) — оставляю на месте"; rm -f "$2.new" 2>/dev/null; return 1
    fi
    if ! mv -f "$2.new" "$2" 2>/dev/null; then
        echo "  $3: не встал на место — оставляю на месте"; rm -f "$2.new" 2>/dev/null; return 1
    fi
    rm -f "$1" 2>/dev/null
    sync
    echo "  $3: $(mb "$_sz") МБ → $_dstdir"
    return 0
}

# НАШИ ДЕМОНЫ, РАБОТАЮЩИЕ С ПРЕЖНЕГО МЕСТА (замер BE7000 30.09.2026: после переезда nfqws исполнял удалённый
# `/data/usr/app/enodia-bin/nfqws`). Файл переехал, а живой процесс исполняет удалённый inode прежнего места — до перезапуска. Движок
# демонов НЕ перезапускает, и это решение, а не забывчивость: рвать живой туннель ради переезда файла — не его дело (тот же довод,
# что у обновления компонента: «работает прежняя сборка»). Но и молчать нельзя: удалённый файл держит МЕСТО (xray — 8 МБ на
# флеше), а при возврате на роутер — сам НАКОПИТЕЛЬ (выдернутый, он уронит демон), и «где лежит» у панели врёт до перезапуска.
# Имя берём, только если наш бинарь с этим именем стоит ТЕПЕРЬ в ДРУГОМ месте: тот же путь — это замена сборки, её ведёт
# `gh-update.sh bin-status`. Имена — через пробел, в порядке сортировки (форма [a-z0-9-], JSON их не экранирует).
# `drive` — только те, чья ПРЕЖНЯЯ копия лежала на накопителе (вне каталога приложений на флеше — там живёт и бутстрап): иначе
# «не вынимайте накопитель» говорилось и про демон, работающий с удалённой копии НА ФЛЕШЕ (ревью ветки, круг 2).
old_place_names() {    # $1 = drive | пусто
    _opr="${ENODIA_BOOT%/*}/"
    exe_deleted | while read -r _opp _opf; do
        _opn=${_opf##*/}
        case "$_opn" in ''|*[!a-z0-9-]*) continue ;; esac
        if [ "$1" = drive ]; then case "$_opf" in "$_opr"*) continue ;; esac; fi
        _opc=$(bin_path "$_opn")
        [ -f "$_opc" ] && [ "$_opc" != "$_opf" ] && echo "$_opn"
    done | sort -u | tr '\n' ' ' | sed 's/ $//'
}
# ИТОГ ПЕРЕЕЗДА — ПОСЛЕДНЕЙ СТРОКОЙ (панель берёт `tail -1`): сколько свободно и, если кто-то держит прежнее место, — кто и до
# какого момента. Иначе «Свободно N МБ» обещало место, которого до перезапуска нет. `drive` — файлы ушли С НАКОПИТЕЛЯ: цена тогда
# не место, а сам накопитель (выдернутый, он уронит демон), и сказать это обязана именно последняя строка — тост видит только её
# (ревью ветки pkg-update, круг 1: предупреждение стояло строкой выше и до панели не доходило).
free_line() {    # $1 = drive | пусто
    _flo=$(old_place_names)
    _fld=""; [ "$1" = drive ] && _fld=$(old_place_names drive)
    printf 'Свободно на %s: %s МБ' "$(our_mp)" "$(mb "$(df_free_b "$ENODIA_DIR")")"
    if [ -n "$_fld" ]; then
        printf '. До перезапуска с накопителя работают: %s — не вынимайте его до перезапуска (проще всего — перезагрузить роутер)' "$_fld"
    elif [ -n "$_flo" ]; then
        printf '. До перезапуска с прежнего места работают: %s — оно освободится после перезапуска (проще всего — перезагрузить роутер)' "$_flo"
    fi
    echo
}

# ДВЕ КОПИИ ОДНОГО БИНАРЯ — разбираем в момент, когда хранилище снова доступно.
#
# Откуда они берутся. Пока накопителя нет, store_ready ложно ⇒ bin_dest указывает на /data, и
# установка/обновление кладут бинарь ТУДА. Снять при этом копию с накопителя bin_prune не может
# (BIN_DIR = ENODIA_DIR, накопителя-то нет). Флешку вернули — и bin_path, который предпочитает
# хранилище, начинает отдавать СТАРЫЙ файл: «обновил, и ничего не изменилось» — ровно тот
# симптом, ради которого в store-lib.sh записан инвариант «копия РОВНО одна».
#
# Кто прав: РЕЗИДЕНТНАЯ копия. Её положили позже — тогда, когда хранилища не было. Одинаковые
# файлы (прерванная миграция) просто схлопываем, не гоняя мегабайты.
#
# Цена под контролем. Дешёвая проверка `[ -f ] && [ -f ]` идёт на каждом тике (это builtin, ни
# одного форка), а до md5/копирования дело доходит только при РЕАЛЬНОМ дубле — то есть почти
# никогда. Штамп ставим лишь тогда: если разобрать не вышло (на накопителе нет места), не
# молотить md5 семимегабайтных файлов каждые две минуты до самого ребута.
resolve_dups() {
    [ "$BIN_DIR" != "$ENODIA_BIN" ] || return 0        # хранилища нет — дублей не бывает по определению
    [ -f "$DEDUP_STAMP" ] && return 0
    _any=0
    for _b in $STORE_MOVABLE; do
        if [ -f "$ENODIA_BIN/$_b" ] && [ -f "$BIN_DIR/$_b" ]; then _any=1; break; fi
    done
    [ "$_any" = 0 ] && return 0
    : > "$DEDUP_STAMP" 2>/dev/null
    for _b in $STORE_MOVABLE; do
        [ -f "$ENODIA_BIN/$_b" ] || continue
        [ -f "$BIN_DIR/$_b" ] || continue
        # ЗАКРЕПЛЁННЫЙ бинарь переворачивает разбор выше. Его место назначения — РЕЗИДЕНТНЫЙ путь,
        # значит все писатели (packages.sh, gh-update.sh, zapret.sh) кладут свежее туда, а копия в
        # хранилище осталась от жизни ДО закрепления. Она проигрывает и когда файлы одинаковы, и
        # когда различаются, — переносить в хранилище тут нечего.
        if bin_pinned "$_b"; then
            # …но снимать копию, которая СЕЙЧАС РАБОТАЕТ, можно только убедившись, что резидентная
            # ЗАПУСКАЕТСЯ. Судим тем же exec_ok, что и переезд, а не битом -x: бит теряется штатно
            # (chmod на exFAT — no-op, `--push` кладёт 644), но и восстановленный бит не обещает,
            # что файл цел — он мог доехать обрезанным. Вопрос ровно один: стартует ли он.
            chmod +x "$ENODIA_BIN/$_b" 2>/dev/null
            if exec_ok "$ENODIA_BIN/$_b"; then
                rm -f "$BIN_DIR/$_b" 2>/dev/null
                echo "usb-offload: $_b закреплён за роутером — копия в хранилище снята"
            else
                echo "usb-offload: $_b закреплён, но резидентная копия не запускается — копию в хранилище ОСТАВЛЯЮ"
            fi
            continue
        fi
        if [ "$(md5_of "$ENODIA_BIN/$_b")" = "$(md5_of "$BIN_DIR/$_b")" ]; then
            rm -f "$ENODIA_BIN/$_b" 2>/dev/null
            echo "usb-offload: $_b — лишняя копия на флеше роутера снята (файлы идентичны)"
        else
            echo "usb-offload: $_b на флеше роутера отличается от копии в хранилище — переношу свежую"
            if ! move_verified "$ENODIA_BIN/$_b" "$BIN_DIR/$_b" "$_b" >/dev/null 2>&1; then
                echo "usb-offload: $_b перенести не вышло — в хранилище остаётся СТАРАЯ копия, она и запускается"
            fi
        fi
    done
    return 0
}

