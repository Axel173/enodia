#!/bin/sh
# vpn-toggle.sh — глобальное вкл/выкл VPN и исключение конкретных устройств.
#
# v2 (май 2026): cmd_on теперь идемпотентно восстанавливает ВСЕ правила
# (mangle PREROUTING + NAT MASQUERADE + FORWARD + ip rule), а не только
# ip rule. Это лечит ситуацию, когда fw3/firewall на роутере reload-ится
# (после изменений в веб-морде Xiaomi или ребута init.d/firewall) и сносит
# ВСЕ iptables-таблицы — heal.sh при этом не помогает, потому что
# у него лок /tmp/enodia-heal.lock один раз за boot.
# Дополнительно добавлена команда `repair` для явного восстановления
# правил без переключения VPN on/off.
#
# Использование:
#   vpn-toggle.sh status              — текущее состояние
#   vpn-toggle.sh off                 — выключить VPN для всех (трафик через провайдера)
#   vpn-toggle.sh on                  — включить + восстановить правила (идемпотентно)
#   vpn-toggle.sh repair              — только восстановить правила (mangle/NAT/FORWARD)
#   vpn-toggle.sh rules               — то же БЕЗ несущей: после своего firewall reload, когда несущая не поднялась
#   vpn-toggle.sh exclude 192.168.31.50  — выключить VPN для одного устройства
#   vpn-toggle.sh include 192.168.31.50  — вернуть устройство в VPN
#   vpn-toggle.sh excluded            — показать список исключённых IP

TABLE=1000
MARK=0x1
EXCLUDE_CHAIN_PRE="VPN_EXCLUDE"   # mangle PREROUTING исключения
ENODIA_LIST="enodia_list"
IPLIST_SET="iplist_set"
HEAL_LOCK="/tmp/enodia-heal.lock"
SWITCH_LOCK="/tmp/enodia-switching.lock"   # ОБЩАЯ идиома «идёт смена несущей — сторож и heal не вмешиваются» (transport.sh, switch-vpn.sh, cgi hold_switch); держим её и на подъёме несущей в cmd_on
ENODIA_DIR=${ENODIA_DIR:-/data/usr/app/enodia}        # для apply-bypass.sh (персист исключений)
ENODIA_STATE=${ENODIA_STATE:-/data/usr/app/enodia-state}
ENODIA_BOOT=${ENODIA_BOOT:-/data/usr/app/enodia-boot}   # только для ПОДСКАЗОК человеку (см. ниже)
# ФЛАГ «человек выключил VPN» — ПЕРСИСТ на /data, а не отметка в RAM. Правила `off` снимает из
# ЯДРА, то есть из ОЗУ: до этого флага ребут возвращал всё обратно (heal переигрывал маркировку
# и поднимал несущую, лестница сторожа воскрешала даже zapret), и выключение читалось как
# сломанное. Читают флаг heal.sh (гасит шаги бута) и watchdog.sh (не сторожит и не чинит);
# снимают ДВОЕ — `on` здесь и `transport.sh switch` (выбор транспорта и есть включение).
# Решение пользователя 02.09.2026: off — это СОСТОЯНИЕ.
VPN_OFF_FLAG="$ENODIA_STATE/.vpn-off"
# Сброс УЖЕ УСТАНОВЛЕННЫХ соединений — только через ct-lib.sh: на ядре 4.4 (AX3600/BE3600)
# утилиты conntrack в прошивке НЕТ ВООБЩЕ, и прежний `conntrack -F || true` был тихим no-op —
# правило стояло, а поток шёл по-старому через NSS/ECM. Шим = прежнее поведение (частичный
# apply-scripts не должен падать), полноценный сброс живёт в самой библиотеке.
if [ -f "$ENODIA_DIR/ct-lib.sh" ]; then . "$ENODIA_DIR/ct-lib.sh"; fi
# Ожидание xtables-лока: ipt-lib.sh подменяет команду `iptables` и добавляет `-w`. Лок занят
# чужим кроном ⇒ без ожидания правило МОЛЧА не встаёт. Нет файла — прежний путь байт-в-байт.
if [ -f "$ENODIA_DIR/ipt-lib.sh" ]; then . "$ENODIA_DIR/ipt-lib.sh"; fi
# Нет ipt-lib.sh с `ipt_top` (частичное обновление) ⇒ прежнее «первым в цепочку», байт-в-байт.
command -v ipt_top >/dev/null 2>&1 || ipt_top() { _itc=$1; shift; iptables -C "$_itc" "$@" 2>/dev/null || iptables -I "$_itc" 1 "$@"; }
if ! command -v ct_flush >/dev/null 2>&1; then
    ct_flush()      { conntrack -F >/dev/null 2>&1 || true; }
    ct_flush_src_n(){ [ -n "$1" ] && conntrack -D --src "$1" 2>/dev/null | wc -l; return 0; }
fi
# «Кто сейчас ведёт несущую» (тик сторожа, прогон heal) — daemon-lib.sh; нет его (старая установка) — доводчика выключения не
# заводим, то есть ведём себя как раньше.
if [ -f "$ENODIA_DIR/daemon-lib.sh" ]; then . "$ENODIA_DIR/daemon-lib.sh"; fi
command -v wd_tick_alive >/dev/null 2>&1 || wd_tick_alive() { return 1; }
command -v heal_alive >/dev/null 2>&1 || heal_alive() { return 1; }
command -v pid_runs >/dev/null 2>&1 || pid_runs() { [ -n "$1" ] && [ -d "/proc/$1" ]; }
SETTLE_PID="/tmp/enodia-vpnoff-settle.pid"
WD_LOG="/tmp/enodia-watchdog.log"           # след доводчика — там же, где видны все смены несущей
# ВЕДЁТ ЛИ НЕСУЩУЮ КТО-ТО ЕЩЁ: чужая смена (switching-лок), живой тик сторожа, живой прогон heal (бутовый или переигрыш). Протухший
# switching-лок судит и снимает СТОРОЖ (`switch_lock_held`, SWITCH_STALE) — второй копии суждения о протухании здесь нет.
settle_busy() { [ -e "$SWITCH_LOCK" ] || wd_tick_alive || heal_alive; }
# ЛОК «ПРОВЕРКА ФЛАГА + ПОВТОР СНЯТИЯ» у доводчика ⟷ «СНЯТИЕ ФЛАГА» (cmd_flag_clear: `on` и `switch --home`). Без него «Включить VPN», нажатое, пока доводчик снимал,
# оставляло VPN «включённым» без несущей: доводчик флаг уже проверил и снимал дальше (ревью ветки, круг 2). Держатель — живой
# процесс vpn-toggle (его пид в файле; труп забираем сразу, лок переживает `kill -9`), живого ждём не дольше минуты: секция — секунды
# снятия, дольше значит завис, и включение важнее. Ловушки нет НАМЕРЕННО: снятие внутри секции ставит и снимает свои.
SETTLE_LOCK="/tmp/enodia-vpnoff-settle.lock"
settle_lock_take() {
    _stw=0
    while ! ( set -C; echo $$ > "$SETTLE_LOCK" ) 2>/dev/null; do
        _sth=$(cat "$SETTLE_LOCK" 2>/dev/null | tr -cd '0-9')
        pid_runs "$_sth" 'vpn-toggle\.sh' || rm -f "$SETTLE_LOCK" 2>/dev/null
        [ "$_stw" -ge 60 ] && return 1
        sleep 1; _stw=$((_stw + 1))
    done
    return 0
}
settle_lock_drop() { [ "$(cat "$SETTLE_LOCK" 2>/dev/null)" = "$$" ] && rm -f "$SETTLE_LOCK" 2>/dev/null; return 0; }

# ВАЖНО про target ACCEPT (а НЕ RETURN) в user-chain VPN_EXCLUDE:
# Каскад в PREROUTING после ensure_chain выглядит так:
#   1) -j VPN_EXCLUDE
#   2) -m set --match-set enodia_list dst -j MARK --set-mark 0x1
#   3) -m set --match-set iplist_set dst -j MARK --set-mark 0x1
# Если в VPN_EXCLUDE стоит `-j RETURN`, то после совпадения мы возвращаемся
# в PREROUTING на правило 2, и пакет ВСЁ РАВНО получает mark → идёт в VPN.
# Если стоит `-j ACCEPT`, в mangle table это останавливает обход всех
# оставшихся правил в этой таблице → mark не ставится → пакет идёт через
# main route (провайдер). Именно это и нужно для exclude.
# Не переписывай обратно на RETURN — оно молча сломает exclude.
#
# ВАЖНО про conntrack -D после exclude/include:
# На BE7000 активен Qualcomm NSS (ECM + PPE + SFE) — ускоритель пакетов.
# Он offload-ит установленные соединения через быстрый путь, минуя iptables.
# Если просто добавить правило в VPN_EXCLUDE, существующие соединения этого
# IP продолжат идти через VPN (ECM кэширует решение).
# Поэтому после изменения exclude-правил мы вызываем `conntrack -D --src $IP`
# — это удаляет conntrack-записи для IP, ECM получает уведомление и сбрасывает
# offload. Новые пакеты пойдут через iptables и увидят свежее правило.

ensure_chain() {
    iptables -t mangle -L "$EXCLUDE_CHAIN_PRE" -n >/dev/null 2>&1 || {
        iptables -t mangle -N "$EXCLUDE_CHAIN_PRE"
    }
    # Гарантируем, что наш chain вызывается ПЕРВЫМ в PREROUTING
    # (для трафика, идущего ЧЕРЕЗ роутер — LAN-клиенты → VPN-цели).
    iptables -t mangle -D PREROUTING -j "$EXCLUDE_CHAIN_PRE" 2>/dev/null
    iptables -t mangle -I PREROUTING 1 -j "$EXCLUDE_CHAIN_PRE"
    # И в OUTPUT (для трафика, который ГЕНЕРИРУЕТ сам роутер — daemons
    # типа xq_info_sync_mqtt / messagingagent, ходящие на Xiaomi cloud).
    # Без этого Mi Home модуль BE7000 ломается: router-cloud-tunnel идёт
    # через VPN → cloud видит "не родной" IP, отказ. См. xiaomi-bypass.sh.
    iptables -t mangle -D OUTPUT -j "$EXCLUDE_CHAIN_PRE" 2>/dev/null
    iptables -t mangle -I OUTPUT 1 -j "$EXCLUDE_CHAIN_PRE"
    # Позицию СРЕДИ ПРОЧИХ цепочек (VPN_PORTS выше нас, VPN_FORCE ниже) знает один
    # владелец — apply-bypass.sh. Своя вставка на позицию 1 задвинула бы VPN_PORTS под
    # наш ACCEPT, а он обрывает обход mangle → правила по портам молча перестали бы
    # работать. Best-effort: нет apply-bypass — остаётся ровно прежнее поведение.
    [ -f "$ENODIA_DIR/apply-bypass.sh" ] && sh "$ENODIA_DIR/apply-bypass.sh" order >/dev/null 2>&1
    return 0
}

cmd_status() {
    # Флаг печатаем ОТДЕЛЬНОЙ строкой, а не вместо вердикта по ядру: «правил нет» и «человек
    # выключил» — разные вопросы, и расхождение между ними (флаг есть, а правила стоят) как раз
    # и есть та поломка, которую надо увидеть глазами.
    [ -f "$VPN_OFF_FLAG" ] && echo "Тумблер: ВЫКЛЮЧЕН человеком (переживает ребут; вернуть — vpn-toggle.sh on)"
    if ip rule show | grep -q "fwmark $MARK"; then
        echo "VPN: ON (глобально)"
    else
        echo "VPN: OFF (глобально)"
    fi
    # Доп-выходы (слоты) — ОТДЕЛЬНАЯ строка, а не молчание: у каждого своя марка 0x2..0x7 и свой
    # ip rule, поэтому по одной лишь марке основного туннеля судить о них нельзя (ревью 04.08.2026 —
    # раньше `off` их не снимал, а status показывал «OFF» при живых выходах).
    _slr=$(ip rule show 2>/dev/null | grep -c 'fwmark 0x[2-7]')
    case "$_slr" in ''|*[!0-9]*) _slr=0 ;; esac   # busybox: grep -c при нуле даёт код 1
    [ "$_slr" -gt 0 ] && echo "Доп-выходы: правил маршрутизации активно: $_slr"
    echo
    echo "awg0 интерфейс:"
    ip a show awg0 2>/dev/null | grep -E 'inet |state' | head -2
    echo
    echo "Исключённые IP (трафик идёт мимо VPN):"
    iptables -t mangle -L "$EXCLUDE_CHAIN_PRE" -n 2>/dev/null | awk '/ACCEPT/{print "  " $4}'
}

# Снимаем PBR ВСЕХ выходов: основного (0x1) и доп-выходов (0x2..0x7). Раньше уходила только марка
# основного туннеля, а группы/устройства, привязанные к доп-выходу, продолжали ехать через свой VPS
# при «VPN выключен для всех» (ревью 04.08.2026) — то есть тумблер врал ровно тем, кто настроил
# больше одного выхода. Форм у слот-правила две (своя table 100N и fallback на 1000) — сносим обе,
# как это делает mark-core.sh; обратно их ставит он же на `on`/`repair`.
cmd_off() {
    # ПЕРВЫМ делом — намерение на диск, и только потом работа с ядром: если нас прибьют на
    # середине (uhttpd режет затянувшийся CGI), человек всё равно получит выключенный VPN
    # после ребута, а не половину снятых правил и полное возвращение через две минуты.
    mkdir -p "$ENODIA_STATE" 2>/dev/null
    # Доводчик (off-settle) момент выключения не переписывает: он доводит ТО ЖЕ нажатие.
    [ "$OFF_SETTLE" = 1 ] || date +%s > "$VPN_OFF_FLAG" 2>/dev/null
    # PIPE и HUP — не просьба остановиться, их глушим ДО КОНЦА выключения, взяли мы лок или нет (как pkg-install.sh): убитый CGI
    # оставляет нас писать в мёртвую трубу, обрыв SSH шлёт HUP, а намерение уже на диске — умри мы здесь, несущая, выходы и
    # доводчик так и не случились бы, и сторож с флагом их не снимет до ребута (ревью C121, круги 1–2).
    trap '' HUP PIPE
    # ЗАНЯТОСТЬ — И В МОМЕНТ НАЖАТИЯ, а не только в конце: тик, кончившийся посреди снятия, успевал поднять несущую после нашего
    # `down` и к концу был уже не виден (ревью ветки, круг 2). Свой switching-лок ниже ещё не взят — всё, что видно, чужое.
    _busy0=0; settle_busy && _busy0=1
    ip rule del fwmark $MARK table $TABLE 2>/dev/null
    for _s in 2 3 4 5 6 7; do
        ip rule del fwmark "0x$_s" table "100$_s" 2>/dev/null
        ip rule del fwmark "0x$_s" table $TABLE 2>/dev/null
    done
    # ЛОК СМЕНЫ НЕСУЩЕЙ — И НА СНЯТИИ ТОЖЕ (зеркало cmd_on). Флаг `.vpn-off` записан выше, и тик
    # сторожа, который начнётся ПОСЛЕ него, из тика выйдет. Но тик, уже прошедший проверку флага,
    # может прямо сейчас вести failover — и поднять несущую ровно между нашим `down` и `cold`.
    # Раньше это стоило «лишних правил до следующего тика»; теперь — ТЁПЛОГО ДЕМОНА, который
    # переживёт выключение молча и до самого ребута (сторож с флагом его не тронет). Лок тот же
    # самый, четвёртой семантики не заводим: сторож и heal выходят на нём безусловно.
    # Занят ⇒ смену ведёт кто-то другой; ЖДАТЬ НЕ БУДЕМ и не откажемся — человек нажал «выключить»,
    # и его намерение уже на диске: снимаем что можем, остальное подберёт `repair`/ребут.
    _offlk=0
    if [ ! -e "$SWITCH_LOCK" ] && : > "$SWITCH_LOCK" 2>/dev/null; then
        _offlk=1
        # Ловушка и на СИГНАЛАХ (INT/TERM; HUP и PIPE заглушены выше): забытый лок держит сторожа и heal до
        # срока SWITCH_STALE (30 мин). Сигнал — ВЫХОД (C121): без `exit` шелл шёл дальше уже без лока.
        trap 'rm -f "$SWITCH_LOCK" 2>/dev/null' EXIT
        trap 'exit 1' INT TERM
    fi
    # НЕСУЩУЮ ОТПУСКАЕМ ВСЕГДА, каким бы транспорт ни был. Раньше здесь спрашивали «везёт ли он
    # маркой» и снимали только НЕмаркирующего (zapret: весь дом идёт напрямую, категории пробивает
    # nfqws на форварде, и снятие марок его не выключало ВООБЩЕ — «после некоторой магии всё
    # вернулось», тестер 18.08.2026). Для маркирующих оставить несущую казалось дешевле: без
    # `ip rule` метка холостая, трафик и так идёт напрямую.
    # НО DNS МАРКОЙ НЕ ХОДИТ. У awg его владелец — плагин: `restore_vpn_dns` пишет в
    # `/etc/dnsmasq.d/00-upstream.conf` ТУННЕЛЬНЫЙ адрес и кладёт к нему маршрут `dev awg0`.
    # Пока awg0 жив, весь дом продолжал резолвить ЧЕРЕЗ выключенный VPN, а на роутере, где `/etc`
    # переживает ребут (AX3600/BE3600 — ubifs), после перезагрузки становилось хуже: heal с флагом
    # несущую НЕ поднимает, и dnsmasq форвардит в адрес, которого больше нет, — ВСЯ СЕТЬ БЕЗ ИМЁН
    # при зелёной панели. Тот же класс ловили живьём 31.08.2026 («только панель» после
    # включил-выключил, transport.sh cmd_dns).
    # `down` плагина — это и есть РЕЛИНКВИШ: маршрут/NAT снимаются, DNS возвращается прямым
    # (тёплый резерв awg0 снимаем ниже, отдельным шагом), а DoH, если он хозяин DNS, остаётся при
    # своём. НАМЕРЕНИЕ (`.transport`) НЕ трогаем: обратно несущую поднимет `on` (repair +
    # `heal.sh replay`, секция 5.6) — ТЕМ ЖЕ путём, что и после ребута. Это и есть главный
    # смысл правки: состояние «выключено» теперь ОДНО И ТО ЖЕ до перезагрузки и после.
    # Нет файла оркестратора (установка старее плагинов) ⇒ ведём себя как раньше, байт-в-байт.
    # СНАЧАЛА ЗАФИКСИРОВАТЬ УЧЁТ, ПОТОМ РУШИТЬ ИНТЕРФЕЙСЫ — и ДО `down`, а не между ним и `cold`.
    # Счётчики живут В САМОМ TUN, а копит их cron (*/5): всё, что прошло с последнего тика, есть
    # ТОЛЬКО в /proc/net/dev и умирает вместе с интерфейсом. Панель показывает этот хвост
    # «незаписанной дельтой» (web/cgi-bin/traffic), причём ИМЯ интерфейса берёт из `.transport`, а
    # тот при выключении ЦЕЛ ⇒ читатель считает дельту по интерфейсу, которого уже нет, и получает
    # ноль. ЗАМЕР 02.09.2026 на BE7000: «Сегодня через VPN» 1.08 ГБ → 1.07 ГБ В МОМЕНТ нажатия
    # «выключить». Счётчик за сегодня монотонен по смыслу, и убывающее число читается как поломка.
    # Место выбрано выше `down` НАРОЧНО: у awg интерфейс умирает позже (в `cold`), а у альтов его
    # уносит САМ `down` (stop_daemons → xtun исчезает вместе с hev) — фиксируй мы после него,
    # хвост спасался бы только для awg. Лок у накопителя свой: занят кроном — выйдет молча.
    [ -f "$ENODIA_DIR/traffic-acct.sh" ] && sh "$ENODIA_DIR/traffic-acct.sh" >/dev/null 2>&1
    _offt=$(active_transport)
    if [ "$_offt" != none ] && [ -f "$ENODIA_DIR/transport.sh" ]; then
        echo "Отпускаю несущую транспорта $_offt (маршрут и DNS — прямые)…"
        sh "$ENODIA_DIR/transport.sh" down "$_offt" >/dev/null 2>&1
    fi
    # ДОП-ВЫХОДЫ — ТОЖЕ РЕСУРС, А НЕ ТОЛЬКО МАРКА. Снятые выше слотовые `ip rule` выключают
    # ТУННЕЛЬНЫЙ выход, но zapret-выход не маршрутизирует вовсе: он правит пакеты на форварде по
    # правилам NFQUEUE, и ЗАМЕР НА ЖЕЛЕЗЕ (BE7000, 02.09.2026) показал ровно это — после «выключить
    # VPN» nfqws жив, правила на месте, ютуб идёт через десинк, а шапка панели обещает «весь трафик
    # напрямую». У туннельных слотов та же половина тише: демон и xtunN остаются жить впустую.
    # Критерий тут один и он наш собственный: после `off` роутер обязан быть ТЕМ ЖЕ, что после
    # ребута с флагом, — а heal с флагом слоты не поднимает. Реестр не трогаем (выход остаётся
    # `on`): выключили VPN, а не выход; обратно поднимет `on` через heal replay, как и ребут.
    if [ -f "$ENODIA_DIR/transport.sh" ]; then
        _offs=$(sh "$ENODIA_DIR/transport.sh" slots-down 2>&1)
        [ -n "$_offs" ] && printf '%s\n' "$_offs" | sed 's/^/  /'
    fi
    # ТЁПЛЫЙ РЕЗЕРВ — ТОЖЕ РЕСУРС. `down` у awg оставляет awg0 живым НАРОЧНО: пока везёт другой
    # транспорт, кросс-возврат стоит один `setconf` вместо старта демона и рукопожатия. Но при
    # выключенном тумблере возвращаться НЕКУДА — сторож с `.vpn-off` выходит из тика, а heal на
    # буте awg0 не поднимает даже резервом. Значит демон оставался жать keepalive к VPS (на линии
    # видно, что «выключенный» роутер разговаривает с сервером) и держал свой пул буферов, который
    # ядру не возвращается: `down` его не сбрасывает, а ЗАМОРАЖИВАЕТ на достигнутом — на 176-МБ
    # моделях это замеренные 40+ МБ впустую. И тот же критерий, что у слотов: после `off` роутер
    # обязан быть ТЕМ ЖЕ, что после ребута с флагом. Спрашиваем ВСЕ транспорты (не только
    # активный): awg0 мог остаться тёплым с прошлого switch, пока вёз xray.
    if [ -f "$ENODIA_DIR/transport.sh" ]; then
        sh "$ENODIA_DIR/transport.sh" cold >/dev/null 2>&1
    fi
    # Лок отпускаем ЗДЕСЬ — после снятия несущих и выходов, но ДО сброса conntrack: держать его на
    # ct_flush незачем, а сторож к этому моменту уже увидит и флаг, и снятое состояние.
    if [ "$_offlk" = 1 ]; then
        trap - EXIT INT TERM
        rm -f "$SWITCH_LOCK" 2>/dev/null
    fi
    # NSS/ECM держит УЖЕ установленные сессии на прежнем маршруте — без сброса выключение видно
    # только на новых соединениях (инвариант проекта: после смены маршрутизации — conntrack).
    ct_flush
    # ДОВОДЧИК ВЫКЛЮЧЕНИЯ. Флаг останавливает автоматику, которая НАЧНЁТСЯ после него, но не ту, что уже идёт: перебор серверов
    # AmneziaWG (switch-vpn под своим локом — минуты), возврат домой, перебор резервов xray/hy2, переподъём awg0 в тике сторожа,
    # прогон heal. Досчитав до живого сервера, она поднимала несущую ПОСЛЕ нашего `down`: default в table 1000, NAT и туннельный DNS
    # на весь дом при «выключенном вами» VPN — до ребута (ревью ветки, круг 1). Латать каждую из шести дорог — шесть копий
    # «как выключить»; вместо этого, если в момент нажатия несущую вёл кто-то ещё (чужой switching-лок, живой тик, живой heal), фоном
    # дожидаемся конца и повторяем это же снятие — оно идемпотентно. Новую автоматику флаг не пустит, ждать только уже идущую.
    # С тех пор несущую при флаге не берёт и сама автоматика (плагины — daemon-lib.sh::carrier_run, перебор серверов, awg_setup,
    # mark-core): доводчик остался СТРАХОВКОЙ на дорогу, которую ещё не научили, и повторяет снятие, только если что-то вернулось.
    if [ "$OFF_SETTLE" != 1 ] && { [ "$_busy0" = 1 ] || [ "$_offlk" = 0 ] || wd_tick_alive || heal_alive; }; then
        if command -v start-stop-daemon >/dev/null 2>&1; then
            start-stop-daemon -S -b -m -p "$SETTLE_PID" -x /bin/sh -- "$ENODIA_DIR/vpn-toggle.sh" off-settle >/dev/null 2>&1
        else
            ( sh "$ENODIA_DIR/vpn-toggle.sh" off-settle >/dev/null 2>&1 & )
        fi
    fi
    echo "VPN глобально ВЫКЛЮЧЕН. Трафик идёт через провайдера (включая доп-выходы)."
    echo "Не забудьте: ipconfig /flushdns на клиентах."
}

# Фон доводчика (см. конец cmd_off). ТРИ ПРАВИЛА, и каждое оплачено ревью ветки (круг 2):
#   · ПОТОЛКА ПО ЧАСАМ НЕТ — ждём, пока держатель ЖИВ (тик и heal — по пиду; switching-лок — пока его не снял владелец или сторож
#     как протухший): прежние 900 с были меньше перебора большого пула (SWITCH_STALE 1800), и доводчик выходил раньше смены;
#     включили VPN обратно — ждать нечего, выходим сразу;
#   · проверка флага и повтор снятия — ПОД ЛОКОМ, общим с `on` (settle_lock_take);
#   · повтор — ТОЛЬКО ЕСЛИ ЧТО-ТО ВЕРНУЛОСЬ (`transport.sh live`): лишнее снятие — это второй сброс conntrack всего дома и рестарт
#     dnsmasq. Старая копия оркестратора без верба (код 2) — «не знаю», значит повторяем, как раньше.
cmd_off_settle() {
    _osw=0
    while [ -f "$VPN_OFF_FLAG" ] && settle_busy; do sleep 2; _osw=$((_osw + 2)); done
    if settle_lock_take; then
        if [ ! -f "$VPN_OFF_FLAG" ]; then
            :                                   # пока ждали, VPN включили обратно — доводить нечего
        elif ! carrier_left; then
            echo "$(date '+%Y-%m-%d %H:%M:%S') vpn-toggle: VPN выключили посреди чужой смены несущей — ждал ${_osw} с, ничего не вернулось" >> "$WD_LOG" 2>/dev/null
        else
            echo "$(date '+%Y-%m-%d %H:%M:%S') vpn-toggle: VPN выключили посреди чужой смены несущей — довожу выключение (ждал ${_osw} с)" >> "$WD_LOG" 2>/dev/null
            OFF_SETTLE=1
            cmd_off >/dev/null 2>&1
        fi
        settle_lock_drop
    fi
    rm -f "$SETTLE_PID" 2>/dev/null
}
# СНЯТИЕ ФЛАГА «VPN выключен вручную» — ЕДИНСТВЕННОЕ место (следит C117). Снимающих двое: «Включить VPN» (`on`) и выбор транспорта
# человеком (`transport.sh switch <t> --home`, верб `flag-clear`), и оба — ПОД ЛОКОМ ДОВОДЧИКА: иначе доводчик, уже проверивший флаг,
# продолжал снимать после них — «включено» без несущей (ревью ветки: круг 2 — у `on`, круг 3 — у `--home`, где снятие было голым
# `rm`). Лок не взялся за минуту (доводчик завис) — флаг снимаем всё равно: включение важнее.
cmd_flag_clear() {
    _onl=0; settle_lock_take && _onl=1
    rm -f "$VPN_OFF_FLAG" 2>/dev/null
    [ "$_onl" = 1 ] && settle_lock_drop
    return 0
}
carrier_left() {
    [ -f "$ENODIA_DIR/transport.sh" ] || return 0
    sh "$ENODIA_DIR/transport.sh" live >/dev/null 2>&1
    [ "$?" != 1 ]
}

# ЕДИНЫЙ ответ «какой транспорт активен» для этого файла (repair и on спрашивают одно и то же).
# Пустой флаг: либо роутер старше `.transport` (несущая awg — так было всегда), либо установка
# «только панель», где транспорта нет вовсе. Отличает их оркестратор (см. transport.sh
# configured); код 2 = старая копия скрипта ⇒ как раньше. С `none` repair чинит ВСЁ, кроме ядра
# маркировки и несущей: вырезы, слоты, «доступ домой» и панель живут и без транспорта.
active_transport() {
    _at=$(cat "$ENODIA_STATE/.transport" 2>/dev/null | tr -d ' \r\n')
    if [ -z "$_at" ]; then
        _at=awg
        if [ -f "$ENODIA_DIR/transport.sh" ]; then
            sh "$ENODIA_DIR/transport.sh" configured >/dev/null 2>&1
            [ "$?" = 1 ] && _at=none
        fi
    fi
    printf '%s' "$_at"
}

# Идемпотентно восстановить ВСЕ правила, которые ставит heal.sh
# (mangle PREROUTING + NAT POSTROUTING + FORWARD + route в таблицу 1000).
# Зачем: fw3/firewall на роутере иногда перезагружается (изменения в
# веб-морде Xiaomi, /etc/init.d/firewall restart) и сносит ВСЕ iptables-
# таблицы. heal.sh при этом сам не восстановит — у него лок
# /tmp/enodia-heal.lock один раз за boot, и cron каждый тик просто выходит.
#
# `rules` — ТОТ ЖЕ список БЕЗ НЕСУЩЕЙ (REPAIR_CARRIER=0): и без её шагов, и без гарда «awg0 не
# поднят». Нужен тому, кто САМ сделал firewall reload, а несущую поднять не смог: `awg_setup.sh`
# кончается reload'ом и тогда, когда awg0 так и не появился, а `repair` на этом месте отказывал
# целиком — вырезы «мимо VPN», zapret, выходы, блокировки и «доступ домой» ждали ребута. Фолбэк
# сторожа «Выкл» повторяет такую попытку раз в 10–30 мин (ревью dev233). Маршрута в туннель `rules`
# не ставит: ядро маркировки без `default` в table 1000 ведёт в main, то есть напрямую, — поэтому
# его можно звать и из прямого режима (safety_off). Список ОДИН на оба верба: вторая копия отстала
# бы с первой же новой подсистемой.
REPAIR_CARRIER=1
cmd_rules() { REPAIR_CARRIER=0; cmd_repair; }
cmd_repair() {
    # ВЫКЛЮЧЕНО ЧЕЛОВЕКОМ — правила VPN не чиним. `repair` возвращает то, что снесли ЧУЖИЕ руки (fw3 reload из вебморды
    # Xiaomi), а правил VPN здесь нет НАРОЧНО: вернуть их = включить VPN за спиной человека. Ровно этим путём лестница сторожа и
    # воскрешала zapret после «выключить».
    # …НО ПРАВИЛА НЕ ПРО VPN — ЧИНИМ И ТУТ: блокировки по адресам, запрет IPv6 и «доступ домой» живут при выключенном VPN (heal
    # на буте с флагом их ставит), а прежде `repair` с флагом выходил сразу — и снесённое чужим reload молча пропадало до ребута
    # при включённых тумблерах (хвост 10 ревью dev233). Критерий тот же, что у `off`: после починки роутер обязан быть ТЕМ ЖЕ,
    # что после ребута с флагом. Код 0: для вызывающего (панель, сторож) это не отказ.
    repair_off=0
    if [ -f "$VPN_OFF_FLAG" ]; then
        repair_off=1
        echo "VPN выключен человеком — правила VPN не переигрываю, возвращаю только блокировки, запрет IPv6 и «доступ домой» (включить VPN: тумблер в панели или vpn-toggle.sh on)"
    fi
    # Активный транспорт определяем СРАЗУ: несущая awg и альтов (xray/hy2) живёт на
    # РАЗНЫХ интерфейсах (awg0 vs xtun). Раньше cmd_repair был awg-центричен —
    # безусловно ставил default table 1000 → awg0 + MASQUERADE/FORWARD awg0 и ТРЕБОВАЛ
    # поднятый awg0, а альт переигрывал лишь в конце. На альт-несущей это создавало
    # переходное «awg0 несёт» состояние → health альта спотыкался → watchdog кросс-
    # эскалировал на awg (несущая молча менялась hy2→awg; ровно это ловил пользователь
    # на «VPN выкл → вкл» под Hysteria2). Теперь awg0-шаги — ТОЛЬКО при transport=awg;
    # для альта несущую (default xtun + FORWARD + DNS) идемпотентно ставит его плагин
    # через transport.sh up, а default table 1000 на awg0 НЕ трогаем.
    repair_t=$(active_transport)

    # awg-несущей нужен поднятый awg0; альту — нет (awg0 тёплый резерв / может отсутствовать).
    if [ "$REPAIR_CARRIER" = 1 ] && [ "$repair_off" = 0 ] && [ "$repair_t" = "awg" ] && ! ip link show awg0 >/dev/null 2>&1; then
        # ПОЧЕМУ awg0 нет — два разных ответа, и советы у них противоположные. Если бинарей
        # AmneziaWG на роутере нет, heal не поднимет несущую НИКОГДА, сколько его ни зови, — а
        # именно это мы и советовали, причём командой с `rm -f` лока. Типовой путь сюда: установка
        # «только панель» + ИМПОРТ бэкапа с другого роутера (намерение `.transport=awg` приехало,
        # файлы — нет; замерено на AX3600 16.08.2026). Владелец ответа «готов ли транспорт» один —
        # оркестратор (`list` печатает готовые; у awg «готов» = ОБА бинаря). Нет оркестратора =
        # роутер старше него ⇒ ведём себя как раньше, байт-в-байт.
        if [ -f "$ENODIA_DIR/transport.sh" ] && ! sh "$ENODIA_DIR/transport.sh" list 2>/dev/null | grep -qx awg; then
            echo "AmneziaWG выбран транспортом, но его бинарей на роутере нет."
            echo "  Установите компонент «AmneziaWG» в панели: «Компоненты» — heal тут не поможет."
            return 1
        fi
        # ПОДСКАЗКА ЧЕЛОВЕКУ — ТОЛЬКО В ФОРМЕ БУТСТРАПА. Прямой `sh $ENODIA_DIR/heal.sh` верен,
        # пока код лежит на флеше; в раскладке `full` он читает ЛИТЕРАЛЫ ФЛЕША (у heal своё
        # `${ENODIA_STATE:-/data/usr/app/enodia-state}`, а окружение ему никто не экспортировал) —
        # то есть heal чинил бы ЧУЖОЕ, пустое состояние, попутно создавая на флеше пустышку-двойника.
        # Пути экспортирует ровно один: `boot.sh`. Наступили на это 02.09.2026 на живом BE7000.
        echo "awg0 не поднят — сначала запустите heal.sh:"
        echo "  rm -f $HEAL_LOCK && sh $ENODIA_BOOT/boot.sh heal.sh"
        return 1
    fi

    # --- транспорт-агностичное ядро: reply-guard + маркировка (PREROUTING+OUTPUT) + ip rule ---
    # ЕДИНЫЙ источник — mark-core.sh. Раньше тут был инлайн-дубль, который ОТСТАЛ: не ставил
    # reply-guard (dst-LOCAL ACCEPT — без него возврат прямого трафика рвётся, если WAN-IP ∈
    # iplist_set, грабля тестера) и OUTPUT-маркировку (трафик самого роутера к CIDR утекал мимо
    # туннеля). Зовём mark-core; инлайн ниже — лишь фолбэк для старых роутеров без него.
    if [ "$repair_off" = 1 ]; then
        :
    elif [ "$repair_t" = none ]; then
        # Транспорта нет — метить некуда: ядро не ставим (иначе repair «чинил» бы правила,
        # которых на этом роутере не заводили).
        echo "транспорт не настроен — ядро маркировки и несущую пропускаю"
    elif [ -f "$ENODIA_DIR/mark-core.sh" ]; then
        sh "$ENODIA_DIR/mark-core.sh" >/dev/null 2>&1
    else
        ip rule del fwmark $MARK table $TABLE 2>/dev/null
        ip rule add fwmark $MARK table $TABLE pref 99
        for set in "$ENODIA_LIST" "$IPLIST_SET"; do
            if ipset list -n 2>/dev/null | grep -qx "$set"; then
                iptables -t mangle -C PREROUTING -m set --match-set "$set" dst -j MARK --set-mark $MARK 2>/dev/null || \
                    iptables -t mangle -A PREROUTING -m set --match-set "$set" dst -j MARK --set-mark $MARK
                iptables -t mangle -C OUTPUT -m set --match-set "$set" dst -j MARK --set-mark $MARK 2>/dev/null || \
                    iptables -t mangle -A OUTPUT -m set --match-set "$set" dst -j MARK --set-mark $MARK
            fi
        done
    fi

    # Цепочка исключений + сами исключения «мимо VPN» из persistent-хранилища. fw3-reload сносит
    # iptables → ensure_chain создаёт VPN_EXCLUDE ПУСТОЙ; без apply устройства/SSID/guest,
    # выведенные напрямую, после repair снова ушли бы в VPN. apply идемпотентен и трогает только
    # прямой путь.
    # ...но при `none` не делаем НИЧЕГО из этого: «мимо VPN» без VPN бессмысленно, а сама пара
    # (цепочка + reply-guard) — единственный наш след в mangle на чистом роутере. Тот же гейт, что
    # в heal 5.5: иначе кнопка «Починить правила» возвращала бы ровно то, что heal не ставит.
    if [ "$repair_off" = 1 ]; then
        :
    elif [ "$repair_t" = none ]; then
        echo "транспорт не настроен — вырезы «мимо VPN» не переигрываю"
    else
        ensure_chain
        # Вывод — В НИКУДА, как у всех соседних шагов: метки этапа («[apply-bypass] порт-правила: нет» — по строке на семью)
        # человеку в тосте «Починить правила» ни к чему, а под английским одна непереведённая строка делала русским ВЕСЬ тост
        # (хвост 9 ревью dev233). Итог починки — последняя строка ниже.
        [ -f "$ENODIA_DIR/apply-bypass.sh" ] && sh "$ENODIA_DIR/apply-bypass.sh" apply >/dev/null 2>&1
    fi

    # --- несущая активного транспорта (у `rules` — не наша забота: её поднимет или не поднимет вызыватель) ---
    if [ "$repair_off" = 1 ] || [ "$repair_t" = none ] || [ "$REPAIR_CARRIER" = 0 ]; then
        :
    elif [ "$repair_t" = "awg" ]; then
        # awg несёт сама (awg0): default table 1000 + MASQUERADE + FORWARD на awg0.
        ip route replace default dev awg0 table $TABLE 2>/dev/null
        iptables -t nat -C POSTROUTING -o awg0 -j MASQUERADE 2>/dev/null || \
            iptables -t nat -A POSTROUTING -o awg0 -j MASQUERADE
        ipt_top FORWARD -o awg0 -j ACCEPT
        ipt_top FORWARD -i awg0 -j ACCEPT
    elif [ -f "$ENODIA_DIR/transport.sh" ]; then
        # Альт (xray/hy2): несущую (default xtun + FORWARD xtun + DNS) ставит ПЛАГИН
        # идемпотентно (демоны живы — не перезапускает). default table 1000 на awg0 НЕ
        # трогаем — иначе тот самый «переходный awg0», что ронял health и провоцировал cross.
        # Вывод плагина (его `status` целиком: демоны, таблица, проба выхода) — только при ОТКАЗЕ и только хвост: на успехе это
        # полтора десятка строк диагностики в тосте. Через ФАЙЛ, а не `$(…)`: подъём может породить демонов, и труба ждала бы
        # их EOF (тот же замер, что у переигрыша в cmd_on).
        _rpu="/tmp/enodia-repair-up.$$"
        if ! sh "$ENODIA_DIR/transport.sh" up "$repair_t" >"$_rpu" 2>&1; then
            echo "ВНИМАНИЕ: несущая $repair_t не поднялась — правила восстановлены, поднимать её будет сторож:"
            tail -n 3 "$_rpu"
        fi
        rm -f "$_rpu" 2>/dev/null
    fi

    # Zapret-транспорт: активен ⇔ .zapret-on есть (двигается вместе с .transport=zapret). fw3-reload
    # снёс его mangle-правила → переигрываем (apply идемпотентен; при неактивном — no-op/teardown).
    # Подстраховка: когда zapret активен, `transport.sh up` выше уже зовёт apply — дубль дёшев и безопасен.
    # Выключено человеком ⇒ десинк и доп-выходы — тоже VPN (их снимает `off`), не возвращаем ни того, ни другого.
    [ "$repair_off" = 0 ] && [ -f "$ENODIA_DIR/zapret.sh" ] && [ -f "$ENODIA_STATE/.zapret-on" ] && sh "$ENODIA_DIR/zapret.sh" apply >/dev/null 2>&1

    # Доп-выходы (слоты, Ф1): fw3-reload снёс их правила. В СЛОТ-режиме zapret .zapret-on НЕТ
    # (несущая — VPN), поэтому ветка zapret-транспорта выше слот не восстановит. Переигрываем как
    # heal 5.13b: zapret-слот re-wire ACCEPT+scoped NFQUEUE на свои сеты (живут в RAM, пережили
    # reload), non-zapret — марку/ip rule через mark-core. Реестр пуст → no-op.
    [ "$repair_off" = 0 ] && [ -f "$ENODIA_DIR/slots.sh" ] && [ -n "$(sh "$ENODIA_DIR/slots.sh" list-enabled 2>/dev/null)" ] && \
        [ -f "$ENODIA_DIR/transport.sh" ] && sh "$ENODIA_DIR/transport.sh" slots-up >/dev/null 2>&1

    # «Доступ домой» (vpn-server.sh): его цепочки (порт наружу, INPUT из туннеля с default-deny,
    # FORWARD) fw3-reload сносит вместе со всеми. Несущая awgs0 при этом ЖИВА, поэтому чинить надо
    # только правила, но зовём `up`, а не `rules`: он идемпотентен (живая несущая = ip link up +
    # правила) и заодно поднимет awgs0, если демон умер сам по себе — иначе такой случай ждал бы
    # следующего ребута. Флага .on нет — секция no-op. Без этого после reload телефон снаружи молча
    # переставал подключаться, а панель показывала «включён»: правила и несущая — РАЗНЫЕ вопросы
    # (тот же урок, что с доп-выходами).
    # -f + `sh`, а не -x: снятый бит превратил бы переигрыш в тихий пропуск (класс Б5-9).
    [ -f "$ENODIA_DIR/vpn-server.sh" ] && [ -f "$ENODIA_STATE/server/.on" ] && \
        sh "$ENODIA_DIR/vpn-server.sh" up >/dev/null 2>&1

    # БЛОКИРОВКИ ПО АДРЕСАМ И ЗАПРЕТ IPv6 — их reload сносит так же, а возвращал до сих пор только heal на буте: после правки в
    # вебморде Xiaomi (и после нашего же awg_setup) DROP по вредоносным адресам, гео-«Блок» и IPv6-запрет молча исчезали до
    # ребута при включённых тумблерах. Наборы живут в ОЗУ и reload переживают — возвращаем только ЦЕПОЧКИ, без перезаливки
    # (`reapply` залил бы набор из снимка заново: секунды на больших списках на каждой починке). Гейты — у владельцев: блокировка
    # выключена, откачена проверкой связи или набор пуст ⇒ no-op. ПОСЛЕ несущей: цепочки встают в начало INPUT/FORWARD, выше
    # её ACCEPT, как на буте.
    [ -f "$ENODIA_DIR/lists-update.sh" ] && sh "$ENODIA_DIR/lists-update.sh" wire ipblock >/dev/null 2>&1
    [ -f "$ENODIA_DIR/geo.sh" ] && sh "$ENODIA_DIR/geo.sh" wire >/dev/null 2>&1
    [ -f "$ENODIA_DIR/net-tune.sh" ] && sh "$ENODIA_DIR/net-tune.sh" apply >/dev/null 2>&1
    # Access schedules: their own tick re-wires a wiped chain within a minute anyway (level-triggered); here — at once, with the
    # rest of the rules the reload took. Not a VPN rule: it stands with the VPN off as well.
    [ -f "$ENODIA_DIR/access-sched.sh" ] && sh "$ENODIA_DIR/access-sched.sh" tick >/dev/null 2>&1

    # NSS/ECM offload: правила только что переставлены — для УЖЕ установленных потоков
    # старый маршрут залипает до conntrack-таймаута. Сбрасываем (инвариант проекта).
    ct_flush

    # ЛОК heal.sh НЕ СНИМАЕМ (июль 2026, разбор ночного «роутер перезагрузился»).
    # Раньше здесь стоял `rm -f "$HEAL_LOCK"` «на всякий случай». Цена: heal без лока идёт
    # ПОЛНЫМ бутовым сценарием — `ip link del awg0` + awg_setup.sh (а тот внутри делает
    # `/etc/init.d/firewall reload`!) + рестарт dnsmasq + письмо «загрузка OK, VPN поднят».
    # То есть КАЖДЫЙ тихий rule-heal watchdog'а превращался в псевдо-ребут: пара секунд без
    # VPN и письмо, которое человек читает как «роутер сам перезагрузился». Плюс риск петли:
    # heal сам зовёт fw3 reload = ровно то событие, от которого rule-heal и лечит.
    # Repair и так делает всё, что сделал бы heal (mark-core + несущая + FORWARD/MASQUERADE +
    # DNS + bypass + слоты), пересоздавать awg0 незачем. Единственный законный случай снятия
    # лока — awg0 физически ИСЧЕЗ; его закрывает сам watchdog (см. rm HEAL_LOCK в его ветке
    # «awg0 ИСЧЕЗ»), где пересоздание интерфейса действительно нужно.

    if [ "$repair_off" = 1 ]; then echo "OK: блокировки, запрет IPv6 и «доступ домой» восстановлены; VPN остаётся выключенным."
    elif [ "$REPAIR_CARRIER" = 1 ]; then echo "OK: правила восстановлены (транспорт: $repair_t)."
    else echo "OK: правила восстановлены без несущей (транспорт: $repair_t)."; fi
}

cmd_on() {
    # Флаг снимаем ПЕРВЫМ делом: ниже мы зовём repair и `heal.sh replay`, а они этот же флаг
    # читают — оставленный, он погасил бы ровно то включение, ради которого нас позвали.
    cmd_flag_clear
    # СНЯТОЕ ДЕАКТИВАЦИЕЙ — ПЕРВЫМ ЖЕ ШАГОМ (`uninstall.sh cron-restore`): расписание и намерение «доступа домой». После «Отключить
    # VPN» cron-строк нет вовсе, а без них роутер живёт без сторожа (мёртвый VPS = дом без интернета: fail-open делать некому), без
    # heal (ребут ничего не поднимет) и без обновления списков — при зелёной панели; что снято, знает ТОЛЬКО снимавший, своей копии
    # реестра задач тут нет. Первым — потому что `heal.sh replay` ниже поднимает «доступ домой» ТОЛЬКО по флагу, и отложенное
    # намерение обязано стать флагом ДО него (ревью шага 6d, круг 2), и потому что при отказе repair повторить починку без cron-строк
    # было бы некому. Верб идемпотентен: на обычном `on` (ничего не снимали) молча выходит.
    restore_cron
    # НЕСУЩАЯ МОГЛА НЕ ПОДНИМАТЬСЯ НИ РАЗУ — и тогда клик «Включить VPN» упирался в гард repair'а,
    # который советует SSH-команду. Типовой путь (замерено на AX3600 17.08.2026): установка
    # «только панель» + импорт бэкапа (намерение `.transport=awg` приезжает ФАЙЛОМ, несущую импорт
    # сознательно не поднимает) + доставка компонента в «Компонентах» (`packages.sh` ставит, но НЕ
    # активирует). Поднять awg0 в этот момент некому: heal сидит на бутовом локе, а repair его
    # сознательно не снимает — окно до трёх минут, пока не спохватится сторож. Другого пути в
    # панели у человека НЕТ: пикер транспорта ТЕКУЩИЙ транспорт не переключает (`return` на
    # cur.transport===k), то есть единственная кнопка отказывала и отправляла в SSH.
    # Поднимаем сами и тем же вербом, что зовут heal (5.6) и repair для АЛЬТОВ: у awg ветка
    # repair'а инлайновая и требует ГОТОВЫЙ awg0, у альтов несущую ставит плагин — асимметрия
    # была только в этом. Гейт `ready` ОБЯЗАТЕЛЕН: без бинарей/конфига `up` дошёл бы до
    # awg_setup.sh, а тот кончается `firewall reload` (снос ВСЕХ iptables) ради заведомо
    # провальной попытки. Нет верба (код 2 = старая копия) ⇒ как раньше, байт-в-байт: причину
    # назовёт гард repair'а ниже. Судим по ФАКТУ (интерфейс появился), а не по коду возврата.
    # ЛОК СМЕНЫ НЕСУЩЕЙ ОБЯЗАТЕЛЕН, и по той же причине, что у `switch`: подъём идёт секунды, а
    # внутри ЕЩЁ НЕТ интерфейса и ЕСТЬ `firewall reload` от awg_setup.sh. Тик сторожа (cron */2),
    # попавший в это окно, увидит «awg0 нет» → safety_off + FAILOPEN + снимет бутовый лок heal, и
    # тот через минуту прогонит ПОЛНЫЙ бутовый сценарий (`ip link del awg0` + второй firewall
    # reload + письмо «загрузка OK») — тот самый псевдо-ребут, от которого лечили в июле. Лок
    # существующий, четвёртой семантики не заводим: и сторож, и heal выходят на нём БЕЗУСЛОВНО
    # (`[ -e ] && exit 0`), поэтому держим его ровно вокруг подъёма и снимаем сразу.
    # Лок УЖЕ занят ⇒ прямо сейчас кто-то меняет транспорт: не лезем вовсе (гонка с ним — ровно
    # то, что лок запрещает), причину назовёт гард repair'а ниже.
    if [ "$(active_transport)" = awg ] && ! ip link show awg0 >/dev/null 2>&1 \
       && [ ! -e "$SWITCH_LOCK" ] \
       && [ -f "$ENODIA_DIR/transport.sh" ] && sh "$ENODIA_DIR/transport.sh" ready awg >/dev/null 2>&1; then
        echo "Несущая AmneziaWG не поднята — поднимаю awg0…"
        _sl=0
        # Ловушка нужна и на СИГНАЛАХ (uhttpd прибивает затянувшийся CGI): голый EXIT их не ловит,
        # а забытый лок держит сторожа и heal до срока SWITCH_STALE (30 мин).
        # Сигнал — ВЫХОД (C121): сигнальная без `exit` снимала лок, а подъём шёл дальше уже без него.
        if : > "$SWITCH_LOCK" 2>/dev/null; then
            _sl=1
            trap 'rm -f "$SWITCH_LOCK" 2>/dev/null' EXIT
            trap 'exit 1' HUP INT TERM PIPE
        fi
        _up=$(sh "$ENODIA_DIR/transport.sh" up awg 2>&1)
        if [ "$_sl" = 1 ]; then
            trap - EXIT HUP INT TERM PIPE
            rm -f "$SWITCH_LOCK" 2>/dev/null
        fi
        if ip link show awg0 >/dev/null 2>&1; then
            echo "awg0 поднят."
        else
            echo "awg0 поднять не удалось:"
            echo "$_up" | tail -n 3
        fi
    fi
    # Отказ repair — отказ всего `on`; расписание к этому моменту уже возвращено первым шагом (разбор у restore_cron выше), так что
    # повторить починку будет кому. Строки — ровно снятые (`cron-restore`).
    cmd_repair || return 1
    # `repair` возвращает ПРАВИЛА (он про снос от fw3 reload, где наборы в RAM живы). А после
    # «Отключить VPN» теряются САМИ НАБОРЫ и dnsmasq-сниппеты: их владельцы — groups.sh, geo.sh,
    # lists-update.sh, dns-hosts.sh, и зовёт их РОВНО heal.sh. Тот сидит на бутовом локе, значит
    # без ребута группы, гео, блокировки, десинк и доп-выходы не возвращались вовсе — при том, что
    # панель показывала их включёнными (замерено на железе 08.08.2026: из 13 ipset оставалось 2).
    # Верб `replay` — тот же порядок heal без бутового сценария; дубль части работы с repair
    # дёшев и случается один раз на клик человека.
    if [ -f "$ENODIA_DIR/heal.sh" ]; then
        echo "Возвращаю группы, гео, списки, десинк и доп-выходы…"
        # ГОВОРИМ ТО, ЧТО СЛУЧИЛОСЬ. Переигрыш умеет ОТКАЗЫВАТЬСЯ (код 3 — занят лок смены
        # транспорта: кто-то меняет сервер или ставит компонент), и глушить его вывод значило бы
        # обещать человеку включённые группы, гео, списки и десинк там, где не вернулось ничего.
        # Своя строка у переигрыша ровно одна — её и печатаем.
        # ЧЕРЕЗ ФАЙЛ, А НЕ ЧЕРЕЗ ПОДСТАНОВКУ. `$(…)` — это ТРУБА, и она ждёт EOF: переигрыш
        # порождает фоновые демоны (перекачка списков и гео), а `start-stop-daemon -b` подменяет
        # им только 0/1/2 — fd 3 (его heal делает из нашего stdout) уезжает к демону вместе с
        # трубой. ЗАМЕР НА ЖЕЛЕЗЕ 09.09.2026: `/proc/<geo-update>/fd/3 -> pipe:[…]`, подстановка
        # висела 75 с и была убита по таймауту, то есть клик «Включить VPN» ждал бы конца
        # перекачки гео. Файл этой семантики не имеет: демон дописать в него не может (у heal он
        # только для одной строки), а мы читаем его сразу.
        _rpf="/tmp/enodia-vpn-on-replay.$$"
        sh "$ENODIA_DIR/heal.sh" replay >"$_rpf" 2>/dev/null; _rc=$?
        _rp=$(cat "$_rpf" 2>/dev/null); rm -f "$_rpf" 2>/dev/null
        if [ -n "$_rp" ]; then echo "$_rp"; fi
        # СОВЕТ РАЗНЫЙ, ПОТОМУ ЧТО ПРИЧИНЫ РАЗНЫЕ: код 3 — занят лок смены транспорта (тогда и
        # правда «повтори, когда закончится»), любой другой — переигрыш не смог сам (например не
        # нашёл свой каталог), и повтор через минуту ничего не изменит.
        if [ "$_rc" = 3 ]; then
            echo "ВНИМАНИЕ: персист подсистем НЕ переигран — группы, гео, списки и десинк вернутся только после повтора: нажмите «Включить VPN» ещё раз, когда закончится смена сервера."
        elif [ "$_rc" != 0 ]; then
            echo "ВНИМАНИЕ: персист подсистем НЕ переигран (код $_rc) — группы, гео, списки и десинк могут не работать; разбор в /tmp/enodia-startup.log."
        fi
    fi
    echo "VPN глобально ВКЛЮЧЁН."
}
restore_cron() { if [ -f "$ENODIA_DIR/uninstall.sh" ]; then sh "$ENODIA_DIR/uninstall.sh" cron-restore >/dev/null 2>&1 || true; fi; }

cmd_exclude() {
    IP=$1
    [ -z "$IP" ] && { echo "укажите IP: vpn-toggle.sh exclude 192.168.31.50"; exit 1; }
    ensure_chain
    iptables -t mangle -C "$EXCLUDE_CHAIN_PRE" -s "$IP" -j ACCEPT 2>/dev/null && {
        echo "IP $IP уже исключён"; exit 0
    }
    iptables -t mangle -A "$EXCLUDE_CHAIN_PRE" -s "$IP" -j ACCEPT
    # NSS-offload может держать старые соединения через VPN — сбрасываем. Число снятых записей
    # есть ТОЛЬКО там, где в прошивке живёт утилита conntrack: пусто ⇒ строку не печатаем вовсе
    # (раньше на ядре 4.4 тут стояло честное с виду «Сброшено записей: 0» при нулевом сбросе).
    N=$(ct_flush_src_n "$IP")
    # Зеркалим в persistent-хранилище, чтобы исключение пережило ребут/fw3-reload
    # (правило выше живёт только в iptables = RAM). add-ip идемпотентен.
    [ -f "$ENODIA_DIR/apply-bypass.sh" ] && sh "$ENODIA_DIR/apply-bypass.sh" add-ip "$IP" >/dev/null 2>&1
    echo "IP $IP исключён из VPN (трафик пойдёт напрямую).${N:+ Сброшено conntrack-записей: $N}"
    echo "Не забудьте на устройстве: ipconfig /flushdns"
}

cmd_include() {
    IP=$1
    [ -z "$IP" ] && { echo "укажите IP: vpn-toggle.sh include 192.168.31.50"; exit 1; }
    if iptables -t mangle -D "$EXCLUDE_CHAIN_PRE" -s "$IP" -j ACCEPT 2>/dev/null; then
        N=$(ct_flush_src_n "$IP")
        echo "IP $IP возвращён в VPN.${N:+ Сброшено conntrack-записей: $N}"
    else
        echo "IP $IP не был в исключениях."
    fi
    # Убираем из persistent-хранилища (чтобы не вернулся после ребута). Идемпотентно.
    [ -f "$ENODIA_DIR/apply-bypass.sh" ] && sh "$ENODIA_DIR/apply-bypass.sh" del-ip "$IP" >/dev/null 2>&1
}

cmd_excluded() {
    iptables -t mangle -L "$EXCLUDE_CHAIN_PRE" -n 2>/dev/null | awk '/ACCEPT/{print $4}'
}

case "$1" in
    status|"")    cmd_status ;;
    off)          cmd_off ;;
    off-settle)   cmd_off_settle ;;     # внутренний: фон доводчика выключения (cmd_off)
    flag-clear)   cmd_flag_clear ;;     # внутренний: снять флаг выключения под локом доводчика (transport.sh switch --home)
    on)           cmd_on ;;
    repair)       cmd_repair ;;
    rules)        cmd_rules ;;
    exclude)      cmd_exclude "$2" ;;
    include)      cmd_include "$2" ;;
    excluded)     cmd_excluded ;;
    *)
        echo "Использование: $0 {status|on|off|repair|rules|exclude IP|include IP|excluded}"
        exit 1
        ;;
esac
