#!/bin/sh
# wifi-lib.sh — ЕДИНСТВЕННЫЙ ответ «какая Wi-Fi сеть живёт на каком интерфейсе».
#
# ЗАЧЕМ ОТДЕЛЬНАЯ БИБЛИОТЕКА. Правила «сеть мимо VPN / сеть целиком в VPN» ставятся по
# `-m physdev --physdev-in wlN` — иначе никак: wlN на BE7000 это slave-порт бриджа, `-i wlN`
# не матчит вовсе. Но ИМЯ `wlN` не является идентичностью сети: сток переклеивает пары
# ifname↔SSID при правке Wi-Fi.
#
# Чем это кончилось на железе 04.08.2026: пользователь включил в штатной панели трёхдиапазонный
# режим, поднялось третье радио, и основная сеть уехала с `wl0` на `wl2` — а на `wl2` висела
# СТАРАЯ отметка «мимо VPN». Итог: awg0 живой, handshake свежий, с роутера выход через туннель
# есть, а ВСЕ клиенты основной 5 ГГц идут напрямую (в панели — домашний IP, заблокированное не
# открывается). Признак в диагностике: MARK-правила mangle PREROUTING с НУЛЁМ пакетов при бодро
# тикающем `VPN_EXCLUDE … --physdev-in`. Разбор — в заметках разработки «грабли-история».
#
# КОНТРАКТ. Хранилища правил (`.bypass-ifaces`, `.fullvpn-ifaces`) держат SSID — то, что человек
# выбирал в панели глазами, — а раскрытие «SSID → живые wlN» происходит В МОМЕНТ ПРИМЕНЕНИЯ.
# Тогда любая перетасовка имён стоком безобидна: правило остаётся на ТОЙ сети, которую отметили.
#   wifi_ssid_of   <iface>  — SSID интерфейса (пусто = не знаем)
#   wifi_ifaces_of <ssid>   — ВСЕ wlN с этим SSID, через пробел (пусто = такой сети сейчас нет)
#   wifi_resolve   <строка> — строка хранилища → список wlN (SSID, иначе legacy-имя интерфейса)
#   wifi_iface_list         — все известные wlN
#
# «ЧТО СЕЙЧАС В ЭФИРЕ» — тоже здесь, и тоже одной копией (читают экран сетей панели и wifi-stats.sh):
#   wifi_live_ifaces        — известные wlN, которые ЕСТЬ в ядре (конфиг выключенной сети лежит, интерфейса нет)
#   wifi_bridge_of <iface>  — мост интерфейса (br-lan · br-guest · br-miot); подсеть моста — wifi_bridge_net <мост>
#   wifi_band_of   <iface>  — диапазон по частоте, которую сообщает драйвер (2.4 · 5 · 6); wifi_mhz_band <МГц>
#   wifi_hidden_of <iface>  — сеть не объявляет имя (код 0)
#   wifi_table              — «iface<TAB>в ядре 1|0<TAB>SSID» на КАЖДЫЙ известный интерфейс одним проходом
#   wifi_key_state <строка> — строка хранилища: live (её сеть в эфире) · off (сеть есть в настройках, но не в
#                             эфире) · gone (сети с таким именем нет вовсе); таблицу берёт из $WIFI_TAB
#
# ПОЧЕМУ SSID, А НЕ СЕКЦИЯ UCI. Секции тоже переезжают (`@wifi-iface[N]` позиционны), а SSID —
# ровно та сущность, которую пользователь видит в панели и выбирает. Побочный выигрыш: две VAP
# с ОДНИМ именем (гостевая 2.4+5 ГГц) — это ОДНА сеть и для правил тоже, раскрытие даёт обе.
#
# ИСТОЧНИКИ И ИХ ПОРЯДОК. Сначала `/var/run/hostapd-<ifc>.conf` — это РАНТАЙМ, то, что реально
# в эфире (и ровно то, по чему панель строит список сетей). Фолбэк — `uci show wireless`: на буте
# нас зовёт heal.sh, и hostapd-конфов может ещё не быть, а без фолбэка правила молча не встали бы
# до следующей правки — то есть ровно тот же класс «сеть тихо вне туннеля», от которого лечим.
#
# busybox-замечания: нет `local` ⇒ все переменные с префиксом `_w` (у вызывающего свои имена
# затирать нельзя, см. грабли про `_id` в vpn-server.sh); имена интерфейсов безопасны для
# словоделения, SSID — НЕТ (пробелы, кириллица, китайский), поэтому SSID ходит только в кавычках
# и целой строкой.

# ВЫГРУЗКА `uci show wireless` — одна на вызывателя, который спрашивает про МНОГО интерфейсов (экран сетей: секция отвечала 17
# запусками uci, из них 11 полных выгрузок — ревью шага 5b, круг 2). Задал `WIFI_UCI` — функции ниже берут её, не задал —
# выгружают сами, как раньше (apply-bypass на бутовом пути ничего не кэширует: конфиг мог смениться между его вызовами).
wifi_uci_show() { if [ -n "${WIFI_UCI+x}" ]; then printf '%s\n' "$WIFI_UCI"; else uci show wireless 2>/dev/null; fi; }

# Секция uci, которой принадлежит интерфейс (`wireless.bh_ap`, `wireless.@wifi-iface[1]`). Пусто + код 1 = не знаем.
wifi_uci_sec_of() {
    case "$1" in
        wl[0-9]*) : ;;
        *) return 1 ;;
    esac
    _wus=$(wifi_uci_show | sed -n "s/\.ifname='$1'\$//p" | head -1)
    [ -n "$_wus" ] || return 1
    printf '%s\n' "$_wus"
}

# SSID интерфейса. Пусто + код 1 = не знаем (сеть выключена, чужой ifname, hostapd ещё не поднят).
wifi_ssid_of() {
    case "$1" in
        wl[0-9]*) : ;;
        *) return 1 ;;
    esac
    if [ -f "/var/run/hostapd-$1.conf" ]; then
        # cut -d= -f2- (а не поле 2): в SSID законен знак «=». Кавычки/бэкслеши срезаем — они от
        # формата конфига, а не от имени сети (то же самое делает web/cgi-bin/data).
        _wS=$(grep -i -E '^[[:space:]]*ssid=' "/var/run/hostapd-$1.conf" 2>/dev/null | \
              head -1 | cut -d= -f2- | tr -d '"\\')
        [ -n "$_wS" ] && { printf '%s\n' "$_wS"; return 0; }
    fi
    # Фолбэк на конфиг: ищем секцию, у которой ifname = наш, и спрашиваем её ssid ЧЕРЕЗ uci.
    # Именно через `uci get`, а не вторым sed'ом по выводу: имя секции содержит `@`, `[`, `]` —
    # в регулярке их пришлось бы экранировать, и `[` молча открыл бы класс символов.
    _wsec=$(wifi_uci_sec_of "$1") || return 1
    # Нормализация ТА ЖЕ, что у рантайм-ветки: иначе один источник дал бы имя с кавычкой, другой
    # без, и строка хранилища перестала бы совпадать сама с собой при смене источника.
    _wS=$(uci -q get "$_wsec.ssid" 2>/dev/null | tr -d '"\\')
    [ -n "$_wS" ] || return 1
    printf '%s\n' "$_wS"
}

# Все известные интерфейсы: рантайм ∪ конфиг (дедуп). Порядок — как отдал источник.
wifi_iface_list() {
    _wl=""
    for _wf in /var/run/hostapd-*.conf; do
        [ -f "$_wf" ] || continue
        _wi=$(basename "$_wf" .conf); _wi=${_wi#hostapd-}
        case "$_wi" in wl[0-9]*) : ;; *) continue ;; esac
        case " $_wl " in *" $_wi "*) continue ;; esac
        _wl="$_wl${_wl:+ }$_wi"
    done
    for _wi in $(wifi_uci_show | sed -n "s/^wireless\..*\.ifname='\(wl[0-9A-Za-z_-]*\)'\$/\1/p"); do
        case " $_wl " in *" $_wi "*) continue ;; esac
        _wl="$_wl${_wl:+ }$_wi"
    done
    printf '%s\n' "$_wl"
}

# ВСЕ интерфейсы с данным SSID. Сравнение строковое (`=`), не регуляркой: в SSID бывает что угодно.
wifi_ifaces_of() {
    [ -n "$1" ] || return 1
    _wout=""
    for _wc in $(wifi_iface_list); do
        [ "$(wifi_ssid_of "$_wc")" = "$1" ] || continue
        _wout="$_wout${_wout:+ }$_wc"
    done
    [ -n "$_wout" ] || return 1
    printf '%s\n' "$_wout"
}

# Строка хранилища → список интерфейсов, к которым ставить правило.
# Порядок проверок: СНАЧАЛА как SSID (новый формат), потом как имя интерфейса — legacy-строки
# (до 04.08.2026) и сети, которых сейчас нет в эфире, продолжают работать ровно как раньше.
wifi_resolve() {
    [ -n "$1" ] || return 1
    _wr=$(wifi_ifaces_of "$1") && { printf '%s\n' "$_wr"; return 0; }
    case "$1" in
        wl[0-9]*) printf '%s\n' "$1"; return 0 ;;
    esac
    return 1
}

# ── ЧТО СЕЙЧАС В ЭФИРЕ ──────────────────────────────────────────────────────────────────────────
# «Известный» интерфейс ≠ «живой»: конфиг третьего радио и hostapd-конф выключенной сети лежат, а интерфейса в ядре
# нет (замер BE7000 22.09.2026: `hostapd-wl2.conf` от выключенного трёхдиапазонного режима, wl14–wl17 гостевой и IoT
# в uci — при четырёх живых). Экран сетей, строивший список по hostapd-конфам, показывал выключенную сеть как
# работающую и склеивал её с живой одноимённой. Для ПРАВИЛ мёртвое имя безвредно (physdev на отсутствующий
# интерфейс не матчит), для ПОКАЗА — ложь.
wifi_live_ifaces() {
    for _wv in $(wifi_iface_list); do
        [ -d "/sys/class/net/$_wv" ] && printf '%s\n' "$_wv"
    done
    return 0
}

# Мост интерфейса = сеть в терминах правил: гостевая и умный дом Xiaomi — ДРУГИЕ мосты и другие подсети.
wifi_bridge_of() {
    for _wb in /sys/class/net/br-*; do
        [ -d "$_wb/brif/$1" ] || continue
        printf '%s\n' "${_wb##*/}"
        return 0
    done
    return 1
}

# Подсеть моста. Сперва маршрут ядра (факт); у моста без портов (гостевая с выключенным Wi-Fi) маршрута нет вовсе —
# тогда адрес роутера на мосту, сведённый к адресу сети (`ipcalc` в busybox этой прошивки нет — замер).
wifi_bridge_net() {
    _wn=$(ip -4 route show dev "$1" proto kernel scope link 2>/dev/null | awk 'NR==1{print $1}')   # not-wan: подсеть МОСТА локальной сети, а не WAN
    case "$_wn" in */*) printf '%s\n' "$_wn"; return 0 ;; esac
    _wa=$(ip -4 addr show dev "$1" 2>/dev/null | sed -n 's/.*inet \([0-9.]*\)\/\([0-9]*\).*/\1 \2/p' | head -1)
    [ -n "$_wa" ] || return 1
    _wq=${_wa#* }; _wa=${_wa% *}; _wo=""; _wk=0
    for _wx in $(printf '%s' "$_wa" | tr . ' '); do
        _wm=$((_wq - _wk*8)); [ "$_wm" -gt 8 ] && _wm=8; [ "$_wm" -lt 0 ] && _wm=0
        _wo="$_wo${_wo:+.}$((_wx & (256 - (1 << (8 - _wm)))))"
        _wk=$((_wk + 1))
    done
    printf '%s/%s\n' "$_wo" "$_wq"
}

# Частота → «диапазон канал» (`2437` → `2.4 6`). Пусто + код 1 — частота вне диапазонов Wi-Fi.
wifi_mhz_band() {
    case "$1" in ''|*[!0-9]*) return 1 ;; esac
    if   [ "$1" -ge 2400 ] && [ "$1" -lt 2500 ]; then printf '2.4 %s\n' $(( ($1 - 2407) / 5 ))
    elif [ "$1" -ge 4900 ] && [ "$1" -lt 5900 ]; then printf '5 %s\n' $(( ($1 - 5000) / 5 ))
    elif [ "$1" -ge 5925 ]; then printf '6 %s\n' $(( ($1 - 5950) / 5 ))
    else return 1; fi
}
# Диапазон интерфейса — по частоте, которую сообщает ДРАЙВЕР (стоковый Xiaomi — qcawifi: `iwconfig`), а не по
# `hw_mode` конфига: у 5 и 6 ГГц он один и тот же (`a`). Пусто — не знаем (другой драйвер, радио не поднято).
wifi_band_of() {
    _wg=$(iwconfig "$1" 2>/dev/null | sed -n 's/.*Frequency:\([0-9.]*\) GHz.*/\1/p' | head -1)
    [ -n "$_wg" ] || return 1
    _wg=$(awk -v f="$_wg" 'BEGIN{printf "%d", f*1000+0.5}')
    _wg=$(wifi_mhz_band "$_wg") || return 1
    printf '%s\n' "${_wg%% *}"
}

# Сеть не объявляет имя: hostapd `ignore_broadcast_ssid` 1 (пустое имя) или 2 (нули вместо имени).
wifi_hidden_of() {
    grep -qE '^[[:space:]]*ignore_broadcast_ssid=[12]' "/var/run/hostapd-$1.conf" 2>/dev/null
}

# ТАБЛИЦА ОДНИМ ПРОХОДОМ: «iface<TAB>в ядре 1|0<TAB>SSID» на каждый известный интерфейс. Нужна тому, кто спрашивает про
# МНОГО строк хранилища разом (экран сетей): wifi_resolve на каждую строку заново перебирает все интерфейсы и зовёт uci
# на каждом без hostapd-конфа — семь строк хранилища BE7000 давали сотню запусков uci на один ответ панели. SSID —
# ПОСЛЕДНИМ полем (в нём законны пробелы, в том числе ведущие: у гостевой стока это «  小米共享WiFi_…»), таб из него
# вычищен: он разделитель.
wifi_table() {
    for _wt in $(wifi_iface_list); do
        _wtl=0; [ -d "/sys/class/net/$_wt" ] && _wtl=1
        printf '%s\t%s\t%s\n' "$_wt" "$_wtl" "$(wifi_ssid_of "$_wt" | tr '\t' ' ')"
    done
}
# СТРОКА ХРАНИЛИЩА ПРОТИВ ТАБЛИЦЫ — та же лестница, что у wifi_resolve (сперва как имя сети, потом как legacy-имя
# интерфейса), только без повторного перебора. live — хоть один её интерфейс есть в ядре (правило действует); off —
# сеть есть в настройках, но не в эфире (выключена в родной панели, радио не поднято): правило встанет само, когда сеть
# появится; gone — сети с таким именем нет вовсе (переименовали, или это legacy-имя интерфейса, которого больше нет).
# Строку отдаём awk ОКРУЖЕНИЕМ, а не через -v: -v разбирает escape-последовательности, и имя с `\` приехало бы другим.
wifi_key_state() {
    _wkt=${WIFI_TAB-$(wifi_table)}
    # Сравнение СТРОКОВОЕ (`""` к обеим сторонам): поле и ENVIRON у awk — «строка-число», и имя «7» иначе совпало бы с сетью
    # «007» (ревью шага 5b, круг 2).
    _wks=$(printf '%s\n' "$_wkt" | WK="$1" awk -F'\t' 'BEGIN{k=ENVIRON["WK"]} ($3"")==(k""){m=1; if($2==1) l=1} END{if(m) print (l ? "live" : "off")}')
    [ -n "$_wks" ] && { printf '%s\n' "$_wks"; return 0; }
    case "$1" in
        wl[0-9]*)
            [ -d "/sys/class/net/$1" ] && { echo live; return 0; }
            printf '%s\n' "$_wkt" | cut -f1 | grep -qxF "$1" && { echo off; return 0; } ;;
    esac
    echo gone
}
