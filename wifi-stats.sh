#!/bin/sh
# wifi-stats.sh — ЕДИНСТВЕННЫЙ ответ «кто сейчас в эфире и на какой скорости».
#
# ЗАЧЕМ. Запрос тестеров: «скорость соединения, протокол и версия wifi, по аналогии как у
# кинетика». Данные есть только у драйвера QCA, и достаёт их РОВНО ОДИН инструмент —
# `wlanconfig <wlN> list sta`. Замерено на живом BE7000 (08.08.2026): 160 вызовов (20 свипов по
# 8 VAP) укладываются в 0 с, то есть поллингом панели этим роутер не нагрузить.
#
# ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ФУНКЦИЯ В wifi-lib.sh. Та библиотека — единственный ответ «какая
# СЕТЬ живёт на каком wlN», и её сорсит apply-bypass на бутовом пути ради постановки правил.
# Разбор станций в этом пути — лишний код там, где важна только скорость и надёжность. Здесь
# зависимость обратная: нам wifi-lib нужна как источник имени сети, и это верное направление.
#
# ПОЧЕМУ НЕ iw / hostapd_cli (обе проверены на железе, обе непригодны):
#   * `iw dev <wlN> station dump` отдаёт ПУСТО — QCA-VAP не публикует станции через nl80211;
#   * `hostapd_cli` требует явный `-p /var/run/hostapd-wifi0|wifi1`, а скорости у него ЖЁСТКО нули.
#
# ЛОВУШКИ ВЫВОДА wlanconfig — все увидены в РЕАЛЬНОМ дампе живого роутера, не в документации:
#  1. ШАПКА `ADDR AID CHAN …` ПОВТОРЯЕТСЯ ПОСРЕДИ вывода (в дампе — снова после шестой станции).
#     Пропускать надо КАЖДУЮ строку-шапку, а не только первую: иначе заголовок уедет в данные.
#  2. Под строкой станции идёт БЛОК её подробностей (` SNR : 31`, ` Operating band : 5GHz`, …).
#     SNR и диапазон есть ТОЛЬКО там ⇒ станция не может быть напечатана в момент чтения её
#     строки. Копим в массивы и печатаем всё в END — так обходимся и БЕЗ user-функций awk
#     (в busybox-сборках их может не быть), и без второго прохода по выводу.
#  3. Колонка IEs — ПЕРЕМЕННОЙ длины (`RSN WME`, бывает пусто) ⇒ хвост строки читаем ЯКОРЯМИ:
#     ASSOCTIME по маске `Ч:ММ:СС`, MODE по префиксу `IEEE80211_MODE_`, RXNSS/TXNSS — два поля
#     сразу за MODE. Позиционно читаются только первые девять колонок: они на месте всегда.
#  4. MAXRATE — ПОСЛЕДНЕЕ ЧИСЛОВОЕ поле перед ASSOCTIME, а не «третье слева от него»: у клиента
#     без HT/VHT колонки HTCAPS/VHTCAPS схлопываются и жёсткое смещение уехало бы.
#  5. TXRATE МГНОВЕННЫЙ и прыгает: замер на железе — телефон с потолком 2401900 кбит/с показывал
#     6M на простое ⇒ честно отдавать ПАРУ «текущая / потолок». Одна текущая обманывает.
#  6. MODE одним токеном несёт И стандарт, И ширину (`IEEE80211_MODE_11BEA_EHT160`). Проверять
#     ТОЛЬКО в порядке EHT → HE → VHT → HT: `VHT80` содержит подстроку `HT`, и проверка «HT»
#     первой объявила бы Wi-Fi 7 четвёртым поколением.
#  7. IDLE = секунды с последнего кадра. В дампе живого роутера нашлась станция с IDLE 35096
#     (~10 часов) при живой строке — таблица помнит УШЕДШИХ. Поле отдаём как есть, решение
#     «показывать ли» принимает панель: молча выбросить нельзя (сонный ТВ выглядит так же).
#  8. `wifi_iface_list` отдаёт и интерфейсы, которых в системе НЕТ (конфиг третьего радио лежит,
#     радио не поднято) ⇒ берём только живые (`wifi_live_ifaces`: те, что есть в `/sys/class/net`),
#     иначе на каждом свипе получаем ошибку драйвера по мёртвому имени.
#  9. Регистр MAC: `wlanconfig` печатает СТРОЧНЫМИ, как и `/tmp/dhcp.leases` (склейка бесплатна),
#     а `iwinfo assoclist` — ПРОПИСНЫМИ. Если сюда когда-нибудь добавят iwinfo — только через
#     `tr A-Z a-z`, иначе склейка молча даст ноль совпадений.
#
# ЧЕГО ЗДЕСЬ НЕ БУДЕТ И ПОЧЕМУ: реального throughput (драйвер отдаёт скорость ЛИНКА; фактическая
# считается только дельтами счётчиков между поллами) и абсолютного времени начала сессии (RTC на
# роутере нет). ASSOCTIME — это ДЛИТЕЛЬНОСТЬ сессии, её и отдаём в секундах.
#
# MAC телефонов рандомизированные ⇒ идентичностью считать нельзя: склейка с арендами даёт IP и
# имя, а «тот же ли это гость, что вчера» вопрос не к нам.
#
# Вербы:
#   json (деф.) — один срез для панели: {"ok":1,"n":N,"sta":[…]}
#   tsv         — то же плоским текстом (диагностика, dump.sh)

ENODIA_DIR="${ENODIA_DIR:-/data/usr/app/enodia}"
if [ -f "$ENODIA_DIR/wifi-lib.sh" ]; then . "$ENODIA_DIR/wifi-lib.sh"; fi
# lease-lib нужен ровно ради neigh_pairs (кто в сети без аренды) — см. ws_stream. Сорсим ТОЛЬКО
# под `[ -f ]`: провалившийся `.` в busybox ash фатален, шелл выходит на месте.
if [ -f "$ENODIA_DIR/lease-lib.sh" ]; then . "$ENODIA_DIR/lease-lib.sh"; fi
# Шимы на случай доисторической установки без wifi-lib (или прежней её копии без «что в эфире»): без имени сети и
# моста срез беднее, но живой. «Живые интерфейсы» (ловушка 8) и мост интерфейса — у библиотеки, своей копии здесь нет.
command -v wifi_iface_list >/dev/null 2>&1 || wifi_iface_list() { ls -1 /sys/class/net 2>/dev/null | grep '^wl[0-9]'; }
command -v wifi_ssid_of >/dev/null 2>&1 || wifi_ssid_of() { return 1; }
command -v wifi_live_ifaces >/dev/null 2>&1 || wifi_live_ifaces() { ls -1 /sys/class/net 2>/dev/null | grep '^wl[0-9]'; }
command -v wifi_bridge_of >/dev/null 2>&1 || wifi_bridge_of() { return 1; }

LEASES=/tmp/dhcp.leases

# Сырой срез всех станций в TSV. Поля (в этом порядке):
#   mac ifc net band chan tx rx max rssi snr nrx ntx assoc idle std width mode ssid
# SSID — ПОСЛЕДНИМ полем и с вычищенными TAB: он единственный, где законны пробелы и юникод.
ws_collect() {
    for _sc in $(wifi_live_ifaces); do
        # SSID уходит ОКРУЖЕНИЕМ, а не через -v: awk обрабатывает escape-последовательности в
        # значении -v, и имя сети с обратным слешем приехало бы искажённым. Присваивание ставим
        # ОТДЕЛЬНОЙ строкой с export: в конвейере `VAR=x cmd | awk` переменная достаётся только
        # ПЕРВОЙ команде, и awk не увидел бы ничего.
        # Из SSID вычищаем ТОЛЬКО таб (он у нас разделитель полей). Перевод строки не трогаем:
        # его снимет сама подстановка, а замена его на пробел оставляла в имени сети ХВОСТОВОЙ
        # пробел — и «Xiaomi_1411_5G » перестало бы совпадать с именем из хранилищ правил.
        WS_IFC="$_sc"; WS_SSID=$(wifi_ssid_of "$_sc" 2>/dev/null | tr '\t' ' '); WS_NET=$(wifi_bridge_of "$_sc")
        export WS_IFC WS_SSID WS_NET
        wlanconfig "$_sc" list sta 2>/dev/null | awk '
        BEGIN { ifc = ENVIRON["WS_IFC"]; ssid = ENVIRON["WS_SSID"]; net = ENVIRON["WS_NET"]; n = 0 }
        /^ADDR/ { next }                                            # ловушка 1: шапок несколько
        $1 ~ /^[0-9a-fA-F][0-9a-fA-F]:[0-9a-fA-F][0-9a-fA-F]:/ {
            n++;
            mac[n] = tolower($1); chan[n] = $3 + 0;
            t = $4; sub(/M$/, "", t); tx[n] = t + 0;
            t = $5; sub(/M$/, "", t); rx[n] = t + 0;
            rssi[n] = $6 + 0; idle[n] = $9 + 0;
            snr[n] = ""; band[n] = ""; mx[n] = 0; asc[n] = 0; mode[n] = ""; nrx[n] = 0; ntx[n] = 0;
            at = 0;
            for (i = 10; i <= NF; i++) if ($i ~ /^[0-9]+:[0-9][0-9]:[0-9][0-9]$/) { at = i; break }
            if (at) {
                # ASSOCTIME = ДЛИТЕЛЬНОСТЬ «Ч:ММ:СС», часов бывает и больше суток. Разбираем
                # substr-ом от КОНЦА строки: минуты и секунды всегда двузначны, часы — нет.
                s = $at; L = length(s);
                asc[n] = substr(s, 1, L - 6) * 3600 + substr(s, L - 4, 2) * 60 + substr(s, L - 1, 2);
                for (j = at - 1; j >= 10; j--) if ($j ~ /^[0-9]+$/) { mx[n] = $j + 0; break }   # ловушка 4
                for (k = at + 1; k <= NF; k++) if ($k ~ /^IEEE80211_MODE_/) {
                    mode[n] = $k; nrx[n] = $(k + 1) + 0; ntx[n] = $(k + 2) + 0; break
                }
            }
            next
        }
        /^[ \t]*SNR[ \t]*:/            { if (n) snr[n]  = $NF + 0; next }   # ловушка 2: блок ПОД строкой
        /^[ \t]*Operating band[ \t]*:/ { if (n) band[n] = $NF;     next }
        END {
            for (i = 1; i <= n; i++) {
                m = mode[i];
                # Ловушка 6: порядок проверок обязателен, «HT» есть внутри VHT и EHT.
                if (m ~ /EHT/)      std = 7;
                else if (m ~ /HE/)  std = 6;
                else if (m ~ /VHT/) std = 5;
                else if (m ~ /HT/)  std = 4;
                else                std = 0;
                # Ширина канала = хвостовые цифры MODE (HT20/VHT80/HE160/EHT320). У легаси-режима
                # (11B/11G) их нет вовсе — тогда честный ноль, а не выдуманные 20.
                w = ""; L = length(m); p = L;
                while (p > 0 && substr(m, p, 1) >= "0" && substr(m, p, 1) <= "9") { w = substr(m, p, 1) w; p-- }
                if (w == "") w = 0;
                # Диапазон: строка блока, а если её не было — по номеру канала (1..14 = 2.4 ГГц).
                b = band[i];
                if (b == "") b = (chan[i] > 0 && chan[i] <= 14) ? "2.4GHz" : (chan[i] > 0 ? "5GHz" : "");
                printf "%s\t%s\t%s\t%s\t%d\t%d\t%d\t%d\t%d\t%s\t%d\t%d\t%d\t%d\t%d\t%d\t%s\t%s\n", \
                    mac[i], ifc, net, b, chan[i], tx[i], rx[i], int(mx[i] / 1000), rssi[i], \
                    (snr[i] == "" ? "" : snr[i]), nrx[i], ntx[i], asc[i], idle[i], std, w + 0, m, ssid
            }
        }' 2>/dev/null
    done
}

# Склейка с арендами и печать. ОДИН awk-проход на весь срез: аренды читаем первым файлом.
# Аренда даёт IP и имя устройства — панель ведёт устройства ПО IP, и без склейки статистику
# было бы не к чему пришить (MAC у телефонов рандомный и в списках панели не фигурирует).
# Склейка с арендами и печать. Вход — ОДИН поток: сперва аренды, затем строка-сентинел, затем
# срез станций (см. ws_stream). ЗАЧЕМ так, а не двумя файлами в аргументах awk:
#   * у аренд разделитель ПРОБЕЛ, у нашего среза — ТАБ, а FS у awk один на весь запуск: строгий
#     таб обязателен, потому что пустые поля (нет SNR, нет имени сети) значащие и схлопнулись бы;
#   * идиома «NR==FNR» на ПУСТОМ файле аренд врёт: для первой же строки второго входа NR и FNR
#     оба равны 1, и станция была бы прочитана как аренда.
ws_emit() {
    WS_FMT="$1"; export WS_FMT
    awk -v FS='\t' '
    BEGIN { fmt = ENVIRON["WS_FMT"]; first = 1; n = 0; part = 0 }
    $0 == "###STA###" { part = 1; next }
    $0 == "###NAMES###" { part = 2; next }
    # Свои имена (dev-names.sh, `mac⇥имя`) — метка панели: список устройств и список станций обязаны звать устройство ОДНИМ
    # именем, иначе в одном месте «Алиса», а в другом голый MAC.
    part == 2 { if ($1 != "") al[tolower($1)] = $2; next }
    part == 0 {
        # /tmp/dhcp.leases: <expiry> <mac> <ip> <host> <clientid>. Имя «*» = аренда без имени.
        if (NF >= 4) { lip[tolower($2)] = $3; lho[tolower($2)] = ($4 == "*" ? "" : $4) }
        next
    }
    {
        n++;
        mac = $1; ifc = $2; net = $3; band = $4; chan = $5; tx = $6; rx = $7; mx = $8;
        rssi = $9; snr = $10; nrx = $11; ntx = $12; asc = $13; idle = $14; std = $15;
        width = $16; mode = $17; ssid = $18;
        ip = lip[mac]; host = lho[mac]; alias = al[mac];
        if (fmt == "tsv") {
            printf "%s\t%s\t%s\t%s\t%s\t%s\t%s/%s Mbps\tmax %s\t%s dBm\tSNR %s\t%sx%s\tstd %s\tw %s\tup %ss\tidle %ss\n", \
                mac, (ip == "" ? "-" : ip), (host == "" ? "-" : host), ifc, (ssid == "" ? "-" : ssid), \
                band, tx, rx, mx, rssi, snr, nrx, ntx, std, width, asc, idle;
            next
        }
        # Экранируем ТОЛЬКО поля со свободным текстом: имя сети и имя устройства. Порядок
        # обязателен — сперва обратный слеш, иначе экранируем собственные вставки.
        gsub(/\\/, "\\\\", ssid); gsub(/"/, "\\\"", ssid);
        gsub(/\\/, "\\\\", host); gsub(/"/, "\\\"", host);
        printf "%s{\"mac\":\"%s\",\"ip\":\"%s\",\"host\":\"%s\",\"alias\":\"%s\",\"ifc\":\"%s\",\"ssid\":\"%s\",\"net\":\"%s\",\"band\":\"%s\",\"chan\":%s,\"tx\":%s,\"rx\":%s,\"max\":%s,\"rssi\":%s,\"snr\":%s,\"nrx\":%s,\"ntx\":%s,\"assoc\":%s,\"idle\":%s,\"std\":%s,\"width\":%s,\"mode\":\"%s\"}", \
            (first ? "" : ","), mac, ip, host, alias, ifc, ssid, net, band, chan, tx, rx, mx, rssi, \
            (snr == "" ? "null" : snr), nrx, ntx, asc, idle, std, width, mode;
        first = 0
    }
    END { if (fmt != "tsv") printf "\n" }
    '
}

# Поток «аренды + сентинел + станции». Аренды приводим к табам ТЕМ ЖЕ разделителем, что у среза;
# сжимаем любую серию пробелов, а не одиночный пробел, — иначе двойной разделитель сдвинул бы поля.
# Срез станций берём из уже СНЯТОГО текста: второй прогон wlanconfig дал бы другой набор станций
# (кто-то отвалился между вызовами), и счётчик разошёлся бы с содержимым.
ws_stream() {
    # СОСЕДИ (ARP) ИДУТ ПЕРВЫМИ, аренды следом и перезаписывают их. Аренды нет вовсе у устройства,
    # которому адрес прописали на нём самом (телевизор, приставка, NAS): без этой строки станцию
    # не к чему пришить — панель ведёт устройства ПО IP, и карточка «Как подключено по Wi-Fi» у
    # такого клиента не появлялась вовсе. Порядок обязателен: у аренды есть ещё и ИМЯ, у ARP его
    # нет и не будет, поэтому побеждать должна аренда. Формат подделываем под неё же
    # (`exp mac ip host clientid`), имя — «*», как у аренды без имени. Разбор ARP — у владельца
    # (lease-lib.sh::neigh_pairs), своей копии здесь нет.
    if command -v neigh_pairs >/dev/null 2>&1; then
        neigh_pairs 2>/dev/null | awk -v FS='\t' -v OFS='\t' '{print 0, $2, $1, "*", "-"}'
    fi
    [ -f "$LEASES" ] && sed 's/[ 	][ 	]*/\t/g' "$LEASES" 2>/dev/null
    # Свои имена устройств — отдельной частью потока, у ВЛАДЕЛЬЦА (`dev-names.sh list`, один запуск на срез): разбор персиста
    # у него один, строки `mac⇥имя` приходят уже чистыми (MAC строчными, без кавычки, косой и управляющих байтов) — поэтому
    # поле alias ниже не экранируется. Прямое чтение файла тут расходилось с cgi-bin/data (регистр MAC, повтор строки) и
    # пропускало CR ручной правки в JSON (ревью 27.09.2026).
    if [ -f "$ENODIA_DIR/dev-names.sh" ]; then printf '###NAMES###\n'; sh "$ENODIA_DIR/dev-names.sh" list 2>/dev/null; fi
    printf '###STA###\n'
    printf '%s\n' "$1"
}

cmd_json() {
    if ! command -v wlanconfig >/dev/null 2>&1; then
        # Честная причина вместо пустого списка: панель обязана отличать «никого нет в эфире»
        # от «спросить нечем» (другая модель роутера, урезанная прошивка).
        printf '{"ok":0,"err":"no-wlanconfig","n":0,"sta":[]}\n'
        return 0
    fi
    _raw=$(ws_collect)
    _cnt=$(printf '%s\n' "$_raw" | grep -c . 2>/dev/null || true)
    [ -n "$_cnt" ] || _cnt=0
    _body=$(ws_stream "$_raw" | ws_emit json)
    printf '{"ok":1,"n":%s,"sta":[%s]}\n' "$_cnt" "$_body"
}

cmd_tsv() {
    command -v wlanconfig >/dev/null 2>&1 || { echo "wlanconfig не найден — статистики Wi-Fi нет"; return 1; }
    ws_stream "$(ws_collect)" | ws_emit tsv
}

case "${1:-json}" in
    json) cmd_json ;;
    tsv)  cmd_tsv ;;
    *)    echo "использование: $0 [json|tsv]" >&2; exit 1 ;;
esac
